def _has_optout(body_low):
    import re as _re
    return any(w in body_low for w in OPTOUT) or any(_re.search(rx, body_low) for rx in OPTOUT_RE)

def allowed_numbers(orig_body):
    base = set(re.findall(r'\d+', orig_body))
    base |= {'5580'} | {str(v) for v in FACTS['region_counts_site_index'].values()}
    base |= {'1', '2', '3', '4', '5', '7', '10', '15', '20', '30', '35', '40', '24', '70'}
    return base

def gate(idx, subject, body):
    fails = []
    text = subject + '\n' + body
    for rx, name in SUBJ_RE:
        if re.search(rx, subject): fails.append(f'{name}: «{subject}»')
    sw = len(subject.split())
    if sw > 6: fails.append(f'тема длинная ({sw} слов)')
    for m in re.finditer(r'(\d[\d,\.]*)\s*%', body):
        if m.group(1).split(',')[0].split('.')[0] not in ('97', '99', '95'):
            fails.append(f'проценты: {m.group(0)}')
    for rx, name in STOP_RE:
        m = re.search(rx, text)
        if m: fails.append(f'{name}: «{text[max(0,m.start()-25):m.end()+25]}»'.replace('\n', ' '))
    low = body.lower()
    if not _has_optout(low): fails.append('нет опции отказа')
    if low.count('извините за') > 1: fails.append('двойное заискивание (отказ дважды)')
    words = len(body.split())
    if not 45 <= words <= 140: fails.append(f'объём {words} слов')
    if not body.rstrip().endswith('С уважением,'): fails.append('финал не «С уважением,»')
    extra = set(re.findall(r'\d+', body)) - allowed_numbers(V[idx]['body'])
    if extra: fails.append(f'непроверенные числа: {sorted(extra)}')
    ach = len(re.findall(r'5580', body)) + len(re.findall(r'опубликованн\w+ (кейс|проект)', body))
    if ach > 1: fails.append(f'витрина: {ach} числа-достижения (максимум одно)')
    return fails

def main():
    # stage 1: rewrite
    B = 5
    chunks = [KC[i:i+B] for i in range(0, len(KC), B)]
    regen = {}
    for n, chunk in enumerate(chunks):
        out = os.path.join(SP, f'regen-rw-{n}.json')
        if os.path.exists(out):
            data = json.load(open(out))
        else:
            print(f'rw {n}: письма {chunk}', flush=True)
            data = ask(rw_prompt(chunk), f'rw{n}')
            json.dump(data, open(out, 'w'), ensure_ascii=False, indent=1)
        for L in data['letters']:
            regen[int(L['idx'])] = {'subject': L['subject'], 'body': L['body']}
    missing = [i for i in KC if i not in regen]
    if missing: print('НЕ ПОКРЫТО rewrite:', missing)

