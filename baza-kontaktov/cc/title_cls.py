import json,csv,random,re,collections
R=[json.loads(l) for l in open('scored.jsonl') if '"err"' not in l]
T={
'elev':r'элеватор(?!н\w* узел)|\bхпп\b|\bкхп\b|хлебоприем|хлебопродукт|зернохранилищ|зерносушил|приемк\w* зерна|хранени\w* зерна|комбикормов\w* завод',
'seed':r'семен(?:а|ам|ами)\b.*(?:производ|оптом|агро|сорт|гибрид)|семеновод|семенн\w* завод|селекц|оригинатор|элитн\w* семен|семена (?:подсолнечника|кукурузы|пшеницы|сои|рапса|ячменя|гороха|льна|многолетних трав|овощей)|питомник|саженц',
'exp':r'экспорт\w* (?:зерна|пшеницы|ячменя|масличн|бобов|нута|чечевицы|льна|подсолнечн|семян|орехов|муки|масла)|grain (?:export|trad)|зернотрейд|трейдинг зерна|зерновая компания|зерновой терминал',
'nuts':r'(?:фундук|грецк\w* орех|кедров\w* орех|миндаль|орехи оптом|ореховодств|переработк\w* орех|производ\w* орех)',
'berr':r'ягод|клубник|голубик|клюкв|брусник|облепих|жимолост|смородин|малин(?:а|ы|у)\b|шоков\w* заморозк\w* ягод',
'food':r'(?:молочн\w*|мясокомбинат|мясоперерабат|хлебозавод|хлебокомбинат|кондитерск\w* фабрик|маслозавод|маслоэкстракц|сыродельн|сыроварн|мукомольн|мельничн\w* комбинат|крупозавод|сахарн\w* завод|консервн\w* завод|ликеро|пивоваренн|птицефабрик|рыбоперераб|молокозавод|пищев\w* производств|производител\w* (?:продуктов|молочной|мясной|колбас|хлеба|сыров|масла|круп|муки|макарон|соков|консервов|полуфабрикатов))',
}
NEGT=r'интернет-магазин|купить|оборудован|техника|станк|дилер|запчаст|ремонт|новости|журнал|портал|блог|форум|рецепт|доставка|кафе|ресторан|пицц|суши|автомоб|мебел|плитк|строит|квартир|недвижим|школ|обучен|курс'
TC={k:re.compile(v,re.I) for k,v in T.items()};NEG=re.compile(NEGT,re.I)
res=[]
for r in R:
    t=r['title']
    segs=[k for k,c in TC.items() if c.search(t)]
    if not segs: continue
    res.append((r,segs,bool(NEG.search(t))))
c=collections.Counter();cn=collections.Counter()
for r,s,n in res:
    for k in s: (cn if n else c)[k]+=1
print('чистые по title:',dict(c)); print('с негативом в title:',dict(cn))
clean=[x for x in res if not x[2]]
print('всего чистых',len(clean))
json.dump([{'d':r['d'],'title':r['title'],'segs':s,'inn':r['inn'],'unp':r['unp'],'sc':r['sc']} for r,s,n in clean],open('title_clean.json','w'),ensure_ascii=False)
random.seed(5)
for r,s,n in random.sample(clean,60): print(f"{','.join(s):9} {r['d'][:30]:30} | {r['title'][:95]}")
