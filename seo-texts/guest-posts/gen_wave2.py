# Независимая проверка раскладки — солверу и собственной арифметике не верим
# --------------------------------------------------------------------------- #

READY = [('enger', 9), ('prokom', 15), ('prokom', 12), ('prokom', 10)]   # волна 1, в журнале
QUOTA = {1: 2, 5: 2, 6: 2, 7: 2, 13: 1, 17: 1}
PRIOR = {1: 1, 5: 1, 9: 1, 10: 1, 12: 1, 15: 1}
SITE_OF = {'enger-air.ru': 'enger', 'prokompressor.ru': 'prokom'}
NUM_OF = {
    'kompressornye-stantsii-szhatogo-vozdukha': 7,
    'kompressory-200-bar': 6,
    'kompressory-40-bar': 17,
    'refrizheratornye_osushiteli': 13,
    'vintovye_kompressory': 1,
    'azotnye-ustanovki': 5,
}


def verify() -> list:
    errs, used, dealers = [], {}, []
    e = sum(1 for s, _ in READY if s == 'enger')
    p = len(READY) - e
    for j in JOBS:
        if not 1 <= len(j['links']) <= 3:
            errs.append(f"{j['slug']}: {len(j['links'])} ссылок (норма 1-3)")
        for url, _ in j['links']:
            host = url.split('//')[1].split('/')[0]
            if host in SITE_OF:
                site = SITE_OF[host]
                n = next((v for k, v in NUM_OF.items() if k in url), None)
                if n is None:
                    errs.append(f"{j['slug']}: не опознан акцептор {url}")
                    continue
                used[n] = used.get(n, 0) + 1
                e, p = (e + 1, p) if site == 'enger' else (e, p + 1)
            else:
                dealers.append(host)
    for n, c in used.items():
        total = c + PRIOR.get(n, 0)
        if total > QUOTA.get(n, 1):
            errs.append(f'№{n}: {total} ссылок при квоте {QUOTA.get(n)}')
    if len(dealers) != len(set(dealers)):
        errs.append(f'дилер повторяется: {dealers}')
    if len(set(dealers)) != 6:
        errs.append(f'дилерских доменов {len(set(dealers))}, а нужно 6: {sorted(set(dealers))}')
    if round(e / (e + p), 2) != 0.40:
        errs.append(f'Enger {e} / ProKompressor {p} = {e / (e + p):.0%}, а нужно 40%')
    print(f'проверка раскладки: Enger {e} / ProKompressor {p} = {e / (e + p):.0%}, '
          f'дилеров {len(set(dealers))}/6, статей {len(JOBS)} '
          f'-> {"ошибок нет" if not errs else str(len(errs)) + " ошибок"}')
    for x in errs:
        print('  ✗', x)
    return errs


def main() -> int:
    if verify():
        print('раскладка не сходится — генерацию не запускаю', file=sys.stderr)
        return 1
    gw.JOBS = JOBS
    gw.main()
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
