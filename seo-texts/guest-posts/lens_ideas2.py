#!/usr/bin/env python3
"""Чего не хватает в приёмке: четыре независимые роли предлагают недостающие линзы.

Текущий набор (12 линз) собран в августе под первую волну статей. С тех пор задача
изменилась: появилась вторая ветка — жанровые статьи для площадок, которые к нашей
теме отношения не имеют, — и вся кампания встала на покупные размещения через биржу.
Часть рисков этим набором не покрыта.

Каждая роль смотрит со своей стороны и не знает мнения остальных: редактор площадки,
юрист по рекламе, SEO-аудитор и практик линкбилдинга. Совпадения между ролями и есть
кандидаты в новые линзы — так же собирался исходный набор (`LENS-JUDGES.md`).

    python3 lens_ideas2.py
"""
from __future__ import annotations

import concurrent.futures as cf
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import gen_provider as gp                                    # noqa: E402

OUT = os.environ.get('LENS_OUT', 'lens-ideas2.jsonl')

CURRENT = """Сейчас статью проверяют 12 линз. Каждая возвращает PASS/FAIL и точечные
правки «цитата -> замена»; правки применяет код, до трёх кругов.

1. link — якорь не обещает лишнего, абзац самодостаточен, нет «читайте здесь».
   Ставит баллы МЕСТО (позиция и окружение ссылки) и РЕЛЕВАНТНОСТЬ (цепочка
   якорь -> абзац -> целевая страница); ниже 7 по любой шкале = FAIL.
2. platform — глазами выпускающего редактора площадки: жанр и тон издания.
3. engineer — физика верна, единицы не перепутаны, советы не опасны.
4. neutral — не реклама: нет призывов, оценочных прилагательных у брендов,
   схемы «проблема -> единственное решение по ссылке».
5. logic — заголовок обещает то, что текст даёт; нет советов из ниоткуда.
6. seo — ключ в первых двух абзацах и 3-5 словоформ, H2 как реальные запросы.
7. seo_yandex — риск Баден-Бадена: переспам, роботные конструкции.
8. seo_google — Helpful Content, E-E-A-T, scaled content abuse, thin content.
9. antiai — стилометрия LLM: симметричные тройки, апофегматические финалы.
10. language — корректор и филолог: опечатки, кальки, канцелярит.
11. teh_technolog — инженерная правда утверждений, установка «оцени честно».
12. teh_skeptik — та же правда, установка «найди неправду; не нашёл — скажи».

Плюс механический гейт до линз: объём 5200-14000 знаков, стоп-слова, длинное тире,
белый список ссылок и их позиции (не в первом и не в последнем абзаце), целостность
тегов, разрешённые теги p/h2/h3/a/strong/ul/ol/li."""

CONTEXT = """=== ЧТО ЗА КАМПАНИЯ ===
Поставщик промышленного компрессорного оборудования (ООО «Руспром», Россия) размещает
24 гостевые статьи на чужих сайтах через биржу Miralinks. Ссылки ведут на его сайты:
prokompressor.ru, enger-air.ru и четыре дилерских.

Размещения ДВУХ типов, и это важно:

* 15 ТЕМАТИЧЕСКИХ — площадки про промышленность, стройку, климат, металл. Там статья
  это отраслевой разбор, читатель решает производственную задачу.
* 9 ЖАНРОВЫХ — площадки, к нашей теме отношения не имеющие: подборки цитат, мемы,
  светская хроника, игровые гайды, календарь праздников, дачная мебель. Проверка
  семантики показала: наша доля аудитории там 0-1%, прямого моста нет. Статья пишется
  В ЖАНРЕ ПЛОЩАДКИ («День машиностроителя», «От песка до RTX: как делают видеокарты»,
  «Как сжатый воздух убивает»), а ссылка стоит внутри как справка на источник.

Все размещения ПОКУПНЫЕ. Статьи пишет модель, редактирует конвейер, публикует
владелец площадки после модерации."""

ROLES = {
 'редактор': """Ты выпускающий редактор площадки, которая продаёт размещения на бирже.
Через тебя проходят десятки покупных статей в месяц, и ты отвечаешь за то, чтобы сайт
не превратился в свалку. Ты умеешь с первого абзаца отличить текст, написанный ради
ссылки, от материала, который читателю полезен.""",
 'юрист': """Ты юрист по рекламному праву РФ. Знаешь ФЗ-38 «О рекламе», требования
к маркировке интернет-рекламы (ERID, пометка «реклама», данные рекламодателя),
ответственность за отсутствие маркировки, а также требования к достоверности заявлений
о товаре, к сравнению с конкурентами и к безопасности рекомендаций в промышленной
тематике.""",
 'seo': """Ты SEO-аудитор, который делает вскрытия провалившихся ссылочных кампаний.
Ты видел, как размещения не давали ничего: ссылка попала в нерелевантное окружение,
страница не проиндексировалась, статью удалили через полгода, площадка обвалилась
под фильтром и утащила профиль за собой.""",
 'линкбилдер': """Ты практик линкбилдинга с десятилетним стажем в рунете. Ты знаешь,
что бывает после публикации: как площадки вырезают ссылки через месяц, как статьи
переезжают в архив и теряют вес, как одинаковые тексты на разных донорах склеиваются,
как редакторы дописывают в статью свою рекламу.""",
}

PROMPT = """{role}

{context}

=== ТЕКУЩАЯ ПРИЁМКА ===
{current}

=== ЗАДАЧА ===
Найди, ЧТО ЭТИ 12 ЛИНЗ НЕ ЛОВЯТ. Предложи 3-5 недостающих проверок — с точки зрения
своей роли, а не вообще.

Требования к предложению:
* проверка должна быть выполнима по ТЕКСТУ статьи и метаданным (заголовок, описание,
  анонс, ссылки, якоря). Проверки, требующие смотреть опубликованную страницу или
  ждать месяц, помечай отдельно как «постпубликационная»;
* не повторяй то, что уже делают 12 линз — скажи прямо, если считаешь, что имеющаяся
  линза покрывает риск лишь частично, и чего именно ей не хватает;
* для каждой проверки: что именно ищем, на каком примере это видно, и что считать
  провалом (когда ставить FAIL).

=== ФОРМАТ ОТВЕТА (plain text, без markdown) ===
Для каждой проверки блок:
ЛИНЗА: <короткое имя латиницей>
ЧТО ЛОВИТ: <одно-два предложения>
ПОЧЕМУ 12 ЛИНЗ ЭТОГО НЕ ВИДЯТ: <одно предложение>
ПРИЗНАК ПРОВАЛА: <когда FAIL>
ТИП: до публикации | постпубликационная
ВАЖНОСТЬ: критично | полезно | на будущее
---
"""


def one(item):
    name, role = item
    try:
        msg = gp.call(None, [{'role': 'user', 'content': PROMPT.format(
            role=role, context=CONTEXT, current=CURRENT)}],
            model='claude-fable-5', attempts=4)
        raw = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    except Exception as e:                                   # noqa: BLE001
        return {'role': name, 'error': repr(e)[:130]}
    import re
    lenses = []
    for block in raw.replace('*', '').split('---'):
        g = lambda k: (re.search(rf'^{k}:\s*(.+?)(?=\n[А-ЯA-Z][А-ЯA-Z 0-9]{{2,}}:|\Z)',
                                 block, re.S | re.M) or [None, ''])[1].strip()
        if g('ЛИНЗА'):
            lenses.append({'name': g('ЛИНЗА'), 'catches': g('ЧТО ЛОВИТ'),
                           'gap': g('ПОЧЕМУ 12 ЛИНЗ ЭТОГО НЕ ВИДЯТ'),
                           'fail': g('ПРИЗНАК ПРОВАЛА'), 'when': g('ТИП'),
                           'weight': g('ВАЖНОСТЬ')})
    return {'role': name, 'lenses': lenses, 'raw': raw}


def main():
    f = open(OUT, 'w', encoding='utf-8')
    with cf.ThreadPoolExecutor(max_workers=4) as ex:
        for rec in ex.map(one, ROLES.items()):
            f.write(json.dumps(rec, ensure_ascii=False) + '\n')
            f.flush(); os.fsync(f.fileno())
            print('\n=== %s (%d предложений)' % (rec['role'], len(rec.get('lenses') or [])),
                  flush=True)
            for l in rec.get('lenses') or []:
                print('  %-22s [%s, %s] %s' % (l['name'][:22], l['weight'][:8], l['when'][:16],
                                               l['catches'][:96]))
            if rec.get('error'):
                print('  ОШИБКА:', rec['error'])
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
