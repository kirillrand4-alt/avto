# ссылки этой волны против остатка квот (после волн 1 и 2)
FREE_BEFORE = {2: 1, 3: 2, 4: 2, 6: 1, 7: 1, 8: 2, 9: 1, 10: 1, 14: 1}
NUM_OF = {'adsorbtsionnye_osushiteli': (3, 'enger'), 'bezmaslyanye_kompressory': (4, 'enger'),
          'kompressornye-stantsii-szhatogo-vozdukha/mks': (8, 'prokom'),
          'kompressornye-stantsii-szhatogo-vozdukha': (7, 'prokom'),
          'prokompressor.ru/services': (10, 'prokom')}


def verify() -> list:
    errs, used, e, p = [], {}, 0, 0
    for j in JOBS:
        if not 1 <= len(j['links']) <= 3:
            errs.append(f"{j['slug']}: {len(j['links'])} ссылок")
        for url, _ in j['links']:
            # самый длинный совпавший ключ - иначе /mks спутается с родителем
            key = max((k for k in NUM_OF if k in url), key=len, default=None)
            if key is None:
                errs.append(f"{j['slug']}: не опознан акцептор {url}")
                continue
            n, site = NUM_OF[key]
            used[n] = used.get(n, 0) + 1
            e, p = (e + 1, p) if site == 'enger' else (e, p + 1)
    for n, c in used.items():
        if c > FREE_BEFORE.get(n, 0):
            errs.append(f'№{n}: берём {c}, свободно {FREE_BEFORE.get(n, 0)}')
    if e + p and round(e / (e + p), 2) != 0.40:
        errs.append(f'Enger {e} / ProKompressor {p} = {e / (e + p):.0%}, нужно 40%')
    print(f'проверка волны 3: Enger {e} / ProKompressor {p} = {e / (e + p):.0%}, '
          f'акцепторы {sorted(used)}, статей {len(JOBS)} -> '
          f'{"ошибок нет" if not errs else str(len(errs)) + " ошибок"}')
    for x in errs:
        print('  ✗', x)
    return errs


def main() -> int:
    if verify():
        print('раскладка не сходится - генерацию не запускаю', file=sys.stderr)
        return 1
    gw.JOBS = JOBS
    gw.main()
    return 0


