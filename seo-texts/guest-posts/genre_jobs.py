#!/usr/bin/env python3
"""Жанровый заход для площадок, где прямого моста нет (решение владельца 19.08).

Десять весовых площадок получили фит 1-2/10 у двух независимых прогонов: пересечения
аудитории с компрессорным оборудованием там нет, и статья «про нас» будет инородной.
Но ссылка с них нужна - это самый дешёвый вес в проекте (citaty.info даёт 9 ₽ за
тысячу органики при Authority 49).

Меняется постановка задачи. Обычный планировщик ищет мост ОТ нашей темы К аудитории
и честно отказывается, когда моста нет. Здесь наоборот: агент ищет тему САМОЙ ПЛОЩАДКИ,
внутри которой упоминание производства уместно, а ссылка стоит справкой. Статья живёт
по законам площадки, наша ссылка в ней - деталь, а не цель.

Приём известный и рабочий: на площадке про праздники это «День машиностроителя» с
историей профессии, на доске объявлений - разбор рабочих профессий на производстве,
на развлекательной - промышленные рекорды. Читатель получает свой контент, ссылка
стоит в естественном месте.

Риск честный: такие статьи слабее по влиянию на позиции - Google взвешивает
тематическую близость донора. Это ставка на вес и на Яндекс, а не на переходы.

    python3 genre_jobs.py [донор ...]
"""
from __future__ import annotations

import concurrent.futures as cf
import json, os, sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
import gen_provider as gp                                    # noqa: E402
from plan_jobs import GENRE, decisions, load, pages_for, parse  # noqa: E402

OUT = os.environ.get('GENRE_OUT', 'genre-jobs.jsonl')

# Кому что: сайт назначается по квотам владельца - основной и сателлиты вперёд.
ASSIGN = {
    'citaty.info': 'prokompressor.ru', 'berkat.ru': 'prokompressor.ru',
    'kakoj-segodnja-prazdnik.com': 'prokompressor.ru', '4tololo.ru': 'prokompressor.ru',
    'tvcenter.ru': 'prokompressor.ru', 'twizz.ru': 'prokompressor.ru',
    'get-color.ru': 'prokompressor.ru', 'satom.ru': 'prokompressor.ru',
    'gorod24.online': 'berg-compressor.com', 'afk-arena.com': 'berg-compressor.com',
}

PROMPT = """=== РЕШЕНИЯ ВЛАДЕЛЬЦА (приоритет выше любых таблиц и прогнозов) ===
{decisions}

=== ЗАДАЧА ===
Ты придумываешь статью для площадки, которая НЕ про промышленность.

Заказчик - поставщик компрессорного оборудования (ООО «Руспром»): винтовые и поршневые
компрессоры, компрессорные станции, генераторы азота и кислорода, осушители, ресиверы.
Ему нужна ссылка с этой площадки. Прямого пересечения аудитории с товаром нет - это
установленный факт, спорить с ним не нужно.

ЗАДАЧА ИНАЯ, ЧЕМ ОБЫЧНО. Не ищи мост от компрессоров к читателю - его нет. Иди с другой
стороны: найди тему, которая ЕСТЕСТВЕННА ДЛЯ ЭТОЙ ПЛОЩАДКИ и внутри которой упоминание
производства уместно само по себе. Статья должна быть настоящим материалом этой площадки,
интересным её читателю без всякой ссылки. Ссылка внутри стоит как справка на источник -
одна, в содержательном месте, не в лиде и не в подвале.

=== ПЛОЩАДКА ===
домен: {dom}
жанр площадки: {genre}
чем живёт по реальным поисковым запросам: {why}
лимиты карточки биржи: ссылок в статье {max_links}, наших доменов {max_domains}

=== НАШ САЙТ: {site} ===
{pages_block}

=== РАБОЧИЕ ПРИЁМЫ (примеры, не список для копирования) ===
* площадка про праздники -> профессиональный праздник (День машиностроителя, День
  металлурга, День работника нефтяной и газовой промышленности): история даты, чем
  занимаются эти люди, как устроено их производство;
* доска объявлений с вакансиями -> рабочие профессии на производстве: кто нужен
  заводам, что за оборудование обслуживают, как выглядит смена;
* развлекательная площадка -> промышленные рекорды и масштабы: самые большие машины,
  сколько воздуха нужно заводу, как устроены вещи, которыми пользуются каждый день;
* цитаты -> инженеры и изобретатели, их фразы о труде и деле;
* туристический портал -> производства, куда водят экскурсии; промышленный туризм;
* дача и хозяйство -> техника в частном хозяйстве, где нужен сжатый воздух.

Придумай СВОЙ ход под эту конкретную площадку - шаблон из списка бери только если он
действительно ложится. Тема должна быть такой, чтобы редактор площадки взял её и без
ссылки.

=== ЧЕГО НЕЛЬЗЯ ===
1. Ссылок больше лимита. Якорь - только БРЕНДОВЫЙ («Компрессор Центр», «ENGER») или
   БЕЗАНКОРНЫЙ (домен). Коммерческий якорь редактор такой площадки завернёт.
2. Рекламных подводок, призывов, оценок вроде «ведущий поставщик».
3. Выдуманных фактов, чисел и местных подробностей.
4. Статьи, которая на 80% про компрессоры с декоративным вступлением - это тот же
   натянутый мост, только замаскированный. Промышленная часть должна быть органичной
   частью темы площадки, а не её содержанием.

=== ФОРМАТ ОТВЕТА (строго, plain text, без markdown и JSON) ===
ВЕРДИКТ: годен | отказ
SLUG: короткий-слаг-латиницей
ТЕМА: заголовок статьи, как он выглядел бы на этой площадке
СТРАНИЦА: полный URL нашей страницы (со слешем в конце)
ЯКОРЬ: текст якоря (брендовый или безанкорный)
СТРАНИЦА2: нет
ЯКОРЬ2: нет
УГОЛ: 2-4 предложения - о чём статья и в каком месте появляется наша тема
КЕЙС: одно предложение, обезличенно, или «не нужен»
СКЕЛЕТ: структура статьи под жанр площадки
ЗАМЕТКА О ПЛОЩАДКЕ: кто читает и как с ними говорить
SEO: главный ключ статьи (по теме площадки, не по компрессорам) + сопутствующие
ПОЧЕМУ: 3-4 строки - почему редактор площадки возьмёт этот материал и почему
        ссылка в нём не выглядит инородной
"""


def one(args):
    dom, prompt = args
    try:
        msg = gp.call(None, [{'role': 'user', 'content': prompt}],
                      model='claude-fable-5', attempts=4)
        raw = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    except Exception as e:                                   # noqa: BLE001
        return {'donor': dom, 'error': repr(e)[:150]}
    rec = {'donor': dom, 'site': ASSIGN[dom], 'mode': 'жанровый', **parse(raw), 'raw': raw}
    rec['verdict'] = (rec.get('verdict') or '?').split()[0].lower()
    import re
    m = re.search(r'^ТЕМА:\s*(.+)$', raw, re.M)
    rec['title'] = m.group(1).strip() if m else ''
    return rec


def main():
    cards, v15, pq, sem, th = load()
    doms = sys.argv[1:] or list(ASSIGN)
    done = set()
    if os.path.exists(OUT):
        for line in open(OUT, encoding='utf-8'):
            if line.strip():
                r = json.loads(line)
                if not r.get('error'):
                    done.add(r['donor'])
    todo = [d for d in doms if d not in done]
    print(f'площадок: {len(doms)} | готово: {len(done)} | к планированию: {len(todo)}', flush=True)
    tasks = []
    for d in todo:
        c = cards.get(d, {})
        s = sem.get(d, {})
        tasks.append((d, PROMPT.format(
            decisions=decisions(), dom=d, genre=GENRE.get(d, ''), why=s.get('why', ''),
            max_links=c.get('max_links', '1'), max_domains=c.get('max_domains', '1'),
            site=ASSIGN[d], pages_block=pages_for(ASSIGN[d], v15, pq, limit=10))))
    f = open(OUT, 'a', encoding='utf-8')
    with cf.ThreadPoolExecutor(max_workers=4) as ex:
        for rec in ex.map(one, tasks):
            f.write(json.dumps(rec, ensure_ascii=False) + '\n')
            f.flush(); os.fsync(f.fileno())
            print('  %-28s %-7s %s' % (rec['donor'], rec.get('verdict', 'ERR'),
                                       (rec.get('title') or rec.get('error') or '')[:70]), flush=True)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
