def city_to_region(city):
    c = (city or '').strip()
    if not c: return None
    # уже регион?
    if re.search(r'(область|край|республик|автономн|Москва|Санкт-Петербург|Севастополь)', c, re.I):
        return c.replace('г. ','').strip()
    base = re.sub(r'^г\.?\s*', '', c).split(',')[0].strip()
    return CITY2REGION.get(base)

REG_CANON = {' - Кузбасс':'', ' - Югра':'', ' - Чувашия':''}
def canon_region(r):
    for a,b in REG_CANON.items(): r=r.replace(a,b)
    return r.strip()

proj = json.load(open(os.path.join(D,'projects-index.json'), encoding='utf-8'))
idx = {o['client']: o for o in json.load(open(os.path.join(D,'client-revenue-index.json'), encoding='utf-8'))}

reg_projects = Counter_like = defaultdict(int)
reg_companies = defaultdict(dict)   # region -> {client: revenue}
reg_cities = defaultdict(set)
unresolved = defaultdict(int)

for r in proj:
    client = (r.get('client') or '').strip()
    info = idx.get(client)
    region = None
    if info and info.get('matched') and info.get('region'):
        region = canon_region(info['region'])
    if not region:
        region = city_to_region(r.get('city'))
    if not region:
        unresolved[(r.get('city') or '').strip() or '(нет города)'] += 1
        region = '(регион не определён)'
    reg_projects[region] += 1
    reg_cities[region].add((r.get('city') or '').strip())
    if info and info.get('revenue') and not info.get('bankrupt'):
        # берём макс. выручку, если компания встречается многократно
        cur = reg_companies[region].get(client, 0)
        if info['revenue'] > cur:
            reg_companies[region][client] = info['revenue']

# свод
out = {}
for region, pc in reg_projects.items():
    comps = sorted(reg_companies[region].items(), key=lambda x: x[1], reverse=True)
    out[region] = {
        'projects': pc,
        'companies_with_revenue': len(comps),
        'top_companies': [{'name': n, 'revenue': v} for n, v in comps[:8]],
    }

ordered = dict(sorted(out.items(), key=lambda x: x[1]['projects'], reverse=True))
json.dump(ordered, open(os.path.join(D,'region-index.json'),'w'), ensure_ascii=False, indent=1)

