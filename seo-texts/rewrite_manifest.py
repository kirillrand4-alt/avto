# -*- coding: utf-8 -*-
"""Чистовая редактура манифеста через Fable: ТОЛЬКО язык, без изменения смысла и цифр.
Выход: manifest-clean.md"""
import os
import gen_provider as gp

DIR = os.path.dirname(os.path.abspath(__file__))

PROMPT = """Ты - редактор-филолог. Приведи деловое письмо в порядок ПО ЯЗЫКУ, не меняя смысл.

ЖЁСТКИЕ ПРАВИЛА (нарушать нельзя):
1. СОХРАНИ ВСЕ факты, аргументы, выводы и структуру пунктов (1, 1.1...1.6, 2, CTA) - ничего не
   добавляй по смыслу и ничего не выбрасывай. Порядок мыслей не меняй.
2. СОХРАНИ ВСЕ ЦИФРЫ И ПРОЦЕНТЫ ровно как в оригинале (1000, 176, 824, 73%, 16%, 11%, 35%, 5%,
   17,7%, 2,7%, 6%, 2,5%, 0,3-0,5%, ~30%, 13,5 лида, ~1 лид, 200-500, 4 задачи и т.д.).
   НЕ выдумывай новых цифр, источников, оговорок и обоснований. НЕ добавляй «как усилить».
3. Что делать: исправь грамматику, пунктуацию, орфографию; разбей предложения-монстры на
   короткие (одна мысль - одно предложение); добавь абзацы; сделай единый деловой регистр
   (убери канцелярит «изысканиям», «в натуральном выражении» и разговорное «на глаз» - замени
   нейтральным, НЕ меняя смысла); единообразная нумерация.
4. ЕДИНСТВЕННАЯ правка формулировки по смыслу: фразу про «+30% категорийного трафика минимум»
   подай как ГИПОТЕЗУ/оценочное предположение (например «по нашей гипотезе - ориентировочно +30%»),
   но саму цифру 30% и «13,5 лида» сохрани.
5. Опечатки чини молча (какой-либо, открывается, в совокупности, проверены/отрецензированы вместо
   «проревьюированы», Fable 5 от Claude вместо «Fabl 5 от Clod»).

Выдай ТОЛЬКО готовый чистовой текст письма, без комментариев и пояснений."""


def main():
    manifest = open(os.path.join(DIR, 'manifest.txt'), encoding='utf-8').read()
    prompt = PROMPT + '\n\n=== ОРИГИНАЛ ===\n' + manifest
    client = gp.make_client()
    msg = gp.call(client, [{'role': 'user', 'content': prompt}], model='claude-fable-5')
    out = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    open(os.path.join(DIR, 'manifest-clean.md'), 'w', encoding='utf-8').write(out)
    print(out)


if __name__ == '__main__':
    main()
