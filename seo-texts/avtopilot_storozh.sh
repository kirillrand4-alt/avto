#!/bin/bash
# СТОРОЖ НАД АВТОПИЛОТОМ. Цикл снимков однажды исчез вместе со своей оболочкой: пачка 8
# началась в 12:22, лог пуст, процессов нет, в журналах причины не осталось. Пока причина
# не названа, ставлю над ним сторожа: раз в минуту смотрит, жив ли цикл, и поднимает его.
# Каждый подъём записывается в лог с временем — если подъёмы участятся, это будет видно
# числом, а не догадкой.
# ОГОВОРКА К ПРОВЕРКЕ ЖИВОСТИ. `pgrep -f` находит строку в ЛЮБОЙ командной строке, включая
# мои же диагностические команды, где это имя написано. Для самого сторожа это безвредно
# (его собственная строка — `avtopilot_storozh.sh`), но пока я в соседнем окне печатаю
# `pgrep -f avtopilot_tehkontakty.sh`, сторож минуту считает цикл живым. Проверять живость
# по PID-файлу надёжнее; менять на ходу не стал, чтобы не поднять ВТОРОЙ цикл — два цикла
# пишут один и тот же файл снимков и затрут друг друга.
SCR="$1"
cd /home/user/avto/seo-texts
while true; do
  if ! pgrep -f "avtopilot_tehkontakty.sh" > /dev/null; then
    echo "$(date -u +%H:%M) сторож: цикл не найден — поднимаю" >> "$SCR/avtopilot.log"
    setsid nohup bash avtopilot_tehkontakty.sh "$SCR" > /dev/null 2>&1 < /dev/null &
    sleep 30
  fi
  sleep 60
done
