# --- нормализация названий -------------------------------------------------

# Организационно-правовые формы и обёртки, которые надо снять перед сравнением.
# Убираем и «филиал», и «группа компаний»: в hh работодатель часто записан
# как холдинг или филиал, а в реестре ЭПБ — как конкретное юрлицо.
LEGAL_FORMS = (
    r"(ООО|ОАО|ПАО|АО|ЗАО|НАО|ПРАО|ОДО|ГУП|ФГУП|МУП|МКУ|ФКУ|ФКП|ФГУ|ФГБУ|ФГАУ|"
    r"ФГБОУ|ГБУ|ГАУ|МБУ|АНО|НКО|НПО|НПП|НПЦ|ПК|СПК|ТОО|АООТ|УК|ГК|ХОЛДИНГ|ФИЛИАЛ|"
    r"КОМПАНИЯ|КОРПОРАЦИЯ|ГРУППА КОМПАНИЙ|ГРУППА)"
)


def norm_name(s):
    """
    Приводит название организации к сравнимому виду:
    верхний регистр, ё→е, снятие кавычек всех видов, скобки «(ИНН ...)»,
    любых знаков препинания и организационно-правовых форм, схлопывание пробелов.

    Это сознательно грубая нормализация. Она даёт НИЖНЮЮ оценку совпадений:
    пропускает «Ивдельское ЛПУМГ, филиал ООО Газпром трансгаз Югорск» против
    «ООО «Газпром трансгаз Югорск»», но не выдумывает ложных пар.
    """
    s = (s or "").upper().replace("Ё", "Е")
    s = re.sub(r"\(ИНН\s*\d+\)", " ", s)          # хвост «(ИНН 2630016211)» в реестре
    s = re.sub(r"[«»\"'`„“”]", " ", s)             # кавычки всех начертаний
    s = re.sub(r"[–—−]", "-", s)                   # тире к дефису
    s = re.sub(r"[^А-ЯA-Z0-9\- ]", " ", s)         # прочая пунктуация
    prev = None
    while prev != s:                               # формы могут идти подряд
        prev = s
        s = re.sub(r"(?:^|(?<=[\s\-]))" + LEGAL_FORMS + r"(?=$|[\s\-])", " ", s)
    return re.sub(r"[\s\-]+", " ", s).strip()


def loose_pairs(left_norms, right_norms, min_len=6):
    """
    Нестрогое сопоставление: одно нормализованное название целиком входит
    в другое. Ловит связки «холдинг — дочка» и «филиал — юрлицо», но даёт
    мусор («Паритет-Плюс» ~ «Т Плюс»). Используем только как ВЕРХНЮЮ границу,
    каждую пару в отчёте показываем поимённо, чтобы её можно было проверить.
    """
    out = defaultdict(set)
    for a in left_norms:
        if len(a) < min_len:
            continue
        for b in right_norms:
            if len(b) < min_len or a == b:
                continue
            if a in b or b in a:
                out[a].add(b)
    return out


# --- 1. агрегация реестра ЭПБ по предприятиям ------------------------------

def agg_centro(rows):
    """
    Сворачивает заключения ЭПБ по ИНН заказчика.

    Оговорка о честности счёта: строка — это заключение, а не обязательно машина.
    Часть строк по запросу «нагнетатель» описывает обвязку (трубопроводы, ЗС),
    а одна машина может иметь заключения разных лет. Поэтому число предприятий
    надёжнее числа строк, а «машин» ниже — верхняя оценка парка.
    """
    per = defaultdict(Counter)
    name = {}
    for r in rows:
        inn = r["inn_zakazchika"].strip()
        per[inn][r["srok"]] += 1
        per[inn]["vsego"] += 1
        if r["tip"] == "ТУ":
            per[inn]["tu"] += 1
        name.setdefault(inn, r["zakazchik"].strip())
    return per, name


def prioritet(vsego, istekaet):
    """
    Приоритет очереди на добор людей.

    Формула простая и проверяемая глазом: prioritet = машин всего + 2 x машин
    с истекающим сроком. Основной вес — размер парка (он же масштаб сделки),
    двойной вес истекающих — потому что там окно замены открыто прямо сейчас,
    а не когда-нибудь.
    """
    return vsego + 2 * istekaet


