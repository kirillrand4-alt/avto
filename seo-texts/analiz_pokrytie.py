def contact_index(contacts):
    """
    Строит индекс контактов по ИНН и по нормализованному названию.
    В накопителе ИНН заполнен далеко не везде — именно это и меряем.
    """
    by_inn = defaultdict(list)
    by_name = defaultdict(list)
    for c in contacts:
        inn = c["inn"].strip()
        if inn:
            by_inn[inn].append(c)
        by_name[norm_name(c["organization"])].append(c)
    return by_inn, by_name


def has_phone(c):
    return bool(c["phone"].strip())


def is_personal_phone(c):
    """Мобильный или прямой номер — то, что ведёт к человеку, а не к секретарю."""
    return c["phone_type"].strip() in ("мобильный", "прямой")


def is_named_email(c):
    return c["email_type"].strip() == "именная"


def age_days(c):
    try:
        y, m, d = (int(x) for x in c["observed_at"].split("-"))
        return (TODAY - date(y, m, d)).days
    except Exception:
        return None


