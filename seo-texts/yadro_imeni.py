# -*- coding: utf-8 -*-
"""Одно ли это предприятие: сверка по ядру имени.

ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Правило нужно сразу трём местам — снятию чужой привязки, сшивке
списков между сессиями, сверке площадок с ЕГРЮЛ, — и везде оно одно и то же. Считать его по
своему файлу нельзя ровно по той же причине, по какой нельзя считать общий номер по своей
выгрузке: у каждого получится своя правда.

ЦЕНА ОШИБКИ ИЗМЕРЕНА. Моё правило «названное рядом предприятие и есть работодатель» сняло
привязку у 449 человек. 1-я сессия сверила ядра и показала: у 52 из них «чужое» предприятие —
то же самое, названное иначе (АО «НИЖНЕКАМСКТЕХУГЛЕРОД» против «Нижнекамск-техуглерод»,
ПАО «ЯТЭК» против «ЯТЭК»). Без сверки правило молча вычёркивает живые контакты.

ЧТО СЧИТАЕТСЯ ЯДРОМ: имя без ОПФ, кавычек, дефисов, точек и пробелов, в нижнем регистре.
Совпадение — равенство ядер или вхождение одного в другое при длине не меньше пяти знаков.
Порог не украшение: «БСК» и «БЭСК» — разные юрлица, и короткое вхождение склеило бы их.
"""
import re

OPF = re.compile(
    r'\b(ООО|ОАО|ЗАО|ПАО|АО|НАО|ФГУП|ГУП|МУП|ФКП|ФГБУ|ФГУ|ГБУ|МБУ|УК|ТД|НПО|НПК|НПП|ПКФ|ПК|'
    r'КФХ|СПК|ИП|филиал|представительство|акционерн\w*|обществ\w*|'
    r'с\s*ограниченной\s*ответственностью|публичн\w*|непубличн\w*|закрыт\w*|открыт\w*|'
    r'управляющ\w*\s*компани\w*|компани\w*|групп\w*|концерн|холдинг|корпораци\w*)\b',
    re.I)
MUSOR_ZNAKI = re.compile(r'[«»"\'`\-–—.,()\[\]/\\\s№]+')
MIN_VHOZHDENIE = 5


def yadro(imya):
    """Слитная основа имени: без ОПФ, знаков и пробелов, в нижнем регистре."""
    v = OPF.sub(' ', imya or '')
    return MUSOR_ZNAKI.sub('', v).lower().replace('ё', 'е')


def to_zhe(a, b):
    """(одно ли предприятие, объяснение словами)."""
    ya, yb = yadro(a), yadro(b)
    if not ya or not yb:
        return False, 'у одного из имён ядра не осталось'
    if ya == yb:
        return True, f'ядра совпали: «{ya}»'
    if len(ya) >= MIN_VHOZHDENIE and ya in yb:
        return True, f'ядро «{ya}» содержится в «{yb}»'
    if len(yb) >= MIN_VHOZHDENIE and yb in ya:
        return True, f'ядро «{yb}» содержится в «{ya}»'
    return False, f'ядра разные: «{ya}» против «{yb}»'


if __name__ == '__main__':
    # Контрольные пары: первые пять — примеры 1-й сессии (должно быть «одно»),
    # последние — те, где склейка была бы ошибкой.
    proby = [('АО «НИЖНЕКАМСКТЕХУГЛЕРОД»', '«Нижнекамск-техуглерод»', True),
             ('АО «СНХЗ»', '«СНХЗ»', True),
             ('АО «АНПЗ ВНК»', '«АНПЗ ВНК»', True),
             ('ПАО «ЯТЭК»', '«ЯТЭК»', True),
             ('АО «РНПК»', '«РНПК»', True),
             ('АО «БСК»', '«БЭСК»', False),
             ('АО «Нижнекамсктехуглерод»', '«НКНХ»', False),
             ('Филиал АО «Сегежский ЦБК»', '«РУСАЛ Надвоицы»', False)]
    for a, b, ozhid in proby:
        est, poch = to_zhe(a, b)
        print(f'{"OK " if est == ozhid else "МИМО"} {a[:34]:<34} vs {b[:24]:<24} {poch}')
