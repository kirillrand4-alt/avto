def stroki(skolko_krupnyh=25, skolko_sluchajno=20, semya=11):
    rows = [r for r in csv.DictReader(open(VK, encoding='utf-8-sig'), delimiter=';')
            if not (r.get('domen') or '').strip()]

    def vyr(x):
        try:
            return float(re.sub(r'[^\d.]', '', x.get('revenue_rub') or '0') or 0)
        except ValueError:
            return 0.0

    random.seed(semya)
    vyborka = sorted(rows, key=vyr, reverse=True)[:skolko_krupnyh] + random.sample(
        rows, min(skolko_sluchajno, len(rows)))
    kol = [k for k in rows[0].keys() if k not in SKUCHNYE]
    t = 'КОЛОНКИ: ' + ' ; '.join(kol) + '\n\n'
    for r in vyborka:
        t += ' | '.join(f'{k}={(r.get(k) or "")[:70]}' for k in kol if (r.get(k) or '').strip()) + '\n'
    return t, rows


