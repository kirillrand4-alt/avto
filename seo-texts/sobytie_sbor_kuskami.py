# -*- coding: utf-8 -*-
"""НОВЫЙ сбор событий под рамки владельца: семь отраслей, вся страна, без порога.

Владелец: «нам нужно не текущие которые собранные, а новые собрать». Значит это не разбор
архива, а свежий прогон. Рамки его же: берём всё и сортируем потом; вся страна; признак
ставим широко, а не отсеиваем узко; тендеры не нужны, поэтому коллектор zakupki выключен.

Отрасли приоритета владельца (дословно): химическая и нефтехимическая, металлургия,
пищевая и фармацевтическая, целлюлозно-бумажная, энергетика, стекольная, цементная.

Триггеры беру РАННИЕ: не «запустили линию» (это уже поздно, оборудование куплено), а
«подписано соглашение», «прошёл госэкспертизу», «выделен участок», «начато строительство».
Штатный список TRIGGERS в модуле смещён к поздним стадиям, поэтому запросы задаю явно.

Коллектор news_scan читает ключ `queries` ТОЛЬКО если он передан явно; без него задание
молча уходит на свой каталог триггеров (на этом уже обжигалась 2-я сессия: вернулось
3 937 чужих материалов, и это выглядело как «запросы не дают ничего»).
"""
import sys
import time

sys.path.insert(0, '/home/user/avto/seo-texts/server')
import run_on_server as R  # noqa: E402

OTRASLI = [
    # химия и нефтехимия
    'химический завод', 'нефтехимический комбинат', 'нефтеперерабатывающий завод',
    'газоперерабатывающий завод', 'производство полимеров', 'завод минеральных удобрений',
    'производство аммиака', 'производство метанола',
    # металлургия
    'металлургический комбинат', 'сталелитейный завод', 'прокатное производство',
    'горно-обогатительный комбинат', 'алюминиевый завод', 'медеплавильный завод',
    # пищевая и фармацевтическая
    'молочный комбинат', 'мясоперерабатывающий завод', 'пивоваренный завод',
    'кондитерская фабрика', 'масложировой комбинат', 'фармацевтический завод',
    'производство лекарственных препаратов',
    # целлюлозно-бумажная
    'целлюлозно-бумажный комбинат', 'картонная фабрика', 'бумажная фабрика',
    # энергетика
    'ТЭЦ', 'ГРЭС', 'энергоблок', 'котельная', 'теплоэлектростанция',
    # стекло и цемент
    'стекольный завод', 'стеклотарный завод', 'цементный завод', 'производство цемента',
]
# РАННИЕ триггеры: от намерения до начала стройки
RANNIE = [
    'подписано соглашение о строительстве',
    'инвестиционное соглашение подписано',
    'прошёл государственную экспертизу проекта',
    'получено положительное заключение экспертизы',
    'выделен участок под строительство',
    'получено разрешение на строительство',
    'начато строительство завода',
    'приступили к проектированию',
]
# средние: стройка идёт, оборудование ещё не куплено
SREDNIE = [
    'строительство завода', 'строительство нового цеха', 'модернизация производства',
    'техническое перевооружение', 'расширение производства',
]

import os as _os
NACHALO = int(_os.environ.get('SBOR_OT', '0'))
SKOLKO = int(_os.environ.get('SBOR_PO', '10'))
_vse = [f'{t} {o}' for t in RANNIE for o in OTRASLI[:16]] \
       + [f'{t} {o}' for t in SREDNIE for o in OTRASLI]
zaprosy = _vse[NACHALO:NACHALO + SKOLKO]
print('всего запросов в наборе: %d, беру срез [%d:%d]' % (len(_vse), NACHALO, NACHALO + SKOLKO))
print('запросов построено: %d (ранних триггеров %d, средних %d, отраслей %d)'
      % (len(zaprosy), len(RANNIE), len(SREDNIE), len(OTRASLI)))

ARGS = {
    'collectors': ['xmlriver'],          # самый урожайный канал; остальные пойдут следом
    'queries': zaprosy,
    'xmlriver_queries': zaprosy,
    'xmlriver_engines': ['yandex', 'google'],
    'days': 45,
    'max_items': 8,
    'enrich': True,                      # нужен ИНН и разбор события, иначе это просто лента
    'write_db': True,                    # владелец: «в бд как новости складываются так же»
}
print('коллекторы: %s · days=%s · max_items=%s · enrich=%s · write_db=%s'
      % (ARGS['collectors'], ARGS['days'], ARGS['max_items'], ARGS['enrich'], ARGS['write_db']))

t0 = time.time()
r = R.submit('news_scan', ARGS, timeout=1700)
d = r.get('data') or r
print('\nответ пришёл за %d с, ключи ответа: %s' % (time.time() - t0, list(d)[:12]))
for k in ('rc', 'raw', 'items', 'events', 'saved', 'written', 'stats', 'summary'):
    if k in d:
        print('  %-10s %s' % (k, str(d[k])[:600]))
hvost = d.get('stdout_tail') or ''
if hvost:
    print('\n--- хвост вывода ---\n' + hvost[-4000:])
err = d.get('stderr_tail') or ''
if err:
    print('\n--- stderr ---\n' + err[-1200:])
