# -*- coding: utf-8 -*-
"""Готовый набор для дообогащения колонок chelovek и dolzhnost из kontekst."""
import re

CLEAN_HTML = re.compile(r'&nbsp;|&quot;|&amp;|&#\d+;|&[a-z]{2,6};')
CLEAN_TAG  = re.compile(r'\[(?:тел|email):\s*[^\]]*\]')       # маркер найденного контакта
OTCH       = r'(?:ович|евич|ьевич|иевич|овна|евна|ьевна|ична|инична|оглы|кызы|улы)'

R_FIO_FULL = re.compile(r'\b([А-ЯЁ][А-Яа-яёЁ]{2,}(?:-[А-ЯЁ][а-яё]+)?)\s+([А-ЯЁ][а-яё]{2,})\s+([А-ЯЁ][а-яё]+%s)\b' % OTCH)   # Фамилия Имя Отчество
R_FIO_IOF  = re.compile(r'\b([А-ЯЁ][а-яё]{2,})\s+([А-ЯЁ][а-яё]+%s)\s+([А-ЯЁ][А-Яа-яёЁ]{2,})\b' % OTCH)                      # Имя Отчество Фамилия
R_FIO_IO   = re.compile(r'\b([А-ЯЁ][а-яё]{2,})\s+([А-ЯЁ][а-яё]+%s)\b' % OTCH)                                               # Имя Отчество (фамилия обрезана)
R_FIO_FIO_ = re.compile(r'\b([А-ЯЁ][А-Яа-яёЁ]{2,})\s+([А-ЯЁ])\.\s?([А-ЯЁ])\.')                                              # Фамилия И.О.
R_FIO_IOF_ = re.compile(r'(?<!им\.\s)\b([А-ЯЁ])\.\s?([А-ЯЁ])\.\s?([А-ЯЁ][а-яё]{2,})\b')                                     # И.О. Фамилия
R_FIO_2W   = re.compile(r'\b([А-ЯЁ][А-Яа-яёЁ]{2,})\s+([А-ЯЁ][А-Яа-яёЁ]{2,})\b')                                             # пара слов -> разбор по словарю имён

# должность (брать ближайшее вхождение СЛЕВА от маркера контакта)
R_DOL = re.compile(r'''(?:
   генеральн\w+\s+директор\w*|исполнительн\w+\s+директор\w*|коммерческ\w+\s+директор\w*
  |техническ\w+\s+директор\w*|финансов\w+\s+директор\w*|ген\.?\s*директор\w*
  |директор\w*(?:\s+по\s+[а-яё]+(?:\s+и\s+[а-яё]+)?)?
  |зам(?:еститель|\.)\s*(?:генеральн\w+\s+)?(?:директор\w*|начальник\w*|главн\w+\s+[а-яё]+)(?:\s+по\s+[а-яё]+(?:\s+[а-яё]+)?)?
  |гл(?:авн\w*|\.)\s*(?:инженер\w*|энергетик\w*|механик\w*|технолог\w*|метролог\w*|бухгалтер\w*|специалист\w*)
  |начальник\w*(?:\s+(?:отдела|управления|службы|цеха|участка|смены|группы|бюро|сектора|производства|станции|филиала|ЦДС|УРО))?(?:\s+по\s+[а-яё]+)?
  |руководител\w*(?:\s+[а-яё]+){0,3}|заведующ\w*(?:\s+[а-яё]+){0,2}|управляющ\w*(?:\s+[а-яё]+){0,2}
  |ведущ\w+\s+(?:инженер\w*|специалист\w*|экономист\w*)(?:\s+[а-яё]+){0,2}
  |инженер\w*(?:\s+по\s+[а-яё]+)?|менеджер\w*(?:\s+по\s+[а-яё]+(?:\s+с\s+[а-яё]+)?)?
  |специалист\w*(?:\s+по\s+[а-яё]+)?|агент\w*\s+по\s+[а-яё]+|офис-менеджер|корпоративн\w+\s+секретар\w*
  |энергетик\w*|механик\w*|технолог\w*|метролог\w*|мастер\w*|диспетчер\w*|бухгалтер\w*|секретар\w*|экономист\w*|юрист\w*
  |помощник\w*(?:\s+[а-яё]+){0,2}
)''', re.I | re.X)

# ТЕХНИЧЕСКИЙ ЛПР — то, ради чего проект
R_TEH_LPR = re.compile(r'''(?:
   гл(?:авн\w*|\.)\s*инженер\w*
  |гл(?:авн\w*|\.)\s*энергетик\w*|\bОГЭ\b|энергослужб\w+|служб\w+\s+главн\w+\s+энергетик\w*
  |гл(?:авн\w*|\.)\s*механик\w*|\bОГМ\b|\bРМЦ\b|ремонтно[- ]механическ\w+
  |техническ\w+\s+директор\w*|директор\w*\s+по\s+(?:производств\w+|техническ\w+|эксплуатац\w+|капитальн\w+|общим\s+вопрос\w+)
  |зам\w*\.?\s*(?:ген\w*\.?\s*)?директор\w*\s+по\s+(?:производств\w+|техническ\w+|эксплуатац\w+|общим)
  |\bПТО\b|производственно[- ]техническ\w+
  |\bКИПиА\b|КИП\s*и\s*А|\bАСУ\s?ТП\b|метролог\w*
  |начальник\w*\s+(?:цеха|участка|смены|котельн\w+|компрессорн\w+|энергоцех\w*|производств\w+|станции|ТЭЦ)
  |гл(?:авн\w*|\.)\s*технолог\w*
  |служб\w+\s+эксплуатац\w+|отдел\w*\s+(?:эксплуатац\w+|ремонт\w*)
  |инженер\w*
)''', re.I | re.X)
R_ULICA = re.compile(r'(?:ул\.|улиц\w+|пр-т|проспект|пер\.|переул\w+|бульвар|шоссе|наб\.|площад\w+)\s*$', re.I)  # фильтр «ул. Энергетиков»

R_SNAB = re.compile(r'(?:снабжен\w+|закупк\w+|закупо\w+|\bОМТС\b|\bМТО\b|материально[- ]техническ\w+|тендерн\w+|комплектаци\w+)', re.I)

# --- МУСОР ---
R_MUSOR_PLACEHOLDER = re.compile(r'0000000|1234567|1111111|9999999|8888888')            # по цифрам номера
R_MUSOR_PDF         = re.compile(r'\d+\s+0\s+obj|endobj|/Type\s*/|\bxref\b')
R_MUSOR_SAYT        = re.compile(r'дизайн\s+сайта|разработ\w+\s+сайта|создание\s+сайта|сделано\s+в\s|веб[- ]?студи|карта\s+сайта|техподдержка\s+сайта|1С-Битрикс|megagroup', re.I)
R_MUSOR_CHUZHAYA    = re.compile(r'горячая\s+лини|телефон\s+доверия|единый\s+контакт-центр|call-центр|колл-центр|единый\s+номер|антикоррупц|роспотребнадзор|СберБанк|Россельхозбанк|@(?:mosreg|gov)\.ru', re.I)
R_MUSOR_REKVIZIT    = re.compile(r'\b(?:БИК|ОГРН|ОКПО|ОКТМО|ОКВЭД|ОКАТО|кор/счет|р/с|к/с|расчётн\w+\s+счёт|расчетн\w+\s+счет)\b', re.I)
R_MUSOR_HR          = re.compile(r'ваканс|резюме|трудоустрой|соискател|отдел\s+кадров', re.I)

if __name__=='__main__':
    import csv, collections
    rows=list(csv.DictReader(open('/home/user/work/OBHOD-kontakty-3s.csv',encoding='utf-8-sig'),delimiter=';'))
    c=collections.Counter()
    for r in rows:
        t=CLEAN_TAG.sub(' ',CLEAN_HTML.sub(' ',r['kontekst']))
        if R_FIO_FULL.search(t) or R_FIO_IOF.search(t) or R_FIO_FIO_.search(t): c['ФИО-строгий']+=1
        if R_DOL.search(t): c['должность']+=1
        m=R_TEH_LPR.search(t)
        if m and not R_ULICA.search(t[max(0,m.start()-14):m.start()]): c['техЛПР']+=1
        if R_SNAB.search(t): c['снабжение']+=1
        for n,p in [('мусор:плейсхолдер',R_MUSOR_PLACEHOLDER),('мусор:pdf',R_MUSOR_PDF),('мусор:сайт',R_MUSOR_SAYT),
                    ('мусор:чужая линия',R_MUSOR_CHUZHAYA),('мусор:реквизиты',R_MUSOR_REKVIZIT),('мусор:hr',R_MUSOR_HR)]:
            if p.search(re.sub(r'\D','',r['kontakt']) if n=='мусор:плейсхолдер' else t): c[n]+=1
    for k,v in c.most_common(): print('%-22s %4d'%(k,v))
