REGION = re.compile(
    r'(?:респ\w*|обл\w*|кра\w+|АО|округ\w*|г\.)\s*[«"]?([А-ЯЁ][А-Яа-яё\- ]{2,28})|'
    r'([А-ЯЁ][а-яё\-]{3,20})\s+(?:обл\w*|кра\w+|респ\w*)', re.I)


def dvuznak(okved):
    m = re.match(r'\s*(\d{2})', str(okved or ''))
    return m.group(1) if m else ''


def gorod_iz(t):
    """Города и области, названные в тексте новости. Грубо: слова с большой буквы в
    предложных оборотах «в Белогорске», «в Пермском крае»."""
    naydeno = set()
    for m in re.finditer(r'\bв\s+([А-ЯЁ][а-яё\-]{3,20})(?:е|ой|ом|и|у)?\b', t or ''):
        naydeno.add(m.group(1).lower())
    for m in re.finditer(r'([А-ЯЁ][а-яё\-]{3,20})\s+(?:област\w+|кра\w+|республик\w+)',
                         t or ''):
        naydeno.add(m.group(1).lower())
    return naydeno


