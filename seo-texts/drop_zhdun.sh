#!/bin/bash
# ЖДУН ДРОПА. Обменник перестал отвечать: `list` висит до таймаута, GET файла тоже, при этом
# GitHub и посторонний хост отвечают за доли секунды — значит сеть песочницы цела, а висит
# сам обменник. Через него ходит И раннер (задания на сервер), поэтому встала вся серверная
# работа, включая автопилот снимков: он всё равно не смог бы ни скачать список, ни выложить
# снимок.
#
# Ждун раз в три минуты стучится коротким запросом. Как только обменник ответит, он поднимает
# автопилот и записывает в общий лог время простоя — чтобы простой был виден числом, а не
# «кажется, что-то тормозило».
SCR="$1"
NACHALO=$(date -u +%s)
while true; do
  KOD=$(curl -s -o /dev/null -m 20 -w '%{http_code}' -H "X-Drop-Token: $DROP_TOKEN" "$DROP_URL/list" 2>/dev/null)
  if [ "$KOD" = "200" ]; then
    PROSTOY=$(( ($(date -u +%s) - NACHALO) / 60 ))
    echo "$(date -u +%H:%M) ждун: обменник ответил 200, простой $PROSTOY мин — поднимаю автопилот" >> "$SCR/avtopilot.log"
    setsid nohup bash avtopilot_storozh.sh "$SCR" > /dev/null 2>&1 < /dev/null &
    exit 0
  fi
  echo "$(date -u +%H:%M) ждун: обменник молчит (код '$KOD')" >> "$SCR/avtopilot.log"
  sleep 180
done
