# -*- coding: utf-8 -*-
"""Добавляет в существующие gen/payload-*.json поля против шаблонности и под E-E-A-T:
  variant           - индекс ротации формулировок (0..5) по хэшу слуга (детерминированно)
  facet_application  - отраслевой акцент для фасета (уникализирует близкие фасеты)
  byline / review_date - авторство Игоря Волкова + дата обновления
Ничего не генерирует, только дополняет payload. Запускать перед массовым прогоном."""
import json, os, glob, hashlib, sys

DIR = os.path.dirname(os.path.abspath(__file__))
REVIEW_DATE = sys.argv[1] if len(sys.argv) > 1 else '15 июля 2026'

BYLINE_URL = '/company/staff/igor-volkov/'


def variant(slug):
    return int(hashlib.md5(slug.encode()).hexdigest(), 16) % 6


def facet_application(dim, value):
    """Отраслевой акцент, чтобы близкие фасеты не были дублями."""
    v = str(value or '').lower()
    num = None
    import re
    m = re.search(r'(\d+[.,]?\d*)', v)
    if m:
        num = float(m.group(1).replace(',', '.'))
    if dim == 'pressure' and num:
        if num <= 8: return 'типовые 6-8 бар: пневмоинструмент, шиномонтаж, автосервис, покраска, деревообработка'
        if num <= 10: return 'универсальные 10 бар: запас над 8 бар с учётом потерь в магистрали, общее производство'
        if num <= 16: return 'повышенное 12-16 бар: металлообработка, лазерная резка, требовательные потребители'
        return 'высокое 25-40 бар и выше: пескоструй, ПЭТ-выдув, пневмоударное бурение, опрессовка сосудов под давлением'
    if dim == 'power' and num:
        if num < 15: return 'малая мощность: мастерские, сервисы, участки с 1-2 потребителями'
        if num < 55: return 'средняя мощность: производственные участки, цеха средней загрузки'
        if num < 160: return 'высокая мощность: крупные цеха, интенсивный сменный режим'
        return 'сверхвысокая мощность: заводы, непрерывное производство, магистральное снабжение'
    if dim == 'perf' and num:
        # num в л/мин; это ПРОИЗВОДИТЕЛЬНОСТЬ компрессора, НЕ объём ресивера
        if num < 1000: return 'небольшая производительность: отдельные посты, ремзона, участок с 1-2 потребителями'
        if num < 3000: return 'средняя производительность: цех с несколькими потребителями, сборка, покраска'
        if num < 10000: return 'высокая производительность: несколько линий, разветвлённая пневмосеть цеха, сменный режим'
        return 'большая производительность: крупное производство, магистральная сеть, непрерывная работа'
    if dim == 'receiver' and num:
        if num <= 270: return 'малый ресивер: буфер под пиковый разбор небольших потребителей'
        if num <= 500: return 'средний ресивер: сглаживание для участка средней сети'
        return 'крупный ресивер: буфер для разветвлённой сети и мощных установок'
    if dim == 'country':
        return 'акцент страны: доступность запчастей и сервиса, сроки поставки, независимость от импортной логистики (без политики)'
    if dim in ('drive',):
        return 'акцент привода: обслуживание передачи, ниша применения, честное сравнение с альтернативой'
    if dim in ('vsd', 'комплектация'):
        return 'акцент комплектации: что даёт и кому нужна, когда переплата не оправдана'
    return None


def byline_variants(vidx):
    pool = [
        f'Материал подготовил Игорь Волков, сооснователь ООО «Руспром», более 5580 реализованных проектов подбора компрессорного оборудования.',
        f'Подбор консультировал Игорь Волков, сооснователь ООО «Руспром» (свыше 5580 реализованных проектов).',
        f'Автор экспертизы: Игорь Волков, сооснователь ООО «Руспром», более 5580 внедрений компрессорного оборудования.',
        f'Технический разбор подготовлен под руководством Игоря Волкова, сооснователя ООО «Руспром» (5580+ проектов).',
        f'Проверено экспертом: Игорь Волков, сооснователь ООО «Руспром», более 5580 реализованных проектов.',
        f'Консультант материала - Игорь Волков, сооснователь ООО «Руспром», свыше 5580 проектов подбора оборудования.',
    ]
    return pool[vidx % len(pool)]


def main():
    n = 0; changed = 0
    for f in glob.glob(os.path.join(DIR, 'gen', 'payload-*.json')):
        d = json.load(open(f))
        n += 1
        d['variant'] = variant(d['slug'])
        d['review_date'] = REVIEW_DATE
        d['byline'] = byline_variants(d['variant'])
        d['byline_url'] = BYLINE_URL
        if d.get('facet_dimension'):
            fa = facet_application(d['facet_dimension'], d.get('facet_value'))
            if fa:
                d['facet_application'] = fa
        json.dump(d, open(f, 'w'), ensure_ascii=False, indent=1)
        changed += 1
    print(f'обогащено payload: {changed}/{n}')


if __name__ == '__main__':
    main()
