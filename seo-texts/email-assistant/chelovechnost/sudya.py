# -*- coding: utf-8 -*-
"""Слепая оценка «человечности» 20 писем Meyer (10 opus с ответом, 10 sonnet 12.10).

Владелец 12.10: «сравни на человечность письма, которые отбирал». Судьи не
знают модели: имена отправителей заменены, порядок перемешан. Два судьи
(sonnet и opus), результат каждого сразу на диск — прогон резюмируется.
"""
import io
import json
import os
import random
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", ".."))
os.environ.setdefault("PROVIDER_THINKING_FIELD", "omit")
import gen_provider as gp  # noqa: E402

ТУТ = os.path.dirname(os.path.abspath(__file__))
ИСХ = os.path.join(ТУТ, "..", "sravnenie-opus-sonnet-12-10.md")
т = io.open(ИСХ, encoding="utf-8").read()
письма = []
for блок in re.split(r"\n(?=## (?:OPUS|SONNET) )", т)[1:]:
    шапка, _, тело = блок.partition("\n")
    м = шапка.split("|")[0].replace("##", "").strip()
    тело = re.sub(r"Меня зовут [^,]+,", "Меня зовут Андрей,", тело.strip())
    письма.append({"модель": м, "компания": шапка.split("|")[1].strip(), "текст": тело})
random.seed(7)
random.shuffle(письма)
for i, п in enumerate(письма, 1):
    п["id"] = i
json.dump(письма, io.open(os.path.join(ТУТ, "ключ.json"), "w", encoding="utf-8"),
          ensure_ascii=False, indent=1)

ПРОМПТ = """Ты опытный руководитель отдела продаж B2B и редактор деловой переписки.
Ниже 20 холодных писем от менеджера компании, продающей фотосепараторы и
рентген-инспекцию пищевым и промышленным предприятиям. Оцени каждое по одной оси —
«ЧЕЛОВЕЧНОСТЬ»: насколько письмо читается как написанное живым менеджером для
ЭТОЙ компании, а не как шаблон или текст от ИИ.

Признаки шаблона: гладкие параллельные конструкции, канцелярит, безличная
правильность, общие фразы, которые подойдут любой компании, пустые связки
(«в связи с этим обращаюсь», «при таком профиле обычно встаёт вопрос»),
рекламный глянец. Признаки живого: конкретика про получателя, естественная
логика «почему пишу именно вам», разговорные связки, вежливая прямота.

Оценка 1-10 (10 — неотличимо от хорошего живого менеджера). Для каждого письма:
балл, одна фраза почему, и самая «шаблонная» цитата из письма (до 10 слов).
Ответ строго JSON: {"оценки":[{"id":N,"балл":N,"почему":"...","шаблон":"..."}],
"общий_вывод":"2-3 фразы: что отличает лучшие письма от худших"}

"""
ПИСЬМА = "\n\n".join("=== ПИСЬМО %d\n%s" % (п["id"], п["текст"]) for п in письма)

for модель in ("claude-sonnet-4-6", "claude-opus-4-8"):
    выход = os.path.join(ТУТ, "sudya-%s.json" % модель)
    if os.path.exists(выход):
        print("уже есть:", выход)
        continue
    ответ = gp.call(None, [{"role": "user", "content": ПРОМПТ + ПИСЬМА}],
                    model=модель, thinking=False)
    д = gp.parse_json(ответ)
    with io.open(выход, "w", encoding="utf-8") as ф:
        json.dump(д, ф, ensure_ascii=False, indent=1)
        ф.flush()
        os.fsync(ф.fileno())
    print("готов судья", модель)
