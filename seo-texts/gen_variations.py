def find_json(raw):
    m = re.search(r'\[.*\]', raw, re.S)
    return m.group(0) if m else None

def gen_bucket(i_bucket):
    i, (equip, industry, pain) = i_bucket
    cf = os.path.join(CACHE, f'b{i:02d}.json')
    if os.path.exists(cf):
        return
    reg = REG[i % len(REG)]  # реальный регион+клиент для реализма
    profiles_txt = "\n".join(
        f"{n+1}) адресат: {r}; угол: {a}; тон: {t}" for n,(r,a,t) in enumerate(PROFILES))
    prompt = (
        f"Ты сильный B2B-копирайтер холодных писем. Сгенерируй 6 РАЗНЫХ писем первого "
        f"касания по оборудованию «{equip}» для сегмента «{industry}». Боль сегмента: {pain}.\n"
        f"Каждое письмо — под свой профиль (варьируй заметно):\n{profiles_txt}\n\n"
        f"РЕАЛЬНЫЙ ПРУФ для писем (можно использовать): в регионе {reg['region']} мы "
        f"реализовали {reg['projects']} проектов, среди них {reg['client']}; всего по стране "
        f"5580+ проектов.\n\n{RULES}\n\n"
        f"Верни СТРОГО JSON-массив из 6 объектов без markdown: "
        f'[{{"role":"","angle":"","tone":"","subject":"","body":""}}]')
    for a in range(5):
        try:
            msg = gen_provider._raw_stream([{'role':'user','content':prompt}],'claude-fable-5',3500,thinking=False)
            t = ''.join(b.text for b in msg.content if getattr(b,'type','')=='text')
            arr = json.loads(find_json(t))
            assert isinstance(arr, list) and len(arr) >= 4
            for k,v in enumerate(arr):
                v.update({'bucket':i,'equipment':equip,'industry':industry,
                          'region':reg['region'],'client':reg['client'],'reg_projects':reg['projects']})
            json.dump(arr, open(cf,'w'), ensure_ascii=False)
            return
        except Exception as e:
            if a==4: json.dump({'error':str(e)[:100],'bucket':i}, open(cf,'w'), ensure_ascii=False)

