# -*- coding: utf-8 -*-
"""Критическая проверка отчёта по поиску через Fable API: какие выводы валидны
с учётом того, что часть тестовых фраз - из выдачи ПС, а не из живого поиска по сайту."""
import json, re

from gen_provider import make_client, call

report = open('inventory/OTCHET-poisk.md').read()
import csv as _csv
_rows = list(_csv.DictReader(open('inventory/search-problems.csv', encoding='utf-8-sig'), delimiter=';'))
csv_text = '\n'.join(f"{r['Запрос']};{r['Тип провала']};{r['Нашлось']};{r['Что не так'][:60]}" for r in _rows)
internal = [json.loads(l) for l in open('inventory/search-results.jsonl')]
internal_phrases = [r['phrase'] for r in internal if r['source'] == 'site']

PROMPT = f"""Ты - строгий рецензент аналитических отчётов. Проверь отчёт об аудите внутреннего
поиска интернет-магазина промышленных компрессоров.

КЛЮЧЕВАЯ ПРЕТЕНЗИЯ ВЛАДЕЛЬЦА (проверь её в первую очередь): тестовый набор состоял из
176 фраз реального ВНУТРЕННЕГО поиска сайта + 824 фраз, по которым сайт ПОКАЗЫВАЛСЯ
в Яндексе/Google. Владелец считает, что фразы из поисковиков типа «компрессор купить»,
«купить поршневой компрессор» люди ВНУТРИ сайта не вводят - внутри ищут модели и категории.
Значит, часть «проблем» отчёта может быть артефактом методики, а не реальной болью.

Вот как реально ищут ЛЮДИ ВНУТРИ сайта (все 176 внутренних фраз):
{json.dumps(internal_phrases, ensure_ascii=False)}

=== ПРОВЕРЯЕМЫЙ ОТЧЁТ ===
{report}

=== ПОЛНЫЙ СПИСОК ПРОБЛЕМНЫХ ЗАПРОСОВ (CSV: запрос;тип;релевантность;источник;нашлось;диагноз;топ-3) ===
{csv_text}

Задание:
1. По каждому из 4 кластеров отчёта: вердикт - подтверждён / подтверждён частично / артефакт
   методики. Обоснуй через призму «как реально ищут внутри сайта» (у тебя есть все 176 фраз).
2. Пересчитай масштаб: сколько проблемных строк CSV остаются РЕАЛЬНОЙ болью, если считать
   только паттерны, характерные для живого внутреннего поиска (модели, бренды, категории,
   характеристики - С УЧЁТОМ того, что и вебмастерская фраза без «купить/цена» может быть
   реалистичной для внутреннего поиска).
3. Отдельно: даже «нереалистичные» фразы («купить поршневой компрессор» → 0 результатов) -
   есть ли аргумент, что чинить всё равно надо? (например: пользователи вставляют запрос
   из поисковика в строку сайта; или это же поведение затрагивает реалистичные фразы).
   Дай честный вердикт, не подыгрывая ни владельцу, ни отчёту.
4. Список конкретных правок отчёта: что переформулировать, какие цифры пересчитать,
   что удалить, что добавить.

Ответь СТРОГО ОДНИМ JSON-объектом без преамбул, пояснений и markdown (первый символ ответа - открывающая фигурная скобка): {{"clusters": [{{"name": "...", "verdict": "...", "reasoning": "..."}}],
"real_problem_count_estimate": N, "artifact_count_estimate": N,
"should_fix_anyway": "...", "report_edits": ["..."], "overall": "..."}}"""

client = make_client()
msg = call(client, [{'role': 'user', 'content': PROMPT}], 'claude-fable-5')
text = ''.join(b.text for b in msg.content if b.type == 'text')
open('inventory/report-review-raw.txt', 'w').write(text)
m = re.search(r'\{.*\}', text, re.S)
if not m:
    print('ОТВЕТ БЕЗ JSON, сырой текст сохранён в report-review-raw.txt')
    raise SystemExit(1)
rev = json.loads(m.group(0))
json.dump(rev, open('inventory/report-review.json', 'w'), ensure_ascii=False, indent=1)
print(json.dumps(rev, ensure_ascii=False, indent=1)[:4000])
