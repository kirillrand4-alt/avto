def _daty_iz_teksta(t):
    out = []
    for m in re.finditer(r'\b(19|20)\d{2}\b', t or ''):
        g = int(m.group(0))
        if 1990 <= g <= 2035:
            out.append(g)
    return out


def razobrat_ts(ts):
    """Дата события из ts. Форматы: RSS, ISO, dd.mm.yyyy. Иначе None."""
    t = (ts or '').strip()
    if not t:
        return None
    m = re.search(r'(\d{4})-(\d{2})-(\d{2})', t)
    if m:
        try:
            return datetime.date(int(m.group(1)), int(m.group(2)), int(m.group(3)))
        except ValueError:
            return None
    m = re.search(r'(\d{1,2})\s+(янв|фев|мар|апр|ма[йя]|июн|июл|авг|сен|окт|ноя|дек)'
                  r'[а-я]*\s+(\d{4})', t, re.I)
    if m:
        mm = 'янв фев мар апр май июн июл авг сен окт ноя дек'.split()
        try:
            i = [j for j, s in enumerate(mm) if m.group(2).lower().startswith(s[:3])][0]
            return datetime.date(int(m.group(3)), i + 1, int(m.group(1)))
        except (IndexError, ValueError):
            return None
    m = re.search(r'(\d{1,2})\s+(Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)\w*\s+'
                  r'(\d{4})', t)
    if m:
        mm = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov',
              'Dec']
        try:
            return datetime.date(int(m.group(3)), mm.index(m.group(2)) + 1,
                                 int(m.group(1)))
        except ValueError:
            return None
    m = re.search(r'(\d{1,2})\.(\d{1,2})\.(\d{4})', t)
    if m:
        try:
            return datetime.date(int(m.group(3)), int(m.group(2)), int(m.group(1)))
        except ValueError:
            return None
    return None


def summa_v_rub(s):
    """Число рублей из строки суммы. Возвращает (float|None, исходная строка)."""
    t = (s or '').lower().replace(' ', ' ')
    if not t.strip():
        return None
    m = re.search(r'(\d[\d\s.,]*)\s*(млрд|миллиард|млн|миллион|тыс|тысяч)?', t)
    if not m or not m.group(1).strip():
        return None
    try:
        x = float(m.group(1).replace(' ', '').replace(',', '.').rstrip('.'))
    except ValueError:
        return None
    k = {'млрд': 1e9, 'миллиард': 1e9, 'млн': 1e6, 'миллион': 1e6, 'тыс': 1e3,
         'тысяч': 1e3}.get(m.group(2) or '', 1.0)
    if 'usd' in t or 'долл' in t or '$' in t:
        x *= 90.0
    if 'евро' in t or 'eur' in t:
        x *= 100.0
    return x * k


SLOV_MIN = 12   # короче этого текст не доказательство сходства


def shingly(t, n=4):
    """4-граммы слов. У КОРОТКОГО текста сходство не считается вовсе.

    Заслон оплачен контролем: пять пустых сигналов одного ИНН давали текст
    «модернизация» из одного слова, Жаккар 1.00 и склейку пяти разных событий в один
    проект-помойку. Сходство двух-трёх слов — не доказательство."""
    w = [osnova(x) for x in SLOVO.findall(t or '')]
    if len(w) < SLOV_MIN:
        return set()
    return {' '.join(w[i:i + n]) for i in range(len(w) - n + 1)}


def zhakkar(a, b):
    if not a or not b:
        return 0.0
    p = len(a & b)
    return p / float(len(a | b)) if p else 0.0


def razobrat_signal(r):
    """Сигнал -> словарь признаков. Только текст сигнала, без внешних справочников."""
    t = (r.get('what') or '') + ' ' + (r.get('event_type') or '')
    o = {'_rid': r.get('_rid'), 'inn': (r.get('inn') or '').strip(),
         'source': r.get('source') or '', 'url': r.get('source_url') or '',
         'what': r.get('what') or '', 'event_type': r.get('event_type') or '',
         'sum_text': r.get('sum') or '', 'hotness': r.get('hotness') or '',
         'ts': r.get('ts') or '', 'updated_at': r.get('updated_at') or '',
         'inn_conf': r.get('inn_conf') or '', 'suspect': r.get('suspect') or ''}
    o['data'] = razobrat_ts(r.get('ts'))
    o['god_iz_teksta'] = sorted(set(_daty_iz_teksta(r.get('what'))))
    o['summa'] = summa_v_rub(r.get('sum'))

    goroda, regiony = set(), set()
    for g, rx in GOR_RE:
        for m in rx.finditer(t):
            if POSLE_REGIONA.match(t, m.end()):
                continue          # «Иркутской области» — регион, а не город
            goroda.add(g)
            break
    for rg, rx in REG_RE:
        if rx.search(t):
            regiony.add(rg)
    # «Москва»/«Санкт-Петербург» стоят и в городах, и в регионах: не считаем регионом дважды
    o['goroda'] = goroda
    regiony = {KANON_REGIONA.get(r, r) for r in regiony}
    o['regiony'] = (regiony - {'Москва', 'Санкт-Петербург'}) if len(regiony) > 1 \
        else regiony

    raboty = {n for n, rx in RABOTY if rx.search(t)}
    o['raboty'] = raboty

    otr, otr_iz = [], []
    for n, prior, rx in OTRASLI:
        m = rx.search(t)
        if m:
            otr.append((prior, n))
            otr_iz.append('%s: «%s»' % (n, m.group(0)[:30]))
    otr.sort(key=lambda x: (-x[0], x[1]))
    o['otrasli'] = [n for _, n in otr]
    o['otrasl_prior'] = 1 if any(p for p, _ in otr) else 0
    o['otrasl_iz'] = ' ; '.join(otr_iz[:4])

    st = [(k, n) for k, n, rx in STADII if rx.search(t)]
    if not st:
        st = [TIP_STADIYA.get(o['event_type'], (6, 'стройка'))]
    o['stadii'] = st
    o['stadiya_kod'] = max(k for k, _ in st)
    o['stadiya_ran'] = min(k for k, _ in st)
    o['stadiya'] = [n for k, n in st if k == o['stadiya_kod']][0]

    # якоря-кандидаты: имена собственные, аббревиатуры, кавычки
    yak = set()
    for m in ABBR.finditer(t):
        w = m.group(0)
        if len(w) >= 3 and w.lower() not in PRAVOVYE:
            yak.add(w.lower().replace('ё', 'е'))
    for m in KAVYCHKI.finditer(t):
        for w in SLOVO.findall(m.group(1)):
            if len(w) >= 4:
                yak.add(osnova(w))
    o['yakorya_kand'] = yak
    o['zaglavnye'] = {osnova(w) for w in re.findall(r'(?<![.!?]\s)(?<!^)\b[А-ЯЁ][а-яё]{3,}',
                                                    t)}
    o['vse_slova'] = [osnova(w) for w in SLOVO.findall(t)]
    o['shingly'] = shingly(t)
    return o


def klyuch_proekta(inn, mesto, obekt, rabota):
    s = '|'.join([inn or '', mesto or '', obekt or '', rabota or ''])
    return 'PR-' + hashlib.sha1(s.encode('utf-8')).hexdigest()[:10], s


def klyuch_uliki(istochnik, ssylka, citata):
    """Устойчивый ключ доказательства: одно и то же доказательство не удваивается,
    а РАЗНЫЕ доказательства одного события накапливаются — правило владельца."""
    s = '|'.join([istochnik or '', ssylka or '', (citata or '')[:300]])
    return hashlib.sha1(s.encode('utf-8')).hexdigest()[:16]
