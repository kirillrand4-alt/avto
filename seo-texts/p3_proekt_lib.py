def osnova(s):
    """Грубая основа: срезаем самое длинное окончание, оставляя не меньше 4 знаков."""
    s = s.lower().replace('ё', 'е')
    for k in _KONCOVKI:
        if len(s) - len(k) >= 4 and s.endswith(k):
            return s[:-len(k)]
    return s


