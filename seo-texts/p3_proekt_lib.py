# «Амурская» = «амур» ловила «Комсомольск-на-Амуре» и приписывала хабаровскому заводу
# Амурскую область — поймано контролем.
PRIL_KON = r'(?:ая|ой|ую|ом|ое|ий|им|ого|ому|ою)(?![а-яё])'


def _reg_re(r):
    """У составного имени требуются ОБА слова. Без этого «Приморский район
    Санкт-Петербурга» становился Приморским краем, а «северная площадка» — Северной
    Осетией: оба случая пойманы на живых сигналах."""
    slova = r.split()
    p = slova[0]
    o = osnova(p)
    prilag = bool(re.search(r'(?:ая|ий|ой|ое)$', p))
    nach = (r'(?<![а-яё-])' + re.escape(o)
            + (r'(?:ск)?' + PRIL_KON if prilag else OKONCH))
    if len(slova) > 1:
        vtor = osnova(slova[1]).rstrip('йь')
        return re.compile(nach + r'\s+' + re.escape(vtor) + r'[а-яё]{0,3}', re.I)
    return re.compile(nach, re.I)


