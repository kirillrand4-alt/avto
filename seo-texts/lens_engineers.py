def ask(prompt, max_tokens=14000, attempts=5, min_len=400):
    """Один вызов провайдера с ретраями. Стриминг обязателен (Cloudflare рвёт молчащие)."""
    thinking, last = True, None
    for attempt in range(attempts):
        if attempt:
            time.sleep(min(120, 10 * 2 ** (attempt - 1)))
        try:
            msg = gp._raw_stream([{'role': 'user', 'content': prompt}], MODEL,
                                 max_tokens, thinking=thinking)
        except httpx.HTTPStatusError as ex:
            code = ex.response.status_code if ex.response is not None else None
            if code == 400 and thinking:
                thinking = False
            last = f'HTTP {code}'
            continue
        except Exception as ex:
            last = 'сбой стрима: ' + repr(ex)[:140]
            continue
        text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
        if len(text) >= min_len:
            return text, {'in': msg.usage.input_tokens, 'out': msg.usage.output_tokens}
        last = f'короткий ответ ({len(text)} симв., stop={msg.stop_reason})'
    raise RuntimeError(f'не получен ответ за {attempts} попыток: {last}')


def run_lens(key):
    title, body = LENSES[key]
    prompt = f'{CONTEXT}\n\nТВОЯ ЛИНЗА: {title}\n{body}\n{REQS}'
    t0 = time.time()
    text, usage = ask(prompt)
    path = os.path.join(OUT, f'lens-{key}.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'# Линза: {title}\n\n'
                f'_Сгенерировано {MODEL} через провайдерский эндпоинт. '
                f'Это идеи модели, а не проверенные факты._\n\n---\n\n{text}\n')
    dt = time.time() - t0
    print(f'[ok] {key:14s} {len(text):6d} симв.  {usage["out"]:6d} out-tok  {dt:5.0f} с',
          file=sys.stderr)
    return {'key': key, 'title': title, 'chars': len(text), 'sec': round(dt), **usage}


