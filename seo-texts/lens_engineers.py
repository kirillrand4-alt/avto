def synthesize(keys):
    parts = []
    for k in keys:
        p = os.path.join(OUT, f'lens-{k}.md')
        if os.path.exists(p):
            parts.append(f'=== ЛИНЗА: {LENSES[k][0]} ===\n\n'
                         + open(p, encoding='utf-8').read())
    if not parts:
        sys.exit('нечего синтезировать')
    prompt = SYNTH.format(n=len(parts), dump='\n\n'.join(parts))
    print(f'[..] синтез по {len(parts)} линзам, вход ~{len(prompt)//4} ток.', file=sys.stderr)
    text, usage = ask(prompt, max_tokens=16000, min_len=1000)
    path = os.path.join(OUT, 'SUMMARY.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('# Инженеры РФ и их работодатели: сводка по линзам\n\n'
                f'_Синтез {len(parts)} независимых линз, модель {MODEL} через провайдерский '
                'эндпоинт. Документ содержит ИДЕИ и ГИПОТЕЗЫ, а не проверенные факты: '
                'ни один источник в нём не открывался и не проверялся._\n\n---\n\n' + text + '\n')
    print(f'[ok] синтез: {len(text)} симв., {usage["out"]} out-tok', file=sys.stderr)
    return usage


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', help='список ключей линз через запятую')
    ap.add_argument('--workers', type=int, default=4)
    ap.add_argument('--no-synth', action='store_true')
    ap.add_argument('--synth-only', action='store_true')
    a = ap.parse_args()

    os.makedirs(OUT, exist_ok=True)
    keys = [k.strip() for k in a.only.split(',')] if a.only else list(LENSES)
    bad = [k for k in keys if k not in LENSES]
    if bad:
        sys.exit(f'неизвестные линзы: {bad}. Доступны: {list(LENSES)}')

    stats = []
    if not a.synth_only:
        print(f'запуск {len(keys)} линз, параллельно {a.workers}, модель {MODEL}', file=sys.stderr)
        with ThreadPoolExecutor(max_workers=a.workers) as ex:
            futs = {ex.submit(run_lens, k): k for k in keys}
            for f, k in futs.items():
                try:
                    stats.append(f.result())
                except Exception as e:
                    print(f'[FAIL] {k}: {e}', file=sys.stderr)
                    stats.append({'key': k, 'error': str(e)[:200]})

    if not a.no_synth:
        try:
            synthesize(keys)
        except Exception as e:
            print(f'[FAIL] синтез: {e}', file=sys.stderr)

    ok = [s for s in stats if 'error' not in s]
    if ok:
        with open(os.path.join(OUT, 'run-stats.json'), 'w', encoding='utf-8') as f:
            json.dump(stats, f, ensure_ascii=False, indent=2)
        print(f'\nготово: {len(ok)}/{len(stats)} линз, '
              f'out-токенов всего {sum(s["out"] for s in ok)}', file=sys.stderr)


if __name__ == '__main__':
    main()
