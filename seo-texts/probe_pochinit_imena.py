# -*- coding: utf-8 -*-
"""Починить мусорные имена моего канала: должность и география вместо ФИО.

ЧТО НАШЁЛ ВЛАДЕЛЕЦ. В карточке стоял «человек» по имени «Республики Карелия Латышкевич,
главный механик», источник «поиск-ЛПР-3с-песочница» — мой. Разбор взял три слова подряд, не
проверив, что первые два это география. Замер по базе: у моего канала 29 записей, где вместо
имени стоит ДОЛЖНОСТЬ («Начальник А.А.», «Начальник Д.В.»), и 1 с географией.

ПОЧЕМУ ЭТО ХУЖЕ ОПЕЧАТКИ. Такое «имя» нельзя ни набрать, ни спросить у секретаря, а в карточке
оно выглядит найденным человеком — то есть создаёт ложное ощущение покрытия. И мой же обратный
ход пойдёт искать несуществующего «Начальника А.А.», тратя запросы.

ЧТО ДЕЛАЮ, И ЧЕГО НЕ ДЕЛАЮ. Не удаляю: у записи может быть телефон или почта, а контакт с
неизвестным владельцем — это по-прежнему вход на предприятие. Меняю ИМЯ на «Имя не
установлено», а то, что стояло вместо имени, переношу в должность, если её там нет. В источник
дописываю пометку — чтобы через день никто не гадал, почему имя пустое.
Правило владельца тут работает буквально: разделять, а не отсеивать. Плохое имя отделяется от
годного контакта, а не выбрасывается вместе с ним.
"""
import json
import os
import re
import sqlite3

MOY = 'поиск-ЛПР-3с-песочница'
NE_IMYA = re.compile(
    r'\b(?:республик\w*|област\w*|кра[йя]|город\w*|район\w*|округ\w*|федерац\w*|'
    r'министерств\w*|управлени\w*|филиал\w*|общество|акционерн\w*|ограниченн\w*|'
    r'предприяти\w*|учреждени\w*|компани\w*|завод\w*|комбинат\w*|фабрик\w*)\b', re.I)
DOLZHNOST = re.compile(
    r'^\s*(?:начальник|директор|инженер|механик|энергетик|заместител\w*|главн\w*|'
    r'руководител\w*|специалист|мастер)\b', re.I)

for baza in (r'C:\seostat\data\centrifugal.db', r'C:\sender\enrich.db'):
    cx = sqlite3.connect(baza)
    tabl = 'person' if baza.endswith('centrifugal.db') else 'people'
    pole_post = 'position' if tabl == 'person' else 'post'
    rows = cx.execute(
        f"select rowid, coalesce(person,''), coalesce({pole_post},''), coalesce(source,'') "
        f"from {tabl}").fetchall()
    pravki = []
    for rid, person, post, src in rows:
        if MOY not in src:
            continue
        p = person.strip()
        if not p:
            continue
        if DOLZHNOST.match(p) or NE_IMYA.search(p):
            novaya_dolzh = post or p
            pravki.append((novaya_dolzh[:120],
                           src + f' [имя разобрано неверно, было: {p[:40]}]',
                           rid))
    print(f'{baza}: к починке {len(pravki)}')
    if 'PRIMENIT' in os.sys.argv and pravki:
        cx.executemany(
            f"update {tabl} set person = 'Имя не установлено', {pole_post} = ?, source = ? "
            f'where rowid = ?', pravki)
        cx.commit()
        print('  починено')
