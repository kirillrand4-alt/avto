# -*- coding: utf-8 -*-
"""Адресный поиск ЛПР по четырём целям: вакансии, закупки, отраслевые публикации.

Владелец назвал «Феликс Николаевич, технический директор Дмитровских колбас» — ищем его
прямо, плюс общие запросы на технических руководителей всех четырёх.

ЗАСЛОН ОТ МУСОРА, оплаченный прошлым заходом: регулярка ФИО брала любые два слова с
заглавной и выдала «Вакансия Главный», «России Найдено», «Москва Предприятие». Теперь имя
обязано иметь ОТЧЕСТВО (…ович/…евич/…ична/…овна) либо инициалы, и не начинаться со слова
из чёрного списка. Лучше ноль, чем правдоподобный мусор.
"""
import json, os, re, urllib.parse, urllib.request

USER = os.environ.get('XMLRIVER_USER', '')
KEY = os.environ.get('XMLRIVER_KEY', '')
ZAPROSY = [
    ('Дмитровские колбасы', '"Дмитровские колбасы" "Феликс Николаевич"'),
    ('Дмитровские колбасы', 'Феликс Николаевич технический директор колбасы Дмитров'),
    ('Дмитровские колбасы', '"Дмитровские колбасы" главный инженер вакансия контактное лицо'),
    ('Дмитровские колбасы', '"Дмитровские колбасы" главный технолог ФИО'),
    ('Брянский молочный комбинат', '"Брянский молочный комбинат" главный инженер ФИО'),
    ('Брянский молочный комбинат', '"Брянский молочный комбинат" технический директор'),
    ('Брянский молочный комбинат', '"Брянский молочный комбинат" начальник лаборатории качества'),
    ('Хлебокомбинат ПЕКО', '"Хлебокомбинат ПЕКО" Лузгин'),
    ('Хлебокомбинат ПЕКО', '"Хлебокомбинат ПЕКО" технический директор ФИО'),
    ('МАЯК Хлеб-соль', '"Слата" Иркутск технический директор ФИО'),
    ('МАЯК Хлеб-соль', '"Хлеб-соль" Слата главный инженер контакты'),
]
DOLZH = re.compile(r'(техническ\w+\s+директор|главн\w+\s+инженер|директор\s+по\s+качеств|'
                   r'главн\w+\s+технолог|главн\w+\s+энергетик|главн\w+\s+механик|'
                   r'начальник\w*\s+производств|начальник\w*\s+лаборатори|'
                   r'директор\s+по\s+производств|начальник\w*\s+отдела\s+качеств)', re.I)
# ИМЯ ОБЯЗАНО БЫТЬ ИМЕНЕМ: либо с отчеством, либо с инициалами.
IMYA = re.compile(r'\b([А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}(?:ович|евич|ич|овна|евна|ична)\b'
                  r'|[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ]\.\s?[А-ЯЁ]\.'
                  r'|[А-ЯЁ]\.\s?[А-ЯЁ]\.\s?[А-ЯЁ][а-яё]{2,})')


def serp(q):
    if not (USER and KEY):
        return [{'err': 'нет ключей xmlriver в окружении'}]
    u = ('http://xmlriver.com/search/xml?user=%s&key=%s&query=%s&groupby=30'
         % (USER, KEY, urllib.parse.quote(q)))
    try:
        x = urllib.request.urlopen(u, timeout=45).read().decode('utf-8', 'replace')
    except Exception as e:
        return [{'err': str(e)[:90]}]
    out = []
    for m in re.finditer(r'<doc>(.*?)</doc>', x, re.S):
        d = m.group(1)
        url = (re.search(r'<url>(.*?)</url>', d, re.S) or [None, ''])[1]
        tit = re.sub(r'<[^>]+>', ' ', (re.search(r'<title>(.*?)</title>', d, re.S) or [None, ''])[1])
        pas = re.sub(r'<[^>]+>', ' ', (re.search(r'<passages>(.*?)</passages>', d, re.S) or [None, ''])[1])
        out.append({'url': url, 't': ' '.join((tit + ' ' + pas).split())})
    return out


itog = {}
for cel, q in ZAPROSY:
    for d in serp(q):
        if d.get('err'):
            print(json.dumps({'ошибка': d['err'], 'запрос': q}, ensure_ascii=False), flush=True)
            break
        t = d['t']
        # 1) имя рядом с должностью
        for m in DOLZH.finditer(t):
            okno = t[max(0, m.start() - 150):m.start() + 180]
            for f in IMYA.findall(okno):
                itog.setdefault(cel, {})[(f, m.group(1).lower()[:18])] = \
                    {'fio': f, 'dolzhnost': ' '.join(m.group(1).split()),
                     'ssylka': d['url'], 'zapros': q, 'citata': ' '.join(okno.split())[:200]}
        # 2) прямое упоминание Феликса Николаевича — ищем и без должности рядом
        if 'Феликс' in t:
            i = t.index('Феликс')
            itog.setdefault(cel, {})[('ФЕЛИКС', d['url'][:40])] = \
                {'fio': 'упоминание «Феликс»', 'dolzhnost': '(проверить глазами)',
                 'ssylka': d['url'], 'zapros': q,
                 'citata': ' '.join(t[max(0, i - 150):i + 200].split())[:260]}

for cel, lyudi in itog.items():
    print(json.dumps({'цель': cel, 'найдено': len(lyudi),
                      'люди': list(lyudi.values())[:12]}, ensure_ascii=False), flush=True)
if not itog:
    print(json.dumps({'итог': 'ничего не найдено ни по одному запросу'}, ensure_ascii=False))
