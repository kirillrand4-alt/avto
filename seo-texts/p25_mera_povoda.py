# -*- coding: utf-8 -*-
"""Стадия A, графа 1 паспорта: мера «подходящая новость». Три уровня, а не «годен/не годен».

ОТКУДА МЕРА. Я прочитала 22 случайных сигнала глазами и сняла собственный критерий «what
короче 60 знаков = огрызок»: «воздухоразделительная установка (ВРУ)» это 37 знаков и
прямое попадание, а РУСАЛ с 300 знаками про электролизёры нашу машину не называет ни
разу. Длина не различает. Различает одно: **названа ли наша машина или наша среда**.

    ПРЯМОЙ     машина/среда названы     -> письмо строится на самой новости
    КОСВЕННЫЙ  капекс есть, машина нет  -> письмо про модернизацию, повод слабее
    ЧУЖОЙ      капекс не про производство (логистика, офис, соцобъект, автосалон)

ЗАЧЕМ ТРИ, А НЕ ДВА. Владелец: «разделять, а не отсеивать». КОСВЕННЫЙ это не брак, это
письмо другого текста. Выбросив его, мы выбросим предприятие, у которого стройка идёт.

ПРОБА, КОТОРАЯ МОЖЕТ ПРОВАЛИТЬСЯ. Мера обязана РАЗЛИЧАТЬ, а не быть непустой — за это уже
заплачено: прибор, который проверяет «нашлось хоть что-то», всегда доволен. Поэтому проба
собрана из тех самых 22 прочитанных глазами, с обеих сторон: пять, которые ОБЯЗАНЫ выйти
ПРЯМЫМИ, и пять, которые обязаны НЕ выйти. Если проба валится — числа ниже недостоверны,
и это печатается первым, до всяких итогов.

Читает базу только на чтение. Провайдера не трогает, seen_news не трогает.
"""
import collections
import json
import os
import re
import sqlite3
import sys

BAZA = r'C:\sender\enrich.db'

# Наша машина и наша среда. Список из прочитанных глазами сигналов, не из головы.
MASHINA = re.compile(
    r'компрессор\w*|компрессорн\w+|турбокомпрессор\w*|газодувк\w+|газодувн\w+|'
    r'воздуходувк\w+|нагнетател\w+|бустер\w*|'
    r'воздухоразделен\w+|воздухоразделительн\w+|\bВРУ\b|\bКС\b|\bКСУ\b|'
    r'сжат\w+\s+воздух\w*|сжатого\s+газа|пневмат\w+|пневмосистем\w+|'
    r'осушител\w+\s+возду\w+|осушк\w+\s+возду\w+|'
    r'генератор\w*\s+(?:азота|кислорода)|азотн\w+\s+станци\w+|кислородн\w+\s+станци\w+|'
    r'\bазот\w*\b|\bкислород\w*\b|'
    r'холодильн\w+\s+машин\w+|чиллер\w*|'
    r'ресивер\w*|винтов\w+\s+компрессор\w*|поршнев\w+\s+компрессор\w*|'
    r'центробежн\w+\s+(?:компрессор\w*|машин\w+|нагнетател\w+)', re.I)

# Капекс не про производство. Эти слова НЕ отменяют машину — проверяются ПОСЛЕ неё.
CHUZHOE = re.compile(
    r'логистическ\w+\s+(?:комплекс\w*|центр\w*)|склад\w+\s+комплекс\w*|'
    r'торгов\w+\s+центр\w*|бизнес-центр\w*|жил\w+\s+(?:комплекс\w*|дом\w*)|'
    r'детск\w+\s+сад\w*|школ\w+|больниц\w+|поликлиник\w+|стадион\w*|'
    r'автосалон\w*|дилерск\w+\s+центр\w*|седан\w*|кроссовер\w*|'
    r'офисн\w+\s+(?:здани\w+|помещени\w+)|благоустройств\w+|'
    r'дорог\w+|мост\w+|путепровод\w*|тротуар\w*', re.I)

# --- проба: размечено ГЛАЗАМИ на 22 прочитанных сигналах -----------------------------
PROBA_PRYAMYE = [
    'Ремонт компрессорной станции ЗИФ-ПВ-4/1,6',
    'замена газодувной машины №2 с полным обновлением центробежного компрессора, 54 млн',
    'Реконструкция компрессорной станции Похвистнево, 4,4 МВт',
    'нанимает в компрессорное хозяйство: аппаратчик воздухоразделения',
    'воздухоразделительная установка (ВРУ)',
]
PROBA_NE_PRYAMYE = [
    'модернизация БрАЗа на 14 млрд: электролизёры, газоочистка, литейное отделение',
    'запуск производства трапов для самолётов',
    'начало выпуска седана Tenet A8',
    'строительство логистических комплексов',
    'ТЕХНОНИКОЛЬ вложит 2 млрд в очистные сооружения и мониторинг воздуха',
]


def uroven(tekst, kapeks=True):
    """ПРЯМОЙ / КОСВЕННЫЙ / ЧУЖОЙ. Порядок проверок и есть правило.

    Машина проверяется ПЕРВОЙ: «компрессорная станция в логистическом комплексе» — наш
    повод, а не чужой. Обратный порядок отправил бы его в брак, и это была бы потеря,
    которую никто бы не увидел.
    """
    t = tekst or ''
    if MASHINA.search(t):
        return 'ПРЯМОЙ'
    if CHUZHOE.search(t):
        return 'ЧУЖОЙ'
    return 'КОСВЕННЫЙ' if kapeks else 'ЧУЖОЙ'


print('=== ПРОБА (может провалиться)')
provalov = 0
for s in PROBA_PRYAMYE:
    u = uroven(s)
    if u != 'ПРЯМОЙ':
        provalov += 1
        print('  ПРОВАЛ: ждали ПРЯМОЙ, вышло %-10s | %s' % (u, s[:78]))
for s in PROBA_NE_PRYAMYE:
    u = uroven(s)
    if u == 'ПРЯМОЙ':
        provalov += 1
        print('  ПРОВАЛ: ждали НЕ ПРЯМОЙ, вышло ПРЯМОЙ | %s' % s[:78])
print('  провалов %d из %d' % (provalov, len(PROBA_PRYAMYE) + len(PROBA_NE_PRYAMYE)))
if provalov:
    print('  ЧИСЛА НИЖЕ НЕДОСТОВЕРНЫ — мера не различает на размеченном глазами')

if not os.path.exists(BAZA):
    print('ИТОГ ' + json.dumps({'базы нет': BAZA}, ensure_ascii=False))
    raise SystemExit

cx = sqlite3.connect('file:%s?mode=ro' % BAZA.replace('\\', '/'), uri=True)
kol = [r[1] for r in cx.execute('pragma table_info(signals)')]
print('\n=== signals: колонки %s' % kol)
vsego = cx.execute('select count(*) from signals').fetchone()[0]
print('строк %d' % vsego)

polya = [k for k in ('what', 'title', 'text', 'summary', 'descr') if k in kol]
ist = 'source' if 'source' in kol else ('src' if 'src' in kol else None)
inn = 'inn' if 'inn' in kol else None
sel = ','.join(['rowid'] + polya + ([ist] if ist else []) + ([inn] if inn else []))

sch = collections.Counter()
po_ist = collections.defaultdict(collections.Counter)
primery = collections.defaultdict(list)
for r in cx.execute('select %s from signals' % sel):
    d = dict(zip(['rowid'] + polya + ([ist] if ist else []) + ([inn] if inn else []), r))
    t = ' '.join(str(d.get(p) or '') for p in polya)
    u = uroven(t)
    sch[u] += 1
    if ist:
        po_ist[str(d.get(ist) or '?')][u] += 1
    if inn and str(d.get(inn) or '').strip():
        sch['%s + ИНН' % u] += 1
    if len(primery[u]) < 6:
        primery[u].append((str(d.get(inn) or '—'), re.sub(r'\s+', ' ', t)[:118]))
cx.close()

print('\n=== СКОЛЬКО ПОВОДОВ КАЖДОГО УРОВНЯ')
for u in ('ПРЯМОЙ', 'КОСВЕННЫЙ', 'ЧУЖОЙ'):
    print('  %-10s %5d   из них с ИНН %5d' % (u, sch[u], sch['%s + ИНН' % u]))

print('\n=== ПО ИСТОЧНИКАМ (кто даёт ПРЯМЫЕ поводы, а кто шум)')
for i, c in sorted(po_ist.items(), key=lambda x: -x[1]['ПРЯМОЙ'])[:18]:
    print('  %-24s прямых %4d | косвенных %4d | чужих %4d'
          % (i[:24], c['ПРЯМОЙ'], c['КОСВЕННЫЙ'], c['ЧУЖОЙ']))

print('\n=== ГЛАЗАМИ: по шесть образцов каждого уровня')
for u in ('ПРЯМОЙ', 'КОСВЕННЫЙ', 'ЧУЖОЙ'):
    print('\n  --- %s' % u)
    for i, t in primery[u]:
        print('    %-12s %s' % (i[:12], t))

print()
print('ИТОГ ' + json.dumps({'провалов пробы': provalov, 'сигналов': vsego,
                            'ПРЯМОЙ': sch['ПРЯМОЙ'], 'ПРЯМОЙ+ИНН': sch['ПРЯМОЙ + ИНН'],
                            'КОСВЕННЫЙ': sch['КОСВЕННЫЙ'], 'ЧУЖОЙ': sch['ЧУЖОЙ']},
                           ensure_ascii=False))
