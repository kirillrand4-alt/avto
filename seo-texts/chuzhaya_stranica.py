"""Номер снят со страницы, которая к предприятию отношения не имеет. Заслон и чистка.

СЛУЧАЙ ВЛАДЕЛЬЦА, разобранный до конца. На карточке АО «ПОЛИЭФ» (ИНН 0258005638) стоял
контакт:

    +7 (495) 664-49-55   Юрин Михаил (М.Н. Юрин)   гл.инженер
    Источник: обратный ход по ФИО | перенос из enrich.db 3-й сессией
    Ссылка:   pulpfor.ru/news/.../privetstvie-uchastnikam-i-gostyam-pulpfor

Открываем ссылку: это ПРИВЕТСТВИЕ участникам выставки PulpFor 2026, подписанное
«Заместитель Министра промышленности и торговли Российской Федерации М.Н. Юрин».

Ошибок сложилось три, и каждая по отдельности выглядела безобидно:
  1. ИМЯ верное, но устаревшее. Юрин М.Н. действительно был главным инженером ПОЛИЭФа, потом
     генеральным директором — это записано в нашем же старом факте. Сейчас он замминистра.
     Должность в карточке годится для истории и не годится для звонка.
  2. СТРАНИЦА чужая. Она не про ПОЛИЭФ, она про выставку. Совпало только имя.
  3. НОМЕР со страницы принадлежит ЕЙ, а не человеку: московский телефон организатора
     выставки. Продавец набирает его, чтобы поговорить с главным инженером в Благовещенске.

КЛАСС, А НЕ СЛУЧАЙ. Это третье возвращение одной и той же ошибки: «близость не доказывает
принадлежность». Сначала она была про фамилию рядом с номером во вложении, потом про инженера
РУСАЛа в докладе Сегежского ЦБК, теперь про имя на чужой странице. Каждый раз я чинил ДАННЫЕ и
не чинил КАНАЛ — и она возвращалась с новой стороны.

ЗАСЛОН. Страница засчитывается источником контакта предприятия, только если выполнено хотя бы
одно:
  * хост страницы совпадает с сайтом предприятия (ядро домена);
  * на странице названо само предприятие (его имя есть в тексте окна вокруг номера);
  * код номера соответствует региону предприятия.
Иначе — это чужая страница, где просто встретилось имя. Контакт не удаляется: он
переписывается на «источник не подтверждает принадлежность», чтобы не потерять след.

ОТДЕЛЬНО ПРО НОВОСТНЫЕ И ВЫСТАВОЧНЫЕ ДОМЕНЫ. Приветствия, программы конференций, отраслевые
новости — самый частый вид чужой страницы: там имена руководителей стоят списком, а телефон
на странице всегда один и тот же, редакции или организатора.
"""
import re

# Домены, где имя человека встречается без всякой связи с его работодателем.
CHUZHOY_DOMEN = re.compile(
    r'pulpfor|expo|vystavk|forum|conference|konferenc|news|novosti|smi|press|media|'
    r'globalmsk|rusprofile|list-org|zachestnyibiznes|checko|sbis|kartoteka|audit-it|'
    r'vedomosti|kommersant|rbc\.|interfax|tass\.|ria\.|regnum|gazeta|journal|zhurnal|'
    r'wikipedia|dzen|vk\.com|ok\.ru|t\.me|telegram|youtube|linkedin|hh\.ru|superjob|'
    r'award|premi[yai]|nagrad', re.I)


# ЗАКУПОЧНЫЕ ПЛОЩАДКИ — НЕ ЧУЖИЕ СТРАНИЦЫ, и первый вариант правила зря их поймал. Карточка
# закупки на zakupki.gov.ru или tektorg.ru называет КОНТАКТНОЕ ЛИЦО ЗАКАЗЧИКА с телефоном —
# это ровно то место, откуда контакт брать и следует. Домен там чужой по имени, а по существу
# страница про наше предприятие: в ней стоит его ИНН.
PLOSHCHADKA = re.compile(
    r'zakupki\.gov|roseltorg|rts-tender|etp-?gpb|etpgpb|tektorg|tender\.pro|b2b-center|'
    r'sberbank-ast|fabrikant|otc\.ru|gazneftetorg|estp|torgi\.gov|zakupki\.mos|'
    r'gz-spb|komita|onlinecontract|tp\.rosseti|zakupki\.rushydro', re.I)


def yadro_domena(url_ili_domen):
    """Второй уровень домена: `www.sibur.ru/polief/` → `sibur`."""
    v = re.sub(r'^\w+://', '', (url_ili_domen or '').strip().lower())
    v = v.split('/')[0].split('?')[0]
    chasti = [c for c in v.split('.') if c and c != 'www']
    if len(chasti) >= 2:
        # ru, com, рф и прочие первого уровня отбрасываем, берём следующий слева.
        return chasti[-2]
    return chasti[0] if chasti else ''


# ПЕРВОИСТОЧНИКИ ПО ТЗ: раскрытие и официальные реестры сведений об организации.
#
# СЛОВО ИЩЕТСЯ В ХОСТЕ, А НЕ ВО ВСЁМ АДРЕСЕ. Проверка поймала: `vypiska-egrul.ru/company/kamaz`
# проходил как «официальный реестр» — в адресе есть подстрока «egrul». Это ровно та же ошибка,
# что и с холдингом: совпадение имени в произвольном месте адреса выдаётся за принадлежность.
# Поддельных выписок в сети больше, чем настоящих реестров, и разница между ними — хост.
RASKRYTIE_HOST = re.compile(
    r'^(?:egrul\.nalog\.ru|www\.nalog\.ru|nalog\.ru|pb\.nalog\.ru|'
    r'www\.e-disclosure\.ru|e-disclosure\.ru|disclosure\.[\w.-]+|'
    r'www\.interfax\.ru|interfax\.ru|zvcom\.ru|scrin\.ru|'
    r'fedresurs\.ru|bankrot\.fedresurs\.ru)$', re.I)


def _raskrytie(url):
    host = re.sub(r'^\w+://', '', (url or '').strip().lower()).split('/')[0].split('?')[0]
    if not RASKRYTIE_HOST.match(host):
        return False
    # `interfax.ru` официальным раскрытием считается только в разделе корпоративных сведений;
    # остальное там — новостная лента, а новость принадлежности контакта не доказывает.
    if 'interfax.ru' in host and '/corporate' not in (url or '').lower():
        return False
    return True

# АГРЕГАТОРЫ ВЫПИСОК. Отдельным списком, потому что они ломают именно правило холдинга.
#
# ЧТО СЛУЧИЛОСЬ. Правило «имя предприятия стоит в АДРЕСЕ страницы» написано под
# `sibur.ru/polief/contacts/` — страницу про ПОЛИЭФ на сайте владеющего холдинга. Как только
# в приёмку начали передавать имя предприятия (до этого туда шла пустая строка), число
# подтверждённых выросло с 7 до 84 — и глазами по доменам оказалось, что 19 из них
# `inndex.ru`, 15 `checko.ru`, 6 `companies.rbc.ru`. Причина простая: агрегатор ВСЕГДА кладёт
# имя компании в адрес карточки — `checko.ru/company/ao-apatit-…`. То есть правило холдинга
# описывает не холдинг, а любую страницу, названную по компании.
#
# Это третий возврат одного класса: «близость не доказывает принадлежность». Сначала фамилия
# рядом с номером, потом имя на чужой странице, теперь имя в адресе чужой страницы.
AGREGATOR = re.compile(
    r'inndex|checko|rusprofile|list-org|zachestnyibiznes|sbis|kartoteka|audit-it|datanewton|'
    r'b2book|b2b\.house|companium|companies\.rbc|ofcheck|credinform|globas|star-pro|'
    r'seldon|synapsenet|kontragent|focus\.kontur|kontur\.ru|sparkinterfax|spark-interfax|'
    # `egrul`/`vypisk` тут широко и намеренно: настоящий реестр отсекается ВЫШЕ, по хосту,
    # а всё остальное с этими словами в адресе — перепродавцы выписок.
    r'egrul|vypisk|reestr-|proverkakontragent|papapomog|bizly|orgpage|vbankcenter', re.I)


def stranica_podtverzhdaet(url, sayt_predpriyatiya='', imya_predpriyatiya='',
                           tekst_stranicy='', strogo=False):
    """(подтверждает ли страница принадлежность, объяснение).

    `strogo=True` — режим приёмки P25. ПОЧЕМУ ОН ПОНАДОБИЛСЯ: мягкое условие «имя предприятия
    названо в тексте страницы» пропускает ЛЮБОЙ агрегатор — они все называют предприятие,
    это их работа. Просмотр глазами десяти случайных строк из выложенного файла: сайт самого
    предприятия — ОДИН, остальные datanewton, comfex, focus.kontur, b2book, companies.rbc,
    статья вуза, страница «гордость выпускников», местная новость. То есть заслон на них не
    срабатывал вовсе, и счётчик «подтверждено 53» был счётчиком не того.

    По ТЗ P25 подтверждением считается ПЕРВОИСТОЧНИК: сайт предприятия (в том числе страница
    про него на сайте холдинга), карточка закупки этого предприятия, документ раскрытия.
    Агрегатор сам по себе — нет. Строгий режим ровно это и требует, а мягкий остаётся для
    центробежной задачи, где «названо в тексте» было осмысленным.
    """
    if not (url or '').strip():
        return False, 'ссылки нет — проверить нечем'
    yd = yadro_domena(url)
    ys = yadro_domena(sayt_predpriyatiya)
    if ys and yd and yd == ys:
        return True, f'страница на сайте предприятия («{yd}»)'
    # САЙТ ХОЛДИНГА — ТОЖЕ САЙТ ПРЕДПРИЯТИЯ. Первый прогон пометил как чужие 6 контактов
    # АО «ПОЛИЭФ» со страницы `sibur.ru/polief/contacts/`: ядро домена «sibur» не совпало с
    # полем `sayt`. Но это страница ПРО ПОЛИЭФ на сайте владеющего холдинга, и контакты на
    # ней его. Признак: имя предприятия стоит в АДРЕСЕ страницы.
    # ПЕРВОИСТОЧНИКИ ПРОВЕРЯЮТСЯ ДО СПИСКА АГРЕГАТОРОВ — иначе список съедает их сам.
    #
    # ЗАМЕР, КОТОРЫЙ ЭТО ПОКАЗАЛ, И ОН ЖЕ МОЙ БРАК. Первый прогон нового заслона по
    # центробежной базе объявил агрегаторами 12 927 контактов из 17 535 — почти всё. Смотрю
    # примеры: `egrul.nalog.ru/index.html#!/search?query=1650032058`. Это ЕГРЮЛ, официальный
    # государственный реестр, самый сильный источник сведений об организации, и он же прямо
    # назван первоисточником двумя строками ниже, в `RASKRYTIE`. Поймал его мой собственный
    # кусок `egrul\.[a-z]`, написанный против поддельных «выписка-егрюл.рф».
    #
    # Урок ровно тот же, что весь день: порядок проверок ЕСТЬ правило. Заслон, поставленный
    # раньше разрешения, отменяет разрешение молча — и число выглядит как открытие, а не как
    # поломка.
    if _raskrytie(url):
        return True, 'документ раскрытия или официальный реестр сведений'
    if PLOSHCHADKA.search(url):
        return True, 'карточка закупки самого предприятия — контактное лицо заказчика назван'
    # АГРЕГАТОР ОТСЕКАЕТСЯ ДО ПРАВИЛА ХОЛДИНГА, а не после. Порядок здесь и есть заслон:
    # правило холдинга смотрит на имя в адресе, а у агрегатора имя в адресе стоит всегда.
    if AGREGATOR.search(url):
        return (False, f'агрегатор выписок («{yd}»): имя предприятия в адресе карточки стоит '
                       f'у него всегда и принадлежности страницы не доказывает')
    if imya_predpriyatiya:
        osnova = re.sub(r'[^а-яёa-z0-9]', '',
                        re.sub(r'\b(ООО|ОАО|ЗАО|ПАО|АО|ФГУП|ГУП|МУП)\b', '',
                               imya_predpriyatiya, flags=re.I).lower())
        # Транслитерация ядра: «полиэф» → «polief». Только ходовые соответствия, без затей.
        tr = str.maketrans({'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'z',
                            'з':'z','и':'i','й':'y','к':'k','л':'l','м':'m','н':'n','о':'o',
                            'п':'p','р':'r','с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'c',
                            'ч':'c','ш':'s','щ':'s','ъ':'','ы':'y','ь':'','э':'e','ю':'u',
                            'я':'a'})
        lat = osnova.translate(tr)
        # ИМЯ ИЩЕТСЯ В ХОСТЕ И ПЕРВОМ СЕГМЕНТЕ ПУТИ, А НЕ ГДЕ УГОДНО В АДРЕСЕ. Первая
        # редакция смотрела на весь адрес — и правило, написанное под `sibur.ru/polief/`,
        # стало подтверждать `checko.ru/company/ao-apatit-…` и `asu-samara.ru/otzyvy/
        # ao-polief/` (страница отзывов поставщика). Разница ровно в глубине: холдинг
        # заводит дочернее предприятие ВЕРХНИМ разделом или поддоменом, а карточка
        # агрегатора и отзыв поставщика прячут имя во втором сегменте и глубже.
        golova = re.sub(r'^\w+://', '', (url or '').strip().lower())
        chasti = [c for c in golova.split('/') if c]
        golova = re.sub(r'[^a-z0-9]', '', ''.join(chasti[:2]))
        if len(lat) >= 5 and lat[:9] in golova:
            return True, f'страница про предприятие на сайте холдинга («{yd}»)'
    if strogo:
        return (False, f'домен «{yd}» не первоисточник: не сайт предприятия, не карточка '
                       f'закупки, не раскрытие — по ТЗ P25 подтверждением не считается')
    # Имя предприятия на странице: сравниваем по ядру, как в `yadro_imeni`.
    if imya_predpriyatiya and tekst_stranicy:
        osnova = re.sub(r'[^а-яёa-z0-9]', '', imya_predpriyatiya.lower())[:14]
        if osnova and osnova in re.sub(r'[^а-яёa-z0-9]', '', tekst_stranicy.lower()):
            return True, 'предприятие названо в тексте страницы'
    if PLOSHCHADKA.search(url):
        return True, 'карточка закупки самого предприятия — контактное лицо заказчика назван'
    if CHUZHOY_DOMEN.search(url):
        return (False, f'страница отраслевого или новостного домена («{yd}») — имя на ней '
                       f'встретилось, но принадлежность контакта из этого не следует')
    return False, f'домен «{yd}» с предприятием не связан и имени предприятия на странице нет'


