def dok(put, ot=None, do=None):
    """Читает документ; ot/do — номера строк (1-based), чтобы делить громоздкие файлы."""
    t = open(put, encoding='utf-8', errors='replace').read()
    if ot or do:
        stroki = t.split('\n')
        t = '\n'.join(stroki[(ot or 1) - 1:do])
    return t


