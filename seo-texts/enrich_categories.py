# -*- coding: utf-8 -*-
"""Досье по некомпрессорным категориям через Fable API (общая инженерная логика подбора)."""
import json, re
from concurrent.futures import ThreadPoolExecutor, as_completed
from gen_provider import make_client, call

CATS = [
 'Рефрижераторные осушители сжатого воздуха',
 'Адсорбционные осушители сжатого воздуха',
 'Магистральные фильтры сжатого воздуха',
 'Ресиверы (воздухосборники) для компрессоров',
 'Генераторы азота (адсорбционные/мембранные)',
 'Генераторы кислорода',
 'Влагомаслоотделители и циклонные сепараторы',
 'Подготовка сжатого воздуха (общий раздел: осушка, фильтрация, ресивер)',
 'Расходомеры и датчики сжатого воздуха',
 'Запасные части и расходники для винтовых компрессоров',
]

PROMPT = """Ты собираешь базу знаний для SEO-текстов интернет-магазина промышленного оборудования
для сжатого воздуха. Категория: {cat}

Дай экспертную фактуру для копирайтера (общеинженерные знания, до января 2026). Помечай
[уверенность: высокая/средняя/низкая] где уместно; НЕ выдумывай конкретные бренды/цифры,
которых не уверен.

Формат (markdown):
# {cat}
## Назначение и принцип работы (кратко, по-инженерному)
## Как выбирают (главные параметры подбора и их логика)
## Ключевые характеристики (что указывать в тексте)
## Типовые ошибки покупателя / на что обратить внимание
## Связь с компрессором (как категория дополняет компрессорную систему - для перелинковки)
## 8-10 реальных вопросов покупателей для FAQ (с пометкой, какие данные нужны для ответа)
## Ловушки для копирайтера (что часто путают, чего избегать)

400-700 слов, плотно и по делу."""

client = make_client()

def worker(cat):
    msg = call(client, [{'role':'user','content':PROMPT.format(cat=cat)}], 'claude-fable-5')
    text = ''.join(b.text for b in msg.content if b.type=='text').strip()
    slug = re.sub(r'[^a-z]+','-', cat.lower().encode('ascii','ignore').decode())[:30].strip('-') or 'cat'
    fn = f'kb/category-{len(cat)%100}-{slug}.md'
    open(fn,'w').write(text+'\n')
    print(f'ок: {cat[:40]} -> {fn}', flush=True)
    return fn

with ThreadPoolExecutor(max_workers=6) as ex:
    futs={ex.submit(worker,c):c for c in CATS}
    for f in as_completed(futs):
        try: f.result()
        except Exception as e: print(f'FAIL {futs[f][:30]}: {repr(e)[:90]}', flush=True)
print('ДОСЬЕ КАТЕГОРИЙ ГОТОВЫ')
