def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', default='')
    ap.add_argument('--workers', type=int, default=6)
    ap.add_argument('--no-synth', action='store_true')
    ap.add_argument('--synth-only', action='store_true')
    a = ap.parse_args()

    keys = [k.strip() for k in a.only.split(',') if k.strip()] or list(LENSES)
    bad = [k for k in keys if k not in LENSES]
    if bad:
        sys.exit(f'нет таких линз: {bad}. Есть: {list(LENSES)}')

    os.makedirs(OUT, exist_ok=True)
    if not a.synth_only:
        print(f'запускаю {len(keys)} линз, воркеров {a.workers}', file=sys.stderr)
        stats = {}
        with ThreadPoolExecutor(max_workers=a.workers) as ex:
            for fut in [ex.submit(run_lens, k) for k in keys]:
                try:
                    k, u = fut.result()
                    stats[k] = u
                except Exception as e:  # noqa: BLE001
                    print(f'  ЛИНЗА УПАЛА: {e}', file=sys.stderr)
        with open(os.path.join(OUT, 'run-stats.json'), 'w', encoding='utf-8') as f:
            json.dump(stats, f, ensure_ascii=False, indent=1)
    if not a.no_synth:
        synthesize(keys)


if __name__ == '__main__':
    main()
