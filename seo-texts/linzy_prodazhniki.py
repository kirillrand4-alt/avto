def stroki(put, skolko_verh=30, skolko_sluchajno=15, semya=7):
    rows = list(csv.DictReader(open(put, encoding='utf-8-sig'), delimiter=';'))
    if not rows:
        return '', []
    random.seed(semya)
    vyborka = rows[:skolko_verh] + random.sample(rows, min(skolko_sluchajno, len(rows)))
    kol = list(rows[0].keys())
    t = 'КОЛОНКИ: ' + ' ; '.join(kol) + '\n\n'
    for r in vyborka:
        t += ' | '.join(f'{k}={(r.get(k) or "")[:70]}' for k in kol if (r.get(k) or '').strip()) + '\n'
    return t, rows


