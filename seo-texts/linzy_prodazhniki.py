def main():
    threads = int(sys.argv[sys.argv.index('--threads') + 1]) if '--threads' in sys.argv else 8
    only = sys.argv[sys.argv.index('--only') + 1].split(',') if '--only' in sys.argv else None
    os.makedirs(OUT, exist_ok=True)
    vse = linzy()
    if only:
        vse = {k: v for k, v in vse.items() if v[1] in only}
    gotovo = {f[3:-3] for f in os.listdir(OUT) if f.startswith('pl-')}
    vse = {k: v for k, v in vse.items() if k not in gotovo}
    print(f'линз к прогону: {len(vse)} (уже готово {len(gotovo)})', file=sys.stderr)
    client = G.make_client()
    lock = threading.Lock()

    def odna(item):
        imya, (telo, _) = item
        try:
            o = G.call(client, [{'role': 'user', 'content': telo}], model=MODEL, attempts=5)
            txt = ''.join(b.text for b in o.content if b.type == 'text').strip()
        except Exception as e:  # noqa: BLE001
            txt = f'ОШИБКА: {type(e).__name__}: {e}'
        with lock:
            open(os.path.join(OUT, f'pl-{imya}.md'), 'w', encoding='utf-8').write(txt + '\n')
        return imya, len(txt)

    with ThreadPoolExecutor(max_workers=threads) as pool:
        for imya, n in pool.map(odna, list(vse.items())):
            print(f'  готово {imya}: {n} знаков', file=sys.stderr, flush=True)
    print(f'всё → {OUT}', file=sys.stderr)


if __name__ == '__main__':
    main()
