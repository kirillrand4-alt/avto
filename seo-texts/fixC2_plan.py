def main():
    db, papka, vyhod = sys.argv[1:4]
    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import fixC_podpisi as P
    import fixC_razbor as RZ
    tekst = P.zagruzit_stranicy(papka)
    c = sqlite3.connect(db)
    c.row_factory = sqlite3.Row
    plan, propuski = [], []
    for kid, inn, polya, pochemu, gruppa in RESHENIYA:
        r = c.execute('SELECT * FROM contact WHERE id=?', (kid,)).fetchone()
        if not r or r['inn'] != inn:
            propuski.append((kid, inn, 'нет контакта или другой ИНН'))
            continue
        if inn in F2_INN or (r['bylo_fixF2'] or '').strip() or (r['rol_vruchnuyu'] or '') == 'дубль номера':
            propuski.append((kid, inn, 'правка агента F2 – не трогаю'))
            continue
        ozhid, novoe = {}, {}
        for pole, (bylo, stalo) in polya.items():
            tek = r[pole]
            if (tek or '') != (bylo or ''):
                propuski.append((kid, inn, 'поле %s сейчас «%s», ожидалось «%s»' % (pole, tek, bylo)))
                ozhid = None
                break
            ozhid[pole] = tek
            novoe[pole] = stalo
        if ozhid is None:
            continue
        plan.append({'id': kid, 'inn': inn, 'value': r['value'], 'ozhid': ozhid, 'polya': novoe,
                     'pochemu': pochemu, 'gruppa': gruppa})
    novye = []
    for n in NOVYE_SO_STRANICY:
        st = tekst(n['url'])
        if not st:
            propuski.append((None, n['inn'], 'страница не скачана: ' + n['url']))
            continue
        L = st['t'].split('\n')
        for j, l in enumerate(L):
            if l.strip() == n['posle'] and j + 1 < len(L):
                d = re.sub(r'\D', '', RZ._TEL.sub(' ', L[j + 1]))
                if len(d) == 11 and d[0] in '78':
                    d = '7' + d[1:]
                    novye.append(dict(n, value='+7 %s %s-%s-%s' % (d[1:4], d[4:7], d[7:9], d[9:])))
                break
    json.dump({'pravki': plan, 'novye': novye, 'propuski_plana': propuski},
              open(vyhod, 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('правок в плане: %d, пропусков: %d' % (len(plan), len(propuski)))
    for p in propuski:
        print('   пропуск', p)


if __name__ == '__main__':
    main()
