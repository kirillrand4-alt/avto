# -*- coding: utf-8 -*-
"""Один разбор номера на все каналы — и ЯВНЫЙ вид номера, чтобы заливка не гадала.

ОТКУДА ЗАДАЧА. 3-я сессия посчитала по базе: в `p25.db` 316 ГОРОДСКИХ номеров помечены
«личный» против 136 верных, и 311 таких строк несут `source=P25-LYUDI-2S*.csv` — то есть мои.
Причина не в добыче: мои выкладки вообще не несли колонки вида номера. Метку ставила заливка,
а поставить её ей было неоткуда — она угадывала. Гадание убирается не проверкой заливки, а
тем, что вид номера едет вместе с номером.

ПРИЗНАК ЛИЧНОГО МОБИЛЬНОГО РОВНО ОДИН: после нормализации номер начинается на 79. Городской
им не бывает никогда — ни на площадке, ни на сайте, ни в карточке закупки.

ВТОРАЯ ПОЧИНКА, НАЙДЕННАЯ ЗАОДНО. 64 номера в выкладке не разбирались ни во что: «7-42135-31680
2507», «3532 66-36-53 032», «7-41136-99000 42049». Это городской и ДОБАВОЧНЫЙ ЧЕРЕЗ ПРОБЕЛ.
Добавочные я уже чинил в ЕИС, но там он отделён дефисом («7-495-9261420-8559»), и правило
писалось под дефис. Пробел — та же сущность, записанная иначе; отдельного правила ей не надо,
надо одно общее и в одном месте, иначе третья запись добавочного разойдётся так же молча.

Использование:
    import p25_nomer
    n = p25_nomer.razobrat('7-42135-31680 2507')
    n.nomer, n.dobavochnyy, n.vid   → '+7 (42135) 3-16-80', '2507', 'городской'
"""
import re
from collections import namedtuple

Nomer = namedtuple('Nomer', 'nomer dobavochnyy vid cifry lichnyy pochemu')

# Слово «добавочный» во всех написаниях, какие встретились в источниках.
DOB_SLOVOM = re.compile(r'(?:доб(?:ав(?:очный)?)?\.?|вн(?:утр)?\.?|ext\.?)\s*[:№]?\s*(\d{1,6})',
                        re.I)
# Добавочный БЕЗ слова: хвост из 3–6 цифр, отделённый дефисом или пробелом. Забирается только
# если без него остаётся правильный номер — иначе это часть самого номера, а не добавочный.
DOB_HVOSTOM = re.compile(r'^(.*?\d)[\s\-–—]+(\d{3,6})\s*$')

MOBILNYY = 'мобильный'
GORODSKOY = 'городской'
NE_RAZOBRAN = 'не разобран'


def cifry(s):
    return re.sub(r'\D', '', s or '')


def _k_odinnadcati(c):
    """10 цифр → добавляем 7; 8XXXXXXXXXX → 7XXXXXXXXXX. Иначе как есть."""
    if len(c) == 10:
        return '7' + c
    if len(c) == 11 and c[0] == '8':
        return '7' + c[1:]
    return c


def krasivo(c):
    """У мобильного код всегда трёхзначный — его и разбиваю. У городского код бывает 3, 4 и 5
    знаков («495», «8332», «42135»), таблицы кодов у меня нет, и разбить «42135-31680» как
    «(421) 353-16-80» значит НАПИСАТЬ НЕВЕРНЫЙ КОД ГОРОДА. Цифры при этом те же и звонок
    пройдёт, но человек читает подпись, а не цифры, — поэтому городской остаётся сплошным."""
    if len(c) != 11:
        return ''
    if c[1] == '9':
        return f'+{c[0]} ({c[1:4]}) {c[4:7]}-{c[7:9]}-{c[9:]}'
    return f'+{c[0]} {c[1:]}'


def razobrat(syroy):
    """Возвращает `Nomer`. `vid` — один из «мобильный» / «городской» / «не разобран».

    `lichnyy` — True ТОЛЬКО у мобильного. Это и есть та метка, которой не хватало заливке.
    """
    syroy = (syroy or '').strip()
    if not syroy:
        return Nomer('', '', NE_RAZOBRAN, '', False, 'пусто')

    dobav = ''
    m = DOB_SLOVOM.search(syroy)
    if m:
        dobav = m.group(1)
        ostatok = DOB_SLOVOM.sub(' ', syroy)
    else:
        ostatok = syroy

    c = _k_odinnadcati(cifry(ostatok))
    # Хвост отрезаем ТОЛЬКО когда он лечит длину: «8-927-481-32-22» тоже кончается группой
    # цифр после дефиса, но это последние две цифры номера, а не добавочный.
    if not dobav and len(c) not in (10, 11):
        h = DOB_HVOSTOM.match(ostatok.strip())
        if h and len(_k_odinnadcati(cifry(h.group(1)))) == 11:
            dobav = h.group(2)
            c = _k_odinnadcati(cifry(h.group(1)))

    if len(c) != 11 or c[0] != '7':
        return Nomer('', dobav, NE_RAZOBRAN, cifry(syroy), False,
                     f'{len(cifry(syroy))} цифр, к российскому номеру не приводится')

    if c[1] == '9':
        return Nomer(krasivo(c), dobav, MOBILNYY, c, True, 'начинается на 79')
    return Nomer(krasivo(c), dobav, GORODSKOY, c, False,
                 'городской: личным мобильным быть не может')


def s_dobavochnym(n):
    """Строка для человека: «+7 (495) 926-14-20 доб. 8559»."""
    if not n.nomer:
        return ''
    return f'{n.nomer} доб. {n.dobavochnyy}' if n.dobavochnyy else n.nomer
