def main():
    klient = P.make_client()
    itog = []
    for slug, linza in LINZY:
        put = os.path.join(KAT, 'metalinza-%s.md' % slug)
        if os.path.exists(put) and os.path.getsize(put) > 500:
            print('%s — уже есть, пропускаю' % slug)
            itog.append(put)
            continue
        soobshchenie = OBSHEE + '\n' + linza + '\n' + ZADANIE
        t0 = time.time()
        try:
            msg = P.call(klient, [{'role': 'user', 'content': soobshchenie}],
                         model='claude-fable-5', attempts=3)
            tekst = ''.join(b.text for b in msg.content if b.type == 'text')
        except Exception as e:  # noqa: BLE001
            # Голого except тут нет: причина отказа печатается и попадает в файл.
            tekst = ''
            print('%s — ОТКАЗ: %s' % (slug, repr(e)[:200]))
        io.open(put, 'w', encoding='utf-8').write(tekst)
        n_kand = tekst.count('КАНДИДАТ |')
        n_idey = tekst.count('ИДЕЯ |')
        print('%-18s %6.0f c · знаков %6d · кандидатов %3d · идей %2d'
              % (slug, time.time() - t0, len(tekst), n_kand, n_idey))
        itog.append(put)
    print('\nфайлы: %s' % ', '.join(os.path.basename(x) for x in itog))


if __name__ == '__main__':
    main()
