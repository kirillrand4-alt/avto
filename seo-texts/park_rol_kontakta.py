"""РОЛЬ контакта: отделяем технического ЛПР от гинеколога, кадровика и бухгалтерии.

ОТКУДА ЗАДАЧА, числом и глазами. Пункт 5 владельца — открыть 25 случайных ссылок и ответить,
всё ли это места, откуда реально было достать факт или контакт. Открыл. Ссылки ведут на
доказательство все 25 из 25: значение действительно на странице. Но роль:

    #19 pkkb1.ru      Новиков Д. В., ГИНЕКОЛОГИЧЕСКОЕ отделение
    #21 kr-evrz.ru    «8 (960) 976-60-88 Ольга» — отдел КАДРОВ со страницы вакансий
    #24 kkb2-kuban.ru «БУХГАЛТЕРИЯ +7 (861) 222-01-56»

Замер по всему файлу, а не по выборке: 3 062 строки, человек нашей роли — 49.
**Дыра не в ссылках, а в роли.** Ссылка честная, контакт не тот.

ПОЧЕМУ БОЛЬНИЦЫ ВООБЩЕ В БАЗЕ — И ЭТО ВЕРНО. У краевой больницы стоит кислородная станция,
она в реестре ЭПБ, и как предприятие парка больница законна. Незаконен контакт: покупает
кислородное оборудование не гинеколог, а главный инженер или отдел закупок.

ПРАВИЛО. Роль ставится по ДОЛЖНОСТИ и по окружению находки, а не по предприятию:
    наша      главный инженер, энергетик, механик, технический директор, начальник цеха,
              начальник отдела главного энергетика/механика, служба эксплуатации, ОГЭ/ОГМ
    закупки   снабжение, закупки, тендерный отдел, МТО, контрактная служба — не ЛПР по
              технике, но именно они объявляют процедуру и знают, кто ЛПР
    чужая     врач, кадры, бухгалтерия, юрист, пресс-служба, регистратура, приёмная, колл-центр
    общий     контакт без человека: телефон приёмной, info@ — держим, но ЛПР не зовём

ЧЕГО МОДУЛЬ НЕ ДЕЛАЕТ. Не выбрасывает ни одной строки. Роль — это ПОМЕТКА, а удаление
доказательства ради красивой витрины и есть подгонка. Витрина ЛПР строится отдельным файлом.
"""
import csv
import io
import os
import re
import sys

BAZA = os.path.dirname(os.path.abspath(__file__))
L = os.path.join(BAZA, 'engineers-lens')
VHOD = os.path.join(L, 'PARK-KONTAKTY-2S.csv')
VYHOD = os.path.join(L, 'PARK-KONTAKTY-2S-S-ROLYU.csv')
VITRINA = os.path.join(L, 'PARK-LPR-2S.csv')

NASHA = re.compile(
    r'главн\w+\s+инженер|главн\w+\s+энергетик|главн\w+\s+механик|главн\w+\s+технолог|'
    r'техническ\w+\s+директор|директор\s+по\s+производств|директор\s+по\s+техни|'
    r'начальник\w*\s+(?:цеха|цехов|котельн|компрессорн|энергослужб|энергоцех|'
    r'отдела\s+главн\w+\s+(?:энергетик|механик)|производств|технического\s+отдел|'
    r'службы\s+эксплуатац|ремонтн)|'
    r'\bОГЭ\b|\bОГМ\b|энергетик\b|механик\b|инженер\s+по\s+(?:эксплуатац|оборудован|надзор)|'
    r'заместител\w+\s+(?:директора|генерального\s+директора)\s+по\s+(?:техни|производств|общим)',
    re.I)
ZAKUPKI = re.compile(r'снабжен|закуп|тендер|\bМТО\b|материально-техническ|'
                     r'контрактн\w+\s+служб|отдел\s+договор', re.I)
CHUZHAYA = re.compile(
    r'врач|акушер|гинеколог|педиатр|хирург|терапевт|невролог|кардиолог|онколог|'
    r'медсестр|медицинск\w+\s+сестр|заведующ\w+\s+отделением|ординатор|фельдшер|'
    r'отдел\w*\s+кадров|кадров\w+\s+служб|\bHR\b|рекрут|бухгалтер|главбух|'
    r'юрист|юридическ|пресс-служб|пресс-секретар|по\s+связям\s+с\s+обществен|'
    r'регистратур|приёмн\w+\s+комисс|call|колл-центр|секретар|канцеляр|'
    r'учител|воспитател|библиотек', re.I)


def rol(dolzhnost, citata, chelovek):
    pole = ' '.join([dolzhnost or '', citata or ''])
    # ДОЛЖНОСТЬ СИЛЬНЕЕ ОКРУЖЕНИЯ. «Главный инженер» на странице, где рядом стоит бухгалтерия,
    # остаётся главным инженером: окружение — это соседи по странице контактов, а не про него.
    if NASHA.search(dolzhnost or ''):
        return 'наша', 'должность названа прямо'
    if CHUZHAYA.search(dolzhnost or ''):
        return 'чужая', 'должность названа прямо'
    if ZAKUPKI.search(dolzhnost or ''):
        return 'закупки', 'должность названа прямо'
    if not (chelovek or '').strip():
        return 'общий', 'человека нет — телефон или почта организации'
    # ОКРУЖЕНИЕ ПРИНАДЛЕЖИТ СТРАНИЦЕ, А НЕ ЧЕЛОВЕКУ. Поймано глазами на выборке из 8 строк:
    # «Аношина Н. Е., Коммерческий директор» и «Уфаева И. В., Финансовый директор» с одной
    # страницы orbita.su получили роль «наша» — потому что где-то в той же цитате стоял
    # чужой «главный инженер». Так вся страница контактов становится техническими ЛПР.
    # Признак засчитывается, только если он стоит РЯДОМ С ЭТИМ ЧЕЛОВЕКОМ (±90 знаков).
    c = citata or ''
    yakor = -1
    for kus in sorted((chelovek or '').split(), key=len, reverse=True):
        if len(kus) >= 4 and kus in c:
            yakor = c.index(kus)
            break
    ryadom = c[max(0, yakor - 90):yakor + 90] if yakor >= 0 else ''
    if ryadom:
        if NASHA.search(ryadom):
            return 'наша', 'признак рядом с именем в цитате'
        if ZAKUPKI.search(ryadom):
            return 'закупки', 'признак рядом с именем в цитате'
        if CHUZHAYA.search(ryadom):
            return 'чужая', 'признак рядом с именем в цитате'
    # Признак есть на странице, но не у него: это ПОВОД посмотреть, а не роль.
    if NASHA.search(pole) or ZAKUPKI.search(pole):
        return 'не определена', 'признак есть на странице, но не рядом с этим человеком'
    if CHUZHAYA.search(pole):
        return 'чужая', 'по окружению находки'
    return 'не определена', 'ни должности, ни признака в цитате'


def main():
    if not os.path.exists(VHOD):
        print('нет входа', VHOD, file=sys.stderr)
        return 1
    rows = list(csv.DictReader(io.open(VHOD, encoding='utf-8-sig'), delimiter=';'))
    cols = list(rows[0].keys()) + ['rol', 'chem_rol']
    sch = {}
    MOB = re.compile(r'^\+?7?9\d{9}$')
    with io.open(VYHOD, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter=';', extrasaction='ignore')
        w.writeheader()
        for r in rows:
            r['rol'], r['chem_rol'] = rol(r.get('dolzhnost'), r.get('citata'), r.get('chelovek'))
            sch[r['rol']] = sch.get(r['rol'], 0) + 1
            w.writerow(r)
    lpr = [r for r in rows if r['rol'] in ('наша', 'закупки')]
    with io.open(VITRINA, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter=';', extrasaction='ignore')
        w.writeheader()
        for r in sorted(lpr, key=lambda x: (x['rol'] != 'наша', x['inn'])):
            w.writerow(r)
    print('строк', len(rows), '| роли:', sch)
    print('витрина ЛПР:', len(lpr), 'строк /',
          len({r['inn'] for r in lpr}), 'предприятий /',
          len({r['chelovek'] for r in lpr if (r.get('chelovek') or '').strip()}), 'имён')
    print('  из них с мобильным +79:',
          sum(1 for r in lpr if MOB.match(re.sub(r'[^\d+]', '', r.get('znachenie') or ''))))
    print('→', VYHOD, '\n→', VITRINA)
    return 0


if __name__ == '__main__':
    sys.exit(main())
