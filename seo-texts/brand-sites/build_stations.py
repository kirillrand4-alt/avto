def razdat_ugly(vint, oil, temy):
    """Каждому сайту свой угол, монопольно.

    Балл нормируем ВНУТРИ УГЛА, по лидеру этого признака, а не по общей шкале.
    Без нормировки признаки с разным потолком несравнимы: «есть категория
    дизельных» давало ровную единицу и обгоняло «доходит до 711 кВт», отчего
    угол тяжёлой станции достался Ремезе с её 315 кВт, а ЗИФ с 711 остался
    без него. После нормировки единицу по каждому признаку получает только
    его настоящий лидер, и жадный разбор ставит углы туда, где они правдивы.
    """
    syr = {}
    for site, p in vint.items():
        t = dict(temy[site], _oil=oil[site])
        for u in UGLY:
            syr[(site, u['key'])] = float(u['ball'](p, t))
    kand = []
    for u in UGLY:
        mx = max(syr[(s, u['key'])] for s in vint) or 1.0
        for site in vint:
            kand.append((syr[(site, u['key'])] / mx, site, u))
    kand.sort(key=lambda x: (-x[0], x[1]))
    vzyato, zanyato = {}, set()
    for ball, site, u in kand:
        # Нулевой балл значит «признака у сайта нет». Такой угол не выдаём
        # вовсе: иначе «станция для небольшого производства» доставалась
        # сайту с потолком 250 кВт просто потому, что он оказался наименьшим
        # из оставшихся. Лучше отдать сайту его второй по силе настоящий
        # признак, чем первый выдуманный.
        if ball <= 0 or site in vzyato or u['key'] in zanyato:
            continue
        vzyato[site] = (u, ball)
        zanyato.add(u['key'])
    return vzyato


def ugol_text(u, p, oil_n):
    n = max(p['n'], 1)
    return u['text'].format(
        doli_resiver=round(100 * p['with_receiver'] / n),
        doli_osush=round(100 * p['with_dryer'] / n),
        doli_vfd=round(100 * p['vfd'] / n),
        oil=oil_n, bar_max=f"{p['pressure_bar'][1]:g}",
        kw_max=f"{p['power_kw'][1]:g}", n=p['n'])


def raznica(site, vint, oil_all):
    """Ось разводки этого сайта: чем его модуль отличается от модуля соседа."""
    kw = vint.get('power_kw') or [0, 0]
    ba = vint.get('pressure_bar') or [0, 0]
    out = []
    if kw[1] <= 100:
        out.append(f'потолок линейки {kw[1]:g} кВт - это малые модули, '
                   f'20 футов и меньше; тяжёлых объектов на этой странице нет')
    elif kw[1] >= 500:
        out.append(f'линейка доходит до {kw[1]:g} кВт - страница про тяжёлые '
                   f'модули, где вопрос уже не «влезет ли», а сколько блоков')
    else:
        out.append(f'рабочий диапазон {rng(kw)} кВт - середина, основной объём '
                   f'заказов, здесь несущая тема это подбор под график, а не габарит')
    if ba[1] >= 25:
        out.append(f'давление до {ba[1]:g} бар - можно вести речь о дожиме, '
                   f'азотировании, опрессовке и заправке баллонов')
    elif ba[1] <= 13:
        out.append(f'потолок {ba[1]:g} бар - высокого давления на этой странице '
                   f'нет, про бустеры и рампы не писать')
    if oil_all:
        out.append(f'в каталоге {oil_all} безмасляных позиций - кислородный '
                   f'модуль можно строить на безмасляной машине')
    else:
        out.append('безмасляных позиций в каталоге нет - кислородный модуль '
                   'строится на маслозаполненной машине с трактом очистки, '
                   'и это надо сказать честно, а не умолчать')
    return out


