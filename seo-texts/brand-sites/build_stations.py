#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сборка заданий на станции и модули - приоритет владельца от 20.08.

    python3 build_stations.py            # пишет station-jobs.json

Четыре типа страниц на каждом брендовом сайте: КС, МКС, модульная азотная,
модульная кислородная. Владелец: «Кс, мкс азотные Кислородные и Модульные
они же, а так же центробежные где применимо в первую очередь надо».

ПОЧЕМУ ЭТИ СТРАНИЦЫ НЕ ПРОХОДЯТ ОБЫЧНЫЙ ГЕЙТ. Правило «меньше восьми карточек
в разделе - страница не генерируется» построено на карточках товара. У модуля
карточек нет и быть не может: модуль это НАША сборка, а не позиция завода,
в выгрузке Битрикса его нет. Доказательством ассортимента служит не счётчик
карточек, а линейка компрессоров бренда, на которой модуль собирается, -
её и кладём в payload. Гейт для этих заданий снят осознанно, поле
gate_override хранит причину.

РАЗВОДКА МЕЖДУ САЙТАМИ. Двенадцать почти одинаковых страниц про контейнер -
это ровно та каннибализация, которую мы меряли. Разводим не синонимами
заголовков, а фактическим конвертом линейки: у ABAC потолок 75 кВт, у ЗИФ
711 кВт - это разные модули, разные контейнеры и разные заказчики. Ось
разводки для каждого сайта считается из payload и уезжает в задание полем
raznica, чтобы копирайтер строил страницу вокруг неё, а не вокруг общих слов.

КИСЛОРОД И МАСЛО. У кислородного модуля есть настоящий инженерный водораздел:
масло в тракте. У части брендов в каталоге есть безмасляные винтовые, у части
нет ни одной позиции. Это меняет содержание страницы, поэтому считается
и кладётся отдельно. Конкретные требования к классу масла по ISO 8573-1
в задании помечены как требующие подтверждения инженером: нормативных
значений в наших данных нет, выдумывать их нельзя.
"""
import json, os

DIR = os.path.dirname(os.path.abspath(__file__))
JOBS = json.load(open(os.path.join(DIR, 'tz-jobs.json'), encoding='utf-8'))

# Газовая часть: генераторы - товар Enger, нашего собственного бренда. Числа
# взяты из его же карточек, они уже посчитаны в tz-jobs.
GAZ = {j['topic']: j['payload'] for j in JOBS
       if j['site'] == 'enger-air.ru' and 'генератор' in j['topic']}

TIPY = [
    ('kompressornaya-stanciya', 'компрессорная станция',
     'Компрессорная станция {b}',
     'заявка на расчёт компрессорной станции под фактический расход и график цеха',
     'стационарный комплект в машинном зале: компрессор, ресивер, осушение, '
     'фильтрация, обвязка, автоматика. Не контейнер - именно станция в помещении'),
    ('mks', 'модульная компрессорная станция',
     'Модульная компрессорная станция {b}',
     'заявка на расчёт модульной станции под условия площадки',
     'блок-контейнер заводской готовности с компрессором {b} внутри: утепление, '
     'вентиляция, отопление, электрика, пожарная автоматика, дренаж конденсата'),
    ('azotnaya-stanciya', 'модульная азотная станция',
     'Модульная азотная станция на базе компрессора {b}',
     'заявка на расчёт азотной станции по чистоте, расходу, давлению и климату',
     'контейнер с компрессором {b}, подготовкой воздуха и генератором азота; '
     'несущая тема страницы - чистота против габарита и расхода воздуха'),
    ('kislorodnaya-stanciya', 'модульная кислородная станция',
     'Модульная кислородная станция на базе компрессора {b}',
     'заявка на расчёт кислородной станции по расходу, чистоте и данным площадки',
     'контейнер с компрессором {b}, подготовкой воздуха и генератором кислорода; '
     'несущая тема - безопасность обогащённой среды и чистота тракта'),
]

VOPROS = {
    'kompressornaya-stanciya': 'Мне нужен компрессор или всё-таки станция целиком?',
    'mks': 'Помещения под компрессорную нет, что делать?',
    'azotnaya-stanciya': 'Сколько будет стоить свой азот вместо баллонов?',
    'kislorodnaya-stanciya': 'Можно поставить кислород прямо на площадке?',
}


def rng(v):
    return f'{v[0]:g}-{v[1]:g}' if v else None


def raznica(site, vint, oil_all):
    """Ось разводки этого сайта: чем его модуль отличается от модуля соседа."""
    kw = vint.get('power_kw') or [0, 0]
    ba = vint.get('pressure_bar') or [0, 0]
    out = []
    if kw[1] <= 100:
        out.append(f'потолок линейки {kw[1]:g} кВт - это малые модули, '
                   f'20 футов и меньше; тяжёлых объектов на этой странице нет')
    elif kw[1] >= 500:
        out.append(f'линейка доходит до {kw[1]:g} кВт - страница про тяжёлые '
                   f'модули, где вопрос уже не «влезет ли», а сколько блоков')
    else:
        out.append(f'рабочий диапазон {rng(kw)} кВт - середина, основной объём '
                   f'заказов, здесь несущая тема это подбор под график, а не габарит')
    if ba[1] >= 25:
        out.append(f'давление до {ba[1]:g} бар - можно вести речь о дожиме, '
                   f'азотировании, опрессовке и заправке баллонов')
    elif ba[1] <= 13:
        out.append(f'потолок {ba[1]:g} бар - высокого давления на этой странице '
                   f'нет, про бустеры и рампы не писать')
    if oil_all:
        out.append(f'в каталоге {oil_all} безмасляных позиций - кислородный '
                   f'модуль можно строить на безмасляной машине')
    else:
        out.append('безмасляных позиций в каталоге нет - кислородный модуль '
                   'строится на маслозаполненной машине с трактом очистки, '
                   'и это надо сказать честно, а не умолчать')
    return out


def main():
    vint = {j['site']: j['payload'] for j in JOBS
            if j['topic'] == 'винтовые компрессоры'}
    oil = {}
    brand = {}
    for j in JOBS:
        oil[j['site']] = oil.get(j['site'], 0) + ((j['payload'] or {}).get('oilfree') or 0)
        brand[j['site']] = j['brand']

    jobs = []
    for site in sorted(vint):
        v, b = vint[site], brand[site]
        ax = raznica(site, v, oil[site])
        for key, tema, h1, konv, chto in TIPY:
            p = {
                'kompressor_liniya': {
                    'pozitsiy': v.get('n'), 'power_kw': v.get('power_kw'),
                    'pressure_bar': v.get('pressure_bar'),
                    'flow_lmin': v.get('flow_lmin'),
                    'oilfree': v.get('oilfree'), 'vfd': v.get('vfd'),
                },
                'bezmaslyanyh_v_kataloge_vsego': oil[site],
            }
            if 'азот' in tema:
                p['generator_azota'] = dict(GAZ.get('генераторы азота', {}),
                                            _istochnik='карточки Enger, наш бренд')
            if 'кислород' in tema:
                p['generator_kisloroda'] = dict(GAZ.get('генераторы кислорода', {}),
                                                _istochnik='карточки Enger, наш бренд')
            jobs.append({
                'slug': f'{site.split(".")[0]}--{key}',
                'site': site, 'brand': b, 'topic': tema,
                'url': f'https://{site}/catalog/{key}/',
                'tier': next(j['tier'] for j in JOBS if j['site'] == site),
                'lead_question': VOPROS[key],
                'glavnaya_konversiya': konv,
                'chto_eto': chto.format(b=b),
                'h1': h1.format(b=b),
                'raznica_etogo_sayta': ax,
                'payload': p,
                'gate_override': (
                    'карточек товара у модуля нет и не будет: это наша сборка, '
                    'а не позиция завода. Доказательство ассортимента - линейка '
                    'компрессоров бренда в payload, а не счётчик карточек'),
                'vnimanie': [
                    'модуль собираем на ВИНТОВОМ компрессоре, центробежные в модули не идут',
                    f'«{b} выпускает станции» писать НЕЛЬЗЯ, если завод их не выпускает; '
                    f'правильная формулировка - «собираем модуль на базе компрессора {b}»',
                    'генератор азота или кислорода - товар отдельного завода, '
                    'в нашем случае Enger; не приписывать его бренду страницы',
                    'требования к классу масла и точке росы по ISO 8573-1 в наших '
                    'данных отсутствуют: писать как «класс согласуется проектом», '
                    'конкретные классы не выдумывать',
                    'СОСТАВ ТРАКТА ПОДГОТОВКИ у нас нигде не зафиксирован. Какие '
                    'именно ступени ставим - фильтры, осушитель, угольная колонна, '
                    'каталитический дожиг - данных нет. Перечислять ступени можно '
                    'ТОЛЬКО как возможные элементы проекта («в зависимости от '
                    'требований к чистоте в тракт входят...»), а не как обязательную '
                    'комплектацию нашего модуля. Утверждение «у нас стоит '
                    'каталитический дожиг» - выдумка, пока владелец не подтвердил',
                    'сроки поставки и цены модулей в данных отсутствуют, не называть',
                ],
            })

    out = os.path.join(DIR, 'station-jobs.json')
    with open(out, 'w', encoding='utf-8') as fh:
        json.dump(jobs, fh, ensure_ascii=False, indent=1)
        fh.flush(); os.fsync(fh.fileno())
    print(f'станционных заданий: {len(jobs)} на {len(vint)} сайтах -> {out}')
    for site in sorted(vint):
        print(f'   {site:<26} ' + ' | '.join(k for k, *_ in TIPY))


if __name__ == '__main__':
    main()
