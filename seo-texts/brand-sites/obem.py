"""Норма объёма страницы. Одна на два генератора.

Раньше число стояло в двух местах и разошлось: ТЗ писало всем страницам
подряд «12 000-16 000 знаков», а проверка готового текста считала норму
по числу блоков скелета и допускала до 27 000. Копирайтер выполнял
задание буквально и получал брак по объёму, причём чем длиннее страница,
тем вернее: у станционных блоков вдвое больше, чем у страницы фильтров.

Единой цифры на сетку быть не может - блоки считаны разводкой отдельно
для каждой страницы. Поэтому норма ВЫЧИСЛЯЕТСЯ, и оба генератора берут
её отсюда, а не хранят свою копию.
"""

OBEM_MIN = 12000
NA_BLOK = 1250        # знаков на один содержательный блок
ZAPAS = 6000          # вступление, таблицы, FAQ, призывы, байлайн
POL = 20000           # нижний потолок: короткой странице тоже есть где развернуться


def vilka(blokov):
    """Норма знаков без тегов для страницы с таким числом H2."""
    return OBEM_MIN, max(POL, blokov * NA_BLOK + ZAPAS)
