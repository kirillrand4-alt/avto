def _tekst(msg):
    if isinstance(msg, str):
        return msg
    return ''.join(b.text for b in msg.content if getattr(b, 'type', '') == 'text')


def main():
    client = gen_provider.make_client()
    shapka = OBSHEE.format(est=EST, mash=MASHINY)
    vse = {}
    for klyuch, opis in KLASTERY.items():
        put = os.path.join(RAB, 'temy-%s.json' % klyuch)
        if os.path.exists(put):
            vse[klyuch] = json.load(open(put))
            print('%s: уже есть, %d тем' % (klyuch, len(vse[klyuch])), flush=True)
            continue
        print('%s: спрашиваю...' % klyuch, flush=True)
        otvet = _tekst(gen_provider.call(
            client,
            [{'role': 'user', 'content': shapka + '\n\n' + ZADANIE.format(opis=opis)}],
            model='claude-fable-5', max_tokens=16000))
        m = re.search(r'\[.*\]', otvet, re.S)
        if not m:
            print('%s: ответ без JSON, пропускаю' % klyuch, flush=True)
            continue
        dan = json.loads(m.group(0))
        with open(put, 'w') as f:
            json.dump(dan, f, ensure_ascii=False, indent=1)
            f.flush()
            os.fsync(f.fileno())
        vse[klyuch] = dan
        print('%s: готово, %d тем' % (klyuch, len(dan)), flush=True)

    with open(os.path.join(RAB, 'temy-svod.json'), 'w') as f:
        json.dump(vse, f, ensure_ascii=False, indent=1)
    print('итого тем:', sum(len(v) for v in vse.values()))


if __name__ == '__main__':
    main()
