def run(name, out_dir, model):
    path = os.path.join(out_dir, f'lens-{name}.md')
    if os.path.exists(path) and os.path.getsize(path) > 500:
        return name, 'кэш', 0
    t0 = time.time()
    msg = G.call(None, [{'role': 'user',
                         'content': PREAMBLE + '\n\n=== ТВОЯ РОЛЬ ===\n' + LENSES[name]}],
                 model=model, attempts=4)
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(f'# Линза: {name}\n\n{text}\n')
        fh.flush(); os.fsync(fh.fileno())          # durability: песочница откатывается
    return name, f'{len(text)} симв', time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=os.path.join(DIR, 'review'))
    ap.add_argument('--only', help='список линз через запятую')
    ap.add_argument('--workers', type=int, default=4)
    ap.add_argument('--model', default='claude-fable-5')
    a = ap.parse_args()

    os.makedirs(a.out, exist_ok=True)
    names = [x.strip() for x in a.only.split(',')] if a.only else list(LENSES)
    bad = [n for n in names if n not in LENSES]
    if bad:
        sys.exit(f'нет таких линз: {bad}. Есть: {list(LENSES)}')

    print(f'линз к прогону: {len(names)}, воркеров {a.workers}, модель {a.model}',
          flush=True)
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        futs = {ex.submit(run, n, a.out, a.model): n for n in names}
        for f in as_completed(futs):
            n = futs[f]
            try:
                name, info, sec = f.result()
                print(f'  готово {name}: {info} за {sec:.0f} с', flush=True)
            except Exception as e:
                print(f'  СБОЙ {n}: {repr(e)[:200]}', file=sys.stderr, flush=True)
    print('итог в', a.out, flush=True)


if __name__ == '__main__':
    main()
