#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Внутренняя согласованность чисел: текст проверяется сам против себя.

    python3 svyaznost.py [--tz tz/] [--pokazat 20]

ЗАЧЕМ. Все прежние проверки сверяют каждое число ОТДЕЛЬНО - с payload,
с картой, со справочником. Поэтому мимо проходит целый класс ошибок,
где числа по отдельности законны, а вместе не сходятся:

  «2100 л/мин (35 м³/ч)»            - и 2100, и 35 законны, но 2100 л/мин
                                      это 126 м³/ч, не 35;
  «55 кВт x 4000 ч x 6 руб = 1,3 млн
   за пять лет»                     - произведение равно 1,32 млн за ГОД,
                                      за пять лет 6,6 млн, ошибка в пять раз;
  «10-20% от 12 000 л/мин = 1200-2400» - тут верно, но проверять надо.

Обе живые ошибки нашёл владелец, а не проверки. Механика их не видела,
потому что смотрела на числа поодиночке.

ЧТО ЭТОТ ИНСТРУМЕНТ МОЖЕТ. Проверить всё, где текст САМ приводит и вход,
и результат: пересчёт единиц, цепочку умножения, процент от названной
базы, сумму частей против целого. Это арифметика, она детерминирована.

ЧЕГО НЕ МОЖЕТ, и это важно не переоценить. Он не знает, ОТНОСЯТСЯ ЛИ два
числа к одному объекту. Случай с ресивером - «расчётный объём для сети
1200-2400 л» против «встроенный ресивер 150-500 л» - прошёл бы и здесь:
обе величины верны, противоречие смысловое, а не арифметическое.
Такое ловится только чтением - линзой или человеком.
"""
import argparse, os, re, sys

DIR = os.path.dirname(os.path.abspath(__file__))

# Коэффициенты приведения к л/мин. Всё, что можно спутать при пересчёте.
K_LMIN = {
    'л/мин': 1.0, 'л/м': 1.0,
    'м3/мин': 1000.0, 'м³/мин': 1000.0,
    'м3/ч': 1000.0 / 60, 'м³/ч': 1000.0 / 60, 'нм³/ч': 1000.0 / 60,
    'нм3/ч': 1000.0 / 60,
    'л/с': 60.0, 'л/сек': 60.0,
    'cfm': 28.3168, 'скфм': 28.3168,
}
ED = '|'.join(sorted((re.escape(k) for k in K_LMIN), key=len, reverse=True))

# «2100 л/мин (35 м³/ч)» и «12,4 м³/мин - это 12 400 л/мин»
PARA = re.compile(
    rf'(\d[\d\s  ]*(?:[.,]\d+)?)\s*({ED})\s*'
    rf'[\(\-–—,]{{1,3}}\s*(?:это\s+|около\s+|=\s*)?'
    rf'(\d[\d\s  ]*(?:[.,]\d+)?)\s*({ED})', re.I)

# «55 кВт x 4000 ч x 6 руб = 1 320 000» в любых знаках умножения
UMNOZH = re.compile(
    r'(\d[\d\s  ]*(?:[.,]\d+)?)\s*[^\d\n]{0,18}?[xXхХ×*·]\s*'
    r'(\d[\d\s  ]*(?:[.,]\d+)?)\s*[^\d\n]{0,18}?'
    r'(?:[xXхХ×*·]\s*(\d[\d\s  ]*(?:[.,]\d+)?)\s*[^\d\n]{0,18}?)?'
    r'=\s*(\d[\d\s  ]*(?:[.,]\d+)?)\s*(млн|тыс|тысяч|миллион\w*)?')

# «10-20% от 12 000 л/мин это 1200-2400 л»
PROTSENT = re.compile(
    r'(\d+(?:[.,]\d+)?)\s*(?:-|–)?\s*(\d+(?:[.,]\d+)?)?\s*%\s*'
    r'(?:от|минутн\w*[^\d\n]{0,30})\s*(\d[\d\s  ]*(?:[.,]\d+)?)')


def chislo(s):
    return float(str(s).replace(' ', '').replace(' ', '')
                 .replace(' ', '').replace(',', '.'))


def bliz(a, b, dopusk=0.06):
    """Сходится ли с учётом округления. Шесть процентов - это про то,
    что в тексте пишут «около 126» и «12,4», а не про терпимость
    к ошибке: промах на порядок или в пять раз сюда не попадает."""
    if b == 0:
        return a == 0
    return abs(a - b) / abs(b) <= dopusk


def pereschety(text):
    """Пересчёты единиц, где текст сам даёт обе величины."""
    out = []
    for m in PARA.finditer(text):
        try:
            a, ea, b, eb = chislo(m.group(1)), m.group(2).lower(), \
                           chislo(m.group(3)), m.group(4).lower()
        except Exception:
            continue
        if ea == eb or a == 0 or b == 0:
            continue
        nado = a * K_LMIN[ea] / K_LMIN[eb]
        if not bliz(b, nado):
            out.append({
                'вид': 'пересчёт единиц',
                'в тексте': f'{m.group(1).strip()} {ea} = {m.group(3).strip()} {eb}',
                'должно быть': f'{nado:.4g} {eb}',
                'во сколько раз мимо': round(max(b, nado) / max(min(b, nado), 1e-9), 1),
                'строка': ' '.join(m.group(0).split())[:110],
            })
    return out


# Седьмой случай, когда моя проверка бракует исправную работу. Первая
# версия пометила «22 x 8 x 250 x 6 = 264 тысячи» (верно: 22 кВт x 8 ч
# x 250 дней x 6 руб) - разборщик захватил три множителя из четырёх,
# потеряв ведущий. И «(15-10) x 0,5 = 2,5» (верно) - взял 10 из скобки
# вместо результата вычитания.
#
# И то же самое расхождение, но между ДВУМЯ списками: matcher выше
# принимал латинскую «x» как знак умножения, а этот guard знал только
# кириллическую «х». Из-за расхождения случай «22 x 8 x 250 x 6», который
# комментарий выше считает закрытым, на деле продолжал браковаться -
# разборщик брал три множителя из четырёх, а guard ведущий «x» не узнавал.
# Наборы знаков у matcher и guard разъезжаться не должны.
#
# Правило, которое надо было заложить сразу: НЕ ПОМЕЧАТЬ ТО, ЧТО
# НЕ РАЗОБРАНО ЦЕЛИКОМ. Проверка, которая ошибается чаще проверяемого,
# вредна: она приучает не смотреть на её вывод.
#
# Пятнадцатый случай ложной тревоги, и опять по той же причине - в списке
# «слева выражение продолжается» были цифра, скобка, умножение, плюс
# и минус, а ДЕЛЕНИЯ не было. «(500 × 100/10) × 1,2 = 6000» - документ
# прав (500 × 10 = 5000, × 1,2 = 6000), а разборщик начал читать
# от «10» после дробной черты и потребовал двенадцать. Черта дроби
# продолжает выражение влево ровно так же, как знак умножения.
OBRYV_SLEVA = re.compile(r'[\d)xXхХ×*·+\-–/÷]\s*$')


# Шестнадцатый случай ложной тревоги. «251 кВт x 4000 ч x 70% загрузка =
# 702 800» - документ ПРАВ: 251 x 4000 x 0,7 = 702 800. А проверка взяла
# семьдесят как множитель и потребовала семьдесят миллионов. Процент
# в цепочке умножения - это доля, а не число.
PROC_MNOZH = re.compile(r'(\d[\d\s]*(?:[.,]\d+)?)\s*%')


def _doli(text, gruppy):
    """Множители с учётом того, что «70%» в цепочке - это 0,7."""
    out = []
    for g in gruppy:
        if g is None:
            continue
        out.append(g)
    return out


# Признак того, что в цепочке смешаны единицы разного масштаба:
# час с минутой, грамм с килограммом, кубометр с литром. Там, где они
# встречаются вместе, множитель пересчёта скрыт в записи.
_RAZNYE_EDINICY = re.compile(
    r'(?=[^%]*(?:/\s*ч|в\s+час|час))[^%]*(?:мин|сек|сут|смен)'
    r'|(?=[^%]*(?:\bг\b|грамм))[^%]*(?:\bкг\b|килограмм|\bт\b|тонн)'
    r'|(?=[^%]*(?:м³|куб))[^%]*(?:\bл\b|литр)'
    r'|(?=[^%]*(?:\bл\b|литр))[^%]*(?:м³|куб)', re.I)


def umnozheniya(text):
    """Цепочки умножения, где текст даёт и множители, и результат."""
    out = []
    for m in UMNOZH.finditer(text):
        # слева от выражения стоит цифра, скобка или знак операции -
        # значит выражение длиннее, чем мы разобрали, и судить нельзя
        if OBRYV_SLEVA.search(text[max(0, m.start() - 12):m.start()]):
            continue
        try:
            a, b = chislo(m.group(1)), chislo(m.group(2))
            c = chislo(m.group(3)) if m.group(3) else 1.0
            rez = chislo(m.group(4))
        except Exception:
            continue
        # процент в цепочке - это доля: «x 70% загрузка» значит x 0,7
        vyr = m.group(0)
        for i, v in ((1, a), (2, b), (3, c)):
            g = m.group(i)
            if g is None:
                continue
            poz = vyr.find(g.strip())
            if poz >= 0 and re.match(r'\s*%', vyr[poz + len(g.strip()):]):
                if i == 1:
                    a = v / 100
                elif i == 2:
                    b = v / 100
                else:
                    c = v / 100
        # ПЕРЕСЧЁТ ЕДИНИЦ ВНУТРИ ЦЕПОЧКИ. Гейт считал в лоб и браковал
        # верное: «15 м³/ч × 3 мин = 0,75» (правильно: три минуты это
        # 1/20 часа, 15/20 = 0,75) и «250 000 кг × 0,35 г/(кг·ч) = 87,5»
        # (правильно: 87 500 граммов это 87,5 кг). Инженерный текст
        # переводит единицы по ходу, это норма записи, а не ошибка.
        #
        # Судить о таких цепочках гейт не умеет, поэтому пропускает:
        # лучше не заметить, чем забраковать исправное.
        if _RAZNYE_EDINICY.search(vyr):
            continue
        mn = {'млн': 1e6, 'миллион': 1e6, 'тыс': 1e3, 'тысяч': 1e3}
        for k, v in mn.items():
            if m.group(5) and m.group(5).lower().startswith(k):
                rez *= v
                break
        nado = a * b * c
        if nado == 0 or bliz(rez, nado):
            continue
        out.append({
            'вид': 'умножение',
            'в тексте': ' '.join(m.group(0).split())[:90],
            'должно быть': f'{nado:.6g}',
            'во сколько раз мимо': round(max(rez, nado) / max(min(rez, nado), 1e-9), 1),
            'строка': ' '.join(m.group(0).split())[:110],
        })
    return out


def protsenty(text):
    """Процент от названной базы."""
    out = []
    for m in PROTSENT.finditer(text):
        try:
            p1 = chislo(m.group(1))
            p2 = chislo(m.group(2)) if m.group(2) else p1
            baza = chislo(m.group(3))
        except Exception:
            continue
        if baza < 100:
            continue
        # ищем результат в той же строке после базы
        hvost = text[m.end():m.end() + 90]
        rez = re.search(r'(\d[\d\s  ]*(?:[.,]\d+)?)\s*(?:-|–)\s*'
                        r'(\d[\d\s  ]*(?:[.,]\d+)?)\s*л', hvost)
        if not rez:
            continue
        try:
            r1, r2 = chislo(rez.group(1)), chislo(rez.group(2))
        except Exception:
            continue
        n1, n2 = baza * p1 / 100, baza * p2 / 100
        if bliz(r1, n1) and bliz(r2, n2):
            continue
        out.append({
            'вид': 'процент от базы',
            'в тексте': f'{p1:g}-{p2:g}% от {baza:g} = {r1:g}-{r2:g}',
            'должно быть': f'{n1:.4g}-{n2:.4g}',
            'во сколько раз мимо': round(max(r2, n2) / max(min(r2, n2), 1e-9), 1),
            'строка': ' '.join(m.group(0).split())[:110],
        })
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tz', default=os.path.join(DIR, 'tz'))
    ap.add_argument('--pokazat', type=int, default=20)
    a = ap.parse_args()

    vsego = collections_files = 0
    nahodki = []
    for name in sorted(os.listdir(a.tz)):
        if not name.endswith('.md'):
            continue
        collections_files += 1
        t = open(os.path.join(a.tz, name), encoding='utf-8').read()
        # Проверка процентов ОТКЛЮЧЕНА. Четыре попытки её настроить дали
        # четыре ложные тревоги подряд и ноль настоящих находок: она путает
        # базу с результатом («10-20% минутной производительности, примерно
        # 150 литров» - 150 это результат) и склеивает числа из соседних
        # предложений. Проверка, ошибающаяся чаще проверяемого, вредна:
        # она приучает не смотреть на свой вывод, и тогда настоящую находку
        # тоже пролистают. Вернуть можно, когда текст будет давать базу
        # и результат в одном предложении явно.
        for n in pereschety(t) + umnozheniya(t):
            n['файл'] = name[3:-3]
            nahodki.append(n)
            vsego += 1

    print(f'ТЗ проверено: {collections_files}, несогласованных чисел: {vsego}\n')
    nahodki.sort(key=lambda n: -n['во сколько раз мимо'])
    for n in nahodki[:a.pokazat]:
        print(f"{n['во сколько раз мимо']:>6}x  [{n['вид']}]  {n['файл']}")
        print(f"        в тексте:    {n['в тексте']}")
        print(f"        должно быть: {n['должно быть']}")
    if not nahodki:
        print('чисто')
    return 1 if nahodki else 0


if __name__ == '__main__':
    sys.exit(main())
