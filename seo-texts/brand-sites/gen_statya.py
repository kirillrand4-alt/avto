# Имя юрлица встречается тремя способами, и обходиться с ними надо
# по-разному:
#   отдельным абзацем      «<p>ООО «Руспром»</p>»      - снести целиком
#   подписью-предложением  «ООО «Руспром», компрессорное направление.»
#                                                       - снести целиком
#   с фактом в приложении  «ООО «Руспром», официальный дилер Atlas Copco.»
#                                                       - имя убрать,
#                                                         факт оставить
# Третий случай важен: дилерство владелец подтвердил, и терять его
# вместе с подписью нельзя.
_PRILOZHENIE = re.compile(
    r'(?:ООО\s*[«"]?\s*Руспром[»"]?)\s*,\s*([^.<]{3,70})\.', re.I)
_PUSTAYA_PODPIS = re.compile(
    r'(?:ООО\s*[«"]?\s*Руспром[»"]?)\s*[,.]\s*'
    r'(?:компрессорн\w+\s+направлени\w+|поставщик\w*|'
    r'постав\w+\s+и\s+монтаж\w*)?\s*\.?\s*(?=Обновлено|$|<)', re.I)


def snyat_baylajn(html):
    """Убрать имя юрлица из тела страницы.

    ПОЧЕМУ ПОСТ-ОБРАБОТКОЙ, А НЕ ПЕРЕГЕНЕРАЦИЕЙ. Владелец 22.08:
    «зачем называть? почему чтобы убрать мелкую плашку надо
    перегенерировать всю статью?» - и он прав. Подпись это одна строка,
    её снимает вычёркивание, а не прогон на триста секунд и триста
    тысяч токенов.

    То же правило шире: всё, что чинится детерминированно, чинится
    детерминированно. Перегенерация нужна там, где меняется СОДЕРЖАНИЕ
    (новый блок скелета, другой угол сайта, снятый перебор призывов),
    а не там, где надо стереть известную строку."""
    novyy = _PUSTAYA_PODPIS.sub('', html)
    # приложение с фактом: имя долой, факт с заглавной
    novyy = _PRILOZHENIE.sub(
        lambda m: m.group(1)[0].upper() + m.group(1)[1:] + '.', novyy)
    novyy = _BAYLAJN.sub('', novyy)
    # осиротевшие пустые абзацы после снятия
    novyy = re.sub(r'<p[^>]*>\s*</p>', '', novyy)
    return novyy, html.count('Руспром') - novyy.count('Руспром')


def _tekst(html):
    """Текст без разметки, но С ГРАНИЦАМИ ЯЧЕЕК.

    Гейт воздух/газ отличает утверждение от строки таблицы по вертикальной
    черте: «| Чистота | Коэффициент | Пример на 10 м³/ч |» - это колонки,
    а не заявление. Снятие тегов границы стирало, и наша же опубликованная
    таблица коэффициентов подбора превращалась в сплошную фразу
    «Чистота азота Коэффициент подбора Пример: 10 м³/ч азота 99% 0,05»,
    которую гейт честно бракует как выдумку.

    Правило было верным, а входные данные я ему портил сам."""
    h = re.sub(r'</t[dh]>', ' | ', html, flags=re.I)
    h = re.sub(r'</tr>', ' |\n', h, flags=re.I)
    return re.sub(r'[ \t]+', ' ', re.sub(r'<[^>]+>', ' ', h)).strip()


