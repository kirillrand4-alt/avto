def sobrat(rol_klyuch, zhivaya, zamena):
    return (
        LINZY[rol_klyuch] + '\n\n' + PRAVILA +
        '\n\n=== ВЕРСИЯ А: та, что сейчас стоит на сайте ===\n\n' + zhivaya +
        '\n\n=== ВЕРСИЯ Б: предложена на замену ===\n\n' + zamena +
        '\n\nВ версии Б пометки «H2:», «H3:», «CTA:» - это разметка чернового\n'
        'документа, а не текст страницы; оценивай замысел, но отметь, что\n'
        'документ отдан в черновом виде, если считаешь это существенным.\n\n' +
        FORMAT
    )


def _tekst(msg):
    """call() отдаёт объект сообщения: собираем из него текстовые блоки."""
    if isinstance(msg, str):
        return msg
    return ''.join(b.text for b in msg.content if getattr(b, 'type', '') == 'text')


def razobrat(otvet):
    otvet = _tekst(otvet)
    m = re.search(r'\{.*\}', otvet, re.S)
    if not m:
        raise ValueError('в ответе нет JSON')
    return json.loads(m.group(0))


def main():
    zhivaya = open(os.path.join(RAB, 'zhivaya.txt')).read()
    zamena = re.sub(r'^\[\d+\]\s*', '', open(os.path.join(RAB, 'zamena.txt')).read(),
                    flags=re.M)

    client = gen_provider.make_client()
    itogi = {}
    for rol in LINZY:
        put = os.path.join(RAB, 'ocenka-%s.json' % rol)
        if os.path.exists(put):
            itogi[rol] = json.load(open(put))
            print('%s: уже есть' % rol, flush=True)
            continue
        print('%s: спрашиваю...' % rol, flush=True)
        otvet = gen_provider.call(
            client,
            [{'role': 'user', 'content': sobrat(rol, zhivaya, zamena)}],
            model='claude-fable-5', max_tokens=16000)
        dan = razobrat(otvet)
        with open(put, 'w') as f:
            json.dump(dan, f, ensure_ascii=False, indent=1)
            f.flush()
            os.fsync(f.fileno())
        itogi[rol] = dan
        print('%s: готово, вердикт %s' % (rol, dan.get('verdikt')), flush=True)

    with open(os.path.join(RAB, 'ocenka-svod.json'), 'w') as f:
        json.dump(itogi, f, ensure_ascii=False, indent=1)
    for rol, dan in itogi.items():
        print('%-12s живая %.1f | замена %.1f | вердикт %s' % (
            rol, dan['zhivaya']['srednyaya'], dan['zamena']['srednyaya'],
            dan['verdikt']))


if __name__ == '__main__':
    main()
