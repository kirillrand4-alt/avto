# доказательства и нужен. Читателю важно «такие же, как я, это ставят»,
# а не в каком году и в каком городе.
def _obezlichit_proekty(job):
    """Снять город и год, оставить отрасль и оборудование."""
    pr = (job.get('payload') or {}).get('proekty') or job.get('proekty')
    if not isinstance(pr, list):
        return job
    chisto = []
    for p in pr:
        if not isinstance(p, dict):
            continue
        d = {k: v for k, v in p.items() if k not in ('город', 'год')}
        if d and d not in chisto:
            chisto.append(d)
    job = json.loads(json.dumps(job, ensure_ascii=False))
    if isinstance(job.get('payload'), dict) and 'proekty' in job['payload']:
        job['payload']['proekty'] = chisto
    if 'proekty' in job:
        job['proekty'] = chisto
    return job


