def _perelinkovka(job):
    """Настоящие адреса разделов этого домена, отобранные по теме."""
    slug = job.get('slug') or ''
    dom, _, tema = slug.partition('--')
    for k in KARTA_URL:
        if k.split('.')[0] == dom.split('.')[0]:
            dom = k
            break
    razdely = KARTA_URL.get(dom) or []
    if not razdely:
        return ''
    klyuchi = BLIZOST.get(tema) or ()
    svoi = _re.compile('|'.join(_re.escape(k) for k in klyuchi), _re.I) \
        if klyuchi else None
    # Своя же тема в подборку не идёт: страница не ссылается на себя.
    sam = _re.compile('|'.join(_re.escape(k) for k in tema.split('-')
                               if len(k) > 4), _re.I) if '-' in tema else None
    otobrano = []
    for r in razdely:
        h1 = r.get('h1') or ''
        if svoi and not svoi.search(h1):
            continue
        if r['url'].rstrip('/').endswith(tema):
            continue
        otobrano.append(r)
    if not otobrano:
        otobrano = [r for r in razdely if r.get('показы')]
    # КАТЕГОРИЯ ВЫШЕ МОДЕЛИ. По показам первым шёл раздел «Компрессор
    # Atlas Copco GA37» - живой и с сеткой карточек, но это одна модель.
    # Ссылка со статьи о модульной станции на «винтовые компрессоры»
    # ведёт читателя к выбору, ссылка на GA37 - в тупик конкретной
    # машины, которая ему, возможно, не подходит вовсе.
    otobrano.sort(key=lambda r: (bool(_MODEL_V_H1.search(r.get('h1') or '')),
                                 -(r.get('показы') or 0)))
    otobrano = otobrano[:SKOLKO_SSYLOK]
    if not otobrano:
        return ''
    stroki = []
    for r in otobrano:
        hv = []
        if isinstance(r.get('товаров'), int):
            hv.append(f'{r["товаров"]} позиций')
        if r.get('показы'):
            hv.append(f'{r["показы"]} показов за месяц')
        stroki.append(f'   {r["h1"]}\n      {r["url"]}'
                      + (f'   [{", ".join(hv)}]' if hv else ''))
    # СОСЕДИ ПО ПАРТИИ. Запретить сочинять адреса оказалось мало: три ТЗ
    # подряд написали /catalog/mks/ и /catalog/kompressornaya-stanciya/
    # уже ПОСЛЕ прямого запрета. Модель не своевольничает - ей нечем
    # обозначить переход на страницу, которая пишется прямо сейчас
    # и адреса ещё не имеет. Значит нужен законный способ, а не запрет.
