def _missing(text):
    low = text.lower()
    return [n for n in NEEDED if n not in low]


def _skelet_ok(slug, text):
    """Сошёлся ли раздел 6 с заданным скелетом.

    Проверяем не побуквенно: заголовок допустимо огранить («Блок 3: X»,
    «X (H2)»), но набор блоков должен совпасть. Считаем по нормализованным
    строкам, порог мягкий - три четверти заданных блоков должны найтись.
    Иначе ТЗ переизобрело структуру, и разводка, посчитанная на скелетах,
    до готовых страниц не доживёт.
    """
    sk = SKELETY.get(slug)
    if not sk:
        return True, ''
    import tz_qa
    br = tz_qa.brendy()
    est = [tz_qa.norm(h, br) for h in tz_qa.skelet(text, br)]
    # Служебные блоки конверсии извлекатель отбрасывает намеренно, они есть
    # на каждой странице. Считать их пропущенными - значит валить исправное
    # ТЗ: у крайнего скелета из тринадцати блоков четыре именно такие.
    nado = [h for h in sk
            if tz_qa.norm(h, br) and not tz_qa.SLUZHEBNYE.match(h.strip())]
    nashli = [h for h in nado
              if any(tz_qa.pohozh(tz_qa.norm(h, br), e) for e in est)]
    dolya = len(nashli) / max(len(nado), 1)
    if dolya >= 0.75:
        return True, ''
    poteryany = [h for h in nado if h not in nashli]
    return False, (f'скелет не сошёлся: из {len(nado)} блоков нашлось '
                   f'{len(nashli)}. Пропущены: ' + '; '.join(poteryany[:5]))


def _complete(text, slug=None):
    if not (text.rstrip().endswith(MARK) and not _missing(text)):
        return False
    if _zadvoen(text):
        return False
    return _skelet_ok(slug, text)[0] if slug else True


def _write(path, text):
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text + '\n')
        fh.flush(); os.fsync(fh.fileno())


class _Kak_msg:
    """Склейку двух проходов дальше по коду проверяют как обычный ответ."""

    def __init__(self, text):
        self.content = []
        self._t = text
        self.stop_reason = 'end_turn'
        self.usage = None


def _prohod(job, model, max_tokens, chast, gotovoe, marker, nachalo=None,
            popytok=3, objazatelno=None):
    """Один проход, со своими попытками. Возврат (текст, причина).

    Повтор ИМЕННО ЭТОГО прохода, а не всего документа. Обрыв стрима -
    штатная флакость шлюза (stop_reason=incomplete), и она случается
    на любом из трёх проходов. Прежде падение третьего заставляло писать
    заново все три: на батче в 399 вызовов это лишние часы и деньги."""
    last = ''
    for k in range(popytok):
        msg = G.call(None, [{'role': 'user',
                             'content': prompt_for(job, chast=chast,
                                                   gotovaya_chast1=gotovoe)}],
                     model=model, attempts=4, max_tokens=max_tokens,
                     thinking_on=False)
        t = ''.join(b.text for b in msg.content if b.type == 'text').strip()
        # НОМЕР РАЗДЕЛА ПРОВЕРЯЕМ ОТДЕЛЬНО. Второй проход однажды
        # пронумеровал свой раздел как «## 7. Подробная структура» вместо
        # шестого, третий написал настоящий седьмой - и документ ушёл
        # в брак как задвоенный, хотя содержимое было в порядке.
        nomer_ok = (not objazatelno) or (objazatelno in t)
        if msg.stop_reason == 'end_turn' and (not marker or marker in t) \
                and nomer_ok:
            if marker:
                t = t.split(marker)[0].rstrip()
            # Проход иногда начинает с любезности вместо своего заголовка.
            if nachalo:
                i = t.find(nachalo)
                if i > 0:
                    t = t[i:]
            return t, ''
        v = getattr(getattr(msg, 'usage', None), 'output_tokens', None)
        prichina = ('нет заголовка ' + objazatelno) if not nomer_ok \
            else f'stop_reason={msg.stop_reason}'
        last = (f'часть {chast} не дописана ({len(t)} симв, вых.токенов {v}, '
                f'{prichina}, попытка {k + 1}/{popytok})')
        print(f'   {job["slug"]}: {last}', file=sys.stderr, flush=True)
    return None, last


def _dva_prohoda(job, model, max_tokens):
    """ТРИ прохода: начало (1-5), раздел 6, хвост (7-13).

    Имя оставлено прежним, чтобы не трогать вызывающий код. Проходов
    стало три, потому что раздел 6 - это девятнадцать блоков по четыре
    подпункта, и на шве 6/7 вся тяжесть падала в первую часть: она
    выдала шесть блоков из девятнадцати, даже не упершись в потолок."""
    t1, why = _prohod(job, model, max_tokens, 1, '', MARK1)
    if t1 is None:
        return None, why
    t2, why = _prohod(job, model, max_tokens, 2, t1, MARK1, '## 6.',
                      objazatelno='## 6.')
    if t2 is None:
        return None, why
    sobrano = t1 + '\n\n' + t2
    t3, why = _prohod(job, model, max_tokens, 3, sobrano, None, '## 7.')
    if t3 is None:
        return None, why
    return (sobrano + '\n\n' + t3).strip(), ''


def run(job, out_dir, model, max_tokens, tries=2, v_dva=False):
    path = os.path.join(out_dir, f"TZ-{job['slug']}.md")
    if os.path.exists(path) and _complete(open(path, encoding='utf-8').read(), job['slug']):
        return job['slug'], 'кэш', 0
    brak_dir = os.path.join(os.path.dirname(out_dir.rstrip('/')) or DIR, 'tz-brak')
    t0 = time.time()
    last = ''
    os.makedirs(brak_dir, exist_ok=True)
    for k in range(tries):
        if v_dva:
            text, pochemu = _dva_prohoda(job, model, max_tokens)
            if text is None:
                last = pochemu
                continue
            msg = _Kak_msg(text)
        else:
            msg = G.call(None, [{'role': 'user', 'content': prompt_for(job)}],
                         model=model, attempts=4, max_tokens=max_tokens,
                         thinking_on=False)
            text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
        text = text.replace('—', '-').replace('–', '-')      # длинное тире запрещено
        sk_ok, sk_why = _skelet_ok(job['slug'], text)
        # Задвоение проверяется ДО записи, а не только в ветке брака.
        # Прежде условие успеха его не смотрело, и документ, пошедший
        # по второму кругу, спокойно сохранялся как готовый.
        import sanity as _sn
        import svyaznost as _sv
        vozduh = _sn.vozduh_na_gaz(text)
        # Пересчёт единиц в приёмку. Кислородное ТЗ Atlas Copco написало
        # «2100 л/мин (35 м³/ч)»: поделило на 60 вместо умножения на 0,06,
        # ровно та ошибка, против которой заведён блок единиц. Блок даёт
        # готовую таблицу, но она посчитана под числа payload, а модель
        # взялась пересчитывать своё.
        chisla = _sv.pereschety(text) + _sv.umnozheniya(text)
        # ВЫДУМАННЫЙ АДРЕС. Правило, держащееся на послушании модели,
        # не правило: получив список проверенных адресов и прямой запрет
        # сочинять свои, модель всё равно дописала ссылки на СОСЕДНИЕ
        # страницы этой же партии - /catalog/kompressornaya-stanciya/
        # и /catalog/mks/. Логика её понятна (странице о станции место
        # рядом со страницей о модуле), но этих разделов на сайте нет,
        # и копирайтер поставил бы 404.
        levye = _levye_adresa(text, job['slug'])
        # Стаж числом и узнаваемый заказчик - решение владельца 22.08.
        stazh = _sn.stazh_i_zakazchik(text)
        # Страна из выгрузки - поле каталога, а не адрес завода.
        strana = _sn.strana_zavoda(text)
        if (text.rstrip().endswith(MARK) and not _missing(text) and sk_ok
                and not _zadvoen(text) and not vozduh and not chisla
                and not levye and not stazh and not strana
                and msg.stop_reason == 'end_turn'):
            _write(path, text + '\n\n' + _shtamp(job))
            return job['slug'], f'{len(text)} симв', time.time() - t0
        # Порядок диагнозов важен: у оборванного стрима ВСЕГДА не хватает
        # последних разделов, и если сначала проверять их, причина запишется
        # как «нет финального смысла», а настоящая - обрыв. Семь категорийных
        # ТЗ так и были помечены, и я полез искать проблему в инструкции,
        # хотя провайдер просто рвал соединение.
        if _zadvoen(text):
            last = 'тело ТЗ задвоено: разделы идут по второму кругу'
            _write(os.path.join(DIR, 'tz-brak', f"TZ-{job['slug']}.try{k+1}.md"), text)
            continue
        if levye:
            last = ('адреса не из проверенной карты, копирайтер поставит '
                    'по ним 404: ' + ', '.join(levye[:4]))
            _write(os.path.join(DIR, 'tz-brak', f"TZ-{job['slug']}.try{k+1}.md"), text)
            continue
        if stazh:
            last = 'стаж числом или узнаваемый заказчик: ' + '; '.join(stazh[:2])
            _write(os.path.join(DIR, 'tz-brak', f"TZ-{job['slug']}.try{k+1}.md"), text)
            continue
        if strana:
            last = ('страна сборки утверждается без ссылки на каталог, '
                    'писать «в каталоге страна указана как X у N позиций»: '
                    + '; '.join(x[-70:] for x in strana[:2]))
            _write(os.path.join(DIR, 'tz-brak', f"TZ-{job['slug']}.try{k+1}.md"), text)
            continue
        gap = _missing(text)
        oborvan = not text.rstrip().endswith(MARK)
        vyh = getattr(getattr(msg, 'usage', None), 'output_tokens', None)
        last = (f'обрыв стрима ({len(text)} симв, вых.токенов {vyh}, '
                f'stop_reason={msg.stop_reason}'
                + (f', не хватает {gap}' if gap else '') + ')') if oborvan else (
                f'нет разделов {gap}' if gap else
                (f'выдуманное соотношение воздух/газ: {vozduh[0][-90:]}'
                 if vozduh else
                 (f"числа не сходятся: {chisla[0]['в тексте']} -> должно "
                  f"{chisla[0]['должно быть']}" if chisla else sk_why)))
        os.makedirs(brak_dir, exist_ok=True)
        _write(os.path.join(brak_dir, f"TZ-{job['slug']}.try{k + 1}.md"), text)
    return job['slug'], f'БРАК: {last}, см. tz-brak/', time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', default=os.path.join(DIR, 'tz-jobs.json'))
    ap.add_argument('--out', default=os.path.join(DIR, 'tz'))
    ap.add_argument('--only')
    ap.add_argument('--workers', type=int, default=3)
    ap.add_argument('--model', default='claude-fable-5')
    # 32000 хватало категорийным ТЗ, но не станционным: там разделов больше
    # и модель уходит за 30 тыс. знаков, упираясь в потолок вместе с thinking.
    # 64000 не хватило: после разбавления скелетов до 12-17 блоков ТЗ
    # выходили на 39-47 тыс. знаков и обрывались, десять прогонов
    # из семидесяти двух уходили в мусор целиком. Обрыв дороже
    # запаса: потолок оплачивается по факту, а обрезанный документ
    # оплачивается полностью и выбрасывается.
    # Скелеты после добавления цены выросли до 10-16 блоков (среднее 13,8),
    # и документ перестал влезать в 96000: три обрыва подряд ровно
    # на 37,4 тыс. знаков. Потолок оплачивается по факту, обрыв -
    # целиком и в мусор.
    ap.add_argument('--max-tokens', type=int, default=140000)
    # Обрыв стрима у провайдера - не дефект промпта, а флаки соединения:
    # у длинных станционных ТЗ он ловится по два раза подряд, а третий
    # заход проходит. Держим ручку, чтобы не править код под каждый прогон.
    ap.add_argument('--tries', type=int, default=2)
    ap.add_argument('--dva', action='store_true',
                    help='два прохода: разделы 1-6, затем 7-13')
    a = ap.parse_args()

    jobs = json.load(open(a.jobs, encoding='utf-8'))
    if a.only:
        keep = {x.strip() for x in a.only.split(',')}
        jobs = [j for j in jobs if j['slug'] in keep]
    os.makedirs(a.out, exist_ok=True)
    print(f'ТЗ к прогону: {len(jobs)}, воркеров {a.workers}', flush=True)
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        futs = {ex.submit(run, j, a.out, a.model, a.max_tokens, a.tries, a.dva): j['slug'] for j in jobs}
        for f in as_completed(futs):
            try:
                s, info, sec = f.result()
                print(f'  готово {s}: {info} за {sec:.0f} с', flush=True)
            except Exception as e:
                print(f'  СБОЙ {futs[f]}: {repr(e)[:200]}', file=sys.stderr, flush=True)
    print('итог в', a.out, flush=True)


if __name__ == '__main__':
    main()
