# Энергия. Владелец 21.08 нашёл в готовом ТЗ: «55 кВт x 4000 ч x 6 руб =
# 1,3 млн за 5 лет». На деле 1,32 млн это ГОД, за пять лет 6,6 млн -
# занижено в 5,1 раза. Годовая цифра подписана пятилетней.
#
# Снова арифметика внутри языковой модели, которой там быть не должно.
# Считаем кодом и подаём готовой таблицей, как единицы.
#
# И вторая поправка владельца, инженерная: считать НЕ по шильдику.
# Паспортные киловатты - мощность двигателя при полной нагрузке, а машина
# работает по профилю: часть смены на холостом, часть под частичной
# загрузкой. Atlas Copco в своих методичках рекомендует то же самое -
# брать фактическую потребляемую мощность, а не цифру с таблички.

# ВЕНТИЛЯЦИЯ. Находка владельца 21.08, и она опаснее прочих: в семнадцати
# ТЗ стояло «два компрессора дают около 450-480 кВт тепла» и рядом
# «вентиляция 10-15 кратных обменов объёма контейнера в час». Связки
# между этими фразами нет никакой.
#
# Считаем: 465 кВт при перегреве 10 K требуют 465/(1,2*1,005*10) = 38,6 м³/с,
# то есть около 139 тысяч м³/ч; при 7 K - около 198 тысяч. А пятнадцать
# обменов сорокафутового контейнера (67 м³) дают 1005 м³/ч. Разница
# в 130-200 раз. По такому проекту станция встанет по перегреву в первый
# же час.
#
# Кратность обменов - честная мера для помещений с людьми, где нормируют
# свежий воздух на человека. Для отвода тепла от машин она не работает
# в принципе: воздуха нужно столько, сколько уносит тепло при допустимом
# перегреве, и от объёма помещения это не зависит.
#
# Правила кратности не было ни в промпте, ни в справочниках - модель взяла
# её из общих знаний. Значит запретом не обойтись: нужна замена, иначе
# на месте запрета образуется пустота, и она снова заполнится
# правдоподобным.
RO_VOZD = 1.2          # кг/м³ при 20 °C
CP_VOZD = 1.005        # кДж/(кг·К)
DOLYA_TEPLA = 0.95     # почти вся подведённая мощность уходит в тепло


def _ventilyaciya(job):
    """Расход вентиляции по тепловой нагрузке. Только модульным страницам."""
    cel = ' '.join(str(job.get(k) or '') for k in ('topic', 'slug', 'h1'))
    if not _re.search(r'модул|mks|мкс|контейн|станци', cel, _re.I):
        return ''
    kw = _chisla(job).get('power_kw')
    if not kw:
        return ''
    sred = None
    d = KARTA.get(job.get('site')) or {}
    r = d.get('распределение по мощности') or []
    if r:
        vsego, nakop = sum(x['позиций'] for x in r), 0
        GRAN = {'до 15 кВт': (5, 15), '15-90 кВт': (15, 90),
                '90-250 кВт': (90, 250), 'свыше 250 кВт': (250, 500)}
        for x in r:
            nakop += x['позиций']
            if nakop >= vsego / 2:
                lo, hi = GRAN.get(x['полка'], (kw[0], kw[1]))
                sred = (lo + hi) / 2
                break
    sred = sred or (kw[0] + kw[1]) / 2
    stroki = []
    for n, imya in ((1, 'одна машина'), (2, 'две машины')):
        Q = sred * n * DOLYA_TEPLA
        for dT in (7, 10, 15):
            V = Q / (RO_VOZD * CP_VOZD * dT) * 3600
            stroki.append(f'   {imya:<12} {sred * n:>6.0f} кВт | тепло '
                          f'{Q:>6.0f} кВт | перегрев {dT:>2} K | '
                          f'{V:>9,.0f} м³/ч'.replace(',', ' '))
    return f"""
=== ВЕНТИЛЯЦИЯ МОДУЛЯ: СЧИТАЕТСЯ ПО ТЕПЛУ, А НЕ ПО ОБЪЁМУ ===

{chr(10).join(stroki)}

ФОРМУЛА, по которой это посчитано: расход = тепловая мощность делить
на (плотность воздуха {RO_VOZD} умножить на теплоёмкость {CP_VOZD} умножить
на допустимый перегрев). В тепло уходит около {DOLYA_TEPLA * 100:.0f}% подведённой
электрической мощности, а не «остаток после КПД».

«КРАТНОСТЬ ОБМЕНОВ» ДЛЯ ЭТОГО НЕ ГОДИТСЯ, и это не придирка. Пятнадцать
обменов сорокафутового контейнера дают около тысячи м³/ч, а на отвод
450 кВт нужно под двести тысяч - разница в двести раз, и станция встанет
по перегреву. Кратность нормируют там, где считают свежий воздух
на человека; тепло машин от объёма помещения не зависит вовсе.

ЧТО ПИСАТЬ НА СТРАНИЦЕ. Величины выше - порядок, а не проект: «расход
вентиляции считается по суммарному тепловыделению установленного
оборудования и допустимому перегреву внутри модуля; конкретный расход
определяется проектом». Одну строку из таблицы можно привести примером,
назвав перегрев, при котором она посчитана.
"""


