#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Генератор технических заданий на страницы брендовой сетки.

    python3 gen_tz.py [--only slug,slug] [--workers 3] [--out tz/]

На вход - карточка страницы (сайт, тема, тир, payload, ведущий вопрос),
на выход - ТЗ по шаблону из 13 разделов, как эталонные ТЗ копирайтера
в tz-etalon/ и как написанное руками TZ-01-berg-vintovye.md.

Все правила сетки зашиты в RULES и уходят в каждый промпт: три уровня
товара, тиры, запреты формулировок, белый список брендов, шесть сортов чисел,
фильтр банальности, отсутствие межсайтовых ссылок и байлайнов.

Результат каждого ТЗ пишется на диск сразу с fsync - песочница при рестарте
откатывается (урок 2026-07-25 из CLAUDE.md). Готовые при повторном запуске
пропускаются, прогон резюмируем.

ОБРЫВЫ. Первый прогон 20.08 дал 7 обрезанных ТЗ из 18: документ на 25 тыс.
знаков вместе с adaptive thinking не влезал в потолок 16000 токенов, стрим
заканчивался на середине раздела. gen_provider.call отдаёт такой ответ как
валидный (там порог «больше 200 знаков»), поэтому целостность проверяем здесь:
потолок поднят, а ТЗ считается готовым только если оно кончается маркером
MARK и провайдер сказал end_turn. Недоделанное уезжает в tz-brak/, чтобы
не занять место готового и не пройти мимо кэша при следующем запуске.
"""
import argparse, json, os, sys, time
from concurrent.futures import ThreadPoolExecutor, as_completed

DIR = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(DIR))
import gen_provider as G

ALLOW = json.load(open(os.path.join(DIR, 'brands-allow.json'), encoding='utf-8'))

MARK = '<!-- ТЗ ЗАВЕРШЕНО -->'   # признак целого документа, проверяется механически

RULES = """
=== ПРАВИЛА СЕТКИ (действуют на каждой странице, нарушение = брак) ===

ТРИ УРОВНЯ ТОВАРА, не смешивать:
- компрессор - товар завода бренда, пишем как есть;
- генератор азота или кислорода - товар ДРУГОГО завода, называем изготовителя по имени;
- модуль (МКС, азотная и кислородная станция) - НАША сборка. Формулировка
  «собираем модуль на базе компрессора X» - можно. «X выпускает МКС» - НЕЛЬЗЯ,
  если завод их не выпускает.

ЗАПРЕТЫ ФОРМУЛИРОВОК:
- «производим», «наш завод», «изготавливаем», «разработка наших инженеров»
  применительно к чужому бренду. Слово «производитель» допустимо только для Enger.
- Называть марки, которых нет в нашем каталоге. Разрешённые бренды - только
  из списка ниже.
- Приписывать бренду сайта товар, которого он не выпускает.
- Центробежные компрессоры как основа МКС: модули собираем только на винтовых.
- ЦЕНТРОБЕЖНЫЕ - ТОЛЬКО ВОЗДУШНЫЕ. Решение владельца 20.08: газовые
  центробежные машины (компримирование природного газа, технологических
  и попутных газов, нефтегазовая транспортировка) мы не продаём и в текстах
  не упоминаем - ни как наш товар, ни как «также бывают». Страница центробежных
  это страница про СЖАТЫЙ ВОЗДУХ: продувка, аэрация, пневмотранспорт,
  цех, стеклотара, очистные сооружения. Слова «технологический газ»,
  «попутный нефтяной газ», «компримирование газа» на этих страницах
  не появляются.

ШЕСТЬ СОРТОВ ЧИСЕЛ, у каждого свой источник:
1. Про наш товар (кВт, бар, л/мин, литры, позиции, цена) - ТОЛЬКО из payload.
   Счётчик позиций можно округлить вниз до красивого.
2. Физические константы и свойства веществ - можно, но только общеизвестное
   и проверяемое, без сомнительной точности.
3. Нормативные величины (ISO 8573-1, ГОСТ, СанПиН) - только с указанием
   документа и класса.
4. Инженерные правила прикидки (объём ресивера 10-20% минутной производительности,
   точка росы, расход воздуха на кубометр газа) - ТОЛЬКО как диапазон и как правило,
   НИКОГДА как конкретная цифра под конкретную машину.
5. Расчётные примеры - показывать вход и множитель, чтобы читатель проверил.
6. Доли рынка, «у 30% предприятий», средние сроки окупаемости - ЗАПРЕЩЕНЫ.

ЦЕНЫ: абсолютные цифры остаются в карточках товаров, они обновляются выгрузкой
из 1С. В тексте - только относительные величины и сегменты («дороже примерно
вдвое», «начальный сегмент»). Причина: цены привязаны к валюте и в тексте
их обновлять нечем.

ССЫЛКИ: только внутри своего домена. Ссылок на prokompressor.ru и на другие
сайты сетки НЕТ - решение владельца, чтобы сетка не читалась как сетка.

БАЙЛАЙН: на брендовых сайтах подписи автора не ставим. Дату обновления оставляем.

ФИЛЬТР БАНАЛЬНОСТИ: если специалист на фразу скажет «ну это очевидно» - она стоит
максимум одной строки, блок на ней строить нельзя. Блок держится только на том,
что противоречит ожиданию, больше по величине чем кажется, или описывает ошибку,
которую в момент покупки не видно.

ВЕДУЩИЙ ВОПРОС - внутренняя рамка для сборки скелета, НЕ заголовок на странице.
Формулируется как прямая речь покупателя.

ЯСНОСТЬ (вычитано владельцем на прошлом проекте):
- позиции не равны моделям: «N позиций с учётом исполнений; под заказ поставляется
  весь модельный ряд завода» - вторая часть обязательна;
- «в нашем каталоге» при первом упоминании, не голое «в каталоге»;
- запрещены слова тег, фасет, листинг, выдача;
- пневмоаудит не субъект действия;
- не подавать как опцию, влияющую на цену, то, что детерминировано мощностью
  или серией.
"""

TEMPLATE = """
=== СТРУКТУРА ТЗ (13 разделов, как в эталонах копирайтера) ===
Шапка таблицей: сайт, URL, тип страницы, тир, ведущий вопрос, объём, CTA, H1, байлайн.
Затем блок «Payload» - таблица чисел, которыми можно оперировать.
Затем разделы:
1. Задача страницы и границы контента (что НЕ раскрывать, куда это вынесено)
2. Интент и защита от каннибализации - таблица разведения с соседними страницами
3. Что продаём и какими словами
4. Оффер и порядок блоков по тиру
5. Лексика: основной и параметрический кластеры, запрещённые слова
6. Подробная структура страницы: 8-12 блоков H2 с описанием, что внутри каждого
7. Таблицы на странице, минимум две, с колонками
8. Изображения: откуда и с какими фильтрами
9. Внутренняя перелинковка
10. Что нельзя писать - общий список плюс специфика этой страницы
11. Черновик FAQ: 5-7 вопросов, гибрид из общего пула и из payload
12. Источники фактуры
13. Требования к сдаче

ЕДИНЫЕ ВЕЛИЧИНЫ ДЛЯ ШАПКИ (одинаковые на всех страницах сетки, не выдумывать свои):
- объём текста страницы: 12 000-16 000 знаков с пробелами;
- дата обновления: та, что передана в поле data_obnovleniya этой страницы.
  Своих дат не придумывать, «февраль 2025» и подобное - брак.
"""


def prompt_for(job):
    job = dict(job, data_obnovleniya=G.updated_date(job['slug']))
    return f"""Ты пишешь техническое задание копирайтеру на одну страницу каталога
промышленного оборудования. Заказчик - ООО «Руспром», компрессорное направление.

{RULES}

РАЗРЕШЁННЫЕ БРЕНДЫ (только эти можно называть в тексте):
{', '.join(sorted(ALLOW))}

{TEMPLATE}

=== ДАННЫЕ ЭТОЙ СТРАНИЦЫ ===
{json.dumps(job, ensure_ascii=False, indent=1)}

Требования к самому ТЗ:
- Пиши по-русски, markdown, без длинных тире.
- ТЗ - документ для исполнителя, а не эссе. Конкретика вместо рассуждений.
- Каждый блок структуры должен отвечать на вопрос «что здесь должно быть
  написано и на основании чего», а не «о чём примерно».
- Числа бери только из payload этой страницы. Если для блока данных не хватает -
  так и напиши: «данных нет, запросить у владельца», не выдумывай.
- Ведущий вопрос используй как рамку, не выноси его заголовком.
- Объём ТЗ: столько, сколько нужно, ориентир 8-14 тысяч знаков. Не раздувай:
  документ должен уместиться целиком, обрезанное на середине ТЗ - брак.
- Последней строкой файла, после всего текста, поставь ровно это и ничего
  после: {MARK}
"""


def _write(path, text):
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text + '\n')
        fh.flush(); os.fsync(fh.fileno())


def run(job, out_dir, model, max_tokens, tries=2):
    path = os.path.join(out_dir, f"TZ-{job['slug']}.md")
    if os.path.exists(path) and MARK in open(path, encoding='utf-8').read():
        return job['slug'], 'кэш', 0
    brak_dir = os.path.join(os.path.dirname(out_dir.rstrip('/')) or DIR, 'tz-brak')
    t0 = time.time()
    last = ''
    for k in range(tries):
        msg = G.call(None, [{'role': 'user', 'content': prompt_for(job)}],
                     model=model, attempts=4, max_tokens=max_tokens)
        text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
        text = text.replace('—', '-').replace('–', '-')      # длинное тире запрещено
        if text.endswith(MARK) and msg.stop_reason == 'end_turn':
            _write(path, text)
            return job['slug'], f'{len(text)} симв', time.time() - t0
        last = f'обрыв ({len(text)} симв, stop_reason={msg.stop_reason})'
        os.makedirs(brak_dir, exist_ok=True)
        _write(os.path.join(brak_dir, f"TZ-{job['slug']}.try{k + 1}.md"), text)
    return job['slug'], f'БРАК: {last}, см. tz-brak/', time.time() - t0


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', default=os.path.join(DIR, 'tz-jobs.json'))
    ap.add_argument('--out', default=os.path.join(DIR, 'tz'))
    ap.add_argument('--only')
    ap.add_argument('--workers', type=int, default=3)
    ap.add_argument('--model', default='claude-fable-5')
    ap.add_argument('--max-tokens', type=int, default=32000)
    a = ap.parse_args()

    jobs = json.load(open(a.jobs, encoding='utf-8'))
    if a.only:
        keep = {x.strip() for x in a.only.split(',')}
        jobs = [j for j in jobs if j['slug'] in keep]
    os.makedirs(a.out, exist_ok=True)
    print(f'ТЗ к прогону: {len(jobs)}, воркеров {a.workers}', flush=True)
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        futs = {ex.submit(run, j, a.out, a.model, a.max_tokens): j['slug'] for j in jobs}
        for f in as_completed(futs):
            try:
                s, info, sec = f.result()
                print(f'  готово {s}: {info} за {sec:.0f} с', flush=True)
            except Exception as e:
                print(f'  СБОЙ {futs[f]}: {repr(e)[:200]}', file=sys.stderr, flush=True)
    print('итог в', a.out, flush=True)


if __name__ == '__main__':
    main()
