def linza(imya, tz, job):
    soob = f"""{LINZY[imya]}

=== ПРАВИЛА ПРОЕКТА (по ним написано ТЗ, нарушение правил - тоже находка) ===
{gen_tz.RULES}

=== ДАННЫЕ СТРАНИЦЫ (единственный законный источник чисел о товаре) ===
{json.dumps(job, ensure_ascii=False, indent=1)[:6000]}

=== ТЕХНИЧЕСКОЕ ЗАДАНИЕ ===
{tz}

{SHEMA}"""
    msg = G.call(None, [{'role': 'user', 'content': soob}],
                 model='claude-fable-5', attempts=3, max_tokens=16000)
    try:
        d = G.parse_json(msg)
        return [n for n in d.get('nahodki', []) if isinstance(n, dict)]
    except Exception as e:
        print(f'    линза {imya}: ответ не разобрался, {repr(e)[:80]}',
              file=sys.stderr, flush=True)
        return []


