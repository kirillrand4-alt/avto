# проверяется готовый текст: любое число рядом с расходом воздуха
# на газовой странице ловится независимо от того, как оно обёрнуто.
#
# Ветка про «коэффициент» сначала была голой и ловила чужое: «коэффициент
# запаса около 20%», «коэффициент использования давления 0,3-0,5» - это
# другие величины, к расходу воздуха отношения не имеющие. Поэтому каждая
# ветка обязана упоминать ВОЗДУХ, а не просто стоять рядом с числом.
_VOZDUH_CHISLO = _re.compile(
    # «600-700 Нм³/ч воздуха», «900 л/мин воздуха»
    r'\d[\d\s]*(?:[.,]\d+)?\s*(?:-|–|до)?\s*(?:\d[\d\s]*(?:[.,]\d+)?)?\s*'
    r'(?:нм³?/ч|нм3/ч|м³/ч|м3/ч|л/мин)\s*воздуха'
    # «коэффициент расхода воздуха примерно 8-11»
    r'|коэффициент\w*[^.\n]{0,30}?воздух\w*[^.\n]{0,30}?\d+(?:[.,]\d+)?'
    r'|воздух\w*[^.\n]{0,30}?коэффициент\w*[^.\n]{0,20}?\d+(?:[.,]\d+)?'
    # «воздуха в полтора раза больше»
    r'|воздух\w*[^.\n]{0,30}?в\s+\d[\d\s]*(?:[.,]\d+)?\s*раза?'
    # «коэффициент около 2» - без слова «воздух», но по смыслу тот же.
    # Отсекаем чужие коэффициенты по уточняющему слову: запаса,
    # использования, полезного действия - это другие величины.
    r'|коэффициент(?!\w*\s+(?:запас|использован|полезн|нагрузк|'
    r'одновремен))\w*[^.\n]{0,25}?\d+(?:[.,]\d+)?', _re.I)


# Двенадцатый случай ложной тревоги: ТЗ ЦИТИРУЕТ этот самый запрет
# в разделе «запрещённые слова и формулировки» - приводит «коэффициент
# около 2» как пример того, чего писать нельзя. Гейт не отличал запрет
# от утверждения и браковал документ за то, что тот выполняет правило.
_ZAPRET_RYADOM = _re.compile(
    # корень «запрет» нужен наравне с «запрещ»: без него «запрет
    # "российская станция"» читался как нарушение, а не как запрет
    r'запрещ\w*|запрет\w*|нельзя|не писать|не приводить|не выдумыв\w*|'
    r'не обещ\w*|не называ\w*|чего нельзя|под запретом|избегать|'
    r'без ссылки на паспорт', _re.I)


# Опубликованные коэффициенты Air:N2 (enger-air.ru, проверено на источнике).
# С 21.08 это ЗАКОННЫЕ числа, и гейт обязан их пропускать - иначе он
# запретит ровно то, ради чего мы этот блок и завели. Всё остальное
# по-прежнему выдумка.
ZAKONNYE_AIR_N2 = {2.2, 3.0, 4.0, 5.2, 8.0}
# Коэффициенты подбора тоже наши и тоже законные. Без них гейт браковал
# документ за то, что тот воспроизводит нашу же таблицу целиком:
# «2,2 / 3 / 4 / 5,2 / 8 м³ ... коэффициент 0,05 / 0,06 / 0,07».
ZAKONNYE_AIR_N2 |= {0.05, 0.06, 0.07}
# Коэффициенты ПОДБОРА компрессора: чистота -> м³/мин на 1 м³/ч азота.
# Здесь белый список чисел не годится: величина зависит от расхода азота,
# законных значений бесконечно много. Поэтому проверяем АРИФМЕТИКУ -
# сходится ли названная подача с названным расходом азота по нашему
# коэффициенту. Считает - законно, не считает - выдумка.
PODBOR_KOEFF = {99.0: 0.05, 99.5: 0.06, 99.9: 0.07}
_AZOT_RASHOD = _re.compile(r'(\d+(?:[.,]\d+)?)\s*(?:нм³?|м³|м3)\s*/\s*ч[^.]{0,40}?азот', _re.I)
_CHISTOTA_V = _re.compile(r'(9\d(?:[.,]\d+)?)\s*%')


def _shoditsya_otnoshenie(fraza):
    """«на 99,999% воздуха в 3,64 раза больше, чем на 99%» - это отношение
    двух ОПУБЛИКОВАННЫХ коэффициентов (8,0 / 2,2), а не выдумка. Гейт
    забраковал эту фразу, хотя она стоит в нашей же инструкции: считать
    надо, а не сверять со списком."""
    ch = [float(x.replace(',', '.')) for x in _CHISTOTA_V.findall(fraza)]
    if len(ch) < 2:
        return False
    tabl = {99.0: 2.2, 99.5: 3.0, 99.9: 4.0, 99.99: 5.2, 99.999: 8.0}
    def bliz_k(c):
        return min(tabl, key=lambda x: abs(x - c))
    a, b = tabl[bliz_k(ch[0])], tabl[bliz_k(ch[1])]
    if not b:
        return False
    nado = max(a, b) / min(a, b)
    for x in _CHISLA_V.findall(fraza):
        v = float(x.replace(',', '.'))
        if abs(v - nado) / nado <= 0.03:
            return True
    return False


def _shoditsya_podbor(fraza):
    """Подача воздуха сходится с расходом азота по коэффициенту подбора."""
    ra = _AZOT_RASHOD.search(fraza)
    ch = _CHISTOTA_V.search(fraza)
    if not ra or not ch:
        return False
    try:
        azot = float(ra.group(1).replace(',', '.'))
        chist = float(ch.group(1).replace(',', '.'))
    except Exception:
        return False
    k = PODBOR_KOEFF.get(min(PODBOR_KOEFF, key=lambda x: abs(x - chist)))
    nado_lmin = azot * k * 1000
    for x in _CHISLA_V.findall(fraza):
        v = float(x.replace(',', '.'))
        if abs(v - nado_lmin) / max(nado_lmin, 1e-9) <= 0.08:
            return True
    return False
_CHISLA_V = _re.compile(r'\d+(?:[.,]\d+)?')


def _zakonnyy_koeff(fraza):
    """Во фразе только опубликованные коэффициенты и ступени чистоты."""
    est = set()
    for x in _CHISLA_V.findall(fraza):
        v = float(x.replace(',', '.'))
        if v in ZAKONNYE_AIR_N2 or 98 <= v <= 100 or v == 1:
            continue
        est.add(v)
    return not est


# Число-ССЫЛКА, а не величина: «коэффициенты из таблицы 2», «блок 3»,
# «раздел 7». Проверка приняла номер таблицы за значение коэффициента
# и забраковала исправный текст.
_SSYLKA = _re.compile(
    r'(?:таблиц\w*|раздел\w*|блок\w*|пункт\w*|рисун\w*|схем\w*|'
    r'приложени\w*|H\d|стр\w*)\s*№?\s*$', _re.I)


def vozduh_na_gaz(text):
    """Выдуманные числа при соотношении воздух/газ.

    Опубликованные коэффициенты пропускаются: с 21.08 они у нас есть."""
    out = []
    for m in _VOZDUH_CHISLO.finditer(text):
        # цитата запрета - не нарушение запрета
        if _ZAPRET_RYADOM.search(text[max(0, m.start() - 200):m.end() + 60]):
            continue
        fraza = m.group(0)
        # «расход воздуха» без числа - законно и нужно
        if not _re.search(r'\d', fraza):
            continue
        # число оказалось номером ссылки, а не величиной
        chislo_v = _re.search(r'\d', fraza)
        if _SSYLKA.search(fraza[:chislo_v.start()]):
            continue
        nachalo = max(0, m.start() - 90)
        okno = text[nachalo:m.end() + 40]
        if not _re.search(r'азот|кислород|генератор', okno, _re.I):
            continue
        # опубликованная таблица - не нарушение. Только для АЗОТА:
        # по кислороду таблицы у нас нет, там любое число выдумка.
        if _re.search(r'азот', okno, _re.I) and \
                not _re.search(r'кислород', okno, _re.I) and \
                (_zakonnyy_koeff(m.group(0)) or _shoditsya_podbor(okno)
                 or _shoditsya_otnoshenie(okno)):
            continue
        out.append(' '.join(okno.split())[-150:])
    return out


# ГЕЙТ НА «ОТЕЧЕСТВЕННУЮ» ГАЗОВУЮ СТАНЦИЮ. Владелец 21.08: генераторы
# Enger производятся в Китае. У ЗИФ в поле тира стоит «A, российское
# производство», и по компрессорам это правда - завод в России. Но
# на азотной и кислородной странице продаётся СТАНЦИЯ, чьё газовое
# сердце китайское, и довод «отечественное решение» там становится
# ложным. Закупщик увидит страну в спецификации к КП и снимет сделку.
_OTECHESTVENNOE = _re.compile(
    r'росси[йи]ск\w*|отечествен\w*|импортозамещ\w*|сделано в россии', _re.I)
_STANCIYA_GAZ = _re.compile(
    r'станци\w*|установк\w*|модул\w*|решени\w*|комплекс\w*', _re.I)


def otechestvennaya_stanciya(text, gazovaya):
    """Заявка на отечественность применительно к газовой станции целиком."""
    if not gazovaya:
        return []
    out = []
    for m in _OTECHESTVENNOE.finditer(text):
        okno = text[max(0, m.start() - 60):m.end() + 60]
        # ЦИТАТА ЗАПРЕТА - НЕ НАРУШЕНИЕ. Тот же дефект, что был у гейта
        # воздуха: ТЗ перечисляет «российская азотная станция» в списке
        # запрещённых формулировок, а гейт браковал документ за то,
        # что тот выполняет правило. Чинится там же, где и там.
        if _ZAPRET_RYADOM.search(text[max(0, m.start() - 200):m.end() + 60]):
            continue
        # и «обещание X» / «X про станцию целиком» - это формулировка
        # самого запрета, а не обещание
        # окно шире самого совпадения: признак цитаты («про станцию
        # целиком») часто стоит за пределами шестидесяти знаков
        shire = text[max(0, m.start() - 160):m.end() + 160]
        if _re.search(r'обещани\w*|про станцию целиком|применительно|'
                      r'генератор китайск|генератор нет|не довод',
                      shire, _re.I):
            continue
        # ОТРИЦАНИЕ - НЕ УТВЕРЖДЕНИЕ. Документ пишет «доводом за станцию
        # целиком отечественность НЕ ДЕЛАТЬ» и «оффер строится НЕ НА
        # отечественности» - то есть выполняет правило, а гейт считал
        # это нарушением. Тот же корень, что у всех прежних ложных
        # тревог: проверка читает слова, а не смысл.
        do_70 = text[max(0, m.start() - 70):m.start()]
        posle_80 = text[m.end():m.end() + 80]
        if _re.search(r'\bне\b[^.]{0,60}$', do_70, _re.I) or \
                _re.search(r'^[^.]{0,60}?\bне\s+(дела\w*|стро\w*|обеща\w*|'
                           r'писа\w*|назыв\w*|утвержда\w*)',
                           posle_80, _re.I):
            continue
        # ПРИВЯЗКА К КОМПРЕССОРУ СНИМАЕТ ВОПРОС. «Российское производство
        # компрессора, наша сборка станции» - это и есть та правильная
        # формулировка, которой мы добивались: заявка привязана
        # к компрессору явно. Прежняя версия браковала её за то, что
        # слово «станция» стоит следом.
        # ЧТО ОПРЕДЕЛЯЕТ ПРОИСХОЖДЕНИЕ - решает падеж следующего слова.
        # «российского ПРОИЗВОДСТВА» определяет стоящее рядом
        # существительное, «российское РЕШЕНИЕ» само является claim
        # о станции. Позиция слова «компрессор» без этого обманывает:
        # в «Станция на компрессоре ЗИФ - российское решение» компрессор
        # стоит раньше, а утверждение всё равно про станцию.
        sled = text[m.end():m.end() + 30]
        if _re.search(r'^\W{0,3}(решени|станци|установк|модул|комплекс|'
                      r'под ключ)', sled, _re.I):
            out.append(' '.join(okno.split()))
            continue
        posle = text[m.end():m.end() + 45]
        k = _re.search(r'компрессор|винтов\w* блок|машин', posle, _re.I)
        st = _STANCIYA_GAZ.search(posle)
        # «российское производство КОМПРЕССОРА, наша сборка станции»:
        # компрессор назван раньше станции - заявка привязана к нему
        if k and (not st or k.start() < st.start()):
            continue
        # ...и обратный порядок: «компрессора ЗИФ российского
        # производства». Слово стоит ПЕРЕД происхождением, и это самая
        # частая правильная формулировка - гейт браковал её восемь раз
        # в одном документе, потому что смотрел только вперёд.
        do = text[max(0, m.start() - 45):m.start()]
        kd = None
        for mm in _re.finditer(r'компрессор|винтов\w* блок|машин', do, _re.I):
            kd = mm
        if kd:
            hvost = do[kd.end():]
            if not _STANCIYA_GAZ.search(hvost):
                continue
        if _re.search(r'компрессор', okno, _re.I) and \
                not _STANCIYA_GAZ.search(okno):
            continue
        # довод становится ложным, только если он про станцию/установку
        if not _STANCIYA_GAZ.search(okno):
            continue
        out.append(' '.join(okno.split()))
    return out


def tema(job):
    return job['topic'].split(' (')[0]


def proverit(job, potolok_flow_sayta):
    """Список замечаний по одному заданию."""
    p = job.get('payload') or {}
    t = tema(job)
    lim = POTOLKI.get(t, {})
    out = []

    def par(k):
        v = p.get(k)
        return v if isinstance(v, list) and len(v) == 2 and None not in v else None

    kw, fl, ba = par('power_kw'), par('flow_lmin'), par('pressure_bar')

    for imya, v in (('power_kw', kw), ('flow_lmin', fl), ('pressure_bar', ba)):
        if not v:
            continue
        if imya in lim and v[1] > lim[imya]:
            out.append(f'{imya} верх {v[1]:g} выше потолка класса {lim[imya]:g}')

    # Узел не может пропускать больше, чем дают компрессоры этого бренда.
    if t in PRIVYAZKA_K_KOMPRESSORAM and fl and potolok_flow_sayta:
        if fl[1] > potolok_flow_sayta * 1.5:
            out.append(f'пропускная способность {fl[1]:g} л/мин против '
                       f'{potolok_flow_sayta:g} у самого крупного компрессора '
                       f'этого сайта - число не про этот товар')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', default='tz-jobs.json,station-jobs.json')
    ap.add_argument('--pochinit', action='store_true',
                    help='пометить подозрительные числа как требующие проверки')
    a = ap.parse_args()

    jobs, files = [], {}
    for name in a.jobs.split(','):
        p = os.path.join(DIR, name.strip())
        d = json.load(open(p, encoding='utf-8'))
        files[p] = d
        jobs += d

    # Потолок компрессорной производительности по каждому сайту.
    KOMPRESSORY = ('винтовые компрессоры', 'поршневые компрессоры',
                   'спиральные компрессоры', 'дизельные компрессоры',
                   'центробежные компрессоры')
    potolok = {}
    for j in jobs:
        if tema(j) in KOMPRESSORY:
            fl = (j.get('payload') or {}).get('flow_lmin')
            if isinstance(fl, list) and fl and fl[1]:
                potolok[j['site']] = max(potolok.get(j['site'], 0), fl[1])

    plohie = []
    for j in jobs:
        z = proverit(j, potolok.get(j['site']))
        if z:
            plohie.append((j, z))

    print(f'заданий проверено: {len(jobs)}, с замечаниями: {len(plohie)}\n')
    for j, z in plohie:
        print(f"{j['slug']}")
        for s in z:
            print(f'    {s}')

    if a.pochinit and plohie:
        for j, z in plohie:
            j['_chisla_pod_somneniem'] = z
            j['_pro_somnitelnye'] = (
                'Эти числа не прошли санитарную проверку: они возможны только '
                'при ошибке единиц в выгрузке. НЕ ИСПОЛЬЗОВАТЬ их в тексте '
                'ни в каком виде - ни в таблице, ни в заголовке, ни в Title. '
                'Вместо числа писать «уточняется по модельному ряду».')
        for p, d in files.items():
            with open(p, 'w', encoding='utf-8') as fh:
                json.dump(d, fh, ensure_ascii=False, indent=1)
                fh.flush(); os.fsync(fh.fileno())
        print(f'\nпомечено заданий: {len(plohie)}')
    return 1 if plohie else 0


if __name__ == '__main__':
    sys.exit(main())
