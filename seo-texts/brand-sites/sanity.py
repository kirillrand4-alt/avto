# ОТРИЦАНИЕ ПЕРЕД ЦИТАТОЙ. ТЗ - документ О ТОМ, КАК ПИСАТЬ, и потому
# постоянно приводит неверную форму как контрпример: «оговорка "страна
# указана в каталоге", А НЕ "компрессоры производства Швеции"», «НЕТ года
# основания компании ("с 2003 года")». Раздельная проверка по заголовку
# такие места не ловит - они стоят внутри обычных разделов, строкой
# инструкции.
_OTRICANIE = _re.compile(
    r'(?:^|[\s(«"\-])(?:а\s+не|но\s+не|вместо|нет|без|ни|никак\w*|'
    r'не\s+(?:писать|ставить|приводить|называть|указывать|использовать|'
    r'добавлять|употреблять|должн\w*)|'
    r'отсутств\w*|исключ\w*|убрат\w*|снят\w*)(?=[\s(«"]|$)', _re.I)


def _otritsanie_ryadom(text, nachalo):
    """Отрицание в ТОМ ЖЕ предложении, до цитаты.

    Область действия отрицания - предложение целиком, а не сорок знаков.
    В строке «Нет года основания компании ("с 2003 года", "более 20 лет")»
    первая цитата стоит вплотную к «Нет», вторая уже за полсотни знаков,
    а отрицание распространяется на обе. Ограничение по расстоянию ловило
    первую и пропускало вторую - то есть браковало документ за перечень,
    который сам же и запрещает.
    """
    kus = text[max(0, nachalo - 400):nachalo]
    granica = 0
    for m in _re.finditer(r'(?:\n|(?<=[.;!?])\s)', kus):
        granica = m.end()
    return bool(_OTRICANIE.search(kus[granica:]))


# Строка-ЗАЧИН перечня. Запреты в ТЗ оформляются тремя способами, и только
# первый - настоящий markdown-заголовок:
#   ## 10. Что нельзя писать
#   **Общие запреты (из правил сетки)**
#   Нельзя писать:
# Проверка искала решётки и пропускала два остальных, поэтому документ
# получал брак за собственный перечень запрещённых формулировок -
# четыре раза на одной странице.
_ZACHIN = _re.compile(r'^(?:#{1,4}\s*(.+)|\*\*(.+?)\*\*\s*:?|(.{4,90}:))\s*$',
                      _re.M)


def _v_razdele_zapretov(text, poz):
    """Стоит ли позиция внутри перечня, запрещающего что-либо.

    Смотрим ближайший зачин выше: заголовок, жирную строку или строку,
    кончающуюся двоеточием. Любой из них вводит перечень, и если в нём
    сказано «нельзя», «запреты», «осторожность» - всё, что ниже
    до следующего зачина, это примеры недопустимого, а не нарушения."""
    # СМОТРИМ НЕ ОДИН ЗАЧИН, А НЕСКОЛЬКО ПОСЛЕДНИХ. Перечень запретов
    # длинный, и внутри него попадаются собственные подзачины
    # («Специфика кислородной страницы:»), которые заслоняют настоящий
    # заголовок «Запрещённые слова и формулировки». По последнему зачину
    # документ снова получал брак за свой же перечень.
    zachiny = [(m.group(1) or m.group(2) or m.group(3))
               for m in _ZACHIN.finditer(text, 0, poz)]
    return any(z and _ZAPRET_V_ZAGOLOVKE.search(z) for z in zachiny[-3:])


