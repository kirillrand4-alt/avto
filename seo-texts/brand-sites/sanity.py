#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Санитарный гейт на payload: ловит числа, невозможные по физике.

    python3 sanity.py [--jobs tz-jobs.json,station-jobs.json] [--pochinit]

ЗАЧЕМ. Красная команда нашла в заданиях: 720 000 л/мин на циклонный
сепаратор Remeza (это 43 200 м³/ч, промышленная магистраль целого завода),
141 600 л/мин на сепаратор ABAC при том, что самый большой компрессор
бренда даёт 12 400, и центробежный компрессор на 14,5 МВт. Число 720 000
уже разошлось по одному ТЗ в семь мест, включая Title и заголовок H2.

Механизм ошибки: парсер выгрузки не различает единицы. Где-то в карточке
стоит производительность в м³/ч, а колонка подписана «л/мин» - и число
умножается на тысячу. Проверок на правдоподобность не было вовсе:
задание принимало любое число, потому что оно «из выгрузки».

ПОЧЕМУ ЭТО ХУЖЕ ВЫДУМКИ. Выдуманное число ловится вопросом «откуда?».
Число из выгрузки такого вопроса не вызывает: оно уже «подтверждено
источником», и детерминированная сверка ставит на него печать. Схема
проверок, где каждое число сверяется с payload, без этого гейта просто
узаконит ошибку данных.

ЧТО ЗДЕСЬ НЕ ПРОВЕРЯЕТСЯ. Гейт не знает, ВЕРНО ли число для конкретной
модели - только правдоподобно ли оно для класса оборудования. Он ловит
промахи на порядок, а не на проценты.
"""
import argparse, json, os, sys

DIR = os.path.dirname(os.path.abspath(__file__))

# Удельная производительность винтового компрессора: сколько литров в минуту
# даёт киловатт. Величина инженерная и устойчивая: на 7-10 бар это примерно
# 100-160 л/мин на кВт, на высоком давлении меньше, на низком больше.
# Коридор взят с запасом в обе стороны, чтобы ловить промахи на порядок,
# а не спорить о процентах.
LMIN_NA_KVT = (40, 260)

# Потолки по классам оборудования. Не «максимум в природе», а граница,
# выше которой число почти наверняка ошибка единиц.
POTOLKI = {
    'винтовые компрессоры':      {'power_kw': 800,   'flow_lmin': 180000, 'pressure_bar': 45},
    'поршневые компрессоры':     {'power_kw': 250,   'flow_lmin': 20000,  'pressure_bar': 40},
    'спиральные компрессоры':    {'power_kw': 60,    'flow_lmin': 8000,   'pressure_bar': 15},
    'дизельные компрессоры':     {'power_kw': 600,   'flow_lmin': 120000, 'pressure_bar': 35},
    'центробежные компрессоры':  {'power_kw': 20000, 'flow_lmin': 4000000, 'pressure_bar': 45},
    'дожимные компрессоры и бустеры': {'power_kw': 400, 'flow_lmin': 40000, 'pressure_bar': 400},
    'генераторы азота':          {'flow_lmin': 40000,  'pressure_bar': 40},
    'генераторы кислорода':      {'flow_lmin': 5000,   'pressure_bar': 40},
    # Узлы подготовки воздуха: их пропускная способность не может быть
    # больше, чем даёт самый крупный компрессор того же бренда на сайте.
    # Проверяется отдельно, здесь только грубый потолок.
    'осушители сжатого воздуха': {'flow_lmin': 200000, 'pressure_bar': 40},
    'магистральные фильтры':     {'flow_lmin': 200000, 'pressure_bar': 40},
    'циклонные сепараторы и влагоотделители': {'flow_lmin': 200000, 'pressure_bar': 40},
    'ресиверы':                  {'pressure_bar': 40},
}
# Узлы, чья производительность обязана укладываться в компрессорную линейку
# того же сайта. Именно тут вылезли 720 000 и 141 600.
PRIVYAZKA_K_KOMPRESSORAM = (
    'осушители сжатого воздуха', 'магистральные фильтры',
    'циклонные сепараторы и влагоотделители',
)
# Проверка ширины диапазона снята: линейка винтовых 2,2-500 кВт это 227 крат,
# и это норма для бренда с тысячами позиций, а не ошибка единиц.
#
# Проверка «л/мин на кВт» по КОНЦАМ диапазона тоже снята, и это отдельный
# урок. Верх производительности и верх мощности - РАЗНЫЕ машины, делить одно
# на другое значит совершить ровно ту ошибку перемножения несвязанных чисел,
# от которой этот гейт и должен защищать. Удельную производительность можно
# считать только по одной карточке, поэтому она считается по выгрузке товаров,
# если та под рукой.
PRODUCTS = os.path.join(os.path.dirname(DIR), '..', 'scratchpad', 'bx',
                        'products.jsonl')


def tema(job):
    return job['topic'].split(' (')[0]


def proverit(job, potolok_flow_sayta):
    """Список замечаний по одному заданию."""
    p = job.get('payload') or {}
    t = tema(job)
    lim = POTOLKI.get(t, {})
    out = []

    def par(k):
        v = p.get(k)
        return v if isinstance(v, list) and len(v) == 2 and None not in v else None

    kw, fl, ba = par('power_kw'), par('flow_lmin'), par('pressure_bar')

    for imya, v in (('power_kw', kw), ('flow_lmin', fl), ('pressure_bar', ba)):
        if not v:
            continue
        if imya in lim and v[1] > lim[imya]:
            out.append(f'{imya} верх {v[1]:g} выше потолка класса {lim[imya]:g}')

    # Узел не может пропускать больше, чем дают компрессоры этого бренда.
    if t in PRIVYAZKA_K_KOMPRESSORAM and fl and potolok_flow_sayta:
        if fl[1] > potolok_flow_sayta * 1.5:
            out.append(f'пропускная способность {fl[1]:g} л/мин против '
                       f'{potolok_flow_sayta:g} у самого крупного компрессора '
                       f'этого сайта - число не про этот товар')
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', default='tz-jobs.json,station-jobs.json')
    ap.add_argument('--pochinit', action='store_true',
                    help='пометить подозрительные числа как требующие проверки')
    a = ap.parse_args()

    jobs, files = [], {}
    for name in a.jobs.split(','):
        p = os.path.join(DIR, name.strip())
        d = json.load(open(p, encoding='utf-8'))
        files[p] = d
        jobs += d

    # Потолок компрессорной производительности по каждому сайту.
    KOMPRESSORY = ('винтовые компрессоры', 'поршневые компрессоры',
                   'спиральные компрессоры', 'дизельные компрессоры',
                   'центробежные компрессоры')
    potolok = {}
    for j in jobs:
        if tema(j) in KOMPRESSORY:
            fl = (j.get('payload') or {}).get('flow_lmin')
            if isinstance(fl, list) and fl and fl[1]:
                potolok[j['site']] = max(potolok.get(j['site'], 0), fl[1])

    plohie = []
    for j in jobs:
        z = proverit(j, potolok.get(j['site']))
        if z:
            plohie.append((j, z))

    print(f'заданий проверено: {len(jobs)}, с замечаниями: {len(plohie)}\n')
    for j, z in plohie:
        print(f"{j['slug']}")
        for s in z:
            print(f'    {s}')

    if a.pochinit and plohie:
        for j, z in plohie:
            j['_chisla_pod_somneniem'] = z
            j['_pro_somnitelnye'] = (
                'Эти числа не прошли санитарную проверку: они возможны только '
                'при ошибке единиц в выгрузке. НЕ ИСПОЛЬЗОВАТЬ их в тексте '
                'ни в каком виде - ни в таблице, ни в заголовке, ни в Title. '
                'Вместо числа писать «уточняется по модельному ряду».')
        for p, d in files.items():
            with open(p, 'w', encoding='utf-8') as fh:
                json.dump(d, fh, ensure_ascii=False, indent=1)
                fh.flush(); os.fsync(fh.fileno())
        print(f'\nпомечено заданий: {len(plohie)}')
    return 1 if plohie else 0


if __name__ == '__main__':
    sys.exit(main())
