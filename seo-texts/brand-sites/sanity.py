# ГЕЙТ НА ПЕРЕНОС ДАВЛЕНИЯ КОМПРЕССОРА НА ГАЗ. Два контура, и путать их
# дорого: компрессор сжимает ВОЗДУХ (у ЗИФ до 40 бар), но генератор
# работает на входном давлении своего паспорта - 5-8 бар, отдельные
# исполнения до 12, - и азот выходит под этим же давлением, а не под
# давлением компрессора. Выше нужен дожимной блок.
#
# Четыре линзы независимо нашли на одной странице: «линейка компрессоров
# ЗИФ доходит до 40 бар - это позволяет строить станции высокого
# давления». Читатель поймёт, что получит азот под 40 бар. Получит
# под восемью, увидит это в спецификации к КП и снимет сделку.
#
# Блок _kontury в промпте про это говорит прямо, но правило, держащееся
# на послушании модели, - не правило.
# УТВЕРЖДЕНИЕ ДОЛЖНО БЫТЬ О НАШЕМ ГАЗЕ, А НЕ О ЧИСЛЕ РЯДОМ СО СЛОВОМ.
# Первая редакция ловила любое число выше 12 возле слов «азот»,
# «кислород», «станция» - и дала шесть ложных из шести: баллоны правда
# под 200 бар, «7,5-13 бар» в перечне относится к компрессорам, а азот
# в зону лазерного реза правда подаётся под 10-20 бар. Всё это верно
# и к контурам отношения не имеет.
#
# Ловим только предикат: станция/генератор ДАЁТ газ под таким давлением.
_DAVLENIE_GAZA = _re.compile(
    r'(?:азот|кислород)\w*\s+(?:под|до)\s+(\d{2,3})\s*бар'
    r'|(?:азотн\w+|кислородн\w+)\s+станци\w+[^.\n]{0,40}?'
    r'(?:до|на)\s+(\d{2,3})\s*бар'
    r'|станци\w+\s+высокого\s+давлени\w+[^.\n]{0,60}?(\d{2,3})\s*бар'
    r'|(?:генератор|станци)\w+[^.\n]{0,30}?(?:выда[её]т|даёт|обеспечива\w+|'
    r'выход\w*)[^.\n]{0,30}?(\d{2,3})\s*бар', _re.I)
POTOLOK_GENERATORA = 12
_DOZHIM_RYADOM = _re.compile(
    r'дожим\w*|бустер\w*|дожат\w*|повыша\w*\s+давлени|'
    r'компрессор\w*\s+высокого\s+давлени', _re.I)
# Чужие давления: баллон, рампа, потребитель, зона реза - не наш выход.
_CHUZHOE_DAVLENIE = _re.compile(
    # «опрессовка» и «испытания» отсюда убраны: это ПРИМЕНЕНИЕ нашего
    # газа, а не чужое давление. С ними правило пропускало настоящее
    # нарушение «азотная станция до 40 бар для опрессовки».
    r'баллон\w*|рамп\w*|дьюар\w*|зон\w*\s+рез|assist|у\s+потребител\w*|'
    r'магистрал\w*\s+завод', _re.I)


def davlenie_gaza(text, gazovaya=True):
    """Давление выше паспортного потолка генератора без упоминания дожима."""
    if not gazovaya:
        return []
    out = []
    for m in _DAVLENIE_GAZA.finditer(text):
        ch = next((g for g in m.groups() if g), None)
        try:
            v = int(ch)
        except (TypeError, ValueError):
            continue
        if v <= POTOLOK_GENERATORA:
            continue
        okno = text[max(0, m.start() - 130):m.end() + 130]
        # рядом сказано про дожим - утверждение корректное
        if _DOZHIM_RYADOM.search(okno):
            continue
        # давление баллона, рампы, потребителя - не выход нашего генератора
        if _CHUZHOE_DAVLENIE.search(okno):
            continue
        if _ZAPRET_RYADOM.search(okno) or _v_razdele_zapretov(text, m.start()):
            continue
        if _otritsanie_ryadom(text, m.start()):
            continue
        # речь про ВОЗДУХ или компрессор, а не про газ - это законно
        if _re.search(r'воздух\w*|компрессор\w*\s+(?:до|на)\s*$', 
                      text[max(0, m.start() - 60):m.start()], _re.I):
            continue
        # показываем САМУ находку с окружением, а не хвост окна: иначе
        # в отчёте видно всё, кроме того, за что забраковано
        vokrug = text[max(0, m.start() - 60):m.end() + 60]
        out.append('«' + ' '.join(m.group(0).split()) + '» в: '
                   + ' '.join(vokrug.split()))
    return out

