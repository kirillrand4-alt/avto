_AZOT_RASHOD = _re.compile(r'(\d+(?:[.,]\d+)?)\s*(?:нм³?|м³|м3)\s*/\s*ч[^.]{0,40}?азот', _re.I)
_CHISTOTA_V = _re.compile(r'(9\d(?:[.,]\d+)?)\s*%')


def _shoditsya_otnoshenie(fraza):
    """«на 99,999% воздуха в 3,64 раза больше, чем на 99%» - это отношение
    двух ОПУБЛИКОВАННЫХ коэффициентов (8,0 / 2,2), а не выдумка. Гейт
    забраковал эту фразу, хотя она стоит в нашей же инструкции: считать
    надо, а не сверять со списком."""
    ch = [float(x.replace(',', '.')) for x in _CHISTOTA_V.findall(fraza)]
    if len(ch) < 2:
        return False
    tabl = {99.0: 2.2, 99.5: 3.0, 99.9: 4.0, 99.99: 5.2, 99.999: 8.0}
    def bliz_k(c):
        return min(tabl, key=lambda x: abs(x - c))
    a, b = tabl[bliz_k(ch[0])], tabl[bliz_k(ch[1])]
    if not b:
        return False
    nado = max(a, b) / min(a, b)
    for x in _CHISLA_V.findall(fraza):
        v = float(x.replace(',', '.'))
        if abs(v - nado) / nado <= 0.03:
            return True
    return False


