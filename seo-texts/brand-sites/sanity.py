# РАЗДЕЛ «ЧТО НЕЛЬЗЯ ПИСАТЬ» - ЭТО СПИСОК ЗАПРЕТОВ, А НЕ НАРУШЕНИЙ.
# Проверка на слово «запрещено» рядом не сработала: в разделе 10 перечень
# идёт длинным списком, и до заголовка от конкретной строки бывает
