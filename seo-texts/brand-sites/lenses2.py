def materials():
    """Пакет материалов для первичных линз. Собирается из рабочих файлов,
    чтобы линзы читали то же, что исполнитель, а не пересказ."""
    parts = []
    for name, path in [
        ('ПЛАН РАБОТ', 'PLAN-RABOT.md'),
        ('ПРАВИЛА СЕТКИ И РЕШЕНИЯ', 'BRIEF-DLYA-REVYU.md'),
        ('ТИПЫ КАТЕГОРИЙ И УГЛЫ ПОДАЧИ', 'UGLY-KATEGORIY.md'),
        ('КЕЙСЫ И СРАВНЕНИЯ', 'KEYSY-I-SRAVNENIYA.md'),
        ('ОБРАЗЕЦ ТЗ НА ОДНУ СТРАНИЦУ', 'TZ-01-berg-vintovye.md'),
        ('РЕЕСТР ПОЛОМОК НА САЙТАХ', 'OSHIBKI-SAYTOV.md'),
    ]:
        p = os.path.join(DIR, path)
        if os.path.exists(p):
            parts.append(f'=== {name} ({path}) ===\n' + open(p, encoding='utf-8').read())
    return '\n\n'.join(parts)


