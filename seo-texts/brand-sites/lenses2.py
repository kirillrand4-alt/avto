def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--phase', choices=['primary', 'meta', 'synth', 'all'], default='all')
    ap.add_argument('--only')
    ap.add_argument('--workers', type=int, default=4)
    ap.add_argument('--model', default='claude-fable-5')
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    mat = materials()
    print(f'пакет материалов: {len(mat)} символов', flush=True)

    if a.phase in ('primary', 'all'):
        names = [x.strip() for x in a.only.split(',')] if a.only else list(PRIMARY)
        names = [n for n in names if n in PRIMARY]
        print(f'первичных линз: {len(names)}', flush=True)
        with ThreadPoolExecutor(max_workers=a.workers) as ex:
            futs = {ex.submit(ask, n,
                              f'{COMMON}\n\n=== МАТЕРИАЛЫ ===\n{mat}\n=== КОНЕЦ ===\n\n'
                              f'=== ТВОЯ РОЛЬ ===\n{PRIMARY[n]}',
                              os.path.join(OUT, f'lens-{n}.md'), a.model): n
                    for n in names}
            for f in as_completed(futs):
                try:
                    n, i, s = f.result(); print(f'  {n}: {i} за {s:.0f} с', flush=True)
                except Exception as e:
                    print(f'  СБОЙ {futs[f]}: {repr(e)[:160]}', file=sys.stderr, flush=True)

    if a.phase in ('meta', 'all'):
        found = []
        for p in sorted(glob.glob(os.path.join(OUT, 'lens-*.md'))):
            found.append(open(p, encoding='utf-8').read())
        body = '\n\n'.join(found)
        print(f'металинзы читают {len(found)} линз, {len(body)} символов', flush=True)
        with ThreadPoolExecutor(max_workers=3) as ex:
            futs = {ex.submit(ask, n,
                              f'{COMMON}\n\n=== ПЛАН ===\n{mat[:60000]}\n\n'
                              f'=== ВЫВОДЫ ЛИНЗ ===\n{body}\n=== КОНЕЦ ===\n\n{META[n]}',
                              os.path.join(OUT, f'meta-{n}.md'), a.model): n
                    for n in META}
            for f in as_completed(futs):
                try:
                    n, i, s = f.result(); print(f'  {n}: {i} за {s:.0f} с', flush=True)
                except Exception as e:
                    print(f'  СБОЙ {futs[f]}: {repr(e)[:160]}', file=sys.stderr, flush=True)

    if a.phase in ('synth', 'all'):
        body = '\n\n'.join(open(p, encoding='utf-8').read()
                           for p in sorted(glob.glob(os.path.join(OUT, '*.md')))
                           if 'SVOD' not in p)
        n, i, s = ask('Синтез', f'{COMMON}\n\n=== ПЛАН ===\n{mat[:60000]}\n\n'
                                f'=== ЛИНЗЫ И МЕТАЛИНЗЫ ===\n{body}\n=== КОНЕЦ ===\n\n{SYNTH}',
                      os.path.join(OUT, 'SVOD-REVYU.md'), a.model, attempts=5)
        print(f'  синтез: {i} за {s:.0f} с', flush=True)
    print('итог в', OUT, flush=True)


if __name__ == '__main__':
    main()
