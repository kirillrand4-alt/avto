def ask(name, body, path, model, attempts=4):
    if os.path.exists(path) and os.path.getsize(path) > 600:
        return name, 'кэш', 0
    t0 = time.time()
    msg = G.call(None, [{'role': 'user', 'content': body}], model=model, attempts=attempts)
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    text = text.replace('—', '-').replace('–', '-')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(f'# {name}\n\n{text}\n')
        fh.flush(); os.fsync(fh.fileno())
    return name, f'{len(text)} симв', time.time() - t0


