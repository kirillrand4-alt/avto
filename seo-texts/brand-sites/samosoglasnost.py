#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""ТЗ против собственных запретов: документ проверяется своим же списком.

    python3 samosoglasnost.py [--tz tz/] [--pokazat 20]

ЗАЧЕМ. Разбор владельца 21.08 дал две находки, и обе одного сорта:
документ объявляет запрет и сам же его нарушает несколькими разделами
ниже.

  раздел 5:  «конкретный срок окупаемости станции в месяцах без данных
             по местной цене покупного азота» - в запретах;
  раздел 11: «окупаемость обычно от полугода до двух лет» - в FAQ.

  раздел 5:  «конкретные числа расхода воздуха без паспорта генератора» -
             в запретах;
  раздел 7:  таблица «99,999% -> выше базовой в 2,6-3,4 раза» - тот же
             air/N2 ratio, только через мощность компрессора.

ЧЕМ ЭТО ЛУЧШЕ РУКОПИСНЫХ ГЕЙТОВ. Каждый прежний гейт я писал руками
под конкретную ошибку: воздух на газ, отечественная станция, единицы,
энергия. Их будет ровно столько, сколько ошибок я успел увидеть, и они
всегда отстают на одну. Здесь проверяемое берётся ИЗ САМОГО ДОКУМЕНТА:
что ТЗ объявило запрещённым, то и проверяется. Список растёт сам вместе
с правилами.

ПОЧЕМУ ОБЕ НАХОДКИ ВО ВТОРОЙ ПОЛОВИНЕ. Запреты стоят в разделе 5,
нарушения в 7 и 11. Чем дальше от запрета, тем слабее он держит - это
видно и по тому, как модель проигнорировала приказ про половину
документа, стоявший в хвосте промпта. Отсюда же практический вывод:
проверять надо готовый текст, а не надеяться на послушание.

СОСТОЯНИЕ: ЧЕРНОВИК, В ПРИЁМКУ НЕ ВКЛЮЧЁН. Три захода настройки дали
три разных набора ложных тревог: «год» внутри «выгоднее», «2» внутри
«H2», «### 5» из нумерации FAQ вместо нарушения, и запрет-цитата,
найденная в тексте другого запрета. Сама идея верна и ценнее рукописных
гейтов - проверяемое берётся из документа, а не из моей памяти об
ошибках. Но подключать проверку, которая ошибается чаще проверяемого,
нельзя: она приучает не смотреть на свой вывод, и тогда настоящую
находку пролистают вместе с шумом. Доводить отдельной задачей, на
корпусе, а не на одном файле.

ЧЕГО НЕ ЛОВИТ. Запрет, сформулированный без опорного слова («не
выдумывать»), проверить нечем. И запрет на КАЧЕСТВЕННОЕ утверждение
(«не обещать») ловится только там, где рядом стоит число: «станция
окупается» пройдёт, «окупается за год» нет. Это сознательно: число -
то, за что владельца спросят «откуда?».
"""
import argparse, os, re, sys

DIR = os.path.dirname(os.path.abspath(__file__))

# Разделы, где живут запреты. Тело проверяется против них, сами они - нет.
ZAPRETNYE = re.compile(
    r'^#{2,3}\s*(?:\d+\.\s*)?.*?(запрет|запрещ|что нельзя|нельзя писать|'
    r'чего мы не знаем)', re.I | re.M)
LYUBOY_RAZDEL = re.compile(r'^#{2,3}\s', re.M)

# Опорные слова запретов. Ключ - что искать в строке запрета, значение -
# чем это выражается в теле. Разведено намеренно: запрет говорит «срок
# окупаемости», а нарушение пишется «окупается за год».
OPORY = [
    ('окупаем',   r'окупа\w*'),
    ('тариф',     r'тариф\w*|руб\w*\s*/?\s*кВт'),
    ('срок поставки', r'срок\w*\s+поставк\w*|поставк\w*\s+за\b'),
    ('шум',       r'шум\w*|дБА?\b'),
    ('расход воздуха', r'расход\w*\s+воздуха|воздуха\s+на\b|air\s*/?\s*n'),
    ('чистоты воздуха по iso', r'ISO\s*8573'),
    ('ресурс',    r'ресурс\w*|межсервисн\w*|до капремонта'),
    ('цена',      r'цена\w*|стоит\b|стоимост\w*'),
    ('экономи',   r'экономи\w*|дешевле|дороже'),
]
# Число рядом. Без числа запрет на «обещание» не нарушен: «станция
# окупается» это довод, «окупается за год» это обещание.
# Цифра как ВЕЛИЧИНА, а не как часть обозначения. Первая версия ловила
# «2» внутри «H2» и браковала фразу про порядок заголовков.
CHISLO = re.compile(r'(?<![A-Za-zА-Яа-я])\d+(?:[.,]\d+)?(?![A-Za-zА-Яа-я])')
# Проценты и разы тоже считаем числом даже словом.
# Границы слова обязательны: без них «год» находился внутри «выгоднее»,
# и проверка показывала не то предложение.
SLOVOM = re.compile(r'\b(?:вдво\w+|втро\w+|в полтора|полугод\w*|год\w*|'
                    r'месяц\w*|лет|года)\b', re.I)

# Запрет-ЦИТАТА («лидер рынка», «самая низкая цена») - это запрет
# конкретной формулировки, а не числа. Его проверяют буквально, иначе
# опора «цена» цепляет любое предложение про стоимость.
CITATA = re.compile(r'[«"]([^«»"]{4,60})[»"]')


def _kuski(text):
    """Текст на (заголовок, тело). Нужен, чтобы отделить запреты от тела."""
    granicy = [m.start() for m in LYUBOY_RAZDEL.finditer(text)] + [len(text)]
    out = []
    for i in range(len(granicy) - 1):
        kus = text[granicy[i]:granicy[i + 1]]
        out.append((kus.split('\n', 1)[0], kus))
    return out


def razobrat(text):
    """(список запретов, тело вне запретных разделов)."""
    zaprety, telo = [], []
    for zag, kus in _kuski(text):
        if ZAPRETNYE.match(zag):
            zaprety += [s.strip(' -*') for s in kus.split('\n')
                        if len(s.strip(' -*')) > 12]
        else:
            telo.append(kus)
    return zaprety, '\n'.join(telo)


ISPOLNENIE = re.compile(
    r'не называ\w*|нет в данных|уточня\w*|запрещ\w*|нельзя|считается по|'
    r'зависит от|берётся из|по паспорту|подстановк\w*|не приводить|'
    r'не обещ\w*|не выдумыв\w*', re.I)


def _frazy(telo, rx):
    for m in re.finditer(rx, telo, re.I):
        a = telo.rfind('.', 0, m.start()) + 1
        b = telo.find('.', m.end())
        f = telo[a:b if b > 0 else m.end() + 90].strip()
        if 0 < len(f) <= 400:
            yield f


def proverit(text):
    zaprety, telo = razobrat(text)
    if not zaprety:
        return []
    out = []
    # ЗАПРЕТЫ-ЦИТАТЫ: ищем ровно ту формулировку
    for z in zaprety:
        for c in CITATA.findall(z):
            if len(c.split()) < 2:
                continue
            if re.search(re.escape(c), telo, re.I):
                out.append({'запрет': ' '.join(z.split())[:110],
                            'нарушение': f'дословно в тексте: «{c}»'})
                break
    # ЧИСЛОВЫЕ ЗАПРЕТЫ: опора плюс величина рядом
    for slovo, rx in OPORY:
        z = next((x for x in zaprety if slovo in x.lower()
                  and not CITATA.search(x)), None)
        if not z:
            continue
        # среди совпадений выбираем НАСТОЯЩЕЕ нарушение: с цифрой сильнее,
        # чем со словом-величиной, иначе проверка показывает не то место
        kand = [f for f in _frazy(telo, rx) if not ISPOLNENIE.search(f)
                and (CHISLO.search(f) or SLOVOM.search(f))]
        if not kand:
            continue
        kand.sort(key=lambda f: (0 if CHISLO.search(f) else 1, len(f)))
        out.append({'запрет': ' '.join(z.split())[:110],
                    'нарушение': ' '.join(kand[0].split())[:190]})
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--tz', default=os.path.join(DIR, 'tz'))
    ap.add_argument('--pokazat', type=int, default=20)
    a = ap.parse_args()

    vsego, fajlov, pokazano = 0, 0, 0
    for name in sorted(os.listdir(a.tz)):
        if not name.endswith('.md'):
            continue
        n = proverit(open(os.path.join(a.tz, name), encoding='utf-8').read())
        if not n:
            continue
        fajlov += 1
        vsego += len(n)
        if pokazano < a.pokazat:
            pokazano += 1
            print(f'\n{name[3:-3]}')
            for x in n[:3]:
                print(f'   запрет:    {x["запрет"]}')
                print(f'   нарушение: {x["нарушение"]}')
    print(f'\nТЗ с самонарушениями: {fajlov}, всего случаев: {vsego}')
    return 1 if vsego else 0


if __name__ == '__main__':
    sys.exit(main())
