for slug, swaps in SWAPS.items():
    path = f'gen/result-{slug}.json'
    d = json.load(open(path))
    html = d['text_html']
    chunks = html.split(f'<div class="{MARK}">')
    done = []
    for old_frag, new_q, new_a in swaps:
        hit = [i for i, c in enumerate(chunks) if i > 0 and old_frag in c]
        if len(hit) != 1:
            print(f'!! {slug}: фрагмент «{old_frag}» найден в {len(hit)} блоках — пропуск')
            continue
        c = chunks[hit[0]]
        # вопрос: последний <span>...</span> внутри accordion-head
        c2 = re.sub(r'(</span><span>)[^<]+(</span>)', r'\g<1>' + new_q + r'\g<2>', c, count=1)
        # ответ: содержимое accordion-body до первого </div>
        c3 = re.sub(r'(<div class="accordion-body">\s*).*?(\s*</div>)',
                    r'\g<1>' + new_a + r'\g<2>', c2, count=1, flags=re.S)
        if c3 == c:
            print(f'!! {slug}: «{old_frag}» — замена не применилась')
            continue
        chunks[hit[0]] = c3
        done.append(new_q)
    d['text_html'] = f'<div class="{MARK}">'.join(chunks)
    json.dump(d, open(path, 'w'), ensure_ascii=False, indent=1)
    print(f'{slug}: заменено {len(done)}/{len(swaps)}: ' + ' | '.join(q[:50] for q in done))
