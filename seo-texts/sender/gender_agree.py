# Имена на -а/-я, которые принадлежат мужчинам: инференс по окончанию на них
# спотыкается, а ошибка тут стоит дорого (письмо от «Никиты» женским родом).
_MALE_A = {
    "никита", "илья", "лука", "кузьма", "фома", "савва", "данила", "гаврила",
    "добрыня", "мина", "сила", "фока", "элиша", "хома", "юра", "миша", "саша",
    "паша", "гоша", "лёша", "леша", "серёжа", "сережа", "дима", "вова",
}
# Женские имена БЕЗ -а/-я (редко, но бывают в базе ящиков).
_FEMALE_OTHER = {"любовь", "нинель", "эсфирь", "рахиль", "адель", "нинэль"}

_WORD_RE = re.compile(r"[А-Яа-яЁёA-Za-z]+")


def gender_of(name: str, explicit: Optional[str] = None) -> str:
    """Пол владельца ящика: 'f' | 'm'.

    explicit — значение из конфига (personalization.mailbox_gender), оно
    главнее любых догадок по имени: имя может быть нетипичным, а конфиг
    владелец правит руками. Ничего не понятно — 'm' (текущее поведение
    генератора, письма и так написаны мужскими формами).
    """
    e = str(explicit or "").strip().lower()
    if e in ("f", "ж", "female", "жен", "женский"):
        return "f"
    if e in ("m", "м", "male", "муж", "мужской"):
        return "m"
    # from_name бывает «Анастасия Мирошниченко, Meyer» — берём первое слово
    m = _WORD_RE.search(str(name or ""))
    имя = (m.group(0) if m else "").lower()
    if not имя:
        return "m"
    if имя in _FEMALE_OTHER:
        return "f"
    if имя in _MALE_A:
        return "m"
    return "f" if имя.endswith(("а", "я")) else "m"


def _replace(m: re.Match) -> str:
    слово = m.group("v")
    жен = _FEM.get(слово.lower())
    if not жен:
        return m.group(0)
    if слово[:1].isupper():
        жен = жен[:1].upper() + жен[1:]
    return m.group(0)[: m.start("v") - m.start()] + жен


# Глагол первого лица: начало предложения/строки, сразу после «я» либо после
# связки «буду/был» («буду рад помочь» — эталонный оборот наших писем).
_PATTERN = re.compile(
    r"(?:(?<=^)|(?<=\n)|(?<=[.!?…]\s)|(?<=[.!?…]\n)|(?<=\bя\s)|(?<=\bЯ\s)"
    r"|(?<=\bбуду\s)|(?<=\bбыл\s))"
    r"(?P<v>" + "|".join(sorted(_FEM, key=len, reverse=True)) + r")\b",
    re.IGNORECASE)


def agree(text: str, gender: str) -> str:
    """Согласовать текст письма с полом отправителя ('f' переписывает,
    'm' возвращает как есть — письма уже написаны мужскими формами)."""
    if not text or str(gender).lower() != "f":
        return text
    return _PATTERN.sub(_replace, text)


# Метка имени отправителя в теле письма. Генератор пишет письмо ДО выбора
# ящика, поэтому имени не знает — но стиль редактора (13.08) требует
# представиться первой строкой: «Меня зовут Ирина, представляю компанию…».
# Модель ставит метку, движок подставляет имя там же, где согласует род, —
# в превью карточки и при отправке.
# Без фигурных скобок: с ними модель 13.08 ломала JSON ответа
# («Expecting property name enclosed in double quotes»), да и любой
# .format() по промпту спотыкался бы о них.
МЕТКА_ИМЕНИ = "ИМЯ_ОТПРАВИТЕЛЯ"


def подставить_имя(text: str, from_name: str) -> str:
    """Заменить метку на личное имя владельца ящика («Ирина Кузнецова» -> «Ирина»).

    Имени нет — метку убираем вместе с оборотом «Меня зовут …, »: письмо без
    имени лучше, чем письмо с фигурной скобкой в первой строке.
    """
    if not text or МЕТКА_ИМЕНИ not in text:
        return text
    m = _WORD_RE.search(str(from_name or ""))
    имя = m.group(0) if m else ""
    if имя:
        return text.replace(МЕТКА_ИМЕНИ, имя)
    без = re.sub(r"(?i)меня зовут\s*" + re.escape(МЕТКА_ИМЕНИ) + r"\s*,\s*",
                 "", text)
    return без.replace(МЕТКА_ИМЕНИ, "")


def agree_for_mailbox(text: str, from_name: str, config=None,
                      mailbox_id: str = "") -> str:
    """Согласовать по ящику: пол берём из конфига (по mailbox_id), иначе из
    имени в from_name. Заодно подставляем имя отправителя вместо метки.
    Любой сбой — текст без изменений (письмо важнее)."""
    try:
        text = подставить_имя(text, from_name)
        explicit = None
        get = getattr(config, "get", None) if config is not None else None
        if callable(get) and mailbox_id:
            карта = get("personalization.mailbox_gender", None)
            # Config отдаёт вложенные секции как mappingproxy (иммутабельный
            # вид), а он НЕ isinstance(..., dict) — проверка на dict молча
            # отключала бы явную карту. Сверяем по Mapping.
            if isinstance(карта, Mapping):
                explicit = карта.get(mailbox_id)
        return agree(text, gender_of(from_name, explicit))
    except Exception:  # noqa: BLE001 - согласование не должно ронять отправку
        return text
