# -*- coding: utf-8 -*-
"""Тело письма — в читаемый текст для ленты переписки.

Владелец 18.08 (скриншот ленты лидов): вместо письма в карточке видно его
исходник — «<div>Кому: …<br /></div>», «&lt;k.yashin@…&gt;», куски
style="background-color:rgb(255,255,255)". Так и есть: входящее приходит
HTML-ом, наши письма тоже собираются HTML-ом, а лента печатает тело как
обычный текст в <pre> — теги показываются буквально.

Разбираем здесь, на стороне сервера, а не в браузере: тем же телом
пользуются черновики ответа и разбор переписки, и им сырой HTML мешает не
меньше. В базе остаётся оригинал — правим только показ.

Отрисовывать HTML в панели нельзя: письмо пришло снаружи, а innerHTML чужого
письма — это чужой скрипт и чужая вёрстка в нашей панели. Поэтому именно
ТЕКСТ.
"""
from __future__ import annotations

import html as _html
import re

# Блоки, которые целиком не нужны: их содержимое — не письмо.
_ВЫРЕЗАТЬ = re.compile(
    r"<(script|style|head|title)\b[^>]*>.*?</\1>", re.I | re.S)
# Жёсткий перенос: <br> и <hr> — это ровно одна новая строка, и два <br>
# подряд обязаны остаться пустой строкой (так наши письма делят абзацы).
_ЖЁСТКИЙ = re.compile(r"<\s*(br|hr)\b[^>]*/?\s*>", re.I)
# Граница блока. Открывающий и закрывающий теги дают ОДНУ границу на двоих,
# иначе каждая строка письма разъезжается на две.
_БЛОК = re.compile(
    r"</?\s*(p|div|tr|li|ul|ol|table|h[1-6]|blockquote|section|article)\b"
    r"[^>]*>", re.I)
_ГРАНИЦА = "\x00"
_ГРАНИЦЫ_ПОДРЯД = re.compile(r"[ \t]*\x00[ \t\x00]*")
_ТЕГ = re.compile(r"<[^>]+>")
# Разметкой считаем ТОЛЬКО известные теги. Иначе «<info@firma.ru>» в обычном
# письме выглядит тегом, и адрес исчезает вместе с угловыми скобками —
# поймано на первом же прогоне тестов.
_ЕСТЬ_ТЕГИ = re.compile(
    r"<\s*/?\s*(?:a|b|i|u|em|strong|span|font|br|hr|p|div|tr|td|th|table|"
    r"tbody|thead|ul|ol|li|h[1-6]|blockquote|img|style|script|head|title|"
    r"body|html|meta|link|pre|code|section|article|center|small|sup|sub)"
    r"\b[^>]*>", re.I)
# ТАБЛИЦА ОСТАЁТСЯ ТАБЛИЦЕЙ. Внутри ячейки почтовые редакторы кладут <p> и
# <div>, а это блочные теги — каждая ячейка уезжала на свою строку, и
# техзадание «СМК Альтернатива» (давление, расход, класс чистоты) читалось
# как столбик из отдельных слов: «No», «Описание», «Давление,», «МПа».
# Собираем строку таблицы обратно в одну строку через « | » ДО общей чистки.
_СТРОКА_ТАБЛИЦЫ = re.compile(r"<\s*tr\b[^>]*>(.*?)</\s*tr\s*>", re.I | re.S)
_ЯЧЕЙКА = re.compile(r"<\s*t[dh]\b[^>]*>(.*?)</\s*t[dh]\s*>", re.I | re.S)
_МНОГО_ПУСТЫХ = re.compile(r"\n{3,}")
_ХВОСТЫ = re.compile(r"[ \t]+\n")
# Мусор почтовых редакторов, который переживает снятие тегов.
_CSS_ХВОСТ = re.compile(
    r"(?m)^\s*(?:[-a-z]+\s*:\s*[^;\n]{1,120};\s*)+$", re.I)


def _tekst_yacheyki(html_ячейки: str) -> str:
    """Содержимое ячейки — в одну строку без тегов и лишних пробелов."""
    т = _ВЫРЕЗАТЬ.sub(" ", html_ячейки or "")
    т = _ЖЁСТКИЙ.sub(" ", т)
    т = _ТЕГ.sub(" ", т)
    return " ".join(т.replace("\xa0", " ").split())


def tablicy_v_stroki(текст: str) -> str:
    """Каждый <tr> — одна строка, ячейки через « | ».

    Строку из ОДНОЙ ячейки не украшаем разделителем: таблицами часто
    верстают обычные абзацы, и « | » вокруг них был бы мусором.
    """
    def строка(m):
        ячейки = [_tekst_yacheyki(я) for я in _ЯЧЕЙКА.findall(m.group(1))]
        if not ячейки:
            return m.group(0)
        while ячейки and not ячейки[-1]:
            ячейки.pop()
        if not ячейки:
            return _ГРАНИЦА
        если = ячейки[0] if len(ячейки) == 1 else " | ".join(ячейки)
        return _ГРАНИЦА + если + _ГРАНИЦА

    return _СТРОКА_ТАБЛИЦЫ.sub(строка, текст or "")


_ЕСТЬ_ТАБЛИЦА = re.compile(r"<\s*table\b[^>]*>.{0,20000}?<\s*tr\b", re.I | re.S)


def est_tablica(html: str) -> bool:
    """Есть ли в разметке настоящая таблица со строками."""
    return bool(_ЕСТЬ_ТАБЛИЦА.search(html or ""))


def luchshee_telo(plain: str, html: str) -> str:
    """Какую часть письма показывать: текстовую или разобранный HTML.

    Обычно текстовая часть лучше — она и есть то, что писал человек. Но
    когда в письме ТАБЛИЦА, почтовые клиенты кладут в plain её обломки:
    Outlook разносит ячейки по строкам и разделяет табами, и техзадание
    «СМК Альтернатива» (давление, расход, класс чистоты по трём установкам)
    читалось столбиком из отдельных слов. В HTML структура цела, и наш
    разбор собирает строку таблицы обратно.

    Поэтому правило простое: есть таблица в HTML - берём HTML.
    """
    п = str(plain or "")
    h = str(html or "")
    if h and est_tablica(h):
        разобрано = v_tekst(h)
        if разобрано.strip():
            return разобрано
    return п if п.strip() else (v_tekst(h) if h else "")


def pohozhe_na_html(текст: str) -> bool:
    """Есть ли в теле разметка. Наши plain-text письма трогать не надо."""
    return bool(_ЕСТЬ_ТЕГИ.search(текст or ""))


def v_tekst(текст, *, proyti_dvazhdy: bool = True) -> str:
    """HTML письма -> читаемый текст. Не HTML возвращаем как есть.

    proyti_dvazhdy: письмо часто содержит СВОЙ исходник в экранированном
    виде (пересланная цитата). После снятия тегов и раскодирования сущностей
    внутри может обнаружиться второй слой разметки — проходим ещё раз, но
    ровно один: дальше это уже не письмо, а бесконечная чистка.
    """
    s = "" if текст is None else str(текст)
    if not s or not pohozhe_na_html(s):
        return s
    s = _ВЫРЕЗАТЬ.sub(" ", s)
    # Таблицы — ДО жёстких переносов: внутри ячеек свои <br>, и они не
    # должны рвать строку таблицы на части.
    s = tablicy_v_stroki(s)
    s = _ЖЁСТКИЙ.sub("\n", s)
    s = _БЛОК.sub(_ГРАНИЦА, s)
    s = _ТЕГ.sub("", s)
    s = _ГРАНИЦЫ_ПОДРЯД.sub("\n", s)
    # Сущности РАСКОДИРУЕМ ПОСЛЕ снятия тегов: иначе «&lt;div&gt;» станет
    # настоящим тегом и уедет в мусор вместе с содержимым, а это, как
    # правило, адрес в угловых скобках — его надо показать.
    s = _html.unescape(s)
    s = s.replace("\xa0", " ").replace("​", "")
    if proyti_dvazhdy and pohozhe_na_html(s):
        s = v_tekst(s, proyti_dvazhdy=False)
    s = _CSS_ХВОСТ.sub("", s)
    s = _ХВОСТЫ.sub("\n", s)
    s = _МНОГО_ПУСТЫХ.sub("\n\n", s)
    return s.strip()
