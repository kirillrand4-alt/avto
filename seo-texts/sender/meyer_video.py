ССЫЛКИ = frozenset([f"{БАЗА}{v[0]}/" for v in ВИДЕО]
                   + [f"{БАЗА}{v[0]}/" for v in ЗАПАСНЫЕ])
_URL_RE = re.compile(r'https?://\S+')
# продукт -> ролик. Первый в списке ВИДЕО выигрывает, если продукт встретился
# дважды: там ролики отобраны от отзыва предприятия к общей демонстрации.
_ПО_ПРОДУКТУ = {}
for _v in ВИДЕО:
    for _п in _v[3]:
        _ПО_ПРОДУКТУ.setdefault((_п, _v[2]), _v)


def ссылка(video_id: str) -> str:
    return f"{БАЗА}{video_id}/"


def _собрать(v: tuple, продукт: str = "") -> dict:
    return {"id": v[0], "о_чём": v[1], "станок": v[2], "url": ссылка(v[0]),
            "продукт": продукт, "кому": v[3]}


def подобрать(*части: object, станок: str = "") -> Optional[dict]:
    """Ролик под профиль получателя или None, если подходящего нет.

    части — что известно о предприятии (паспорт с сайта, ОКВЭД, описание).
    станок — 'рентген' | 'фото', чтобы к письму про рентген не прилетел ролик
    про сортировку зерна. Пусто — годится любой.

    Порядок: продукты профиля по убыванию уверенности, и берём первый, под
    который ролик есть. Так у кофейного производства ролик будет про кофе, а
    не про элеватор, — какие бы слова ни стояли рядом в карточке.
    """
    for п in _продукты_профиля(*части, станок=станок):
        v = _ПО_ПРОДУКТУ.get((п["продукт"], п["станок"]))
        if v:
            return _собрать(v, п["продукт"])
    # Запасной путь. В каталоге у продукта один станок — тот, на котором его
    # обычно сортируют. Но ролик под него бывает снят на другом: изюм в
    # каталоге числится за фотосепаратором, а рентген-детектор XS для сыпучих
    # его тоже показывает. Ищем ролик ЗАПРОШЕННОГО станка по продуктам,
    # найденным без ограничения.
    if станок:
        for п in _продукты_профиля(*части):
            v = _ПО_ПРОДУКТУ.get((п["продукт"], станок))
            if v:
                return _собрать(v, п["продукт"])
    return None


def чей(video_id: str) -> tuple:
    """Кому этот ролик показываем — для отчётов и разбора спорных писем."""
    for v in ВИДЕО:
        if v[0] == video_id:
            return v[3]
    return ()


def без_rolika(станок: str = "") -> tuple:
    """Продукты каталога, под которые ролика нет — что ещё стоит снять."""
    from sender.meyer_products import ПРОДУКТЫ
    return tuple(п[0] for п in ПРОДУКТЫ
                 if (not станок or п[1] == станок)
                 and (п[0], п[1]) not in _ПО_ПРОДУКТУ)


def чужие_ссылки(текст: str) -> list:
    """Ссылки в письме, которых нет в библиотеке. Пусто — всё чисто.

    Модель, которой дали одну ссылку, легко сочиняет вторую «такую же» —
    правдоподобный адрес на несуществующий ролик. Письмо от лица юрлица с
    битой ссылкой хуже письма вовсе без ссылки, поэтому проверка жёсткая.
    """
    из_письма = [u.rstrip('.,;)»"') for u in _URL_RE.findall(str(текст or ""))]
    return [u for u in из_письма if u not in ССЫЛКИ]
