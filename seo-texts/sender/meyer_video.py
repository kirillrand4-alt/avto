ССЫЛКИ = frozenset(f"{БАЗА}{v[0]}/" for v in ВИДЕО)
_URL_RE = re.compile(r'https?://\S+')


def ссылка(video_id: str) -> str:
    return f"{БАЗА}{video_id}/"


def подобрать(*части: object, станок: str = "") -> Optional[dict]:
    """Ролик под профиль получателя или None, если похожего нет.

    части — что известно о предприятии (ОКВЭД, описание с сайта, боль).
    станок — 'рентген' | 'фото', чтобы к письму про рентген не прилетел ролик
    про сортировку зерна. Пусто — годится любой.

    Выигрывает ролик с наибольшим числом совпавших ключей; при равенстве —
    тот, что выше в списке (там свежие и наиболее показательные).
    """
    текст = " ".join(str(ч or "") for ч in части).lower()
    if not текст.strip():
        return None
    # При равном числе совпадений выигрывает тот, чьё ключевое слово встретилось
    # РАНЬШЕ. Списки продукции и сырья идут от главного к второстепенному, и
    # порядок в них — сам по себе сигнал. Без этого «кофейные зерна; какао»
    # отдавали ролик про элеватор (ключ «зерн» нашёлся в слове «зерна»), а не
    # про кофе: оба совпали по разу, и побеждал тот, кто выше в списке роликов.
    лучший, вес, где = None, 0, len(текст) + 1
    for vid, о_чём, ст, ключи in ВИДЕО:
        if станок and ст != станок:
            continue
        места = [текст.find(к) for к in ключи if к in текст]
        совпало = len(места)
        первое = min(места) if места else len(текст) + 1
        if совпало > вес or (совпало == вес and совпало and первое < где):
            лучший, вес, где = (vid, о_чём, ст), совпало, первое
    if лучший is None:
        return None
    return {"id": лучший[0], "о_чём": лучший[1], "станок": лучший[2],
            "url": ссылка(лучший[0]), "совпадений": вес}


def чужие_ссылки(текст: str) -> list:
    """Ссылки в письме, которых нет в библиотеке. Пусто — всё чисто.

    Модель, которой дали одну ссылку, легко сочиняет вторую «такую же» —
    правдоподобный адрес на несуществующий ролик. Письмо от лица юрлица с
    битой ссылкой хуже письма вовсе без ссылки, поэтому проверка жёсткая.
    """
    из_письма = [u.rstrip('.,;)»"') for u in _URL_RE.findall(str(текст or ""))]
    return [u for u in из_письма if u not in ССЫЛКИ]
