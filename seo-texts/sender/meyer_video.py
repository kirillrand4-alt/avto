def _bez_zontikov(кандидаты: list) -> list:
    """Убрать общий продукт, если в профиле нашёлся его частный случай.

    Разбор письма #970 («Салаты и деликатесы», правка редактора 14.08). В
    паспорте у них «хумус с кедровыми орешками» и «сырых семян или орехов».
    Общий ключ «орехи» совпал ДВАЖДЫ — и один из двух раз на тех же самых
    «кедровых орешках», которые дают частный продукт «кедровый орех». Счёт
    совпадений стоит в сортировке выше силы ролика, поэтому зонтик с двумя
    случайными попаданиями обошёл отзыв предприятия ровно про их продукт.
    Редактор поставила туда кейс по кедровому ореху — и была права.

    Частный случай узнаём по самому каталогу, а не по спискам-исключениям:
    прогоняем ИМЯ продукта через каталог, и если в имени «кедровый орех»
    опознаётся ещё и «орехи» — значит «орехи» ему зонтик. Отношение
    несимметрично (в слове «орехи» кедровый орех не опознаётся), поэтому
    правило само отличает общее от частного и не трогает пары вроде
    «кофе» / «картофель фри», где никто никого не накрывает.
    """
    продукты = {к[3] for к in кандидаты}
    зонтики = set()
    for п in продукты:
        накрывают = {x["продукт"] for x in _продукты_профиля(п)} - {п}
        зонтики |= (накрывают & продукты)
    оставить = [к for к in кандидаты if к[3] not in зонтики]
    return оставить or кандидаты


