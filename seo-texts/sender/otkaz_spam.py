# -*- coding: utf-8 -*-
"""Отказ НАШЕГО почтовика «подозрение на спам» — распознать и остановиться.

ЧТО ЭТО. Не отбивка получателя, а отказ на выходе: письмо не ушло вовсе.
Яндекс отвечает `554 5.7.1 Message rejected under suspicion of SPAM`,
mail.ru — своим текстом про спам. Это прямая оценка НАШЕЙ репутации, и
единственный правильный ответ на неё — перестать слать, а не слать дальше.

ПОЧЕМУ ЗАВЕДЕНО ОТДЕЛЬНО ОТ ОТБИВОК. Отбивка (bounce) говорит о мёртвом
адресе — виноват список. Отказ говорит о нас самих — виноват темп, домен
или текст. Считать их вместе значит потерять и тот сигнал, и другой.

СЛУЧАЙ, РАДИ КОТОРОГО НАПИСАНО (21.08.2026). Три мейеровских домена за два
часа выдали 133 письма. В 12:00 МСК отказ был один на 114 писем, в 13:00 —
двадцать девять на сорок восемь. Никто не остановился: отказ нигде не
считался, ни на экране, ни в гейте, и лежал только в messages.last_error,
куда не смотрит ни один рубеж. Владелец: «по идее остановка отправки должна
идти же сразу при начале попадания в спам».

ДВА РУБЕЖА, И ОБА СРАЗУ, А НЕ ПО ОБХОДУ РАЗ В ЧАС:
  * ЯЩИК — {ПОРОГ_ЯЩИКА} отказа за сутки, и он на паузе;
  * НАПРАВЛЕНИЕ — {ПОРОГ_НАПРАВЛЕНИЯ} отказов за сутки по всем его ящикам,
    и на паузе весь пул: домены у направления общие, и придушивают их
    вместе.
Оба порога — конфигом (`gates.otkaz_stop_yashchik`, `gates.otkaz_stop_
napravlenie`), 0 выключает рубеж.
"""
from __future__ import annotations

import re
from typing import Optional

# тип события в журнале; рядом с 'bounce'/'complaint', но НЕ вместо них
СОБЫТИЕ = "reject_spam"

ПОРОГ_ЯЩИКА = 2
ПОРОГ_НАПРАВЛЕНИЯ = 5
# Сколько РАЗНЫХ ящиков направления должны словить отказ, чтобы душить пул.
# Одна опальная учётка — её собственная беда, а не беда общих доменов.
МИН_ЯЩИКОВ = 2

# Узкий разбор. «550 No such user» сюда не попадает намеренно: это мёртвый
# адрес, чужая история. Ловим то, где почтовик прямо говорит про спам.
_КОД = re.compile(r"\b(?:554|5\.7\.1)\b")
_СПАМ = re.compile(
    r"spam|подозрен|suspicion|bulk|blacklist|blocked due to|"
    r"message rejected|отклонено", re.I)


def eto_otkaz_spam(oshibka: object) -> bool:
    """Отказ ли это по спаму (а не мёртвый ящик и не таймаут).

    Требуем ОБА признака: код 554/5.7.1 и слово про спам. Только кода мало:
    5.7.1 отдают и на «recipient address rejected: Inactive» — там дело в
    адресе, а не в нас.
    """
    т = str(oshibka or "")
    if not т:
        return False
    if not _КОД.search(т):
        return False
    if re.search(r"no such user|invalid mailbox|mailbox .* unavailable|"
                 r"recipient address rejected", т, re.I):
        return False
    return bool(_СПАМ.search(т))


def _iz_config(config, ключ: str, по_умолчанию: int) -> int:
    """Целое из конфига, не роняясь ни на отсутствии ключа, ни на мусоре."""
    try:
        з = config.get(ключ, None)
    except Exception:                                              # noqa: BLE001
        return по_умолчанию
    if з is None or str(з).strip() == "":
        return по_умолчанию
    try:
        return max(0, int(з))
    except (TypeError, ValueError):
        return по_умолчанию


def porogi(config) -> tuple[int, int]:
    """(порог по ящику, порог по направлению) из конфига; 0 — рубеж выключен."""
    return (_iz_config(config, "gates.otkaz_stop_yashchik", ПОРОГ_ЯЩИКА),
            _iz_config(config, "gates.otkaz_stop_napravlenie", ПОРОГ_НАПРАВЛЕНИЯ))


def min_yashchikov(config) -> int:
    """Сколько разных ящиков направления должны словить отказ для общей паузы.

    СЛУЧАЙ 25.08.2026. Пять отказов ОДНОГО a.kozlov@zernosort.ru погасили
    шесть чужих мейеровских ящиков, у которых отказов не было ни одного:
    счёт направления складывал всё подряд, и одной опальной учётки хватало,
    чтобы остановить направление на сутки. Свой ящик к тому мигу уже стоял
    по собственному порогу — то есть вина была зачтена дважды.

    Рубеж направления заведён про ОБЩИЕ ДОМЕНЫ («придушивают их вместе»), а
    общая беда видна тем, что отказы идут не с одного адреса. Порог 1 —
    прежнее поведение.
    """
    return _iz_config(config, "gates.otkaz_min_yashchikov", МИН_ЯЩИКОВ)


def prichina_pauzy(skolko: int, oblast: str) -> str:
    """Текст причины паузы — его увидит оператор в панели."""
    return f"отказ почтовика по спаму: {skolko} за сутки ({oblast})"


def nachalo_sutok(now) -> Optional[object]:
    """Начало текущих суток UTC — окно, в котором считаем отказы.

    Сутки, а не 14 дней окна гейтов: репутация на отказах меняется за часы,
    и вчерашние отказы не должны держать ящик, если сегодня он чист.
    """
    try:
        return now.replace(hour=0, minute=0, second=0, microsecond=0)
    except Exception:                                              # noqa: BLE001
        return None
