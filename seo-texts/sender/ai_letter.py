def target_division(rec: dict, default: str = 'kc') -> tuple:
    """Какое направление писать этому получателю → (division, reason).

    Приоритет (задача 43; для компаний «kc+meyer» это и есть правило выбора
    товара, полностью описано в README патча):
      1. explicit   — оператор/кампания задали target_division (ai_division);
      2. news       — новостной повод однозначно про одно направление;
      3. needs      — колонка потребностей «Все категории оборудования»;
      4. base_label — метка базы обзвона (составная не решает);
      5. profile    — ОКВЭД и описание деятельности;
      6. fallback   — kc (79% базы, и только у КЦ есть проверяемые счётчики).
    Новость выше потребностей осознанно: заход письма строится на событии, и
    писать про компрессоры под новость о линии сортировки - абсурд. Случай
    «новость про одно, потребность про другое» помечается reason=news_over_needs
    и виден оператору в очереди подтверждений.
    """
    explicit = norm_division(_rec_field(rec, 'target_division', 'ai_division'))
    if explicit:
        return explicit, 'explicit'

    ex = rec.get('extra') or {}
    news_hit = set()
    if str(rec.get('mode') or '').upper() == 'NEWS':
        news_text = ' '.join(str(ex.get(k) or '') for k in
                             ('news_object', 'news_title', 'news_text',
                              'news_summary', 'news_topic'))
        news_hit = _markers_hit(news_text, _NEWS_MARKERS)

    needs = divisions_by_equipment(
        _rec_field(rec, 'equip_categories', 'equipment', 'equipment_all'))

    if len(news_hit) == 1:
        d = next(iter(news_hit))
        return d, ('news_over_needs' if needs and d not in needs else 'news')
    if len(needs) == 1:
        return next(iter(needs)), 'needs'

    label = divisions_of(_rec_field(rec, 'division', 'segment', 'base_label'))
    if len(label) == 1:
        return next(iter(label)), 'base_label'

    profile = _markers_hit(
        ' '.join(str(_rec_field(rec, k) or '') for k in ('okved', 'activity',
                                                         'okved_main', 'profile')),
        _PROFILE_MARKERS)
    if len(profile) == 1:
        return next(iter(profile)), 'profile'

    d = default if default in RULES_BY_DIVISION else 'kc'
    # потребность в обоих и ничего не разрулило: пишем про КЦ, но помечаем -
    # оператор в очереди видит, что второе направление тоже законно
    return d, ('default_both_needs' if len(needs) > 1 else 'fallback')


def load_facts(path: Optional[str] = None, division: str = 'kc') -> dict:
    """Факты направления + продуктовый глоссарий. Файла нет → фолбэк без
    падения: письмо без цифр лучше, чем сорванная фаза генерации."""
    division = division if division in RULES_BY_DIVISION else 'kc'
    p = path or FACTS_PATH_BY_DIVISION[division]
    try:
        facts = json.load(open(p, encoding='utf-8'))
    except Exception:  # noqa: BLE001 - без фактов работаем на техконстантах
        facts = json.loads(json.dumps(_FACTS_FALLBACK[division]))
    facts.setdefault('division', division)
    # C8: продуктовый глоссарий из KB (чтобы генератор не путал названия оборудования)
    try:
        facts['product_glossary'] = json.load(
            open(GLOSSARY_PATH_BY_DIVISION[division], encoding='utf-8'))
    except Exception:  # noqa: BLE001
        facts.setdefault('product_glossary', {})
    return facts


def load_facts_all() -> dict:
    """{'kc': facts, 'meyer': facts} — для смешанных партий получателей."""
    return {d: load_facts(division=d) for d in RULES_BY_DIVISION}


def _facts_block_meyer(facts: dict) -> str:
    def _bullets(key, head, limit=14):
        vals = [str(x) for x in (facts.get(key) or []) if str(x).strip()][:limit]
        return f"\n{head}\n" + "\n".join(f"  - {v}" for v in vals) if vals else ""

    gl = facts.get('product_glossary') or {}
    gloss = ""
    if gl:
        gloss = ("\nОБОРУДОВАНИЕ MEYER (глоссарий — для ТОЧНОСТИ терминов, "
                 "НЕ вставлять спеки и названия серий в письмо):\n"
                 + "\n".join(f"  - {k}: {v}" for k, v in list(gl.items())[:12]))
    head = [f"- {facts[k]}" for k in ('total_crm', 'published_site') if facts.get(k)]
    if not head:   # фактов нет — честнее письмо совсем без цифр, чем выдуманные
        head = ["- (проверяемых чисел нет: письмо пишем БЕЗ цифр-достижений)"]
    return ("ФАКТЫ (только их можно использовать как числа/имена):\n"
            + "\n".join(head)
            + "\n- Подтверждённых публичных клиентов НЕТ: имена компаний и города "
              "внедрений в письме НЕ называть."
            + _bullets('proof_points',
                       "ОПОРНЫЕ ФАКТЫ (максимум ОДИН на письмо и только если он и есть повод):")
            + _bullets('industries_typical',
                       "ОТРАСЛИ, ГДЕ ЭТО РАБОТАЕТ (для попадания в профиль, НЕ перечислять списком):")
            + _bullets('pains_typical',
                       "ТИПИЧНЫЕ БОЛИ (ориентир для связки; формулировать СВОИМИ словами, дословно не брать):")
            + gloss)


def facts_block(facts: dict, division: str = 'kc') -> str:
    if (division or 'kc') == 'meyer':
        return _facts_block_meyer(facts)
    rc = "\n".join(f"  - {k}: {v} проектов"
                    for k, v in (facts.get('region_counts_site_index') or {}).items())
    cl = "\n".join(f"  - {k} ({v['city']}, {v['sphere']}): {v['equipment']}"
                    for k, v in (facts.get('clients_verified') or {}).items())
    gl = facts.get('product_glossary') or {}
    gloss = ""
    if gl:
        gloss = "\nОБОРУДОВАНИЕ КЦ (глоссарий — для ТОЧНОСТИ терминов, НЕ вставлять спеки в письмо):\n" \
            + "\n".join(f"  - {k}: {v}" for k, v in list(gl.items())[:12])
    return (f"ФАКТЫ (только их можно использовать как числа/имена):\n"
            f"- {facts.get('total_crm', '')}\n- {facts.get('published_site', '')}\n"
            f"- Проекты по регионам (все типы оборудования, индекс сайта):\n{rc}\n"
            f"- Подтверждённые клиенты (упоминать только в письме их региона):\n{cl}"
            f"{gloss}")


