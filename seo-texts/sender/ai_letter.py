#  Просьба «отдайте письмо тому, кто этим занимается» в живых формах. Одного
#  корня «перенаправ» мало: 14.08 правило (в) само велело писать иначе, чтобы не
#  задваивать «буду признателен», и первое же письмо по новым правилам гейт снял
#  за отсутствие просьбы, которую сам же и просил переформулировать. Проверяем
#  СМЫСЛ, а не одно слово; список форм тот же, что предложен модели в правилах.
_PROSBA_ПРЯМО = re.compile(r'(?i)перенаправ|перешл|переслат')
# Глагол передачи + КОМУ или ЧТО в пределах фразы. Одного «передайте письмо»
# мало: карточка приёмной прямо просит «передать снабжению или главному
# инженеру», и модель пишет «передайте, пожалуйста, руководителю службы» —
# просьба на месте, слова «письмо» в ней нет. Живой брак #1054 (кофе): три
# раунда починки и $1.60 ушли на требование, которого в правилах нет.
_PROSBA_ГЛАГОЛ = re.compile(
    r'(?i)(передайт|передать|направьт|направить|адресуйт|отдайт|покажит)\w*'
    r'[^.!?\n]{0,70}?'
    r'(письм|его\b|коллег|ответственн|специалист|руководител|снабжен|'
    r'инженер|технолог|отдел|служб|нужному|тому,?\s+кто|кто\s+заним)')
_PROSBA_ВОПРОС = re.compile(
    r'(?i)к\s+кому\s+(?:мне\s+)?(?:лучше\s+)?(?:стоит\s+)?обрат|'
    r'кто\s+(?:у\s+вас\s+)?(?:отвечает|занимается)|'
    r'с\s+кем\s+(?:лучше\s+)?(?:мне\s+)?(?:поговорить|обсудить)|'
    r'свяжите\s+меня')


def _prosba_perenapravit(body: str) -> bool:
    """Есть ли в письме просьба отдать его тому, кто этим занимается.

    Проверяем СМЫСЛ тремя путями: прямой глагол пересылки, глагол передачи с
    указанием кому, вопрос «к кому обратиться». Одно слово «перенаправ» здесь
    не годится: правило (в) само велит формулировать иначе, чтобы «буду
    признателен» не задваивалось с канонной концовкой.
    """
    т = str(body or '')
    return bool(_PROSBA_ПРЯМО.search(т) or _PROSBA_ГЛАГОЛ.search(т)
                or _PROSBA_ВОПРОС.search(т))


# ВНЕ ПРОФИЛЯ MEYER — И ТОЛЬКО MEYER (слово владельца 14.08 по АО «Полюс
# Красноярск»: «про золотодобычу правильно что не пишет, не наше это»).
