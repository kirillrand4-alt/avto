_ОПФ_ПОЛНАЯ = re.compile(
    r'(?i)^\s*(общество\s+с\s+ограниченной\s+ответственностью'
    r'|(не)?публичное\s+акционерное\s+общество|акционерное\s+общество'
    r'|(закрытое|открытое)\s+акционерное\s+общество'
    r'|снабженческо-сбытовой\s+сельскохозяйственный\s+потребительский\s+кооператив'
    r'|сельскохозяйственный\s+производственный\s+кооператив'
    r'|производственный\s+кооператив'
    # ИП и КФХ НЕ трогаем: «ИП Иванов» без формы превращается в «Иванов», и
    # письмо начинает обращаться к человеку как к заводу.
    r'|ООО|ЗАО|ОАО|ПАО|НАО|АО|ФГУП|МУП|ГУП|АНО|СПК)\s*')


def короткое_имя(name: object) -> str:
    """Как компания зовёт себя сама: без правовой формы и без капса.

    Зачем (13.08): в карточку получателя едет юридическое имя из ЕГРЮЛ —
    «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "КАСИМОВСКИЙ
    КАРТОФЕЛЕПЕРЕРАБАТЫВАЮЩИЙ КОМБИНАТ"». Короткое имя модель должна была
    вывести сама, и на неудобных именах она просто уходила от названия вовсе:
    два письма из двенадцати забракованы правилом 19и, причём одно из них —
    как раз Касимовский комбинат. Даём готовую строку.

    Регистр приводим к обычному только если имя пришло СПЛОШНЫМ капсом:
    «АгроМарт» и «Meyer» трогать нельзя.
    """
    имя = str(name or '').strip()
    if not имя:
        return ''
    имя = _ОПФ_ПОЛНАЯ.sub('', имя).strip()
    # Кавычки любых видов вокруг имени убираем — в письме их ставит сама модель
    имя = имя.strip('«»"\'“”„ ').strip()
    # «ТИТАН - АГРО» пишут через пробелы, а зовут себя «Титан-Агро»
    имя = re.sub(r'\s*-\s*', '-', имя)
    буквы = [c for c in имя if c.isalpha()]
    if буквы and all(c.isupper() for c in буквы):
        слова = []
        for i, w in enumerate(имя.split()):
            # Части через дефис — это части ИМЕНИ («Конти-Рус»), а не текст:
            # у редактора они с заглавных, поэтому поднимаем каждую.
            слова.append('-'.join(ч.capitalize() for ч in w.split('-'))
                         if i == 0 else w.lower())
        имя = ' '.join(слова)
    return имя


def _predpriyatie_nazvano(name: object, domain: object, text: str):
    """Названо ли предприятие в письме. None = судить нечем (нет своего имени).

    Правило 19и просило называть компанию, и МОДЕЛЬ ЕГО НЕ ИСПОЛНЯЕТ: на партии
    05.08 без имени было 9 писем из 27 до правила и 6 из 22 после - разницы
    нет. Правило в промпте это просьба, заслон в гейте это заслон.

    Матчер намеренно снисходительный: примерка на 49 письмах показала, что
    строгий вариант заворачивает хорошие письма (7 ложных из 16). Считаем
    названным, если есть слово имени от 3 знаков, ОСНОВА длинного слова
    (падеж: «ГАЗСТРОЙ» -> «в Газстрое»), аббревиатура из первых букв или
    латинское имя из домена.
    """
    words = [w for w in re.findall(r'[А-ЯЁA-Z][А-ЯЁA-Zа-яёa-z\-]{1,}',
                                   str(name or '').upper())
             if w not in _ИМЯ_ШУМ and len(w) >= 2]
    if not words:
        return None
    up = text.upper()
    for w in words:
        if len(w) >= 3 and w in up:
            return True
        if len(w) >= 6 and w[:len(w) - 2] in up:
            return True
    abbr = ''.join(w[0] for w in words)[:6]
    if len(abbr) >= 3 and re.search(r'\b' + re.escape(abbr) + r'\b', up):
        return True
    latin = re.sub(r'^(www\.)?', '', str(domain or '')).split('.')[0].upper()
    if len(latin) >= 4 and latin in up:
        return True
    return False


def gate(subject: str, body: str, *, mode: str = 'GENERIC',
         extra: Optional[dict] = None, facts: Optional[dict] = None,
         division: str = 'kc') -> list:
    """Механический гейт письма. [] = чисто. Порядок и регексы — спека §3,
    плюс проверка перекрёстной лексики направления (задача 43)."""
    facts = facts or {}
    division = division if division in RULES_BY_DIVISION else 'kc'
    fails: list = []
    text = subject + '\n' + body
    for rx, name in SUBJ_RE:
        if re.search(rx, subject):
            fails.append(f'{name}: «{subject}»')
    # канон редактора (19а): «Вопрос по расширению … в «Компании»» - до 10
    # слов по правилу, гейт даёт люфт до 12 (название компании из двух слов).
    if len(subject.split()) > 12:
        fails.append(f'тема длинная ({len(subject.split())} слов)')
    for m in re.finditer(r'(\d[\d,\.]*)\s*%', body):
        if m.group(1).split(',')[0].split('.')[0] not in ('97', '99', '95'):
            fails.append(f'проценты: {m.group(0)}')
    заслоны = STOP_RE + CROSS_LEX[division]
    # Рентген-письмо не имеет права называть находкой то, чего детектор не
    # видит. Включаем заслон по САМОМУ ТЕКСТУ, а не по направлению: у
    # фотосепаратора щепка и деревяшка в зерновом потоке — законная задача
    # сортировки, и запрещать их всему Meyer было бы неверно.
    if str(division or '').startswith('meyer') and re.search(r'(?i)рентген', body):
        заслоны = заслоны + NEVIDIMOE_RENTGENOM
    if str(division or '').startswith('meyer'):
        заслоны = заслоны + STRASHILKI_MEYER
    for rx, name in заслоны:
        if name == 'подпись в теле':
            # Первое совпадение может быть законным представлением — ищем
            # первое НЕзаконное, иначе настоящая подпись ниже проскочит.
            m = next((x for x in re.finditer(rx, text)
                      if not _представление_ok(x, text, division)), None)
        else:
            m = re.search(rx, text)
        if m:
            frag = text[max(0, m.start() - 25):m.end() + 25].replace('\n', ' ')
            fails.append(f'{name}: «{frag}»')
    if mode != 'NEWS' and re.search(PSEUDO_NEWS_RE, body):
        fails.append('псевдо-новость без данных (GENERIC)')
    # Ссылка в письме допустима ОДНА и только из библиотеки роликов: модель,
    # которой дали адрес, легко сочиняет второй «такой же» — правдоподобный
    # и мёртвый. Письмо от лица юрлица с битой ссылкой хуже письма без неё.
    _чужие = чужие_ссылки(body)
    if _чужие:
        fails.append(f'ссылка не из библиотеки роликов: {_чужие[0][:70]}')
    if len(re.findall(r'https?://', body)) > 1:
        fails.append('в письме больше одной ссылки')
    # Правки владельца 14.08 по живому письму.
    # «Буду признателен» дважды — тавтология: оборот стоит и в просьбе
    # перенаправить, и в строке отказа, и рядом они звучат заискиванием.
    if len(re.findall(r'(?i)буду призна(?:телен|тельна)', body)) > 1:
        fails.append('«буду признателен» дважды — тавтология, второй раз скажи иначе')
    # Лесть очевидным: «контроль качества для вас принципиален» верно для любого
    # предприятия и потому не значит ничего. Факт о них обязан ТРЕБОВАТЬ действия.
    if re.search(r'(?i)(контрол\w* качества|качеств\w+|безопасност\w+)'
                 r'[^.\n]{0,45}(для вас|у вас)[^.\n]{0,35}'
                 r'(принципиал|важн|в приоритете|на первом месте)', body):
        fails.append('лесть очевидным («качество для вас важно») — вместо этого '
                     'скажи, чего требует их сертификация или аудит')
    # ПЕРВАЯ ФРАЗА. Запрещать конкретный заход всем письмам оказалось неверно:
    # 12.08 запретили «Смотрел профиль…» - модель тут же выдала новый штамп,
    # 37% партии начались с «На». Плохо не слово, а одинаковость партии,
    # поэтому квоту держит zahod_overflow по партии, а гейт лишь СЛЕДИТ за
    # исполнением: письму, которому велено сменить заход, повторять свою форму
    # нельзя. Просьбы в промпте тут мало - шесть перегенераций 12.08 подряд
    # начались теми же словами, работает только заслон в коде.
    сменить = str((extra or {}).get('сменить_заход') or '')
    if сменить and форма_захода(body) == сменить:
        fails.append(f'заход «{сменить}» израсходован на партии — '
                     f'начни иначе: «{_первая_фраза(body)[:50]}»')
    # КАНОН РЕДАКТОРА для холодных писем Meyer: представление первой строкой и
    # просьба перенаправить. 13.08 письмо на 74 слова прошло гейт и вышло в
    # старом стиле («Смотрел профиль…») - длиной такое не поймать, новостные
    # письма законно короче. Ловим по структуре и только GENERIC.
    if str(division or '').startswith('meyer') and mode != 'NEWS':
        if not re.search(r'(?i)меня зовут', body):
            fails.append('нет представления первой строкой — канон редактора '
                         'требует «Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю…»')
        if not re.search(r'(?i)перенаправ', body):
            fails.append('нет просьбы перенаправить письмо ответственному')
    # ПРЕДСТАВЛЕНИЕ ПО ИМЕНИ. Канон редактора начинается с «Меня зовут …», но
    # письмо пишется ДО выбора ящика: имя подставит движок вместо метки. Модель,
    # предоставленная себе, придумает имя — и письмо уйдёт за подписью другого
    # человека. Поэтому имя допустимо ТОЛЬКО меткой.
    if re.search(r'(?i)меня зовут', body) and 'ИМЯ_ОТПРАВИТЕЛЯ' not in body:
        fails.append('представление по имени без метки ИМЯ_ОТПРАВИТЕЛЯ — '
                     'имя подставляет движок, придумывать его нельзя')
    low = body.lower()
    if БРАКОВАТЬ_БЕЗ_ОТКАЗА and not _has_optout(low):
        fails.append('нет опции отказа')
    if low.count('извините за') > 1:
        fails.append('двойное заискивание (отказ дважды)')
    words = len(body.split())
    # У Meyer канон редактора (13.08) длиннее компрессорного: там надо
    # представиться, назвать задачу предприятия и сказать, чем её решают.
    # Её три письма — 150-180 слов; со старым потолком 140 гейт браковал бы
    # ровно тот стиль, под который мы подстраиваемся.
    низ, верх = (45, 200) if str(division or '').startswith('meyer') else (45, 140)
    if not низ <= words <= верх:
        fails.append(f'объём {words} слов (норма {низ}-{верх})')
    if not body.rstrip().endswith('С уважением,'):
        fails.append('финал не «С уважением,»')
    # Ревью №28: цифра в названии («ЭТК № 2», «ТЭЦ-3») давала ложный брак —
    # лид терялся навсегда. Числа из имени/города считаем законными.
    _own = set()
    for _k in ('company_name', 'name', 'city', 'contact_name'):
        _own |= set(re.findall(r'\d+', str((extra or {}).get(_k) or '')))
    leftover = (set(re.findall(r'\d+', body))
                - allowed_numbers(facts, extra, division) - _own)
    if leftover:
        fails.append(f'непроверенные числа: {sorted(leftover)}')
    # Правило 19и механически: без названия письмо читается как веерная
    # рассылка. «Судить нечем» (в базе только организационная форма) - не брак.
    _nazvano = _predpriyatie_nazvano(
        (extra or {}).get('company_name'),
        (extra or {}).get('domain') or (extra or {}).get('site'),
        subject + '\n' + body)
    if _nazvano is False:
        fails.append('предприятие не названо ни в теме, ни в теле (19и)')
    ach = len(re.findall(r'5580', body)) + len(re.findall(r'опубликованн\w+ (кейс|проект)', body))
    if division == 'meyer':
        ach = len(re.findall(r'(?i)(больше|более)\s+200|200\s+предприят', body))
    if ach > 1:
        fails.append(f'витрина: {ach} числа-достижения (максимум одно)')
    # падежный гейт города (урок 2026-07-24: «в Санкт-Петербург» из шаблонной
    # подстановки). Город в именительном сразу после «в/во» = не склонён.
    city = str((extra or {}).get('city') or '').strip()
    if city and not city.lower().endswith(_INDECLINABLE_END):
        if re.search(r'(?i)\bво?\s+' + re.escape(city) + r'(?![\w-])', text):
            fails.append(f'город без склонения: «в {city}»')
    # Вычитка 27.07 (аудит 359 карточек, 101 брак) — три массовых класса:
    # 1) обрезанный регион: «в Чеченской», «в Пензенской -» без слова
    #    область/край/Республика; прилагательное региона после «в» обязано
    #    сопровождаться существительным
    m = re.search(
        r'\bво?\s+[А-ЯЁ][а-яё-]+(?:ской|цкой|ском|цком)\b'
        r'(?!\s+(?:област|обл\.|кра[ею]|район|[Рр]еспублик|автономн|округ|'
        r'город|ГЭС|ГРЭС|ТЭЦ|НПЗ|заводе))', body)
    if m:
        fails.append(f'обрезанный регион: «{m.group(0)}…» — допиши '
                     f'область/край/Республику')
    # 2) имя в приветствии, которого нет в карточке (разворачивание инициала
    #    «Киселев А.» -> «Алексей» дало письмо Антону с чужим именем)
    пм = re.search(r'^(?:Добрый день|Здравствуйте|Доброе утро),\s*([^!\n]{1,50})!',
                   body.strip())
    if пм:
        кому = str((extra or {}).get('contact_name') or '').strip()
        слова = {w.strip('.,!') for w in кому.split() if len(w.strip('.,!')) > 2}
        обращение = [w for w in пм.group(1).replace('!', '').split()
                     if len(w) > 2]
        if обращение and not all(w in слова for w in обращение):
            fails.append(f'имя не из карточки: «{пм.group(0)}» (контакт: '
                         f'«{кому or "нет"}») — приветствие без имени')
    # 3) вопросы: канон редактора (19г) разрешает второй короткий уточняющий
    # вопрос сразу за основным; три и больше - по-прежнему брак.
    if body.count('?') > 2:
        fails.append(f'вопросов в письме: {body.count("?")} (максимум два)')
    return fails


# ------------------------------------------------------ анти-штамп (§6) --- #

# лимиты на 49 писем (спека §6), масштабируются пропорционально размеру партии
STAMP_LIMITS_PER49 = {
    r'частый случай|такая история|похожая ситуация': 4,
    r'судя по профилю': 3,
    r'смотрел\w*\s+(ваш|профиль|сайт|чем занима)': 3,
    r'посмотрел\w*\s+(ваш|профиль|сайт|чем занима)': 2,
    r'рано или поздно': 3,
    r'бьёт по': 3, r'встаёт вопрос': 4, r'под контролем': 5,
}

# Свои штампы направления Meyer: обороты, которые модель тиражирует из правил
# и глоссария (проверено на КЦ: первым выгорает язык самих правил).
STAMP_LIMITS_PER49_MEYER = {
    r'частый случай|такая история|похожая ситуация': 4,
    r'судя по профилю': 3,
    r'смотрел\w*\s+(ваш|профиль|сайт|чем занима)': 3,
    r'посмотрел\w*\s+(ваш|профиль|сайт|чем занима)': 2,
    r'рано или поздно': 3,
    r'посторонн\w+ включени|инородн\w+ включени': 4,
    r'пищев\w+ безопасност': 3, r'контрол\w* качества': 4,
    r'ручн\w+ переборк': 4, r'рекламац': 3, r'на всякий случай': 3,
}
STAMP_LIMITS_BY_DIVISION = {'kc': STAMP_LIMITS_PER49,
                            'meyer': STAMP_LIMITS_PER49_MEYER}


def stamp_overflow(bodies: list, division: str = 'kc') -> list:
    """Какие обороты израсходованы на партии (для перефраз-вызова)."""
    limits = STAMP_LIMITS_BY_DIVISION.get(division or 'kc', STAMP_LIMITS_PER49)
    n = max(1, len(bodies))
    out = []
    for rx, lim in limits.items():
        limit = max(1, round(lim * n / 49))
        cnt = sum(1 for b in bodies if re.search('(?i)' + rx, b))
        if cnt > limit:
            out.append(f'{rx} ({cnt}>{limit})')
    return out


# --- квота на форму первой фразы -------------------------------------------- #
# Жёсткий запрет одного захода проблему не решает, а двигает: 12.08 запретили
# «Смотрел профиль…» - и модель выдала новый штамп, 37% партии начались с «На».
# Плохо не то, ЧТО написано первой фразой, а то, что вся партия начинается
# одинаково. Поэтому считаем не слова, а ФОРМУ зачина, и держим квоту: одна
# форма - не больше трети партии, лишние идут на перегенерацию.
_ФОРМЫ_ЗАХОДА = (
    # Запятая после глагола («Посмотрел, чем занимается») — та же форма,
    # поэтому разделитель [\s,]+, а не \s+.
    ('от профиля', r'^\W*((по)?смотрел\w*|изучил\w*|глянул\w*|видел\w*|'
                   r'ознакомил\w*)[\s,]+(ваш|профиль|сайт|чем занима|'
                   r'что делает|производств)|^\W*судя по (профил|сайт|описан)|'
                   r'^\W*профиль ваш'),
    ('от вопроса', r'^\W*(подскажите|скажите|вопрос|интересно)'),
    ('от условия', r'^\W*(если|когда|пока)\s'),
    ('от отрасли', r'^\W*(производств|обработк|изготовлен|компани|'
                   r'предприяти|завод)'),
    ('от площадки', r'^\W*(на|в|при|у)\s'),
)


def _первая_фраза(body: object) -> str:
    """Первая содержательная строка: приветствие не в счёт."""
    for стр in str(body or '').split('\n'):
        стр = стр.strip()
        if стр and not re.match(r'(?i)^(добрый день|здравствуйте|доброе утро|'
                                r'добрый вечер)', стр):
            return стр
    return ''


def форма_захода(body: object) -> str:
    """Как письмо заходит. Незнакомый заход опознаём по первым двум словам -
    иначе квота ловила бы только те формы, которые я успел перечислить."""
    первая = _первая_фраза(body)
    if not первая:
        return ''
    for имя, rx in _ФОРМЫ_ЗАХОДА:
        if re.search('(?i)' + rx, первая):
            return имя
    слова = re.findall(r'[а-яёa-z]+', первая.lower())
    return ' '.join(слова[:2]) if слова else ''


def zahod_overflow(bodies: list, доля: float = 0.34) -> dict:
    """Кто в партии обязан сменить заход. {индекс письма: форма}.

    Первые письма квоту занимают и остаются как есть, лишние помечаются -
    так перегенерация касается меньшинства, а не всей партии.
    """
    предел = max(1, int(len(bodies) * доля))
    видано: dict = {}
    лишние: dict = {}
    for i, тело in enumerate(bodies):
        ф = форма_захода(тело)
        if not ф:
            continue
        видано[ф] = видано.get(ф, 0) + 1
        if видано[ф] > предел:
            лишние[i] = ф
    return лишние


