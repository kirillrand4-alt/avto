def короткое_имя(name: object) -> str:
    """Как компания зовёт себя сама: без правовой формы и без капса.

    Зачем (13.08): в карточку получателя едет юридическое имя из ЕГРЮЛ —
    «ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "КАСИМОВСКИЙ
    КАРТОФЕЛЕПЕРЕРАБАТЫВАЮЩИЙ КОМБИНАТ"». Короткое имя модель должна была
    вывести сама, и на неудобных именах она просто уходила от названия вовсе:
    два письма из двенадцати забракованы правилом 19и, причём одно из них —
    как раз Касимовский комбинат. Даём готовую строку.

    Регистр приводим к обычному только если имя пришло СПЛОШНЫМ капсом:
    «АгроМарт» и «Meyer» трогать нельзя.
    """
    имя = str(name or '').strip()
    if not имя:
        return ''
    имя = _ОПФ_ПОЛНАЯ.sub('', имя).strip()
    # Кавычки любых видов вокруг имени убираем — в письме их ставит сама модель
    имя = имя.strip('«»"\'“”„ ').strip()
    # «ТИТАН - АГРО» пишут через пробелы, а зовут себя «Титан-Агро»
    имя = re.sub(r'\s*-\s*', '-', имя)
    # ВЛОЖЕННЫЕ КАВЫЧКИ (живой брак 14.08, письмо #969). У «АКЦИОНЕРНОЕ
    # ОБЩЕСТВО "ГРУППА КОМПАНИЙ "РЕСА"» после снятия формы остаётся ГРУППА
    # КОМПАНИЙ "РЕСА" — с ОДНОЙ кавычкой внутри. Прежний код срезал только
    # крайние кавычки, поэтому в письмо уезжало «Группа компаний "реса»:
    # висячая кавычка и бренд в нижнем регистре. Разбираем на описание и
    # собственно имя, регистр правим у каждого своим правилом.
    _вл = re.match(r'^(.*?)[«"\'“„]([^»"\'”“]+)[»"\'”]?\s*$', имя)
    описание, бренд = ('', имя)
    if _вл and _вл.group(2).strip():
        описание, бренд = _вл.group(1).strip(' -,'), _вл.group(2).strip()
    описание = описание.replace('"', '').replace('«', '').replace('»', '')
    бренд = бренд.replace('"', '').replace('«', '').replace('»', '')

    def _рег(кусок: str, первое_с_заглавной: bool = True) -> str:
        буквы = [c for c in кусок if c.isalpha()]
        if not (буквы and all(c.isupper() for c in буквы)):
            return кусок              # «АгроМарт», «Meyer» — не трогаем
        слова = []
        for i, w in enumerate(кусок.split()):
            # Части через дефис — это части ИМЕНИ («Конти-Рус»), а не текст:
            # у редактора они с заглавных, поэтому поднимаем каждую.
            подъём = '-'.join(ч.capitalize() for ч in w.split('-'))
            слова.append(подъём if (i == 0 and первое_с_заглавной) else w.lower())
        return ' '.join(слова)

    # Заглавная — только у первого слова, и у бренда, и у описания: в русском
    # «Мука ставропольская», а не «Мука Ставропольская». Первая редакция
    # поднимала каждое слово бренда ради односложной «РЕСА» — и портила все
    # многословные имена разом.
    бренд = _рег(бренд) if бренд else ''
    описание = _рег(описание) if описание else ''
    return f'{описание} «{бренд}»' if описание and бренд else (бренд or описание)


