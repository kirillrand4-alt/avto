def _куски_json(text: str) -> list:
    """Все сбалансированные {...} в ответе, по порядку появления.

    Балансный обход вместо жадного `\\{.*\\}`: в правилах и пуле механик стоят
    плейсхолдеры «{news_object}», «{city}», и модель повторяет их эхом в
    преамбуле перед ответом. Жадная вырезка начинала кусок с этого эха и
    падала с «Expecting property name enclosed in double quotes» (13.08,
    письмо #952). Внутренность строк не считаем — скобка в тексте письма
    больше баланс не ломает.
    """
    куски, i, n = [], 0, len(text)
    while i < n:
        if text[i] != '{':
            i += 1
            continue
        глубина, в_строке, экран, j = 0, False, False, i
        while j < n:
            ch = text[j]
            if в_строке:
                if экран:
                    экран = False
                elif ch == '\\':
                    экран = True
                elif ch == '"':
                    в_строке = False
            elif ch == '"':
                в_строке = True
            elif ch == '{':
                глубина += 1
            elif ch == '}':
                глубина -= 1
                if глубина == 0:
                    куски.append(text[i:j + 1])
                    break
            j += 1
        i = (j + 1) if j < n else n
    return куски


_ХВОСТОВАЯ_ЗАПЯТАЯ = re.compile(r',\s*([}\]])')


def _починить_json(кусок: str) -> str:
    """Две типовые поломки ответа модели: хвостовая запятая и сырой перевод
    строки внутри строкового значения (тело письма многострочное, и модель
    иногда забывает \\n экранировать)."""
    вышло, в_строке, экран = [], False, False
    for ch in кусок:
        if в_строке:
            if экран:
                экран = False
            elif ch == '\\':
                экран = True
            elif ch == '"':
                в_строке = False
            elif ch in '\n\r\t':
                вышло.append({'\n': '\\n', '\r': '\\r', '\t': '\\t'}[ch])
                continue
        elif ch == '"':
            в_строке = True
        вышло.append(ch)
    return _ХВОСТОВАЯ_ЗАПЯТАЯ.sub(r'\1', ''.join(вышло))


def _parse_json(text: str, tag: str):
    куски = _куски_json(text or '')
    if not куски:
        raise ValueError(f'{tag}: нет JSON в ответе (ответ: {(text or "")[:160]!r})')
    разобранные, беда = [], None
    for кусок in куски:
        for вариант in (кусок, _починить_json(кусок)):
            try:
                значение = json.loads(вариант)
            except Exception as e:  # noqa: BLE001 - перебираем кандидатов
                беда = e
                continue
            if isinstance(значение, dict):
                разобранные.append((len(кусок), значение))
            break
    if not разобранные:
        raise ValueError(f'{tag}: JSON не разобран ({беда}); '
                         f'ответ: {(text or "")[:160]!r}')
    # Самый большой кусок — это полезная нагрузка, а не пример или эхо.
    return max(разобранные, key=lambda п: п[0])[1]


class AiLetterGen:
    """Генератор писем. caller: (prompt)->text — боевой провайдерский снаружи
    (sender.review_lenses.default_caller), в тестах фейк. Движок stdlib.

    facts — легаси-аргумент (факты КЦ). Для направленческой работы передавать
    facts_by_division={'kc': ..., 'meyer': ...}; чего нет — догрузится
    load_facts(division=...) и в худшем случае будет пустым фолбэком."""

    def __init__(self, caller: Callable[[str], str], facts: Optional[dict] = None,
                 batch: int = 4, rounds: int = 3, json_tries: int = 3,
                 facts_by_division: Optional[dict] = None,
                 default_division: str = 'kc', best_of: int = 1):
        self._call = caller
        self._facts: dict = dict(facts_by_division or {})
        if facts is not None:
            self._facts.setdefault('kc', facts)
        self.batch = max(1, batch)
        self.rounds = rounds
        self.json_tries = json_tries
        # best_of>1: N независимых вариантов каждого письма (разные механики
        # через сдвиг angle_base) + судья-редактор выбирает ближний к канону.
        # Директива владельца 28.07: «бюджет на письмо небольшой, если что-то
        # мешает качеству - можно увеличивать в разы».
        self.best_of = max(1, int(best_of))
        self.default_division = (default_division if default_division in RULES_BY_DIVISION
                                 else 'kc')

    def facts_for(self, division: str) -> dict:
        """Факты направления с ленивой загрузкой (файл читаем один раз)."""
        division = division if division in RULES_BY_DIVISION else 'kc'
        if division not in self._facts:
            self._facts[division] = load_facts(division=division)
        return self._facts[division]

    @property
    def facts(self) -> dict:      # обратная совместимость: gen.facts == факты КЦ
        return self.facts_for('kc')

    def _ask(self, prompt: str, tag: str):
        last = None
        for t in range(self.json_tries):
            try:
                return _parse_json(self._call(prompt), tag)
            except Exception as e:  # noqa: BLE001 - битый JSON/обрыв → ретрай
                last = f'{tag}: {e} (попытка {t + 1})'
        raise RuntimeError(last)

    def generate(self, recipients: list) -> AiLetterResult:
        """recipients: [{company_name, okved, activity, contact_name, mode, extra{},
        division|target_division|equip_categories}].
        mode: NEWS|GENERIC|auto (auto: NEWS если extra.news_object и extra.city).
        Направление письма — target_division() (см. приоритет в её докстринге)."""
        res = AiLetterResult()
        for r in recipients:
            if (r.get('mode') or 'auto') == 'auto':
                ex = r.get('extra') or {}
                r['mode'] = 'NEWS' if (ex.get('news_object') and ex.get('city')) else 'GENERIC'
        # направление считаем ДО генерации: от него зависят правила, факты,
        # глоссарий, пул новостных механик и гейт
        div_of: dict = {}
        for i, r in enumerate(recipients):
            d, why = target_division(r, default=self.default_division)
            div_of[i] = d
            r['_division'], r['_division_reason'] = d, why
            res.divisions[i] = (d, why)
        groups: dict = {}
        for i, d in div_of.items():
            groups.setdefault(d, []).append(i)

        letters: dict = {}
        rounds_log: dict = {i: [] for i in range(len(recipients))}
        # 1) генерация батчами ВНУТРИ направления (в одном промпте — одни правила)
        for div, idxs in groups.items():
            facts = self.facts_for(div)
            for n in range(0, len(idxs), self.batch):
                chunk = idxs[n:n + self.batch]
                # angle_base=n: ротация углов сквозная по направлению, а не
                # с нуля в каждой партии (§5б)
                data = self._ask(gen_prompt([recipients[i] for i in chunk],
                                            facts, div, angle_base=n),
                                 f'gen{div}{n}')
                res.calls += 1
                for L in data.get('letters', []):
                    # Ревью №20 (критично): idx вне диапазона батча раньше молча
                    # трактовался как ГЛОБАЛЬНЫЙ — письмо для одной компании
                    # попадало в слот ДРУГОЙ. Чужой idx отбраковываем: лид уйдёт
                    # в брак, но никогда не получит текст про чужой завод.
                    try:
                        li = int(L['idx'])
                    except (KeyError, TypeError, ValueError):
                        continue
                    if not (0 <= li < len(chunk)):
                        continue
                    gi = chunk[li]
                    letters[gi] = {'subject': str(L.get('subject', '')).strip(),
                                   'body': str(L.get('body', '')).strip()}
        # 1б) best-of-N (директива владельца 28.07: бюджет на письмо можно
        # кратно поднимать ради качества): ещё best_of-1 независимых заходов
        # (сдвиг angle_base назначает ДРУГУЮ механику - варианты реально
        # разные), затем судья-редактор выбирает ближний к канону 19.
        # Сбой доп-варианта или судьи не роняет письмо: остаётся вариант №0.
        if self.best_of > 1 and letters:
            cands: dict = {i: [dict(L)] for i, L in letters.items()}
            for att in range(1, self.best_of):
                for div, idxs in groups.items():
                    facts = self.facts_for(div)
                    for n in range(0, len(idxs), self.batch):
                        chunk = [i for i in idxs[n:n + self.batch]]
                        try:
                            data = self._ask(gen_prompt(
                                [recipients[i] for i in chunk], facts, div,
                                angle_base=n + att * 3), f'gen{div}{n}v{att}')
                        except RuntimeError:
                            continue
                        res.calls += 1
                        for L in data.get('letters', []):
                            try:
                                li = int(L['idx'])
                            except (KeyError, TypeError, ValueError):
                                continue
                            if not (0 <= li < len(chunk)):
                                continue
                            gi = chunk[li]
                            if gi in cands:
                                cands[gi].append(
                                    {'subject': str(L.get('subject', '')).strip(),
                                     'body': str(L.get('body', '')).strip()})
            for div, idxs in groups.items():
                mine = [i for i in idxs if len(cands.get(i) or []) > 1]
                for n in range(0, len(mine), 4):
                    part = mine[n:n + 4]
                    try:
                        data = self._ask(judge_prompt(
                            [(i, cands[i]) for i in part], div), f'jdg{div}{n}')
                    except RuntimeError:
                        continue
                    res.calls += 1
                    for ch in data.get('choices', []):
                        try:
                            i, k = int(ch['idx']), int(ch['pick'])
                        except (KeyError, TypeError, ValueError):
                            continue
                        if i in cands and 0 <= k < len(cands[i]):
                            letters[i] = cands[i][k]
        # 2) циклы: гейт -> верификатор -> fix
        for rnd in range(self.rounds + 1):
            bad: dict = {}
            for i, L in letters.items():
                div = div_of.get(i, self.default_division)
                # Ревью №28 разрешил числа из имени компании, но берёт их
                # ТОЛЬКО из `extra`. У партии, залитой со своим extra
                # (металлообработка, 05.08), имени там нет - и первое же письмо
                # ушло в брак за «непроверенные числа: ['65']», где 65 это
                # часть названия ООО «УПТК-65». Имя, контакт и город лежат в
                # самой записи получателя: подкладываем их в проверку, не
                # трогая белый список ЧИСЕЛ-фактов (_SAFE его не включает).
                _rec = recipients[i]
                _extra = dict(_rec.get('extra') or {})
                for _k in ('company_name', 'contact_name', 'city', 'domain', 'site'):
                    if not _extra.get(_k) and _rec.get(_k):
                        _extra[_k] = _rec[_k]
                fails = gate(L['subject'], L['body'], mode=_rec['mode'],
                             extra=_extra,
                             facts=self.facts_for(div), division=div)
                if fails:
                    bad[i] = fails
            clean = [i for i in letters if i not in bad]
            if clean and rnd < self.rounds:      # верификатор только до принуд. раунда
                for div in groups:
                    part_all = [i for i in clean if div_of.get(i) == div]
                    for n in range(0, len(part_all), 8):
                        part = part_all[n:n + 8]
                        data = self._ask(vf_prompt(
                            [(i, letters[i]['subject'], letters[i]['body']) for i in part],
                            div), f'vf{div}{rnd}-{n}')
                        res.calls += 1
                        for vd in data.get('verdicts', []):
                            if not vd.get('ok'):
                                # Ревью №26: битый/чужой idx вердикта не должен
                                # ронять батч — игнорируем такой вердикт.
                                try:
                                    _vi = int(vd['idx'])
                                except (KeyError, TypeError, ValueError):
                                    continue
                                if _vi not in letters:
                                    continue
                                bad[_vi] = vd.get('problems') or ['verify fail']
            # анти-штамп по партии — счётчики свои у каждого направления
            for div, idxs in groups.items():
                mine = [i for i in idxs if i in letters]
                over = stamp_overflow([letters[i]['body'] for i in mine], div)
                for i in mine:
                    for o in over:
                        rx = o.split(' (')[0]
                        if re.search('(?i)' + rx, letters[i]['body']) and i not in bad:
                            bad[i] = [f'анти-штамп: оборот израсходован: {o} — замени своим']
            # Квота на форму первой фразы: одна форма — не больше трети партии.
            # Помечаем в extra получателя, чтобы и промпт перегенерации, и гейт
            # знали, ЧТО именно повторять нельзя (владелец 12.08 — «заменить
            # запрет на квоту»).
            for div, idxs in groups.items():
                mine = [i for i in idxs if i in letters]
                for поз, форма in zahod_overflow(
                        [letters[i]['body'] for i in mine]).items():
                    i = mine[поз]
                    try:
                        recipients[i].setdefault('extra', {})['сменить_заход'] = форма
                    except (AttributeError, IndexError, KeyError, TypeError):
                        pass          # чужая структура получателя — не роняем партию
                    if i not in bad:
                        bad[i] = [f'заход «{форма}» израсходован на партии — '
                                  'начни иначе']
            for i, fails in bad.items():
                rounds_log[i].append({'round': rnd, 'fails': [str(f)[:160] for f in fails[:8]]})
            if not bad:
                break
            if rnd >= self.rounds:               # принудительный не помог
                for i, fails in bad.items():
                    res.rejected[i] = fails
                    letters.pop(i, None)
                break
            # ПРИНУДИТЕЛЬНЫЙ РАУНД. До 14.08 он требовал дословную строку
            # отказа - ту самую, которую редактор вычеркнула, а движок теперь
            # механически срезает. Модель её вписывала, zashit_kontsovku
            # удаляла, круги шли впустую. Теперь требуем то, что и правило 2.
            force = ('\nЖЁСТКО: письмо кончается СВОИМ вопросом, следом сразу '
                     '«С уважением,». Строки отказа («если тема неактуальна», '
                     '«больше не побеспокою») быть не должно.'
                     if rnd == self.rounds - 1 else '')
            for div in groups:
                ids = sorted(i for i in bad if div_of.get(i) == div)
                facts = self.facts_for(div)
                for n in range(0, len(ids), 4):
                    part = ids[n:n + 4]
                    blocks = []
                    for i in part:
                        blocks.append(f"=== ПИСЬМО #{i} [режим: {recipients[i]['mode']}]\n"
                                      f"ТЕМА: {letters[i]['subject']}\n{letters[i]['body']}\n"
                                      f"НАРУШЕНИЯ: {'; '.join(str(x) for x in bad[i][:6])}")
                    prompt = ("Доработай письма: устрани ПЕРЕЧИСЛЕННЫЕ нарушения, ничего не ломая."
                              + force + f"\n\n{RULES_BY_DIVISION[div]}\n\n"
                              + facts_block(facts, div) + "\n\n"
                              + 'ФОРМАТ: {"letters":[{"idx":N,"subject":"...","body":"..."}]}\n\n'
                              + "\n\n".join(blocks))
                    data = self._ask(prompt, f'fx{div}{rnd}-{n}')
                    res.calls += 1
                    for L in data.get('letters', []):
                        i = int(L['idx'])
                        if i in letters:
                            letters[i] = {'subject': str(L.get('subject', '')).strip(),
                                          'body': str(L.get('body', '')).strip()}
        # 3) ФИНАЛ: инженерные линзы техпроцесса (владелец 06.08 - «в конец
        # комбайна»). Технолог и скептик независимо; браку письмо отдаёт
        # только вердикт «ошибка» ЛЮБОЙ из линз - «сомнительно» не режем
        # (по прогону 274 писем спорных 16%, резать их значит убить выход;
        # оператор их и так читает). Одна попытка починки с претензией
        # линзы, после починки - повторный механический гейт и повторная
        # линза; не помогло - брак с причиной.
        self._teh_lens_stage(letters, recipients, div_of, res, rounds_log)
        # 4) Концовка — дословно и у каждого письма (владелец 06.08). Ставим
        # МЕХАНИЧЕСКИ, а не просьбой в промпте: правило 19и («назови
        # предприятие») модель игнорировала в трети писем, и починил его
        # только заслон в коде. Здесь то же самое, но мягче — не бракуем, а
        # приводим к канону.
        for i, L in letters.items():
            L['body'] = zashit_kontsovku(L.get('body', ''))
        for i, L in letters.items():
            d, why = res.divisions.get(i, (self.default_division, 'fallback'))
            res.ok[i] = {**L, 'rounds': rounds_log.get(i, []),
                         'division': d, 'division_reason': why}
        return res

    def _teh_lens_verdicts(self, ids: list, letters: dict, recipients: dict,
                           div_of: Optional[dict] = None) -> dict:
        """{idx: (verdict, претензия)} - худший вердикт двух линз по письму.

        Партии режем ещё и ПО НАПРАВЛЕНИЮ: у компрессорного и у Meyer разные
        технологические связки, и общий промпт компрессорной линзы бракует все
        письма Meyer подряд («нет утверждения про сжатый воздух»)."""
        порядок = {'верно': 0, 'сомнительно': 1, 'ошибка': 2}
        div_of = div_of or {}
        итог: dict = {}
        по_напр: dict = {}
        for i in ids:
            d = str(div_of.get(i) or self.default_division)
            по_напр.setdefault('meyer' if d.startswith('meyer') else 'kc',
                               []).append(i)
        for направление, свои in по_напр.items():
            for lens in ('технолог', 'скептик'):
                for n in range(0, len(свои), 3):
                    part = свои[n:n + 3]
                    items = []
                    for i in part:
                        r = recipients[i]
                        _пасп = ((r.get('extra') or {}).get('site_facts')
                                 or {})
                        _куски = []
                        for _к in ('продукция', 'сырьё', 'мощности',
                                   'упаковка_фасовка', 'расширение'):
                            _v = _пасп.get(_к) if isinstance(_пасп, dict) else None
                            if isinstance(_v, str):
                                _v = [_v]
                            if _v:
                                _куски.append(
                                    f"{_к}: " + '; '.join(str(x) for x in _v[:8]))
                        items.append((i, str(r.get('company_name') or ''),
                                      str(r.get('activity') or ''),
                                      str(r.get('okved') or ''),
                                      letters[i]['subject'], letters[i]['body'],
                                      ' | '.join(_куски)[:700]))
                    try:
                        data = self._ask(
                            teh_lens_prompt(items, lens, направление),
                            f'teh{lens[:4]}{направление[:2]}{n}')
                    except RuntimeError:
                        continue
                    for vd in data.get('verdicts', []):
                        try:
                            vi = int(vd['idx'])
                        except (KeyError, TypeError, ValueError):
                            continue
                        if vi not in letters:
                            continue
                        v = str(vd.get('verdict') or '').strip().lower()
                        if v not in порядок:
                            continue
                        старое = итог.get(vi)
                        if старое is None or порядок[v] > порядок[старое[0]]:
                            итог[vi] = (v, str(vd.get('chto_ne_tak') or '')[:200])
        return итог

    def _teh_lens_stage(self, letters, recipients, div_of, res, rounds_log):
        if os.environ.get('AI_LETTER_TEH_LENS', '1') == '0':
            return
        ids = sorted(letters)
        if not ids:
            return
        верд = self._teh_lens_verdicts(ids, letters, recipients, div_of)
        res.calls += 1
        плохие = {i: п for i, (v, п) in верд.items() if v == 'ошибка'}
        for i, (v, п) in верд.items():
            if v != 'верно':
                rounds_log[i].append({'round': 'техлинза', 'verdict': v,
                                      'fails': [п][:1] if п else []})
        if not плохие:
            return
        # одна попытка починки: та же машинерия, что у fix-раундов
        for n in range(0, len(sorted(плохие)), 4):
            part = sorted(плохие)[n:n + 4]
            blocks = []
            for i in part:
                div = div_of.get(i, self.default_division)
                blocks.append(f"=== ПИСЬМО #{i} [режим: {recipients[i]['mode']}]\n"
                              f"ТЕМА: {letters[i]['subject']}\n{letters[i]['body']}\n"
                              f"НАРУШЕНИЕ (инженерная линза): {плохие[i]}")
            div = div_of.get(part[0], self.default_division)
            prompt = ("Доработай письма: технологическая связка инженерно неверна "
                      "для производства получателя - перепиши её на честную и "
                      "нейтральную (или убери конкретику, оставив общий заход), "
                      "ничего больше не ломая.\n\n"
                      + RULES_BY_DIVISION[div] + "\n\n"
                      + facts_block(self.facts_for(div), div) + "\n\n"
                      + 'ФОРМАТ: {"letters":[{"idx":N,"subject":"...","body":"..."}]}\n\n'
                      + "\n\n".join(blocks))
            try:
                data = self._ask(prompt, f'tehfx{n}')
                res.calls += 1
            except RuntimeError:
                continue
            for L in data.get('letters', []):
                try:
                    i = int(L['idx'])
                except (KeyError, TypeError, ValueError):
                    continue
                if i in letters:
                    letters[i] = {'subject': str(L.get('subject', '')).strip(),
                                  'body': str(L.get('body', '')).strip()}
        # починенные - через механический гейт и повторную линзу
        осталось = []
        for i in sorted(плохие):
            if i not in letters:
                continue
            r = recipients[i]
            extra = dict(r.get('extra') or {})
            for k in ('company_name', 'contact_name', 'city', 'domain', 'site'):
                if not extra.get(k) and r.get(k):
                    extra[k] = r[k]
            div = div_of.get(i, self.default_division)
            fails = gate(letters[i]['subject'], letters[i]['body'], mode=r['mode'],
                         extra=extra, facts=self.facts_for(div), division=div)
            if fails:
                res.rejected[i] = fails
                rounds_log[i].append({'round': 'техлинза-fix', 'fails':
                                      [str(f)[:160] for f in fails[:6]]})
                letters.pop(i, None)
            else:
                осталось.append(i)
        if not осталось:
            return
        верд2 = self._teh_lens_verdicts(осталось, letters, recipients, div_of)
        res.calls += 1
        for i in осталось:
            v, п = верд2.get(i, ('верно', ''))
            if v == 'ошибка':
                res.rejected[i] = [f'инженерная линза после починки: {п}']
                rounds_log[i].append({'round': 'техлинза-повтор', 'fails': [п]})
                letters.pop(i, None)


