# лимиты на 49 писем (спека §6), масштабируются пропорционально размеру партии
STAMP_LIMITS_PER49 = {
    r'частый случай|такая история|похожая ситуация': 4,
    r'судя по профилю': 3,
    r'смотрел\w*\s+(ваш|профиль|сайт|чем занима)': 3,
    r'посмотрел\w*\s+(ваш|профиль|сайт|чем занима)': 2,
    r'рано или поздно': 3,
    r'бьёт по': 3, r'встаёт вопрос': 4, r'под контролем': 5,
}

# Свои штампы направления Meyer: обороты, которые модель тиражирует из правил
# и глоссария (проверено на КЦ: первым выгорает язык самих правил).
STAMP_LIMITS_PER49_MEYER = {
    r'частый случай|такая история|похожая ситуация': 4,
    r'судя по профилю': 3,
    r'смотрел\w*\s+(ваш|профиль|сайт|чем занима)': 3,
    r'посмотрел\w*\s+(ваш|профиль|сайт|чем занима)': 2,
    r'рано или поздно': 3,
    r'посторонн\w+ включени|инородн\w+ включени': 4,
    r'пищев\w+ безопасност': 3, r'контрол\w* качества': 4,
    r'ручн\w+ переборк': 4, r'рекламац': 3, r'на всякий случай': 3,
}
STAMP_LIMITS_BY_DIVISION = {'kc': STAMP_LIMITS_PER49,
                            'meyer': STAMP_LIMITS_PER49_MEYER}


def stamp_overflow(bodies: list, division: str = 'kc') -> list:
    """Какие обороты израсходованы на партии (для перефраз-вызова)."""
    limits = STAMP_LIMITS_BY_DIVISION.get(division or 'kc', STAMP_LIMITS_PER49)
    n = max(1, len(bodies))
    out = []
    for rx, lim in limits.items():
        limit = max(1, round(lim * n / 49))
        cnt = sum(1 for b in bodies if re.search('(?i)' + rx, b))
        if cnt > limit:
            out.append(f'{rx} ({cnt}>{limit})')
    return out


# --- квота на форму первой фразы -------------------------------------------- #
# Жёсткий запрет одного захода проблему не решает, а двигает: 12.08 запретили
# «Смотрел профиль…» - и модель выдала новый штамп, 37% партии начались с «На».
# Плохо не то, ЧТО написано первой фразой, а то, что вся партия начинается
# одинаково. Поэтому считаем не слова, а ФОРМУ зачина, и держим квоту: одна
# форма - не больше трети партии, лишние идут на перегенерацию.
_ФОРМЫ_ЗАХОДА = (
    # Запятая после глагола («Посмотрел, чем занимается») — та же форма,
    # поэтому разделитель [\s,]+, а не \s+.
    ('от профиля', r'^\W*((по)?смотрел\w*|изучил\w*|глянул\w*|видел\w*|'
                   r'ознакомил\w*)[\s,]+(ваш|профиль|сайт|чем занима|'
                   r'что делает|производств)|^\W*судя по (профил|сайт|описан)|'
                   r'^\W*профиль ваш'),
    ('от вопроса', r'^\W*(подскажите|скажите|вопрос|интересно)'),
    ('от условия', r'^\W*(если|когда|пока)\s'),
    ('от отрасли', r'^\W*(производств|обработк|изготовлен|компани|'
                   r'предприяти|завод)'),
    ('от площадки', r'^\W*(на|в|при|у)\s'),
)


def _первая_фраза(body: object) -> str:
    """Первая содержательная строка: приветствие не в счёт."""
    for стр in str(body or '').split('\n'):
        стр = стр.strip()
        if стр and not re.match(r'(?i)^(добрый день|здравствуйте|доброе утро|'
                                r'добрый вечер)', стр):
            return стр
    return ''


def форма_захода(body: object) -> str:
    """Как письмо заходит. Незнакомый заход опознаём по первым двум словам -
    иначе квота ловила бы только те формы, которые я успел перечислить."""
    первая = _первая_фраза(body)
    if not первая:
        return ''
    for имя, rx in _ФОРМЫ_ЗАХОДА:
        if re.search('(?i)' + rx, первая):
            return имя
    слова = re.findall(r'[а-яёa-z]+', первая.lower())
    return ' '.join(слова[:2]) if слова else ''


def zahod_overflow(bodies: list, доля: float = 0.34) -> dict:
    """Кто в партии обязан сменить заход. {индекс письма: форма}.

    Первые письма квоту занимают и остаются как есть, лишние помечаются -
    так перегенерация касается меньшинства, а не всей партии.
    """
    предел = max(1, int(len(bodies) * доля))
    видано: dict = {}
    лишние: dict = {}
    for i, тело in enumerate(bodies):
        ф = форма_захода(тело)
        if not ф:
            continue
        видано[ф] = видано.get(ф, 0) + 1
        if видано[ф] > предел:
            лишние[i] = ф
    return лишние


