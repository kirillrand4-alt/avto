@dataclass
class AiLetterResult:
    ok: dict = field(default_factory=dict)      # idx -> {subject, body, rounds, division}
    rejected: dict = field(default_factory=dict)  # idx -> [причины]
    divisions: dict = field(default_factory=dict)  # idx -> (division, reason)
    calls: int = 0


def _parse_json(text: str, tag: str):
    m = re.search(r'\{.*\}', text or '', re.S)
    if not m:
        raise ValueError(f'{tag}: нет JSON в ответе')
    return json.loads(m.group(0))


class AiLetterGen:
    """Генератор писем. caller: (prompt)->text — боевой провайдерский снаружи
    (sender.review_lenses.default_caller), в тестах фейк. Движок stdlib.

    facts — легаси-аргумент (факты КЦ). Для направленческой работы передавать
    facts_by_division={'kc': ..., 'meyer': ...}; чего нет — догрузится
    load_facts(division=...) и в худшем случае будет пустым фолбэком."""

    def __init__(self, caller: Callable[[str], str], facts: Optional[dict] = None,
                 batch: int = 4, rounds: int = 3, json_tries: int = 3,
                 facts_by_division: Optional[dict] = None,
                 default_division: str = 'kc'):
        self._call = caller
        self._facts: dict = dict(facts_by_division or {})
        if facts is not None:
            self._facts.setdefault('kc', facts)
        self.batch = max(1, batch)
        self.rounds = rounds
        self.json_tries = json_tries
        self.default_division = (default_division if default_division in RULES_BY_DIVISION
                                 else 'kc')

    def facts_for(self, division: str) -> dict:
        """Факты направления с ленивой загрузкой (файл читаем один раз)."""
        division = division if division in RULES_BY_DIVISION else 'kc'
        if division not in self._facts:
            self._facts[division] = load_facts(division=division)
        return self._facts[division]

    @property
    def facts(self) -> dict:      # обратная совместимость: gen.facts == факты КЦ
        return self.facts_for('kc')

    def _ask(self, prompt: str, tag: str):
        last = None
        for t in range(self.json_tries):
            try:
                return _parse_json(self._call(prompt), tag)
            except Exception as e:  # noqa: BLE001 - битый JSON/обрыв → ретрай
                last = f'{tag}: {e} (попытка {t + 1})'
        raise RuntimeError(last)

    def generate(self, recipients: list) -> AiLetterResult:
        """recipients: [{company_name, okved, activity, contact_name, mode, extra{},
        division|target_division|equip_categories}].
        mode: NEWS|GENERIC|auto (auto: NEWS если extra.news_object и extra.city).
        Направление письма — target_division() (см. приоритет в её докстринге)."""
        res = AiLetterResult()
        for r in recipients:
            if (r.get('mode') or 'auto') == 'auto':
                ex = r.get('extra') or {}
                r['mode'] = 'NEWS' if (ex.get('news_object') and ex.get('city')) else 'GENERIC'
        # направление считаем ДО генерации: от него зависят правила, факты,
        # глоссарий, пул новостных механик и гейт
        div_of: dict = {}
        for i, r in enumerate(recipients):
            d, why = target_division(r, default=self.default_division)
            div_of[i] = d
            r['_division'], r['_division_reason'] = d, why
            res.divisions[i] = (d, why)
        groups: dict = {}
        for i, d in div_of.items():
            groups.setdefault(d, []).append(i)

        letters: dict = {}
        rounds_log: dict = {i: [] for i in range(len(recipients))}
        # 1) генерация батчами ВНУТРИ направления (в одном промпте — одни правила)
        for div, idxs in groups.items():
            facts = self.facts_for(div)
            for n in range(0, len(idxs), self.batch):
                chunk = idxs[n:n + self.batch]
                # angle_base=n: ротация углов сквозная по направлению, а не
                # с нуля в каждой партии (§5б)
                data = self._ask(gen_prompt([recipients[i] for i in chunk],
                                            facts, div, angle_base=n),
                                 f'gen{div}{n}')
                res.calls += 1
                for L in data.get('letters', []):
                    # Ревью №20 (критично): idx вне диапазона батча раньше молча
                    # трактовался как ГЛОБАЛЬНЫЙ — письмо для одной компании
                    # попадало в слот ДРУГОЙ. Чужой idx отбраковываем: лид уйдёт
                    # в брак, но никогда не получит текст про чужой завод.
                    try:
                        li = int(L['idx'])
                    except (KeyError, TypeError, ValueError):
                        continue
                    if not (0 <= li < len(chunk)):
                        continue
                    gi = chunk[li]
                    letters[gi] = {'subject': str(L.get('subject', '')).strip(),
                                   'body': str(L.get('body', '')).strip()}
        # 2) циклы: гейт -> верификатор -> fix
        for rnd in range(self.rounds + 1):
            bad: dict = {}
            for i, L in letters.items():
                div = div_of.get(i, self.default_division)
                fails = gate(L['subject'], L['body'], mode=recipients[i]['mode'],
                             extra=recipients[i].get('extra'),
                             facts=self.facts_for(div), division=div)
                if fails:
                    bad[i] = fails
            clean = [i for i in letters if i not in bad]
            if clean and rnd < self.rounds:      # верификатор только до принуд. раунда
                for div in groups:
                    part_all = [i for i in clean if div_of.get(i) == div]
                    for n in range(0, len(part_all), 8):
                        part = part_all[n:n + 8]
                        data = self._ask(vf_prompt(
                            [(i, letters[i]['subject'], letters[i]['body']) for i in part],
                            div), f'vf{div}{rnd}-{n}')
                        res.calls += 1
                        for vd in data.get('verdicts', []):
                            if not vd.get('ok'):
                                # Ревью №26: битый/чужой idx вердикта не должен
                                # ронять батч — игнорируем такой вердикт.
                                try:
                                    _vi = int(vd['idx'])
                                except (KeyError, TypeError, ValueError):
                                    continue
                                if _vi not in letters:
                                    continue
                                bad[_vi] = vd.get('problems') or ['verify fail']
            # анти-штамп по партии — счётчики свои у каждого направления
            for div, idxs in groups.items():
                mine = [i for i in idxs if i in letters]
                over = stamp_overflow([letters[i]['body'] for i in mine], div)
                for i in mine:
                    for o in over:
                        rx = o.split(' (')[0]
                        if re.search('(?i)' + rx, letters[i]['body']) and i not in bad:
                            bad[i] = [f'анти-штамп: оборот израсходован: {o} — замени своим']
            for i, fails in bad.items():
                rounds_log[i].append({'round': rnd, 'fails': [str(f)[:160] for f in fails[:8]]})
            if not bad:
                break
            if rnd >= self.rounds:               # принудительный не помог
                for i, fails in bad.items():
                    res.rejected[i] = fails
                    letters.pop(i, None)
                break
            force = ('\nЖЁСТКО: предпоследняя строка тела - ДОСЛОВНО «Если неактуально - '
                     'извините за письмо, больше не побеспокою.»' if rnd == self.rounds - 1 else '')
            for div in groups:
                ids = sorted(i for i in bad if div_of.get(i) == div)
                facts = self.facts_for(div)
                for n in range(0, len(ids), 4):
                    part = ids[n:n + 4]
                    blocks = []
                    for i in part:
                        blocks.append(f"=== ПИСЬМО #{i} [режим: {recipients[i]['mode']}]\n"
                                      f"ТЕМА: {letters[i]['subject']}\n{letters[i]['body']}\n"
                                      f"НАРУШЕНИЯ: {'; '.join(str(x) for x in bad[i][:6])}")
                    prompt = ("Доработай письма: устрани ПЕРЕЧИСЛЕННЫЕ нарушения, ничего не ломая."
                              + force + f"\n\n{RULES_BY_DIVISION[div]}\n\n"
                              + facts_block(facts, div) + "\n\n"
                              + 'ФОРМАТ: {"letters":[{"idx":N,"subject":"...","body":"..."}]}\n\n'
                              + "\n\n".join(blocks))
                    data = self._ask(prompt, f'fx{div}{rnd}-{n}')
                    res.calls += 1
                    for L in data.get('letters', []):
                        i = int(L['idx'])
                        if i in letters:
                            letters[i] = {'subject': str(L.get('subject', '')).strip(),
                                          'body': str(L.get('body', '')).strip()}
        for i, L in letters.items():
            d, why = res.divisions.get(i, (self.default_division, 'fallback'))
            res.ok[i] = {**L, 'rounds': rounds_log.get(i, []),
                         'division': d, 'division_reason': why}
        return res


