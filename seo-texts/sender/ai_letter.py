def _прибрать(текст: str) -> str:
    """Дырки от удалённых строк убрать, но абзацный отступ перед подписью и
    перед концовкой СОХРАНИТЬ.

    Первая версия схлопывала пустые строки скопом — и концовка прилипала к
    «С уважением,» одним абзацем. Разделение абзацев здесь смысловое: письмо
    читают глазами, слипшийся хвост выглядит обрывком.
    """
    текст = re.sub(r'[ \t]*\n[ \t]*\n[ \t]*\n+', '\n\n', текст)
    канон = re.escape(KONTSOVKA)
    текст = re.sub(r'\n+(?=' + канон + r')', '\n\n', текст)
    текст = re.sub(канон + r'\n+(?=С уважением)', KONTSOVKA + '\n\n', текст)
    return текст.rstrip()


def zashit_kontsovku(body: str) -> str:
    """Привести концовку письма к канону. Идемпотентно.

    Три случая, все встречаются в живой очереди:
      * есть строка отказа в старой формулировке -> заменяем целиком;
      * строки нет вовсе (модель её пропустила) -> вставляем перед финалом;
      * канон уже стоит -> ничего не меняем.
    Финал «С уважением,» остаётся последней строкой: на него смотрит гейт.
    """
    текст = (body or '').rstrip()
    if not текст:
        return body
    if _СТАРЫЙ_ОТКАЗ_RE.search(текст):
        # первое вхождение -> канон, остальные строки отказа убираем совсем:
        # «извините за письмо» + «больше не побеспокою» двумя строками подряд
        # встречается в живой очереди, и оставить второй хвост нельзя
        счёт = {'n': 0}

        def _замена(m):
            счёт['n'] += 1
            return KONTSOVKA if счёт['n'] == 1 else ''

        текст = _СТАРЫЙ_ОТКАЗ_RE.sub(_замена, текст)
        return _прибрать(текст)
    if KONTSOVKA in текст:
        return _прибрать(текст)          # канон стоит — только выправить отступы
    абзацы = текст.split('\n\n')
    финал = абзацы[-1].strip()
    if финал.startswith('С уважением'):
        абзацы.insert(len(абзацы) - 1, KONTSOVKA)
    else:
        абзацы.append(KONTSOVKA)
    return '\n\n'.join(абзацы).rstrip()
