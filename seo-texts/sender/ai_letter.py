def target_division(rec: dict, default: str = 'kc') -> tuple:
    """Какое направление писать этому получателю → (division, reason).

    Приоритет (задача 43; для компаний «kc+meyer» это и есть правило выбора
    товара, полностью описано в README патча):
      1. explicit   — оператор/кампания задали target_division (ai_division);
      2. news       — новостной повод однозначно про одно направление;
      3. needs      — колонка потребностей «Все категории оборудования»;
      4. base_label — метка базы обзвона (составная не решает);
      5. profile    — ОКВЭД и описание деятельности;
      6. fallback   — kc (79% базы, и только у КЦ есть проверяемые счётчики).
    Новость выше потребностей осознанно: заход письма строится на событии, и
    писать про компрессоры под новость о линии сортировки - абсурд. Случай
    «новость про одно, потребность про другое» помечается reason=news_over_needs
    и виден оператору в очереди подтверждений.
    """
    explicit = norm_division(_rec_field(rec, 'target_division', 'ai_division'))
    if explicit:
        return explicit, 'explicit'

    ex = rec.get('extra') or {}
    news_hit = set()
    if str(rec.get('mode') or '').upper() == 'NEWS':
        news_text = ' '.join(str(ex.get(k) or '') for k in
                             ('news_object', 'news_title', 'news_text',
                              'news_summary', 'news_topic'))
        news_hit = _markers_hit(news_text, _NEWS_MARKERS)

    needs = divisions_by_equipment(
        _rec_field(rec, 'equip_categories', 'equipment', 'equipment_all'))

    if len(news_hit) == 1:
        d = next(iter(news_hit))
        return d, ('news_over_needs' if needs and d not in needs else 'news')
    if len(needs) == 1:
        return next(iter(needs)), 'needs'

    label = divisions_of(_rec_field(rec, 'division', 'segment', 'base_label'))
    if len(label) == 1:
        return next(iter(label)), 'base_label'

    profile = _markers_hit(
        ' '.join(str(_rec_field(rec, k) or '') for k in ('okved', 'activity',
                                                         'okved_main', 'profile')),
        _PROFILE_MARKERS)
    if len(profile) == 1:
        return next(iter(profile)), 'profile'

    d = default if default in RULES_BY_DIVISION else 'kc'
