def _predpriyatie_nazvano(name: object, domain: object, text: str):
    """Названо ли предприятие в письме. None = судить нечем (нет своего имени).

    Правило 19и просило называть компанию, и МОДЕЛЬ ЕГО НЕ ИСПОЛНЯЕТ: на партии
    05.08 без имени было 9 писем из 27 до правила и 6 из 22 после - разницы
    нет. Правило в промпте это просьба, заслон в гейте это заслон.

    Матчер намеренно снисходительный: примерка на 49 письмах показала, что
    строгий вариант заворачивает хорошие письма (7 ложных из 16). Считаем
    названным, если есть слово имени от 3 знаков, ОСНОВА длинного слова
    (падеж: «ГАЗСТРОЙ» -> «в Газстрое»), аббревиатура из первых букв или
    латинское имя из домена.
    """
    words = [w for w in re.findall(r'[А-ЯЁA-Z][А-ЯЁA-Zа-яёa-z\-]{1,}',
                                   str(name or '').upper())
             if w not in _ИМЯ_ШУМ and len(w) >= 2]
    if not words:
        return None
    up = text.upper()
    for w in words:
        if len(w) >= 3 and w in up:
            return True
        if len(w) >= 6 and w[:len(w) - 2] in up:
            return True
    abbr = ''.join(w[0] for w in words)[:6]
    if len(abbr) >= 3 and re.search(r'\b' + re.escape(abbr) + r'\b', up):
        return True
    latin = re.sub(r'^(www\.)?', '', str(domain or '')).split('.')[0].upper()
    if len(latin) >= 4 and latin in up:
        return True
    return False


def gate(subject: str, body: str, *, mode: str = 'GENERIC',
         extra: Optional[dict] = None, facts: Optional[dict] = None,
         division: str = 'kc') -> list:
    """Механический гейт письма. [] = чисто. Порядок и регексы — спека §3,
    плюс проверка перекрёстной лексики направления (задача 43)."""
    facts = facts or {}
    division = division if division in RULES_BY_DIVISION else 'kc'
    fails: list = []
    text = subject + '\n' + body
    for rx, name in SUBJ_RE:
        if re.search(rx, subject):
            fails.append(f'{name}: «{subject}»')
    # канон редактора (19а): «Вопрос по расширению … в «Компании»» - до 10
    # слов по правилу, гейт даёт люфт до 12 (название компании из двух слов).
    if len(subject.split()) > 12:
        fails.append(f'тема длинная ({len(subject.split())} слов)')
    for m in re.finditer(r'(\d[\d,\.]*)\s*%', body):
        if m.group(1).split(',')[0].split('.')[0] not in ('97', '99', '95'):
            fails.append(f'проценты: {m.group(0)}')
    # Служебный текст ловим у ОБОИХ направлений: утечка инструкции
    # модели ничем не связана с тем, про воздух письмо или про
    # сортировку.
    заслоны = STOP_RE + SLUZHEBNOE_V_TELE + CROSS_LEX[division]
    # Рентген-письмо не имеет права называть находкой то, чего детектор не
    # видит. Включаем заслон по САМОМУ ТЕКСТУ, а не по направлению: у
    # фотосепаратора щепка и деревяшка в зерновом потоке — законная задача
    # сортировки, и запрещать их всему Meyer было бы неверно.
    if str(division or '').startswith('meyer') and re.search(r'(?i)рентген', body):
        заслоны = заслоны + NEVIDIMOE_RENTGENOM
    if str(division or '').startswith('meyer'):
        заслоны = заслоны + STRASHILKI_MEYER + PRAVKI_REDAKTORA_1408
        fails.extend(_vozdukh_ne_po_delu(body))
        fails.extend(_kultury_zontik_i_perechen(body))
        fails.extend(_tavtologiya_v_predlozhenii(body))
