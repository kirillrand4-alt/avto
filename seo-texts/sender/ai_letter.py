def norm_division(raw: object) -> Optional[str]:
    """Свободный текст направления → kc|meyer|None. Составное («kc+meyer»)
    осознанно даёт None: одно письмо = один товар, выбор делает
    target_division() по приоритету."""
    s = str(raw or '').strip().lower()
    if not s or '+' in s or ',' in s:
        return None
    if 'meyer' in s or 'мейер' in s or 'мейр' in s or 'мейєр' in s:
        return 'meyer'
    if s in ('kc', 'кц') or 'компрессор' in s or 'kc' in s or 'кц' in s:
        return 'kc'
    return None


