def _equipment_hint(raw: object, division: str) -> str:
    """Подсказка «оборудование по профилю» без товаров ЧУЖОГО направления.
    У 23709 компаний Meyer-сегмента в колонке лежат и компрессоры: показать их
    в meyer-письме значит самому подложить модели перекрёстную лексику."""
    text = str(raw or '').strip()
    if not text:
        return ''
    alien = [k for d, keys in _EQUIP_MARKERS.items() if d != division for k in keys]
    parts = [p.strip() for p in re.split(r'[,;/|]|\sи\s', text) if p.strip()]
    return ', '.join(p for p in parts if not any(k in p.lower() for k in alien))


def _сдвиг_механики(ex: dict) -> int:
    """Дополнительный сдвиг ротации заходов, если он задан в extra.

    Ротация считается от МЕСТА письма в партии, и это верно для массового
    прогона. Но перегенерация идёт по одному письму: партия из единицы, место
    всегда нулевое — и каждое перегенерированное письмо получало бы одну и ту
    же, первую механику. Тогда мы просто меняем один штамп на другой.
    Перегенерация кладёт сюда номер письма очереди, и заходы снова расходятся.
    """
    try:
        return abs(int((ex or {}).get('angle_shift') or 0))
    except (TypeError, ValueError):
        return 0


def _recipient_block(i: int, rec: dict, division: str = 'kc',
                     angle_base: int = 0) -> str:
    mode = rec.get('mode') or 'GENERIC'
    lines = [f"=== ПОЛУЧАТЕЛЬ #{i} [режим: {mode}]",
             f"Компания: {rec.get('company_name') or '(нет названия)'}",
             f"ОКВЭД/профиль: {rec.get('okved') or ''} {rec.get('activity') or ''}".strip()]
    # ГОТОВОЕ КОРОТКОЕ ИМЯ. В карточку едет юридическое имя из ЕГРЮЛ капсом, и
    # на неудобных («КАСИМОВСКИЙ КАРТОФЕЛЕПЕРЕРАБАТЫВАЮЩИЙ КОМБИНАТ») модель
    # уходила от названия вовсе — два письма из двенадцати 13.08 забракованы
    # правилом 19и. Просить «пиши кратко» мало, надо дать строку.
    _кратко = короткое_имя(rec.get('company_name'))
    if _кратко:
        lines.append(f"КАК НАЗЫВАТЬ В ПИСЬМЕ: «{_кратко}» (падеж по фразе). Это "
                     "имя ОБЯЗАНО встретиться в письме хотя бы раз — в теме "
                     "или в начале второго абзаца. Письмо без названия "
                     "получателя бракуется.")
    ex = rec.get('extra') or {}
    # НАДЁЖНОСТЬ ИМЕНИ. Имя в карточке — ещё не повод обращаться по имени.
    # Сессия обогащения 11.08 замерила: у четверти контактов ссылка-источник
    # уже не открывается, то есть перепроверить имя нечем. Именное приветствие
    # разрешаем только когда контакт снят с СОБСТВЕННОГО сайта компании и есть
    # живая ссылка на страницу. Ошибиться именем в холодном письме дороже, чем
    # написать «Добрый день!»: это первое, что читает человек.
    источник = str(ex.get('contact_source') or '').strip().lower()
    ссылка = str(ex.get('contact_source_url') or '').strip()
    # Значения источника — из разметки сессии обогащения (11.08). Первая
    # редакция правила ждала «own-site» и отвергла бы ВСЕ имена: таких значений
    # в базе нет вовсе. Собственный сайт — это enrich, mass, panel-run*,
    # recheck и own-site*; чужие сборники (checko:contacts — 3308 адресов,
    # сайт:справочник, zakupki:eis, краул-соседа) именем ручаться не могут.
    # zenno (14.08, слово владельца): «самый современный обход, он будет у
    # всех». Метка ставится обходом ПО САЙТУ КОМПАНИИ и приходит со ссылкой на
    # страницу — то есть по надёжности это тот же собственный сайт. Без неё
    # 1412 контактов с живыми ссылками уходили бы в письма безымянными.
    СВОЙ_САЙТ = ('own-site', 'enrich', 'mass', 'panel-run', 'recheck', 'zenno')
    ЧУЖОЙ_СБОРНИК = ('checko:', 'сайт:справочник', 'zakupki:', 'краул-соседа')
    свой_сайт = (источник.startswith(СВОЙ_САЙТ)
                 and not источник.startswith(ЧУЖОЙ_СБОРНИК))
    имя_надёжно = bool(rec.get('contact_name')) and свой_сайт and bool(ссылка)
    if имя_надёжно:
        lines.append(f"Контакт: {rec['contact_name']} (можно именное приветствие)")
    elif rec.get('contact_name'):
        lines.append(f"Контакт: {rec['contact_name']}, но источник имени "
                     "ненадёжен — приветствие строго «Добрый день!», имя НЕ "
                     "упоминать")
    else:
        lines.append("Контакт: нет имени — приветствие строго «Добрый день!», без имён")
    # КОНТАКТ С ЧУЖОГО САЙТА. Адрес снят со страницы, которую эта компания
    # своей может не считать (общий сайт холдинга). Про «ваш сайт» в таком
    # письме говорить нельзя — получатель не узнает у себя ни страницу, ни
    # текст, и письмо превращается в очевидную рассылку.
    # ЧЕМ ДОКАЗАН САЙТ. Сессия обогащения 11.08 замерила: у 7943 компаний из
    # 14166 в колонке verified стоит NULL. Это «не смотрели», а НЕ «доказано,
    # что сайт чужой», — разница принципиальная, и запрет на пустоту
    # распространять нельзя: иначе персонализация выключится у большинства.
    доказан = str(ex.get('verified') or '').strip().lower()
    if доказан in ('inn', 'ogrn', 'base+serp'):
        pass                       # сайт доказан — данные с него можно брать
    elif доказан in ('phone', 'provider'):
        lines.append("ОСТОРОЖНО С САЙТОМ: принадлежность сайта компании "
                     "доказана слабо. Данные использовать можно, но НЕ писать "
                     "«на вашем сайте указано…» и ничего не цитировать.")
    elif доказан in ('спорно', 'mismatch'):
        lines.append("САЙТ НЕ ДОКАЗАН: он может принадлежать другой компании. "
                     "Персонализацию по сайту НЕ строить — вести письмо от "
                     "отрасли и размера бизнеса.")
    if источник.startswith('краул-соседа'):
        lines.append("ВНИМАНИЕ: адрес взят с ЧУЖОГО сайта (общий сайт группы). "
                     "Не ссылаться на «ваш сайт», не цитировать его и не "
                     "упоминать сайт вовсе — вести письмо от отрасли и роли.")
    # §7а: кому пишем — от роли зависит, о чём говорить
    role = str(ex.get('role') or '').strip().lower()
    if role in ROLE_ANGLES:
        lines.append(f"РОЛЬ АДРЕСАТА: {role}. {ROLE_ANGLES[role]}")
