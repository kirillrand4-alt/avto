def _представление_ok(m: 're.Match', text: str, division: object) -> bool:
    """Слово «Руспром» в первой строке — это представление, а не подпись.

    Заслон «подпись в теле» стоял на «Руспром», и это было верно, пока подпись
    целиком дописывал движок. Канон редактора (13.08) требует другого: письмо
    Meyer начинается с «Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю компанию
    „Руспром Meyer“…». Гейт браковал ровно то, что просит промпт — четыре
    перегенерации подряд ушли в «подпись в теле».

    Разрешаем только эту конструкцию и только у Meyer: строка со словом должна
    нести «представляю» или «меня зовут». Подпись внизу («С уважением, … ООО
    „Руспром“, ИНН …») такой строки не имеет и по-прежнему бракуется, как и
    сайты с ИНН в любом месте — они в том же правиле отдельными вариантами.
    """
    if not str(division or '').startswith('meyer'):
        return False
    if not re.match(r'(?i)руспром', text[m.start():m.end()]):
        return False          # сайт/ИНН — не представление, бракуем как раньше
    нач = text.rfind('\n', 0, m.start()) + 1
    кон = text.find('\n', m.start())
    строка = text[нач:кон if кон >= 0 else len(text)]
    return bool(re.search(r'(?i)представля[юе]|меня зовут', строка))


