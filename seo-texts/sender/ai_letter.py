def _градация_мейера(code: str, pains: dict) -> str:
    """Какой станок Meyer уместен этому коду: сортировка или рентген.

    Карта лежит в самом файле болей (`_meyer_gradaciya`), рядом с текстами —
    чтобы правка отрасли не требовала правки кода."""
    карта = pains.get('_meyer_gradaciya') or {}
    к = str(code or '').strip()
    while к:
        если = карта.get(к)
        if если:
            return 'meyer_foto' if str(если).startswith('фото') else 'meyer_rentgen'
        к = к.rsplit('.', 1)[0] if '.' in к else ''
    return 'meyer_rentgen'


def градация_из_текста(raw: object) -> str:
    """«мейер-фото» / «Meyer (рентген-детекторы)» → meyer_foto | meyer_rentgen.

    Нужна там, где станок известен НЕ по коду ОКВЭД, а по решению оператора:
    партия называется «мейер-фото», значит все её письма про сортировку, даже
    если карта градаций по коду сказала бы «рентген». Владелец 11.08 просил
    ровно две очереди — название очереди и есть его выбор товара.
    """
    s = str(raw or '').strip().lower()
    if not s:
        return ''
    if 'meyer_foto' in s or 'фото' in s or 'photo' in s or 'сепарат' in s:
        return 'meyer_foto'
    if ('meyer_rentgen' in s or 'рентген' in s or 'ренген' in s
            or 'x-ray' in s or 'xray' in s or 'детектор' in s):
        return 'meyer_rentgen'
    return ''


def _из_таблицы(table: dict, code: str) -> str:
    """Точный код бьёт родительский: «10.61» точнее, чем «10»."""
    к = str(code or '').strip()
    while к:
        if к in table:
            return table[к]
        к = к.rsplit('.', 1)[0] if '.' in к else ''
    return ''


def боль_по_кодам(коды: object, division: str = 'kc') -> tuple:
    """Боль по ЛЮБОМУ коду компании, начиная с основного. Возвращает (боль, код).

    Вопрос владельца 11.08: «если в базе есть другой дополнительный оквед — он
    возьмётся, если подходящий?» До этой правки ответ был «нет, и это половина
    беды»: в ОТБОР компания попадала по всем своим кодам (division_for_okveds
    смотрит okved + okved_all), а письмо строилось по ОСНОВНОМУ. Завод с
    основным «11.07 розлив воды» и дополнительным «10.61 мукомольное» получал
    письмо про воду, хотя интересен нам мельницей.

    Порядок важен: основной код первый. Если по нему боль есть — берём её, не
    подменяя профиль компании дополнительным видом деятельности.

    Два прохода, а не один. Точность таблицы важнее места кода в списке: у
    мельницы с дополнительным «10.13 мясопереработка» в очереди рентгена один
    проход отдавал ОБЩУЮ боль пищёвки по первому коду и до точной по второму не
    доходил. Сначала ищем по своей таблице градации ВСЕ коды, и только потом
    падаем в общую таблицу Meyer.
    """
    if isinstance(коды, str):
        список = [c.strip() for c in коды.replace('|', ',').split(',')]
    else:
        список = [str(c).strip() for c in (коды or [])]
    список = [c.split()[0] if ' ' in c else c for c in список if c]
    pains = _okved_pains()
    база = division if division in НАПРАВЛЕНИЯ_БОЛЕЙ else 'kc'
    for код in список:
        div = _градация_мейера(код, pains) if база == 'meyer' else база
        боль = _из_таблицы(pains.get(div) or {}, код)
        if боль:
            return боль, код
    if база == 'meyer' or база in MEYER_ГРАДАЦИИ:
        for код in список:
            боль = _из_таблицы(pains.get('meyer') or {}, код)
            if боль:
                return боль, код
    # Ни по одному коду точной боли нет — общий дефолт направления.
    return equipment_pitch(список[0] if список else '', division), ''


def equipment_pitch(okved: object, division: str = 'kc') -> str:
    """Боль отрасли по коду ОКВЭД.

    Направление может быть названо и точно (`meyer_foto`, `meyer_rentgen`), и
    общо (`meyer`) — во втором случае градацию выбираем по коду сами. Нет
    ничего — общий дефолт направления, а не пустая строка: письмо без «зачем»
    вырождается в рекламу."""
    pains = _okved_pains()
    div = division if division in НАПРАВЛЕНИЯ_БОЛЕЙ else 'kc'
    code = str(okved or '').strip()
    if div == 'meyer':
        div = _градация_мейера(code, pains)
    боль = _из_таблицы(pains.get(div) or {}, code)
    if not боль and div in MEYER_ГРАДАЦИИ:
        # Своей градации нет — берём общую боль Meyer, она честнее пустоты.
        боль = _из_таблицы(pains.get('meyer') or {}, code)
        div = 'meyer'
    if боль:
        return боль
    умолч = pains.get('_по_умолчанию') or {}
    return умолч.get(div) or умолч.get('meyer' if div in MEYER_ГРАДАЦИИ
                                       else div, '')


