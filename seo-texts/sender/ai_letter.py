def allowed_numbers(facts: Optional[dict] = None, extra: Optional[dict] = None,
                    division: str = 'kc') -> set:
    facts = facts or {}
    division = division if division in RULES_BY_DIVISION else 'kc'
    base = set(TECH_NUMS_BY_DIVISION[division])
    if division == 'kc':
        base |= {'5580'}   # канон КЦ живёт в правилах, не только в файле фактов
    # числа самих фактов направления (счётчики CRM/сайта и белый список)
    for key in ('total_crm', 'published_site'):
        base |= set(re.findall(r'\d+', str(facts.get(key) or '')))
    base |= {str(v) for v in (facts.get('region_counts_site_index') or {}).values()}
    base |= {d for v in (facts.get('numbers_allowed') or [])
             for d in re.findall(r'\d+', str(v))}
    # Числа из ПОДТВЕРЖДЁННЫХ кейсов: модель оборудования («Berg ВК-15/8»),
    # мощность, давление. Это проверенные факты с опубликованной страницы
    # проекта — без них письмо не могло сослаться на реальный кейс: гейт резал
    # модель как выдуманную цифру, и генератор скатывался к общим счётчикам.
    for _c in (facts.get('clients_verified') or {}).values():
        if isinstance(_c, dict):
            base |= set(re.findall(r'\d+', str(_c.get('equipment') or '')))
    # Ревью №27: раньше в белый список шли ВСЕ значения extra — туда попадали
    # ИНН, идентификаторы и телефоны, и числовой гейт переставал ловить
    # выдуманные цифры. Берём только поля-факты.
    _SAFE = ('news_sum', 'news_detail', 'news_object', 'news_type', 'equipment',
             'city', 'sum', 'volume', 'power', 'year')
    for _k, v in (extra or {}).items():
        if _k in _SAFE:
            base |= set(re.findall(r'\d+', str(v)))
    # ЧИСЛА ИЗ ПАСПОРТА ИХ САЙТА (14.08, на пилоте обогащённых паспортов).
    # «Каждый день мы производим свыше 10 тонн», «более 100 наименований», год
    # основания — это цитаты с сайта самой компании, то есть самый проверяемый
    # источник, какой у нас есть: письмо ими и должно быть сильно. Пока их не
    # было в белом списке, гейт бракавал письмо за «непроверенные числа» ровно
    # там, где оно опиралось на факт, — и круги правок шли по полной цене.
    # Берём только поля-факты; источники и служебные ключи не трогаем.
    _ПАСПОРТ_ЧИСЛА = ('продукция', 'сырьё', 'упаковка_фасовка', 'мощности',
                      'контроль_качества', 'экспорт', 'оборудование_линии',
                      'география_поставок', 'масштаб', 'год_основания',
                      'свежая_новость', 'цитата')
    _пасп = (extra or {}).get('site_facts')
    if isinstance(_пасп, dict):
        for _k in _ПАСПОРТ_ЧИСЛА:
            v = _пасп.get(_k)
            if isinstance(v, (list, tuple)):
                v = ' '.join(str(x) for x in v)
            base |= set(re.findall(r'\d+', str(v or '')))
    return base


