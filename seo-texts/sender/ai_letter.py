def _predpriyatie_nazvano(name: object, domain: object, text: str):
    """Названо ли предприятие в письме. None = судить нечем (нет своего имени).

    Правило 19и просило называть компанию, и МОДЕЛЬ ЕГО НЕ ИСПОЛНЯЕТ: на партии
    05.08 без имени было 9 писем из 27 до правила и 6 из 22 после - разницы
    нет. Правило в промпте это просьба, заслон в гейте это заслон.

    Матчер намеренно снисходительный: примерка на 49 письмах показала, что
    строгий вариант заворачивает хорошие письма (7 ложных из 16). Считаем
    названным, если есть слово имени от 3 знаков, ОСНОВА длинного слова
    (падеж: «ГАЗСТРОЙ» -> «в Газстрое»), аббревиатура из первых букв или
    латинское имя из домена.
    """
    words = [w for w in re.findall(r'[А-ЯЁA-Z][А-ЯЁA-Zа-яёa-z\-]{1,}',
                                   str(name or '').upper())
             if w not in _ИМЯ_ШУМ and len(w) >= 2]
    if not words:
        return None
    up = text.upper()
    for w in words:
        if len(w) >= 3 and w in up:
            return True
        if len(w) >= 6 and w[:len(w) - 2] in up:
            return True
    abbr = ''.join(w[0] for w in words)[:6]
    if len(abbr) >= 3 and re.search(r'\b' + re.escape(abbr) + r'\b', up):
        return True
    latin = re.sub(r'^(www\.)?', '', str(domain or '')).split('.')[0].upper()
    if len(latin) >= 4 and latin in up:
        return True
    return False


def gate(subject: str, body: str, *, mode: str = 'GENERIC',
         extra: Optional[dict] = None, facts: Optional[dict] = None,
         division: str = 'kc') -> list:
    """Механический гейт письма. [] = чисто. Порядок и регексы — спека §3,
    плюс проверка перекрёстной лексики направления (задача 43)."""
    facts = facts or {}
    division = division if division in RULES_BY_DIVISION else 'kc'
    fails: list = []
    text = subject + '\n' + body
    for rx, name in SUBJ_RE:
        if re.search(rx, subject):
            fails.append(f'{name}: «{subject}»')
    # канон редактора (19а): «Вопрос по расширению … в «Компании»» - до 10
    # слов по правилу, гейт даёт люфт до 12 (название компании из двух слов).
    if len(subject.split()) > 12:
        fails.append(f'тема длинная ({len(subject.split())} слов)')
    for m in re.finditer(r'(\d[\d,\.]*)\s*%', body):
        if m.group(1).split(',')[0].split('.')[0] not in ('97', '99', '95'):
            fails.append(f'проценты: {m.group(0)}')
    for rx, name in STOP_RE + CROSS_LEX[division]:
        m = re.search(rx, text)
        if m:
            frag = text[max(0, m.start() - 25):m.end() + 25].replace('\n', ' ')
            fails.append(f'{name}: «{frag}»')
    if mode != 'NEWS' and re.search(PSEUDO_NEWS_RE, body):
        fails.append('псевдо-новость без данных (GENERIC)')
    low = body.lower()
    if БРАКОВАТЬ_БЕЗ_ОТКАЗА and not _has_optout(low):
        fails.append('нет опции отказа')
    if low.count('извините за') > 1:
        fails.append('двойное заискивание (отказ дважды)')
    words = len(body.split())
    if not 45 <= words <= 140:
        fails.append(f'объём {words} слов')
    if not body.rstrip().endswith('С уважением,'):
        fails.append('финал не «С уважением,»')
    # Ревью №28: цифра в названии («ЭТК № 2», «ТЭЦ-3») давала ложный брак —
    # лид терялся навсегда. Числа из имени/города считаем законными.
    _own = set()
    for _k in ('company_name', 'name', 'city', 'contact_name'):
        _own |= set(re.findall(r'\d+', str((extra or {}).get(_k) or '')))
    leftover = (set(re.findall(r'\d+', body))
                - allowed_numbers(facts, extra, division) - _own)
    if leftover:
        fails.append(f'непроверенные числа: {sorted(leftover)}')
    # Правило 19и механически: без названия письмо читается как веерная
    # рассылка. «Судить нечем» (в базе только организационная форма) - не брак.
    _nazvano = _predpriyatie_nazvano(
        (extra or {}).get('company_name'),
        (extra or {}).get('domain') or (extra or {}).get('site'),
        subject + '\n' + body)
    if _nazvano is False:
        fails.append('предприятие не названо ни в теме, ни в теле (19и)')
    ach = len(re.findall(r'5580', body)) + len(re.findall(r'опубликованн\w+ (кейс|проект)', body))
    if division == 'meyer':
        ach = len(re.findall(r'(?i)(больше|более)\s+200|200\s+предприят', body))
    if ach > 1:
        fails.append(f'витрина: {ach} числа-достижения (максимум одно)')
    # падежный гейт города (урок 2026-07-24: «в Санкт-Петербург» из шаблонной
    # подстановки). Город в именительном сразу после «в/во» = не склонён.
    city = str((extra or {}).get('city') or '').strip()
    if city and not city.lower().endswith(_INDECLINABLE_END):
        if re.search(r'(?i)\bво?\s+' + re.escape(city) + r'(?![\w-])', text):
            fails.append(f'город без склонения: «в {city}»')
    # Вычитка 27.07 (аудит 359 карточек, 101 брак) — три массовых класса:
    # 1) обрезанный регион: «в Чеченской», «в Пензенской -» без слова
    #    область/край/Республика; прилагательное региона после «в» обязано
    #    сопровождаться существительным
    m = re.search(
        r'\bво?\s+[А-ЯЁ][а-яё-]+(?:ской|цкой|ском|цком)\b'
        r'(?!\s+(?:област|обл\.|кра[ею]|район|[Рр]еспублик|автономн|округ|'
        r'город|ГЭС|ГРЭС|ТЭЦ|НПЗ|заводе))', body)
    if m:
        fails.append(f'обрезанный регион: «{m.group(0)}…» — допиши '
                     f'область/край/Республику')
    # 2) имя в приветствии, которого нет в карточке (разворачивание инициала
    #    «Киселев А.» -> «Алексей» дало письмо Антону с чужим именем)
    пм = re.search(r'^(?:Добрый день|Здравствуйте|Доброе утро),\s*([^!\n]{1,50})!',
                   body.strip())
    if пм:
        кому = str((extra or {}).get('contact_name') or '').strip()
        слова = {w.strip('.,!') for w in кому.split() if len(w.strip('.,!')) > 2}
        обращение = [w for w in пм.group(1).replace('!', '').split()
                     if len(w) > 2]
        if обращение and not all(w in слова for w in обращение):
            fails.append(f'имя не из карточки: «{пм.group(0)}» (контакт: '
                         f'«{кому or "нет"}») — приветствие без имени')
    # 3) вопросы: канон редактора (19г) разрешает второй короткий уточняющий
    # вопрос сразу за основным; три и больше - по-прежнему брак.
    if body.count('?') > 2:
        fails.append(f'вопросов в письме: {body.count("?")} (максимум два)')
    return fails


