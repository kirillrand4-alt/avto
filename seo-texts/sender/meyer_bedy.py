"""Беды конкретных культур, которые снимает наше оборудование.

ОТКУДА (владелец 14.08, его таблица и слайд): «Это проблемы определённых
продуктов, которые мы решаем... редактор на них основывается». То есть это не
мои догадки об отрасли, а перечень от владельца — он же и ground truth.

ЗАЧЕМ. До этого письмо про любую культуру писало одно и то же: «сорные примеси,
дефектные зёрна, камни». Мукомол читает это и видит рассылку: у него не «сорные
примеси», у него ОВСЮГ, который гробит выход муки, и АМБРОЗИЯ, которая
карантинная. Названная по имени беда — единственное место в холодном письме,
где видно, что писавший знает отрасль. Ровно на этом строит письма редактор.

ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. В исходном слайде рядом с бедами стоит, ЗА СЧЁТ ЧЕГО
машина их берёт: «мощная светодиодная подсветка», «технология AI Deep
Learning». В письмо это не идёт — редактор 14.08 вычеркнула описание
устройства во всех письмах («НЕ нужно описывать НИ В КАКИХ ПИСЬМАХ за счет
чего и как проходит сортировка»). Здесь остаются только РЕЗУЛЬТАТЫ.

КАК ПОДКЛЮЧЕНО. Ключи словаря — канонические имена продуктов из
meyer_products, поэтому беды находятся тем же разбором профиля, что и ролик:
паспорт сайта -> продукт каталога -> беды. Продукта нет в таблице — строки в
карточке не будет, и письмо напишется общими словами, как раньше.
"""
from typing import Optional

# продукт каталога -> (болезни и поражения, засорители и примеси, что даёт нам
#                      результат: чем именно беда бьёт по клиенту)
#
# Формулировки короткие и «письменные»: карточка отдаёт их модели почти
# дословно, и длинная агрономическая справка там только мешает.
БЕДЫ = {
    "пшеница": (
        ("фузариоз", "альтернариоз (чернь колоса, чёрный зародыш)",
         "проросшие зёрна", "недозревшие зёрна"),
        ("овсюг", "амброзия (карантинный сорняк)",
         "эгилопс цилиндрический"),
        "овсюг снижает выход муки и её мукомольные качества, амброзия "
        "карантинная, а эгилопс на ранних стадиях почти неотличим от пшеницы; "
        "по стекловидности партия тоже вытягивается",
    ),
    "гречиха": (
        (),
        ("дикая редька", "подсолнечник"),
        "это труднотделимые включения: обычная очистка их не берёт",
    ),
    "подсолнечник": (
        ("склероций (белая гниль)",),
        (),
        "плюс калибровка по размеру",
    ),
    "рапс": (
        ("склеротиниоз (белая гниль)",),
        ("горчица", "рыжик", "сурепица"),
        "крестоцветные засорители близки к рапсу по форме и размеру, глазом их "
        "не разделить, а горчичные масла портят качество масла и снижают класс "
        "продукции",
    ),
    "соя": (
        ("склеротиниоз (белая гниль)",),
        ("амброзия", "марь", "щирица", "канатник"),
        "семена сорняков уходят в товарную партию, и партию могут "
        "дисквалифицировать",
    ),
    "нут": (
        ("аскохитоз", "фузариоз"),
        ("вязель разноцветный (токсичный)",),
        "при обмолоте сок сорняков красит зерно и портит товарный вид",
    ),
    "лён": (
        ("фузариоз", "антракноз"),
        ("повилика (карантинный паразит)",),
        "повилика маскируется среди культуры, а семена сорняков с шероховатой "
        "поверхностью отделяются только специально",
    ),
}

# Культуры, которые в каталоге зовутся иначе или входят в общий ключ.
СИНОНИМЫ = {
    "семена подсолнечника": "подсолнечник",
    "масличные": "подсолнечник",
}


def беды(продукт: object) -> Optional[dict]:
    """Беды по каноническому имени продукта каталога или None."""
    п = str(продукт or "").strip().lower()
    п = СИНОНИМЫ.get(п, п)
    з = БЕДЫ.get(п)
    if not з:
        return None
    болезни, засорители, эффект = з
    return {"продукт": п, "болезни": list(болезни),
            "засорители": list(засорители), "эффект": эффект}


def строка_для_karto4ki(продукты: object) -> str:
    """Строка карточки по списку продуктов профиля. Пусто — беды не найдены.

    Берём максимум две культуры: письмо на 140-190 слов не выдержит перечня
    по пяти, а редактор в своих письмах называет беды одной-двух главных.
    """
    найдено = []
    for п in (продукты or ()):
        b = беды(п)
        if b and b["продукт"] not in [x["продукт"] for x in найдено]:
            найдено.append(b)
        if len(найдено) >= 2:
            break
    if не_пусто := [b for b in найдено if b["болезни"] or b["засорители"]]:
        куски = []
        for b in не_пусто:
            части = []
            if b["болезни"]:
                части.append("поражения: " + ", ".join(b["болезни"]))
            if b["засорители"]:
                части.append("засорители: " + ", ".join(b["засорители"]))
            хвост = f" ({b['эффект']})" if b["эффект"] else ""
            куски.append(f"{b['продукт'].upper()} - " + "; ".join(части) + хвост)
        return (
            "ЧТО ИМЕННО МЫ СНИМАЕМ У ИХ КУЛЬТУР (перечень владельца, на нём же "
            "строит письма редактор - НАЗЫВАЙ БЕДУ ПО ИМЕНИ, а не «сорные "
            "примеси»; хватит двух-трёх позиций, всё подряд не перечисляй): "
            + " | ".join(куски))
    return ""
