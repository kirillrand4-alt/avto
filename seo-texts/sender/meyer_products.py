def подобрать_все(*части: object, станок: str = "") -> list:
    """Все подходящие продукты по убыванию уверенности.

    Уверенность = сколько ключей совпало, дальше — насколько рано ключ
    встретился в тексте (списки продукции и сырья идут от главного к
    второстепенному), дальше — частота продукта в базе знаний.

    Нужен подбору роликов: там важен не один «лучший» продукт, а очередь —
    если под первый ролика нет, берём следующий, вместо того чтобы оставлять
    письмо без ссылки при живом кандидате рядом.
    """
    текст = " ".join(str(ч or "") for ч in части).lower()
    if not текст.strip():
        return []
    # Пробелы по краям: часть ключей начинается с пробела («&nbsp;нут»), чтобы
    # не ловиться внутри «минут» и «внутренний». Без набивки такой ключ не
    # находил слово, стоящее первым в строке.
    текст = " " + текст + " "
    найдено = []
    for канон, ст, скольких, ключи in ПРОДУКТЫ:
        if станок and ст != станок:
            continue
        места = [текст.find(к) for к in ключи if к in текст]
        if not места:
            continue
        найдено.append({"продукт": канон, "станок": ст, "строк_базы": скольких,
                        "совпадений": len(места), "первое_вхождение": min(места)})
    найдено.sort(key=lambda d: (-d["совпадений"], d["первое_вхождение"],
                                -d["строк_базы"]))
    return найдено


def подобрать(*части: object, станок: str = "") -> Optional[dict]:
    """Самый уверенный продукт профиля или None.

    Тонкая обёртка над подобрать_все: раньше здесь лежала ВТОРАЯ копия того же
    перебора, и правки доставались только одной из них. Так и вышло 14.08:
    набивку пробелами (чтобы ключ « нут» не терялся в начале строки) я внёс в
    подобрать_все, а подобрать продолжал возвращать None.
    """
    все = подобрать_все(*части, станок=станок)
    if not все:
        return None
    п = все[0]
    return {"продукт": п["продукт"], "станок": п["станок"],
            "строк_базы": п["строк_базы"], "совпадений": п["совпадений"]}


