def подобрать(*части: object, станок: str = "") -> Optional[dict]:
    """Продукт из подтверждённых, который есть у этого получателя.

    части — что известно о предприятии (паспорт с его сайта, ОКВЭД, описание).
    станок — 'фото' | 'рентген' | '' (любой).

    Выигрывает продукт с наибольшим числом совпавших ключей; при равенстве —
    тот, что чаще встречается в базе знаний (мера уверенности сайта).
    """
    текст = " ".join(str(ч or "") for ч in части).lower()
    if not текст.strip():
        return None
    лучший, вес, частота = None, 0, 0
    for канон, ст, скольких, ключи in ПРОДУКТЫ:
        if станок and ст != станок:
            continue
        совпало = sum(1 for к in ключи if к in текст)
        if совпало > вес or (совпало == вес and совпало and скольких > частота):
            лучший, вес, частота = (канон, ст, скольких), совпало, скольких
    if лучший is None or not вес:
        return None
    return {"продукт": лучший[0], "станок": лучший[1],
            "строк_базы": лучший[2], "совпадений": вес}


def все_под(станок: str = "") -> tuple:
    """Каноны продуктов под указанный станок — для отчётов и тестов."""
    return tuple(п[0] for п in ПРОДУКТЫ if not станок or п[1] == станок)
