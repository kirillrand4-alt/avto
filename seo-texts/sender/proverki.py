# -*- coding: utf-8 -*-
"""Какие проверки прошёл адрес письма — значками, для очереди подтверждений.

Владелец 11.08: «сделай у каждой почты галочки проверок, которые она прошла,
значками, с расшифровкой — чтобы понимать, какая почта прошла все проверки, а
какая нет».

Проверок к этому дню накопилось шесть, и все они жили порознь: проба адресов в
своей таблице, стоп-лист в своей, гейт адресата в третьей, заслон ловушек в
коде, тип почтового сервера в карточке получателя. Оператор видел только адрес
и должен был помнить, что за ним стоит. Здесь всё сводится в одну строку
значков рядом с письмом.

Правило значков одно и оно важнее удобства: **зелёная галка ставится только за
пройденную проверку, а не за отсутствие плохих новостей.** Непроверенное
показывается серым вопросом, а не галкой: «мы не знаем» и «всё хорошо» — разные
вещи, и путать их в интерфейсе опаснее, чем не показывать ничего.
"""
from __future__ import annotations

from typing import Any, Optional

# Порядок = порядок значков в строке. Слева направо: от адреса к письму.
ПОРЯДОК = ("mx", "proba", "lovushki", "stop", "gejt", "server")

ЛЕГЕНДА = [
    {"код": "mx", "значок": "📮", "имя": "почтовый сервер найден",
     "что": "у домена есть MX-запись, письму есть куда идти"},
    {"код": "proba", "значок": "✉", "имя": "проба адреса",
     "что": "спросили у сервера получателя, существует ли ящик; письмо при "
            "этом не отправлялось"},
    {"код": "lovushki", "значок": "🪤", "имя": "заслон ловушек",
     "что": "адрес не служебный (abuse@, postmaster@), домен не опечатка от "
            "популярного, адрес не «воскресший»"},
    {"код": "stop", "значок": "⛔", "имя": "стоп-лист",
     "что": "ни адрес, ни домен, ни ИНН не в стоп-листе (отписка, идёт сделка, "
            "конкурент)"},
    {"код": "gejt", "значок": "🎯", "имя": "гейт адресата",
     "что": "две линзы судят по роду деятельности с их сайта, покупает ли "
            "компания то, что мы продаём"},
    {"код": "server", "значок": "🏢", "имя": "почта получателя",
     "что": "публичный провайдер (Яндекс, Mail.ru, Google) или собственный "
            "сервер компании; корпоративные шлюзы строже к молодым доменам"},
]

ЗНАЧКИ_СОСТОЯНИЙ = {"ok": "✅", "warn": "⚠️", "bad": "❌", "net": "❔"}


def _проба(вердикт: Optional[str]) -> tuple:
    if not вердикт:
        return "net", "адрес не проверялся"
    if вердикт == "есть":
        return "ok", "сервер подтвердил: ящик существует"
    if вердикт == "нет ящика":
        return "bad", "сервер ответил «такого пользователя нет»"
    if вердикт == "принимает всё":
        # Отдельное состояние, а не «ok»: домен говорит «приму» кому угодно,
        # значит его «приму» ничего не подтверждает. Поймано 11.08 отбивкой
        # kk@vebfabrika.ru — проба назвала живым, письмо вернулось.
        return "warn", "домен принимает любой адрес — подтверждения нет"
    if вердикт == "нет MX":
        return "bad", "у домена нет почтового сервера"
    if вердикт == "отказ пробе":
        return "net", "сервер отказал НАШЕЙ пробе, про адрес не сказал ничего"
    return "net", f"вердикт «{вердикт}» — не подтверждение и не отказ"


def проверки_письма(*, email: str, inn: Optional[str], mx_provider: Optional[str],
                    вердикт_пробы: Optional[str], в_стоп_листе: Optional[str],
                    вердикт_гейта: Optional[str],
                    ловушка: Optional[tuple] = None) -> dict:
    """Состояние всех проверок для одного письма.

    Возвращает {'itogo': 'ok|warn|bad|net', 'punkty': [{код, значок, статус,
    знак, podpis}]} — фронту остаётся только нарисовать.
    """
    пункты = []

    есть_mx = bool(mx_provider) or (вердикт_пробы not in (None, "нет MX"))
    пункты.append(("mx", ("ok", "почтовый сервер домена найден") if есть_mx
                   else ("bad", "у домена нет MX-записи")))

    пункты.append(("proba", _проба(вердикт_пробы)))

    if ловушка:
        пункты.append(("lovushki", ("bad", f"{ловушка[0]}: {ловушка[1]}")))
    else:
        пункты.append(("lovushki", ("ok", "по повадкам ловушек чисто")))

    if в_стоп_листе:
        пункты.append(("stop", ("bad", f"в стоп-листе: {в_стоп_листе}")))
    else:
        пункты.append(("stop", ("ok", "в стоп-листе не значится")))

    if вердикт_гейта == "покупатель":
        пункты.append(("gejt", ("ok", "линзы согласились: наш покупатель")))
    elif вердикт_гейта == "не покупатель":
        пункты.append(("gejt", ("bad", "линзы сошлись: не наш покупатель")))
    elif вердикт_гейта:
        пункты.append(("gejt", ("warn", f"линзы разошлись: {вердикт_гейта}")))
    else:
        пункты.append(("gejt", ("net", "компанию ещё не судили")))

    свой = str(mx_provider or "").strip().lower() in ("other", "unknown")
    пункты.append(("server", ("warn", "свой почтовый сервер компании: шлюз "
                              "строже к письмам с молодых доменов") if свой
                   else ("ok", f"публичный провайдер"
                              f"{' (' + str(mx_provider) + ')' if mx_provider else ''}")))

    порядок = {к: n for n, к in enumerate(ПОРЯДОК)}
    пункты.sort(key=lambda x: порядок.get(x[0], 99))
    имена = {л["код"]: л for л in ЛЕГЕНДА}
    собрано = [{"код": к, "значок": имена.get(к, {}).get("значок", "•"),
                "статус": ст, "знак": ЗНАЧКИ_СОСТОЯНИЙ.get(ст, "•"),
                "имя": имена.get(к, {}).get("имя", к), "podpis": подпись}
               for к, (ст, подпись) in пункты]
    если_есть = {x["статус"] for x in собрано}
    итого = ("bad" if "bad" in если_есть else
             "warn" if "warn" in если_есть else
             "net" if "net" in если_есть else "ok")
    return {"itogo": итого, "znak": ЗНАЧКИ_СОСТОЯНИЙ.get(итого, "•"),
            "punkty": собрано}


def собрать_карты(store: Any, письма: list) -> dict:
    """Один запрос на каждую таблицу вместо запроса на письмо.

    Писем в очереди сотни; ходить в базу по разу на каждое — это тысячи
    запросов на один показ страницы.
    """
    почты = {str(r.get("email") or "").strip().lower() for r in письма if r.get("email")}
    инны = {str(r.get("inn") or "").strip() for r in письма if r.get("inn")}
    карты = {"proba": {}, "stop": {}, "gejt": {}, "bounce": set()}
    if not почты:
        return карты
    try:
        con = store._conn  # noqa: SLF001 - читаем ту же живую базу
        метки = ",".join("?" * len(почты))
        for e, v in con.execute(
                f"SELECT email, verdict FROM addr_probe WHERE email IN ({метки})",
                list(почты)):
            карты["proba"][str(e).strip().lower()] = v
        домены = {p.split("@")[-1] for p in почты}
        значения = list(почты | домены | инны)
        if значения:
            метки2 = ",".join("?" * len(значения))
            for v, r in con.execute(
                    f"SELECT value, reason FROM suppression WHERE value IN ({метки2})",
                    значения):
                карты["stop"][str(v).strip().lower()] = r
        if инны:
            метки3 = ",".join("?" * len(инны))
            for i, v in con.execute(
                    f"SELECT inn, verdict FROM target_verdicts WHERE inn IN ({метки3})",
                    list(инны)):
                карты["gejt"][str(i)] = v
        for (e,) in con.execute(
                "SELECT value FROM suppression WHERE reason='bounce_hard'"):
            карты["bounce"].add(str(e).strip().lower())
    except Exception:  # noqa: BLE001 - показ очереди важнее значков
        pass
    return карты
