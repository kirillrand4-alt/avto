"""Беды культур по имени (таблица владельца 14.08).

«Это проблемы определённых продуктов, которые мы решаем... редактор на них
основывается». До этого письмо любой культуре писало одно и то же — «сорные
примеси, дефектные зёрна, камни», — и адресат видел рассылку.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender.ai_letter import RULES_MEYER, _recipient_block, gate  # noqa: E402
from sender.meyer_bedy import (беды, строка_для_karto4ki)  # noqa: E402


def _карточка(**site_facts):
    rec = {"company_name": "ООО «Тест»", "okved": "10.61 мукомольное",
           "activity": "переработка", "extra": {"meyer_gradaciya": "мейер-фото",
                                                "site_facts": site_facts}}
    return _recipient_block(0, rec, "meyer", 0)


def _строка_бед(блок):
    return next((с for с in блок.splitlines() if "СНИМАЕМ У ИХ КУЛЬТУР" in с), "")


def test_pshenitsa_nazyvaet_svoi_sornyaki():
    с = _строка_бед(_карточка(продукция=["мука пшеничная"], сырьё=["пшеница"]))
    assert с, "строки бед нет вовсе"
    for слово in ("овсюг", "амброзия", "эгилопс", "фузариоз"):
        assert слово in с.lower(), (слово, с)


def test_kazhdaya_kultura_svoyu_bedu():
    пары = (("рапс", ("склеротиниоз", "сурепица")),
            ("соя", ("склеротиниоз", "щирица")),
            ("нут", ("аскохитоз", "вязель")),
            ("лён", ("антракноз", "повилика")),
            ("гречиха", ("дикая редька",)),
            ("подсолнечник", ("склероций",)))
    for культура, ожидаем in пары:
        с = _строка_бед(_карточка(сырьё=[культура])).lower()
        assert с, культура
        for слово in ожидаем:
            assert слово in с, (культура, слово, с)


def test_kultura_bez_tablitsy_stroki_ne_daet():
    """Продукт есть в каталоге, бед по нему в таблице владельца нет — молчим,
    а не сочиняем: письмо напишется общими словами, как раньше."""
    assert _строка_бед(_карточка(продукция=["изюм"], сырьё=["виноград"])) == ""


def test_ne_bolshe_dvuh_kultur():
    """Письмо на 140-190 слов не выдержит перечня по пяти культурам."""
    с = _строка_бед(_карточка(сырьё=["пшеница", "рапс", "соя", "нут", "лён"]))
    названо = sum(1 for к in ("ПШЕНИЦА", "РАПС", "СОЯ", "НУТ", "ЛЁН") if к in с)
    assert названо <= 2, с


def test_mehanizm_v_tablitsu_ne_popal():
    """В исходном слайде рядом с бедами стояло, ЗА СЧЁТ ЧЕГО машина их берёт
    (светодиодная подсветка, AI Deep Learning). Редактор описание устройства
    вычеркнула — в таблице этого быть не должно, иначе гейт снимет письмо,
    написанное строго по карточке."""
    весь = " ".join(str(x) for к in ("пшеница", "гречиха", "подсолнечник",
                                     "рапс", "соя", "нут", "лён")
                    for x in (беды(к) or {}).values() if x)
    for запрет in ("подсветк", "deep learning", "камер", "распозна", "алгоритм"):
        assert запрет not in весь.lower(), запрет


def test_slova_bed_ne_lovyatsya_zaslonami():
    """Названия бед обязаны проходить механический гейт: письмо, написанное
    ровно по таблице владельца, не должно им же и браковаться."""
    тело = ("Добрый день!\n\n"
            "Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю компанию «Руспром Meyer». "
            "Работаю с мукомольными предприятиями по вопросам сортировки "
            "зерна.\n\n"
            "«Тест» перерабатывает пшеницу, поэтому обращаюсь по вопросу "
            "очистки зерна перед помолом.\n\n"
            "Фотосепаратор убирает овсюг, амброзию и эгилопс, а также зёрна с "
            "фузариозом и альтернариозом, проросшие и недозревшие.\n\n"
            "Подскажите, актуальна ли для вас задача качественной очистки "
            "зерна?\n\n"
            "Если этим вопросом занимается другой специалист, передайте, "
            "пожалуйста, письмо ему.\n\n"
            "С уважением,")
    fails = gate("Вопрос по сортировке зерна в «Тест»", тело, mode="GENERIC",
                 extra={"company_name": "ООО «Тест»"}, facts={},
                 division="meyer")
    assert fails == [], fails


