"""Напитки — не адресат Meyer (слово владельца 19.08 по письму #3080).

«Союз-Вино» выпускает вина и сидр в банках и бутылках, а письмо предлагало
рентген-инспекцию. Рентген светит сквозь упаковку и ищет плотное включение
в теле продукта; в банке вина искать нечего.

Это отказ ПО НАПРАВЛЕНИЮ, а не по компании: на розливе компрессор нужен
всегда (выдув преформ, пневматика линии), и компрессорное письмо такой
завод получит своей очередью — тест это проверяет отдельно.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender import ai_letter as AI  # noqa: E402


def test_vino_ne_nash_dlya_meyer():
    п = AI.vne_profilya_meyer("11.02", "производство вин")
    assert п and "напитки" in п


def test_po_slovam_bez_koda():
    """ОКВЭД врёт часто — ловим и по роду деятельности."""
    for деят in ("винодельческое предприятие", "пивоварня полного цикла",
                 "розлив минеральной воды", "производство лимонадов",
                 "ликёро-водочный завод"):
        assert AI.vne_profilya_meyer("", деят), деят


def test_pishchevka_ne_zadeta():
    """Кондитер, мукомол и мясопереработка остаются нашими."""
    for код, деят in (("10.71", "производство хлеба"),
                      ("10.61", "мукомольное производство"),
                      ("10.13", "мясопереработка"),
                      ("10.82", "производство шоколада")):
        assert AI.vne_profilya_meyer(код, деят) == "", (код, деят)


def test_otkaz_govorit_pro_kompressornoe_napravlenie():
    """Отказ обязан объяснять, что лид не потерян — он к КЦ."""
    п = AI.vne_profilya_meyer("11.05", "пивоварня")
    assert "КОМПРЕССОРНОГО" in п


