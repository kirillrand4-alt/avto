"""Формулировки Мартюшова для Meyer (19.08) — заслон обязан их принимать.

Владелец передал правки по мейеровским шаблонам: расширить обороты перехода
к теме и просьбу перенаправить. Две из трёх новых просьб гейт срезал —
проверено до правки, — потому что узнавал просьбу по короткому списку форм.
Это ровно та ошибка, что уже была 14.08: правила велят писать живее, а
заслон знает один оборот.

Проверяю поведение: все формы пула проходят проверку просьбы, а письмо без
просьбы вовсе — не проходит (иначе тест ничего не стоит).
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender import ai_letter as AI  # noqa: E402

ПУЛ = [
    "Если этим вопросом занимается другой специалист, буду признателен, "
    "если перенаправите ему письмо.",
    "Если это зона ответственности другого коллеги, подскажите, пожалуйста, "
    "с кем лучше связаться.",
    "Если вопрос не к вам, буду благодарен за контакт коллеги - обращусь "
    "напрямую.",
    "Подскажите, пожалуйста, к кому лучше обратиться из отдела качества.",
]


def test_ves_pul_prohodit():
    for ф in ПУЛ:
        assert AI._prosba_perenapravit(f"Добрый день!\n\nТело письма.\n\n{ф}"), ф


def test_bez_prosby_ne_prohodit():
    """Тест обязан уметь провалиться: письмо без просьбы её не имеет."""
    assert not AI._prosba_perenapravit(
        "Добрый день!\n\nВопрос по сортировке семян.\n\nС уважением,")


def test_pul_v_pravilah_meyer():
    п = AI.RULES_BY_DIVISION["meyer"]
    assert "с кем лучше связаться" in п
    assert "контакт коллеги" in п
    assert "отдела качества" in п
    assert "контролю посторонних включений" in п
    assert "тестовую сортировку" in п


def test_pul_ne_popal_v_kc():
    """Правки касаются Meyer: у компрессорного направления своих слов хватает."""
    assert "отдела качества" not in AI.RULES_BY_DIVISION["kc"]
