"""Гейт адресата обязан видеть паспорт сайта, а не одну строку.

Замер 20.08 на десяти снятых гейтом компаниях: примерно половина снята
зря, и опровержение лежало в паспорте той же компании. ОКБ «ССП-ЕКБ»
гейт назвал складской логистикой — в паспорте корпуса испарителя,
шестерни, шнеки, изделия из чугуна. «Феррум-Трейд» назвал торговой
компанией без производства — цитата с их сайта: «занимается изготовлением
металлоконструкций по чертежам заказчика».

Причина не в модели, а в том, что ей давали: блок промпта нёс только
`activity` — короткую строку из карточки. Паспорт лежал в той же базе.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__),
                                                "..", "..")))

from sender.target_gate import TargetGate  # noqa: E402

ПАСПОРТ = ("цитата: изготовление металлоконструкций по чертежам заказчика\n"
           "продукция: шестерни; шнеки; корпуса испарителя")
ТОРГОВЕЦ_НА_ВИД = {"inn": "6658407300", "name": "ООО «Феррум-Трейд»",
                   "okved": "25.11", "activity": "торговля металлопрокатом",
                   "pasport": ПАСПОРТ}
ТОЛЬКО_ПАСПОРТ = {"inn": "6671266088", "name": "ООО «ОКБ»", "okved": "24.10",
                  "activity": "", "pasport": ПАСПОРТ}
СОВСЕМ_ПУСТО = {"inn": "7800000000", "name": "ООО «Тайна»", "okved": "25.62",
                "activity": "", "pasport": ""}


def _гейт(tmp_path, ответ):
    зовы = []

    def caller(prompt):
        зовы.append(prompt)
        return ответ

    return TargetGate(str(tmp_path / "t.db"), caller), зовы


def _json(инн, вердикт):
    return ('{"verdicts":[{"inn":"%s","verdict":"%s","chem":"x",'
            '"pochemu":"y"}]}' % (инн, вердикт))


def test_pasport_doezzhaet_do_promta(tmp_path):
    """Слова паспорта обязаны быть в промпте — иначе судить по ним нечем."""
    g, зовы = _гейт(tmp_path, _json(ТОРГОВЕЦ_НА_ВИД["inn"], "покупатель"))
    g.not_buyers([ТОРГОВЕЦ_НА_ВИД])
    assert зовы, "провайдера не позвали вовсе"
    for слово in ("шнеки", "по чертежам заказчика", "Паспорт сайта"):
        assert слово in зовы[0], (слово, зовы[0][:400])


def test_stroka_deyatelnosti_tozhe_ostayotsya(tmp_path):
    """Паспорт добавлен, а не подменил собой прежний блок."""
    g, зовы = _гейт(tmp_path, _json(ТОРГОВЕЦ_НА_ВИД["inn"], "покупатель"))
    g.not_buyers([ТОРГОВЕЦ_НА_ВИД])
    assert "торговля металлопрокатом" in зовы[0]
    assert "ОКВЭД: 25.11" in зовы[0]


def test_odin_pasport_bez_stroki_uzhe_povod_sudit(tmp_path):
    """Пустая activity при живом паспорте — не повод отправлять в «неясно»."""
    g, зовы = _гейт(tmp_path, _json(ТОЛЬКО_ПАСПОРТ["inn"], "покупатель"))
    g.not_buyers([ТОЛЬКО_ПАСПОРТ])
    assert зовы, "компанию с паспортом не осудили"


def test_pusto_i_pusto_ne_sudim(tmp_path):
    """Ни строки, ни паспорта — провайдера не зовём и не режем."""
    g, зовы = _гейт(tmp_path, _json(СОВСЕМ_ПУСТО["inn"], "не покупатель"))
    assert g.not_buyers([СОВСЕМ_ПУСТО]) == set()
    assert зовы == []
