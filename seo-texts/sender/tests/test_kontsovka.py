"""Концовка письма: один вопрос и подпись (владелец 14.08).

История правила. 06.08 владелец завёл канон: письмо кончается просьбой о
коротком ответе («Если тема сейчас неактуальна, буду признателен за короткий
ответ, чтобы в дальнейшем вас не отвлекать») — вместо прежнего извинения
(«извините за письмо, больше не побеспокою»), которое ничего не давало.

14.08 редактор эту строку вычеркнула: «предлагаю не использовать этот
вариант». Владелец решил: «в конце оставить один вопрос». Механический шаг
остался на месте, но теперь он не ПРИШИВАЕТ строку отказа, а СРЕЗАЕТ её —
включая бывший канон, который стоит в трёхстах письмах уже лежащей очереди.

Юридически отписка обеспечена заголовком List-Unsubscribe (RFC 8058), а не
текстом письма, поэтому удаление строки ничего не нарушает.

Проверяю дозатор, а не промпт: правило 19и показало, что просьбу в промпте
модель выполняет через раз, и надёжен только механический шаг.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender.ai_letter import KONTSOVKA, gate, zashit_kontsovku  # noqa: E402

ТЕЛО = ("Добрый день!\n\n"
        "У «Тест» гальваника, и воздух там держит и обдув оснастки, и "
        "пневмоприжимы на участке обработки, поэтому запас по "
        "производительности уходит быстрее, чем кажется, а требования к "
        "чистоте выше цехового уровня.\n\n"
        "Я веду направление компрессорного оборудования в Компрессор Центре. "
        "Подскажите, актуален ли для вас вопрос обновления парка?\n\n"
        "{отказ}\n\n"
        "С уважением,")


def test_staryy_otkaz_vyrezaetsya():
    было = ТЕЛО.format(отказ="Если неактуально - извините за письмо, "
                             "больше не побеспокою.")
    стало = zashit_kontsovku(было)
    assert "побеспокою" not in стало and "извините" not in стало
    assert стало.rstrip().endswith("С уважением,")


def test_byvshiy_kanon_tozhe_vyrezaetsya():
    """Триста писем очереди написаны с каноном 06.08 — при перегенерации и
    правке они обязаны от него избавляться, а не сохранять его."""
    стало = zashit_kontsovku(ТЕЛО.format(отказ=KONTSOVKA))
    assert KONTSOVKA not in стало
    assert "буду признателен" not in стало.lower()
    assert стало.rstrip().endswith("С уважением,")


def test_pismo_konchaetsya_voprosom_i_podpisyu():
    стало = zashit_kontsovku(ТЕЛО.format(отказ=KONTSOVKA))
    абзацы = [s for s in стало.split("\n\n") if s.strip()]
    assert абзацы[-1] == "С уважением,"
    assert абзацы[-2].rstrip().endswith("?")     # последним остаётся вопрос


def test_chuzhoy_tekst_ne_edim():
    """Срезаем только строку отказа. Абзац по делу на её месте остаётся."""
    без = ТЕЛО.format(отказ="Готов прислать пару конфигураций для сравнения.")
    стало = zashit_kontsovku(без)
    assert "конфигураций" in стало
    assert стало.rstrip().endswith("С уважением,")


def test_idempotentno():
    один = zashit_kontsovku(ТЕЛО.format(отказ=KONTSOVKA))
    два = zashit_kontsovku(один)
    assert один == два


def test_dvoynoy_otkaz_vyrezaetsya_ves():
    """Две формулировки подряд — обе долой, а не первая."""
    было = ТЕЛО.format(отказ="Если неактуально - извините за письмо.\n"
                             "Больше не побеспокою.")
    стало = zashit_kontsovku(было)
    assert "побеспокою" not in стало and "извините" not in стало


def test_pustoe_telo_ne_lomaet():
    assert zashit_kontsovku("") == ""
    assert zashit_kontsovku(None) is None


def test_pochinennoe_pismo_prohodit_gate():
    """Письмо без строки отказа не должно спотыкаться о механический гейт:
    финал остаётся «С уважением,», заискивания нет."""
    тело = zashit_kontsovku(ТЕЛО.format(отказ="Если неактуально - извините "
                                              "за письмо, больше не побеспокою."))
    fails = gate("Вопрос по компрессорному парку в «Тест»", тело,
                 mode="GENERIC", extra={"company_name": "ООО «Тест»"},
                 facts={}, division="kc")
    assert "финал не «С уважением,»" not in fails
    assert not [f for f in fails if "заискивание" in f]
