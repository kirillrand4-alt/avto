"""Канон концовки писем (владелец 06.08): просьба о коротком ответе.

Раньше письмо заканчивалось извинением («извините за письмо, больше не
побеспокою») — виноватой формулировкой, которая ничего не давала: отказавшийся
молчал так же, как незаинтересованный. Теперь просим действие.

Проверяю дозатор, а не промпт: правило 19и показало, что просьбу в промпте
модель выполняет через раз, и надёжен только механический шаг.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender.ai_letter import KONTSOVKA, gate, zashit_kontsovku  # noqa: E402

ТЕЛО = ("Добрый день!\n\n"
        "У «Тест» гальваника, и воздух там держит и обдув оснастки, и "
        "пневмоприжимы на участке обработки, поэтому запас по "
        "производительности уходит быстрее, чем кажется, а требования к "
        "чистоте выше цехового уровня.\n\n"
        "Я веду направление компрессорного оборудования в Компрессор Центре. "
        "Подскажите, актуален ли для вас вопрос обновления парка?\n\n"
        "{отказ}\n\n"
        "С уважением,")


def test_staryy_otkaz_zamenyaetsya():
    было = ТЕЛО.format(отказ="Если неактуально - извините за письмо, "
                             "больше не побеспокою.")
    стало = zashit_kontsovku(было)
    assert KONTSOVKA in стало
    assert "побеспокою" not in стало and "извините" not in стало
    assert стало.rstrip().endswith("С уважением,")


def test_otkaza_ne_bylo_vstavlyaem():
    без = ТЕЛО.format(отказ="Готов прислать пару конфигураций для сравнения.")
    стало = zashit_kontsovku(без)
    строки = [s for s in стало.split("\n\n") if s.strip()]
    assert строки[-1] == "С уважением,"
    assert строки[-2] == KONTSOVKA          # ровно предпоследней строкой
    assert "конфигураций" in стало          # чужой текст не съеден


def test_kontsovka_otdelnym_abzatsem():
    """Концовка — свой абзац, а не хвост, прилипший к подписи.

    Первая версия дозатора схлопывала пустые строки скопом, и в 292 живых
    письмах концовка склеилась с «С уважением,» — письмо читают глазами,
    слипшийся хвост выглядит обрывком."""
    стало = zashit_kontsovku(ТЕЛО.format(отказ="Если неактуально - извините "
                                               "за письмо, больше не побеспокою."))
    assert KONTSOVKA + "\n\nС уважением," in стало
    # и починка уже слипшегося текста
    слипшееся = стало.replace(KONTSOVKA + "\n\nС уважением,",
                              KONTSOVKA + "\nС уважением,")
    assert KONTSOVKA + "\n\nС уважением," in zashit_kontsovku(слипшееся)


def test_idempotentno():
    один = zashit_kontsovku(ТЕЛО.format(отказ=KONTSOVKA))
    два = zashit_kontsovku(один)
    assert один == два
    assert один.count(KONTSOVKA) == 1


def test_dvoynoy_otkaz_shlopyvaetsya():
    """Две старые формулировки подряд -> одна каноничная."""
    было = ТЕЛО.format(отказ="Если неактуально - извините за письмо.\n"
                             "Больше не побеспокою.")
    стало = zashit_kontsovku(было)
    assert стало.count(KONTSOVKA) == 1
    assert "побеспокою" not in стало


def test_pustoe_telo_ne_lomaet():
    assert zashit_kontsovku("") == ""
    assert zashit_kontsovku(None) is None


def test_pochinennoe_pismo_prohodit_gate():
    """Письмо с новой концовкой не должно спотыкаться о механический гейт:
    финал остаётся «С уважением,», опция отказа распознаётся."""
    тело = zashit_kontsovku(ТЕЛО.format(отказ="Если неактуально - извините "
                                              "за письмо, больше не побеспокою."))
    fails = gate("Вопрос по компрессорному парку в «Тест»", тело,
                 mode="GENERIC", extra={"company_name": "ООО «Тест»"},
                 facts={}, division="kc")
    assert "нет опции отказа" not in fails
    assert "финал не «С уважением,»" not in fails
    assert not [f for f in fails if "заискивание" in f]
