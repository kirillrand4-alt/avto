def test_skeptik_znaet_material_i_neproizvodstvo():
    """Дыра, найденная прогоном 06.08: письмо обещало производителю
    СТЕКЛОПЛАСТИКА «плазменную резку» (плазма режет только токопроводящее),
    и линза сказала «верно». Второй случай — оценщику недвижимости писали про
    цех и окраску. Обе оси теперь названы скептику явно."""
    п = AI.teh_lens_prompt([(0, 'ООО «Тест»', 'изделия из стеклопластика',
                             '22.29', 'тема', 'тело')], 'скептик')
    assert 'плазма режет' in п.lower() or 'плазма' in п
    assert 'стеклопластик' in п
