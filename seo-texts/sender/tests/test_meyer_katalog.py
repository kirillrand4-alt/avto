def test_korotkie_klyuchi_ne_lovyatsya_vnutri_chuzhih_slov():
    """Живой случай #986: «Полюс Красноярск — КРУПнейший производитель золота»
    получил ролик про сортировку круп, потому что ключ «круп» нашёлся внутри
    слова «крупнейший». Тот же класс ошибки, что «зерна» → элеватор.
    """
    от_обратного = (
        ("производство крупы, хлопьев и мюсли", "крупы"),
        ("переработка нута и чечевицы", "нут"),
        ("рисовая крупа высшего сорта", "рис"),
    )
    for текст, ждём in от_обратного:
        р = подобрать(текст, станок="фото")
        assert р and р["продукт"] == ждём, (текст, р)
    # Золотодобытчик теперь не ловится вовсе: «минералы и руда» из каталога
    # убраны по слову владельца, а «круп» больше не находится в «крупнейший».
    for пусто in ("Крупнейший производитель золота, добыча на рудных",
                  "через пять минут внутренний контроль качества",
                  "риск-менеджмент и страхование грузов"):
        assert подобрать(пусто, станок="фото") is None, пусто


def test_imya_na_obshchem_yashchike_ne_idyot_v_privetstvie():
    """Вопрос владельца: ФИО ЛПР, а адрес — приёмная.

    Надёжное имя не значит, что письмо откроет этот человек: на info@ и в
    приёмной «Здравствуйте, Иван Иванович» читает секретарь, и письмо сразу
    выглядит рассылкой, не понимающей, куда попала. Имя не выбрасываем — оно
    работает в просьбе передать.
    """
    общий = {"company_name": "ООО Завод", "okved": "10.61 крупы",
             "contact_name": "Иванов Иван Иванович",
             "extra": {"contact_source": "own-site:staff",
                       "contact_source_url": "https://zavod.ru/kontakty/",
                       "domain": "zavod.ru", "role": "приёмная"}}
    личный = dict(общий, extra=dict(общий["extra"], role="гл.инженер"))
    блок_общий = _recipient_block(0, общий, "meyer", 0)
    assert "по имени НЕ обращаться" in блок_общий, блок_общий
    assert "передайте письмо ему" in блок_общий
    assert "можно именное приветствие" not in блок_общий
    assert "можно именное приветствие" in _recipient_block(0, личный, "meyer", 0)


def test_kartochka_sama_reshaet_stavit_li_ssylku():
    """Перезалив 14.08 дал ноль ссылок при живом ролике в карточке.

    Причина: правило заканчивалось словами «если ролик не про их продукт — не
    вставляй вовсе», и модель перестраховывалась. Но релевантность мы теперь
    доказываем ДО модели: ролик подбирается по продукту из паспорта их сайта.
    Значит и решение принимаем мы, а не она.
    """
    с_паспортом = {"company_name": "АО ГК РЕСА", "okved": "01.11 зерновые",
                   "activity": "зерновые и масличные",
                   "extra": {"meyer_gradaciya": "мейер-фото",
                             "site_facts": {"продукция": ["лен", "горох"]}}}
    без = {"company_name": "ООО Икс", "okved": "10.61 мукомольное",
           "activity": "мука", "extra": {"meyer_gradaciya": "мейер-фото"}}
    строка = [с for с in _recipient_block(0, с_паспортом, "meyer", 0).splitlines()
              if "ВИДЕО-ДОКАЗАТЕЛЬСТВО" in с][0]
    assert "ссылку СТАВЬ" in строка, строка
    осторожно = [с for с in _recipient_block(0, без, "meyer", 0).splitlines()
                 if "ВИДЕО-ДОКАЗАТЕЛЬСТВО" in с][0]
    assert "паспортом сайта не подтверждён" in осторожно, осторожно


def test_dobycha_ruды_vne_nashego_profilya():
    """Слово владельца 14.08: «про золотодобычу — правильно что не пишет, не
    наше это».

    Обе модели отказались писать «Полюсу» сами и были правы, но узнали об этом,
    потратив по доллару на раунды починки, а письмо всё равно легло в очередь.
    Дешевле сказать заранее. Каталог отвечает на «кому мы пишем», а не «что
    умеет оборудование», поэтому «минералы и руда» из него убраны.
    """
    from sender.ai_letter import vne_profilya_meyer
    assert vne_profilya_meyer("07.29.41 добыча руд", "производство золота")
    assert vne_profilya_meyer("05.10 добыча угля", "")
    assert not vne_profilya_meyer("10.61 мукомольное производство", "мука")
    assert not vne_profilya_meyer("10.39 переработка овощей", "хумус")
    assert подобрать("добыча руды, золотодобыча", станок="фото") is None
    полюс = {"company_name": "АО Полюс", "okved": "07.29.41 добыча руд",
             "activity": "золото", "extra": {"meyer_gradaciya": "мейер-фото"}}
    блок = _recipient_block(0, полюс, "meyer", 0)
    assert "ВНЕ НАШЕГО ПРОФИЛЯ" in блок
    assert "Письмо по этой карточке НЕ пиши" in блок
