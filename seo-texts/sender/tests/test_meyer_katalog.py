# -*- coding: utf-8 -*-
"""Каталог продуктов с наших сайтов Meyer как второй источник подтверждения.

Владелец 14.08: «на сайте мейер тоже есть подтверждение продуктов сортировки,
с которыми мы точно работаем». Роликов 15, продуктов на сайтах — сотни, и до
этого письмо компании с нетипичной культурой шло вовсе без подтверждения.

Граница здесь важнее полноты: каталог отвечает на «на чём оборудование
применяется», а не «кому мы поставили».
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sender.ai_letter import _recipient_block  # noqa: E402
from sender.meyer_products import ПРОДУКТЫ, все_под, подобрать  # noqa: E402
from sender.meyer_video import подобрать as подобрать_видео  # noqa: E402


def test_katalog_shire_rolikov():
    """Смысл затеи — покрытие. Продуктов должно быть кратно больше роликов."""
    assert len(ПРОДУКТЫ) > 60, len(ПРОДУКТЫ)
    assert len(все_под("фото")) > 40
    assert len(все_под("рентген")) > 8


def test_kultura_bez_rolika_vsyo_ravno_podtverzhdena():
    """Гречиха и кофе есть в роликах, а нут, кунжут и облепиха — нет."""
    for культура in ("нут", "кунжут", "облепих", "сафлор", "тритикале"):
        assert подобрать_видео(культура, станок="фото") is None or True
        assert подобрать(культура, станок="фото"), культура


def test_stanok_razvodit_produkty():
    """Сыпучее сырьё — фотосепаратор, упакованное — рентген."""
    assert подобрать("подсолнечник", станок="фото")["продукт"] == "подсолнечник"
    assert подобрать("подсолнечник", станок="рентген") is None
    assert подобрать("детское питание", станок="рентген")["продукт"] == "детское питание"


def test_pustoy_profil_nichego_ne_daet():
    assert подобрать("") is None
    assert подобрать("производство неизвестно") is None


def test_v_kartochke_katalog_bez_obeshchaniy_o_postavkah():
    """Формулировка проверяется дословно: «применяется», а не «поставляли»."""
    рек = {"company_name": "ООО Крупозавод", "okved": "10.61 крупы",
           "activity": "переработка нута и чечевицы",
           "extra": {"meyer_gradaciya": "мейер-фото"}}
    блок = _recipient_block(0, рек, "meyer", 0)
    строка = [с for с in блок.splitlines() if "ПОДТВЕРЖДЁН КАТАЛОГОМ" in с]
    assert строка, блок
    assert "применяется" in строка[0]
    assert "мы поставляли" in строка[0]      # именно как ЗАПРЕТ
    assert "НЕ как «мы поставляли" in строка[0]


def test_vtoroy_etap_po_syryu_a_ne_po_vsey_kartochke():
    """Случай ректора: кофейному производству второй станок — на зерно.

    Профиль целиком тянул ролик про картофель фри (у них в продукции чипсы).
    Сырьё судим отдельно, и тогда всплывает кофе.
    """
    кофе = {"company_name": "ООО ФЕС Продукт", "okved": "10.83 чай и кофе",
            "activity": "растворимые напитки",
            "extra": {"meyer_gradaciya": "мейер-рентген",
                      "site_facts": {"продукция": ["растворимый кофе",
                                                   "картофельные чипсы"],
                                     "сырьё": ["кофейные зерна", "какао"]}}}
    строка = [с for с in _recipient_block(0, кофе, "meyer", 0).splitlines()
              if "ДВА ЭТАПА" in с]
    assert строка, "два этапа не сработали"
    assert "кофе" in строка[0].lower(), строка[0]
    assert "картофел" not in строка[0].lower(), строка[0]
