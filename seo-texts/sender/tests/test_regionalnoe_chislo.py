"""Региональное число — «до минимума» (владелец 19.08).

Оборот «46 опубликованных проектов по области» стоял в трёх письмах из
четырёх подряд: правило промпта разрешает его «если он сам повод письма», а
модель ставила довеском. Проверяю поведение заслона, а не наличие констант:

  * с флагом bez_regionalnogo_chisla гейт бракует письмо с таким оборотом;
  * без флага то же письмо проходит (запрет включается квотой, а не навсегда);
  * образец ловит разные формы: кейсы, проекты, внедрения;
  * промпт получателя с флагом несёт прямой запрет.

Тест обязан уметь провалиться: уберите проверку из gate — упадёт первый случай.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender import ai_letter as AI  # noqa: E402

ТЕЛО_С_ЧИСЛОМ = (
    "Добрый день!\n\n"
    "У «Тест» механическая обработка - на участках стоят станки с ЧПУ, и "
    "сжатый воздух идёт на обдув оснастки и пневмозажимы. Запас по "
    "производительности на таких линиях уходит быстрее, чем кажется.\n\n"
    "Я веду направление компрессорного оборудования в Компрессор Центре. "
    "В Новосибирской области у нас 46 опубликованных проектов.\n\n"
    "Подскажите, актуален ли для вас вопрос обновления компрессорного "
    "парка?\n\n"
    "С уважением,")
ТЕЛО_БЕЗ_ЧИСЛА = ТЕЛО_С_ЧИСЛОМ.replace(
    "В Новосибирской области у нас 46 опубликованных проектов.", "")


def _гейт(тело, extra):
    return AI.gate("Вопрос по компрессорному парку в «Тест»", тело,
                   mode="GENERIC", extra=extra, facts={}, division="kc")


def test_s_flagom_brakuet():
    fails = _гейт(ТЕЛО_С_ЧИСЛОМ, {"bez_regionalnogo_chisla": True})
    assert any("региональное число" in str(f) for f in fails), fails


def test_bez_flaga_prohodit():
    """Запрет включает квота по кампании, а не запрет навсегда."""
    fails = _гейт(ТЕЛО_С_ЧИСЛОМ, {})
    assert not any("региональное число" in str(f) for f in fails), fails


def test_pismo_bez_chisla_chisto():
    fails = _гейт(ТЕЛО_БЕЗ_ЧИСЛА, {"bez_regionalnogo_chisla": True})
    assert not any("региональное число" in str(f) for f in fails), fails


def test_obrazec_lovit_formy():
    о = AI._РЕГИОНАЛЬНОЕ_ЧИСЛО
    assert о.search("у нас 44 опубликованных кейса")
    assert о.search("46 опубликованных проектов по области")
    assert о.search("больше 5580 внедрений по стране")
    assert not о.search("компрессор на 8 бар и 12 кВт")


def test_promt_nesyot_zapret():
    блок = AI._recipient_block(
        0, {"mode": "GENERIC", "company_name": "ООО «Тест»",
            "activity": "мехобработка", "okved": "25.62",
            "extra": {"bez_regionalnogo_chisla": True}}, "kc", 0)
    assert "РЕГИОНАЛЬНОЕ ЧИСЛО НЕ УПОМИНАТЬ" in блок
