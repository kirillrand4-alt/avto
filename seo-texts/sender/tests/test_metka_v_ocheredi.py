# -*- coding: utf-8 -*-
"""Метка имени не должна доезжать до глаз редактора (13.08).

Генератор пишет письмо ДО выбора ящика и ставит метку ИМЯ_ОТПРАВИТЕЛЯ; движок
подставляет имя в предпросмотре и при отправке. Но окно «Править» в панели
открывается по СЫРОЙ строке письма, а не по предпросмотру — редактор увидела бы
там служебное слово капслоком и приняла бы его за брак.
"""
import os
import sys

sys.path.insert(
    0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender.gender_agree import (  # noqa: E402
    МЕТКА_ИМЕНИ, agree_for_mailbox, подставить_имя,
)

ПИСЬМО = ("Добрый день!\n\n"
          f"Меня зовут {МЕТКА_ИМЕНИ}, представляю компанию «Руспром Meyer». "
          "Работаю с молочными предприятиями.\n\n"
          "Буду признателен за короткий ответ.\n\nС уважением,")


def test_metka_uhodit_vmeste_s_rodom():
    """Одна точка: agree_for_mailbox и имя подставит, и род согласует."""
    вышло = agree_for_mailbox(ПИСЬМО, "Ирина Кузнецова, Meyer")
    assert МЕТКА_ИМЕНИ not in вышло
    assert "Меня зовут Ирина," in вышло
    assert "буду признательна" in вышло.lower()


def test_muzhskoy_yashchik_imya_tozhe_poluchaet():
    вышло = agree_for_mailbox(ПИСЬМО, "Алексей Козлов, Meyer")
    assert МЕТКА_ИМЕНИ not in вышло and "Меня зовут Алексей," in вышло
    assert "Буду признателен" in вышло


def test_povtornaya_podstanovka_bezopasna():
    """Тело в БД остаётся сырым, подстановка идёт и на показе, и на отправке."""
    один = подставить_имя(ПИСЬМО, "Ирина Кузнецова")
    два = подставить_имя(один, "Ирина Кузнецова")
    assert один == два


def test_pravka_redaktora_ne_lomaetsya_metkoy():
    """Если редактор сохранит правку по видимому тексту, метки там уже нет и
    повторная подстановка ничего не портит."""
    видимое = agree_for_mailbox(ПИСЬМО, "Ирина Кузнецова, Meyer")
    правка = видимое.replace("молочными предприятиями",
                             "молочными и сырными предприятиями")
    итог = agree_for_mailbox(правка, "Ирина Кузнецова, Meyer")
    assert итог == правка
