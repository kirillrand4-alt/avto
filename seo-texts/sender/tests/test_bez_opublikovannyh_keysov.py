def test_meyer_ne_tronut():
    """У Meyer свой редактор — его углы и правила править не просили.

    Сверяем блок углов Meyer с версией из гита построчно: тонкая логика тут
    не нужна, нужна ровно уверенность, что файл в этой части не менялся.
    """
    import subprocess
    from pathlib import Path

    корень = Path(__file__).resolve().parents[3]
    было = subprocess.run(
        ["git", "show", "HEAD:seo-texts/sender/ai_letter.py"],
        cwd=корень, capture_output=True, text=True).stdout
    if not было:
        return                       # нет гита под рукой — сравнивать нечем
    стало = Path(__file__).resolve().parents[1].joinpath(
        "ai_letter.py").read_text(encoding="utf-8")

    def углы(текст):
        н = текст.index("GENERIC_MECHANICS_MEYER = (")
        return текст[н:текст.index("\n)", н) + 2]

    assert углы(было) == углы(стало), "углы Meyer изменились, а не просили"


def test_korotkoe_imya_v_padezhe():
    """«Скала» в письме пишется «в Скале» — это НАЗВАНО.

    Основа бралась только у имён от шести букв, и пятибуквенные падежа не
    переживали: письмо «…парка в «Скале»» браковалось как безымянное. Новые
    заходы 19.08 это обострили — письмо, не начинающееся с названия, чаще
    упоминает компанию один раз и в косвенном падеже.
    """
    from sender.ai_letter import _predpriyatie_nazvano as f

    тело = "вопрос обновления парка в «Скале»? Если да, то под какие задачи"
    assert f('ООО "СКАЛА"', "", тело) is True
    assert f('ООО "ВОЛГА"', "на «Волге» стоят компрессоры", "") is not True
    assert f('ООО "ВОЛГА"', "", "на «Волге» стоят компрессоры") is True
    # четырёхбуквенную основу не берём: «СКА» нашлось бы где угодно
    assert f('ООО "СКАЛА"', "", "письмо без имени компании вовсе") is False
    # длинные имена как работали, так и работают
    assert f('ООО "ГАЗСТРОЙ"', "", "работы в Газстрое идут") is True
