"""Каждая фраза, которую генератор диктует письму, обязана иметь женский род.

Владелец 20.08 прислал скриншот отправленного письма: «Меня зовут
Анастасия, представляю компанию «Руспром Meyer»… Разбирался, чем
занимается «Эйва-Про»». Женская подпись и мужской глагол в соседних
абзацах.

Согласование по роду в панели есть и работает - «буду благодарна» в том
же письме стоит верно. Дыра была в словаре: он знал совершенный вид
(«разобрался») и не знал несовершенный («разбирался»), а именно эта форма
лежит в ZNAKOMSTVO, откуда генератор берёт фразу знакомства.

Замер по 1980 отправленным письмам: пять ушли с женских ящиков с мужским
глаголом - «разбирался» (2), «прошёлся» (2), «знакомился» (1).

Поэтому проверяем не отдельные слова, а ПРАВИЛО: любая фраза, которую мы
кладём в промпт готовой, должна согласовываться. Новая фраза без женской
формы уронит этот тест, а не уедет клиенту.
"""
import os
import re
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__),
                                                "..", "..")))

from sender.ai_letter import GENERIC_MECHANICS, ZNAKOMSTVO  # noqa: E402
from sender.gender_agree import _FEM, agree  # noqa: E402

# Мужское 1 лицо прошедшего времени: «-л», «-лся», кроме уже женских «-ла».
ГЛАГОЛ = re.compile(r"\b([А-ЯЁа-яё]+(?:лся|л))\b")


def _муж_глаголы(текст):
    из_ = set()
    for сл in ГЛАГОЛ.findall(текст):
        н = сл.lower()
        if н.endswith(("ла", "лась")) or len(н) < 4:
            continue
        из_.add(н)
    return из_


def test_kazhdaya_fraza_znakomstva_soglasuetsya():
    """Ровно тот случай, что попал к владельцу."""
    без = [z for z in ZNAKOMSTVO
           if z.split()[0].lower().strip(",") not in _FEM]
    assert без == [], без


def test_razbiralsya_stal_zhenskim():
    вышло = agree("Разбирался, чем занимается «Эйва-Про».", "f")
    assert "Разбиралась" in вышло, вышло


def test_mehaniki_zahoda_ne_nesut_nesoglasuemyh_glagolov():
    """Механики диктуют первую фразу - их глаголы тоже обязаны склоняться."""
    пропущены = set()
    for м in GENERIC_MECHANICS:
        for г in _муж_глаголы(м):
            if г not in _FEM:
                пропущены.add(г)
    assert пропущены == set(), пропущены


def test_muzhskoy_rod_ne_lomaetsya():
    """Мужской ящик не должен получить женские формы."""
    исходник = "Разбирался, чем занимается компания. Буду благодарен."
    assert agree(исходник, "m") == исходник


def test_idempotentno():
    """Женская форма второй раз не переписывается."""
    один = agree("Прошёлся по вашему сайту.", "f")
    два = agree(один, "f")
    assert один == два == "Прошлась по вашему сайту."
