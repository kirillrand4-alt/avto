"""Медицина — минус-класс (решение владельца 18.08).

Проверяю поведение, а не наличие констант:

  * клинике вердикт «не покупатель» ВЫНОСИТСЯ БЕЗ ВЫЗОВА модели;
  * старый кэш «покупатель» у клиники минус-класс не отменяет — иначе мы
    продолжали бы писать тем, кому уже насудили до решения;
  * фармзавод с «мед» в названии, но производственным ОКВЭД, НЕ режется:
    это цех со сжатым воздухом;
  * обычный завод по-прежнему судится моделью, а не отсекается вслепую.

Тест обязан уметь провалиться: уберите вызов минус_класс из judge — упадут
первые два случая.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender import target_gate as TG  # noqa: E402


def _гейт(tmp_path, ответ=None):
    зовы = []

    def caller(prompt):
        зовы.append(prompt)
        return ответ or '{"verdicts": []}'

    g = TG.TargetGate(str(tmp_path / "gate.db"), caller)
    return g, зовы


def test_klinika_rezhetsya_bez_modeli(tmp_path):
    g, зовы = _гейт(tmp_path)
    итог = g.judge([{"inn": "7700000001", "name": 'ООО "ГЛАЗНАЯ ХИРУРГИЯ"',
                     "okved": "86.10", "activity": "офтальмология"}])
    assert итог["7700000001"] == TG.НЕ_ПОКУПАТЕЛЬ
    assert зовы == []                      # провайдера не трогали вовсе


def test_staryy_kesh_ne_spasaet_kliniku(tmp_path):
    g, _ = _гейт(tmp_path)
    g._save("7700000002", TG.ПОКУПАТЕЛЬ, "кислород", "больницам нужен", "тест")
    итог = g.judge([{"inn": "7700000002", "name": 'ООО "МЦ ПАНАЦЕЯ"',
                     "okved": "86.10", "activity": "медцентр"}])
    assert итог["7700000002"] == TG.НЕ_ПОКУПАТЕЛЬ


def test_farmzavod_ne_rezhetsya(tmp_path):
    """«НПО ПЕТРОВАКС ФАРМ» — производство, сжатый воздух там нужен."""
    g, зовы = _гейт(tmp_path)
    итог = g.judge([{"inn": "7700000003",
                     "name": 'ООО "НПО МЕДИЦИНСКИЕ ПРЕПАРАТЫ"',
                     "okved": "21.20", "activity": "производство лекарств"}])
    assert итог.get("7700000003") != TG.НЕ_ПОКУПАТЕЛЬ
    assert зовы, "производственную компанию обязан судить провайдер"


def test_zavod_sudyat_modelyu(tmp_path):
    g, зовы = _гейт(tmp_path)
    g.judge([{"inn": "7700000004", "name": 'ООО "ЗАВОД"', "okved": "25.62",
              "activity": "механическая обработка"}])
    assert зовы, "обычную компанию минус-класс трогать не должен"


def test_minus_klass_pryamo():
    assert TG.минус_класс("86.10", "ООО Клиника")
    assert TG.минус_класс("47.11", "ООО Стоматология на Ленина")
    assert not TG.минус_класс("21.20", "ООО Медпрепараты")
    assert not TG.минус_класс("25.62", "ООО Завод")
    assert not TG.минус_класс("", "")
