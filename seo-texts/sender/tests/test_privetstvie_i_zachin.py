def test_sertifikaciya_v_opisanii_kompanii_ne_zachin():
    """Три ложные тревоги прогона по всем письмам 19.08.

    «производство и экспорт растительных масел с сертификацией Халяль» —
    это описание получателя, и письмо начинается именно с него. Регламент
    запрещён как ЗАЧИН, а не как слово.
    """
    for первый in (
        "Смотрел профиль масложирового завода «Сигма» - производство и "
        "экспорт растительных масел с сертификацией Халяль.",
        # Условие САМОГО получателя, а не чужой регламент: их производство
        # сертифицировано, отсюда и требование к чистоте. Такое письмо
        # начинается с получателя и остаётся законным.
        "Узлы для АЭС и гидромоторы - производство со строгими стандартами, "
        "где сертификация требует держать чистоту процессов.",
        "На производствах биоматериалов система сжатого воздуха попадает в "
        "зону внимания во время сертификационных проверок.",
    ):
        тело = f"Добрый день!\n\n{первый}" + ХВОСТ
        assert not any("регламент как причина письма" in str(f) for f in _гейт(тело)), первый


