def test_zhivye_pisma_vladelca_lovyatsya():
    """Два письма со скриншотов владельца 19.08 — оба должны браковаться.

    Фраза сидит ВНУТРИ третьего абзаца, после описания компании: правило
    «регламент открывает абзац» их не поймало бы, а прежнее «регламент
    где-то рядом» ловило заодно три законных письма.
    """
    для_проверки = [
        "«Кейтеринг технолоджи» выпускает шаурму с мясом, морепродуктами и "
        "овощами - аудиты торговых сетей и требования ХАССП требуют "
        "инспекции таких продуктов на посторонние включения перед отгрузкой.",
        "Салаирский молочносырзавод выпускает рассольные сыры, жареный сыр и "
        "масло с сертификацией по ХАССП - торговые сети и регулярные аудиты "
        "требуют, чтобы посторонних включений в упаковке не было.",
    ]
    for третий in для_проверки:
        тело = ("Добрый день!\n\n"
                "Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю «Руспром Meyer».\n\n"
                + третий + ХВОСТ)
        assert any("регламент как причина письма" in str(f)
                   for f in _гейт(тело)), третий[:60]
