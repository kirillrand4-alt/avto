"""Два брака из письма #1240 (владелец 19.08).

1. «Здравствуйте, Сергей Лещёв!» — по-русски так не здороваются. Форма
   обращения считалась верно («Сергей»), но полное имя стояло в промпте
   строкой «Контакт:», и модель взяла его целиком. Гейт приветствие не
   проверял вовсе.
2. «Аудиты торговых сетей и требования ХАССП предполагают...» — заход с
   чужого регламента. Взялся из наших же правил: там пара ПЛОХО/ХОРОШО про
   то, КАК упоминать HACCP, а модель прочла её как разрешение с этого
   НАЧИНАТЬ.

Тесты обязаны уметь провалиться: уберите проверки из gate — упадут первые
два случая.
"""

import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))

from sender import ai_letter as AI  # noqa: E402

ХВОСТ = ("\n\nДля готовой упакованной продукции применяется "
         "рентген-инспекция: оборудование выявляет металл, стекло, керамику "
         "и прочие плотные включения.\n\n"
         "Подскажите, актуальна ли для предприятия задача контроля "
         "включений в готовой продукции?\n\n"
         "Если это зона ответственности другого коллеги, подскажите, "
         "пожалуйста, с кем лучше связаться.\n\nС уважением,")


def _гейт(тело):
    return AI.gate("Вопрос по контролю включений", тело, mode="GENERIC",
                   extra={}, facts={}, division="meyer")


def test_familiya_v_privetstvii_brakuetsya():
    тело = ("Здравствуйте, Сергей Лещёв!\n\nМеня зовут ИМЯ_ОТПРАВИТЕЛЯ, "
            "представляю «Руспром Meyer». «Тест» выпускает су-вид "
            "полуфабрикаты и выпечку." + ХВОСТ)
    assert any("приветствие с фамилией" in str(f) for f in _гейт(тело))


