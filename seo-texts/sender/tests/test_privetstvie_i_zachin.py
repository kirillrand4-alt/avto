def test_zahod_s_reglamenta_brakuetsya():
    """СТРУКТУРА КАК В ЖИВОМ #1240: приветствие, представление, регламент.

    Первая редакция заслона смотрела два абзаца и живое письмо не поймала бы
    — регламент стоял третьим, после мейеровского представления. Тест был
    написан под реализацию, а не под письмо, и это скрывало дыру.
    """
    тело = ("Добрый день!\n\n"
            "Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю компанию «Руспром "
            "Meyer». Работаю с производителями готовых блюд по вопросам "
            "контроля посторонних включений.\n\n"
            "Аудиты торговых сетей и требования ХАССП предполагают "
            "документированный контроль включений на всех этапах - от "
            "приёмки сырья до отгрузки." + ХВОСТ)
    assert any("регламент как причина письма" in str(f) for f in _гейт(тело))


