# -*- coding: utf-8 -*-
"""Квота на форму первой фразы вместо запрета одного захода.

12.08 в промпт и гейт поставили жёсткий запрет на «Смотрел профиль…» — потому
что 186 писем очереди начинались одинаково. Запрет проблему не решил, а
подвинул: модель выдала новый штамп, 37% партии начались с «На».

Владелец: «заменить запрет на квоту». Плохо не слово, а одинаковость партии,
поэтому считаем ФОРМУ зачина и держим потолок в треть партии. Первые письма
квоту занимают и остаются как есть, лишние идут на перегенерацию — и только им
промпт говорит, какую форму повторять нельзя.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sender.ai_letter import (форма_захода, gate,  # noqa: E402
                              zahod_overflow)


def _письмо(первая: str) -> str:
    return (f"Добрый день!\n\n{первая}\n\nЯ веду компрессорное направление "
            "в Компрессор Центре. Подскажите, актуален ли сейчас вопрос "
            "по компрессорному парку? Если да, помогу с пневмоаудитом "
            "и расчётом конфигурации под ваше потребление воздуха.\n\n"
            "Если тема сейчас неактуальна, буду признателен за короткий "
            "ответ, чтобы в дальнейшем вас не отвлекать.\n\nС уважением,")


# --- распознавание формы ----------------------------------------------------- #

def test_zahod_ot_profilya_uznayotsya_v_raznyh_slovah():
    """Одна форма, разные глаголы: запрет по словам их бы не поймал."""
    for первая in ("Смотрел профиль «Лука»: профили и пороги.",
                   "Изучил профиль «Вириал»: техническая керамика.",
                   "Посмотрел, чем занимается «СПС»: трубопроводы.",
                   "Судя по профилю, у вас лазерный раскрой."):
        assert форма_захода(_письмо(первая)) == 'от профиля', первая


def test_privetstvie_ne_schitaetsya_zahodom():
    assert форма_захода(_письмо("На таком переделе воздух идёт непрерывно."))\
        == 'от площадки'


def test_neznakomyy_zahod_opoznayotsya_po_slovam():
    """Иначе квота ловила бы только перечисленные формы."""
    assert форма_захода(_письмо("Ваши сварочные посты требуют воздуха.")) \
        == 'ваши сварочные'


def test_pustoe_telo_ne_lomaet():
    assert форма_захода("") == '' and форма_захода(None) == ''


# --- сама квота -------------------------------------------------------------- #

def test_tret_partii_zahod_sohranyaet():
    """Шесть писем одной формой: двое остаются, четверо переписывают."""
    партия = [_письмо(f"Смотрел профиль «Фирма {i}»: металлоконструкции.")
              for i in range(6)]
    лишние = zahod_overflow(партия)
    assert sorted(лишние) == [2, 3, 4, 5]
    assert set(лишние.values()) == {'от профиля'}


def test_raznye_zahody_kvotu_ne_prevyshayut():
    партия = [_письмо("Смотрел профиль «А»: металлоконструкции."),
              _письмо("На участке окраски воздух идёт непрерывно."),
              _письмо("Если рез лазерный, важна чистота азота."),
              _письмо("Подскажите, чем закрываете пиковый расход?")]
    assert zahod_overflow(партия) == {}


def test_novyy_shtamp_lovitsya_tak_zhe():
    """Ровно тот случай, который создал прошлый запрет: партия на «На…»."""
    партия = [_письмо(f"На участке {i} воздух делится между постами.")
              for i in range(6)]
    лишние = zahod_overflow(партия)
    assert len(лишние) == 4 and set(лишние.values()) == {'от площадки'}


def test_odno_pismo_kvotu_ne_narushaet():
    assert zahod_overflow([_письмо("Смотрел профиль «А»: трубы.")]) == {}


# --- гейт следит только за помеченными --------------------------------------- #

def _fails(тело, extra=None):
    return [f for f in gate('Вопрос по компрессорному парку в «Лука»', тело,
                            extra=extra or {}) if 'заход' in f]


def test_gate_ne_zapreshchaet_zahod_bez_pometki():
    """Главная правка: сам по себе «Смотрел профиль» больше не брак."""
    assert _fails(_письмо("Смотрел профиль «Лука»: профили и пороги.")) == []


def test_gate_brakuet_povtor_togo_zhe_zahoda_u_pomechennogo():
    тело = _письмо("Смотрел профиль «Лука»: профили и пороги.")
    assert _fails(тело, {'сменить_заход': 'от профиля'})


def test_gate_propuskaet_smenivshego_zahod():
    тело = _письмо("На участке окраски воздух идёт непрерывно.")
    assert _fails(тело, {'сменить_заход': 'от профиля'}) == []
