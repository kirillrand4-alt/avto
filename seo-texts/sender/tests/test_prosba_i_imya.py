"""Просьба перенаправить: решает не имя, а КТО адресат.

Владелец 17.08 сперва «просьбы перенаправить для обращений с именем быть не
должно», затем уточнил «хотя опять же если это не ЛПР а закупщик то можно».
Значит состояний три, а не два.
"""
import os
import sys

