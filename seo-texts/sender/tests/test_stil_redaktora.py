# -*- coding: utf-8 -*-
"""Стиль писем Meyer подстроен под редактора (правки 13.08).

Владелец прислал три письма, которые редактор переписала перед отправкой, и
попросил подстроиться под её стиль. Правки системные, одни и те же во всех
трёх: убраны страшилки и укол в металлодетектор, представление вынесено в
первую строку, добавлен второй станок там, где у компании есть обе задачи,
закрытие сменилось на открытый вопрос, длина выросла вдвое.

Здесь проверяем, что новые правила действительно стоят в промпте и что гейт
пропускает её стиль и ловит старый.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from sender.ai_letter import RULES_MEYER, _recipient_block, gate  # noqa: E402
from sender.gender_agree import подставить_имя  # noqa: E402

# Письмо в новом каноне: представление меткой, факт о них, что применяется,
# открытый вопрос, просьба перенаправить, отказ, «С уважением,».
ПО_КАНОНУ = (
    "Добрый день!\n\n"
    "Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю компанию «Руспром Meyer». Работаю "
    "с молочными предприятиями по вопросам контроля качества продукции.\n\n"
    "На вашем производстве контроль охватывает весь цикл, от приёмки сырья до "
    "готовой продукции. В связи с этим обращаюсь по вопросу контроля продукта "
    "на предмет посторонних включений.\n\n"
    "Для таких задач применяется рентген-инспекция: оборудование выявляет "
    "металл, стекло, камень, керамику, силикон и другие плотные посторонние "
    "включения. Контролировать можно на разных этапах, от сырья до готовой "
    "упаковки, и это не требует перестройки линии.\n\n"
    "Подскажите, используется ли у вас сейчас такой контроль и актуальна ли "
    "эта задача для предприятия?\n\n"
    "Если этим вопросом занимается другой специалист, буду признателен, если "
    "перенаправите ему письмо.\n\n"
    "Если тема сейчас неактуальна, буду признателен за короткий ответ, чтобы "
    "в дальнейшем вас не отвлекать.\n\n"
    "С уважением,")


def _fails(тело, **kw):
    return gate("Вопрос по контролю качества в «Лактис»", тело,
                division="meyer", **kw)


# --- правила в промпте ------------------------------------------------------- #

def test_pravila_nesut_kanon_redaktora():
    for кусок in ("БЕЗ СТРАШИЛОК", "ДВА СТАНКА MEYER В ОДНОМ ПИСЬМЕ",
                  "ИМЯ_ОТПРАВИТЕЛЯ", "ПРО МЕТАЛЛОДЕТЕКТОР В ХОЛОДНОМ ПИСЬМЕ",
                  "140-190 слов", "ПРОСЬБА ПЕРЕНАПРАВИТЬ",
                  "ОТКРЫТЫЙ ВОПРОС"):
        assert кусок in RULES_MEYER, кусок


def test_etalon_iz_pisem_redaktora():
    """Старые выдуманные фрагменты заменены её реальными письмами."""
    assert "ТРИ ПИСЬМА РЕДАКТОРА" in RULES_MEYER
    assert "переборщицы к концу смены" not in RULES_MEYER


def test_vtoroy_stanok_razreshyon_v_kartochke():
    рек = {"company_name": "ООО Крупозавод", "okved": "10.61",
           "extra": {"meyer_gradaciya": "рентген"}}
    блок = _recipient_block(0, рек, "meyer", 0)
    assert "ГЛАВНЫЙ СТАНОК ПАРТИИ" in блок
    assert "не упоминать вовсе" not in блок


# --- гейт пропускает новый стиль --------------------------------------------- #

def test_pismo_po_kanonu_prohodit():
    fails = [f for f in _fails(ПО_КАНОНУ)
             if "объём" in f or "заход" in f or "страшил" in f
             or "металлодетектор" in f or "ИМЯ_ОТПРАВИТЕЛЯ" in f]
    assert fails == [], fails


def test_dlina_kanona_ne_brakuetsya():
    """Старый потолок 140 слов зарубил бы её стиль: у неё 150-180."""
    assert not any("объём" in f for f in _fails(ПО_КАНОНУ)), _fails(ПО_КАНОНУ)


def test_kompressornoe_pismo_derzhit_staryy_potolok():
    длинное = ("Добрый день!\n\n" + "слово " * 160
               + "\n\nЕсли тема сейчас неактуальна, буду признателен за "
                 "короткий ответ, чтобы в дальнейшем вас не отвлекать.\n\n"
                 "С уважением,")
    assert any("объём" in f for f in gate("Вопрос по парку", длинное,
                                          division="kc"))


# --- гейт ловит старый стиль -------------------------------------------------- #

def test_strashilka_brakuetsya():
    плохое = ПО_КАНОНУ.replace(
        "Для таких задач применяется рентген-инспекция:",
        "Осколок доходит до торговой сети, и это удар по репутации. "
        "Для таких задач применяется рентген-инспекция:")
    assert any("страшилка" in f for f in _fails(плохое)), _fails(плохое)


def test_metallodetektor_brakuetsya():
    плохое = ПО_КАНОНУ.replace(
        "Для таких задач применяется",
        "Металлодетектор стекло не видит. Для таких задач применяется")
    assert any("металлодетектор" in f for f in _fails(плохое))


def test_pridumannoe_imya_brakuetsya():
    """Модель не знает ящика — имя обязано быть меткой."""
    плохое = ПО_КАНОНУ.replace("ИМЯ_ОТПРАВИТЕЛЯ", "Сергей")
    assert any("ИМЯ_ОТПРАВИТЕЛЯ" in f for f in _fails(плохое)), _fails(плохое)


# --- подстановка имени -------------------------------------------------------- #

def test_metka_zamenyaetsya_lichnym_imenem():
    вышло = подставить_имя(ПО_КАНОНУ, "Ирина Кузнецова, Meyer")
    assert "Меня зовут Ирина," in вышло and "ИМЯ_ОТПРАВИТЕЛЯ" not in вышло


def test_bez_imeni_oborot_ubiraetsya_tselikom():
    """Пустое имя не должно оставить метку в первой строке."""
    вышло = подставить_имя(ПО_КАНОНУ, "")
    assert "ИМЯ_ОТПРАВИТЕЛЯ" not in вышло and "Меня зовут" not in вышло
    assert "представляю компанию" in вышло


def test_pismo_bez_metki_ne_trogaem():
    т = "Добрый день!\n\nОбычное письмо.\n\nС уважением,"
    assert подставить_имя(т, "Ирина Кузнецова") == т
