# -*- coding: utf-8 -*-
"""Телефон из блока РЕКВИЗИТОВ — это линия предприятия, а не номер подписанта.

НАШЁЛ ВЛАДЕЛЕЦ. В карточке АО «Инфраструктурные Проекты» стоял «технический ЛПР Лебедь Олег
Александрович, мобильный +7 949 314 55 05». Он попросил показать первоисточник, потому что по
ссылке имени не нашёл. Разобрала до конца:

  * ИМЯ ДОКАЗАНО, и доказано сильно. Вложение `eis_f_32413842425_6.bin`, документ «Проект
    Договора СбТЭС.docx»: «АО «ИНФРАСТРУКТУРНЫЕ ПРОЕКТЫ» … в лице заместителя главного
    инженера по эксплуатации Лебедя Олега Александровича, действующего на основании
    Доверенности от 25.06.2024 № 2506/1». Это подписант по доверенности — привязка к
    предприятию крепче не бывает. Почему владелец не нашёл: ссылка в карточке ведёт на
    страницу закупки, а имя лежит ВНУТРИ приложенного файла. Ссылка не на тот уровень.
  * ТЕЛЕФОН НЕ ЕГО. Он стоит в блоке реквизитов заказчика:
        «Адрес: … ОГРН 1221500003812 ИНН 1500004950 КПП … р/с … БИК … к/с …
         Тел.: +7 949 314 55 05  e-mail: delo@in-pr.ru
         Заместитель главного инженера по эксплуатации … ____________ О.А. Лебедь»
    То есть это общий телефон юрлица, а подпись идёт СЛЕДОМ. Мой заслон «номер берётся, если
    рядом фамилия» здесь сработал ровно наоборот: в реквизитах рядом с номером всегда стоит
    подписант, и любой договор даст ложный личный номер.
    Та же почта delo@in-pr.ru показана в карточке как ПОЧТА ПРЕДПРИЯТИЯ — то есть база уже
    знала, что это общий адрес, и всё равно выдала его как контакт человека.

ЗДЕСЬ СЧИТАЕТСЯ, СКОЛЬКО ТАКИХ ПО ВСЕЙ БАЗЕ. Признак блока реквизитов однозначен и не
требует догадок: в окне перед номером стоят ОГРН, ИНН, КПП, р/с, БИК или к/с.
"""
import collections
import csv
import json
import re
import sys

REKV = re.compile(r'\bОГРН\b|\bКПП\b|р/с|к/с|\bБИК\b|расчётн\w+ счёт|корреспондентск', re.I)
TEL = re.compile(r'\+?7[\s\-(]*\d{3}[\s\-)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}')

put = sys.argv[1] if len(sys.argv) > 1 else 'zhurnal/vlozheniya-lica.csv'
csv.field_size_limit(10 ** 7)
rows = list(csv.DictReader(open(put, encoding='utf-8-sig'), delimiter=';'))
print('колонки:', list(rows[0]))
sch = collections.Counter()
primery = []
for r in rows:
    cit = ' '.join(str(v) for v in r.values() if v and len(str(v)) > 40)
    tel = next((v for k, v in r.items() if 'tel' in k.lower() and v), '')
    if not tel:
        sch['без телефона'] += 1
        continue
    m = TEL.search(cit)
    if not m:
        sch['телефон есть, но цитаты с ним нет — судить не по чему'] += 1
        continue
    okno = cit[max(0, m.start() - 260):m.start()]
    if REKV.search(okno):
        sch['ТЕЛЕФОН ИЗ БЛОКА РЕКВИЗИТОВ — линия предприятия'] += 1
        if len(primery) < 5:
            primery.append({'kto': (r.get('fio') or r.get('chelovek') or '')[:40],
                            'tel': tel, 'okno': okno[-160:]})
    else:
        sch['номер не в реквизитах — привязка не опровергнута'] += 1
print(json.dumps({'строк': len(rows), 'счёт': dict(sch), 'примеры': primery},
                 ensure_ascii=False, indent=1)[:2200])
