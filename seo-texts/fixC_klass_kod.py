_LAT_KIR = str.maketrans("cCoOeEaApPxXyKkMTBH", "сСоОеЕаАрРхХуКкМТВН")


def _norm_tekst(*chasti) -> str:
    t = " ".join(str(c or "") for c in chasti).replace("ё", "е").replace("Ё", "Е").strip()
    # латиница-двойник внутри русского слова («отдел cнабжения» с латинской c)
    return re.sub(r"[А-Яа-я]*[cCoOeEaApPxXyKkMTBH][А-Яа-яcCoOeEaApPxXyKkMTBH]*",
                  lambda m: m.group(0).translate(_LAT_KIR) if re.search(r"[А-Яа-я]", m.group(0)) else m.group(0), t)


def vid_po_tekstu(tekst: str) -> str:
    t = _norm_tekst(tekst).casefold()
    if not t:
        return ""
    for vid, rx in _PRAVILA_RE:
        if rx.search(t):
            return vid
    return ""


def rol_kontakta(item: dict) -> dict:
    """Роль номера по смыслу. -> {"vid", "lpr", "uroven", "teh", "zakup", "musor"}.

    Порядок решения: ручной вид (rol_vruchnuyu) → номер с чужой страницы → мусор/битый
    (vid_nomera) → должность (position) → прежняя роль (role) → «без подписи».
    """
    ruchnoy = str(item.get("rol_vruchnuyu") or "").strip()
    vid = ""
    if ruchnoy:
        vid = ruchnoy
    elif str(item.get("chuzhoy_istochnik") or "").strip():
        vid = "с сайта другого юрлица"
    elif str(item.get("vid_nomera") or "").strip() in VIDY_MUSOR | {"номер только в ссылке tel:"}:
        vid = str(item.get("vid_nomera")).strip()
    else:
        dolzh = str(item.get("position") or "").strip()
        rol = str(item.get("role") or "").strip()
        istochnik = str(item.get("source") or "")
        if re.match(r"(?i)контактн\w* лицо закупки", dolzh) or "номер на карточке закупки" in istochnik:
            predmet = istochnik.split("номер на карточке закупки;", 1)[-1].split("Заказчик", 1)[0]
            if _EIS_OBORUD.search(predmet):
                vid = "снабжение"
            elif re.search(_SYRYO, _norm_tekst(predmet).casefold()):
                vid = "закупки сырья"
            else:
                vid = "контрактный менеджер ЕИС"
        elif dolzh and not _OBSHCHAYA.match(dolzh):
            vid = vid_po_tekstu(dolzh) or ""
            if not vid:
                # должность не опознана: прежняя роль годится, только если она не ЛПР
                # («заместитель гендиректора по строительству» с ролью «директор/руководитель»
                # не первое лицо)
                po_roli = _PO_ROLI.get(rol, "")
                vid = po_roli if po_roli and po_roli not in ROLI_LPR else "другая должность"
        if not vid and rol:
            vid = vid_po_tekstu(rol) if rol not in _PO_ROLI else _PO_ROLI[rol]
        if not vid:
            vid = "без подписи"
    uroven = ROLI_LPR.get(vid, 0)
    return {"vid": vid, "lpr": int(bool(uroven)), "uroven": uroven,
            "teh": int(vid in ROLI_TEH), "zakup": int(vid == "снабжение"),
            "musor": int(vid in VIDY_MUSOR or vid in ("с сайта другого юрлица", "номер только в ссылке tel:"))}


def vid_nomera_po_cifram(value: object) -> str:
    """Вид номера по цифрам: мобильный / 8-800 / городской / Казахстан / международный / битый."""
    osn, dob = _razdelit_dobavochnyy(value)
    s = str(osn or "").strip()
    d = re.sub(r"\D", "", s)
    if s.startswith("+") and not s.startswith("+7"):
        return "международный" if 8 <= len(d) <= 15 else "битый номер"
    if len(d) == 11 and d[0] == "8":
        d = "7" + d[1:]
    if len(d) == 10:
        d = "7" + d
    if len(d) != 11 or d[0] != "7":
        return "битый номер"
    if d[1] == "7":
        return "Казахстан"
    if d[1:4] == "800":
        return "8-800"
    if d[1] == "9":
        return "мобильный"
    if d[1] not in "3489":
        return "битый номер"
    return "рабочий с добавочным" if dob else "рабочий"
