# -*- coding: utf-8 -*-
"""285 фактов в парке — это компрессоры НА БУРОВЫХ УСТАНОВКАХ. Помечаю, а не выбрасываю.

Очередь сторожа говорит «дочистить помеченные провайдером НЕ НАША МАШИНА (буровая техника
Atlas Copco)». Померил: провайдерская чистка уже сделана — все 10 364 факта с типом
«НЕ НАША МАШИНА» имеют `vid_fakta='НЕТ'` и в парке их НОЛЬ.

Но нашлось соседнее: 285 фактов В ПАРКЕ, где речь о компрессоре в составе буровой
установки: «Закупка компрессора винтового в сборе для буровой установки DM45-LP
(Atlas Copco)», «запчасти для компрессора Atlas Copco XL1900 бурового станка PitViper».

Выбрасывать нельзя, и вот почему: предприятие ПОКУПАЕТ КОМПРЕССОР — для продавца
компрессоров это живой сигнал, даже если машина стоит на буровом станке. Но и молчать
нельзя: это не отдельно стоящая промышленная установка, и продавец должен знать разницу
ДО звонка. Поэтому — пометка в `pochemu`, видимая в карточке, и отдельный список соседке,
у которой уже есть провайдерский разбор предметов.
"""
import os, re, sqlite3

D = os.path.dirname(os.path.abspath(__file__))
p = sqlite3.connect(os.path.join(D, 'park.db'))
c = p.cursor()
BUR = re.compile(r'буров|перфоратор|\bdrill\b|PitViper|PowerROC|SmartROC|Boomer|Simba|DM-?\d{2}',
                 re.I)
POMETKA = ('компрессор В СОСТАВЕ БУРОВОЙ УСТАНОВКИ — сигнал живой (предприятие покупает '
           'компрессор), но это не отдельно стоящая промышленная машина')
# СНАЧАЛА СОБИРАЕМ, ПОТОМ ПИШЕМ. Первый прогон пометил 1 факт вместо 285: я писал
# UPDATE тем же курсором, по которому шёл SELECT, и обход обрывался на первой же записи.
# Ошибка тихая — счётчик показал «1», и без сверки с замером я бы решил, что их и было 1.
celi = [(fid, i) for fid, i, txt, poch in c.execute(
            "select id, inn, coalesce(chto_naydeno,''), coalesce(pochemu,'') from fakt"
            " where v_parke=1").fetchall()
        if BUR.search(txt) and POMETKA not in poch]
n = 0
inn = set()
for fid, i in celi:
    c.execute("update fakt set pochemu = case when coalesce(pochemu,'')='' then ? "
              "else pochemu || ' | ' || ? end where id=?", (POMETKA, POMETKA, fid))
    n += 1
    inn.add(i)
p.commit()
print('помечено фактов: %d на %d предприятиях' % (n, len(inn)))
print('в парке они ОСТАЮТСЯ — предприятие покупает компрессор')
q = lambda s: c.execute(s).fetchone()[0]
print('всего с пометкой в базе: %d' % q("select count(*) from fakt where pochemu like '%В СОСТАВЕ БУРОВОЙ%'"))
p.close()
