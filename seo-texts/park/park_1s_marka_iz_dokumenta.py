# -*- coding: utf-8 -*-
"""Марка берётся из СЛОВА В ДОКУМЕНТЕ, а не из формы кода.

Правило дала 3-я сессия, разрешив наш спор про К-601 цитатой самого заключения ЭПБ:

    «Центробежный компрессор КВД ТИП 3М7 (компрессор высокого давления компрессорной
     установки К-901), ТЕХНОЛОГИЧЕСКИЙ ИНДЕКС К-901 КВД, заводской № 3-7-3228»

Документ сам называет вещи: марка — `3М7`, а `К-901` — технологический индекс, то есть
позиция. Значит различать марку и позицию надо не по форме кода (я пробовал — ловит
настоящие модели ЦК-135/8, ВК9020, ТВ-80), а по слову, которое стоит рядом в документе.

Проверил правило на своих 39 879 фактах выдачи, и оно сработало В ОБЕ СТОРОНЫ:

    в тексте есть «технологический индекс» ....... 86 фактов
    из них марка совпала с индексом (то есть в марку попала позиция) ... 14
    из них марка НЕ равна индексу (значит марка настоящая) ............. 5

Пять «оправданных» — ровно тот случай, о котором 3-я сессия предупреждала: `К-250-61-2`
при позиции `М-14`, `К-1290-121-1` при позиции `402`. Префикс тот же самый «К», а вещи
разные, и различает их только документ:

    22347  марка К-250-61-2   тип К-250-61-2   индекс М-14      -> марка настоящая
    21856  марка К-602        тип 3М-10-8      индекс К-602 КВД -> в марке позиция

Это дополняет мой прежний признак («предмет факта — узел, а не машина»), а не спорит с ним:
у всех 14 найденных пометки `marka_pozicionnaya` НЕ стояло, потому что предмет там — сама
машина, компрессор. Два признака ловят разные срезы одного класса.

Главное отличие от пометки: здесь мы не только помечаем порок, но и **достаём настоящую
марку** — 3М7, 3М9-7, 3М-10-8, 553-В9, 373-В5/5, 272-В7/1R, 4М-8-6. Прежнее значение не
затирается молча: оно уезжает в `marka_pozicionnaya_kod`, чтобы связь с документом не
потерялась и правку можно было отменить.

Второй заход — добор: у фактов БЕЗ марки в тексте бывает «тип X». Отсеиваю мусор, потому
что слово «тип» встречается и в «№ 12-ТУ», и в «тип не установлен»: беру только кода с
цифрой, длиной от 4 знаков, вне стоп-списка.

Досмотрел все 64 уникальных значения добора глазами — и **отсев по одному мусору оказался
мал**. Настоящие марки там есть (Н-370-18-1, Н-280-12-7, ВШВ-3/100, 4ВМ10-100/8, ТГ-170-1,
2BCL-607, SBD250/150, EGSI-S-140/1400), но рядом лезет марка НЕ ТОЙ ВЕЩИ:

    «Электродвигатель взрывозащищенного исполнения тип ВАСО4-13-12УХЛ-1»  — 22 факта
    «Предохранительный клапан тип 2600»                                    — 12 фактов
    «Конденсатор системы кондиционирования воздуха тип SPRx-63»

Это тот же класс, что ловит мой прежний признак «предмет факта — узел, а не машина». Но
прежний признак смотрел ГОЛОВУ описания, и на доборе он оказался негоден: перед предметом
часто стоит название ОПО — «Площадка промысловой компрессорной станции Ямсовейского
месторождения ... Электродвигатель тип ВАСО4-13-12УХЛ-1» — и слово «компрессорной»
перебивало узел. Пропускал 32 факта из 190.

Заслон переписан с привязкой к самому «тип X»: чьё название стоит БЛИЖЕ к нему слева, того
и марка. И к машинам добавлены аббревиатуры ЦБН/ЦБК (центробежный нагнетатель) и
ЦНД/ЦВД/ЦСД/КВД/КНД/КСД (цилиндры компрессора) — без них заслон срезал настоящие марки
«Корпус ЦБН тип Н-370-18-1» и «ЦНД тип 3М9-7».

Третья корзина — «неясно»: если рядом нет ни машины, ни узла, вердикт не выносится и марка
не пишется. Таких 2 («СИСТЕМА ВОЗДУШНОГО ОХЛАЖДЕНИЯ тип АВГ-9-ж-6-Б1-в3/6-6-4»), они
остаются в очереди. Гадать вслепую хуже, чем оставить пустым.

Итог заслона: берём 117, отсеиваем 71 (предохранительные клапаны, электродвигатели),
неясно 2. Два признака работают вместе: её правило говорит, ГДЕ марка, мой заслон — ЧЬЯ.

Запуск: python3 park_1s_marka_iz_dokumenta.py [--pisat]
"""
import os, re, sqlite3, sys, time

D = os.path.dirname(os.path.abspath(__file__))
PISAT = '--pisat' in sys.argv
INDEKS = re.compile(r'технологическ\w+\s+индекс\w*\s*([A-ZА-Я0-9][^,;.)]{0,24})', re.I)
TIP = re.compile(r'\bтип\s+([A-ZА-Я0-9][A-ZА-Я0-9/\-]{1,22})', re.I)
# «тип» в документах значит не только марку: «заключение № 12-ТУ», «тип не установлен»
STOP = {'ТУ', 'НЕ', 'ТС', 'ТП', 'II', 'III', 'ES', 'GM', 'АКЕ', 'ОПО', 'ЭПБ', 'ПБ'}


def normal(s):
    return re.sub(r'[\s\-«»"]', '', s or '').upper()


def indeks_i_tip(tekst):
    """-> (технологический индекс, тип) — то, как их называет сам документ."""
    i = INDEKS.search(tekst or '')
    t = TIP.search(tekst or '')
    return (i.group(1).strip() if i else ''), (t.group(1).strip() if t else '')


def marka_eto_poziciya(marka, indeks):
    """True — в поле марки лежит то, что документ зовёт технологическим индексом."""
    if not marka or not indeks:
        return False
    m, i = normal(marka), normal(indeks)
    return m in i or i.startswith(m)


def godnaya_marka(tip):
    """Отсев мусора: марка обязана иметь цифру и длину, и не быть служебным словом."""
    t = (tip or '').strip()
    return bool(t) and len(t) >= 4 and any(c.isdigit() for c in t) and t.upper() not in STOP


# Заслон «чья это марка». Первый вариант смотрел голову описания — и оказался негодным:
# перед предметом часто стоит название ОПО, «Площадка промысловой компрессорной станции
# Ямсовейского месторождения ... Электродвигатель тип ВАСО4-13-12УХЛ-1», и слово
# «компрессорной» перебивало узел. Пропускало 32 факта из 190.
# Признак привязан к самому «тип X»: чьё название стоит БЛИЖЕ к нему слева, того и марка.
UZEL = re.compile(r'(электродвигател|клапан|конденсатор|горелк|вентилятор|мультипликатор|'
                  r'теплообменник|сепаратор|холодильник|трубопровод|бак|насос|фильтр|'
                  r'маслоохладител|нагревател|редуктор|муфт|подшипник)', re.I)
# аббревиатуры самих машин и их ступеней: ЦБН/ЦБК — центробежный нагнетатель,
# ЦНД/ЦВД/ЦСД/КВД/КНД/КСД — цилиндры компрессора. Без них заслон резал настоящие марки
# («Корпус ЦБН тип Н-370-18-1», «ЦНД тип 3М9-7»).
MASH = re.compile(r'(компрессор|воздуходувк|нагнетател|турбокомпрессор|генератор|мкс|ресивер|'
                  r'воздухосборник|рессивер|установк|агрегат|гпа|станци|'
                  r'\bЦБН\b|\bЦБК\b|\bЦНД\b|\bЦВД\b|\bЦСД\b|\bКВД\b|\bКНД\b|\bКСД\b)', re.I)


def chya_marka(tekst, poz_tip):
    """-> 'машина' | 'узел' | 'неясно' по тому, чьё название ближе к слову «тип» слева."""
    pered = (tekst or '')[max(0, poz_tip - 60):poz_tip]
    u, m = list(UZEL.finditer(pered)), list(MASH.finditer(pered))
    if not u and not m:
        return 'неясно'
    return 'машина' if (m[-1].start() if m else -1) > (u[-1].start() if u else -1) else 'узел'


p = sqlite3.connect(os.path.join(D, 'park.db'), timeout=120)
c = p.cursor()
est = [r[1] for r in c.execute('pragma table_info(fakt)')]
if PISAT:
    for kol in ('marka_pozicionnaya_kod', 'marka_iz_dokumenta'):
        if kol not in est:
            c.execute('alter table fakt add column %s text' % kol)

V = "v_parke=1 and coalesce(v_obzvone,0)=0 and coalesce(posrednik,0)=0"
rows = c.execute(f"""select id, inn, coalesce(marka,''), coalesce(chto_naydeno,'')
                       from fakt where {V}""").fetchall()
pochineno, opravdano, dobrano, bez_tipa, ne_ta_veshch, neyasno = [], [], [], 0, 0, 0
for fid, inn, marka, tekst in rows:
    ind, tip = indeks_i_tip(tekst)
    m_tip = TIP.search(tekst or '')
    chya = chya_marka(tekst, m_tip.start()) if m_tip else 'неясно'
    if marka and ind:
        if marka_eto_poziciya(marka, ind):
            if godnaya_marka(tip) and chya == 'машина':
                pochineno.append((fid, inn, marka, ind, tip))
            else:
                bez_tipa += 1
        else:
            opravdano.append((fid, inn, marka, ind, tip))
    elif not marka and godnaya_marka(tip):
        if chya == 'машина':
            dobrano.append((fid, inn, '', ind, tip))
        elif chya == 'узел':
            ne_ta_veshch += 1
        else:
            neyasno += 1

print('фактов выдачи ................................... %d' % len(rows))
print('ПОЧИНКА: в марке позиция, документ даёт настоящий тип .. %d' % len(pochineno))
print('  из них без пригодного «тип X» — только пометка ....... %d' % bez_tipa)
print('ОПРАВДАНО: марка не равна индексу, значит настоящая ..... %d' % len(opravdano))
print('ДОБОР: марки не было, документ даёт «тип X» ............. %d' % len(dobrano))
print('  отсеяно: «тип X» относится к узлу, не к машине ....... %d' % ne_ta_veshch)
print('  неясно, чья марка — не пишем, оставляем в очереди .... %d' % neyasno)
print()
for imya, spisok in (('починка', pochineno[:6]), ('оправдано', opravdano[:5]),
                     ('добор', dobrano[:8])):
    print('%s:' % imya)
    for fid, inn, marka, ind, tip in spisok:
        print('   %-7s %-11s было=%-13s индекс=%-13s стало=%s'
              % (fid, inn, marka or '(пусто)', ind[:13] or '—', tip or '—'))
    print()

if not PISAT:
    print('это сухой прогон, база не тронута; писать — с ключом --pisat')
    p.close()
    raise SystemExit
for fid, inn, marka, ind, tip in pochineno:
    c.execute("""update fakt set marka_pozicionnaya_kod=?, marka=?, marka_iz_dokumenta=?,
                        marka_pozicionnaya=1 where id=?""", (marka, tip, tip, fid))
for fid, inn, marka, ind, tip in dobrano:
    c.execute('update fakt set marka=?, marka_iz_dokumenta=? where id=?', (tip, tip, fid))
c.execute('insert into zhurnal_vlivaniya values (?,?,?,?,?,?)',
          (time.strftime('%Y-%m-%d %H:%M:%S'), 'МАРКА из документа (правило 3-й сессии)',
           len(rows), len(pochineno) + len(dobrano), len(opravdano),
           'марка из «тип X», позиция из «технологический индекс X»; прежнее в marka_pozicionnaya_kod'))
p.commit()
q = lambda s: c.execute(s).fetchone()[0]
print('записано. марок из документа в базе: %d'
      % q("select count(*) from fakt where coalesce(marka_iz_dokumenta,'')<>''"))
print('фактов выдачи с маркой стало: %d'
      % q(f"select count(*) from fakt where coalesce(marka,'')<>'' and {V}"))
p.close()
