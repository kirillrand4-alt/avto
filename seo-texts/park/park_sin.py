# -*- coding: utf-8 -*-
"""Синонимы типа машины для проверки «названа ли машина на странице» — ОДИН список на всех.

Зачем отдельный файл. Проверок две: съёмка доказательств (`park_1s_dokaz.py`) и разбор
случайных ссылок (`park_1s_5ssylok.py`). Синонимы были только в первой, вторая искала
каноническое слово в лоб — и на живом жребии записала «тип на странице: нет» для записи ЭПБ
ОАО «РЖД», где чёрным по белому стоит «воздухосборник В-10 зав. № 216-73». Ресивер и есть
воздухосборник; занижен был ПРИБОР, а не доказательство.

Список держим здесь, оба скрипта зовут отсюда — иначе копии снова разъедутся.
"""

SIN = {
    'турбокомпрессор': ['турбокомпрессор', 'центробежн', 'компрессор'],
    'компрессорная станция': ['компрессорн'],
    'ПКС': ['компрессор'],
    # в заключениях МКС пишут «Модули компрессоров М19.47.00.000», без слова «компрессорная»
    'МКС': ['компрессорн', 'модул', 'компрессор'],
    'ГПА': ['газоперекачив', 'нагнетател', 'гпа'],
    'нагнетатель': ['нагнетател', 'компрессор'],
    # «Ротационный нагнетатель ЗАФ-49» — это и есть роторная воздуходувка; на четырёх
    # карточках ЭПБ прибор записал «машина не названа» ровно из-за отсутствия этого слова
    'воздуходувка': ['воздуходувк', 'газодувк', 'нагнетател', 'ротационн', 'компрессор'],
    'ресивер': ['ресивер', 'воздухосборник', 'буферн'],
    'осушитель': ['осушител', 'влагоотделител'],
    'ВРУ': ['воздухораздел', 'кислород', 'азот'],
    'генератор азота': ['азот'],
    'генератор кислорода': ['кислород'],
    'компрессор': ['компрессор', 'компримир', 'сжатого воздуха'],
}


def nazvana(tip, tekst_nizhnim):
    """Названа ли машина типа `tip` в тексте страницы (текст уже приведён к нижнему регистру)."""
    slova = SIN.get(tip) or ([tip.split()[0].lower()[:9]] if tip else [])
    return any(s and s in tekst_nizhnim for s in slova)
