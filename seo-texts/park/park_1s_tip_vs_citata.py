# -*- coding: utf-8 -*-
"""Сверка: совпадает ли ТИП машины в базе с тем, как машина названа в её же цитате.

Повод — проверка пяти случайных ссылок. У АО «МАКФА» тип стоял «воздуходувка», а на
карточке ЭПБ написано «компрессор ЗАФ-57». Обе машины наши, на цель это не влияет, но
правило владельца — факт доказывается ссылкой, значит и ТИП должен следовать из текста,
а не расходиться с ним.

Меряем строго: несовпадением считается случай, когда в цитате есть слово ДРУГОГО
канонического типа и НЕТ ни одного слова своего. Если в цитате нет ни одного типа
(«Поставка запчастей поз. 624») — это не ошибка, а просто отсутствие слова, считаем
отдельно и не трогаем.

Скрипт только СЧИТАЕТ и печатает примеры. Ничего не меняет: правка типов — отдельное
решение, и делать её вслепую по регулярке хуже, чем показать список.
"""
import collections, os, re, sqlite3

D = os.path.dirname(os.path.abspath(__file__))
p = sqlite3.connect('file:%s?mode=ro' % os.path.join(D, 'park.db'), uri=True)
c = p.cursor()

# слова, по которым тип узнаётся в тексте (свои синонимы у каждого)
SLOVA = {
    'компрессор': [r'компрессор'],
    'турбокомпрессор': [r'турбокомпрессор', r'центробежн\w*\s+компрессор'],
    'воздуходувка': [r'воздуходувк', r'газодувк'],
    'ресивер': [r'ресивер', r'воздухосборник'],
    'осушитель': [r'осушител', r'влагоотделител'],
    'генератор азота': [r'азотн\w*\s+(станци|установк|генератор)', r'генератор\w*\s+азота'],
    'генератор кислорода': [r'кислородн\w*\s+(станци|установк|генератор)',
                            r'генератор\w*\s+кислорода', r'концентратор\w*\s+кислорода'],
    'ВРУ': [r'воздухоразделительн', r'\bВРУ\b'],
    'ГПА': [r'газоперекачивающ', r'\bГПА\b'],
    'МКС': [r'модульн\w*\s+компрессорн', r'\bМКС\b'],
    'ПКС': [r'передвижн\w*\s+компрессорн', r'\bПКС\b'],
    'вакуумный насос': [r'вакуумн\w*\s+насос'],
    'нагнетатель': [r'нагнетател'],
}
RE = {t: [re.compile(x, re.I) for x in v] for t, v in SLOVA.items()}

itog = collections.Counter()
primery = collections.defaultdict(list)
for tip, tekst, inn, model in c.execute(
        """select tip, coalesce(chto_naydeno,''), inn, coalesce(model,'')
           from fakt where v_parke=1 and coalesce(chto_naydeno,'')<>''"""):
    if tip not in RE:
        itog['тип вне словаря'] += 1
        continue
    svoy = any(r.search(tekst) for r in RE[tip])
    chuzhie = [t for t, rr in RE.items() if t != tip and any(r.search(tekst) for r in rr)]
    if svoy:
        itog['тип подтверждён цитатой'] += 1
    elif chuzhie:
        k = '%s -> в цитате %s' % (tip, chuzhie[0])
        itog['РАСХОЖДЕНИЕ'] += 1
        if len(primery[k]) < 2:
            primery[k].append((inn, model, tekst[:110]))
    else:
        itog['в цитате нет ни одного типа'] += 1

for k, v in itog.most_common():
    print('%-34s %d' % (k, v))
print('\nпримеры расхождений:')
for k, v in sorted(primery.items(), key=lambda x: -len(x[1]))[:10]:
    print(' ', k)
    for x in v:
        print('     ', x)
p.close()
