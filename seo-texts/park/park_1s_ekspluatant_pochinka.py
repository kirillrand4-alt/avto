# -*- coding: utf-8 -*-
"""Починка признака «ИНН принадлежит эксплуатанту, а не экспертной организации».

Прибор был сломан, и сломал его я сам. Признак стоял такой:

    Эксплуатант\\b[^И]{0,120}?ИНН\\s*[:№]?\\s*(\\d{10,12})

`[^И]` должен был запретить перескок через слово «Экспертная организация» — но он запрещает
букву «И» ВООБЩЕ. А буква «И» стоит в названии почти каждой второй компании:

    Эксплуатант ООО "ДИЭКСПО" ИНН 7725334109          -> старый признак вернул НИЧЕГО
    Эксплуатант ПАО "ХИМПРОМ" ИНН 2124009521          -> НИЧЕГО
    Эксплуатант АО "ЕНИСЕЙСКАЯ ТГК (ТГК-13)" ИНН ...  -> НИЧЕГО

Поймал это жребием: карточка 89-ТУ-854933-2026 (ООО «ДИЭКСПО» — само себе и экспертная
организация, и эксплуатант) дала «ИНН на странице есть, но не у эксплуатанта». Полез
смотреть глазами — оказалось, ИНН стоит ровно там, где надо, а не видит его мой признак.

Цена, измеренная на 2 139 сохранённых цитатах:

    цитат со словом «Эксплуатант» ....... 2139
    старый признак засчитал .............. 1565
    новый признак засчитал ............... 2139
    ПОТЕРЯНО из-за буквы «И» .............. 574   (26,8 %)

Эти 574 — ровно те «571 не разобрать», которые я в записи 110 журнала списал на обрезанную
цитату. Причина была названа НЕВЕРНО: цитаты хватало, не хватало исправного признака.

Второе следствие: перечитывать 2 139 страниц по сети было не нужно — сохранённой цитаты
достаточно. Сетевой прогон (172 карточки за час) закрываю, размечаю из базы мгновенно.

Третье: новый признак даёт 2 139 из 2 139 «ИНН эксплуатанта» и НИ ОДНОГО «ИНН экспертной».
То есть класс, ради которого всё затевалось, в моей базе не реализовался ни разу. Это
сходится с замером 3-й сессии (16 карточек из 16 — эксплуатант, промахов ноль).
"""
import os, re, sqlite3, time

D = os.path.dirname(os.path.abspath(__file__))
# режем не по буквам, а по расстоянию до ближайшего «ИНН» после слова «Эксплуатант»;
# 160 знаков хватает на «ООО "ЕНИСЕЙСКАЯ ТГК (ТГК-13)"» и не хватает, чтобы перескочить
# в следующий раздел карточки («Объект экспертизы»)
EKSPL = re.compile(r'Эксплуатант\b\s*(.{0,160}?)ИНН\s*[:№]?\s*(\d{10,12})', re.S)
# страховка от перескока: если между «Эксплуатант» и найденным ИНН попал заголовок
# соседнего раздела — совпадение не в счёт
CHUZHOY = re.compile(r'Объект экспертизы|Экспертная организация|Заключение экспертизы', re.I)


def inn_ekspluatanta(inn, tekst):
    """True — ИНН стоит в разделе «Эксплуатант» карточки ЭПБ."""
    for hvost, nayden in EKSPL.findall(tekst or ''):
        if nayden == inn and not CHUZHOY.search(hvost):
            return True
    return False


p = sqlite3.connect(os.path.join(D, 'park.db'), timeout=120)
c = p.cursor()
rows = c.execute("""select fakt_id, inn, coalesce(citata,'') from dokaz_tekst
                     where http=200 and coalesce(inn_na_stranice,0)=1""").fetchall()
est = net = pusto = 0
for fid, inn, cit in rows:
    if 'Эксплуатант' not in cit:
        pusto += 1
        continue
    v = 1 if inn_ekspluatanta(inn, cit) else 0
    est += v
    net += 1 - v
    c.execute('update dokaz_tekst set inn_ekspluatant=? where fakt_id=?', (v, fid))
c.execute('insert into zhurnal_vlivaniya values (?,?,?,?,?,?)',
          (time.strftime('%Y-%m-%d %H:%M:%S'), 'ЭПБ: починен признак эксплуатанта',
           len(rows), est, net,
           'старый признак [^И] терял 574 из 2139 — буква И в названии компании'))
p.commit()
q = lambda s: c.execute(s).fetchone()[0]
print('карточек ЭПБ с ИНН на странице ............ %d' % len(rows))
print('  цитата без слова «Эксплуатант» .......... %d (признак не применим)' % pusto)
print('  ИНН эксплуатанта ........................ %d' % est)
print('  ИНН НЕ эксплуатанта (чужое доказательство) %d' % net)
print()
print('размечено всего: %d' % q('select count(*) from dokaz_tekst where inn_ekspluatant is not null'))
print('предприятий, где ВСЕ карточки чужие: %d'
      % q("""select count(*) from (select inn from dokaz_tekst where inn_ekspluatant is not null
              group by inn having sum(coalesce(inn_ekspluatant,0))=0)"""))
p.close()
