def sprosit(s, popytok=6):
    posl = None
    for n in range(popytok):
        if n:
            # 403 от WAF шлюза — это предел параллельности, а не отказ ключа: одиночный
            # запрос в ту же секунду проходит. Отступаем дольше и врозь по шардам.
            time.sleep(min(120, 10 * 2 ** (n - 1)) + 2 * SHARD)
        try:
            body = json.dumps({'model': MODEL, 'stream': False, 'max_tokens': 4000,
                               'messages': [{'role': 'user', 'content': s}]}).encode()
            req = urllib.request.Request(_BASE + '/v1/chat/completions', data=body, headers={
                'Content-Type': 'application/json', 'Authorization': 'Bearer ' + _KEY,
                'User-Agent': 'curl/8.5.0'})
            d = json.loads(_NP.open(req, timeout=300).read())
            return d['choices'][0]['message']['content']
        except Exception as e:
            posl = e
    raise posl


def sdelannye():
    """Пропускаем всё, что уже разобрано ЛЮБЫМ шардом — переживает рестарт и
    перетасовку шардов."""
    s = set()
    for f in glob.glob(os.path.join(D, 'park_tipy_polnyy_*.jsonl')):
        for ln in open(f, encoding='utf-8'):
            try:
                s.add(json.loads(ln)['id'])
            except Exception:
                pass
    return s


def main():
    p = sqlite3.connect('file:%s?mode=ro' % PARK, uri=True)
    rows = p.execute(
        "select id, kto, tip, marka, model, chto_naydeno from fakt order by id").fetchall()
    p.close()
    gotovo = sdelannye()
    moi = [r for r in rows if r[0] % SHARDS == SHARD and r[0] not in gotovo]
    print('шард %d/%d: к сверке %d (всего в базе %d, уже сделано %d)'
          % (SHARD, SHARDS, len(moi), len(rows), len(gotovo)), flush=True)
    n = 0
    for i in range(0, len(moi), PACHKA):
        pach = moi[i:i + PACHKA]
        vhod = json.dumps([{
            'id': r[0], 'tip_postavlen': r[2] or '',
            'marka': (r[3] or '') + (' ' + r[4] if r[4] else ''),
            'tekst': (r[5] or '')[:600]} for r in pach], ensure_ascii=False)
        try:
            t = sprosit(PROMPT + '\n\nВХОД:\n' + vhod)
            m = re.search(r'\[.*\]', t, re.S)
            dan = json.loads(m.group(0)) if m else []
        except Exception as e:
            print('пачка %d СБОЙ %r' % (i, e), flush=True)
            continue
        bylo = {r[0]: (r[2] or '') for r in pach}
        kto = {r[0]: r[1] for r in pach}
        with open(OUT, 'a', encoding='utf-8') as f:
            for d in dan:
                if d.get('id') not in bylo:
                    continue
                d['tip_bylo'] = bylo[d['id']]
                d['kto'] = kto[d['id']]
                f.write(json.dumps(d, ensure_ascii=False) + '\n')
                n += 1
            f.flush()
            os.fsync(f.fileno())
        if (i // PACHKA) % 10 == 0:
            print('шард %d: %d/%d' % (SHARD, i + len(pach), len(moi)), flush=True)
    print('шард %d ГОТОВО, записано %d' % (SHARD, n), flush=True)


if __name__ == '__main__':
    main()
