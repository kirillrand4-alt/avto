# -*- coding: utf-8 -*-
"""Шаблон телефона, ловящий ПЯТИЗНАЧНЫЕ коды городов. Общий для всех каналов.

ЧТО ВСКРЫЛОСЬ. Замер щелей на 9 335 карточках показал 1 130 случаев «человек есть,
номера регулярка не взяла». Примеры из живых карточек:

    тел. (81366) 94-910        Пикалевский глинозёмный завод
    8 3439 395 360             КУМЗ

Это настоящие номера. Мой прежний шаблон требовал код из 3-4 цифр и разбиение 3-2-2:

    (?:\\+7|\\b8)[\\s\\-(]*(\\d{3,4})[\\s\\-)]*\\d{2,3}[\\s\\-]*\\d{2}[\\s\\-]*\\d{2}

Пятизначный код (81366, 34394, 35161) в него не влезает, и номер после него разбит
иначе. Пятизначные коды — это МАЛЫЕ ПРОМЫШЛЕННЫЕ ГОРОДА, то есть ровно наша аудитория:
Пикалёво, Каменск-Уральский, Сатка. Шаблон молчал именно там, где предприятия наши.

Хуже всего, что молчал он БЕЗ ПРИЗНАКА: в отчётах это выглядело как «номера на странице
нет», и такой ноль неотличим от честного.

КАК СДЕЛАНО ТЕПЕРЬ. Номер опознаётся по ЦИФРАМ, а не по разбиению: берётся кусок из
цифр и разделителей, нормализуется, и годным считается тот, у кого 11 цифр и первая 7
или 8 (либо 10 цифр — тогда 7 добавляется). Разбиение больше не участвует в решении:
это свойство того, кто печатал, а не свойство номера.

ЗАСЛОН ОТ ЛОЖНЫХ СРАБАТЫВАНИЙ. Широкий шаблон легко ловит ИНН, ОГРН, суммы и номера
договоров — в прошлом обогащении регулярка по десяти цифрам собрала 3 815 ложных
номеров из координат векторной графики. Поэтому:
  * 12 цифр подряд (ИНН юрлица) и 13 (ОГРН) отвергаются целиком;
  * если прямо перед числом стоит слово-ловушка (ИНН, ОГРН, КПП, счёт, лот, цена,
    сумма, договор, заказ) — отвергается;
  * если рядом НЕТ ни слова-признака связи (тел, моб, сот, факс, контакт, обращаться,
    звонить, доб), ни скобок кода — номер считается СЛАБЫМ и помечается видом, а не
    выбрасывается: разделять, а не отсеивать.

Модуль отдельный, потому что шаблон стоит в шести каналах, и правка в одном месте
дешевле шести расхождений.
"""
import re

# Кусок «цифры и разделители» — намеренно широкий; решает нормализация, а не форма.
SYROY = re.compile(r'(?:\+7|\b8)?[\s\-(]{0,3}\d[\d\s\-()]{7,18}\d')
SLOVO_SVYAZI = re.compile(r'тел|моб|сот|факс|контакт|обращат|звонит|доб|вн\.|call|phone', re.I)
LOVUSHKA_PERED = re.compile(
    r'(?:ИНН|ОГРН|ОКПО|КПП|БИК|р/?с|к/?с|счет|счёт|лот|цена|сумма|стоимость|договор|'
    r'заказ|инв|№)\s*[:№]?\s*$', re.I)
# «доб» после номера — принадлежит ЭТОМУ номеру только в ближайших 40 знаках.
DOB = re.compile(r'\(?\s*(?:доб(?:ав(?:очный)?)?\.?|вн(?:утр)?\.?|ext\.?)\s*[:№]?\s*(\d{2,5})',
                 re.I)


def cifry(s):
    """Номер как ЧИСЛО. 10 цифр — добавляем 7; 11 с 7 или 8 впереди — приводим к 7.

    ОДИННАДЦАТЬ ЦИФР САМИ ПО СЕБЕ НОМЕРОМ НЕ ДЕЛАЮТ. Первая версия возвращала любую
    11-значную строку как есть, и первый же прогон по потокам вернул «31705108347» —
    одиннадцать цифр, начинающихся с тройки. Это обрывок чего угодно: склеенные ИНН и
    сумма, номер документа, кусок ОГРН. Российский номер в нормальной форме начинается
    с семёрки, и это единственное, что отличает его от случайной цепочки нужной длины.

    Возвращаю пустую строку, а не саму цепочку: вызывающий проверяет длину 11, и
    вернуть непригодное значение той же длины значит протащить мусор через проверку.
    """
    syroy = str(s or '')
    c = re.sub(r'\D', '', syroy)
    if len(c) == 11 and c[0] in '78':
        return '7' + c[1:]
    if len(c) == 10:
        # ДЕСЯТЬ ЦИФР — ЭТО И НОМЕР БЕЗ ВОСЬМЁРКИ, И ИНН ЮРЛИЦА. Различает их не длина,
        # а НАПИСАНИЕ: «(81366) 94-910» человек разбивает скобками и дефисами, а ИНН
        # пишут сплошным числом. Первая попытка развести их по первой цифре («только
        # мобильный достраиваем») сломала пятизначные коды — ровно то, ради чего модуль
        # и писался. Признак взят у самого текста, а не выдуман.
        if c[0] == '9':
            return '7' + c          # мобильный без восьмёрки — однозначен
        if re.search(r'[\s\-()]', syroy.strip()):
            return '7' + c          # городской, разбитый разделителями
    return ''


def nomera(tekst):
    """Все телефоны текста с их местом, видом и добавочным. Ничего не выбрасывает.

    Возвращает список словарей: nachalo, konec, kak_napisan, cifry, vid, dobavochnyy.
    Вид называет силу находки, чтобы вызывающий сам решал, что засчитывать:
      «номер» — рядом слово связи или скобки кода;
      «слабый номер» — цифры подходят, но признака связи рядом нет;
      «отвергнут: <причина>» в поток не идёт вовсе (ИНН, ОГРН, слово-ловушка).
    """
    out = []
    t = tekst or ''
    for m in SYROY.finditer(t):
        syroy = m.group(0)
        golye = re.sub(r'\D', '', syroy)
        # ИНН юрлица (10) отличается от номера тем, что стоит без кода и без слова связи;
        # 12 и 13 цифр — ИНН физлица и ОГРН, они номером быть не могут.
        if len(golye) in (12, 13) or len(golye) > 13:
            continue
        c = cifry(syroy)
        if len(c) != 11:
            continue
        pered = t[max(0, m.start() - 24):m.start()]
        if LOVUSHKA_PERED.search(pered):
            continue
        okno = t[max(0, m.start() - 30):m.end() + 30]
        est_svyaz = bool(SLOVO_SVYAZI.search(okno)) or '(' in syroy
        md = DOB.search(t[m.end():m.end() + 40])
        out.append({
            'nachalo': m.start(), 'konec': m.end(), 'kak_napisan': syroy.strip(),
            'cifry': c, 'vid': 'номер' if est_svyaz else 'слабый номер',
            # У мобильного добавочного не бывает: если «доб» стоит рядом с мобильным,
            # он относится к соседнему городскому.
            'dobavochnyy': (md.group(1) if (md and not c.startswith('79')) else ''),
            'mobilnyy': c.startswith('79'),
        })
    return out


def _samoproverka():
    """Проба на живых строках, из-за которых модуль и написан."""
    sluchai = [
        ('тел. (81366) 94-910', '78136694910', 'пятизначный код в скобках'),
        ('8 3439 395 360', '73439395360', 'пятизначный код без скобок'),
        ('+7-812-331-08-66', '78123310866', 'обычный трёхзначный'),
        ('8(35161) 9-41-70', '73516194170', 'пятизначный с дефисами'),
        ('+7 (343) 229-00-75', '73432290075', 'скобки и пробелы'),
        ('8-950-433-36-76', '79504333676', 'мобильный'),
    ]
    ok = 0
    for tekst, zhdem, pochemu in sluchai:
        n = nomera(tekst)
        vyshlo = n[0]['cifry'] if n else '—'
        horosho = vyshlo == zhdem
        ok += horosho
        print('  %-22s -> %-13s %s  (%s)'
              % (tekst, vyshlo, 'ок' if horosho else 'ПЛОХО, ждали ' + zhdem, pochemu))
    # Контроль в другую сторону: то, что номером быть НЕ должно.
    ne_nomera = [('ИНН 7706613770', 'ИНН'), ('ОГРН 1027700132195', 'ОГРН'),
                 ('цена 1 200 000 руб', 'сумма'), ('договор № 2024051234', 'номер договора'),
                 # Одиннадцать цифр, начинающихся не с 7 и не с 8. Первая версия модуля
                 # принимала такое за номер и вернула «31705108347» из потока.
                 ('тел 31705108347', 'одиннадцать цифр, но не с семёрки'),
                 ('счёт 40702810100000012345', 'расчётный счёт')]
    for tekst, pochemu in ne_nomera:
        n = nomera(tekst)
        horosho = not n
        ok += horosho
        print('  %-22s -> %-13s %s  (%s)'
              % (tekst, 'пусто' if not n else n[0]['cifry'],
                 'ок' if horosho else 'ПЛОХО, поймал лишнее', pochemu))
    print('ИТОГ %d из %d' % (ok, len(sluchai) + len(ne_nomera)))


if __name__ == '__main__':
    _samoproverka()
