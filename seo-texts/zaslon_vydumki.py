"""Один заслон против выдуманных провайдером данных — для всех модулей сразу.

ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ. Проверка «номер обязан быть во входном тексте» была написана трижды,
в трёх модулях, и все три раза одинаково НЕДОДЕЛАНА: модуль помечал непроверенное значение
колонкой `telefon_est_v_tekste=''` — и всё равно его записывал. Пометку никто не читал: сборка
панели берёт колонку `telefon` как есть.

Цена замерена 03.08.2026. Провайдер выдумал 32 номера — проверка каждого показала, что его нет
в карточке НИГДЕ: ни в комментарии, ни в размеченных площадкой телефонах. **Пять из них стояли
в панели личными мобильными технических людей.** Продавец позвонил бы постороннему человеку и
назвал его главным энергетиком предприятия.

ПРАВИЛО, которое отсюда следует и которое этот файл делает единственным:
    непроверяемое значение НЕ ЗАПИСЫВАЕТСЯ ВОВСЕ.
Не помечается, не откладывается, не остаётся «на всякий случай» — его нет. Пустая клетка
честна и безопасна, помеченная клетка честна и опасна, потому что пометку читает не тот, кто
данные потребляет.

Имя и должность при этом остаются: они из текста и проверяемы отдельно. Выбрасывается ровно то,
что не подтвердилось.

ЧЕМ СВЕРЯЕМ. Только цифрами: у номера в ответе модели формат почти всегда свой
(«+7 (912) 345-67-89» против «89123456789» в источнике), и сверка строк дала бы ложную тревогу
на каждом втором. Замер той же ошибки у себя: восемь номеров с сайтов выглядели выдумкой, пока
не оказалось, что в одном поле лежат ДВА номера через запятую, и сверялась их склейка.
Поэтому: каждое значение разбирается на отдельные номера, и каждый сверяется сам по себе.

Использование:
    from zaslon_vydumki import nomer_iz_teksta, pochta_iz_teksta, proverit_stroku

    tel = nomer_iz_teksta(otvet_modeli, ishodnyy_tekst)      # '' если не подтвердился
    est, poteryano = proverit_stroku({'telefon': ...}, tekst)
"""
import re

# Меньше шести цифр — это не номер, а обрывок вроде «85-40» или добавочный. Такие не сверяем и
# не пропускаем: отдельно они бессмысленны, а как «номер» вводят в заблуждение.
MINIMUM_CIFR = 6


def cifry(s):
    return re.sub(r'\D', '', s or '')


# Добавочный — не часть номера. «+7(8352)73-55-55 (доб. 60-30)» это номер 8352-735555 плюс
# внутренний 60-30; если считать хвост по всей строке, получится 7355556030 — такого номера
# в источнике нет, и честная запись объявляется выдумкой. Поймано замером: 695 ложных тревог
# из 5 415 номеров, то есть каждый восьмой.
DOBAVOCHNYY = re.compile(r'\s*[\(\[]?\s*(?:доб|вн|ext|доп)\w*\.?\s*[:№]?\s*'
                         r'[\(\[]?[\d\-\s]*[\)\]]?\s*[\)\]]?\s*$', re.I)


def bez_dobavochnogo(s):
    return DOBAVOCHNYY.sub('', s or '').strip()


def hvost(s):
    """Последние десять цифр — то, чем номера сравниваются между собой.

    Иначе заслон выбрасывает ВСЕ настоящие номера, записанные через «+7», когда в источнике
    стоит «8»: `+7 (912) 345-67-89` это `79123456789`, а в тексте `89123456789` — те же десять
    цифр, но первая разная. Поймано самопроверкой этого файла, до первого применения.
    Городские с кодом города сравниваются так же: у них те же десять значащих цифр.
    """
    d = cifry(bez_dobavochnogo(s))
    return d[-10:] if len(d) >= 10 else d


def razdelit(znachenie):
    """Одно поле — часто несколько номеров: «+7 (495) 641 58 58, +7 (965) 247 23 42».
    Сверять их склейку нельзя: в источнике такой последовательности цифр нет, и честный номер
    будет объявлен выдумкой. Именно так я сам получил восемь ложных тревог."""
    return [x.strip() for x in re.split(r'[;,|]|\s{3,}', znachenie or '') if x.strip()]


def nomer_iz_teksta(znachenie, *istochniki):
    """Вернуть только те номера, чьи цифры ЕСТЬ хотя бы в одном источнике.

    `istochniki` — все места, где номер может законно лежать: текст комментария, колонка
    размеченных площадкой телефонов, текст страницы. Достаточно одного совпадения: номер,
    взятый из разметки, в тексте отсутствует законно.
    """
    if not (znachenie or '').strip():
        return ''
    syrye = ' '.join(str(x or '') for x in istochniki)
    if not cifry(syrye):
        return ''
    # Сверяем ДЕСЯТЬ ЗНАЧАЩИХ ЦИФР номера с цифрами источника, взятыми подряд.
    #
    # Первая версия резала источник кусками `[\d()\-\s+]{7,30}` и сравнивала номер с куском.
    # Это выглядело точнее, а на деле теряло номер НА ГРАНИЦЕ куска: предел в 30 знаков резал
    # его пополам, и честная запись объявлялась выдумкой. Поймано на живых данных — «8-965-548
    # -56-22» лежал в колонке телефонов карточки и всё равно не подтверждался.
    #
    # Ложных совпадений тут бояться нечего: десять цифр подряд — уже почти уникальная строка,
    # а короче десяти мы и не сверяем.
    cifry_ist = cifry(syrye)
    godnye = []
    for n in razdelit(znachenie):
        chistyy = bez_dobavochnogo(n)
        h = hvost(chistyy)
        if len(cifry(chistyy)) < MINIMUM_CIFR or not h:
            continue
        if h in cifry_ist:
            godnye.append(n)
    return ', '.join(godnye)


def pochta_iz_teksta(znachenie, *istochniki):
    """То же для почты. Сверяется дословно и без регистра: почта не переформатируется, а вот
    выдумать её модель может так же легко — и чужая именная почта уже приписывалась не тому
    человеку (наблюдение третьей сессии: `RosihinaOV@nknh.ru` достался Лапаеву)."""
    if not (znachenie or '').strip():
        return ''
    vhod = ' '.join(str(x or '') for x in istochniki).lower()
    godnye = [p for p in razdelit(znachenie) if p.lower() in vhod]
    return ', '.join(godnye)


def proverit_stroku(stroka, *istochniki, polya_telefonov=('telefon', 'telefony', 'lichnyy_nomer'),
                    polya_pocht=('pochta', 'pochty')):
    """Вычистить строку целиком. Возвращает (строка, сколько значений выброшено).

    Число выброшенного возвращается намеренно: молча вычищенный заслон невозможно отличить от
    заслона, который не сработал ни разу, а это разные вещи. Модуль обязан это число печатать.
    """
    poteryano = 0
    for k in polya_telefonov:
        if k in stroka and (stroka[k] or '').strip():
            bylo = stroka[k]
            stroka[k] = nomer_iz_teksta(bylo, *istochniki)
            poteryano += len(razdelit(bylo)) - len(razdelit(stroka[k]))
    for k in polya_pocht:
        if k in stroka and (stroka[k] or '').strip():
            bylo = stroka[k]
            stroka[k] = pochta_iz_teksta(bylo, *istochniki)
            poteryano += len(razdelit(bylo)) - len(razdelit(stroka[k]))
    return stroka, poteryano


def samoproverka():
    """Проверка заслона на случаях, которые его уже обманывали. Гонять при правках."""
    sluchai = [
        # (значение, источник, что должно остаться, почему)
        ('+7 (912) 345-67-89', 'звоните 89123456789', '+7 (912) 345-67-89',
         'формат другой, цифры те же — номер годен'),
        ('+7 (495) 641 58 58, +7 (965) 247 23 42', 'тел 84956415858 и 89652472342',
         '+7 (495) 641 58 58, +7 (965) 247 23 42', 'два номера в одном поле — оба годны'),
        ('+7 (495) 641 58 58, +7 (965) 247 23 42', 'тел 84956415858',
         '+7 (495) 641 58 58', 'один подтверждён, второй выдуман — остаётся один'),
        ('8-960-314-72-92', 'АНАЛОГИ СОГЛАСОВЫВАТЬ ЗАРАНЕЕ', '',
         'номера в источнике нет вовсе — выброшен'),
        ('85-40', 'добавочный 85-40 у Иванова', '',
         'меньше шести цифр — не номер, а обрывок'),
        ('+7(8352)73-55-55 (доб. 60-30)', 'тел 8(8352)73-55-55',
         '+7(8352)73-55-55 (доб. 60-30)', 'добавочный не часть номера — не мешает сверке'),
        ('(8352)73-55-55 доб.(66-50)', 'тел (8352) 73-55-55',
         '(8352)73-55-55 доб.(66-50)', 'добавочный в скобках — тоже не часть номера'),
        ('', 'что угодно', '', 'пусто остаётся пустым'),
    ]
    oshibok = 0
    for znach, ist, zhdem, pochemu in sluchai:
        vyshlo = nomer_iz_teksta(znach, ist)
        if vyshlo != zhdem:
            oshibok += 1
            print(f'  ОШИБКА: {znach!r} + {ist!r} → {vyshlo!r}, ждали {zhdem!r} ({pochemu})')
    print(f'самопроверка заслона: случаев {len(sluchai)}, ошибок {oshibok}')
    return oshibok == 0


if __name__ == '__main__':
    import sys
    sys.exit(0 if samoproverka() else 1)
