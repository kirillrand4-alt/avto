def v_regex(m):
    if m == 'ГПА':                      # только отдельным словом
        return re.compile(r'(?<![А-Яа-яЁёA-Za-z])ГПА(?![а-яё])', re.I)
    return re.compile(r'\w*'.join(re.escape(x) for x in m.split('*')), re.I)


