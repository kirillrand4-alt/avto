"""Сколько закупок в ЕИС находит каждое слово — по двум спискам: КЦ и Мейер.

Счётчик снят С РАЗМЕТКИ, а не угадан: `<div class="search-results__total"> N записей </div>`.
Прежний шаблон брал число только у нулевого случая — то есть молча врал на всех непустых.

Ищем и актуальные, и завершённые (af=on&ca=on): нам нужны предприятия, которые УЖЕ купили,
а не только те, кто покупает сейчас.

Контроль: выдуманное слово обязано дать 0 записей. Без него «0» у настоящего слова
неотличим от поломки запроса.
"""
import re
import ssl
import time
import urllib.parse
import urllib.request

ctx = ssl.create_default_context()
ctx.check_hostname = False
ctx.verify_mode = ssl.CERT_NONE
net = urllib.request.build_opener(urllib.request.HTTPSHandler(context=ctx),
                                  urllib.request.ProxyHandler({}))
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) '
      'Chrome/120.0.0.0 Safari/537.36')
TOTAL = re.compile(r'search-results__total"?>\s*([\d\s ]+)\s*запис', re.I)


def skolko(slovo):
    u = ('https://zakupki.gov.ru/epz/order/extendedsearch/results.html?searchString='
         + urllib.parse.quote(slovo)
         + '&morphology=on&pageNumber=1&recordsPerPage=_10&sortBy=UPDATE_DATE'
           '&fz44=on&fz223=on&af=on&ca=on')
    for att in range(3):
        try:
            t = net.open(urllib.request.Request(u, headers={'User-Agent': UA}),
                         timeout=60).read().decode('utf-8', 'replace')
        except Exception as e:  # noqa: BLE001
            time.sleep(3 + att * 3)
            if att == 2:
                return None, 'СЕТЬ: ' + str(e)[:40]
            continue
        m = TOTAL.search(t)
        if m:
            return int(re.sub(r'\D', '', m.group(1)) or 0), ''
        return None, 'счётчика нет в разметке (знаков %d)' % len(t)
    return None, 'не дошло'


