# -*- coding: utf-8 -*-
"""Проверка предупреждения 1-й сессии: не попались ли мои 4 769 в ту же ловушку.

ИХ НАХОДКА. Строгое правило «среда из текста» ловится на двух вещах:
  * «дожимн*» само по себе даёт 586 газовых — но это ИМЯ ЗДАНИЯ: «Трубопровод "Вода оборотная
    II системы в дожимной компрессорной"». Здание не задаёт среду машины;
  * «Воздух КИП» в именительном падеже не совпадает с шаблоном `воздушн|воздуха` и уезжает
    в газ.
Строгое правило перевернуло бы у них 1 507 фактов из «наша» в «не наша». Их вариант Б дал
воздух 2 478, газ 971.

ЧТО ПРОВЕРЯЮ У СЕБЯ. Мой шаблон другой: VOZDUH ловит `воздух|воздушн|воздуходувк|пневмо|
дутьев`, то есть «Воздух КИП» он берёт — корень `воздух` без падежного хвоста. А слова
«дожимн» у меня в газовом шаблоне нет вовсе. Но проверять надо не рассуждением, а счётом:
беру свои 4 769 и смотрю, сколько из них держатся ТОЛЬКО на слове из их ловушки.
"""
import collections
import json
import re
import sqlite3

cx = sqlite3.connect(r'C:\seostat\data\centrifugal.db')
GAZ = re.compile(r'синтез-газ|синтез газ|природн\w*\s*газ|попутн\w*\s*газ|нефтян\w*\s*газ|'
                 r'\bГПА\b|газоперекачив|азот\w*|кислород\w*|аммиак|водород|этилен|пропилен|'
                 r'углекислот|сероводород|\bхлор\b|\bметан\b|циркуляционн\w*\s*газ|'
                 r'коксов\w*\s*газ|доменн\w*\s*газ|технологическ\w*\s*газ|газов\w*\s', re.I)
VOZ = re.compile(r'воздух|воздушн|воздуходувк|турбовоздуходувк|пневмо|дутьев', re.I)
DOZHIM = re.compile(r'дожимн', re.I)
ZDANIE = re.compile(r'трубопровод|здани|сооружени|компрессорн\w+\s+станци|цех\b', re.I)

o = collections.Counter()
primery = collections.defaultdict(list)
for tip, sreda, quote in cx.execute(
        "select coalesce(equipment_type,''), coalesce(medium,''), coalesce(quote,'') from fact"):
    if (sreda or '').strip() and 'не назван' not in sreda.lower():
        continue
    g, v = bool(GAZ.search(quote)), bool(VOZ.search(quote))
    if not (g or v):
        continue
    vyvod = 'и газ, и воздух' if g and v else 'газ' if g else 'воздух'
    o[f'мой вывод: {vyvod}'] += 1
    # Ловушка 1: вывод «газ» держится только на «дожимн».
    if vyvod == 'газ' and DOZHIM.search(quote) and not GAZ.search(DOZHIM.sub(' ', quote)):
        o['ЛОВУШКА дожимн: газ держится только на этом слове'] += 1
        if len(primery['дожимн']) < 3:
            primery['дожимн'].append(quote[:130])
    # Ловушка 2: «Воздух КИП» — проверяю, что мой шаблон его берёт.
    if re.search(r'воздух\s+КИП', quote, re.I):
        o['«Воздух КИП» встретился'] += 1
        if v:
            o['«Воздух КИП» опознан как воздух — верно'] += 1
    # Ловушка 3: среда взята из имени ЗДАНИЯ, а не машины.
    if ZDANIE.search(quote) and vyvod != 'воздух':
        o['вывод не-воздух там, где объект здание или труба'] += 1
o['примеры_дожимн'] = primery['дожимн']
print(json.dumps(dict(o), ensure_ascii=False, indent=1))
