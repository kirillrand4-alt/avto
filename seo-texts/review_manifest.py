# -*- coding: utf-8 -*-
"""Ревью делового манифеста через провайдер (Fable): персона «филолог + критик».
Ищет слабые места и в языке, и в аргументации. Выход: review-manifest.md."""
import os
import gen_provider as gp

DIR = os.path.dirname(os.path.abspath(__file__))

PERSONA = """Ты выступаешь в ДВУХ ролях одновременно и даёшь разбор с обеих сторон.

РОЛЬ 1 - ФИЛОЛОГ-РЕДАКТОР (носитель русского, 20 лет правит деловые тексты).
Оцени: грамматику, пунктуацию, синтаксис, орфографию, ясность, читаемость, тон, структуру.
Отдельно отметь: канцелярит, перегруженные предложения (по 3-5 придаточных без точки), сбитое
согласование, опечатки, неудачные формулировки. Приводи конкретные цитаты и как переписать.

РОЛЬ 2 - КРИТИК / СКЕПТИЧНЫЙ АДРЕСАТ (это письмо-обоснование от подрядчика/команды заказчику или
руководителю, который ПОДСВЕТИЛ проблемы на сайтах; автор объясняет, почему часть проблем в низком
приоритете). Читай как человек, которому надо возразить. Найди: уязвимые/необоснованные цифры,
логические разрывы, подмены, внутренние противоречия, места где «удобные» выводы не следуют из данных,
самоуверенные оценки без источника, где адресат справедливо придерётся. По каждому - почему это слабо
и как усилить (какой довод/цифру/оговорку добавить), чтобы письмо стало убедительнее и честнее.

ФОРМАТ ОТВЕТА (по-русски, по делу, без воды):
# 1. Язык и редактура (филолог)
   - список замечаний с цитатами и правкой; в конце — 3 самые грубые языковые проблемы.
# 2. Аргументация и слабые места (критик)
   - по пунктам манифеста (1.1-1.6, 2, CTA): где довод уязвим, чем возразит скептик, как усилить.
# 3. Итог
   - убедительно ли письмо в целом (1-10), 3 главных риска, что переписать в первую очередь.
Будь конкретным и честным - цель найти слабые места, а не похвалить."""


def main():
    manifest = open(os.path.join(DIR, 'manifest.txt'), encoding='utf-8').read()
    prompt = PERSONA + '\n\n=== ТЕКСТ МАНИФЕСТА ДЛЯ РАЗБОРА ===\n' + manifest
    client = gp.make_client()
    msg = gp.call(client, [{'role': 'user', 'content': prompt}], model='claude-fable-5')
    out = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    open(os.path.join(DIR, 'review-manifest.md'), 'w', encoding='utf-8').write(out)
    print(out)


if __name__ == '__main__':
    main()
