def норм_by(сырое):
    ц = re.sub(r'\D', '', сырое)
    if len(ц) == 11 and ц.startswith('80'):
        ц = '375' + ц[2:]
    if len(ц) != 12 or not ц.startswith('375'):
        return ''
    return '+375 %s %s-%s-%s' % (ц[3:5], ц[5:8], ц[8:10], ц[10:12])


