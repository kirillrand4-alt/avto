def _совп(код, префикс):
    # ОКВЭД2: класс XX.XX, подкласс XX.XX.X, группа XX.XX.XX — в третьем сегменте цифра продолжает иерархию
    return код == префикс or код.startswith(префикс + '.') or (префикс.count('.') == 2 and код.startswith(префикс))


def категории(осн, доп=()):
    """-> {ключ: 'осн'|'доп'}; самый длинный префикс внутри газа решает спор (03.22.2 -> прудовое, не ядро)."""
    коды = [(str(осн or '').strip(), 'осн')] + [(str(к).strip(), 'доп') for к in доп or () if к]
    итог = {}
    for код, откуда in коды:
        if not код:
            continue
        лучш = {}
        for ключ, (газ, _ст, _н, пп, _пор, _п) in КАТ.items():
            for п in пп:
                if _совп(код, п) and len(п) > лучш.get(газ, ('', 0))[1]:
                    лучш[газ] = (ключ, len(п))
        for ключ, _ in лучш.values():
            if итог.get(ключ) != 'осн':
                итог[ключ] = откуда
    return итог


