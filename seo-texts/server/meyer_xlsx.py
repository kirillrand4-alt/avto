            'в доп. кодах они есть почти у всех (так отсеяно 4 347 компаний). По основному в нашей базе таких 10: '
            'база обзвона собиралась под производство, трейдеров в ней почти нет — их нужно добирать отдельно.',
            'Исключены конкуренты и ликвидированные компании. Выручка — не фильтр, только колонка.',
            'Почты, где домен не совпадает с сайтом компании, оставлены с пометкой «проверить» (часто это почта '
