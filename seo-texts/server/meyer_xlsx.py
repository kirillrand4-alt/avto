    ws.append(['Компаний всего', len(комп)])
    ws.append(['  в сегменте по основному ОКВЭД', сила.get('основной ОКВЭД', 0)])
    ws.append(['  только по дополнительному ОКВЭД (слабее, в конце списка)', сила.get('только доп. ОКВЭД', 0)])
    ws.append(['  только по признаку экспорта в описании', сила.get('по тексту (экспорт)', 0)])
    ws.append([])
    ws.append([ж('Сегмент'), ж('Всего компаний'), ж('по основному ОКВЭД'), ж('только по доп. ОКВЭД')])
    for с in sorted(сегм):
        ws.append([с] + сегм[с])
    ws.append(['(компания может входить в несколько сегментов)'])
    ws.append([])
    ws.append([ж('Контакты'), ж('Компаний')])
    ws.append(['Есть ЛПР сегмента с каналом связи (приоритет 1-2)', лпр])
    ws.append(['  из них ЛПР с ФИО', именных])
    ws.append(['Есть мобильный номер (роль чаще не указана)', с_моб])
    ws.append(['Только общие каналы (приёмная, info@, продажи и т.п.)', len(комп) - лпр - без])
    ws.append(['Нет ни телефона, ни почты (в лучшем случае ФИО директора из ЕГРЮЛ)', без])
    ws.append(['Есть выручка', с_выр])
    ws.append(['Строк на листе «Контакты»', len(конт)])
    ws.append(['  из них со ссылкой на источник', со_ссылкой])
    ws.append([])
