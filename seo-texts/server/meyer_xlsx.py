def описание_источника(ист):
    for префикс, текст in ИСТОЧНИКИ:
        if ист.startswith(префикс):
            return текст
    return 'Наш обход открытых источников (ссылка на страницу, если есть)'


def читать(п):
    with open(п, encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f, delimiter=';'))


def лист(wb, имя, поля, строки, ширины):
    ws = wb.create_sheet(имя)
    for i, ш in enumerate(ширины):
        ws.column_dimensions[chr(65 + i) if i < 26 else 'A' + chr(65 + i - 26)].width = ш
    ws.freeze_panes = 'C2'
    шапка = []
    for п in поля:
        cell = WriteOnlyCell(ws, value=п)
        cell.font = Font(bold=True, color='FFFFFF')
        cell.fill = PatternFill('solid', fgColor='305496')
        cell.alignment = Alignment(wrap_text=True, vertical='top')
        шапка.append(cell)
    ws.append(шапка)
    for с in строки:
        ряд = []
        for п in поля:
            v = с.get(п, '')
            if п in ЧИСЛА and v not in ('', None):
                try:
                    v = int(float(v))
                except ValueError:
                    pass
            ряд.append(v)
        ws.append(ряд)
    последняя = len(поля)
    буква = chr(64 + последняя) if последняя <= 26 else 'A' + chr(64 + последняя - 26)
    ws.auto_filter.ref = 'A1:%s%d' % (буква, len(строки) + 1)
    return ws


def main(п_комп, п_конт, п_out):
    комп = читать(п_комп)
    конт = читать(п_конт)
    for к in комп:
        к['В какой базе обзвона'] = БАЗА.get(к['В какой базе обзвона'], 'нет в базе обзвона')

    def ключ(к):
        выр = float(к['Выручка, руб'] or 0)
        return (ПОРЯДОК.get(к['Попадание'], 9), к['Сегмент'].split(' | ')[0], -выр)
    комп.sort(key=ключ)
    место = {к['ИНН']: i for i, к in enumerate(комп)}
    конт.sort(key=lambda x: (место.get(x['ИНН'], 10 ** 9), int(x['Приоритет'] or 9)))

    # сводка по сегментам
    сегм = collections.OrderedDict()
    for к in комп:
        осн = set(filter(None, к['Сегмент по основному ОКВЭД'].split(' | ')))
        for с in к['Сегмент'].split(' | '):
            з = сегм.setdefault(с, [0, 0, 0])
            з[0] += 1
            з[1 if с in осн else 2] += 1
    сила = collections.Counter(к['Попадание'] for к in комп)
    лпр = sum(1 for к in комп if int(к['Из них ЛПР (приоритет 1-2)'] or 0) > 0)
    именных = sum(1 for к in комп if int(к['Из них ЛПР (приоритет 1-2)'] or 0) > 0 and к['ЛПР: ФИО'])
    без = sum(1 for к in комп if int(к['Каналов связи всего'] or 0) == 0)
    с_моб = sum(1 for к in комп if к['Мобильный (любой)'])
    с_выр = sum(1 for к in комп if к['Выручка, руб'])
    со_ссылкой = sum(1 for к in конт if к['Ссылка на источник'])
    источники = collections.Counter(к['Источник'] for к in конт)

    wb = Workbook(write_only=True)
    ws = wb.create_sheet('Сводка')
    ws.column_dimensions['A'].width = 46
    ws.column_dimensions['B'].width = 16
    ws.column_dimensions['C'].width = 22
    ws.column_dimensions['D'].width = 22
    b = Font(bold=True)

    def ж(текст):
        cell = WriteOnlyCell(ws, value=текст)
        cell.font = b
        return cell
