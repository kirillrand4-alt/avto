# -*- coding: utf-8 -*-
"""Файл 5 базы Meyer: компании из «Парка компрессорного оборудования» (park_panel.db).

Владелец 07.10: «номера с checko.ru бесполезны, выкинь», «только сайт или тендерные площадки»,
«карточки закупок не всегда значило именно номер на странице, иногда он был в приложенных файлах».
  * номер остаётся, если источник — сайт самой компании (проверка «чья»: park5-chya.jsonl + ручной
    разбор) и номер есть на живой странице, или площадка закупок, где компания — заказчик
    (ИНН на карточке); номера нет на карточке -> «номер в документах закупки»;
  * служебный номер самой площадки (Росэлторг, 8-800 на сайте школы и т.п.) — не номер компании;
  * роль: подпись рядом с номером на странице (модель, park5/park5_roli), для площадок —
    «контактное лицо закупки»; ЛПР — по списку сегмента (meyer_lpr.РОЛИ);
  * порядок: ЛПР с ФИО -> ЛПР -> другие должности -> общие; мобильные выше;
  * проверка: ни одной компании из файлов 1–4, ни одной сделки/запрета панели.

    python park5_xlsx.py <park5.jsonl> <park5-chya.jsonl> <park5-roli.jsonl> <sdelki-inn.json> <папка 4 файлов> <out.xlsx>
"""
import json
import os
import re
import sys
import time
import urllib.parse

from openpyxl import Workbook, load_workbook

from meyer_lpr import РОЛИ
from meyer_xlsx import лист as _лист
from unikalnye_4_fayla import запреты, инн_листа

ЗАКУПКИ = re.compile(r'zakupki\.gov|tender\.pro|roseltorg|b2b-center|etpgpb|fabrikant|zakupki360|rts-tender|'
                     r'sberbank-ast|tektorg|lot-online|zakazrf|otc\.ru|onlinecontract|bicotender|etp-ets', re.I)
# свои сайты: park5_chya.py «да» + ручной разбор 07.10 (chhp.ru — свой, но имя в базе без кавычек)
СВОИ = {'mtscentrrb.ru', 'mlkgroup.ru', 'kazanmez.ru', 'candy-factory.ru', 'biorosva.ru', 'kstovo-hleb.com', 'chhp.ru'}
ЧУЖИЕ = {  # прошли автопроверку по совпадению короткого названия, но это другая организация
    'mukomol.com': 'сайт АО ВКХП «Мукомол» (Владимир, тел. 4922), а ИНН компании — Рязанской обл.',
    'sozvezdie.ru': 'сайт аптечного объединения «МС Созвездие», компания — птицехозяйство',
    'zaman-mebel.ru': 'сайт мебельной фабрики ZAMAN, не эта компания',
    'besao.ru': 'сайт АО «БЭС», не эта компания',
    'sandugachschool.obr.site': 'сайт школы/лагеря «Сандугач» (Башкирия), компания — Саратовская обл.',
    'moscow-ice.ru': 'на сайте «Московское мороженое» нет ни ИНН, ни названия компании',
    'roshleb.com': 'PDF не открылся, принадлежность не подтверждена',
}
СЛУЖЕБНЫЕ = {'74951502020': 'справочный номер площадки Росэлторг, не компании'}
НЕ_ПЕРВОЕ_ЛИЦО = re.compile(r'по развитию|по маркетингу|региональн|финансов|по продаж|по персоналу|по безопасност', re.I)
КЛАСС_В_РОЛЬ = {'директор': 'директор/руководитель', 'приёмная': 'общий/приёмная', 'общий': 'общий/приёмная',
                'закупки': 'закупки', 'главный инженер': 'главный инженер', 'технический директор': 'технический директор',
                'производство': 'производство', 'главный технолог': 'главный технолог', 'технолог': 'технолог',
                'качество': 'качество', 'агроном': 'агроном', 'семеноводство': 'семеноводство', 'элеватор': 'производство',
                'коммерческий директор': 'коммерческий директор', 'продажи': 'продажи', 'бухгалтерия': 'бухгалтерия',
                'кадры': 'кадры', 'инженер': 'инженер/механик', 'другое': 'другая должность'}


def лист(wb, имя, поля, строки, ширины):
    _лист(wb, имя, поля, [dict(zip(поля, r)) for r in строки], ширины)


def хост(u):
    h = (urllib.parse.urlsplit(u or '').hostname or '').lower()
    return h[4:] if h.startswith('www.') else h


def свой_хост(h):
    return next((с for с in СВОИ | set(ЧУЖИЕ) if h == с or h.endswith('.' + с)), h)


def сегмент_лпр(сегм):
    роли = set()
    for с in (сегм or '').split(' | '):
        if с.startswith('7'):
            роли |= РОЛИ['7 доп. ОКВЭД (предложено)']
        elif с in РОЛИ:
            роли |= РОЛИ[с]
    return роли or РОЛИ['3 пищевые']


def добавочный(контекст, ц):
    if not контекст:
        return ''
    м = re.search(r'\D{0,3}'.join(ц[-7:]), контекст)
    if not м:
        return ''
    д = re.match(r'[\s,;]*(?:доб|вн)\.?\s*:?\s*(\d{1,6})', контекст[м.end():])
    return д.group(1) if д else ''


def main(п_park5, п_chya, п_roli, п_сделки, п_4, п_out):
    стр = [json.loads(s) for s in open(п_park5, encoding='utf-8')]
    комп, номера = стр[0]['данные'], стр[1:]
    чья = {(x['inn'], x['url']): x for x in map(json.loads, open(п_chya, encoding='utf-8'))}
    роли = {(x['inn'], x['номер']): x for x in map(json.loads, open(п_roli, encoding='utf-8'))}
    зап = запреты(п_сделки)
    в_файлах = {}
    for f in sorted(os.listdir(п_4)):
        if f.endswith('.xlsx'):
            wb = load_workbook(os.path.join(п_4, f), read_only=True)
            for ws in wb.worksheets:
                if ws.title not in ('Компании', 'Спорные'):
                    continue  # «Сверка»/«Снято» — это убранные номера, не компании файла
                for i in инн_листа(ws) or ():
                    в_файлах.setdefault(i, f[:1])
    строки, снято, счёт = {}, [], {'checko.ru (выкинуты по слову владельца)': 0}
    for x in номера:
        h = хост(x['url'])
        к = комп[x['inn']]['кандидат']
        if 'checko.ru' in h:
            счёт['checko.ru (выкинуты по слову владельца)'] += 1
            continue
        причина = ''
        if not x['номер']:
            причина = 'в парке нет номера'
        elif x['номер'] in СЛУЖЕБНЫЕ:
            причина = СЛУЖЕБНЫЕ[x['номер']]
        elif свой_хост(h) in ЧУЖИЕ:
            причина = ЧУЖИЕ[свой_хост(h)]
        elif ЗАКУПКИ.search(h):
            ч = чья.get((x['inn'], x['url']), {}).get('чья', '')
            if not ч.startswith('да'):
                причина = 'на карточке закупки нет ИНН компании'
        elif свой_хост(h) not in СВОИ:
            причина = 'источник не сайт компании и не площадка (%s)' % h
        if not причина and not (x['итог'] == 'на странице' or x['итог'].startswith('закупка')):
            причина = 'номера сейчас нет на странице (%s)' % x['итог']
        if причина:
            if [к['Название'], x['inn'], x['номер'], x['url'], x['итог'], причина] in снято:
                continue
            снято.append([к['Название'], x['inn'], x['номер'], x['url'], x['итог'], причина])
            continue
        закупка = bool(ЗАКУПКИ.search(h))
        р = роли.get((x['inn'], x['номер'])) or {}
        фио = (x.get('стр_фио') or р.get('стр_фио') or '').strip()
        должн = (x.get('стр_должность') or р.get('стр_должность') or '').strip()
        класс = x.get('стр_класс') or р.get('стр_класс') or ''
        if закупка:
            фио = фио or (x.get('person') or '').strip()
            должн, роль = 'контактное лицо закупки', 'закупки'
        else:
            роль = КЛАСС_В_РОЛЬ.get(класс, '')
            if роль == 'директор/руководитель' and НЕ_ПЕРВОЕ_ЛИЦО.search(должн):
                роль = 'другая должность'
            if not роль:
                роль = 'общий/приёмная' if not (фио or должн) else 'другая должность'
        лпр = роль in сегмент_лпр(к['Сегмент по осн. ОКВЭД'])
        моб = x['номер'].startswith('79')
        доб = добавочный(x.get('контекст'), x['номер'])
        ключ = (x['inn'], x['номер'])
        if ключ in строки:  # тот же номер с двух страниц — оставить лучшую подпись
            if строки[ключ]['_вес'] <= (0 if лпр else 1, 0 if фио else 1):
                continue
        п = комп[x['inn']]
        строки[ключ] = {
            '_вес': (0 if лпр else 1, 0 if фио else 1),
            '_порядок': (0 if лпр and фио else 1 if лпр else 2 if роль not in ('общий/приёмная',) else 3, 0 if моб else 1),
            'Название': к['Название'], 'ИНН': x['inn'], 'Регион': к['Регион'], 'Сегмент': к['Сегмент по осн. ОКВЭД'],
            'Основной ОКВЭД': к['Основной ОКВЭД'], 'Все ОКВЭД (парк)': п.get('okved_vse') or п.get('okved_kody') or '',
            'Выручка (парк)': к['Выручка'], 'Доход 2025, руб (ФНС)': п.get('доход_2025'),
            'Где у нас': к['Где у нас'], 'ФИО': фио, 'Должность': должн, 'Роль': роль,
            'ЛПР по сегменту': 'да' if лпр else '', 'Мобильный': x['номер'] if моб else '',
            'Рабочий': '' if моб else (x['номер'] + (' доб. ' + доб if доб else '')), 'Добавочный': доб,
            'Источник': 'площадка закупок (компания — заказчик)' if закупка else 'сайт компании',
            'Проверка номера': ('номер на карточке закупки' if x['итог'] == 'на странице' else
                                'номер в документах закупки (на карточке нет)') if закупка else 'номер на живой странице сайта',
            'Ссылка на источник': x['url'],
            'Фрагмент страницы': (x.get('контекст') or '')[-220:],
        }
    # проверки уникальности и сделок
    ин5 = {k[0] for k in строки}
    повтор = sorted(i for i in ин5 if i in в_файлах)
    сделка = sorted(i for i in ин5 if i in зап)
    if повтор or сделка:
        raise SystemExit('стоп: в файле 5 есть компании из файлов 1–4 %s или запреты панели %s' % (повтор, сделка))
    ряд = sorted(строки.values(), key=lambda r: (r['Название'], r['_порядок']))
    # компании по лучшему контакту, внутри — контакты по приоритету
    лучший = {}
    for r in ряд:
        лучший[r['ИНН']] = min(лучший.get(r['ИНН'], (9, 9)), r['_порядок'])
    ряд.sort(key=lambda r: (лучший[r['ИНН']], r['Название'], r['_порядок']))
    кол = [k for k in ряд[0] if not k.startswith('_')]
    wb = Workbook(write_only=True)
    без = sorted((v for i, v in комп.items() if i not in ин5), key=lambda v: v['кандидат']['Название'])
    # сводка
    св = [['Файл 5 — компании из «Парка компрессорного оборудования», целевые для Meyer по основному ОКВЭД'],
          ['Собран %s. Откуда: база park_panel.db (дроп) — 76 компаний, которых нет в файлах 1–4, без сделок,'
           ' запретов панели и ликвидированных.' % time.strftime('%d.%m.%Y')],
          ['Номера только с сайта самой компании (номер есть на живой странице, сайт проверен на принадлежность)'
           ' или с площадок закупок, где компания — заказчик. Номера с checko.ru выкинуты.'],
          ['Карточка закупки без номера: номер был в документах закупки — оставлен с пометкой.'],
          [],
          ['Компаний с номером', len(ин5)], ['Номеров', len(ряд)],
          ['  из них ЛПР по сегменту', sum(1 for r in ряд if r['ЛПР по сегменту'])],
          ['  мобильных', sum(1 for r in ряд if r['Мобильный'])],
          ['  с площадок закупок', sum(1 for r in ряд if r['Источник'].startswith('площадка'))],
          ['  с сайтов компаний', sum(1 for r in ряд if r['Источник'] == 'сайт компании')],
          ['Компаний без номера с сайта/площадки (лист «Без номера»)', len(без)],
          ['Номеров checko.ru выкинуто', счёт['checko.ru (выкинуты по слову владельца)']],
          ['Номеров снято по проверке (лист «Снято»)', len(снято)],
          ['Повторов с файлами 1–4', 0], ['Сделок и запретов панели', 0]]
    лист(wb, 'Сводка', ['Показатель', 'Значение'], [r + [''] * (2 - len(r)) for r in св], [100, 14])
    лист(wb, 'Контакты', кол, [[r[k] for k in кол] for r in ряд],
         [34, 12, 18, 16, 10, 24, 14, 14, 18, 26, 28, 18, 8, 13, 18, 8, 22, 24, 40, 60])
    лист(wb, 'Без номера', ['Название', 'ИНН', 'Регион', 'Сегмент', 'Основной ОКВЭД', 'Выручка (парк)',
                            'Доход 2025, руб (ФНС)', 'Где у нас'],
         [[v['кандидат']['Название'], v['кандидат']['ИНН'], v['кандидат']['Регион'], v['кандидат']['Сегмент по осн. ОКВЭД'],
           v['кандидат']['Основной ОКВЭД'], v['кандидат']['Выручка'], v.get('доход_2025'), v['кандидат']['Где у нас']] for v in без],
         [40, 12, 20, 18, 10, 14, 14, 30])
    лист(wb, 'Снято', ['Название', 'ИНН', 'Номер', 'Ссылка', 'Итог проверки', 'Почему снят'], снято,
         [34, 12, 13, 50, 26, 60])
    wb.save(п_out)
    print(json.dumps({'компаний': len(ин5), 'номеров': len(ряд), 'лпр': св[7][1], 'моб': св[8][1], 'без_номера': len(без),
                      'снято': len(снято), 'checko': счёт}, ensure_ascii=False))


if __name__ == '__main__':
    main(*sys.argv[1:7])
