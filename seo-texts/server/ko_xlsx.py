# 21.10, владелец: список КО (KO-inn-ne-v-rabote-20261021.csv, 523 ИНН) — домены из всех панелей + полное обогащение контактами
# (без паспорта). Наборы ko1/ko2/ko3 (_ko_obogashchenie.py: первый/второй/третий подтверждённый домен компании) -> pilot_xlsx
# (лесенка КЦ, снятия чужих/битых, ЛПР, письмо) через fsa_vse_xlsx.прогон_набора -> один файл:
#   «Работа» — все 523 ИНН (менеджер/статус из выгрузки, домены с вердиктом, ЛПР и адрес письма — из первого домена, где есть),
#   «Контакты» — контакты всех доменов без повторов, «Домены» — каждая пара ИНН–домен и чем подтверждена,
#   «Спорные», «Снято», «Сводка».
# Запуск: python3 ko_xlsx.py <папка ko-наборов с дропа> <рабочая папка> <папка meyer7-стоп-файлов> <ko-inn.json> <выход.xlsx>
#         [<сделки Meyer.csv> <сделки КЦ/СЦ.csv>] — выгрузки Битрикса: колонки «Битрикс КЦ/СЦ», «Битрикс Meyer»
import json, os, sys
import openpyxl
from openpyxl.styles import Font, PatternFill
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fsa_vse_xlsx as F  # noqa: E402
import kc_cel as KC  # noqa: E402
import re  # noqa: E402

НАБОРЫ = ('ko1', 'ko2', 'ko3')
ПОЛЯ_ЛПР = ('ЛПР: ФИО', 'ЛПР: должность', 'ЛПР: роль', 'ЛПР: телефон', 'ЛПР: e-mail', 'Письмо: e-mail', 'Письмо: кому (ФИО)',
            'Письмо: должность', 'Письмо: ступень лесенки')
ЧИСЛА = ('Номеров', 'Почт', 'Из них ЛПР', 'Мобильных')


def jl(п):
    return [json.loads(s) for s in open(п, encoding='utf-8') if s.strip()] if os.path.exists(п) else []


def лист(wb, имя, шапка, строки):
    ws = wb.create_sheet(имя)
    ws.append(list(шапка))
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in строки:
        ws.append([r.get(k, '') if isinstance(r, dict) else r[i] for i, k in enumerate(шапка)])
    ws.freeze_panes = 'C2'
    ws.auto_filter.ref = ws.dimensions
    return ws


def битрикс(сд):
    """22.10, владелец «тут ты не проставлял метки, есть в Битриксе или нету?»: сводка сделок компании одной строкой."""
    if not сд:
        return ''
    акт = [x for x in сд if (x.get('АКТИВНА') or '').strip().lower() == 'да']
    усп = [x for x in сд if (x.get('СТАТУС') or '') == 'Успешна' or (x.get('STAGE_ID') or '').endswith('WON')]
    пров = [x for x in сд if (x.get('СТАТУС') or '') == 'Провалена' or (x.get('STAGE_ID') or '').endswith('LOSE')]
    посл = max(сд, key=lambda x: x.get('DATE_CREATE') or '')
    ч = ['сделок %d' % len(сд)]
    if акт:
        ч.append('АКТИВНАЯ: ' + '; '.join(F.опис(x) for x in акт[:2]))
    if усп:
        ч.append('успешных %d (посл. %s)' % (len(усп), max((x.get('CLOSEDATE') or x.get('DATE_CREATE') or '')[:10] for x in усп)))
    if пров:
        ч.append('провалено %d' % len(пров))
    ч.append('последняя ' + F.опис(посл))
    return ' | '.join(ч)


def main(папка, раб, M, путь_ko, выход, путь_meyer='', путь_кц=''):
    ko = json.load(open(путь_ko, encoding='utf-8'))
    сд_м = F.сделки(путь_meyer) if путь_meyer else {}
    сд_к = F.сделки(путь_кц) if путь_кц else {}
    пр = jl(os.path.join(папка, 'ko-domeny-proverka.jsonl'))
    рез, спорные, снято, не_откр = {}, [], [], []
    for н in НАБОРЫ:
        сп = json.load(open(os.path.join(папка, н + '-spisok.json'), encoding='utf-8'))['компании']
        си = {x['inn']: {'сайт': x['домен'], 'как': x['как'], 'страница_с_инн': ''} for x in пр
              if x['свой'] and x['inn'] in сп and F.хост(сп[x['inn']]['сайт']) == F.хост(x['домен'])}
        р, пояс = F.прогон_набора(н, папка, раб, M, си, {}, False)
        if р is None:
            sys.exit('%s: %s' % (н, пояс))
        рез[н] = р
        wb = openpyxl.load_workbook(os.path.join(раб, н, н + '.xlsx'), read_only=True)
        for имя, куда in (('Спорные', спорные), ('Снято', снято), ('Не открылись (для Зенки)', не_откр)):
            if имя in wb.sheetnames:
                for r in F.строки(wb, имя):
                    куда.append(dict(r, Домен=н[-1]))
    # 21.10: КО — дочки холдингов, домен из панелей часто сайт группы (НЛМК, Металлоинвест…): pilot такие контакты снимает
    # («опровергнуто (группа)») — отдаём их отдельным листом с пометкой, в «Контакты» не смешиваем
    группа, видели = [], set()
    for x in снято:
        if 'опровергнуто (группа)' in str(x.get('Почему не взят') or '') and (str(x.get('ИНН / УНП')), x.get('Контакт')) not in видели:
            видели.add((str(x.get('ИНН / УНП')), x.get('Контакт')))
            группа.append(x)
    снято = [x for x in снято if 'опровергнуто (группа)' not in str(x.get('Почему не взят') or '')]
    сколько_гр = {}
    for x in группа:
        сколько_гр[str(x.get('ИНН / УНП'))] = сколько_гр.get(str(x.get('ИНН / УНП')), 0) + 1
    домены = {}
    for x in пр:
        домены.setdefault(x['inn'], []).append(x)
    работа = []
    for i, инфо in ko.items():
        дд = домены.get(i, [])
        r = {'ИНН': i, 'Название': инфо.get('имя', ''), 'Регион': инфо.get('регион', ''), 'Менеджер': инфо.get('менеджер', ''),
             'Статус': инфо.get('статус', ''), 'Сайт в выгрузке': инфо.get('сайт', ''),
             'Битрикс КЦ/СЦ': битрикс(сд_к.get(i)), 'Битрикс Meyer': битрикс(сд_м.get(i)),
             'Домены (подтверждены)': '\n'.join('%s — %s' % (x['домен'], x['как']) for x in дд if x['свой']),
             'Домены (не подтверждены)': '\n'.join(x['домен'] for x in дд if not x['свой'])}
        строки = [(н, рез[н]['комп'][i]) for н in НАБОРЫ if i in рез[н]['комп']]
        с_лпр = [(н, x) for н, x in строки if x.get('ЛПР: ФИО') or x.get('Письмо: e-mail')]
        н0, x0 = (с_лпр or строки or [('', {})])[0]
        r['Обогащён с домена'] = F.хост(x0.get('Сайт') or '') if x0 else ''
        for k in ПОЛЯ_ЛПР:
            r[k] = x0.get(k, '') or ''
        for k in ЧИСЛА:
            r[k] = sum(int(x.get(k) or 0) for _, x in строки)
        r['Сайт: чей'] = x0.get('Сайт: чей', '') or ''
        r['Описание (по сайту)'] = x0.get('Описание (по сайту)', '') or ''
        r['Спорный (опровергатель)'] = '; '.join(sorted({str(s.get('Почему') or '')[:200] for s in спорные if str(s.get('ИНН')) == i}))
        r['Контактов сайта группы'] = сколько_гр.get(i, 0)
        r['Итог'] = ('нет подтверждённого домена' if not строки else
                     'есть ЛПР/письмо' if с_лпр else 'контакты только общие' if r['Номеров'] or r['Почт'] else
                     'только контакты сайта группы' if r['Контактов сайта группы'] else 'контактов на сайте нет')
        работа.append(r)
    работа.sort(key=lambda r: (r['Итог'] != 'есть ЛПР/письмо', r['Итог'] == 'нет подтверждённого домена', r['Менеджер'], r['Название']))
    конт, видели = [], set()
    for н in НАБОРЫ:
        for x in рез[н]['конт']:
            кл = (str(x.get('ИНН / УНП')), x.get('ФИО') or '', x.get('Рабочий') or '', x.get('Мобильный') or '', x.get('E-mail') or '')
            if кл in видели:
                continue
            видели.add(кл)
            инфо = ko.get(str(x.get('ИНН / УНП')), {})
            конт.append(dict(x, Менеджер=инфо.get('менеджер', ''), Статус=инфо.get('статус', '')))
    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    ш = ('ИНН', 'Название', 'Регион', 'Менеджер', 'Статус', 'Битрикс КЦ/СЦ', 'Битрикс Meyer', 'Итог') + ПОЛЯ_ЛПР + ЧИСЛА + ('Контактов сайта группы',
        'Обогащён с домена', 'Домены (подтверждены)', 'Домены (не подтверждены)', 'Сайт в выгрузке', 'Сайт: чей',
        'Спорный (опровергатель)', 'Описание (по сайту)')
    ws = лист(wb, 'Работа', ш, работа)
    зел = PatternFill('solid', fgColor='E2EFDA')
    for row in ws.iter_rows(min_row=2):
        if row[7].value == 'есть ЛПР/письмо':
            row[7].fill = зел
    шк = ('ИНН / УНП', 'Название', 'Менеджер', 'Статус', 'ФИО', 'Должность (как на сайте)', 'Роль', 'ЛПР по оборудованию',
          'Мобильный', 'Рабочий', 'Добавочный', 'E-mail', 'Сайт', 'Почему ЛПР', 'Источник', 'Проверка', 'Ссылка на источник',
          'Фрагмент страницы')
    лист(wb, 'Контакты', шк, конт)
    # 21.10, владелец: «это для прозвона файл… по лесенке для 523 ИНН сделай» — строка на номер; внутри компании номера по
    # ступеням лесенки КЦ (kc_cel.ступень: механик/энергетик -> главный инженер -> снабжение -> производство -> технолог ->
    # руководитель -> коммерция -> общий); при равной ступени — ЛПР, мобильный, с ФИО. Кадры/бухгалтерия/продажи/горячие
    # линии (ступень «никогда») — не звоним. Номера сайта группы — последними, с пометкой.
    звон, лучшее = {}, {}

    def имя_ст(ст):  # для звонка 8-я ступень — общий номер, а не «общий ящик»
        return 'общий номер / приёмная' if ст == 8 else KC.название(ст)
    for x in конт:
        инн = str(x.get('ИНН / УНП'))
        for тел, моб in ((x.get('Мобильный'), True), (x.get('Рабочий'), False)):
            if not тел:
                continue
            ст = KC.ступень(x.get('Роль') or '', '', x.get('Должность (как на сайте)') or '', x.get('E-mail') or '', x.get('ФИО') or '')
            if ст is None:
                continue
            кл = (ст, 0 if x.get('ЛПР по оборудованию') == 'да' else 1, 0 if моб else 1, 0 if x.get('ФИО') else 1)
            к = (инн, re.sub(r'\D', '', str(тел))[-10:] + '#' + str(x.get('Добавочный') or ''))
            if к not in звон or кл < звон[к][0]:
                звон[к] = (кл, {'ИНН': инн, 'Название': x.get('Название'), 'Менеджер': x.get('Менеджер'), 'Статус': x.get('Статус'),
                                'Ступень лесенки': '%d. %s' % (ст, имя_ст(ст)), 'ФИО': x.get('ФИО'),
                                'Должность': x.get('Должность (как на сайте)'), 'Роль': x.get('Роль'),
                                'ЛПР': x.get('ЛПР по оборудованию'), 'Телефон': тел, 'Мобильный': 'да' if моб else '',
                                'Добавочный': x.get('Добавочный'), 'E-mail': x.get('E-mail'), 'Сайт': x.get('Сайт'),
                                'Источник': x.get('Ссылка на источник')})
    for x in группа:
        инн, к_ = str(x.get('ИНН / УНП')), str(x.get('Контакт') or '')
        if '@' in к_ or len(re.sub(r'\D', '', к_)) < 10:
            continue
        к = (инн, re.sub(r'\D', '', к_)[-10:] + '#')
        if к not in звон:
            инфо = ko.get(инн, {})
            звон[к] = ((11, 1, 1, 1), {'ИНН': инн, 'Название': x.get('Название'), 'Менеджер': инфо.get('менеджер'),
                                       'Статус': инфо.get('статус'), 'Ступень лесенки': '11. сайт группы (не проверено, что эта компания)',
                                       'Телефон': к_, 'Сайт': x.get('Ссылка'), 'Источник': x.get('Ссылка')})
    for (инн, _), (кл, r) in звон.items():
        лучшее[инн] = min(лучшее.get(инн, (99,)), кл)
    строки_з = sorted(звон.values(), key=lambda t: (лучшее[t[1]['ИНН']], str(t[1]['Менеджер'] or ''), t[1]['ИНН'], t[0]))
    номер, пред = 0, None
    for _, r in строки_з:
        номер = номер + 1 if r['ИНН'] == пред else 1
        пред = r['ИНН']
        r['Очерёдность в компании'] = номер
    # 22.10, владелец «проставь у всех метки, включая тех, у кого не получилось найти контакты»: все 523 ИНН в прозвоне —
    # без номеров строкой «номеров не найдено» с причиной (итог по компании) в конце листа
    итог_по = {r['ИНН']: r for r in работа}
    for i, инфо in ko.items():
        if i not in лучшее:
            rr = итог_по.get(i) or {}
            строки_з.append(((99,), {'ИНН': i, 'Название': инфо.get('имя'), 'Менеджер': инфо.get('менеджер'),
                                     'Статус': инфо.get('статус'), 'Ступень лесенки': '— номеров не найдено',
                                     'Сайт': rr.get('Обогащён с домена') or (rr.get('Домены (подтверждены)') or '').split(' — ')[0]
                                     or инфо.get('сайт') or '', 'Источник': rr.get('Итог', '')}))
    for _, r in строки_з:
        r['Битрикс КЦ/СЦ'], r['Битрикс Meyer'] = битрикс(сд_к.get(r['ИНН'])), битрикс(сд_м.get(r['ИНН']))
        r['Итог по компании'] = (итог_по.get(r['ИНН']) or {}).get('Итог', '')
    шз = ('Менеджер', 'Название', 'ИНН', 'Статус', 'Битрикс КЦ/СЦ', 'Битрикс Meyer', 'Итог по компании', 'Очерёдность в компании', 'Ступень лесенки', 'ФИО', 'Должность', 'Роль', 'ЛПР',
          'Телефон', 'Мобильный', 'Добавочный', 'E-mail', 'Сайт', 'Источник')
    wz = лист(wb, 'Прозвон по лесенке', шз, [r for _, r in строки_з])
    wb.move_sheet(wz, -(len(wb.sheetnames) - 1))
    for буква, ш in zip('ABCDEFGHIJKLMNOPQRS', (10, 40, 13, 14, 40, 30, 22, 10, 30, 30, 34, 24, 6, 20, 9, 9, 28, 28, 40)):
        wz.column_dimensions[буква].width = ш
    по_ст = {}
    for кл, _ in звон.values():
        по_ст[кл[0]] = по_ст.get(кл[0], 0) + 1
    лист(wb, 'Домены', ('ИНН', 'Название', 'Домен', 'Свой', 'Чем подтверждён'),
         [{'ИНН': x['inn'], 'Название': ko.get(x['inn'], {}).get('имя', ''), 'Домен': x['домен'], 'Свой': 'да' if x['свой'] else 'нет',
           'Чем подтверждён': x['как']} for x in пр])
    if группа:
        лист(wb, 'Контакты сайта группы', ('Название', 'ИНН / УНП', 'Контакт', 'Ссылка', 'Почему не взят', 'Фрагмент'), группа)
    if спорные:
        лист(wb, 'Спорные', tuple(спорные[0].keys()), спорные)
    if снято:
        лист(wb, 'Снято', tuple(снято[0].keys()), снято)
    if не_откр:
        лист(wb, 'Не открылись (для Зенки)', tuple(не_откр[0].keys()), не_откр)
    итоги = {}
    for r in работа:
        итоги[r['Итог']] = итоги.get(r['Итог'], 0) + 1
    св = [('ИНН в списке КО', len(ko)),
          ('Есть сделки КЦ/СЦ в Битриксе', sum(1 for i in ko if сд_к.get(i))),
          ('  из них активная КЦ/СЦ', sum(1 for i in ko if 'АКТИВНАЯ' in битрикс(сд_к.get(i)))),
          ('Есть сделки Meyer в Битриксе', sum(1 for i in ko if сд_м.get(i))),
          ('  из них активная Meyer', sum(1 for i in ko if 'АКТИВНАЯ' in битрикс(сд_м.get(i)))),
          ('Нет ни одной сделки в Битриксе', sum(1 for i in ko if not сд_к.get(i) and not сд_м.get(i))), ('Пар ИНН–домен найдено в панелях', len(пр)),
          ('Из них подтверждены (сайт из выгрузки / ИНН на сайте / название на главной)', sum(1 for x in пр if x['свой'])),
          ('Компаний с подтверждённым доменом', sum(1 for i in ko if any(x['свой'] for x in домены.get(i, []))))]
    св += [('Итог: ' + k, v) for k, v in sorted(итоги.items(), key=lambda t: -t[1])]
    св += [('Контактов (без повторов)', len(конт)), ('Контактов сайта группы (отдельный лист, не проверены как контакт '
                                                     'именно этой компании)', len(группа)), ('Из них с ФИО', sum(1 for x in конт if x.get('ФИО'))),
           ('Номеров (сумма по компаниям)', sum(r['Номеров'] for r in работа)), ('Почт (сумма по компаниям)', sum(r['Почт'] for r in работа)),
           ('Прозвон: номеров всего (без кадров/бухгалтерии/продаж/горячих линий)', len(звон)),
           ('Прозвон: компаний с номером', len(лучшее))] + [('Прозвон: ступень ' + ('%d. %s' % (k, имя_ст(k)) if k < 11 else
                                                                              '11. сайт группы'), v) for k, v in sorted(по_ст.items())] + [
           ('Лесенка', 'КЦ (кому писать — по ступеням лесенки компрессорного направления)'), ('Паспорт', 'не строился (по заданию)')]
    ws = wb.create_sheet('Сводка', 0)
    ws.append(['Показатель', 'Значение'])
    for k, v in св:
        ws.append([k, v])
    ws.column_dimensions['A'].width = 80
    wb.save(выход)
    for k, v in св:
        print(k, '|', v)


if __name__ == '__main__':
    main(*sys.argv[1:8])
