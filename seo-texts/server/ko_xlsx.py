# -*- coding: utf-8 -*-
# 21.10, владелец: список КО (KO-inn-ne-v-rabote-20261021.csv, 523 ИНН) — домены из всех панелей + полное обогащение контактами
# (без паспорта). Наборы ko1/ko2/ko3 (_ko_obogashchenie.py: первый/второй/третий подтверждённый домен компании) -> pilot_xlsx
# (лесенка КЦ, снятия чужих/битых, ЛПР, письмо) через fsa_vse_xlsx.прогон_набора -> один файл:
#   «Работа» — все 523 ИНН (менеджер/статус из выгрузки, домены с вердиктом, ЛПР и адрес письма — из первого домена, где есть),
#   «Контакты» — контакты всех доменов без повторов, «Домены» — каждая пара ИНН–домен и чем подтверждена,
#   «Спорные», «Снято», «Сводка».
# Запуск: python3 ko_xlsx.py <папка ko-наборов с дропа> <рабочая папка> <папка meyer7-стоп-файлов> <ko-inn.json> <выход.xlsx>
import json, os, sys
import openpyxl
from openpyxl.styles import Font, PatternFill
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fsa_vse_xlsx as F  # noqa: E402

НАБОРЫ = ('ko1', 'ko2', 'ko3')
ПОЛЯ_ЛПР = ('ЛПР: ФИО', 'ЛПР: должность', 'ЛПР: роль', 'ЛПР: телефон', 'ЛПР: e-mail', 'Письмо: e-mail', 'Письмо: кому (ФИО)',
            'Письмо: должность', 'Письмо: ступень лесенки')
ЧИСЛА = ('Номеров', 'Почт', 'Из них ЛПР', 'Мобильных')


def jl(п):
    return [json.loads(s) for s in open(п, encoding='utf-8') if s.strip()] if os.path.exists(п) else []


def лист(wb, имя, шапка, строки):
    ws = wb.create_sheet(имя)
    ws.append(list(шапка))
    for c in ws[1]:
        c.font = Font(bold=True)
    for r in строки:
        ws.append([r.get(k, '') if isinstance(r, dict) else r[i] for i, k in enumerate(шапка)])
    ws.freeze_panes = 'C2'
    ws.auto_filter.ref = ws.dimensions
    return ws


def main(папка, раб, M, путь_ko, выход):
    ko = json.load(open(путь_ko, encoding='utf-8'))
    пр = jl(os.path.join(папка, 'ko-domeny-proverka.jsonl'))
    рез, спорные, снято, не_откр = {}, [], [], []
    for н in НАБОРЫ:
        сп = json.load(open(os.path.join(папка, н + '-spisok.json'), encoding='utf-8'))['компании']
        си = {x['inn']: {'сайт': x['домен'], 'как': x['как'], 'страница_с_инн': ''} for x in пр
              if x['свой'] and x['inn'] in сп and F.хост(сп[x['inn']]['сайт']) == F.хост(x['домен'])}
        р, пояс = F.прогон_набора(н, папка, раб, M, си, {}, False)
        if р is None:
            sys.exit('%s: %s' % (н, пояс))
        рез[н] = р
        wb = openpyxl.load_workbook(os.path.join(раб, н, н + '.xlsx'), read_only=True)
        for имя, куда in (('Спорные', спорные), ('Снято', снято), ('Не открылись (для Зенки)', не_откр)):
            if имя in wb.sheetnames:
                for r in F.строки(wb, имя):
                    куда.append(dict(r, Домен=н[-1]))
    # 21.10: КО — дочки холдингов, домен из панелей часто сайт группы (НЛМК, Металлоинвест…): pilot такие контакты снимает
    # («опровергнуто (группа)») — отдаём их отдельным листом с пометкой, в «Контакты» не смешиваем
    группа, видели = [], set()
    for x in снято:
        if 'опровергнуто (группа)' in str(x.get('Почему не взят') or '') and (str(x.get('ИНН / УНП')), x.get('Контакт')) not in видели:
            видели.add((str(x.get('ИНН / УНП')), x.get('Контакт')))
            группа.append(x)
    снято = [x for x in снято if 'опровергнуто (группа)' not in str(x.get('Почему не взят') or '')]
    сколько_гр = {}
    for x in группа:
        сколько_гр[str(x.get('ИНН / УНП'))] = сколько_гр.get(str(x.get('ИНН / УНП')), 0) + 1
    домены = {}
    for x in пр:
        домены.setdefault(x['inn'], []).append(x)
    работа = []
    for i, инфо in ko.items():
        дд = домены.get(i, [])
        r = {'ИНН': i, 'Название': инфо.get('имя', ''), 'Регион': инфо.get('регион', ''), 'Менеджер': инфо.get('менеджер', ''),
             'Статус': инфо.get('статус', ''), 'Сайт в выгрузке': инфо.get('сайт', ''),
             'Домены (подтверждены)': '\n'.join('%s — %s' % (x['домен'], x['как']) for x in дд if x['свой']),
             'Домены (не подтверждены)': '\n'.join(x['домен'] for x in дд if not x['свой'])}
        строки = [(н, рез[н]['комп'][i]) for н in НАБОРЫ if i in рез[н]['комп']]
        с_лпр = [(н, x) for н, x in строки if x.get('ЛПР: ФИО') or x.get('Письмо: e-mail')]
        н0, x0 = (с_лпр or строки or [('', {})])[0]
        r['Обогащён с домена'] = F.хост(x0.get('Сайт') or '') if x0 else ''
        for k in ПОЛЯ_ЛПР:
            r[k] = x0.get(k, '') or ''
        for k in ЧИСЛА:
            r[k] = sum(int(x.get(k) or 0) for _, x in строки)
        r['Сайт: чей'] = x0.get('Сайт: чей', '') or ''
        r['Описание (по сайту)'] = x0.get('Описание (по сайту)', '') or ''
        r['Спорный (опровергатель)'] = '; '.join(sorted({str(s.get('Почему') or '')[:200] for s in спорные if str(s.get('ИНН')) == i}))
        r['Контактов сайта группы'] = сколько_гр.get(i, 0)
        r['Итог'] = ('нет подтверждённого домена' if not строки else
                     'есть ЛПР/письмо' if с_лпр else 'контакты только общие' if r['Номеров'] or r['Почт'] else
                     'только контакты сайта группы' if r['Контактов сайта группы'] else 'контактов на сайте нет')
        работа.append(r)
    работа.sort(key=lambda r: (r['Итог'] != 'есть ЛПР/письмо', r['Итог'] == 'нет подтверждённого домена', r['Менеджер'], r['Название']))
    конт, видели = [], set()
    for н in НАБОРЫ:
        for x in рез[н]['конт']:
            кл = (str(x.get('ИНН / УНП')), x.get('ФИО') or '', x.get('Рабочий') or '', x.get('Мобильный') or '', x.get('E-mail') or '')
            if кл in видели:
                continue
            видели.add(кл)
            инфо = ko.get(str(x.get('ИНН / УНП')), {})
            конт.append(dict(x, Менеджер=инфо.get('менеджер', ''), Статус=инфо.get('статус', '')))
    wb = openpyxl.Workbook()
    wb.remove(wb.active)
    ш = ('ИНН', 'Название', 'Регион', 'Менеджер', 'Статус', 'Итог') + ПОЛЯ_ЛПР + ЧИСЛА + ('Контактов сайта группы',
        'Обогащён с домена', 'Домены (подтверждены)', 'Домены (не подтверждены)', 'Сайт в выгрузке', 'Сайт: чей',
        'Спорный (опровергатель)', 'Описание (по сайту)')
    ws = лист(wb, 'Работа', ш, работа)
    зел = PatternFill('solid', fgColor='E2EFDA')
    for row in ws.iter_rows(min_row=2):
        if row[5].value == 'есть ЛПР/письмо':
            row[5].fill = зел
    шк = ('ИНН / УНП', 'Название', 'Менеджер', 'Статус', 'ФИО', 'Должность (как на сайте)', 'Роль', 'ЛПР по оборудованию',
          'Мобильный', 'Рабочий', 'Добавочный', 'E-mail', 'Сайт', 'Почему ЛПР', 'Источник', 'Проверка', 'Ссылка на источник',
          'Фрагмент страницы')
    лист(wb, 'Контакты', шк, конт)
    лист(wb, 'Домены', ('ИНН', 'Название', 'Домен', 'Свой', 'Чем подтверждён'),
         [{'ИНН': x['inn'], 'Название': ko.get(x['inn'], {}).get('имя', ''), 'Домен': x['домен'], 'Свой': 'да' if x['свой'] else 'нет',
           'Чем подтверждён': x['как']} for x in пр])
    if группа:
        лист(wb, 'Контакты сайта группы', ('Название', 'ИНН / УНП', 'Контакт', 'Ссылка', 'Почему не взят', 'Фрагмент'), группа)
    if спорные:
        лист(wb, 'Спорные', tuple(спорные[0].keys()), спорные)
    if снято:
        лист(wb, 'Снято', tuple(снято[0].keys()), снято)
    if не_откр:
        лист(wb, 'Не открылись (для Зенки)', tuple(не_откр[0].keys()), не_откр)
    итоги = {}
    for r in работа:
        итоги[r['Итог']] = итоги.get(r['Итог'], 0) + 1
    св = [('ИНН в списке КО', len(ko)), ('Пар ИНН–домен найдено в панелях', len(пр)),
          ('Из них подтверждены (сайт из выгрузки / ИНН на сайте / название на главной)', sum(1 for x in пр if x['свой'])),
          ('Компаний с подтверждённым доменом', sum(1 for i in ko if any(x['свой'] for x in домены.get(i, []))))]
    св += [('Итог: ' + k, v) for k, v in sorted(итоги.items(), key=lambda t: -t[1])]
    св += [('Контактов (без повторов)', len(конт)), ('Контактов сайта группы (отдельный лист, не проверены как контакт '
                                                     'именно этой компании)', len(группа)), ('Из них с ФИО', sum(1 for x in конт if x.get('ФИО'))),
           ('Номеров (сумма по компаниям)', sum(r['Номеров'] for r in работа)), ('Почт (сумма по компаниям)', sum(r['Почт'] for r in работа)),
           ('Лесенка', 'КЦ (кому писать — по ступеням лесенки компрессорного направления)'), ('Паспорт', 'не строился (по заданию)')]
    ws = wb.create_sheet('Сводка', 0)
    ws.append(['Показатель', 'Значение'])
    for k, v in св:
        ws.append([k, v])
    ws.column_dimensions['A'].width = 80
    wb.save(выход)
    for k, v in св:
        print(k, '|', v)


if __name__ == '__main__':
    main(*sys.argv[1:6])
