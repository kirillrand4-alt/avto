# -*- coding: utf-8 -*-
"""Забракованные по заходу: лежат ли они с телом или уйдут на перегенерацию.

Резюм partiya_gen считает компанию отработанной, если в журнальной записи
есть «ок» ЛИБО «тело». Значит судьба брака решается наличием тела: с телом
он ждёт спасения, без тела — вернётся в пул и будет написан заново опусом
за полную цену.
"""
import io
import json
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
записи = []
for с in io.open(ЖУРНАЛ, encoding="utf-8"):
    с = с.strip()
    if not с:
        continue
    try:
        записи.append(json.loads(с))
    except Exception:  # noqa: BLE001
        pass

брак = [з for з in записи if з.get("ок") is False]
print("записей всего: %d, из них брак: %d" % (len(записи), len(брак)))

виды = Counter()
for з in брак:
    п = з.get("брак") or []
    п = п if isinstance(п, list) else [str(п)]
    for причина in (п or ["(пусто)"]):
        ключ = str(причина).split(":")[0].strip()[:56]
        виды[ключ] += 1
print("\n=== ПРИЧИНЫ БРАКА ===")
for к, н in виды.most_common(14):
    print("  %-58s %5d" % (к, н))

def по_заходу(з):
    п = з.get("брак") or []
    п = п if isinstance(п, list) else [str(п)]
    return any("заход" in str(x).lower() for x in п)

заход = [з for з in брак if по_заходу(з)]
с_телом = [з for з in заход if з.get("тело")]
без_тела = [з for з in заход if not з.get("тело")]
print("\n=== БРАК ПО ЗАХОДУ ===")
print("  всего: %d" % len(заход))
print("  С ТЕЛОМ (лежат, ждут спасения, заново НЕ пишутся): %d" % len(с_телом))
print("  без тела (вернутся в пул и будут написаны заново): %d" % len(без_тела))

# сколько из них реально ещё не имеют письма ни в одной записи
инн_с_телом = {str(з.get("inn")) for з in записи if з.get("тело") or з.get("ок")}
потеряны = {str(з.get("inn")) for з in без_тела} - инн_с_телом
print("  из «без тела» у %d компаний нет письма НИ В ОДНОЙ записи —" % len(потеряны))
print("  именно они уйдут на повторную генерацию опусом")

print("\n=== ПРИМЕРЫ «С ТЕЛОМ» ===")
for з in с_телом[:3]:
    print("  %s | %s" % (str(з.get("имя"))[:40],
                         "; ".join(str(x)[:90] for x in (з.get("брак") or []))))
    print("    тема: %s" % str(з.get("тема"))[:70])
    print("    тело: %s…" % str(з.get("тело"))[:150].replace("\n", " "))

print("\n=== СКОЛЬКО ПОПЫТОК УЖЕ ПОТРАЧЕНО НА ЭТИ КОМПАНИИ ===")
попыток = Counter()
for з in записи:
    if з.get("inn") and з.get("этап") != "итог":
        попыток[str(з.get("inn"))] += 1
у_заходных = Counter(попыток[str(з.get("inn"))] for з in заход)
for п in sorted(у_заходных):
    print("  попыток %d: %d компаний%s"
          % (п, у_заходных[п], "  ← следующая станет последней" if п == 2
             else "  ← уже исчерпаны" if п >= 3 else ""))
