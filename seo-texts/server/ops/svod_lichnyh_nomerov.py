# -*- coding: utf-8 -*-
"""Свод личных номеров трёх сессий в ОДНО честное число.

Зачем вообще: каждая сессия назвала свой счёт — 232 у третьей, 210 у второй,
84 у меня, — и сложить их нельзя. Предприятия у нас почти одни и те же (из её
32 у меня есть 29), поэтому сумма 526 была бы приписками втрое. Складывать
можно только САМИ НОМЕРА с дедупом по десяти цифрам.

Три вещи, из-за которых этот скрипт устроен именно так.

1. **Мера у файлов РАЗНАЯ, и это видно сразу.** В моём файле роли из канона —
   гл.инженер, гл.механик, техконтакт. В файле третьей сессии роли крупные:
   «техническая» 329, «снабжение» 243, «неясно» 183. Если просто склеить, в
   общем числе окажутся снабженцы, а владелец просил ТЕХНИЧЕСКИХ. Поэтому
   каждая строка прогоняется через ОДИН канон (`EnrichDB._canon_role` по
   должности) и в отчёте два числа: всего личных и из них технических. Это тот
   же рубеж, который третья сессия записала сегодня: сравнивать надо не доли, а
   то, на чём держится метка.

2. **Служебные линии считаются на ОБЪЕДИНЁННОМ множестве.** Правило третьей
   сессии — номер, встречающийся у трёх и более разных ИНН, это не человек, а
   линия. По отдельности каждая сессия видит только свою часть раскида, и линия
   может не набрать трёх. После склейки видно больше, отсев строже.

3. **Добавочный отрезается ДО нормализации.** На этом я сегодня чуть не снёс
   141 живой номер: последние десять цифр съезжают на хвост добавочного, и
   настоящий номер выглядит мусором.

ПОПРАВКА ПОСЛЕ ПЕРВОГО ПРОГОНА, и она была моей, а не соседской. Первый свод
насчитал 130 технических и это неправда. У третьей сессии 409 строк из 756 БЕЗ
должности — человек назван, номер есть, а подписи нет, — и мой канон на пустой
строке честно возвращает пусто. Из этих 409 у неё 155 помечены `rol=техническая`
её собственным разбором, и все они выпадали из счёта. Роль автора теперь идёт
ЗАПАСНЫМ ходом, когда должности нет, с пометкой, на чём держится метка
(`osnovanie_roli`: должность / роль автора / нет).

И вторая поправка того же прогона: её файл ШИРЕ моего — там и городские номера,
у неё для этого есть своя колонка `vid_nomera`, и она с моей проверкой «первая
цифра 9» сходится ровно, 390 к 390, ни одного расхождения. То есть у неё не
ошибка, а другой охват: она выложила ВСЕ номера с ролями, я — только мобильные.
Считать «личные» надо по мобильным, поэтому в отчёте теперь две базы: весь свод
и его мобильная часть.

Числа в отчёте — ПЕРЕЧИТЫВАНИЕМ готового файла, а не счётчиком прогона.

Запуск: python svod_lichnyh_nomerov.py
"""
import csv
import io
import os
import re
import sys
from collections import Counter, defaultdict

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ДРОП = r'C:\seostat\drop\drop-storage'
ИМЯ = 'SVOD-LICHNYE-NOMERA.csv'
ПАПКА = r'C:\sender\server'
_ДОБ = re.compile(r'\s*(?:доб|вн|внутр|ext)\.?\s*[:№]?\s*[\d\-]+\s*$', re.I)


def д10(т):
    ц = re.sub(r'\D', '', _ДОБ.sub('', str(т or '')))
    return ц[-10:] if len(ц) >= 10 else ''


def клч(т):
    """Нормализованный вид для сравнения: регистр, ё и лишние пробелы — не
    расхождение фактов, а расхождение записи. Третья сессия замерила: у неё
    210 строк из 756 «согласны» только потому, что расхождение было невидимо,
    а большая часть их — как раз регистр и обрезка."""
    return re.sub(r'\s+', ' ', str(т or '').strip().lower()).replace('ё', 'е')


def на_дроп(путь, имя):
    import urllib.request
    урл = os.environ.get('DROP_URL', 'https://parsercompressor.online/drop')
    зпр = urllib.request.Request(
        урл.rstrip('/') + '/' + имя, data=open(путь, 'rb').read(), method='PUT',
        headers={'X-Drop-Token': os.environ.get('DROP_TOKEN', '')})
    with urllib.request.urlopen(зпр, timeout=180) as о:
        return о.read()[:200]


def читать(имя):
    п = os.path.join(ДРОП, имя)
    return list(csv.DictReader(
        io.StringIO(open(п, encoding='utf-8-sig', errors='replace').read()),
        delimiter=';'))


def main():
    файлы = sorted(n for n in os.listdir(ДРОП)
                   if n.upper().startswith('LICHNYE-NOMERA-')
                   and n.lower().endswith('.csv'))
    if not файлы:
        raise SystemExit('на дропе нет ни одного LICHNYE-NOMERA-*.csv')
    print('файлы сессий, которые нашлись на дропе:')
    for н in файлы:
        print(f'  {н}')
    нет = [f'{n}-Я СЕССИЯ' for n in ('1', '2', '3')
           if not any(f'-{n}-SESSIYA' in х.upper() for х in файлы)]
    if нет:
        print(f'  ЕЩЁ НЕ ВЫЛОЖИЛИ: {", ".join(нет)} — свод неполный, '
              'пересобрать после появления')

    db = EDB.EnrichDB()
    q = db.cx.execute
    тех = set(EDB.EnrichDB.TECH_ROLES)

    # мои собственные даты — из уже собранного файла с датами, чтобы логика
    # «что это за дата» жила В ОДНОМ месте (daty_u_lyudey.py), а не двоилась
    мои_даты = {}
    for r in читать('LYUDI-1-SESSIYA-s-datami.csv'):
        к = ((r.get('inn') or '').strip(), клч(r.get('fio')))
        if к[0] and r.get('data_sobytiya'):
            мои_даты[к] = (r['data_sobytiya'].strip(),
                           (r.get('chto_za_data') or '').strip())
    print(f'моих людей с проставленной датой: {len(мои_даты)}')

    # 1) собрать всё как есть, с пометкой чьё
    сырые = []
    порода = Counter()
    for н in файлы:
        чья = re.sub(r'^LICHNYE-NOMERA-|\.csv$', '', н, flags=re.I) or н
        for r in читать(н):
            инн = (r.get('inn') or '').strip()
            ц = д10(r.get('nomer_10cifr') or r.get('telefon') or '')
            if not (инн and ц):
                порода[f'{чья}: без ИНН или без номера'] += 1
                continue
            сырые.append({
                'inn': инн, 'ц': ц, 'чья': чья,
                'fio': (r.get('fio') or r.get('imya') or '').strip(),
                'dolzhnost': (r.get('dolzhnost') or '').strip(),
                'rol_avtora': (r.get('rol') or '').strip(),
                'istochnik': (r.get('istochnik') or '').strip(),
                'predpriyatie': (r.get('predpriyatie') or '').strip(),
                'tip_mashiny': (r.get('tip_mashiny') or '').strip(),
                'telefon_syroy': (r.get('telefon') or '').strip(),
                # Колонки, которые автор файла уже собрал сам. Переношу ДОСЛОВНО
                # и не схлопываю — прямая просьба третьей сессии, и она права:
                # «должность записана иначе» это не конфликт, который надо
                # решить в чью-то пользу, а два наблюдения одного факта.
                # ДАТА ФАКТА. Третья сессия уже носит её у себя, и если мой
                # свод её не перенесёт, поправка владельца («дату событий
                # помечайте везде, где известна») умрёт ровно на склейке —
                # тихо, как умирали проигравшие должности.
                'data_avt': ((r.get('data_fakta_samaya_svezhaya') or '').strip()
                             or (r.get('data_fakta') or '').strip()),
                'osnov_avt': (r.get('osnovanie') or '').strip(),
                'var_dolzh_avt': (r.get('varianty_dolzhnosti') or '').strip(),
                'var_imya_avt': (r.get('varianty_imeni') or '').strip(),
                'var_nomer_avt': (r.get('varianty_zapisi_nomera') or '').strip(),
                'rasx_avt': (r.get('rasxozhdeniya') or '').strip(),
            })
        print(f'  {н}: строк принято {sum(1 for s in сырые if s["чья"] == чья)}')
    for к, n in порода.items():
        print(f'  ОТБРОШЕНО {n}: {к}')

    # 2) проверка меры: личный номер начинается с 9. Если у кого-то в файле
    #    городские — это разная мера, и молча складывать её нельзя.
    негор = Counter()
    for с in сырые:
        if not с['ц'].startswith('9'):
            негор[с['чья']] += 1
    if негор:
        print()
        print('ВНИМАНИЕ, РАЗНАЯ МЕРА: строки, где номер НЕ мобильный (не 9xx):')
        for ч, n in негор.most_common():
            print(f'  {ч}: {n}')
        print('  такие строки помечены vid=городской и в счёт «личных» не идут')

    # 3) служебные линии на ОБЪЕДИНЁННОМ множестве
    раскид = defaultdict(set)
    for с in сырые:
        раскид[с['ц']].add(с['inn'])
    служебные = {ц for ц, s in раскид.items() if len(s) >= 3}
    снято_служ = sum(1 for с in сырые if с['ц'] in служебные)
    print()
    print(f'служебных линий (номер у 3+ разных ИНН, объединённо): '
          f'{len(служебные)}; строк под ними {снято_служ}')

    # 4) дедуп по (ИНН, десять цифр); выигрывает строка с техроли/длинной
    #    должностью, источники и авторы склеиваются — провенанс не теряем
    групп = defaultdict(list)
    for с in сырые:
        if с['ц'] in служебные:
            continue
        групп[(с['inn'], с['ц'])].append(с)

    # роль: сперва по должности своим каноном, при пустой должности — роль
    # автора файла. Основание хранится рядом, иначе через день не отличить
    # доказанное от принятого на веру.
    _АВТ = {'техническая': 'техконтакт', 'снабжение': 'снабжение/закупки',
            'руководство': 'директор', 'неясно': '', 'neясно': ''}

    def роль_и_основание(с):
        r = EDB.EnrichDB._canon_role(с['dolzhnost']) or ''
        if r:
            return r, 'должность'
        а = _АВТ.get(с['rol_avtora'].strip().lower(), '')
        return (а, 'роль автора') if а else ('', 'нет')

    строки = []
    for (инн, ц), гр in sorted(групп.items()):
        for с in гр:
            с['rol'], с['осн'] = роль_и_основание(с)
        гр.sort(key=lambda с: (с['rol'] in тех, с['осн'] == 'должность',
                               len(с['dolzhnost']), len(с['fio'])), reverse=True)
        поб = гр[0]
        авторы = ','.join(sorted({с['чья'] for с in гр}))
        ист = '; '.join(dict.fromkeys(
            [с['istochnik'] for с in гр if с['istochnik']]))[:120]
        фио = поб['fio'] or next((с['fio'] for с in гр if с['fio']), '')
        долж = поб['dolzhnost'] or next(
            (с['dolzhnost'] for с in гр if с['dolzhnost']), '')
        предпр = поб['predpriyatie'] or next(
            (с['predpriyatie'] for с in гр if с['predpriyatie']), '')
        тип = поб['tip_mashiny'] or next(
            (с['tip_mashiny'] for с in гр if с['tip_mashiny']), '')
        рольк, осн = поб['rol'], поб['осн']
        техл = рольк in тех or рольк == 'техконтакт'

        # ПРОИГРАВШИЕ ЗНАЧЕНИЯ СОХРАНЯЮТСЯ. Дыра, которую нашла у себя третья
        # сессия и тем же вопросом нашла у меня: заслон отбрасывает явно, а
        # склейка тихо — она не отвергает проигравшее значение, она его просто
        # не переносит, и снаружи это выглядит как согласие источников.
        # Считаем расхождение по НОРМАЛИЗОВАННОМУ виду (регистр и ё), иначе
        # «Менеджер по закупкам» и «менеджер по закупкам» разойдутся как два
        # факта, а хранить надо разные наблюдения, а не разный регистр.
        def _вар(поле, победа):
            видно = {клч(победа)}
            из_гр = []
            for с in гр:
                з = (с.get(поле) or '').strip()
                if з and клч(з) not in видно:
                    видно.add(клч(з))
                    из_гр.append(з)
            return из_гр

        вар_долж = _вар('dolzhnost', долж)
        вар_имя = _вар('fio', фио)
        # варианты, уже собранные АВТОРАМИ файлов, переносим дословно
        авт_долж = [с['var_dolzh_avt'] for с in гр if с['var_dolzh_avt']]
        авт_имя = [с['var_imya_avt'] for с in гр if с['var_imya_avt']]
        авт_ном = [с['var_nomer_avt'] for с in гр if с['var_nomer_avt']]
        авт_рас = [с['rasx_avt'] for с in гр if с['rasx_avt']]
        сырые_ном = _вар('telefon_syroy', '')
        расх = []
        if вар_долж:
            расх.append('должность')
        if вар_имя:
            расх.append('имя')
        if len(сырые_ном) > 1:
            расх.append('запись номера')

        # ЗДЕСЬ Я ОШИБСЯ И ЛОВЛЮ СЕБЯ ДО ОТЧЁТА. Колонку `osnovanie` третьей
        # сессии я принял за подпись к дате, а это основание РОЛИ: там стоит
        # «Контактное лицо по вопросам технического задания». В выгрузке
        # получилось «что за дата: Ответственный сотрудник» — бессмыслица,
        # которая выглядит как заполненное поле. Подпись к дате должна
        # говорить про ДАТУ, поэтому она фиксированная, а основание роли
        # уезжает в свою колонку и не притворяется чужой.
        осн_авт = next((с['osnov_avt'] for с in гр if с['osnov_avt']), '')
        дата = next((с['data_avt'] for с in гр if с['data_avt']), '')
        что_дата = ('дата факта из файла сессии-соседа (дата закупки '
                    'или документа, где человек назван)') if дата else ''
        if not дата:
            дата, что_дата = мои_даты.get((инн, клч(фио)), ('', ''))
        if not дата:
            что_дата = 'даты нет: источник её не публикует'

        строки.append([
            инн, предпр[:60], фио[:60], долж[:90], ц,
            'мобильный' if ц.startswith('9') else 'городской',
            рольк, осн, 'да' if техл else 'нет',
            поб['rol_avtora'], осн_авт[:90], тип, дата, что_дата, авторы, ист,
            'да' if len(гр) > 1 else 'нет',
            ' | '.join(dict.fromkeys(вар_долж + авт_долж))[:300],
            ' | '.join(dict.fromkeys(вар_имя + авт_имя))[:200],
            ' | '.join(dict.fromkeys(сырые_ном + авт_ном))[:200],
            ' + '.join(dict.fromkeys(расх + авт_рас))[:160]])

    # 5) сколько из этого УЖЕ есть у меня в базе — чтобы владелец видел
    #    прирост, а не общий объём
    мои = set()
    for инн, тел in q('SELECT inn, phone FROM phone_contacts').fetchall():
        ц = д10(тел)
        if ц:
            мои.add((инн, ц))
    for инн, тел in q("SELECT inn, COALESCE(phone,'') FROM people").fetchall():
        ц = д10(тел)
        if ц:
            мои.add((инн, ц))
    новых = sum(1 for с in строки if (с[0], с[4]) not in мои)

    путь = os.path.join(ПАПКА, ИМЯ)
    with open(путь, 'w', encoding='utf-8-sig', newline='') as ф:
        в = csv.writer(ф, delimiter=';')
        в.writerow(['inn', 'predpriyatie', 'fio', 'dolzhnost', 'nomer_10cifr',
                    'vid', 'rol_kanon', 'osnovanie_roli', 'tehLPR',
                    'rol_avtora', 'osnovanie_avtora', 'tip_mashiny',
                    'data_sobytiya', 'chto_za_data',
                    'ch_i_sessii', 'istochnik',
                    'byl_dubl', 'varianty_dolzhnosti', 'varianty_imeni',
                    'varianty_zapisi_nomera', 'rasxozhdeniya'])
        в.writerows(строки)
        ф.flush()
        os.fsync(ф.fileno())

    # 6) ЧИСЛА ПЕРЕЧИТЫВАНИЕМ ФАЙЛА. Главное число — по МОБИЛЬНЫМ: владелец
    #    просил телефоны людей, а прямой городской это телефон рабочего места.
    вс = моб = тл = мобтех = 0
    предпр, номера, мобномера = set(), set(), set()
    предпр_тех, предпр_мобтех = set(), set()
    роли, поавт, основания = Counter(), Counter(), Counter()
    with open(путь, encoding='utf-8-sig', newline='') as ф:
        for r in csv.DictReader(ф, delimiter=';'):
            вс += 1
            предпр.add(r['inn'])
            номера.add(r['nomer_10cifr'])
            поавт[r['ch_i_sessii']] += 1
            роли[r['rol_kanon'] or '(роль не установлена)'] += 1
            основания[r['osnovanie_roli']] += 1
            м = r['vid'] == 'мобильный'
            т = r['tehLPR'] == 'да'
            if м:
                моб += 1
                мобномера.add(r['nomer_10cifr'])
            if т:
                тл += 1
                предпр_тех.add(r['inn'])
            if м and т:
                мобтех += 1
                предпр_мобтех.add(r['inn'])

    print()
    print('=== СВОД, ЧИСЛА ПЕРЕЧИТЫВАНИЕМ ФАЙЛА ===')
    print(f'  строк после дедупа по (ИНН, десять цифр): {вс}')
    print(f'  разных номеров: {len(номера)}, предприятий: {len(предпр)}')
    print(f'  технических (техЛПР + техконтакт) всего: {тл} '
          f'на {len(предпр_тех)} предприятиях')
    print()
    print('  --- ГЛАВНОЕ ЧИСЛО, только МОБИЛЬНЫЕ ---')
    print(f'  мобильных строк: {моб}, разных мобильных номеров: '
          f'{len(мобномера)}')
    print(f'  ЛИЧНЫЙ МОБИЛЬНЫЙ ТЕХНИЧЕСКОГО ЧЕЛОВЕКА: {мобтех} '
          f'на {len(предпр_мобтех)} предприятиях')
    print(f'  (остальное — прямые городские, это телефон места, не человека)')
    print()
    print(f'  НЕТ в моей базе (прирост от соседей): {новых}')
    print('  на чём держится роль:')
    for о, n in основания.most_common():
        print(f'    {n:>5}  {о}')
    print('  роль по общему канону:')
    for р, n in роли.most_common(14):
        print(f'    {n:>5}  {р}')
    прочит = list(csv.DictReader(
        open(путь, encoding='utf-8-sig', newline=''), delimiter=';'))
    срасх = sum(1 for r in прочит if r['rasxozhdeniya'].strip())
    свар = Counter()
    for r in прочит:
        for к in ('varianty_dolzhnosti', 'varianty_imeni',
                  'varianty_zapisi_nomera'):
            if r[к].strip():
                свар[к] += 1
    сдат = Counter(r['chto_za_data'] or '(пусто)' for r in прочит)
    print('  что за дата у строки свода:')
