# -*- coding: utf-8 -*-
"""Сколько стоит письмо ПОСЛЕ удешевления — по свежим записям журнала.

Сравниваем со старой ценой из того же журнала: до 18.08 письмо писалось и
проверялось одной моделью, и в записи не было раздельного счёта. Свежие
записи несут цена_письма_$ и цена_проверок_$ — по ним видно не только
«дешевле», но и куда уходит остаток.
"""
import io
import json
from collections import Counter

Ж = r"C:\sender\_ops\gen-partiya-935.jsonl"
старые, новые = [], []
for s in io.open(Ж, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if z.get("этап") in ("итог", "отмена_попытки"):
        continue
    (новые if "цена_проверок_$" in z else старые).append(z)


def _свод(записи, имя):
    if not записи:
        print(f"{имя}: записей нет")
        return
    ок = [z for z in записи if z.get("ок")]
    ц = sorted(float(z.get("цена_$") or 0) for z in записи)
    всего = sum(ц)
    выз = sorted(int(z.get("вызовов") or 0) for z in записи)
    print(f"\n{имя}: попыток {len(записи)}, удачных {len(ок)}")
    print(f"  сумма ${всего:.2f}, на готовое письмо "
          f"${всего / max(1, len(ок)):.4f}")
    print(f"  цена попытки: медиана ${ц[len(ц)//2]:.4f}")
    print(f"  вызовов письма: медиана {выз[len(выз)//2]}")
    if "цена_проверок_$" in (записи[0] or {}):
        п = sum(float(z.get("цена_проверок_$") or 0) for z in записи)
        w = sum(float(z.get("цена_письма_$") or 0) for z in записи)
        пв = sorted(int(z.get("вызовов_проверок") or 0) for z in записи)
        print(f"  из них письмо ${w:.2f} / проверки ${п:.2f}")
        print(f"  вызовов проверок: медиана {пв[len(пв)//2]}")


_свод(старые, "БЫЛО (одна модель на всё)")
_свод(новые, "СТАЛО (проверки отдельной моделью, одна линза, 2 варианта)")
