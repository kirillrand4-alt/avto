sys.path.insert(0, r"C:\sender")

from sender.ai_letter import gate, load_facts, короткое_имя      # noqa: E402
from sender.ai_quota import build_ai_quota                       # noqa: E402
from sender.config import Config                                 # noqa: E402
from sender.store import Store                                   # noqa: E402

cfg = Config.load(r"C:\sender\sender.yaml")
store = Store(cfg.get("service.db_path", r"C:\sender\sender.db"))
q = build_ai_quota(store, cfg)
ФАКТЫ = {"kc": load_facts(division="kc"), "meyer": load_facts(division="meyer")}


def _без_чисел(т):
    """Гейт разрешает только числа из блока ФАКТЫ, а в паспорте они свои
    («авиационный привод 305-го г-та», «14 700 м²»). Вырезаем."""
    т = re.sub(r"\d[\d\s.,-]*", "", str(т))
    return re.sub(r"\s{2,}", " ", т).strip(" ,;-")


def _первый(v, сколько=2):
    """Первые элементы поля паспорта строкой."""
    if not v:
        return ""
    если_список = v if isinstance(v, list) else [x.strip() for x in
                                                 str(v).split(";")]
    куски = [_без_чисел(x) for x in если_список if str(x).strip()]
    куски = [к for к in куски if len(к) > 3][:сколько]
    return ", ".join(куски).lower()


def собрать(rec, паспорт, div="kc"):
    """Механическая сборка письма из паспорта. Без модели."""
    имя = короткое_имя(getattr(rec, "company_name", "")) or "вашей компании"
    продукция = _первый(паспорт.get("продукция"), 2)
    линии = _первый(паспорт.get("оборудование_линии"), 1)
    мощности = _первый(паспорт.get("мощности"), 1)
    сырьё = _первый(паспорт.get("сырьё"), 2)

    # НАБЛЮДЕНИЕ О НИХ — только факты с их же сайта.
    наблюдение = []
    if продукция:
        наблюдение.append(f"Смотрел, что выпускает «{имя}»: {продукция}.")
    if линии:
        наблюдение.append(f"На производстве {линии}.")
    elif мощности:
        наблюдение.append(f"Заявленные мощности - {мощности}.")
    первый = " ".join(наблюдение)

    # СВЯЗКА — техническая логика направления, без обещаний и цен.
    if div == "kc":
        связка = ("Такое производство обычно завязано на сжатом воздухе: "
                  "пневмоприводы, обдув, подача инструмента. Винтовая пара "
                  "со временем изнашивается - падает производительность и "
                  "растёт расход электроэнергии при той же выработке.")
        вопрос = ("Подскажите, актуален ли для вас вопрос обновления или "
                  "расширения компрессорного парка? Если да - под какие "
                  "участки?")
        предст = ("Я веду направление компрессорного оборудования в "
                  "Компрессор Центре - подбираю машины под конкретные "
                  "задачи производства.")
    else:
        связка = ("В таком производстве инородное включение, попавшее в "
                  "готовый продукт, обходится дорого. Рентген-инспекция видит их "
                  "внутри упакованной продукции, фотосепаратор снимает "
                  "посторонние фракции на потоке сырья.")
        вопрос = ("Подскажите, как сейчас закрыт контроль включений - на "
                  "сырье, на готовой продукции или нигде?")
        # Канон редактора Meyer проверяется буквально: gate ищет «меня зовут»
        # в теле. Формулировка не выбор стиля, а условие прохождения.
        предст = ("Меня зовут ИМЯ_ОТПРАВИТЕЛЯ, я веду направление "
                  "рентген-инспекции и фотосепарации в Meyer - подбираю "
                  "решения под конкретную линию.")
        if сырьё:
            связка = f"Работаете с сырьём: {сырьё}. " + связка

    переслать = ("Если этот вопрос ведёт кто-то другой, буду признателен, "
                 "если перешлёте письмо коллеге.")
    тело = "\n\n".join(x for x in ("Добрый день!", предст, первый, связка,
                                   вопрос, переслать, "С уважением,") if x)
    тема = (f"Вопрос по компрессорному парку в «{имя}»" if div == "kc"
            else f"Вопрос по контролю включений в «{имя}»")
    return тема, тело


ПОЛЯ = ("цитата", "продукция", "оборудование_линии", "сырьё", "масштаб",
        "мощности")
группы = store.recipient_groups().get("по_id") or {}
from collections import Counter
причины = Counter()
показано = 0
прошли = всего = 0
for rid, gr in sorted(группы.items()):
    if "Партия 935" not in gr:
        continue
    rec = store.get_recipient(rid)
    if not rec or not getattr(rec, "inn", None):
        continue
    try:
        п = q._site_facts(rec.inn) or {}
    except Exception:  # noqa: BLE001
        continue
    if sum(1 for к in ПОЛЯ if п.get(к)) < 4:
        continue
    try:
        req = q._request(rec)
        div = str(req.get("target_division") or "kc")
        div = div if div in ("kc", "meyer") else "kc"
    except Exception:  # noqa: BLE001
        div = "kc"
    тема, тело = собрать(rec, п, div)
    всего += 1
    try:
        плохо = gate(тема, тело, mode='GENERIC',
                    extra=dict(req.get('extra') or {},
                               company_name=getattr(rec, 'company_name', '')),
                    facts=ФАКТЫ[div], division=div)
    except Exception as e:  # noqa: BLE001
        плохо = ["гейт упал: %s" % str(e)[:90]]
    if not плохо:
        прошли += 1
    else:
        for _п in плохо:
            причины[str(_п).split(":")[0]] += 1
    if показано < 3:
        показано += 1
        print("\n" + "=" * 78)
        print("%s  [%s]" % (str(getattr(rec, "company_name", ""))[:52], div))
        print("ТЕМА: %s" % тема)
        print("-" * 78)
        print(тело)
        print("-" * 78)
        print("ГЕЙТ: %s" % ("ЧИСТО" if not плохо else "; ".join(
            str(x)[:150] for x in плохо)))
    if всего >= 40:
        break

print("\n\n=== ИТОГ ПО %d ПИСЬМАМ (ноль вызовов к модели) ===" % всего)
print("  прошли гейт без правок: %d (%.0f%%)"
      % (прошли, 100.0 * прошли / всего if всего else 0))
print("\n  за что бракует гейт:")
for к, н in причины.most_common(12):
    print("    %-58s %d" % (к[:58], н))
