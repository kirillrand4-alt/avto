# -*- coding: utf-8 -*-
"""Кэш и цена по ВСЕМ моделям шлюза — на настоящем промпте письма.

Владелец: «подорожание идёт на всех опусах и фабл доступных?». Отвечаем
замером, а не рассуждением. По три вызова на модель РАЗНЫМИ компаниями
(одинаковый промпт шлюз отдаёт из кэша ОТВЕТА за секунду — сравнивать по
нему нельзя), статика промпта одна и та же.

Смотрим на второй и третий вызов: если чтение растёт, а запись падает —
кэш работает. Если запись каждый раз полная, а чтение ноль — не работает,
и мы платим 1.25 ставки за услугу, которой не пользуемся.
"""
import sys
import time

sys.path.insert(0, r"C:\sender")
import gen_provider as GP                                        # noqa: E402
from sender.ai_letter import gen_prompt, load_facts              # noqa: E402

МОДЕЛИ = ["claude-opus-4-8", "claude-opus-4-7", "claude-opus-4-6",
          "claude-opus-5", "claude-fable-5", "claude-sonnet-5",
          "claude-sonnet-4-6", "claude-haiku-4-5"]
# Ставки шлюза, замеренные по его же журналу списаний (5707/5034 токенов ->
# $0.1558 = 5$/M вход, 25$/M выход). Соннет и хайку — по тарифу поменьше.
СТАВКИ = {"opus": (5.0, 25.0), "fable": (10.0, 50.0),
          "sonnet": (3.0, 15.0), "haiku": (1.0, 5.0)}


def ставка(м):
    for к, з in СТАВКИ.items():
        if к in м:
            return з
    return (5.0, 25.0)


ФИРМЫ = [("ООО «Первый Прокатный»", "прокат чёрных металлов", "24.10"),
         ("ООО «Второй Литейный»", "литьё чугуна", "24.51"),
         ("ООО «Третий Кузнечный»", "ковка и штамповка", "25.50")]
факты = load_facts(division="kc")

print(f"{'модель':<20} {'№':>2} {'вход':>7} {'чтение':>8} {'запись':>8} "
      f"{'выход':>7} {'сек':>4} {'$':>9}")
итоги = {}
for м in МОДЕЛИ:
    сумма = 0.0
    чт_всего = зап_всего = 0
    ошибка = None
    for i, (фирма, вид, оквэд) in enumerate(ФИРМЫ, 1):
        пол = {"mode": "GENERIC", "company_name": фирма, "activity": вид,
               "okved": оквэд, "extra": {}}
        сис, тело = GP.razrezat_promt(gen_prompt([пол], факты, "kc",
                                                 angle_base=i))
        т0 = time.time()
        try:
            msg = GP._raw_stream([{"role": "user", "content": тело}], м, 1200,
                                 thinking=False, effort="low", system=сис)
        except Exception as ex:                                  # noqa: BLE001
            ошибка = f"{type(ex).__name__}: {str(ex)[:70]}"
            print(f"{м:<20} {i:>2} — {ошибка}")
            break
        u = getattr(msg, "usage", None)
        вх = int(getattr(u, "input_tokens", 0) or 0)
        чт = int(getattr(u, "cache_read_input_tokens", 0) or 0)
        зап = int(getattr(u, "cache_creation_input_tokens", 0) or 0)
        вых = int(getattr(u, "output_tokens", 0) or 0)
        вх_ст, вых_ст = ставка(м)
        ц = ((вх + 1.25 * зап + 0.10 * чт) / 1e6 * вх_ст
             + вых / 1e6 * вых_ст)
        сумма += ц
        чт_всего += чт
        зап_всего += зап
        print(f"{м:<20} {i:>2} {вх:>7} {чт:>8} {зап:>8} {вых:>7} "
              f"{time.time()-т0:>4.0f} {ц:>9.4f}")
    if not ошибка:
        итоги[м] = (сумма / len(ФИРМЫ), чт_всего, зап_всего)

print("\n== ИТОГ: средняя цена вызова и работает ли кэш ==")
print(f"{'модель':<20} {'$/вызов':>9} {'чтение':>10} {'запись':>10} "
      f"{'чт/зап':>7}  вывод")
for м, (ц, чт, зап) in sorted(итоги.items(), key=lambda t: t[1][0]):
    о = чт / max(1, зап)
    вывод = ("кэш РАБОТАЕТ" if о > 0.5 else
             "кэш не читается — платим 1.25 за запись впустую")
    print(f"{м:<20} {ц:>9.4f} {чт:>10,} {зап:>10,} {о:>7.2f}  {вывод}")
