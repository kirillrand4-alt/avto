# -*- coding: utf-8 -*-
"""Только цифры: во что обошлось письмо на соннете против опуса.

Отдельно от показа текстов: раннер отдаёт ХВОСТ вывода, и шапка со сводкой
тонула под письмами.
"""
import io
import json
import os
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
строки = []
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    if z.get("этап") == "сгенерировано" or z.get("цена_$") is not None:
        строки.append(z)


def свод(отбор, имя):
    if not отбор:
        print(f"\n== {имя}: нет данных ==")
        return None
    ц = Counter()
    годных = 0
    for z in отбор:
        ц["цена"] += float(z.get("цена_$") or 0)
        ц["письмо"] += float(z.get("цена_письма_$") or 0)
        ц["проверки"] += float(z.get("цена_проверок_$") or 0)
        ц["зап"] += int(z.get("вход_кэш_запись") or 0)
        ц["чт"] += int(z.get("вход_кэш_чтение") or 0)
        ц["вызовов"] += int(z.get("вызовов") or 0)
        if z.get("тело"):
            годных += 1
    n = len(отбор)
    print(f"\n== {имя} ==")
    print(f"  попыток {n}, годных {годных} "
          f"({годных/n*100:.0f}%)")
    print(f"  ЗА ПОПЫТКУ:  ${ц['цена']/n:.4f}  "
          f"(письмо ${ц['письмо']/n:.4f} + проверки ${ц['проверки']/n:.4f})")
    if годных:
        print(f"  ЗА ГОДНОЕ ПИСЬМО: ${ц['цена']/годных:.4f}")
    print(f"  кэш на попытку: записано {ц['зап']/n:,.0f}, "
          f"прочитано {ц['чт']/n:,.0f}  "
          f"(чтение/запись {ц['чт']/max(1,ц['зап']):.2f})")
    print(f"  вызовов на попытку: {ц['вызовов']/n:.1f}")
    return (ц["цена"]/max(1, годных)) if годных else None


сон = [z for z in строки if "sonnet" in str(z.get("модель") or "")]
_все_опус = [z for z in строки if "opus" in str(z.get("модель") or "")]
a = свод(сон, f"СОННЕТ (все {len(сон)} попыток)")
b = свод(_все_опус[-100:], "ОПУС (последние 100 попыток)")
# ВСЯ ПАРТИЯ ТОЖЕ. Последняя сотня — это свежие дорогие прогоны, и цену
# всей партии по ней считать нельзя: разница выходила втрое.
c = свод(_все_опус, f"ОПУС (вся партия, {len(_все_опус)} попыток)")
if a and b:
    print(f"\n>>> ЗА ГОДНОЕ ПИСЬМО: соннет ${a:.4f} против опуса ${b:.4f} "
          f"— соннет {'дешевле' if a < b else 'ДОРОЖЕ'} "
          f"в {max(a,b)/min(a,b):.1f} раза")
