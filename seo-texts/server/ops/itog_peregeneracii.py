# -*- coding: utf-8 -*-
"""Итог перегенерации брака: сколько переписано, сколько отказано и почему.

Считаем по двум durable-журналам на сервере, без единого вызова модели:

  rezenzii-pisem.jsonl       - вердикты рецензента, ПОСЛЕДНИЙ на письмо
                               считается текущим (перечитывание дописывает
                               строку в конец, времени в записи нет);
  peregeneraciya-braka.jsonl - попытки перегенерации, последняя на письмо.

Пул брака берём как «когда-либо получил не годно»: после перечитывания
переписанные письма меняют вердикт, и по текущему вердикту исходный пул уже
не собрать.

Причины отказа печатаем поимённо из fails: «генерация забракована» само по
себе не говорит, кто забраковал - механический гейт или верификатор с
линзой.
"""
import io
import json
import os
from collections import Counter

РЕЦ = r"C:\sender\_ops\rezenzii-pisem.jsonl"
ПЕР = r"C:\sender\_ops\peregeneraciya-braka.jsonl"

вердикт = {}          # id -> последний вердикт рецензента
был_брак = set()
for s in io.open(РЕЦ, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(s)
        i = int(z["id"])
    except Exception:                                            # noqa: BLE001
        continue
    v = str(z.get("verdict") or "")
    вердикт[i] = v
    if v == "не годно":
        был_брак.add(i)

попытка = {}          # id -> последняя запись перегенерации
попыток = Counter()
if os.path.exists(ПЕР):
    for s in io.open(ПЕР, encoding="utf-8", errors="replace"):
        try:
            z = json.loads(s)
            i = int(z["id"])
        except Exception:                                        # noqa: BLE001
            continue
        попыток[i] += 1
        # успех держим: письмо переписано - повторные строки его не отменяют
        if попытка.get(i, {}).get("ок") and not z.get("ок"):
            continue
        попытка[i] = z

переписано = {i for i in был_брак if (попытка.get(i) or {}).get("ок")}
отказ = {i for i in был_брак if i in попытка and i not in переписано}
не_бралось = был_брак - set(попытка)

print(f"забраковано рецензентом всего: {len(был_брак)}")
print(f"  переписано:            {len(переписано)}")
print(f"  отказ перегенерации:   {len(отказ)}")
print(f"  не бралось (не pending/письма нет): {len(не_бралось)}")
print(f"  попыток на письмо в среднем: "
      f"{sum(попыток.values()) / max(1, len(попыток)):.2f}")

причины = Counter()
for i in отказ:
    z = попытка[i]
    f_ = z.get("fails") or []
    if f_:
        for x in f_[:3]:
            причины[str(x)[:74]] += 1
    else:
        причины[str(z.get("почему"))[:74]] += 1
if причины:
    print("\nпочему отказ (поимённо, у письма бывает несколько причин):")
    for п, n in причины.most_common(15):
        print(f"  {n:>4}  {п}")

# Перечитал ли рецензент переписанные и что сказал.
после = Counter(вердикт.get(i, "нет вердикта") for i in переписано)
print("\nтекущий вердикт рецензента у переписанных:")
for v, n in после.most_common():
    print(f"  {n:>4}  {v}")
print("  («не годно» здесь = ещё НЕ перечитано после правки: "
      "перечитывание запускается ops/rezenzent_pisem.py --перечитать-брак)")
