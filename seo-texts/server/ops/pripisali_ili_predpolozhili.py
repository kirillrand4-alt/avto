# -*- coding: utf-8 -*-
"""Письмо ПРИПИСАЛО процесс получателю или ПРЕДПОЛОЖИЛО его как типовой?

Разница решает, кто виноват. Карточка несёт одну строку — ЧТО компания
выпускает. Тела письма в карточке нет: «как это делают» модель
достраивает сама. Достроить можно двумя способами:

  ПРИПИСАЛ  — «у вас линии окраски и сборки панелей», «у вас детали для
      авиационной промышленности». Это утверждение о ЭТОЙ компании, и если
      сайт его не подтверждает — выдумка;
  ПРЕДПОЛОЖИЛ — «на производствах металлоконструкций сжатый воздух обычно
      нужен для резки и окраски». Это утверждение об ОТРАСЛИ, оговорённое
      словом «обычно/как правило/чаще всего». Придираться к нему как к факту
      о компании — перебор рецензента.

Считаем по телу письма, а не по претензии: ищем прямые обороты о получателе
рядом с названием процесса.

    python zapusk_svoego_skripta.py ops/pripisali_ili_predpolozhili.py
"""
import io
import json
import re
import sys
from collections import Counter

sys.path.insert(0, r"C:\sender")
from sender.config import Config                                 # noqa: E402
from sender.store import Store                                   # noqa: E402

cfg = Config.load(r"C:\sender\sender.yaml")
store = Store(cfg.get("service.db_path", r"C:\sender\sender.db"))

ПРОЦЕСС = (r"покрас|окраск|распылен|плазменн|лазерн|резк|гибк|сварк|"
           r"дробеструй|пескоструй|пневмоинструмент|компрессорн|прессован|"
           r"штамп|литьё|литье|термообработ|сборк|фрезер|токарн|шлифов|"
           r"опрессовк|продувк|линии|цех|станк|участк")
ПРЯМО = re.compile(
    r"(?i)(у вас\b|ваши\b|ваша\b|ваш\b|в ваших\b|вы (?:выпускаете|производите|"
    r"делаете|используете)|на вашем|на ваших)[^.!?]{0,120}(" + ПРОЦЕСС + ")")
ОГОВОРКА = re.compile(
    r"(?i)(обычно|как правило|чаще всего|нередко|часто|típ|типов|"
    r"в таких производствах|на таких производствах|на производствах)")

последний = {}
for s in io.open(r"C:\sender\_ops\rezenzii-pisem.jsonl", encoding="utf-8",
                 errors="replace"):
    try:
        z = json.loads(s)
        последний[int(z["id"])] = z
    except Exception:                                            # noqa: BLE001
        continue
плохие = [i for i, z in последний.items()
          if str(z.get("verdict") or "") == "не годно"]
годные = [i for i, z in последний.items()
          if str(z.get("verdict") or "") == "годно"]


def _разбор(ids, имя):
    ключи = ",".join("?" * len(ids))
    with store._lock:
        ряд = store._conn.execute(
            f"SELECT id, body FROM confirm_reviews WHERE id IN ({ключи})",
            ids).fetchall()
    c = Counter()
    примеры = {}
    for cid, тело in ряд:
        т = re.sub(r"<[^>]+>", " ", тело or "")
        прямо = ПРЯМО.search(т)
        if прямо:
            k = "ПРИПИСАЛ процесс получателю"
            примеры.setdefault(k, (cid, прямо.group(0)[:120]))
        elif ОГОВОРКА.search(т):
            k = "предположил как типовое для отрасли (с оговоркой)"
            примеры.setdefault(k, (cid, ОГОВОРКА.search(т).group(0)))
        else:
            k = "ни того, ни другого"
            примеры.setdefault(k, (cid, т[:100]))
        c[k] += 1
    print(f"\n{имя} (всего {sum(c.values())}):")
    for k, n in c.most_common():
        cid, ц = примеры[k]
        print(f"  {n:>4}  {k}")
        print(f"        напр. #{cid}: «{ц}»")


_разбор(плохие, "«не годно»")
_разбор(годные, "«годно» — для сравнения")
