"""Из чего состоит статическая часть промпта и что там лишнее.

Владелец: «разбери + это может же влиять на точность ответа». Оба довода
верны. По деньгам: за статику платим по 1.25 ставки на каждом вызове, кэш
на опусе не читается. По качеству: чем длиннее контекст, тем слабее модель
держит инструкции - лишние тридцать тысяч знаков не бесплатны и здесь.

Считаем по файлу, без единого обращения к модели.
"""
import sys

sys.path.insert(0, r"C:\sender")
import gen_provider as GP                                        # noqa: E402
from sender import ai_letter as AI                               # noqa: E402


def _токенов(s):
    """Грубая оценка: у кириллицы ~1.8 знака на токен по замеру шлюза
    (21 327 знаков статики КЦ = 11 830 токенов записи)."""
    return int(len(s) / 1.8)


ПОЛ = {"mode": "GENERIC", "company_name": "ООО «Тест»",
       "activity": "мехобработка", "okved": "25.62", "extra": {}}

for div in ("kc", "meyer"):
    факты = AI.load_facts(division=div)
    п = AI.gen_prompt([ПОЛ], факты, div, angle_base=0)
    с, т = GP.razrezat_promt(п)
    с = с or ""
    print(f"\n===== {div}: статика {len(с)} знаков ≈ {_токенов(с)} токенов "
          f"| переменная {len(т)} знаков =====")

    куски = []
    правила = AI.RULES_BY_DIVISION[div]
    куски.append(("правила письма (RULES)", len(правила)))
    try:
        фб = AI.facts_block(факты, div)
        куски.append(("блок ФАКТЫ (бренды, модели, кейсы)", len(фб)))
    except Exception as ex:                                      # noqa: BLE001
        фб = ""
        print("  facts_block не собрался:", str(ex)[:80])
    голова = AI._GEN_HEAD.get(div, "")
    куски.append(("шапка задания", len(голова)))
    прочее = len(с) - sum(n for _, n in куски)
    куски.append(("прочее (склейка, формат ответа)", прочее))
    for имя, n in sorted(куски, key=lambda x: -x[1]):
        print(f"  {имя:<40} {n:>7} знаков  {100.0 * n / max(1, len(с)):>4.0f}%"
              f"  ≈{_токенов(str(' ' * n)):>6} токенов")

    # Сколько в фактах брендов и насколько они нужны одному письму
    if isinstance(факты, dict):
        бренды = факты.get("brands") or факты.get("бренды") or {}
        if isinstance(бренды, dict):
            print(f"  брендов в блоке фактов: {len(бренды)}")
            for имя in list(бренды)[:12]:
                кусок = str(бренды[имя])
                print(f"    {str(имя)[:28]:<30} {len(кусок):>6} знаков")
