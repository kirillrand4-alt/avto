# -*- coding: utf-8 -*-
"""Сколько денег съела перегенерация целиком - по счётчику шлюза.

Журнал замеров: каждая строка - показание total_usage и число строк в
журнале перегенерации на тот момент. Разница между соседними замерами и
есть расход за отрезок; писем за отрезок - разница вторых чисел.
"""
import io
import json

Ж = r"C:\sender\_ops\schyotchik-shlyuza.jsonl"
строки = []
for s in io.open(Ж, encoding="utf-8", errors="replace"):
    try:
        строки.append(json.loads(s))
    except Exception:                                            # noqa: BLE001
        pass
print(f"{'метка':<30} {'время':<20} {'расход,$':>9} {'писем':>6} {'на письмо':>10}")
всего_д = всего_п = 0.0
for a, b in zip(строки, строки[1:]):
    д = (b["total_usage"] - a["total_usage"]) / 100.0
    п = b.get("писем_в_журнале", 0) - a.get("писем_в_журнале", 0)
    всего_д += д
    всего_п += п
    # Отрезок, в котором писем много, а денег почти нет - это не дешёвая
    # генерация, а отсутствие замера: журнал перегенерации к первому
    # показанию счётчика уже был полон. Такие отрезки в среднее не берём.
    без_замера = п > 0 and д / п < 0.01
    на = "замера не было" if без_замера else (f"${д / п:.4f}" if п else "-")
    if без_замера:
        п = 0
    print(f"{str(b.get('метка'))[:29]:<30} {str(b.get('ts'))[11:19]:<20} "
          f"{д:>9.2f} {п:>6} {на:>10}")
print(f"\nвсего за отрезки: ${всего_д:.2f}, попыток {int(всего_п)}")
if всего_п:
    print(f"в среднем на попытку: ${всего_д / всего_п:.4f}")
