          "Аудиты торговых сетей и требования ХАССП предполагают "
          "документированный контроль включений на всех этапах - от приёмки "
          "сырья до отгрузки. «Успешные технологии питания» выпускают су-вид "
          "полуфабрикаты, выпечку и кондитерские изделия, поэтому обращаюсь "
          "по теме такого контроля.\n\n"
          "Для готовой упакованной продукции применяется рентген-инспекция: "
          "оборудование выявляет металл, стекло, керамику, камень и прочие "
          "плотные включения.\n\n"
          "Подскажите, актуальна ли для предприятия задача контроля "
          "включений в готовой продукции?\n\n"
