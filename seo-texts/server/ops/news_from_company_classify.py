"""Классификация статей пачки newsco через провайдерский API (claude-fable-5).

Работает В ПЕСОЧНИЦЕ: PROVIDER_API_KEY есть локально, а раннер — узкое место,
им пользуются другие агенты. Результат сразу выкладывается на дроп (песочница
при рестарте откатывается, дроп — нет).

Вход:  newsco_batch_<тег>.json.gz  (скачан с дропа)
Выход: newsco_signals_<тег>.json  {'сигналы': [...], 'люди': [...], 'метрики': {}}
Кэш:   newsco_cache_<тег>.jsonl — по url, чтобы не платить дважды при рестарте.
"""
import gzip
import hashlib
import json
import os
import re
import sys
import threading
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor

ТЕГ = sys.argv[1] if len(sys.argv) > 1 else 'b0'
ДИР = os.path.dirname(os.path.abspath(__file__))
ВХОД = os.path.join(ДИР, 'newsco_batch_%s.json.gz' % ТЕГ)
ВЫХОД = os.path.join(ДИР, 'newsco_signals_%s.json' % ТЕГ)
КЭШ = os.path.join(ДИР, 'newsco_cache_%s.jsonl' % ТЕГ)
ПОТОКОВ = int(os.environ.get('NEWSCO_WORKERS', '10'))

_МОДЕЛЬ = 'claude-fable-5'
_замок = threading.Lock()
_стат = {'вызовов': 0, 'сбоев': 0, 'из_кэша': 0}


def провайдер(промпт, попыток=4):
    """Стриминг обязателен (Cloudflare рвёт молчащие соединения). Заголовки — как
    в боевом клиенте: WAF шлюза отклоняет дефолтные заголовки SDK."""
    key = os.environ.get('PROVIDER_API_KEY', '')
    base = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
    тело = json.dumps({'model': _МОДЕЛЬ, 'max_tokens': 2000, 'stream': True,
                       'messages': [{'role': 'user', 'content': промпт}]},
                      ensure_ascii=False).encode('utf-8')
    посл = ''
    for п in range(попыток):
        if п:
            time.sleep(4 * п)
        try:
            req = urllib.request.Request(
                base + '/v1/messages', data=тело, method='POST',
                headers={'x-api-key': key, 'anthropic-version': '2023-06-01',
                         'content-type': 'application/json',
                         'accept': 'text/event-stream', 'User-Agent': 'curl/8.5.0'})
            куски = []
            with urllib.request.urlopen(req, timeout=240) as r:
                for сырая in r:
                    стр = сырая.decode('utf-8', 'replace').strip()
                    if not стр.startswith('data:'):
                        continue
                    try:
                        ev = json.loads(стр[5:].strip())
                    except Exception:  # noqa: BLE001
                        continue
                    if ev.get('type') == 'content_block_delta':
                        куски.append((ev.get('delta') or {}).get('text', ''))
            т = ''.join(куски)
            if т.strip():
                with _замок:
                    _стат['вызовов'] += 1
                return т
            посл = 'пустой ответ'
        except Exception as ex:  # noqa: BLE001
            посл = '%s: %s' % (type(ex).__name__, str(ex)[:90])
    with _замок:
        _стат['сбоев'] += 1
    sys.stderr.write('провайдер сдался: %s\n' % посл)
    return ''


