def домен(u):
    m = re.match(r'https?://([^/]+)', (u or '').strip(), re.I)
    # НЕ lstrip: он снимает НАБОР символов «w» и «.», а не префикс —
    # «water-service.ru» становился «ater-service.ru», «www.wwww.ru» → «ru».
    # Здесь на домене строится рубеж привязки, то есть битый домен = либо
    # пропущенная своя страница, либо принятая чужая.
    d = re.sub(r'^www\.', '', (m.group(1) if m else (u or '')).lower())
    return d.split(':')[0].strip('/')


_ОПФ_СЛОВА = {
    'акционерное', 'общество', 'ограниченной', 'ответственностью', 'публичное',
    'закрытое', 'открытое', 'непубличное', 'предприятие', 'унитарное',
    'федеральное', 'государственное', 'муниципальное', 'бюджетное', 'краевое',
    'областное', 'учреждение', 'здравоохранения', 'компания', 'компании',
    'завод', 'завода', 'фирма', 'группа', 'холдинг', 'производственный',
    'производственная', 'торговый', 'торговая', 'научно', 'коммерческая'}


def токены(имя):
    """Содержательные слова названия. ОПФ и родовые слова выброшены: без этого
    у «АКЦИОНЕРНОЕ ОБЩЕСТВО "ВАД"» доказательством становилось присутствие слов
    «акционерное общество» на странице — то есть ЛЮБОЙ деловой текст."""
    return [t for t in re.findall(r'[а-яёa-z0-9]+', (имя or '').lower())
            if len(t) >= 4 and t not in _ОПФ_СЛОВА]


def привязка(текст, инн, ядро, полное, сайт, url):
    """ДОКАЗАТЕЛЬСТВО принадлежности статьи компании. Порядок по силе:
    ИНН на странице -> собственный домен -> все содержательные слова полного
    имени -> все слова ядра. Аббревиатуры короче 4 букв («ТСМ», «ДИМ», «ВАД»)
    доказать словами НЕЛЬЗЯ — им нужен домен или ИНН, иначе честный ответ
    «не знаю» (правило из разбора hh-ошибки: кусок названия не доказывает ничего).
    """
    t = (текст or '').lower()
    if инн and инн in t:
        return 'инн'
    if свой_домен(url, сайт):
        return 'свой_домен'
    if not t:
        return 'нет_текста'
    тп = токены(полное)
    if тп and all(w[:6] in t for w in тп):
        return 'полное_имя'
    тя = токены(ядро)
    if тя and all(w[:5] in t for w in тя):
        return 'ядро'
    return 'аббревиатура' if not тя else 'нет'


def свой_домен(url_статьи, сайт_компании):
    """Статья на СОБСТВЕННОМ сайте компании — доказательство сильнее имени.

    Ради этого правила: у «ТСМ», «ДИМ», «ВАД» ядро имени короче 4 символов,
    токенов для сверки нет вовсе, и 13 настоящих сигналов (в том числе с
    tsm.ru и aodim.ru — сайтов САМИХ компаний) уходили в отсев как
    «непривязанные». Точный домен стоит в одном ряду с ИНН на странице.
    """
    д = домен(сайт_компании)
    if not д or len(д) < 5 or '.' not in д:
        return False
    a = домен(url_статьи)
    return a == д or a.endswith('.' + д)


# должности, которые НЕ означают работу в компании: чиновники, главы районов,
# сотрудники агентств развития. Модель их включала вопреки запрету в промпте
# (АО «Эссен Продакшн» получило «главу Елабужского района» и «руководителя
# Агентства инвестиционного развития»).
_ЧУЖОЙ_ПОСТ = re.compile(
    r'\bглава\b|администрац|губернатор|\bмэр\b|министр|депутат|префект|'
    r'агентств|правительств|ведомств|прокур|полпред|сенатор|'
    r'председател\w+ (?:правительств|комитет|дум)', re.I)


def ключ(url):
    return hashlib.sha1((url or '').encode('utf-8')).hexdigest()[:16]


def загрузить_кэш():
    к = {}
    if os.path.exists(КЭШ):
        for line in open(КЭШ, encoding='utf-8'):
            try:
                r = json.loads(line)
                к[r['k']] = r['v']
            except Exception:  # noqa: BLE001
                continue
    return к


def main():
    with gzip.open(ВХОД, 'rb') as f:
        пачка = json.loads(f.read().decode('utf-8'))
    кэш = загрузить_кэш()
    кф = open(КЭШ, 'a', encoding='utf-8')
    задачи = []
    for c in пачка:
        for a in c.get('статьи', []):
            задачи.append((c, a))
    sys.stderr.write('компаний %d, статей %d, в кэше %d\n'
                     % (len(пачка), len(задачи), len(кэш)))

    def одна(t):
        c, a = t
        k = ключ(a['url'])
        if k in кэш:
            with _замок:
                _стат['из_кэша'] += 1
            return c, a, кэш[k]
        текст = (a.get('текст') or '')[:7000]
        if len(текст) < 200:
            текст = ((a.get('title') or '') + '. ' + (a.get('passage') or ''))[:1500]
        p = ПРОМПТ.format(krat=c.get('krat', ''), poln=c.get('poln', ''),
                          inn=c.get('inn', ''), region=c.get('регион', ''),
                          city=c.get('город', ''), okved=c.get('оквэд', ''),
                          url=a.get('url', ''), дата=a.get('дата') or 'не найдена',
                          текст=текст)
        ответ = провайдер(p)
        m = re.search(r'\{.*\}', ответ or '', re.S)
        v = {}
        if m:
            try:
                v = json.loads(m.group(0))
            except Exception:  # noqa: BLE001
                v = {'parse_error': (ответ or '')[:200]}
        with _замок:
            кф.write(json.dumps({'k': k, 'v': v}, ensure_ascii=False) + '\n')
            кф.flush()
            os.fsync(кф.fileno())
            кэш[k] = v
        return c, a, v

    рез = []
    with ThreadPoolExecutor(max_workers=ПОТОКОВ) as ex:
        for r in ex.map(одна, задачи):
            рез.append(r)
    кф.close()

    сигналы, люди = [], []
    м = {'статей': len(задачи), 'про_компанию': 0, 'не_про_компанию': 0,
         'неясно': 0, 'капекс': 0, 'наше_оборудование': 0, 'людей': 0,
         'без_ответа': 0, 'отсев_привязка': 0, 'отсев_не_капекс': 0,
         'привязка': {}, 'капекс_по_мнению_модели': 0}
    комп_с_новостью, комп_с_капексом = set(), set()
    for c, a, v in рез:
        if not v or v.get('parse_error'):
            м['без_ответа'] += 1
            continue
        комп_с_новостью.add(c['inn'])
        про = str(v.get('about_company') or '').lower()
        прив = (a.get('привязка') or {}).get('уровень', '')
        # ДОКАЗАТЕЛЬСТВО: модель говорит yes И механическая привязка не «нет».
        # unclear принимаем только когда на странице найден ИНН или ПОЛНОЕ имя.
        прив = привязка((a.get('текст') or '') + ' ' + (a.get('title') or '')
                        + ' ' + (a.get('passage') or ''), c.get('inn'),
                        c.get('имя'), c.get('poln') or c.get('krat'),
                        c.get('сайт') or '', a['url'])
        принято = (про == 'yes' and прив in ('инн', 'свой_домен', 'полное_имя', 'ядро')) or \
                  (про == 'unclear' and прив in ('инн', 'свой_домен', 'полное_имя'))
        if про == 'yes':
            м['про_компанию'] += 1
        elif про == 'no':
            м['не_про_компанию'] += 1
        else:
            м['неясно'] += 1
        м['привязка'][прив] = м['привязка'].get(прив, 0) + 1
        if v.get('is_capex'):
            м['капекс_по_мнению_модели'] += 1
        if not принято:
            м['отсев_привязка'] += 1
            continue
        if not v.get('is_capex'):
            м['отсев_не_капекс'] += 1
            continue
        м['капекс'] += 1
        комп_с_капексом.add(c['inn'])
        дата = a.get('дата') or (v.get('date') or '')
        возр = a.get('возраст_мес')
        if возр is None and дата:
            try:
                import datetime as _dt
                возр = round((_dt.date.today() - _dt.date(*[int(z) for z in дата.split('-')[:3]])).days / 30.44, 1)
            except Exception:  # noqa: BLE001
                возр = None
        hot = int(v.get('hotness') or 0)
        # НЕ выдавать устаревшее за свежее: модель оценивает масштаб события, а
        # не его возраст, и ставила 4 новости 2018 года. Потолок по возрасту.
        if возр is None:
            hot = min(hot, 3)
        elif возр > 36:
            hot = min(hot, 1)
        elif возр > 24:
            hot = min(hot, 2)
        elif возр > 12:
            hot = min(hot, 3)
        if v.get('equipment'):
            м['наше_оборудование'] += 1
        сигналы.append({'inn': c['inn'], 'name': c.get('krat') or c.get('poln'),
                        'okved': c.get('оквэд'), 'region': c.get('регион'),
                        'выручка': c.get('выручка'),
                        'url': a['url'], 'title': a.get('title'),
                        'date': дата, 'возраст_мес': возр,
                        'event_type': v.get('event_type'), 'what': v.get('what'),
                        'sum': v.get('sum'), 'hotness': hot,
                        'hotness_модели': v.get('hotness'),
                        'equipment': v.get('equipment') or '',
                        'about': про, 'why': v.get('why'),
                        'привязка': прив})
        for p in (v.get('people') or []):
            if _ЧУЖОЙ_ПОСТ.search(p.get('post') or ''):
                м['людей_чужих'] = м.get('людей_чужих', 0) + 1
                continue
            if (p.get('person') or '').strip() and (p.get('post') or '').strip():
                люди.append({'inn': c['inn'], 'person': p['person'].strip(),
                             'post': p['post'].strip(),
                             'quote': (p.get('quote') or '')[:200],
                             'url': a['url']})
                м['людей'] += 1
    м['компаний_в_пачке'] = len(пачка)
    м['компаний_с_новостью'] = len(комп_с_новостью)
    м['компаний_с_капексом'] = len(комп_с_капексом)
    м.update(_стат)
    out = {'тег': ТЕГ, 'сигналы': сигналы, 'люди': люди, 'метрики': м}
    with open(ВЫХОД, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False)
        f.flush()
        os.fsync(f.fileno())
    print(json.dumps(м, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
