# -*- coding: utf-8 -*-
"""ai_letter (гейт «покупатель Руспрома»): хозяйство с зерном — ВСЕГДА покупатель
фотосепаратора (владелец 22.10: «зерно сортировать = фотосепаратор», «это же
напрямую подходит», «всех»). Было (13.10): только при своей очистке/сушилке/
складе/лаборатории или от 1000 га, иначе «НЕ покупатель» — гейт отбрасывал
хозяйства из деклараций ФСА, у которых паспорта нет. Правка по якорю, бэкап,
py_compile, откат. --otkat — вернуть из последнего бэкапа этой правки."""
import glob
import io
import py_compile
import shutil
import sys
import time

ПУТЬ = r"C:\sender\sender\ai_letter.py"
БЫЛО = ("     бобовыми или масличными в паспорте, если у них есть свой\n"
        "     зерноочистительный комплекс, сушилка, зерносклад, лаборатория или земли от\n"
        "     тысячи гектаров. Хозяйство без этого - НЕ покупатель.")
СТАЛО = ("     бобовыми или масличными в паспорте ИЛИ в декларациях ФСА - ВСЕГДА\n"
         "     покупатель (владелец 22.10: «зерно сортировать = фотосепаратор»). Своя\n"
         "     очистка, сушилка, склад или площадь земли - НЕ условие.")
if "--otkat" in sys.argv:
    б = sorted(glob.glob(ПУТЬ + ".bak-zerno-*"))
    if not б:
        sys.exit("нет бэкапа")
    shutil.copy2(б[-1], ПУТЬ)
    print("=== ЗЕРНО: ОТКАТ из %s ===" % б[-1])
    sys.exit(0)
т = io.open(ПУТЬ, encoding="utf-8").read()
if "зерно сортировать = фотосепаратор" in т:
    print("=== ЗЕРНО: УЖЕ БЫЛО ===")
    sys.exit(0)
if т.count(БЫЛО) != 1:
    i = т.find("тысячи гектаров")
    print("якорь найден %d раз; вокруг: %r" % (т.count(БЫЛО), т[max(0, i - 300):i + 120]))
    print("=== ЗЕРНО: НЕ ПРИМЕНЕНО ===")
    sys.exit(0)
бэкап = ПУТЬ + ".bak-zerno-%d" % int(time.time())
shutil.copy2(ПУТЬ, бэкап)
io.open(ПУТЬ, "w", encoding="utf-8").write(т.replace(БЫЛО, СТАЛО))
try:
    py_compile.compile(ПУТЬ, doraise=True)
except Exception as е:  # noqa: BLE001
    shutil.copy2(бэкап, ПУТЬ)
    print("сбой, откат: %s" % е)
    sys.exit(0)
print("бэкап:", бэкап)
print("=== ЗЕРНО: ПРИМЕНЕНО ===")
