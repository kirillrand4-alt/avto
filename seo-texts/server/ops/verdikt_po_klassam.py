# -*- coding: utf-8 -*-
"""Доля «покупателей» по классам ОКВЭД — на вердиктах, уже вынесенных гейтом.

Это не рассуждение, а замер: берём 13.5к готовых вердиктов, подтягиваем
ОКВЭД компании из обогащения и считаем, какой класс какую долю покупателей
даёт. По этому видно, стоит ли обогащать собранное по Чеко.
"""
import sqlite3
from collections import Counter, defaultdict

НАЗВАНИЯ = {
    "10": "производство пищевых продуктов",
    "11": "производство напитков",
    "01": "сельское хозяйство",
    "03": "рыболовство",
    "46": "оптовая торговля",
    "47": "розничная торговля",
    "52": "склады и хранение",
    "22": "изделия из пластмасс",
    "82": "упаковывание",
    "20": "химия",
}


def цифры(з):
    return "".join(c for c in str(з or "") if c.isdigit())


e = sqlite3.connect("file:%s?mode=ro" % r"C:\sender\enrich.db", uri=True,
                    timeout=120)
оквэд = {}
for и, к in e.execute("SELECT inn, okved FROM companies"):
    ц = цифры(и)
    if ц:
        оквэд[ц] = str(к or "").strip()
e.close()

s = sqlite3.connect("file:%s?mode=ro" % r"C:\sender\sender.db", uri=True,
                    timeout=120)
по_классу = defaultdict(Counter)
по_коду = defaultdict(Counter)
без_оквэд = 0
всего = 0
for и, в in s.execute("SELECT inn, verdict FROM target_verdicts"):
    ц = цифры(и)
    к = оквэд.get(ц) or ""
    всего += 1
    if not к:
        без_оквэд += 1
        continue
    по_классу[к.split(".")[0]][в] += 1
    по_коду[к][в] += 1
s.close()

строки = []
for кл, счёт in по_классу.items():
    н = sum(счёт.values())
    пок = счёт.get("покупатель", 0)
    строки.append((н, кл, пок, счёт))
строки.sort(reverse=True)

print("=== КЛАССЫ ОКВЭД: ДОЛЯ ПОКУПАТЕЛЕЙ ===")
for н, кл, пок, счёт in строки:
    if н < 20:
        continue
    print("   %-4s %6d вердиктов  покупателей %5d (%4.1f%%)  не пок. %5d  "
          "неясно %4d  %s"
          % (кл, н, пок, 100.0 * пок / н, счёт.get("не покупатель", 0),
             счёт.get("неясно", 0), НАЗВАНИЯ.get(кл, "")))

# самые массовые коды внутри торговли и внутри производства
print("")
print("=== КРУПНЕЙШИЕ КОДЫ ВНУТРИ КЛАССОВ 46 И 10 ===")
for целевой in ("46", "10", "01"):
    внутри = [(sum(c.values()), к, c) for к, c in по_коду.items()
              if к.split(".")[0] == целевой and sum(c.values()) >= 25]
    внутри.sort(reverse=True)
    for н, к, c in внутри[:6]:
        пок = c.get("покупатель", 0)
        print("   %-10s %5d вердиктов  покупателей %4d (%4.1f%%)"
              % (к, н, пок, 100.0 * пок / н))

итог = Counter()
for _, кл, _, счёт in строки:
    группа = ("ядро (10/11/03)" if кл in ("10", "11", "03")
              else "торговля/склад (46/47/52)" if кл in ("46", "47", "52")
              else "сельхоз (01)" if кл == "01" else "прочее")
    for в, н in счёт.items():
        итог[(группа, в)] += н

print("")
print("=" * 68)
print("=== СВОДКА: ЧТО ГЕЙТ ДУМАЕТ О КАЖДОЙ ГРУППЕ ===")
print("вердиктов в кэше: %d, из них без ОКВЭД в обогащении: %d"
      % (всего, без_оквэд))
print("")
for группа in ("ядро (10/11/03)", "сельхоз (01)",
               "торговля/склад (46/47/52)", "прочее"):
    н = sum(v for (г, _), v in итог.items() if г == группа)
    пок = итог.get((группа, "покупатель"), 0)
    if not н:
        continue
    print("   %-26s %6d вердиктов -> покупателей %5d (%4.1f%%)"
          % (группа, н, пок, 100.0 * пок / н))
