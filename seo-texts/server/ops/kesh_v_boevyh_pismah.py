# -*- coding: utf-8 -*-
"""Читается ли кэш в БОЕВЫХ письмах: по журналу партии, а не пробой.

В журнале у каждого письма есть вход_кэш_запись и вход_кэш_чтение —
цифры самого шлюза. Смотрим по дням: механизм разреза промпта у нас
включён давно, вопрос в том, отвечает ли на него шлюз.
"""
import io
import json
from collections import defaultdict

Ж = r"C:\sender\_ops\gen-partiya-935.jsonl"
# Даты в записях нет, зато журнал дописывается: делим по позиции.
по_дням = defaultdict(lambda: {"писем": 0, "зап": 0, "чт": 0})
строки = []
for s in io.open(Ж, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if z.get("этап") != "итог":
        continue
    строки.append(z)

ВСЕГО = len(строки)
куски = [("самое начало", строки[:400]),
         ("середина", строки[ВСЕГО // 2 - 200:ВСЕГО // 2 + 200]),
         ("последние 400", строки[-400:]),
         ("последние 100", строки[-100:]),
         ("последние 50", строки[-50:])]
for имя, кусок in куски:
    к = по_дням[имя]
    for z in кусок:
        к["писем"] += 1
        к["зап"] += int(z.get("вход_кэш_запись") or 0)
        к["чт"] += int(z.get("вход_кэш_чтение") or 0)

print(f"{'кусок журнала':<16} {'писем':>6} {'записано в кэш':>15} {'прочитано':>11} "
      f"{'чт/зап':>7}")
for д, _ in куски:
    к = по_дням[д]
    о = к["чт"] / к["зап"] if к["зап"] else 0
    print(f"{д:<16} {к['писем']:>6} {к['зап']:>15} {к['чт']:>11} {о:>7.2f}")
