# -*- coding: utf-8 -*-
"""P25: два дефекта МОЕЙ приёмки людей, найденные на сухом прогоне 3S-008.

ОТКУДА ВЗЯЛОСЬ. Файл соседки показал строку `Уважаемый Сергей Владимирович` —
это обращение из письма, а не фамилия. Приёмка её пропускает: правило было
«два слова и больше». Рядом — `Крашенинников Евгений Геннадьевич` и
`Евгений Геннадьевич Крашенинников`: один человек, два порядка слов, и мой
уникальный индекс `ux_person(inn, person)` их не склеивает, потому что строки
разные. Обе строки уже В БАЗЕ с прошлых заливок, значит это не про файл 3-й
сессии, а про мой заслон.

ЧТО ДЕЛАЮ С НОМЕРОМ ЛОЖНОГО ЧЕЛОВЕКА. Не выбрасываю. Правило владельца
«разделять, а не отсеивать»: номер остаётся контактом предприятия с пометкой
`is_unknown_owner=1`, `phone_type='общий'`, уходит только ЛОЖНАЯ ПРИПИСКА к
несуществующему человеку. Наблюдение в `contact_source` не трогаю вовсе — это
запись о том, что мы видели, и она была правдой.

ДУБЛИ ПОРЯДКА СЛОВ. Ключ — набор слов в нижнем регистре, отсортированный.
Оставляю написание в порядке «Фамилия Имя Отчество» (у русского отчества
опознаваемый хвост -вич/-вна), номера и наблюдения переношу на оставшегося.
Если порядок опознать нельзя — не трогаю, лучше два человека, чем склеенные
разные.

Запуск: python p25_gigiena_lyudey.py [--apply]
"""
import io
import json
import os
import re
import sqlite3
import sys
import time
from collections import Counter, defaultdict

P25 = r'C:\seostat\data\p25.db'
ПОТОК = r'C:\seostat\drop\p25_gigiena_lyudey.jsonl'
ПРИМЕНИТЬ = '--apply' in sys.argv

# Первое слово, после которого «два слова» перестают быть фамилией с именем
НЕ_ФАМИЛИЯ = {
    'уважаемый', 'уважаемая', 'уважаемые', 'господин', 'госпожа',
    'директор', 'генеральный', 'заместитель', 'главный', 'начальник',
    'руководитель', 'ответственный', 'исполнительный', 'технический',
    'коммерческий', 'финансовый', 'приемная', 'приёмная', 'отдел',
    'служба', 'секретарь', 'дирекция', 'администрация', 'дежурный',
    'контактное', 'контактный', 'ф.и.о', 'фио', 'тел', 'телефон',
}
ОТЧЕСТВО = re.compile(r'(вич|вна|чна|оглы|кызы)$', re.I)


def слова(имя):
    return [с for с in re.split(r'\s+', str(имя or '').strip()) if с]


def ложное_имя(имя):
    с = слова(имя)
    if not с:
        return 'пусто'
    if с[0].lower().strip('.,:') in НЕ_ФАМИЛИЯ:
        return 'обращение или должность вместо фамилии'
    if len(с) < 2:
        return 'одно слово'
    if not any(re.search(r'[а-яё]', х, re.I) for х in с):
        return 'нет кириллицы'
    return ''


def ключ_порядка(имя):
    return ' '.join(sorted(х.lower().strip('.,') for х in слова(имя)))


def инициал(х):
    return len(х.strip('.')) == 1


def фамилия_первой(имя):
    """Написание «Фамилия Имя Отчество» опознаётся двумя способами.

    Полное имя — по хвосту отчества в ПОСЛЕДНЕМ слове. Сокращённое — по тому,
    что первое слово длинное, а остальные инициалы: «Тихонова Е. А.» против
    «Е. А. Тихонова». Второй случай стоил бы двух нерешённых групп: отчества
    в «А.» нет, и определитель по хвосту молчал бы.
    """
    с = слова(имя)
    if len(с) < 2:
        return False
    if ОТЧЕСТВО.search(с[-1]):
        return True
    return not инициал(с[0]) and all(инициал(х) for х in с[1:])


def вес_написания(имя):
    """Из двух правильных по порядку берём читаемое: «Шепталин Константин»,
    а не «ШЕПТАЛИН КОНСТАНТИН». Верхний регистр — след выгрузки, не имя."""
    с = слова(имя)
    вес = 0
    if фамилия_первой(имя):
        вес += 8
    буквенные = [х for х in с if len(х.strip('.')) > 1]
    if буквенные and not any(х.isupper() for х in буквенные):
        вес += 4
    if буквенные and not any(х.islower() for х in буквенные):
        вес += 2
    return вес + min(len(имя), 60) / 100.0


def main():
    цб = sqlite3.connect(P25, timeout=30)
    цб.row_factory = sqlite3.Row
    люди = [dict(r) for r in цб.execute(
        'SELECT rowid AS rid, inn, person, COALESCE(position,\'\') AS position, '
        'COALESCE(role,\'\') AS role, COALESCE(phone,\'\') AS phone '
        'FROM person')]
    стат = Counter()
    стат['людей всего'] = len(люди)

    ложные = []
    for ч in люди:
        п = ложное_имя(ч['person'])
        if п:
            ложные.append((ч, п))
            стат[f'ЛОЖНОЕ ИМЯ: {п}'] += 1

    # дубли порядка слов внутри одного ИНН
    группы = defaultdict(list)
    ложные_rid = {ч['rid'] for ч, _ in ложные}
    for ч in люди:
        if ч['rid'] in ложные_rid:
            continue
        группы[(str(ч['inn']), ключ_порядка(ч['person']))].append(ч)
    дубли = [г for г in группы.values()
             if len({х['person'] for х in г}) > 1]
    стат['ДУБЛЬ ПОРЯДКА СЛОВ: групп'] = len(дубли)
    стат['ДУБЛЬ ПОРЯДКА СЛОВ: строк'] = sum(len(г) for г in дубли)

    print('ЛОЖНЫЕ ИМЕНА (номер останется у предприятия, уйдёт приписка):')
    for ч, п in ложные[:12]:
        print(f"   {ч['inn']} {ч['person'][:40]:40} [{п}]")
    if not ложные:
        print('    нет ни одного')

    print()
    print('ДУБЛИ ПОРЯДКА СЛОВ (показываю, КАКОЕ написание останется):')
    for г in дубли[:10]:
        с_порядком = [х for х in г if фамилия_первой(х['person'])]
        if с_порядком:
            гл = max(с_порядком, key=lambda х: вес_написания(х['person']))
            уйдут = sorted({х['person'] for х in г} - {гл['person']})
            print(f"   {г[0]['inn']} ОСТАНЕТСЯ «{гл['person']}» ← уйдёт: {'; '.join(уйдут)}")
        else:
            print(f"   {г[0]['inn']} ПОРЯДОК НЕ ОПОЗНАН, не трогаю: "
                  f"{' | '.join(sorted({х['person'] for х in г}))}")
    if not дубли:
        print('    нет ни одной')

    if not ПРИМЕНИТЬ:
        print()
        print(json.dumps(dict(стат.most_common()), ensure_ascii=False, indent=1))
        print('СУХОЙ ПРОГОН, ничего не изменено')
        цб.close()
        return

    ts = time.strftime('%Y-%m-%dT%H:%M:%S')
    журнал = []
    поля_c = {r[1] for r in цб.execute('PRAGMA table_info(contact)')}
    столкновений = Counter()

    def переписать(табл, новое_имя, старый):
        """Перевесить строки с уходящего написания на остающееся.

        Прямой UPDATE тут падает на `ux_contact`: у оставшегося человека такая
        строка уже есть — тот же ИНН, тот же номер, только имя написано иначе.
        Это не ошибка, а ровно тот дубль, который мы и склеиваем: строка не
        переписывается, а удаляется, потому что её близнец уже на месте.
        """
        for rid, in list(цб.execute(
                f'SELECT rowid FROM {табл} WHERE inn=? AND person=?',
                (старый['inn'], старый['person']))):
            try:
                цб.execute(f'UPDATE {табл} SET person=? WHERE rowid=?',
                           (новое_имя, rid))
            except sqlite3.IntegrityError:
                цб.execute(f'DELETE FROM {табл} WHERE rowid=?', (rid,))
                столкновений[табл] += 1

    # 1) ЛОЖНЫЕ ИМЕНА: номер спасаем, приписку убираем
    спасено = 0
    for ч, причина in ложные:
        тел = str(ч.get('phone') or '').strip()
        if тел:
            зн = {'inn': ч['inn'], 'kind': 'phone', 'value': тел, 'person': '',
                  'role': '', 'phone_type': 'общий', 'is_unknown_owner': 1,
                  'source': 'спасено из ложной приписки к человеку',
                  'chem_podtverzhdena': f'приписка снята: {причина}'}
            зн = {к: v for к, v in зн.items() if к in поля_c}
            имена = list(зн)
            цб.execute(
                f"INSERT OR IGNORE INTO contact ({','.join(имена)}) "
                f"VALUES ({','.join('?' * len(имена))})", [зн[к] for к in имена])
            спасено += 1
        цб.execute('DELETE FROM person WHERE rowid=?', (ч['rid'],))
        журнал.append({'что': 'ложное имя', 'inn': ч['inn'],
                       'person': ч['person'], 'причина': причина,
                       'номер_спасён': bool(тел), 'ts': ts})
    стат['номеров спасено из ложных приписок'] = спасено

    # 2) ДУБЛИ ПОРЯДКА СЛОВ: оставляем написание с отчеством в конце
    склеено = 0
    не_понял = 0
    for г in дубли:
        с_порядком = [х for х in г if фамилия_первой(х['person'])]
        if not с_порядком:
            не_понял += 1
            continue
        главный = max(с_порядком, key=lambda х: вес_написания(х['person']))
        for х in г:
            if х['rid'] == главный['rid']:
                continue
            if not str(главный.get('phone') or '').strip() and str(х.get('phone') or '').strip():
                цб.execute('UPDATE person SET phone=? WHERE rowid=?',
                           (х['phone'], главный['rid']))
            переписать('contact', главный['person'], х)
            переписать('contact_source', главный['person'], х)
            цб.execute('DELETE FROM person WHERE rowid=?', (х['rid'],))
            склеено += 1
            журнал.append({'что': 'дубль порядка слов', 'inn': х['inn'],
                           'убрано': х['person'], 'оставлено': главный['person'],
                           'ts': ts})
    стат['склеено дублей'] = склеено
    стат['порядок не опознан, не трогал'] = не_понял
    for табл, кол in столкновений.items():
        стат[f'{табл}: строка-близнец уже была, удалена вместо переписи'] = кол
    цб.commit()

    людей = цб.execute('SELECT COUNT(*) FROM person').fetchone()[0]
    контактов = цб.execute('SELECT COUNT(*) FROM contact').fetchone()[0]
    набл = цб.execute('SELECT COUNT(*) FROM contact_source').fetchone()[0]
    цб.close()

    with io.open(ПОТОК, 'a', encoding='utf-8') as ф:
        for з in журнал:
            ф.write(json.dumps(з, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())

    print()
    print(json.dumps(dict(стат.most_common()), ensure_ascii=False, indent=1))
    print(f'СТАЛО: person {людей} | contact {контактов} | наблюдений {набл}')


if __name__ == '__main__':
    main()
