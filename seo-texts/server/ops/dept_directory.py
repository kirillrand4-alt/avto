    доб = len(EC._EXT_RE.findall(текст))
    пост = len(list(_ПОСТ.finditer(текст)))
    отд = len(re.findall(r'(?:отдел|управлени|служб|цех|бюро)\w*', текст, re.I))
    ок = len(тел) >= 4 and (пост >= 2 or доб >= 3) and отд >= 2
    return ок, {'тел': len(тел), 'доб': доб, 'пост': пост, 'отд': отд}


