def цели():
    строк = e.execute(
        "SELECT inn,name,site,okved,COALESCE(revenue_rub,0) FROM companies "
        "WHERE COALESCE(site,'')<>'' AND COALESCE(is_competitor,0)=0").fetchall()
    # домен, поделённый ДВУМЯ ИНН, пропускаем: по домену юрлица не различить
    по_дом = {}
    for r in строк:
        d = EC.site_domain(r[2])
        if d:
            по_дом.setdefault(d, set()).add(r[0])
    спорный = {d for d, s in по_дом.items() if len(s) > 1}

    def обраб(ok):
        m = re.match(r'\s*(\d{1,2})', str(ok or ''))
        return bool(m) and 10 <= int(m.group(1)) <= 33
    из = [r for r in строк if обраб(r[3]) and EC.site_domain(r[2])
          and EC.site_domain(r[2]) not in спорный]
    # ОКВЭД обрабатывающих уже отсёк больницы, которым выгрузка приписала
    # 546 млрд, поэтому сортировать по выручке внутри этого класса безопасно
    из.sort(key=lambda r: -(r[4] or 0))
    return [(r[0], r[1], r[2]) for r in из], len(спорный)


