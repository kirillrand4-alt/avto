def строки(html):
    """Разметка -> список непустых строк (по блочным тегам)."""
    h = EC.без_графики(html or '')
    h = _БЛОК_ТЕГ.sub('\n', h)
    h = re.sub(r'<[^>]+>', ' ', h)
    h = _html.unescape(h)
    из = []
    for ln in h.split('\n'):
        ln = re.sub(r'[ \t\xa0\u2009\u202f]+', ' ', ln).strip()
        if ln:
            из.append(ln)
    return из


def плоский(html):
    return re.sub(r'\s+', ' ', ' '.join(строки(html)))


def норм_роль_текст(s):
    """Текст для канона роли: родительный падеж -> именительный.

    Плюс метролог: канон ролей его не знает вовсе и «Главный метролог» падает в
    «общий», хотя метрология с автоматизацией — одна служба (на «Каустике» это
    буквально «Управление по автоматизации и метрологическому обеспечению»).
    Подставляем метку КИПиА, чтобы он попал в свой класс, а не в чужой.
    """
    s = _РОД_ПАД.sub(lambda m: _КАНОН_РОД[m.group(1).lower()], s or '')
    return re.sub(r'метролог\w*', 'метролог КИПиА', s, flags=re.I)


def должность(s):
    m = _ПОСТ.search(s or '')
    return EC._clean_post(m.group(1)) if m else ''


def телефон_из(s):
    """(номер, добавочный) из отрезка. Добавочный — только ВПЛОТНУЮ к номеру."""
    for m in EC.phones_in(s or ''):
        ном = re.sub(r'\s+', ' ', m.group(0)).strip()
        d = _ДОБ_РЯДОМ.match((s or '')[m.end():m.end() + 24])
        return ном, (d.group(1) if d else '')
    return '', ''


