_A = re.compile(r'<a\b([^>]*)>(.*?)</a>', re.S | re.I)
_HREF = re.compile(r'href\s*=\s*["\']([^"\']+)["\']', re.I)


def ссылки(html, dom):
    из = []
    for m in _A.finditer(html or ''):
        h = _HREF.search(m.group(1))
        if not h:
            continue
        u = h.group(1).strip()
        if u.startswith(('mailto:', 'tel:', '#', 'javascript:', 'data:')):
            continue
        t = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', m.group(2))).strip()[:90]
        full = u if u.startswith('http') else (
            'http://' + dom + (u if u.startswith('/') else '/' + u))
        if EC._domain(full) == dom:
            из.append((full, _html.unescape(t)))
    return из


