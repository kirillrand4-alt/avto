def записи_справочника(html, url):
    """[{person, post, dept, phone, email}] со страницы-справочника.

    Отрезок одного человека ограничен СОСЕДНИМИ ФИО: телефон, лежащий за
    следующим именем, к этому человеку не приклеится. Записи БЕЗ ФИО, но с
    заголовком подразделения и номером, тоже берём — «ОГЭ +7…» это рабочий
    контакт службы.
    """
    лн = строки(html)
    фио_i, фио_v = [], {}
    for i, ln in enumerate(лн):
        if len(ln) > 220:
            continue
        f = EC._фио(ln)
        if f:
            фио_i.append(i)
            фио_v[i] = f
    # заголовок подразделения и его «свежесть»: заголовок из другого раздела
    # страницы приклеивался за сорок строк («Начальник бюро по подбору» получал
    # отдел «Производственный эколого-аналитический контроль»)
    отдел_на, отдел_где = {}, {}
    текущий, где = '', -999
    загол = set()
    for i, ln in enumerate(лн):
        if len(ln) <= 120 and _ОТДЕЛ.match(ln) and not фио_v.get(i) \
                and not next(EC.phones_in(ln), None) and '@' not in ln:
            текущий, где = ln, i
            загол.add(i)
        отдел_на[i], отдел_где[i] = текущий, где

    def есть_контакт(ln):
        return bool(next(EC.phones_in(ln), None)) or '@' in ln

    из = []
    занято = set()
    for k, i in enumerate(фио_i):
        пред = фио_i[k - 1] if k else -1
        след = фио_i[k + 1] if k + 1 < len(фио_i) else len(лн)
        # НАЗАД — не дальше двух строк и НИКОГДА через заголовок отдела, чужой
        # телефон или почту: ровно на этом ломалась привязка (ловушка 4.7,
        # склейка номера приёмной с добавочным другого человека). Проверено на
        # kaustik.ru: Горелову доставался номер Лясникова.
        lo = i
        for j in range(i - 1, max(i - 3, пред, -1), -1):
            if j in загол or есть_контакт(лн[j]):
                break
            lo = j
        # ВПЕРЁД — до следующего ФИО или до следующего заголовка отдела
        hi = i
        for j in range(i + 1, min(i + 7, след, len(лн))):
            if j in загол:
                break
            hi = j
        окно = лн[lo:hi + 1]
        занято.update(range(lo, hi + 1))
        сег = ' | '.join(окно)
        фио = фио_v[i]
        пост = должность(сег.replace(фио, ' '))
        ном, доб = телефон_из(сег)
        почты = [x.lower() for x in EC.EMAIL_RE.findall(сег)
                 if not EC._is_junk_email(x)]
        отд = отдел_на.get(i, '') if (i - отдел_где.get(i, -999)) <= 12 else ''
        if not (пост or ном or почты):
            continue
        из.append({'person': фио, 'post': пост, 'dept': отд,
                   'phone': (f'{ном} доб. {доб}' if (ном and доб) else ном),
                   'email': (почты[0] if почты else ''), 'url': url,
                   'kind': 'человек'})
    # службы без имени: заголовок подразделения + номер рядом
    for i, ln in enumerate(лн):
        if i in занято:
            continue
        отд = отдел_на.get(i, '') if (i - отдел_где.get(i, -999)) <= 6 else ''
        if not отд:
            continue
        ном, доб = телефон_из(ln)
        if not ном:
            continue
        из.append({'person': '', 'post': '', 'dept': отд,
                   'phone': (f'{ном} доб. {доб}' if доб else ном),
                   'email': '', 'url': url, 'kind': 'служба'})
    return из


def записи_вакансий(html, url):
    """Люди/телефоны со страницы вакансий СВОЕГО сайта.

    Строже справочника: на странице вакансий «люди» это ещё и соискатели с
    кусками текста обязанностей (штатный `people_from_html` такие страницы
    отвергает целиком — `_НЕ_СТРАНИЦА`). Берём ТОЛЬКО отрезки с явным
    намерением «сюда обращаться»: «резюме направлять», «обращаться к»,
    «контактное лицо», «телефон для справок».
    """
    лн = строки(html)
    из = []
    for i, ln in enumerate(лн):
        окно = ' | '.join(лн[max(0, i - 2):i + 4])
        if not _НАМЕРЕНИЕ.search(окно):
            continue
        ном, доб = телефон_из(окно)
        почты = [x.lower() for x in EC.EMAIL_RE.findall(окно)
                 if not EC._is_junk_email(x)]
        if not (ном or почты):
            continue
        фио = EC._фио(окно)
        пост = должность(окно.replace(фио, ' ') if фио else окно)
        из.append({'person': фио, 'post': пост, 'dept': '',
                   'phone': (f'{ном} доб. {доб}' if (ном and доб) else ном),
                   'email': (почты[0] if почты else ''), 'url': url,
                   'kind': 'вакансия'})
    # дедуп по (ФИО, телефон, почта)
    свод = {}
    for r in из:
        k = (r['person'].lower(), r['phone'], r['email'])
        if k not in свод or len(r['post']) > len(свод[k]['post']):
            свод[k] = r
    return list(свод.values())


