def _пишем(inn, r, источник):
    """Одна найденная запись: в durable-поток всегда, в базу — при --apply."""
    роль = EDB.EnrichDB._canon_role(норм_роль_текст(r['_post_для_роли']))
    r = dict(r, inn=inn, роль=роль, источник=источник, ts=time.strftime('%FT%T'))
    with замок:
        фн.write(json.dumps(r, ensure_ascii=False) + '\n')
        фн.flush()
        os.fsync(фн.fileno())
    if not ПРИМЕНИТЬ:
        return роль
    if r.get('person'):
        db.add_person(inn, r['person'], post=r['_post_для_роли'],
                      phone=r.get('phone') or '', email=r.get('email') or '',
                      source=источник, source_url=r.get('url') or '')
        with замок:
            out['записано_людей'] += 1
    if r.get('phone'):
        if db.add_phone(inn, r['phone'], person=r.get('person') or '',
                        role=норм_роль_текст(r['_post_для_роли']),
                        source=источник, source_url=r.get('url') or ''):
            with замок:
                out['записано_тел'] += 1
    if r.get('email'):
        db.add_email(inn, r['email'], role=норм_роль_текст(r['_post_для_роли']),
                     person=r.get('person') or '', source=источник,
                     source_url=r.get('url') or '')
        with замок:
            out['записано_почт'] += 1
    return роль


def работа(ц):
    inn, имя, сайт = ц
    if time.time() - НАЧАЛО > БЮДЖЕТ:
        return
    свой = time.time()
    итог = {'inn': inn, 'dom': EC.site_domain(сайт)}
    # бренд компании — чтобы отличить чужое юрлицо в заголовке блока
    бренд = (EC.бренд_компании(имя, сайт) or '').lower().strip()
    try:
        d = EC.site_domain(сайт)
        h0 = взять('http://' + d)
        if not h0:
            итог['err'] = 'главная не открылась'
            raise RuntimeError(итог['err'])
        with замок:
            out['страниц'] += 1
        лс = ссылки(EC.без_графики(h0), d)
        ворота = [u for u, t in лс
                  if any(k in (u + ' ' + t).lower() for k in _СЛАГ_ВОРОТА)][:5]
        for u in ворота:
            if time.time() - свой > НА_КОМПАНИЮ or time.time() - НАЧАЛО > БЮДЖЕТ:
                break
            h = взять(u)
            if h:
                with замок:
                    out['страниц'] += 1
                лс += ссылки(EC.без_графики(h), d)
        видано, канд_а, канд_б, доки = set(), [], [], []
        for u, t in лс:
            if u in видано:
                continue
            видано.add(u)
            s = (u + ' ' + t).lower()
            if _ДОК.search(u):
                if any(k in s for k in ('справочник', 'spravochnik', 'телефон',
                                        'telefon', 'подразделен')) \
                        and len(доки) < 3:
                    доки.append(u)
                continue
            if any(k in s for k in _СЛАГ_СПР) and len(канд_а) < 8:
                канд_а.append(u)
            if any(k in s for k in _СЛАГ_ВАК) and len(канд_б) < 5:
                канд_б.append(u)
        итог['канд_а'] = len(канд_а)
        итог['канд_б'] = len(канд_б)
        итог['док'] = len(доки)

        # ---------------- А: справочник ----------------
        найдено_а, стр_а = [], []
        if 'a' in РЕЖИМ:
            for u in канд_а + доки:
                if time.time() - свой > НА_КОМПАНИЮ or time.time() - НАЧАЛО > БЮДЖЕТ:
                    break
                док = _ДОК.search(u)
                if док:
                    txt = EC.doc_text(u)
                    if not txt:
                        continue
                    html_ = '<p>' + txt.replace('\n', '</p><p>') + '</p>'
                    with замок:
                        out['A_док'] += 1
                else:
                    html_ = взять(u)
                    if not html_:
                        continue
                    with замок:
                        out['страниц'] += 1
                    txt = плоский(html_)
                ок, мет = похоже_на_справочник(txt)
                if not ок:
                    continue
                стр_а.append({'url': u, **мет})
                найдено_а += записи_справочника(html_, u)
        # ---------------- Б: вакансии ----------------
        найдено_б, стр_б = [], []
        if 'b' in РЕЖИМ:
            for u in канд_б:
                if time.time() - свой > НА_КОМПАНИЮ or time.time() - НАЧАЛО > БЮДЖЕТ:
                    break
                html_ = взять(u)
                if not html_:
                    continue
                with замок:
                    out['страниц'] += 1
                зп = записи_вакансий(html_, u)
                if зп:
                    стр_б.append(u)
                    найдено_б += зп

        # ---------------- запись ----------------
        for тег, найдено, страниц in (('A', найдено_а, стр_а),
                                      ('B', найдено_б, стр_б)):
            if страниц:
                with замок:
                    out[f'{тег}_есть_раздел'] += 1
            видано_к = set()
            for r in найдено:
                # чужое юрлицо в заголовке подразделения
                чуж = _ЧУЖОЕ_ЮЛ.search(r.get('dept') or '')
                if чуж and бренд and чуж.group(1).lower() not in бренд \
                        and бренд not in чуж.group(1).lower():
                    with замок:
                        out['чужое_юл'] += 1
                    continue
                # Текст для роли: должность ЦЕЛИКОМ (не обрезаем — «заместитель
                # главного инженера» иначе завышается до главного инженера), а
                # имя подразделения приклеиваем лишь как ЗАПАСНОЙ признак:
                #   * должность руководящая («Начальник управления» без
                #     предмета) — сам предмет и есть подразделение;
                #   * и только когда должность СОБСТВЕННОЙ роли не даёт.
                # Без второго условия «Начальник бюро по подбору персонала» из
                # раздела «Производственный контроль» становился начальником
                # производства, а рекрутёр — техническим ЛПР.
                пост = r.get('post') or ''
                отд = r.get('dept') or ''
                своя = EDB.EnrichDB._canon_role(норм_роль_текст(пост))
                если_рук = bool(_РУК_ПОСТ.search(пост))
                if отд and своя in ('', 'общий') and (если_рук or not пост):
                    полн = f'{пост} ({отд})'.strip() if пост else отд
                else:
                    полн = пост
                r['_post_для_роли'] = полн[:158]
                k = (r.get('person', '').lower(), r.get('phone', ''),
                     r.get('email', ''), полн.lower())
                if k in видано_к or not (r.get('person') or r.get('phone')
                                         or r.get('email')):
                    continue
                видано_к.add(k)
                роль = _пишем(inn, r, 'сайт:справочник' if тег == 'A'
                              else 'сайт:вакансии')
                with замок:
                    out[f'{тег}_записей'] += 1
                    if r.get('person'):
                        out[f'{тег}_людей'] += 1
                    if r.get('phone'):
                        out[f'{тег}_с_телефоном'] += 1
                    if роль in EDB.EnrichDB.TECH_ROLES:
                        out[f'{тег}_техЛПР'] += 1
                        if len(out['примеры']) < 25:
                            out['примеры'].append(
                                {'инн': inn, 'фио': r.get('person'),
                                 'долж': полн[:70], 'роль': роль,
                                 'тел': r.get('phone'), 'почта': r.get('email'),
                                 'url': (r.get('url') or '')[:95]})
        итог['A'] = len(найдено_а)
        итог['B'] = len(найдено_б)
        итог['стр_а'] = [x['url'][:110] for x in стр_а]
    except Exception as ex:  # noqa: BLE001
        итог.setdefault('err', f'{type(ex).__name__}: {str(ex)[:70]}')
        with замок:
            out['ошибок'] += 1
    with замок:
        out['обработано'] += 1
        ф.write(json.dumps(итог, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())


