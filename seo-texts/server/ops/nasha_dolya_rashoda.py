# -*- coding: utf-8 -*-
"""Сколько сегодня потратили НАШИ прогоны — против итога по шлюзу.

Владелец 24.08 показал панель шлюза: $28.52 в 16:07 и $96.99 в 16:39,
то есть почти семьдесят долларов за полчаса. Шлюз считает ВСЕХ
потребителей ключа сразу: кроме двух прогонов партии на сервере крутятся
процессы обогащения, панельная генерация и работа соседней сессии.
Прежде чем резать генерацию, надо знать её долю, а не догадываться.

Считаем по журналу партии: цена письма и цена проверок пишутся в каждую
строку «итог». Заодно печатаем разбивку по вызовам и токенам, чтобы
видеть, что именно дорого.
"""
import io
import json
import os
import subprocess
import time
from collections import Counter

Ж = r"C:\sender\_ops\gen-partiya-935.jsonl"
СЕГОДНЯ = time.strftime("%Y-%m-%d")

письма = []
for с in io.open(Ж, encoding="utf-8", errors="replace"):
    try:
        з = json.loads(с)
    except Exception:                                          # noqa: BLE001
        continue
    if з.get("этап") != "итог":
        continue
    письма.append(з)

# Дня в старых записях нет — он добавлен только что и появится после
# перезапуска. Сегодняшние отделяем по review_id: свежие карточки идут
# сплошным хвостом, а старые записи их не имеют либо имеют меньшие.
свежие = [з for з in письма if з.get("день") == СЕГОДНЯ]
if not свежие:
    # запасной ход: берём хвост журнала по времени изменения файла
    свежие = письма[-40:]
    print("поле «день» ещё не в записях (появится после перезапуска) — "
          "считаю по хвосту журнала: последние %d писем" % len(свежие))

цена = sum(float(з.get("цена_$") or 0) for з in свежие)
цена_писем = sum(float(з.get("цена_письма_$") or 0) for з in свежие)
цена_пров = sum(float(з.get("цена_проверок_$") or 0) for з in свежие)
вызовов = sum(int(з.get("вызовов") or 0) for з in свежие)
вызовов_пр = sum(int(з.get("вызовов_проверок") or 0) for з in свежие)
запись = sum(int(з.get("вход_кэш_запись") or 0) for з in свежие)
чтение = sum(int(з.get("вход_кэш_чтение") or 0) for з in свежие)

print("писем в выборке: %d" % len(свежие))
print("суммарно: $%.2f  (письма $%.2f + проверки $%.2f)"
      % (цена, цена_писем, цена_пров))
if свежие:
    print("на письмо: $%.3f  |  вызовов %.1f + проверок %.1f"
          % (цена / len(свежие), вызовов / len(свежие),
             вызовов_пр / len(свежие)))
print("кэш: записано %d токенов, прочитано %d" % (запись, чтение))
if запись:
    print("доля чтения: %.1f%%" % (100.0 * чтение / (запись + чтение)))

направления = Counter(з.get("направление", "?") for з in свежие)
print("по направлениям:", dict(направления))

print("\n=== ЧТО ЕЩЁ КРУТИТСЯ НА СЕРВЕРЕ (потребители того же ключа) ===")
try:
    вывод = subprocess.run(
        ["wmic", "process", "where", "name='python.exe'",
         "get", "ProcessId,CommandLine", "/format:list"],
        capture_output=True, text=True, timeout=60).stdout
    ком = ""
    for строка in вывод.splitlines():
        строка = строка.strip()
        if строка.startswith("CommandLine="):
            ком = строка[12:]
        elif строка.startswith("ProcessId=") and ком.strip():
            print("  %-6s %s" % (строка.split("=", 1)[1], ком[:110]))
except Exception as e:                                         # noqa: BLE001
    print("  список процессов не снялся:", e)

print("\nразмер журнала: %d байт" % os.path.getsize(Ж))
