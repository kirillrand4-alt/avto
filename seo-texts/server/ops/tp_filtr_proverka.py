"""Не общая ли это выдача: приходит ли один тендер под разными ИНН.

3-я сессия нашла, что у tender.pro НИ ОДИН id не фильтрует список — фильтрует
только имя текстом, а прогон с `company_id` возвращал «тендеров 2820»
одинаково у восьми разных предприятий. Её правило: проба обязана показывать
РАЗЛИЧЕНИЕ, а не непустоту.

Проверяю у себя тем признаком, который различает без всяких проб: если список
не фильтруется, ОДИН И ТОТ ЖЕ tender_id обязан появиться под разными ИНН.
"""
import io, json, os
from collections import Counter, defaultdict
С = r'C:\seostat\drop\drop-storage\tp_raw.json'
д = json.load(io.open(С, encoding='utf-8'))
карточки = д.get('карточки') or []
по_тендеру = defaultdict(set)
для_инн = Counter()
for к in карточки:
    по_тендеру[str(к.get('tender_id'))].add(str(к.get('inn')))
    для_инн[str(к.get('inn'))] += 1
общие = {т: и for т, и in по_тендеру.items() if len(и) > 1}
print('ПОВТОРЫ ТЕНДЕРА ПОД РАЗНЫМИ ИНН (признак нефильтрованной выдачи):')
for т, и in list(общие.items())[:8]:
    print(f'   тендер {т}: ИНН {", ".join(sorted(и))}')
if not общие:
    print('   ни одного — каждый тендер пришёл ровно одному предприятию')
print()
print('РАСПРЕДЕЛЕНИЕ КАРТОЧЕК ПО ПРЕДПРИЯТИЯМ (одинаковое число у всех — тоже признак):')
ч = Counter(для_инн.values())
for сколько, скольким in sorted(ч.items()):
    print(f'   {скольким:4} предприятий получили ровно по {сколько} карточек')
print()
print('=== ЧИСЛА ===')
print(f'   карточек всего                 {len(карточки):5}')
print(f'   различных тендеров             {len(по_тендеру):5}')
print(f'   тендеров под 2+ ИНН            {len(общие):5}')
print(f'   предприятий с карточками       {len(для_инн):5}')
