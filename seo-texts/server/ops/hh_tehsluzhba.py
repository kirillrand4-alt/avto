# -*- coding: utf-8 -*-
"""Наём в ТЕХСЛУЖБУ: разметка уже собранных hh-сигналов.

Задача висела в очереди с самого начала и ни разу не делалась. Вакансий с hh
в базе 880 (445 «hh-вакансия» плюс 435 «hh»), но они лежат общей кучей: есть
и «менеджер по продажам», и «главный энергетик». Между тем это разные вещи.

**Почему вакансия в техслужбу — сильный сигнал, а не просто факт.** Она
означает СРАЗУ ДВА: служба главного энергетика (механика, инженера) на
предприятии существует — то есть там есть кому эксплуатировать компрессор, —
и прямо сейчас в ней дыра. Человека ищут, значит место пустует или
расширяется. Для звонка это повод: «у вас ищут энергетика, пока его нет,
кто ведёт компрессорную?»

Сети не требует: разбираем текст уже записанных сигналов регуляркой.
Ничего не удаляем — поднимаем hotness и уточняем event_type.

Запуск: python hh_tehsluzhba.py [--dry]
"""
import re
import sys

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

СУХОЙ = '--dry' in sys.argv

# Роли ТЕХСЛУЖБЫ. Формулировки взяты не из головы, а из канона ролей
# enrich_db плюс живые вывески, которые сегодня же чинили: паросиловое
# хозяйство, энергоцентр, компрессорный цех.
_ТЕХ = re.compile(
    r'главн\w*\s+(?:энергетик|механик|инженер|технолог)|'
    r'\bэнергетик|\bмехан(?:ик|ику)|\bтеплотехник|'
    r'начальник\w*\s+(?:\S+\s+){0,2}(?:цех|участк|котельн|компрессорн|'
    r'энергослужб|огэ|огм)|'
    r'компрессорн|паросилов|энергоцентр|энергохозяйств|энергоучаст|'
    r'кипиа|кип и а|асу\s?тп|'
    r'инженер\w*\s+по\s+(?:эксплуатац|оборудован|ремонт|энерг)', re.I)
# То, что выглядит технически, но нам не адресат: транспорт, стройка, ИТ.
_НЕ_НАШ = re.compile(
    r'автомехан|механик гараж|автотранспорт|транспортн|гараж|'
    r'программист|системн\w+ администратор|инженер-проектировщик|\bгип\b|'
    r'охранно-пожарн|сварщик|электромонтёр|электромонтер|слесар', re.I)


def main():
    db = EDB.EnrichDB()
    q = db.cx.execute
    ряды = q("SELECT rowid, inn, source, event_type, what, hotness FROM signals "
             "WHERE source IN ('hh-вакансия','hh')").fetchall()
    print(f'hh-сигналов всего: {len(ряды)}')

    # ВОССТАНОВЛЕНИЕ. Первый прогон затёр event_type у 644 строк, потому что
    # регулярка читала ЕГО ЖЕ, а не текст вакансии: подпись «наём в
    # компрессорную» содержит «компрессорн» и совпадала у всех подряд, включая
    # кладовщика и оператора котельной. Возвращаем прежнюю подпись — источник
    # hh пишет её один, чужого тут нет.
    вернули = q("UPDATE signals SET event_type='наём в компрессорную' "
                "WHERE source IN ('hh-вакансия','hh') "
                "AND event_type='наём в техслужбу'").rowcount
    if вернули:
        db.cx.commit()
        print(f'восстановлено затёртых подписей: {вернули}')
    ряды = q("SELECT rowid, inn, source, event_type, what, hotness FROM signals "
             "WHERE source IN ('hh-вакансия','hh')").fetchall()

    тех, не_наш, прочее = [], 0, 0
    for rid, инн, ист, тип, что, жар in ряды:
        # ТОЛЬКО текст вакансии. event_type сюда не входит намеренно — именно
        # он и испортил первый замер.
        текст = f'{что or ""}'
        if _НЕ_НАШ.search(текст):
            не_наш += 1
            continue
        if _ТЕХ.search(текст):
            тех.append((rid, инн, текст.strip()[:90], жар))
        else:
            прочее += 1
    print(f'  наём в ТЕХСЛУЖБУ: {len(тех)}')
    print(f'  явно не наш профиль (транспорт, ИТ, стройка): {не_наш}')
    print(f'  прочие вакансии: {прочее}')
    print(f'  предприятий с наймом в техслужбу: {len({t[1] for t in тех})}')

    if not СУХОЙ and тех:
        for rid, _инн, _т, жар in тех:
            # hotness 3 — как у плана закупки: и служба есть, и в ней дыра
            q('UPDATE signals SET event_type = ?, hotness = ? WHERE rowid = ?',
              ('наём в техслужбу', max(int(жар or 0), 3), rid))
        db.cx.commit()

    сколько = q("SELECT COUNT(*) FROM signals WHERE event_type='наём в техслужбу'"
                ).fetchone()[0]
    комп = q("SELECT COUNT(DISTINCT inn) FROM signals "
             "WHERE event_type='наём в техслужбу'").fetchone()[0]
    print()
    print('=== ИЗ БАЗЫ (не из счётчиков прогона) ===')
    print(f'  сигналов «наём в техслужбу»: {сколько} в {комп} компаниях')

    # сколько из них уже с техЛПР, а сколько — новый повод без человека
    трл = "','".join(EDB.EnrichDB.TECH_ROLES)
    с_чел = q("SELECT COUNT(DISTINCT s.inn) FROM signals s WHERE "
              "s.event_type='наём в техслужбу' AND s.inn IN "
              f"(SELECT inn FROM people WHERE role IN ('{трл}'))").fetchone()[0]
    print(f'  из них уже с техЛПР в базе: {с_чел}, без человека: {комп - с_чел}')

    print()
    print('=== ПРИМЕРЫ ===')
    for _rid, инн, т, _ж in тех[:12]:
        print(f'  {инн}  {т}')
    print(f'техслужба {len(тех)}, компаний {комп}')


if __name__ == '__main__':
    main()
