def паспорт(con, инн):
    try:
        r = con.execute("SELECT facts_json FROM site_facts WHERE inn=?",
                        (str(инн),)).fetchone()
    except Exception:                                            # noqa: BLE001
        return ""
    if not r or not (r[0] or "").strip():
        return ""
    try:
        d = json.loads(r[0])
    except Exception:                                            # noqa: BLE001
        return ""
    куски = []
    for k in ("цитата", "продукция", "оборудование_линии", "сырьё",
              "масштаб", "мощности", "контроль_качества"):
        v = d.get(k)
        if not v:
            continue
        куски.append(f"{k}: " + (v if isinstance(v, str)
                                 else "; ".join(map(str, v))[:300]))
    return "\n".join(куски)[:1500]


