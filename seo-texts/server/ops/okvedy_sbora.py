# -*- coding: utf-8 -*-
"""Какие ОКВЭД собрались по Чеко и насколько они мейеровские по сути.

Meyer продаёт рентген-инспекцию и фотосепараторы для ПИЩЕВОГО СЫРЬЯ, то есть
покупатель — тот, у кого есть СВОЙ поток продукта: производство (10.xx,
11.xx), переработка, иногда хозяйство со своей подработкой зерна (01.xx).
Оптовая торговля (46.xx) продукт не производит — линза покупателя таких
отбивает («это склад, потока нет»). Поэтому считаем не только штуки, но и
раскладку по классам.
"""
import csv
import io
from collections import Counter, defaultdict

CSV = r"C:\seostat\Parser2\data\agro-base.csv"

КЛАССЫ = [
    ("10", "производство пищевых продуктов"),
    ("11", "производство напитков"),
    ("01", "сельское хозяйство (выращивание, животноводство)"),
    ("03", "рыболовство и рыбоводство"),
    ("46", "ОПТОВАЯ ТОРГОВЛЯ (продукт не производят)"),
    ("47", "розничная торговля"),
    ("82", "упаковывание и прочие услуги"),
    ("52", "склады и хранение"),
    ("20", "химия"),
    ("21", "фармацевтика"),
]

коды = Counter()
имена = {}
по_классам = Counter()
класс_кодов = defaultdict(set)
всего = 0
with io.open(CSV, encoding="utf-8-sig", errors="replace", newline="") as ф:
    for р in csv.DictReader(ф, delimiter=";"):
        всего += 1
        к = str(р.get("Основной ОКВЭД") or "").strip()
        if not к:
            к = "(пусто)"
        коды[к] += 1
        имена.setdefault(к, str(р.get("Вид деятельности") or "").strip())
        кл = к.split(".")[0]
        по_классам[кл] += 1
        класс_кодов[кл].add(к)

print("=== ВСЕ КОДЫ СБОРА, ПО УБЫВАНИЮ ===")
for к, н in коды.most_common():
    print("   %-10s %7d  %s" % (к, н, имена.get(к, "")[:88]))

print("")
print("=" * 68)
print("=== СВОДКА: ЧТО ЗА СБОР ===")
print("компаний всего: %d, разных кодов: %d" % (всего, len(коды)))
print("")
print("ПО КЛАССАМ ОКВЭД:")
названия = dict(КЛАССЫ)
ядро = торговля = прочее = 0
for кл, н in по_классам.most_common():
    подпись = названия.get(кл, "")
    доля = 100.0 * н / всего if всего else 0
    print("   %-4s %8d (%4.1f%%)  кодов %2d  %s"
          % (кл, н, доля, len(класс_кодов[кл]), подпись))
    if кл in ("10", "11", "03"):
        ядро += н
    elif кл in ("46", "47", "52"):
        торговля += н
    else:
        прочее += н
print("")
print("ГРУППЫ ПО СМЫСЛУ ДЛЯ MEYER:")
print("   производство продуктов/напитков/рыбы: %7d (%4.1f%%)  <- ядро"
      % (ядро, 100.0 * ядро / всего if всего else 0))
print("   торговля и склады:                    %7d (%4.1f%%)  <- линза "
      "покупателя такие отбивает" % (торговля, 100.0 * торговля / всего
                                     if всего else 0))
print("   остальное (в т.ч. сельхоз 01.xx):     %7d (%4.1f%%)"
      % (прочее, 100.0 * прочее / всего if всего else 0))
