# -*- coding: utf-8 -*-
"""Убрать из базы номера, которые обратный ход приписал людям ошибочно.

ЧТО СЛУЧИЛОСЬ. Обратный ход ищет страницу человека по «ФИО + компания» и берёт
телефон из окрестности фамилии. На первых же 25 записях выяснилось, что
окрестность фамилии — недостаточная защита:

* `8 (915) 570-31-13` приписан ЧЕТВЕРЫМ разным людям на ТРЁХ разных ИНН. Это
  страница преподавателей учебного центра `uc.efko.ru/prepodavateli/`: номер
  там один на всех, а фамилии идут списком;
* `8 (800) 300-43-43` — федеральный колл-центр с карточки агрегатора
  `vbankcenter.ru/contragent/person/…`, приписан двоим;
* `+7 (34370) 9-02-62` — номер с краеведческой страницы библиотеки, двоим.

Сам оп теперь такие страницы не берёт (путь-агрегатор, список фамилий рядом,
номер 8-800), но записанное до правки надо убрать.

ПРАВИЛО ЧИСТКИ, простое и проверяемое: номер, приписанный ДВУМ И БОЛЕЕ РАЗНЫМ
ЛЮДЯМ либо двум и более разным ИНН, личным быть не может. Плюс явные
федеральные и агрегаторские адреса. Остальное не трогаем: «Занин Дмитрий
Николаевич, главный инженер, +7 (8442) 40-68-80» со страницы руководства
самого «Каустика» — настоящая находка, и терять её из-за общего правила нельзя.

По умолчанию СУХОЙ ПРОГОН. Запуск: python chistka_obratnogo.py [--apply]
"""
import json
import re
import sys
from collections import defaultdict

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ПРИМЕНИТЬ = '--apply' in sys.argv
_ИСТОЧНИК = "source LIKE '%обратн%' OR source LIKE '%back%'"
_НЕЛИЧНЫЙ = re.compile(r'^7?800\d{7}$')
_ПУТЬ_СПИСКА = re.compile(
    r'/contragent|/operators-registry|/prepodavatel|/sovet-deputat|'
    r'/vypisk|/person/\d|/deputat|/sostav|/biblioteka|/moya-rodina|'
    r'/personalii|/pochetn|/spisok|/user-profile|/profile/|/forum', re.I)


def д10(т):
    ц = re.sub(r'\D', '', str(т or ''))
    return ц[-10:] if len(ц) >= 10 else ц


def main():
    db = EDB.EnrichDB()
    строки = list(db.cx.execute(
        'SELECT rowid, inn, phone, COALESCE(person,\'\'), COALESCE(role,\'\'), '
        'COALESCE(source_url,\'\') FROM phone_contacts WHERE ' + _ИСТОЧНИК))
    по_номеру = defaultdict(lambda: {'люди': set(), 'инн': set(), 'ряды': []})
    for rid, инн, тел, чел, роль, урл in строки:
        з = по_номеру[д10(тел)]
        з['люди'].add((чел or '').strip().lower())
        з['инн'].add(str(инн))
        з['ряды'].append((rid, инн, тел, чел, роль, урл))

    к_удалению, причины = [], {}
    for ц, з in по_номеру.items():
        причина = ''
        if len(з['инн']) > 1:
            причина = f'один номер на {len(з["инн"])} разных ИНН'
        elif len([л for л in з['люди'] if л]) > 1:
            причина = f'один номер на {len(з["люди"])} разных людей'
        elif _НЕЛИЧНЫЙ.match(ц):
            причина = 'федеральный 8-800, не личный'
        else:
            плохие = [r for r in з['ряды'] if _ПУТЬ_СПИСКА.search(r[5] or '')]
            if плохие:
                причина = 'страница-агрегатор или список людей'
        if причина:
            for r in з['ряды']:
                к_удалению.append(r)
                причины[r[0]] = причина

    осталось = len(строки) - len(к_удалению)
    print(json.dumps({
        'записей_обратного_хода': len(строки),
        'К_УДАЛЕНИЮ': len(к_удалению),
        'останется': осталось,
        'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
    }, ensure_ascii=False, indent=1))
    for rid, инн, тел, чел, роль, урл in к_удалению:
        print(f'  убрать: {инн} {(чел or "")[:26]:<26} {роль:<14} {тел[:20]:<20} '
              f'{причины[rid][:40]:<40} {урл[:44]}')
    print('  --- остаются ---')
    for rid, инн, тел, чел, роль, урл in строки:
        if rid not in причины:
            print(f'  ОК:     {инн} {(чел or "")[:26]:<26} {роль:<14} '
                  f'{тел[:20]:<20} {урл[:52]}')

    if not ПРИМЕНИТЬ or not к_удалению:
        if not ПРИМЕНИТЬ:
            print('\nсухой прогон. Повторить с --apply')
        return
    db.cx.executemany('DELETE FROM phone_contacts WHERE rowid=?',
                      [(r[0],) for r in к_удалению])
    db.cx.commit()
    стало = db.cx.execute(
        'SELECT COUNT(*) FROM phone_contacts WHERE ' + _ИСТОЧНИК).fetchone()[0]
    print(json.dumps({'удалено': len(к_удалению),
                      'осталось_от_обратного_хода': стало}, ensure_ascii=False))


if __name__ == '__main__':
    main()
