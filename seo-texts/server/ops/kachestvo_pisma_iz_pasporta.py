# -*- coding: utf-8 -*-
"""Насколько хорошее письмо выйдет из этого паспорта — дешёвой моделью.

Идея владельца 19.08: «давай ещё один классификатор — насколько хорошее
письмо получится под кц/мейер из исходного паспорта» + «прогоним по нему кц,
возьмём лучшие паспорта пока кеш не работает».

Смысл. Первый классификатор отвечает КУДА (кц/мейер/никуда). Этот отвечает
СТОИТ ЛИ: хватит ли в паспорте конкретики, чтобы письмо было про них, а не
про отрасль вообще. Пока кэш шлюза мёртв и попытка стоит ~$0.55, порядок
кандидатов решает деньги: сначала те, из кого выйдет письмо.

Что считаем хорошим паспортом (по нашим же причинам брака):
  * названы КОНКРЕТНЫЕ изделия или операции - есть за что зацепиться;
  * видно оборудование или линии - можно говорить о процессе;
  * есть масштаб или география - письмо звучит адресно;
а плохим:
  * общие слова («качественная продукция», «широкий ассортимент»);
  * одна визитка без дела;
  * профиль, из которого письмо неизбежно выйдет про «типичное производство»
    - а это ровно наш брак «цех не подтверждён сайтом».

Прогон проверочный: берём компании с ИЗВЕСТНЫМ исходом (письмо вышло или
забраковано) и смотрим, предсказывает ли оценка исход.
"""
import io
import json
import os
import re
import sqlite3
import sys
import time
from collections import Counter

sys.path.insert(0, r"C:\sender")
import gen_provider as GP                                        # noqa: E402

МОДЕЛЬ = next((a.split("=", 1)[1] for a in sys.argv[1:]
               if a.startswith("модель=")), "gpt-5.6-luna")
НАПР = next((a for a in sys.argv[1:] if a in ("kc", "meyer")), "kc")
СКОЛЬКО = int(next((a for a in sys.argv[1:] if a.isdigit()), "40"))
ЖУРНАЛ_ГЕН = r"C:\sender\_ops\gen-partiya-935.jsonl"
ВЫХОД = r"C:\sender\_ops\kachestvo-pasportov.jsonl"
ENRICH = r"C:\sender\enrich.db"

СИСТЕМА = """Ты оцениваешь, ХВАТИТ ЛИ материала для холодного письма.

Тебе дают выжимку с сайта компании. Мы пишем ей письмо про промышленное
оборудование и должны сказать что-то КОНКРЕТНОЕ про её дело - иначе письмо
получится про «типичное производство вашего профиля», а это брак.

Оценка 0-10:
9-10 названы конкретные изделия ИЛИ операции ИЛИ оборудование, плюс масштаб
     или география - письмо будет адресным и проверяемым;
6-8  есть конкретика, но негусто: одна-две зацепки;
3-5  общие слова, ассортимент, «качество» - зацепиться почти не за что;
0-2  визитка, контакты, ничего о деле; или профиль вообще не наш.

Отдельно назови ЗАЦЕПКУ - ту деталь, вокруг которой строится письмо
(3-8 слов, дословно из выжимки). Нет зацепки - пустая строка.

ОТВЕТ - СТРОГО JSON:
{"firmy":[{"inn":"...","ball":N,"zacepka":"...","pochemu":"3-6 слов"}]}"""


def паспорт(con, инн):
    try:
        r = con.execute("SELECT facts_json FROM site_facts WHERE inn=?",
                        (str(инн),)).fetchone()
    except Exception:                                            # noqa: BLE001
        return ""
    if not r or not (r[0] or "").strip():
        return ""
    try:
        d = json.loads(r[0])
    except Exception:                                            # noqa: BLE001
        return ""
    куски = []
    for k in ("цитата", "продукция", "оборудование_линии", "сырьё",
              "масштаб", "мощности", "география_поставок",
              "контроль_качества"):
        v = d.get(k)
        if not v:
            continue
        куски.append(f"{k}: " + (v if isinstance(v, str)
                                 else "; ".join(map(str, v))[:280]))
    return "\n".join(куски)[:1400]


# ---- компании с известным исходом ---------------------------------------- #
исходы = {}
for s in io.open(ЖУРНАЛ_ГЕН, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if z.get("этап") != "итог" or not z.get("inn"):
        continue
    if z.get("направление") != НАПР:
        continue
    б = z.get("брак")
    т = б if isinstance(б, str) else "; ".join(str(x) for x in (б or []))
    исходы[str(z["inn"])] = {
        "имя": z.get("имя"),
        "вышло": bool(z.get("тело")),
        "цех_не_подтверждён": bool(re.search(r"(?i)цех не подтверж", т)),
        "линза": bool(re.search(r"(?i)инженерная линза", т)),
    }
пары = list(исходы.items())[-СКОЛЬКО:]
con = sqlite3.connect(f"file:{ENRICH}?mode=ro", uri=True, timeout=15)
работа = []
for инн, и in пары:
    п = паспорт(con, инн)
    if п:
        работа.append((инн, и, п))
con.close()
print(f"направление {НАПР}, компаний с паспортом и известным исходом: "
      f"{len(работа)}, модель {МОДЕЛЬ}")
if not работа:
    raise SystemExit(0)

оценки = {}
цена = 0.0
СТАВКИ = {"gpt-5.6-luna": (0.11, 0.67), "claude-haiku-4-5": (1.0, 5.0)}
вх_ст, вых_ст = СТАВКИ.get(МОДЕЛЬ, (5.0, 25.0))
ШАГ = 25
t0 = time.time()
for i in range(0, len(работа), ШАГ):
    пачка = работа[i:i + ШАГ]
    блоки = [f"ИНН {инн} · {и['имя']}\n{п}" for инн, и, п in пачка]
    try:
        m = GP._raw_stream(
            [{"role": "user", "content": "Компании:\n\n" + "\n\n".join(блоки)}],
            МОДЕЛЬ, 2500, thinking=False, system=СИСТЕМА)
    except Exception as ex:                                      # noqa: BLE001
        print(f"пачка {i}: {str(ex)[:90]}")
        continue
    т = "".join(getattr(b, "text", "") for b in getattr(m, "content", []) or [])
    u = getattr(m, "usage", None)
    цена += (int(getattr(u, "input_tokens", 0) or 0) / 1e6 * вх_ст
             + int(getattr(u, "output_tokens", 0) or 0) / 1e6 * вых_ст)
    мм = re.search(r"\{.*\}", т, re.S)
    д = json.loads(мм.group(0)) if мм else {}
    for v in (д.get("firmy") or []):
        инн = "".join(c for c in str(v.get("inn") or "") if c.isdigit())
        if инн:
            оценки[инн] = v
print(f"оценено {len(оценки)} за {time.time()-t0:.0f}с, ${цена:.5f} "
      f"= ${цена/max(1,len(оценки)):.6f} на компанию")

# ---- предсказывает ли балл исход ----------------------------------------- #
вёдра = {}
with io.open(ВЫХОД, "a", encoding="utf-8") as f:
    for инн, и, _п in работа:
        v = оценки.get(инн) or {}
        б = v.get("ball")
        if б is None:
            continue
        к = "9-10" if б >= 9 else "6-8" if б >= 6 else "3-5" if б >= 3 else "0-2"
        вёдра.setdefault(к, Counter())["всего"] += 1
        вёдра[к]["вышло" if и["вышло"] else "брак"] += 1
        if и["цех_не_подтверждён"]:
            вёдра[к]["цех не подтверждён"] += 1
        f.write(json.dumps({"inn": инн, "имя": и["имя"], "ball": б,
                            "zacepka": v.get("zacepka"),
                            "вышло": и["вышло"]}, ensure_ascii=False) + "\n")
    f.flush()
    os.fsync(f.fileno())

print(f"\n{'балл':>6} {'компаний':>9} {'вышло':>7} {'доля':>7} "
      f"{'цех не подтв.':>14}")
for к in ("9-10", "6-8", "3-5", "0-2"):
    c = вёдра.get(к)
    if not c:
        continue
    доля = c["вышло"] / max(1, c["всего"]) * 100
    print(f"{к:>6} {c['всего']:>9} {c['вышло']:>7} {доля:>6.0f}% "
          f"{c['цех не подтверждён']:>14}")

print("\n== примеры зацепок у лучших ==")
лучшие = sorted(((v.get("ball", 0), инн, v) for инн, v in оценки.items()),
                reverse=True)[:6]
for б, инн, v in лучшие:
    имя = (исходы.get(инн) or {}).get("имя", "")
    print(f"  {б:>2}  {str(имя)[:34]:<34} «{str(v.get('zacepka'))[:52]}»")
print("\n== примеры у худших ==")
худшие = sorted(((v.get("ball", 99), инн, v) for инн, v in оценки.items()))[:6]
for б, инн, v in худшие:
    имя = (исходы.get(инн) or {}).get("имя", "")
    print(f"  {б:>2}  {str(имя)[:34]:<34} {str(v.get('pochemu'))[:44]}")
