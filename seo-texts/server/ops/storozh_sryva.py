# -*- coding: utf-8 -*-
"""Сторож срыва: тревога только когда ответа по сути нет.

Владелец 12.10 включил канал Claude Kiro: он читает кэш промпта (вход в
10 раз дешевле), но сам включает рассуждение, игнорируя thinking=False.
Старый сторож считал срывом «знаков текста меньше, чем токенов выхода» —
при принудительном рассуждении это любой нормальный ответ гейта, и каждый
вызов гонялся до 8 оплаченных повторов без результата.

Новое правило: срыв — когда выход большой, а текста почти нет (меньше
десятой доли знака на токен и не больше 40 знаков). Нормальный ответ с
приложенным рассуждением проходит; молчание в обёртке из рассуждения —
по-прежнему ловится.
"""
import importlib.util as _iu
import io
import os
import py_compile
import shutil
import sys
import time

sys.path.insert(0, r"C:\sender")
ПУТЬ = r"C:\sender\sender\review_lenses.py"
т = io.open(ПУТЬ, encoding="utf-8").read()
СТАР = """    # Живой ответ даёт примерно 2-4 знака на токен. Ниже одного - это молчание
    # в обёртке из рассуждения.
    return len(text or '') < вых
"""
НОВ = """    # ТРЕВОГА ТОЛЬКО НА ПУСТОМ ОТВЕТЕ (владелец 12.10, канал Claude Kiro).
    # Канал сам включает рассуждение, и токенов выхода законно больше знаков
    # текста: «меньше одного знака на токен» стало обычным ответом гейта, и
    # каждый вызов гонялся до 8 оплаченных повторов. Срыв — это когда текста
    # по сути нет: меньше десятой доли знака на токен или не больше 40 знаков.
    длина = len((text or '').strip())
    return длина <= 40 or длина < вых * 0.1
"""
if "ТРЕВОГА ТОЛЬКО НА ПУСТОМ ОТВЕТЕ" in т:
    print("сторож уже переделан")
    print("=== СТОРОЖ: УЖЕ БЫЛ ===")
    sys.exit(0)
if т.count(СТАР) != 1:
    print("якорь не найден (%d)" % т.count(СТАР))
    print("=== СТОРОЖ: НЕ ПРИМЕНЁН ===")
    sys.exit(0)
бэкап = ПУТЬ + ".bak-%d" % int(time.time())
shutil.copy2(ПУТЬ, бэкап)
io.open(ПУТЬ, "w", encoding="utf-8").write(т.replace(СТАР, НОВ))
try:
    py_compile.compile(ПУТЬ, doraise=True)
    сп = _iu.spec_from_file_location("rl_sv", ПУТЬ)
    м = _iu.module_from_spec(сп)
    sys.modules["rl_sv"] = м
    сп.loader.exec_module(м)

    class У:  # noqa: D401 - заглушка usage
        def __init__(s, n):
            s.output_tokens = n

    class М:
        def __init__(s, n):
            s.usage = У(n)

    print("проверка: 3000 ток, JSON 400 зн    -> срыв %s"
          % м._eto_sryv(М(3000), "x" * 400, 2000))
    print("проверка: 3000 ток, 10 зн          -> срыв %s"
          % м._eto_sryv(М(3000), "x" * 10, 2000))
    print("проверка: 18000 ток, 1500 зн       -> срыв %s"
          % м._eto_sryv(М(18000), "x" * 1500, 2000))
    print("проверка: 800 ток (ниже порога)    -> срыв %s"
          % м._eto_sryv(М(800), "", 2000))
    assert not м._eto_sryv(М(3000), "x" * 400, 2000)
    assert м._eto_sryv(М(3000), "x" * 10, 2000)
    assert м._eto_sryv(М(18000), "x" * 1500, 2000)
    print("ПРИМЕНЕНО, бэкап %s" % os.path.basename(бэкап))
    print("=== СТОРОЖ: ПРИМЕНЁН ===")
except Exception as e:  # noqa: BLE001
    shutil.copy2(бэкап, ПУТЬ)
    print("ОТКАТ: %s" % e)
    print("=== СТОРОЖ: ОТКАТ ===")
