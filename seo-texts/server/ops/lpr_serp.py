_EMAIL = re.compile(r'[A-Za-z0-9._%+-]{2,50}@[A-Za-z0-9.-]{2,40}\.[A-Za-z]{2,10}')


def обратный(лимит=25, бюджет=900, воркеров=5, применить_ли=False, тег='back'):
    """По уже записанному человеку ищем ЕГО СТРАНИЦУ с контактом:
    «"Фамилия Имя Отчество" "<компания>"». Профиль на отраслевом портале,
    программа конференции с почтой, карточка спикера."""
    db = EDB.EnrichDB()
    e = db.cx
    ряды = e.execute(
        "SELECT p.inn, p.person, p.post, p.role, COALESCE(c.name,''), "
        "COALESCE(p.phone,''), COALESCE(p.email,'') "
        "FROM people p LEFT JOIN companies c ON c.inn=p.inn "
        "WHERE p.source LIKE 'поиск-ЛПР%' AND COALESCE(p.phone,'')='' "
        "AND COALESCE(p.email,'')='' ORDER BY p.updated_at DESC LIMIT ?",
        (лимит,)).fetchall()
    поток = open(ПОТОК, 'a', encoding='utf-8')
    lock = threading.Lock()
    t0 = time.time()
    сч = {'людей': len(ряды), 'с_выдачей': 0, 'страниц': 0, 'с_телефоном': 0,
          'с_почтой': 0, 'записано_тел': 0, 'записано_почт': 0}
    рез = []

    def один(r):
        if time.time() - t0 > бюджет:
            return
        инн, фио, пост, роль, имя_к, _ph, _em = r
        имя = ядро_имени(имя_к) or имя_к
        q = '"%s" "%s"' % (фио, имя)
        d = серп(q, 'yandex')
        чист = [x for x in d if not мусорный(x['url'])]
        with lock:
            if чист:
                сч['с_выдачей'] += 1
        найдено = []
        фам = фио.split()[0] if фио else ''
        for x in чист[:4]:
            if time.time() - t0 > бюджет:
                break
            html = быстрый_фетч(x['url'])
            if not html or EC._looks_blocked(html):
                continue
            чистый = EC.без_графики(html)
            текст = EC._текст(чистый)
            with lock:
                сч['страниц'] += 1
            if фам and фам.lower()[:7] not in текст.lower():
                continue
            # контакт ищем В ОКРЕСТНОСТИ фамилии, а не по всей странице:
            # иначе в человека уедет телефон приёмной из подвала сайта
            окрестности = []
            for m in re.finditer(re.escape(фам[:7]), текст, re.I):
                окрестности.append(текст[max(0, m.start() - 260):m.start() + 420])
            бл = ' … '.join(окрестности[:6])
            телефоны = [m.group(0) for m in EC.phones_list(бл)]
            почты = [x2 for x2 in _EMAIL.findall(бл) if not EC._is_junk_email(x2)]
            if телефоны or почты:
                найдено.append({'url': x['url'], 'дата': дата_страницы(html, x['url'], текст,
                                                                      x.get('pubdate') or ''),
                                'телефоны': телефоны[:3], 'почты': почты[:3],
                                'кусок': бл[:400]})
        with lock:
            if any(f['телефоны'] for f in найдено):
                сч['с_телефоном'] += 1
            if any(f['почты'] for f in найдено):
                сч['с_почтой'] += 1
        зап = {'inn': инн, 'фио': фио, 'пост': пост, 'роль': роль, 'запрос': q,
               'выдача': len(d), 'чистых': len(чист), 'найдено': найдено,
               'режим': 'back', 'тег': тег, 'ts': int(time.time())}
        with lock:
            поток.write(json.dumps(зап, ensure_ascii=False) + '\n')
            поток.flush()
            os.fsync(поток.fileno())
            рез.append(зап)
        if применить_ли:
            for f in найдено:
                for t in f['телефоны'][:1]:
                    try:
                        if db.add_phone(инн, t, person=фио, role=пост,
                                        source='обратный ход по ФИО',
                                        source_url=f['url']):
                            with lock:
                                сч['записано_тел'] += 1
                    except Exception:  # noqa: BLE001
                        pass
                for m2 in f['почты'][:1]:
                    try:
                        db.add_email(инн, m2, role=пост, person=фио,
                                     source='обратный ход по ФИО', source_url=f['url'])
                        with lock:
                            сч['записано_почт'] += 1
                    except Exception:  # noqa: BLE001
                        pass

    with ThreadPoolExecutor(max_workers=воркеров) as ex:
        list(ex.map(один, ряды))
    поток.close()
    try:
        db.cx.commit()
    except Exception:  # noqa: BLE001
        pass
    итог = {'счётчики': сч, 'оплачено': ЗАПРОСОВ[0],
            'стоимость_руб': round(ЗАПРОСОВ[0] * 0.025, 3),
            'секунд': round(time.time() - t0),
            'примеры': [x for x in рез if x['найдено']][:6]}
    print(json.dumps(итог, ensure_ascii=False)[:9000])
    print(json.dumps({'счётчики': сч, 'оплачено': ЗАПРОСОВ[0]}, ensure_ascii=False))


