_ДАТА_URL = re.compile(r'/(20\d\d)[/\-_.](\d{1,2})(?:[/\-_.](\d{1,2}))?/')
_ДАТА_META = re.compile(
    r'(?:article:published_time|datePublished|publish[-_]?date|itemprop="datePublished")'
    r'[^>]{0,80}?(20\d\d)-(\d{2})-(\d{2})', re.I)
_ДАТА_TIME = re.compile(r'<time[^>]*datetime="(20\d\d)-(\d{2})-(\d{2})', re.I)
_МЕС = {'янв': 1, 'фев': 2, 'мар': 3, 'апр': 4, 'мая': 5, 'май': 5, 'июн': 6,
        'июл': 7, 'авг': 8, 'сен': 9, 'окт': 10, 'ноя': 11, 'дек': 12}
_ДАТА_РУС = re.compile(r'(\d{1,2})\s+([а-яё]{3})[а-яё]*\.?\s+(20\d\d)', re.I)
_ДАТА_ТОЧ = re.compile(r'\b(\d{2})\.(\d{2})\.(20\d\d)\b')


def дата_страницы(html, url, текст='', pubdate=''):
    """meta → <time> → URL → русская дата → дд.мм.гггг → pubDate выдачи."""
    for rx in (_ДАТА_META, _ДАТА_TIME):
        m = rx.search(html or '')
        if m:
            return '%s-%s-%s' % (m.group(1), m.group(2), m.group(3))
    m = _ДАТА_URL.search(url or '')
    if m:
        мес = int(m.group(2))
        if 1 <= мес <= 12:
            return '%s-%02d-%02d' % (m.group(1), мес, int(m.group(3) or 1))
    m = _ДАТА_РУС.search((текст or '')[:2500])
    if m:
        мес = _МЕС.get(m.group(2).lower())
        if мес:
            return '%s-%02d-%02d' % (m.group(3), мес, int(m.group(1)))
    m = _ДАТА_ТОЧ.search((текст or '')[:2500])
    if m:
        return '%s-%s-%s' % (m.group(3), m.group(2), m.group(1))
    m = re.search(r'(20\d\d)-(\d{2})-(\d{2})', pubdate or '')
    if m:
        return m.group(0)
    m = _ДАТА_РУС.search(pubdate or '')
    if m and _МЕС.get(m.group(2).lower()):
        return '%s-%02d-%02d' % (m.group(3), _МЕС[m.group(2).lower()], int(m.group(1)))
    return ''


def возраст_мес(дата):
    if not дата:
        return None
    try:
        import datetime as dt
        d = dt.date(*[int(x) for x in дата.split('-')[:3]])
        return round((dt.date.today() - d).days / 30.44, 1)
    except Exception:  # noqa: BLE001
        return None


def свежесть(дата):
    """Правило владельца: <=24 мес свежий, 24-36 устаревший, >36 НЕ БРАТЬ."""
    в = возраст_мес(дата)
    if в is None:
        return 'дата?'
    if в < 0:
        return 'свежий'
    if в <= 24:
        return 'свежий'
    if в <= 36:
        return 'устаревший'
    return 'старьё'


