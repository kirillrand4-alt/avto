def _сделано(тег, режим):
    """Резюм по durable-потоку: задание раннера могут убить по таймауту, а за
    уже сделанные запросы платить второй раз незачем."""
    было = set()
    if os.path.exists(ПОТОК):
        for line in open(ПОТОК, encoding='utf-8'):
            try:
                r = json.loads(line)
            except Exception:  # noqa: BLE001
                continue
            if r.get('тег') == тег and r.get('режим') == режим:
                было.add(r.get('inn'))
    return было


def набор_запросов(режим, ключи=None):
    """УЗКИЕ запросы по одной должности. Проба на 10 заводах: широкий OR из 13
    должностей дал 5 «людных» сниппетов, узкие по 4 должностям — 17. Скобочный OR
    Яндекс размывает, и цена запроса (0.025₽) того не стоит."""
    роли = [r for r in РОЛИ if not ключи or r[0] in ключи]
    if режим == 'a':
        зап = [(k, '"{n}" "назначен %s"' % тв) for k, _им, тв, _p in роли]
        зап += [('_общ1', '"{n}" "возглавил техническую службу"'),
                ('_общ2', '"{n}" "приступил к обязанностям главного инженера"'),
                ('_общ3', '"{n}" "занял пост технического директора"')]
        return зап
    return [(k, '"{n}" "%s"' % им) for k, им, _тв, _p in роли]


