def применить(файлы):
    """Вход — результат классификации (в песочнице, провайдером):
    {'люди':[{inn, person, post, url, date, свежесть, привязка, quote, режим}]}"""
    люди = []
    for ф in (файлы or '').split(','):
        ф = ф.strip()
        if not ф:
            continue
        путь = ф if os.path.exists(ф) else os.path.join(ХРАН, ф)
        d = json.load(open(путь, encoding='utf-8'))
        люди += d.get('люди') or []
    db = EDB.EnrichDB()
    жур = open(os.path.join(ДРОП, 'lpr_applied.jsonl'), 'a', encoding='utf-8')
    сч = {'на_входе': len(люди), 'записано': 0, 'отсев_старьё': 0,
          'отсев_привязка': 0, 'отсев_пусто': 0, 'компаний': 0, 'с_телефоном': 0}
    комп = set()
    for p in люди:
        инн = str(p.get('inn') or '')
        фио = (p.get('person') or '').strip()
        пост = (p.get('post') or '').strip()
        if not (инн and фио and пост):
            сч['отсев_пусто'] += 1
            continue
        if p.get('привязка') not in ('инн', 'полное_имя', 'ядро'):
            сч['отсев_привязка'] += 1
            continue
        св = p.get('свежесть') or свежесть(p.get('date') or '')
        if св == 'старьё':
            сч['отсев_старьё'] += 1
            continue
        режим = 'A' if (p.get('режим') or '').lower().startswith('a') else 'Б'
        ист = 'поиск-ЛПР:%s' % режим
        if св == 'устаревший':
            ист += '[устарело]'
        elif св == 'дата?':
            ист += '[дата не определена]'
        д = p.get('date') or ''
        try:
            db.upsert_company(инн, name=p.get('company') or '')
        except Exception:  # noqa: BLE001
            pass
        try:
            db.add_person(инн, фио, post=пост, phone=p.get('phone') or '',
                          email=p.get('email') or '', source=ист,
                          source_url=p.get('url') or '',
                          observed_at=д if re.match(r'20\d\d-\d\d-\d\d', д) else '')
            сч['записано'] += 1
            комп.add(инн)
            if p.get('phone'):
                сч['с_телефоном'] += 1
            жур.write(json.dumps(p, ensure_ascii=False) + '\n')
        except Exception as ex:  # noqa: BLE001
            жур.write(json.dumps({'ошибка': str(ex)[:120], 'зап': p},
                                 ensure_ascii=False) + '\n')
        try:
            db.mark_stage(инн, 'lpr_person', (пост or '')[:60])
        except Exception:  # noqa: BLE001
            pass
    сч['компаний'] = len(комп)
    жур.flush()
    os.fsync(жур.fileno())
    жур.close()
    итог = {'записано': сч, 'ИЗ_БАЗЫ': отчёт_из_базы(db)}
    print(json.dumps(итог, ensure_ascii=False)[:9000])
    print(json.dumps(итог, ensure_ascii=False)[:9000])


