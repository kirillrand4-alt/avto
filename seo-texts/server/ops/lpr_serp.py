def отчёт_из_базы(db=None):
    db = db or EDB.EnrichDB()
    e = db.cx
    q = "source LIKE 'поиск-ЛПР%'"
    из = {}
    из['людей'] = e.execute('SELECT count(*) FROM people WHERE %s' % q).fetchone()[0]
    из['компаний'] = e.execute(
        'SELECT count(DISTINCT inn) FROM people WHERE %s' % q).fetchone()[0]
    техроли = ','.join("'%s'" % r for r in EDB.EnrichDB.TECH_ROLES)
    из['техЛПР'] = e.execute(
        'SELECT count(*) FROM people WHERE %s AND role IN (%s)' % (q, техроли)).fetchone()[0]
    из['техЛПР_компаний'] = e.execute(
        'SELECT count(DISTINCT inn) FROM people WHERE %s AND role IN (%s)'
        % (q, техроли)).fetchone()[0]
    из['по_роли'] = dict(e.execute(
        'SELECT role, count(*) FROM people WHERE %s GROUP BY role ORDER BY 2 DESC' % q
    ).fetchall())
    из['по_источнику'] = dict(e.execute(
        'SELECT source, count(*) FROM people WHERE %s GROUP BY source ORDER BY 2 DESC' % q
    ).fetchall())
    из['с_телефоном'] = e.execute(
        "SELECT count(*) FROM people WHERE %s AND COALESCE(phone,'')!=''" % q).fetchone()[0]
    из['с_почтой'] = e.execute(
        "SELECT count(*) FROM people WHERE %s AND COALESCE(email,'')!=''" % q).fetchone()[0]
    из['телефонов_обратным_ходом'] = e.execute(
        "SELECT count(*) FROM phone_contacts WHERE source='обратный ход по ФИО'"
    ).fetchone()[0]
    из['почт_обратным_ходом'] = e.execute(
        "SELECT count(*) FROM emails WHERE source='обратный ход по ФИО'").fetchone()[0]
    из['заместителей'] = e.execute(
        "SELECT count(*) FROM people WHERE %s AND (post LIKE '%%аместител%%' "
        "OR post LIKE '%%Зам.%%' OR post LIKE '%%зам.%%')" % q).fetchone()[0]
    из['примеры'] = [{'inn': r[0], 'фио': r[1], 'пост': r[2], 'роль': r[3],
                      'источник': r[4], 'дата': r[5], 'url': (r[6] or '')[:120]}
                     for r in e.execute(
        'SELECT inn, person, post, role, source, observed_at, source_url '
        'FROM people WHERE %s ORDER BY observed_at DESC LIMIT 12' % q).fetchall()]
    return из


