def упаковать(тег, режим=None):
    все, видел = [], set()
    if os.path.exists(ПОТОК):
        for line in open(ПОТОК, encoding='utf-8'):
            try:
                r = json.loads(line)
            except Exception:  # noqa: BLE001
                continue
            if r.get('тег') != тег:
                continue
            if режим and r.get('режим') != режим:
                continue
            k = (r.get('inn'), r.get('режим'))
            if k in видел:
                continue
            видел.add(k)
            все.append(r)
    имя_ф = 'lpr_batch_%s%s.json.gz' % (тег, ('_' + режим) if режим else '')
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode='wb') as z:
        z.write(json.dumps(все, ensure_ascii=False).encode('utf-8'))
    with open(os.path.join(ХРАН, имя_ф), 'wb') as f:
        f.write(buf.getvalue())
        f.flush()
        os.fsync(f.fileno())
    return {'пачка': имя_ф, 'записей': len(все), 'байт_gz': len(buf.getvalue()),
            'страниц': sum(len(r.get('страницы') or []) for r in все)}


