# -*- coding: utf-8 -*-
"""Отфильтровать вердикты провайдера перед записью в базу.

Владелец: «только с выборочной перепроверкой». Проверка показала, что правило,
которое Я САМ вписал в промпт («заместитель = роль общий»), калечит именно тех,
ради кого база собиралась. Модель его исполнила буквально и снесла в «общий»:
  — «заместитель Генерального директора – главный инженер» — это И ЕСТЬ главный
    инженер завода, ранг зам-гендира сверху делает его СИЛЬНЕЕ, а не слабее;
  — «и.о. заместителя гендиректора по техническому развитию» — и.о. значит, что
    человек эту должность сейчас и занимает;
  — «руководитель филиала АО Криогенмаш в Самаре» — руководитель площадки, ЛПР;
  — «заместитель главного инженера» — технарь, которого продажнику как раз
    проще застать, чем самого главного.
Плюс модель дала два РАЗНЫХ вердикта на одну и ту же строку «заместитель
директора по производству» (нач.производства и общий) — признак, что в этой
зоне ей верить нельзя.

Поэтому: понижение до нетехнической роли отклоняется, если в должности есть
техническое ядро, приставка «и.о.» или руководство площадкой. Остальное —
принимается: «инженер по комплектации» это снабжение, «инженер технического
отдела» это рядовой, «бывший главный инженер» это бывший.
"""
import json
import re

ТЕХ = {'гл.инженер', 'гл.энергетик', 'гл.механик', 'гл.технолог',
       'гл.конструктор', 'техдиректор', 'нач.производства', 'нач.цеха',
       'АСУ/КИПиА'}

# техническое ядро должности: понижать такого до «общий» нельзя
_ЯДРО = re.compile(
    r'главн\w*\s+(?:инженер|конструктор|энергетик|механик|технолог)'
    r'|по\s+техни\w*|техническ\w+\s+(?:директор|развити)'
    r'|по\s+производству|производственн\w+',
    re.I)
_ИО = re.compile(r'\bи\.?\s?о\.?\s|\bисполняющ', re.I)
_ПЛОЩАДКА = re.compile(r'руководител\w*\s+филиала|директор\w*\s+филиала'
                       r'|управляющ\w+\s+(?:филиалом|заводом|площадкой)', re.I)
# «бывший» бьёт всё: должность неактуальна
_БЫВШИЙ = re.compile(r'\bбывш', re.I)


def решение(x):
    post = (x.get('post') or '').strip()
    было, стало = x['role'], x['новая']
    if _БЫВШИЙ.search(post):
        return True, 'бывший сотрудник — должность неактуальна'
    if стало in ТЕХ:
        return True, 'повышение в техническую роль'
    if было not in ТЕХ and стало not in ТЕХ:
        # обе роли нетехнические — цена ошибки мала, но щадим руководство площадки
        if _ПЛОЩАДКА.search(post):
            return False, 'руководитель площадки — ЛПР, не «общий»'
        return True, 'перестановка внутри нетехнических'
    # понижение ИЗ технической роли — самое опасное, тут и режем
    if _ИО.search(post):
        return False, 'и.о. = человек занимает должность сейчас'
    if _ПЛОЩАДКА.search(post):
        return False, 'руководитель площадки — ЛПР'
    if _ЯДРО.search(post):
        return False, 'в должности техническое ядро: «заместитель» понижает ранг, а не профиль'
    return True, 'технического ядра в должности нет'


def main():
    v = json.load(open('roles_verdicts.json', encoding='utf-8'))
    прим, откл = [], []
    for x in v:
        ок, почему = решение(x)
        (прим if ок else откл).append({**x, 'вердикт_фильтра': почему})
    json.dump(прим, open('roles_apply.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)
    json.dump(откл, open('roles_rejected.json', 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

    было_тех = sum(1 for x in json.load(open('roles_dump.json', encoding='utf-8'))['люди']
                   if x['role'] in ТЕХ)
    минус = sum(1 for x in прим if x['role'] in ТЕХ and x['новая'] not in ТЕХ)
    плюс = sum(1 for x in прим if x['role'] not in ТЕХ and x['новая'] in ТЕХ)
    print(f'вердиктов модели: {len(v)}; принято: {len(прим)}; отклонено: {len(откл)}')
    print(f'технических: было {было_тех}, станет {было_тех - минус + плюс} '
          f'(-{минус}/+{плюс})')
    print('\n--- ОТКЛОНЕНО (модель хотела снести, я не даю) ---')
    for x in откл:
        print(f'  «{x["post"][:66]}»\n      {x["role"]} -x-> {x["новая"]}   ({x["вердикт_фильтра"]})')
    print('\n--- ПРИНЯТО, выборочно каждое 2-е ---')
    for x in прим[::2]:
        print(f'  «{x["post"][:60]}»  {x["role"]} -> {x["новая"]}')


if __name__ == '__main__':
    main()
