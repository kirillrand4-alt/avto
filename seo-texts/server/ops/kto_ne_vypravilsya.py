# -*- coding: utf-8 -*-
"""Почему письмо не выправилось: наша ли это компания вообще.

После переписывания по претензиям осталось ведро «всё ещё не годно». Их
надо разделить: одно дело — модель не справилась с формулировкой, другое —
компании вообще нельзя писать по нашим направлениям. Второе переписыванием
не лечится, такие надо снимать с причиной.
"""
import io
import json
import re
import sys
from collections import Counter

Ж = r"C:\sender\_ops\perepisano-po-recenzii.jsonl"
# Признаки, что дело в САМОЙ КОМПАНИИ, а не в словах письма.
НЕ_НАША = re.compile(
    r'(?i)(не производ|нет производств|торгов\w*\s+(компан|организац|деятельн)|'
    r'перепрода|дистрибь|розничн|аренд\w*\s+(техник|оборудован|спецтехник)|'
    r'услуг\w*\s+(по|компан)|логистик|транспортн\w*\s+компан|'
    r'проектн\w*\s+организац|монтажн\w*\s+организац|'
    r'сайт\w*\s+не\s+(содержит|говорит|подтвержда)\w*\s+(о\s+)?производств)')

записи = []
for s in io.open(Ж, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                             # noqa: BLE001
        continue
    if "не годно" in str(z.get("итог") or ""):
        записи.append(z)

вёдра = Counter()
примеры = {}
для_скипа = []
for z in записи:
    пр = z.get("pretenzii") or []
    т = "; ".join(str(x) for x in пр) if isinstance(пр, list) else str(пр)
    if НЕ_НАША.search(т):
        вёдра["НЕ НАША КОМПАНИЯ (снять)"] += 1
        для_скипа.append((z["id"], т[:200]))
    else:
        вёдра["слова письма (можно ещё раз)"] += 1
    к = "НЕ НАША КОМПАНИЯ (снять)" if НЕ_НАША.search(т) else "слова письма (можно ещё раз)"
    if к not in примеры:
        примеры[к] = f"#{z['id']} {т[:190]}"

print(f"записей «после правки не годно»: {len(записи)}\n")
for в, n in вёдра.most_common():
    print(f"  {n:>4}  {в}")
    print(f"        {примеры.get(в,'')}")

print("\n== кандидаты на снятие (первые 12) ==")
for i, т in для_скипа[:12]:
    print(f"  #{i}: {т[:150]}")
io_out = r"C:\sender\_ops\na-skip-ne-nasha.json"
with io.open(io_out, "w", encoding="utf-8") as f:
    json.dump([i for i, _ in для_скипа], f)
print(f"\nсписок id сохранён: {io_out} ({len(для_скипа)} шт)")
