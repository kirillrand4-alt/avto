"""Где вердикт пересуда спорит с собственным объяснением.

Замечено на «Сити кофе» и «Звук и свет»: вердикт «покупатель», а
причина рядом — «не наш сегмент», «нет операций, требующих сжатый
воздух». Это след того, что линзы разошлись: правило гейта режет только
при обоюдном отказе, и любое одиночное «покупатель» перевешивает. Для
СНЯТИЯ это правильно (не режем на спорном), но записывать в кэш
«покупатель» — значит утверждать то, чего линзы не говорили.
"""
import re
import sqlite3
from collections import Counter

ОТРИЦАНИЯ = (
    "не наш", "не требует", "нет операций", "ничтожен", "не нужен",
    "не использует", "нет производства", "не покупател", "не подходит",
    "нет потребности", "не критич", "нет цех",
)

c = sqlite3.connect(r"C:\sender\sender.db")
c.row_factory = sqlite3.Row
ряды = c.execute(
    "SELECT inn, verdict, COALESCE(chem,'') chem, COALESCE(pochemu,'') pochemu, "
    "       (SELECT company_name FROM recipients WHERE inn=target_verdicts.inn "
    "        LIMIT 1) имя "
    "FROM target_verdicts WHERE source='пересуд с паспортом'").fetchall()

счёт = Counter()
спорные = []
for r in ряды:
    в = str(r["verdict"])
    текст = (str(r["pochemu"]) + " " + str(r["chem"])).lower()
    отрицает = any(о in текст for о in ОТРИЦАНИЯ)
    счёт[(в, "объяснение против" if отрицает else "объяснение за")] += 1
    if в == "покупатель" and отрицает:
        спорные.append((str(r["inn"]), str(r["имя"] or "")[:40],
                        str(r["pochemu"])[:150]))

print(f"пересужено: {len(ряды)}")
for (в, k), n in счёт.most_common():
    print(f"  {n:>4}  {в:<16} {k}")
print(f"\nвердикт «покупатель» при отрицающем объяснении: {len(спорные)}")
for инн, имя, поч in спорные[:25]:
    print(f"  {инн}  {имя:<40} {поч}")
