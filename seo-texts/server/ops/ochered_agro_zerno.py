def _слово(т):
    if not т:
        return т
    if т.upper() != т:                      # уже в смешанном регистре
        return т
    ядро = "".join(c for c in т if c.isalpha())
    if т.lower() in ("им.", "имени"):
        return т.lower()
    if len(ядро) <= 3 or not (set(ядро) & ГЛАСНЫЕ):
        return т                            # аббревиатура
    return "-".join(ч[:1] + ч[1:].lower() for ч in т.split("-"))


def название(сырое):
    """«ООО "ФАКЕЛ"» → «Факел»; «СХП "БИС"» → «БИС»; «АГРОФИРМА "ЮГ"» → «Агрофирма ЮГ»."""
    т = " ".join(str(сырое or "").replace("«", '"').replace("»", '"').split())
    ниж = т.lower()
    for ф in ФОРМЫ:
        if ниж.startswith(ф + " ") or ниж.startswith(ф + '"'):
            т = т[len(ф):].strip()
            break
    т = т.strip('" \t')
    т = " ".join(т.replace('"', " ").split())
    return " ".join(_слово(с) for с in т.split(" ")).strip()


