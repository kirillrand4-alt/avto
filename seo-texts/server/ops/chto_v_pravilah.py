"""Показать префикс по разделам: что в нём лежит и сколько стоит каждый кусок.

Владелец спросил, что значит «урезать префикс». Ответ должен быть не
рассуждением, а самим текстом: вот разделы, вот их размер, вот цена куска
в день при 4500 вызовах.
"""
import sys

sys.path.insert(0, r"C:\sender\sender")
sys.path.insert(0, r"C:\sender")

from sender.ai_letter import RULES_BY_DIVISION, facts_block, load_facts  # noqa: E402

ВЫЗОВОВ_В_ДЕНЬ = 4496
СТАВКА = 6.25 / 1_000_000        # запись в кэш: $5 × 1.25 за 1M
ЗНАКОВ_НА_ТОКЕН = 1.8


def цена(знаков):
    return знаков / ЗНАКОВ_НА_ТОКЕН * СТАВКА * ВЫЗОВОВ_В_ДЕНЬ


правила = RULES_BY_DIVISION.get("kc", "")
факты = facts_block(load_facts(division="kc"), "kc")
print("правила: %d знаков, ~$%.0f в день" % (len(правила), цена(len(правила))))
print("факты:   %d знаков, ~$%.0f в день" % (len(факты), цена(len(факты))))

print("\n=== РАЗДЕЛЫ БЛОКА ПРАВИЛ ===")
# заголовком считаем строку из ЗАГЛАВНЫХ букв или начинающуюся с цифры-точки
разделы, текущий, буфер = [], "начало", []
for с in правила.split("\n"):
    голая = с.strip()
    заголовок = (голая and (голая.isupper() and len(голая) > 6)
                 or (len(голая) > 3 and голая[0].isdigit() and голая[1] in ".)"))
    if заголовок:
        разделы.append((текущий, "\n".join(буфер)))
        текущий, буфер = голая[:70], []
    else:
        буфер.append(с)
разделы.append((текущий, "\n".join(буфер)))
разделы.sort(key=lambda п: -len(п[1]))
for имя, текст in разделы[:22]:
    print("  %6d знаков  ~$%5.0f/день  %s"
          % (len(текст), цена(len(текст)), имя[:66]))
print("  --- разделов всего: %d" % len(разделы))

print("\n=== ПЕРВЫЕ 40 СТРОК ПРАВИЛ (как они выглядят) ===")
for с in правила.split("\n")[:40]:
    print("  | %s" % с[:120])

print("\n=== БЛОК ФАКТОВ ЦЕЛИКОМ (первые 30 строк) ===")
for с in факты.split("\n")[:30]:
    print("  | %s" % с[:120])
