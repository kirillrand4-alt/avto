# -*- coding: utf-8 -*-
"""Одна ли модель за именами opus-4-6/4-7/4-8/5 у шлюза.

Способ прямой: одинаковый промпт каждому имени, дважды, и сверка ответа
побайтово. Совпадение текстов у ДВУХ РАЗНЫХ имён при живой выборке -
событие исчезающе редкое, поэтому идентичность читается как один бэкенд.
Второй прогон того же имени показывает, детерминирован ли он вообще: если
одно имя само себе отвечает по-разному, а два имени - одинаково, вывод
про общий бэкенд только крепче.

Смотрим ещё и на счётчики токенов: у одного бэкенда вход на одинаковом
промпте совпадает точно.
"""
import hashlib
import sys

sys.path.insert(0, r"C:\sender")
import gen_provider                                           # noqa: E402

ПРОМПТ = ("Придумай ровно пять названий для промышленного фотосепаратора. "
          "Каждое - одно слово, кириллицей, без пояснений. "
          "Ответь только списком через запятую.")
ИМЕНА = ["claude-opus-4-6", "claude-opus-4-7",
         "claude-opus-4-8", "claude-opus-5"]

итог = {}
for имя in ИМЕНА:
    for попытка in (1, 2):
        try:
            м = gen_provider._raw_stream(
                [{"role": "user", "content": ПРОМПТ}], имя, 300,
                thinking=False)
            т = "".join(getattr(b, "text", "")
                        for b in getattr(м, "content", []) or []).strip()
            u = getattr(м, "usage", None)
            вх = getattr(u, "input_tokens", 0) if u else 0
            вых = getattr(u, "output_tokens", 0) if u else 0
        except Exception as ex:                               # noqa: BLE001
            print(f"{имя} #{попытка}: СБОЙ {str(ex)[:90]}")
            continue
        х = hashlib.sha256(т.encode()).hexdigest()[:12]
        итог.setdefault(х, []).append(f"{имя}#{попытка}")
        print(f"{имя} #{попытка}: sha={х} вх={вх} вых={вых}")
        print(f"    {т[:150]}")

print("\nгруппы одинаковых ответов:")
for х, кто in итог.items():
    print(f"  {х}: {', '.join(кто)}")
общие = [к for к in итог.values()
         if len({и.split('#')[0] for и in к}) > 1]
if общие:
    for группа in общие:
        имена = sorted({и.split('#')[0] for и in группа})
        print(f"СОВПАЛИ РАЗНЫЕ ИМЕНА: {', '.join(имена)} — один бэкенд")
else:
    print("совпадений между разными именами нет — модели отвечают по-разному")
