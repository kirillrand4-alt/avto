# -*- coding: utf-8 -*-
"""Сколько вызовов модели уходит на письмо — до и после удешевления.

Журнал перегенерации пишет вызовов на каждое письмо с 18.08. Записи без
этого поля сделаны СТАРЫМ конвейером (две линзы, три варианта, всё опусом),
записи с полем - новым. Сравниваем их напрямую.
"""
import io
import json
from collections import Counter

Ж = r"C:\sender\_ops\peregeneraciya-braka.jsonl"
старые = новые = 0
вызовы = []
исходы = Counter()
for s in io.open(Ж, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if "вызовов" in z and z.get("вызовов") is not None:
        новые += 1
        вызовы.append(int(z["вызовов"]))
        исходы["ок" if z.get("ок") else str(z.get("почему"))[:40]] += 1
    else:
        старые += 1
print(f"записей всего: {старые + новые}")
print(f"  старым конвейером (без счётчика): {старые}")
print(f"  новым конвейером:                {новые}")
if вызовы:
    вызовы.sort()
    print(f"\nвызовов модели на письмо (новый конвейер):")
    print(f"  медиана {вызовы[len(вызовы)//2]}, минимум {вызовы[0]}, "
          f"максимум {вызовы[-1]}, среднее {sum(вызовы)/len(вызовы):.1f}")
    print(f"  для сравнения: старый конвейер по журналу партии — медиана 10-11")
    print(f"  исходы: {dict(исходы.most_common(5))}")
else:
    print("\nновых записей пока нет — прогон ещё идёт")
