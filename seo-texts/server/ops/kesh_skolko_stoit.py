# -*- coding: utf-8 -*-
"""Во что обходится отсутствие кэша: считаем по сегодняшнему журналу.

Ставки Opus 4.8 у Anthropic: $5 за 1M входа, $25 за 1M выхода; запись в
кэш 1.25 ставки входа, чтение 0.1. У шлюза кэша нет вовсе (доказано:
поле «запись» приходит даже когда cache_control не отправлялся), поэтому
префикс оплачивается целиком на каждом вызове.
"""
import io
import json
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ВХОД = 5.0 / 1_000_000
ВЫХОД = 25.0 / 1_000_000

записи = []
for с in io.open(ЖУРНАЛ, encoding="utf-8"):
    с = с.strip()
    if с:
        try:
            записи.append(json.loads(с))
        except Exception:  # noqa: BLE001
            pass
print("ключи записи: %s" % ", ".join(sorted(записи[-1].keys())))

# сегодняшние = те, что легли последними; берём по review_id/created за прогон
поля = Counter()
for з in записи:
    for к in з:
        поля[к] += 1
print("\nполя и сколько раз встречаются (топ-20):")
for к, н in поля.most_common(20):
    print("  %-24s %d" % (к, н))

# суммируем по последним 583 записям с ценой (сегодняшние два прогона)
сцен = [з for з in записи if з.get("цена_$") is not None]
сег = сцен[-583:]
итог = Counter()
for з in сег:
    for к in ("вход", "выход", "вход_кэш_запись", "вход_кэш_чтение",
              "вызовов", "вызовов_проверок"):
        итог[к] += int(з.get(к) or 0)
    итог["цена_журнала"] += float(з.get("цена_$") or 0)

print("\n=== СУММА ПО %d ПИСЬМАМ ===" % len(сег))
for к in ("вход", "вход_кэш_запись", "вход_кэш_чтение", "выход",
          "вызовов", "вызовов_проверок"):
    print("  %-20s %12d" % (к, итог[к]))
print("  %-20s %12.2f $" % ("цена по журналу", итог["цена_журнала"]))

вх_всего = итог["вход"] + итог["вход_кэш_запись"] + итог["вход_кэш_чтение"]
без_кэша = вх_всего * ВХОД + итог["выход"] * ВЫХОД
print("\n=== ЕСЛИ БЫ ЭТО ШЛО ЧЕРЕЗ ОФИЦИАЛЬНЫЙ API ===")
print("  входных токенов всего: %d" % вх_всего)
print("  без кэша:            %8.2f $" % без_кэша)

# с кэшем: префикс пишется ОДИН раз на партию, дальше читается
префикс_на_вызов = (итог["вход_кэш_запись"] /
                    max(1, итог["вызовов"] + итог["вызовов_проверок"]))
вызовов = итог["вызовов"] + итог["вызовов_проверок"]
# грубо: 2 записи (генерация+верификатор) на всю партию, остальное чтение
запись_раз = префикс_на_вызов * 2
чтение = итог["вход_кэш_запись"] - запись_раз
с_кэшем = ((итог["вход"] + итог["вход_кэш_чтение"]) * ВХОД
           + запись_раз * ВХОД * 1.25
           + чтение * ВХОД * 0.1
           + итог["выход"] * ВЫХОД)
print("  с работающим кэшем:  %8.2f $" % с_кэшем)
print("  разница:             %8.2f $ (%.0f%%)"
      % (без_кэша - с_кэшем,
         100.0 * (без_кэша - с_кэшем) / без_кэша if без_кэша else 0))
print("\n  вызовов всего: %d, префикс на вызов ~%.0f токенов"
      % (вызовов, префикс_на_вызов))
print("  доля префикса во входе: %.1f%%"
      % (100.0 * итог["вход_кэш_запись"] / вх_всего if вх_всего else 0))
