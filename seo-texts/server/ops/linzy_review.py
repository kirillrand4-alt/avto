def провайдер(промпт, максимум=4000, попыток=3):
    key = os.environ.get('PROVIDER_API_KEY', '')
    if not key:
        return '', 'нет ключа'
    base = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
    тело = json.dumps({'model': 'claude-fable-5', 'max_tokens': максимум,
                       'stream': True,
                       'messages': [{'role': 'user', 'content': промпт}]},
                      ensure_ascii=False).encode('utf-8')
    for п in range(попыток):
        куски = []
        try:
            req = urllib.request.Request(
                base + '/v1/messages', data=тело, method='POST',
                headers={'x-api-key': key, 'anthropic-version': '2023-06-01',
                         'content-type': 'application/json',
                         'accept': 'text/event-stream',
                         'User-Agent': 'curl/8.5.0'})
            with urllib.request.urlopen(req, timeout=300) as r:
                for сыр in r:
                    с = сыр.decode('utf-8', 'replace').strip()
                    if not с.startswith('data:'):
                        continue
                    try:
                        ev = json.loads(с[5:].strip())
                    except Exception:  # noqa: BLE001
                        continue
                    if ev.get('type') == 'content_block_delta':
                        куски.append((ev.get('delta') or {}).get('text', ''))
            текст = ''.join(куски)
            if текст.strip():
                return текст, ''
            # шлюз периодически отдаёт только ping-кадры — это не пустой ответ
            time.sleep(4 * (п + 1))
        except Exception as ex:  # noqa: BLE001
            частично = ''.join(куски)
            if len(частично) > 400:
                return частично, f'оборвано: {type(ex).__name__}'
            time.sleep(4 * (п + 1))
    return '', 'шлюз не ответил за 3 попытки'


def куски_документов(предел=42000):
    """Документы целиком, если влезают; иначе по частям с сохранением заголовков."""
    из = []
    for путь, метка in ДОКИ:
        try:
            т = open(путь, encoding='utf-8', errors='replace').read()
        except Exception as ex:  # noqa: BLE001
            из.append((метка, f'[НЕ ПРОЧИТАН: {type(ex).__name__}]'))
            continue
        if len(т) <= предел:
            из.append((метка, т))
            continue
        # режем по разделам верхнего уровня, чтобы не рвать таблицы посередине
        части, тек = [], ''
        for строка in т.splitlines(keepends=True):
            if строка.startswith('#') and len(тек) > предел * 0.6:
                части.append(тек)
                тек = строка
            else:
                тек += строка
        if тек:
            части.append(тек)
        for i, ч in enumerate(части, 1):
            из.append((f'{метка} (часть {i} из {len(части)})', ч))
    return из


def линза(ключ):
    имя, задача = ЛИНЗЫ[ключ]
    куски = куски_документов()
    # каждой линзе показываем ВСЕ документы, но по одному куску за вызов:
    # шлюз рвёт длинный поток, а сводить находки будем отдельным вызовом
    находки = []

    def один(пара):
        метка, текст = пара
        промпт = (ОБЩЕЕ + '\n\n' + задача
                  + f'\n\n=== ДОКУМЕНТ: {метка} ===\n' + текст
                  + '\n\n=== КОНЕЦ ДОКУМЕНТА ===\n\n'
                  'Найди в ЭТОМ документе места по своей линзе. Если для вывода '
                  'нужен другой документ, которого сейчас нет перед глазами, — '
                  'так и напиши: «нужна сверка с <какой>». Кратко, по делу.')
        текст_ответа, ош = провайдер(промпт)
        return {'линза': имя, 'документ': метка, 'ответ': текст_ответа,
                'ошибка': ош}

    with ThreadPoolExecutor(max_workers=4) as пул:
        for r in пул.map(один, куски):
            находки.append(r)
            with open(ВЫХОД, 'a', encoding='utf-8') as f:
                f.write(json.dumps(r, ensure_ascii=False) + '\n')
                f.flush()
                os.fsync(f.fileno())

    # сводка: отдаём модели ЕЁ ЖЕ находки и просим отсеять пустое и повторы
    сырое = '\n\n'.join(f'--- {x["документ"]} ---\n{x["ответ"][:3000]}'
                        for x in находки if (x['ответ'] or '').strip())
    свод, ош = провайдер(
        ОБЩЕЕ + '\n\n' + задача + '\n\nНиже ТВОИ ЖЕ находки по отдельным '
        'документам. Сведи их: выкинь пустое и повторы, отбрось то, что при '
        'взгляде на всю картину оказалось не находкой, и оставь только то, что '
        'реально надо править. Отсортируй по важности. Для каждой находки: где, '
        'что не так, как надо.\n\n' + сырое[:60000], максимум=6000)
    return {'линза': имя, 'свод': свод, 'ошибка': ош,
            'кусков': len(куски),
            'ответов_непустых': sum(1 for x in находки if (x['ответ'] or '').strip())}


