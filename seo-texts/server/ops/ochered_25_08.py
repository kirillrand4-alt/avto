# -*- coding: utf-8 -*-
"""Очередь генерации 25.08: 700 лучших Meyer, затем 2300 КЦ. Модель — sonnet.

Команда владельца: «давай соннет, сначала лучших мейер 700 штук, потом
2300 кц». Соннет выбран не наугад: по замеру он даёт 87% годных против 65%
у опуса при цене $0.23 против $0.46 за годное письмо.

Внутри блока partiya_gen сам ставит вперёд компании с самым полным
паспортом сайта, а среди равных — именные адреса выше ролевых. Блоки идут
подряд одним процессом: резюм по журналу исключает уже написанное, поэтому
второй блок продолжает, а не повторяет.

Запускать отцеплённо: pustit_otceplenno.py ochered_25_08.py
"""
import io
import json
import os
import subprocess
import time

ПИТОН = r"C:\Program Files\Python311\python.exe"
КАТАЛОГ = r"C:\sender\_ops"
ОТЧЁТ = os.path.join(КАТАЛОГ, "ochered-25-08.jsonl")

# (потолок писем, направление, лимит секунд на блок)
БЛОКИ = [(700, "meyer", 18000), (2300, "kc", 54000)]
ПОРОГ = "porog=2.50"      # ЛАТИНИЦЕЙ И БЕЗ ДЕФИСОВ: разбор берёт только
                          # «имя=значение», кириллические ключи не переживают
                          # дорогу через PowerShell Start-Process.
МОДЕЛЬ = "model=claude-sonnet-4-6"


def записать(строка):
    """Durable: итог блока ложится на сервер сразу, с fsync."""
    with io.open(ОТЧЁТ, "a", encoding="utf-8") as ф:
        ф.write(json.dumps(строка, ensure_ascii=False) + "\n")
        ф.flush()
        os.fsync(ф.fileno())


записать({"этап": "старт", "блоков": len(БЛОКИ),
          "писем_всего": sum(б[0] for б in БЛОКИ),
          "модель": МОДЕЛЬ, "ts": time.time()})

for н, (потолок, направление, лимит) in enumerate(БЛОКИ, 1):
    начало = time.time()
    лог = os.path.join(КАТАЛОГ, "ochered2508-blok%d-%s.log" % (н, направление))
    print("\n=== БЛОК %d/%d: %d писем %s (лимит %d с) ==="
          % (н, len(БЛОКИ), потолок, направление.upper(), лимит), flush=True)
    аргументы = [ПИТОН, os.path.join(КАТАЛОГ, "partiya_gen.py"),
                 str(потолок), str(лимит), направление, "0", ПОРОГ, МОДЕЛЬ]
    записать({"этап": "блок_старт", "блок": н, "потолок": потолок,
              "направление": направление, "ts": time.time()})
    with io.open(лог, "w", encoding="utf-8") as ф:
        код = subprocess.call(аргументы, stdout=ф, stderr=subprocess.STDOUT,
                              cwd=КАТАЛОГ)
    итог = ""
    try:
        строки = io.open(лог, encoding="utf-8", errors="replace").readlines()
        итог = next((с.strip() for с in reversed(строки)
                     if с.startswith("итог:")),
                    строки[-1].strip() if строки else "")
    except Exception as e:  # noqa: BLE001
        итог = "лог не прочитан: %s" % e
    прошло = time.time() - начало
    print("  блок %d кончился за %.0f мин, код %d | %s"
          % (н, прошло / 60.0, код, итог), flush=True)
    записать({"этап": "блок_конец", "блок": н, "код": код,
              "минут": round(прошло / 60.0, 1), "итог": итог, "ts": time.time()})

записать({"этап": "конец", "ts": time.time()})
print("\nвсе блоки отработаны", flush=True)
