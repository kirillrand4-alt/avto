# -*- coding: utf-8 -*-
"""За что 698 компаний выбыли «по трём попыткам» — и стоит ли их вернуть.

Попытка это один заход генератора на компанию. Три неудачных подряд — и
компания откладывается: каждая стоит денег, а бесконечно биться об одну и
ту же нечего. Считаем по журналу, чем именно кончались эти попытки: если
причина в старом промпте или в разовом сбое шлюза, компанию можно вернуть,
а если сайт не подтверждает профиль — незачем.
"""
import io
import json
import os
from collections import Counter, defaultdict

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
попыток = Counter()
готово = set()
причины = defaultdict(list)
имена = {}
когда = defaultdict(list)

for с in io.open(ЖУРНАЛ, encoding="utf-8", errors="replace"):
    if not с.startswith("{"):
        continue
    try:
        з = json.loads(с)
    except Exception:  # noqa: BLE001
        continue
    инн = str(з.get("inn") or "")
    if not инн:
        continue
    if з.get("этап") == "отмена_попытки":
        попыток[инн] = max(0, попыток[инн] - 1)
        continue
    if з.get("этап") != "итог":
        попыток[инн] += 1
    if з.get("ок") or з.get("тело"):
        готово.add(инн)
    if з.get("имя"):
        имена[инн] = з["имя"]
    п = з.get("почему") or з.get("брак") or з.get("этап")
    if п and not з.get("ок"):
        причины[инн].append(str(п))

выбыли = [и for и, н in попыток.items() if н >= 3 and и not in готово]
print("компаний с тремя и более попытками без письма: %d" % len(выбыли))
print("(для сравнения: у кого письмо всё-таки вышло — %d)" % len(готово))


def куча(п):
    п = str(п or "").lower()
    if "403" in п or "баланс" in п or "quota" in п or "rate" in п:
        return "сбой шлюза (не вина компании)"
    if "нет json" in п or "не разобрал" in п or "срыв" in п or "таймаут" in п:
        return "срыв разбора ответа модели"
    if "сайт не подтверждает" in п or "профил" in п:
        return "сайт не подтверждает профиль"
    if "направлени" in п:
        return "не то направление"
    if "линза" in п or "правило" in п or "человечн" in п or "реклама" in п:
        return "линза забраковала текст"
    if "перенаправ" in п or "корпоратив" in п or "зачин" in п:
        return "канон письма не сложился"
    return "прочее: " + п[:46]


свод = Counter()
примеры = defaultdict(list)
for и in выбыли:
    последняя = причины[и][-1] if причины[и] else ""
    к = куча(последняя)
    свод[к] += 1
    if len(примеры[к]) < 3:
        примеры[к].append("%s — %s" % (имена.get(и, и), последняя[:70]))

# Мелочь сводим в одну строку: полсотни разных «цех не подтверждён сайтом:
# пневмоинструмент, продувк» — это одна и та же причина с разным хвостом.
крупные = [(к, н) for к, н in свод.most_common() if н >= 10]
мелочь = sum(н for к, н in свод.items() if н < 10)
print("\n=== ЧЕМ КОНЧАЛАСЬ ПОСЛЕДНЯЯ ПОПЫТКА ===")
for к, н in крупные:
    print("   %-46s %5d" % (к[:46], н))
if мелочь:
    print("   %-46s %5d" % ("прочее по мелочи (меньше 10 на причину)", мелочь))
print("\n=== ПРИМЕРЫ ПО КРУПНЫМ КУЧАМ ===")
for к, _н in крупные[:4]:
    print("   %s:" % к[:60])
    for пример in примеры[к][:2]:
        print("      %s" % пример[:110])
