# -*- coding: utf-8 -*-
"""Последние письма: вызовов, срывов, цена — чтобы понять, письмо это или срыв."""
import io, json, os, time
Ж = r"C:\sender\_ops\gen-partiya-935.jsonl"
сырые = [json.loads(s) for s in io.open(Ж, encoding="utf-8") if s.strip()]

# ОДНА ЗАПИСЬ НА ПИСЬМО. С 17.08 журнал пишется дважды: первая строка -
# сразу после генерации, до обращения к базе, вторая («итог») - после
# постановки в очередь. Считать обе строки значило бы удвоить и число
# писем, и потраченные деньги. «Итог» замещает свою первую строку и встаёт
# на её место; первая строка без итога остаётся - это письмо, чей поток
# умер на постановке в очередь, и прятать его из отчёта нельзя. Старый
# журнал (строки без этапа) считается как раньше, по строке на письмо.
#
# ДВА ИМЕНИ У ПЕРВОЙ СТРОКИ. Правку писали две сессии сразу и назвали этап
# по-разному: «текст» здесь, «сгенерировано» в версии соседей. 17.08 в
# 13:26:01 их выкатка легла поверх нашей за 21 секунду до старта обоих
# прогонов, и журнал наполнился строками «сгенерировано» - которых этот
# отчёт не узнавал и считал отдельными письмами. Замер: 6 новых писем
# показывались как 12 записей, деньги - вдвое. Спорить об имени дороже,
# чем принять оба: журнал уже смешанный, и переписать его задним числом
# нельзя.
НАЧАЛО = ("текст", "сгенерировано")
пары, попытка = {}, {}
for i, x in enumerate(сырые):
    rid = x.get("recipient_id")
    этап = x.get("этап")
    if этап in НАЧАЛО:
        попытка[rid] = попытка.get(rid, 0) + 1
        пары[(rid, попытка[rid])] = x
    elif этап == "итог":
        пары[(rid, попытка.get(rid, 1))] = x
    else:
        пары[("стар", i)] = x
z = list(пары.values())

print(f"записей {len(z)} | ок {sum(1 for x in z if x.get('ок'))} | "
      f"${sum(float(x.get('цена_$') or 0) for x in z):.2f}")
print("последняя запись:", time.strftime(
    '%H:%M:%S', time.localtime(os.path.getmtime(Ж))),
    "| сейчас:", time.strftime('%H:%M:%S'))
print("\nпоследние 12 записей:")
print(f"{'имя':<30}{'ок':<5}{'сек':<6}{'выз':<5}{'срыв':<6}{'$':<8}")
for x in z[-12:]:
    print(f"{str(x.get('имя'))[:28]:<30}"
          f"{'да' if x.get('ок') else 'нет':<5}"
          f"{x.get('сек', '?'):<6}{x.get('вызовов', '?'):<5}"
          f"{x.get('срывов', 0):<6}{float(x.get('цена_$') or 0):<8.3f}")
свежие = [x for x in z if x.get("вызовов")]
if свежие:
    сс = sum(x.get("срывов", 0) for x in свежие)
    сv = sum(x.get("вызовов", 0) for x in свежие)
    print(f"\nпо записям с учётом: вызовов {сv}, срывов {сс} "
          f"({100 * сс // max(1, сv)}%)")
    цена_ок = [float(x.get('цена_$') or 0) for x in свежие if x.get("ок")]
    if цена_ок:
        цена_ок.sort()
        print(f"цена вышедшего письма: медиана ${цена_ок[len(цена_ок)//2]:.3f}, "
              f"мин ${цена_ок[0]:.3f}, макс ${цена_ок[-1]:.3f}")
без_итога = sum(1 for x in z if x.get("этап") in НАЧАЛО)
if без_итога:
    print(f"\nписем с текстом, но без итога очереди: {без_итога} - "
          f"доложить: python ops/partiya_dolozhit_iz_zhurnala.py primenit")
