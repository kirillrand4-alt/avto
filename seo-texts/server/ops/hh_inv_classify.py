"""hh-ИНВЕРСИЯ, шаг 4: КТО ЭТОТ РАБОТОДАТЕЛЬ.

Без этого шага счёт лидов врёт в самую выгодную сторону. Две трети вакансий по
названиям должностей выставили ДВЕ вахтовые конторы («ПрессБук» — одна и та же
вакансия на 234 города), а среди тех, кто ищет «сервисного инженера
компрессорного оборудования», сидят наши прямые конкуренты — продавцы
компрессоров. Ни те, ни другие лидом не являются, хотя оба идеально проходят
формальный фильтр «нанимает компрессорщика».

Тяжёлую разметку делает провайдерский API (правило владельца — не жечь квоту
сессии). Ответы кэшируются по ключу работодателя: прогон резюмируемый.
"""
import json
import os
import sys

sys.path.insert(0, '/home/user/avto/seo-texts')
import gen_provider as GP  # noqa: E402

СИСТЕМА = """Ты размечаешь работодателей с hh.ru для отдела продаж компании,
которая ПРОДАЁТ промышленные компрессоры, генераторы азота и кислорода,
компрессорные станции (ООО «Руспром», бренд «Компрессор Центр»).

Задача: по названию работодателя, его сайту и названиям его вакансий понять,
КТО это, и годится ли он как потенциальный ПОКУПАТЕЛЬ компрессорного
оборудования.

Классы (поле "класс", ровно одно значение):
  "конечный потребитель" — завод, комбинат, добывающее/перерабатывающее
     предприятие, агрохолдинг, ЖКХ/водоканал, больница: у него СВОЁ
     компрессорное хозяйство, он его эксплуатирует. Это лид.
  "конкурент" — производит, продаёт, поставляет или сервисит компрессорное,
     газоразделительное, пневматическое оборудование; торговый дом,
     инжиниринг, дилер, сервисная компания по компрессорам. НЕ лид.
  "кадровое агентство" — аутстаффинг, вахтовый набор, кадровое агентство,
     подбор персонала под чужие объекты. НЕ лид, компрессоров у него нет.
  "подрядчик" — строительно-монтажная, буровая, нефтесервисная организация,
     работающая на объекте заказчика (строит компрессорные станции, бурит,
     монтирует). Компрессоры использует, но чаще арендует; лид спорный.
  "неясно" — данных не хватает.

Поле "профиль": "да" (эксплуатирует стационарное компрессорное хозяйство /
воздухоразделение — прямой профиль), "спорно" (только передвижные дизельные
компрессоры на стройке, либо только холодильные компрессоры), "нет".

Поле "почему": одна короткая фраза по-русски, что именно тебя убедило.

Отвечай ТОЛЬКО JSON-массивом объектов {"key","класс","профиль","почему"},
по одному на каждого работодателя из входа, в том же порядке. Без пояснений."""


def пачки(items, n):
    for i in range(0, len(items), n):
        yield items[i:i + n]


def main():
    src = sys.argv[1]
    out = sys.argv[2]
    зап = [json.loads(l) for l in open(src, encoding='utf-8')]
    кэш = {}
    if os.path.exists(out):
        кэш = json.load(open(out, encoding='utf-8'))
    надо = [r for r in зап if r['key'] not in кэш]
    print(f'=== классификация: всего {len(зап)}, в кэше {len(кэш)}, '
          f'к разметке {len(надо)} ===', flush=True)
    cl = GP.make_client()
    for k, пачка in enumerate(пачки(надо, 20), 1):
        вход = []
        for r in пачка:
            вход.append({
                'key': r['key'],
                'работодатель': r.get('employer'),
                'сайт': (r.get('sites') or [''])[0],
                'из_егрюл': r.get('dadata_name') or '',
                'оквэд': r.get('dadata_okved') or '',
                'вакансий_за_30_дней': r.get('n_vac'),
                'городов': len(r.get('areas') or {}),
                'вакансии': [v.get('name') for v in (r.get('vacancies') or [])][:6],
            })
        msg = [{'role': 'user', 'content':
                СИСТЕМА + '\n\nВХОД:\n' + json.dumps(вход, ensure_ascii=False, indent=1)}]
        try:
            m = GP.call(cl, msg, model='claude-fable-5', attempts=4)
            txt = ''.join(b.text for b in m.content if b.type == 'text').strip()
        except Exception as e:  # noqa: BLE001
            print(f'  пачка {k}: сбой {type(e).__name__}: {str(e)[:80]}', flush=True)
            continue
        txt = txt[txt.find('['):txt.rfind(']') + 1] if '[' in txt else ''
        try:
            arr = json.loads(txt)
        except Exception as e:  # noqa: BLE001
            print(f'  пачка {k}: не разобрал JSON ({str(e)[:60]})', flush=True)
            continue
        for a in arr:
            if a.get('key'):
                кэш[a['key']] = {'класс': a.get('класс') or 'неясно',
                                 'профиль': a.get('профиль') or '',
                                 'почему': (a.get('почему') or '')[:160]}
        with open(out, 'w', encoding='utf-8') as f:
            json.dump(кэш, f, ensure_ascii=False, indent=0)
            f.flush()
            os.fsync(f.fileno())
        print(f'  пачка {k}: размечено {len(arr)}, в кэше {len(кэш)}', flush=True)
    from collections import Counter
    print('=== ИТОГ классификации ===')
    print('классы:', Counter(v['класс'] for v in кэш.values()).most_common())
    print('профиль:', Counter(v['профиль'] for v in кэш.values()).most_common())
    print(f'всего размечено: {len(кэш)} из {len(зап)}')


if __name__ == '__main__':
    main()
