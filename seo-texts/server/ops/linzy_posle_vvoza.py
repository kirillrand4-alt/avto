def _клод(модель, промпт, максимум=4000):
    """Claude через /v1/messages со стримом. Свой urllib, а не SDK.

    Соседка сегодня потеряла целый прогон на том, что клиент SDK отдаёт для
    claude-моделей ОБЪЕКТ сообщения, который не сериализуется, и падение
    случилось ПОСЛЕ того, как все ответы были получены и оплачены. Здесь текст
    собирается из событий стрима — объекту неоткуда взяться.
    """
    тело = json.dumps({'model': модель, 'max_tokens': максимум, 'stream': True,
                       'messages': [{'role': 'user', 'content': промпт}]},
                      ensure_ascii=False).encode('utf-8')
    зпр = urllib.request.Request(
        БАЗА_API + '/v1/messages', data=тело, method='POST',
        headers={'x-api-key': КЛЮЧ, 'anthropic-version': '2023-06-01',
                 'content-type': 'application/json',
                 'accept': 'text/event-stream', 'User-Agent': 'curl/8.5.0'})
    # ТЕКСТ И РАЗМЫШЛЕНИЕ СОБИРАЕМ ПОРОЗНЬ. Первая правка складывала их в одну
    # кучу, и судья выдал в ответе собственный черновик: «Let me identify the
    # lenses I have… Wait, let me re-read». Ответ, склеенный с рассуждением,
    # хуже пустого — его нельзя ни прочитать, ни отдать соседям.
    # Правило: берём текст; если текстового блока нет вовсе — берём
    # размышление, потому что тогда весь ответ ушёл туда.
    куски, думки = [], []
    with urllib.request.urlopen(зпр, timeout=600) as о:
        for сырая in о:
            с = сырая.decode('utf-8', 'replace').strip()
            if not с.startswith('data:'):
                continue
            try:
                ев = json.loads(с[5:].strip())
            except Exception:  # noqa: BLE001
                continue
            if ев.get('type') == 'content_block_delta':
                д = ев.get('delta') or {}
                # ТЕКСТ ЛИБО В `text`, ЛИБО В `thinking`. Соседка предупредила
                # об этом сегодня, я ответил, что меня не касается, потому что
                # хожу своим urllib, — и ошибся: дело не в клиенте, а в поле.
                # Четыре линзы из шести вернули ПУСТО, хотя ответ был получен и
                # оплачен: модель отдала его блоками размышления
                # (`thinking_delta`), а я собирал только `text`.
                if д.get('text'):
                    куски.append(д['text'])
                elif д.get('thinking'):
                    думки.append(д['thinking'])
    готово = ''.join(куски).strip()
    return готово if готово else ''.join(думки)


def записать(запись):
    with open(ЖУРНАЛ, 'a', encoding='utf-8') as ф:
        ф.write(json.dumps(запись, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())


def прочитать_линзы():
    из = {}
    if os.path.exists(ЖУРНАЛ):
        for стр in open(ЖУРНАЛ, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(стр)
            except Exception:  # noqa: BLE001
                continue
            if з.get('роль') and з.get('ответ'):
                из[з['роль']] = з['ответ']
    return из


def одна_линза(пара):
    имя, роль = пара
    т0 = time.time()
    try:
        ответ = _клод(МОДЕЛЬ_ЛИНЗЫ, f'{роль}\n\n{ЗАДАЧА}')
    except Exception as e:  # noqa: BLE001
        записать({'роль': имя, 'err': f'{type(e).__name__}: {str(e)[:200]}',
                  'ts': int(time.time())})
        return имя, ''
    записать({'роль': имя, 'ответ': ответ, 'знаков': len(ответ),
              'секунд': round(time.time() - т0, 1), 'ts': int(time.time())})
    print(f'  линза «{имя}»: {len(ответ)} знаков за '
          f'{time.time() - т0:.0f} с')
    sys.stdout.flush()
    return имя, ответ


