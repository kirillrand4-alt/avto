# -*- coding: utf-8 -*-
"""За что рецензент забраковал 254 письма — по видам претензий.

Рецензент читает САЙТ компании и сверяет с ним каждое утверждение письма.
Вердикт «не годно» означает не плохой слог, а несовпадение с фактами сайта.
Разбираем претензии по ключевым словам: точной рубрикации в журнале нет,
поэтому считаем по тому, о чём претензия говорит.

    python zapusk_svoego_skripta.py ops/pochemu_ne_godno.py
"""
import io
import json
from collections import Counter

ж = r"C:\sender\_ops\rezenzii-pisem.jsonl"

ВИДЫ = (
    ("приписали производство, а там торговля/монтаж",
     ("торгу", "продаж", "дилер", "монтаж", "под ключ", "поставщик",
      "перепрода", "магазин")),
    ("процесса нет на сайте (покраска, резка, сварка и т.п.)",
     ("нет упомин", "нет ни слова", "не указан", "не подтвержда",
      "нет данных", "не найдено", "не сказано", "отсутству")),
    ("профиль назван шире/уже, чем на сайте",
     ("шире", "уже", "только о", "лишь", "а сайт говорит", "а сайт показыва",
      "позиционируется")),
    ("нужда выдумана (кислород, азот, сепарация)",
     ("кислород", "азот", "сепарат", "реанимац", "стационар")),
    ("компания не та (тёзка, другой профиль)",
     ("другая компания", "тёзк", "не та организац", "иная сфера")),
)

всего = 0
виды = Counter()
без_рубрики = []
сайт_пустой = 0
for s in io.open(ж, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if str(z.get("verdict") or "") != "не годно":
        continue
    всего += 1
    if not int(z.get("сайт_знаков") or 0):
        сайт_пустой += 1
    текст = " ".join(str(x) for x in (z.get("pretenzii") or [])).lower()
    нашлось = False
    for имя, слова in ВИДЫ:
        if any(w in текст for w in слова):
            виды[имя] += 1
            нашлось = True
            break
    if not нашлось:
        без_рубрики.append((z.get("id"), (z.get("pretenzii") or [""])[0]))

print(f"писем «не годно»: {всего}")
print(f"  из них у рецензента не было сайта вовсе: {сайт_пустой}")
print("\nвиды претензий:")
for имя, n in виды.most_common():
    print(f"  {n:>4}  {имя}")
print(f"  {len(без_рубрики):>4}  прочее")
print("\nпримеры «прочего»:")
for i, т in без_рубрики[:6]:
    print(f"  #{i}: {str(т)[:150]}")
