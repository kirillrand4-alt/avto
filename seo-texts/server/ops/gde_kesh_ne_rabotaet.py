# -*- coding: utf-8 -*-
"""Какие промпты конвейера вообще режутся под кэш, а какие идут целиком.

Кэш шлюза читается только из поля system, а туда попадает левая часть
разреза gen_provider.razrezat_promt. Границы разреза - это конкретные
строки промптов (_ГРАНИЦЫ). Если у промпта такой строки нет, razrezat_promt
честно возвращает (None, промпт) - и вызов идёт БЕЗ кэша, молча.

Вызовов моделей тут нет: только строим промпты и смотрим, режутся ли они.
"""
import sys

sys.path.insert(0, r"C:\sender")
import gen_provider as GP                                        # noqa: E402
from sender import ai_letter as AI                               # noqa: E402

факты = AI.load_facts()
ПОЛ = [{"mode": "GENERIC", "company_name": "ООО «Тест»",
        "activity": "мехобработка", "okved": "25.62", "extra": {}}]
# ПИСЬМО БЕРЁМ НАСТОЯЩЕЙ ДЛИНЫ. Первый замер я сделал на теле в три слова и
# получил «верификатор не режется»: разрез требует, чтобы после границы
# оставалось больше 100 знаков, а там оставалось 46. Промпт был ни при чём -
# ошибка была в моей заготовке.
ТЕЛО = ("Добрый день!\n\nУ «Тест» механическая обработка - на участках стоят "
        "станки с ЧПУ, и сжатый воздух идёт и на обдув оснастки, и на "
        "пневмозажимы. Запас по производительности на таких линиях уходит "
        "быстрее, чем кажется: смена идёт без остановок, а требования к "
        "чистоте воздуха выше обычного цехового уровня.\n\nЯ веду направление "
        "компрессорного оборудования в Компрессор Центре. Подскажите, "
        "актуален ли для вас вопрос обновления компрессорного парка?\n\n"
        "Если неактуально - извините за письмо, больше не побеспокою.\n\n"
        "С уважением,")

промпты = {}
промпты["генерация"] = AI.gen_prompt(ПОЛ, факты, "kc", angle_base=0)
try:
    промпты["судья best_of"] = AI.judge_prompt(
        [(0, [("Тема A", "тело A"), ("Тема B", "тело B")])], "kc")
except Exception as ex:                                          # noqa: BLE001
    промпты["судья best_of"] = f"НЕ СОБРАЛСЯ: {ex}"
try:
    промпты["верификатор"] = AI.vf_prompt([(0, "Вопрос по компрессорному парку", ТЕЛО)], "kc")
except Exception as ex:                                          # noqa: BLE001
    промпты["верификатор"] = f"НЕ СОБРАЛСЯ: {ex}"
for линза in ("обе", "технолог", "скептик"):
    промпты[f"линза {линза}"] = AI.teh_lens_prompt(
        [(0, "ООО «Тест»", "мехобработка", "25.62",
          "Вопрос по компрессорному парку", ТЕЛО)], линза, "kc")

print(f"{'промпт':<20} {'длина':>7} {'статика':>8}  кэш")
for имя, п in промпты.items():
    if п.startswith("НЕ СОБРАЛСЯ"):
        print(f"{имя:<20} {п[:60]}")
        continue
    с, _ = GP.razrezat_promt(п)
    print(f"{имя:<20} {len(п):>7} {(len(с) if с else 0):>8}  "
          f"{'да' if с else 'НЕТ - идёт целиком'}")
    if not с:
        for г in GP._ГРАНИЦЫ:
            i = п.find(г)
            print(f"{'':<20} граница {г.strip():<14} позиция {i:>6} "
                  f"хвост {(len(п) - i) if i >= 0 else -1:>6}")
print("\nграницы разреза:", [g.strip() for g in GP._ГРАНИЦЫ])
