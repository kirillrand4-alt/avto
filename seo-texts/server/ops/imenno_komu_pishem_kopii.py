# -*- coding: utf-8 -*-
"""Копии - конкретным людям, чьи имена названы во входящем.

Владелец: «имена есть в письмах которые нам написали / емейлы же берутся
из писем для копий». Так и оказалось: адреса пришли из автоответов, и в
самих автоответах человек назван.

  Гастрофабрика  «Прошу обращаться к моим коллегам: 1. этикетки,
                 расходные материалы, инвентарь, газ, униформа -
                 Хабибуллаев Рамзан; 2. упаковка, гофрокороба -
                 Свечникова Екатерина»
  ВКТМ           «обращаться к моей коллеге, Гадецких Ольге»
  Полиформ       «обратиться напрямую к Исполнительному директору
                 Давыдову Максиму»
  Интермет       «По срокам готовности ответит Алексей»
  Лазер116       адрес для вопросов и претензий, имени нет
  Ритм           «вся почта теперь на info@», имени нет

Правим две вещи: обращение по имени и одну строку о том, ОТКУДА мы взяли
этот адрес. Тогда письмо перестаёт быть слепым дублем.

Длинных тире не ставим - в письмах дефис.
"""
import sqlite3
import sys
from datetime import datetime, timezone

sys.path.insert(0, r"C:\sender")
from sender.auto_send import (next_slot, recipient_tz_name,      # noqa: E402
                              window_from)
from sender.config import Config                                 # noqa: E402
from sender.store import Store                                   # noqa: E402

КАТИТЬ = "--katit" in sys.argv

# id -> (имя или "", строка-объяснение)
ПРАВКИ = {
    3312: ("Рамзан", "Писал на общий адрес компании, в автоответе коллега "
                     "переадресовал к вам."),
    3313: ("Екатерина", "Писал на общий адрес компании, в автоответе коллега "
                        "переадресовал к вам."),
    3051: ("Ольга", "Ваш коллега в автоответе просил на время отпуска "
                    "обращаться к вам - дублирую вопрос."),
    3473: ("Максим", "В автоответе компании вы указаны для прямого "
                     "обращения - пишу вам."),
    3050: ("Алексей", "Ваш коллега в автоответе указал вас как контакт по "
                      "срокам - дублирую вопрос вам."),
    2601: ("", "Писал на общий адрес компании; в автоответе этот адрес указан "
               "для вопросов - дублирую."),
    3472: ("", "Писал на прежний адрес компании; в автоответе указано, что "
               "переписка теперь идёт сюда - дублирую."),
}

cfg = Config.load(r"C:\sender\sender.yaml")
store = Store(cfg.get("service.db_path", r"C:\sender\sender.db"))
окно = window_from(store, cfg)
сейчас = datetime.now(timezone.utc)
c = sqlite3.connect(r"C:\sender\sender.db")
c.row_factory = sqlite3.Row

готово = []
for rid, (имя, строка) in ПРАВКИ.items():
    r = c.execute(
        "SELECT cr.id, cr.status, cr.email, cr.subject, cr.body, "
        "       cr.message_id, "
        "       cr.recipient_id, rc.company_name "
        "FROM confirm_reviews cr LEFT JOIN recipients rc "
        "ON rc.id=cr.recipient_id WHERE cr.id=?", (rid,)).fetchone()
    if not r or str(r["status"]) != "pending":
        print(f"  #{rid} статус {r['status'] if r else 'нет карточки'} - мимо")
        continue
    тело = str(r["body"] or "")
    if not тело.startswith("Добрый день!"):
        print(f"  #{rid} начало незнакомое - не трогаю")
        continue
    начало = f"Добрый день, {имя}!" if имя else "Добрый день!"
    новое = начало + тело[len("Добрый день!"):]
    # Старая просьба «если вопрос не к вам, дайте контакт коллеги» после
    # того, как коллега нас СЮДА и направил, читается глупо. Там, где мы
    # теперь знаем имя, меняем её на объяснение и короткую оговорку.
    СТАРОЕ = ("Если вопрос не к вам, буду благодарен за контакт коллеги - "
              "обращусь напрямую.")
    if имя and СТАРОЕ in новое:
        новое = новое.replace(
            СТАРОЕ, строка + " Если тема не ваша, подскажите, к кому "
                             "обратиться.")
        строка = ""
    # Строку об источнике адреса ставим перед подписью: она объясняет
    # письмо, а не продаёт, и в конце читается как оговорка, а не как
    # заход.
    if not строка:
        pass
    elif "\nС уважением," in новое:
        новое = новое.replace("\nС уважением,",
                              f"\n{строка}\n\nС уважением,", 1)
    else:
        новое = новое.rstrip() + f"\n\n{строка}\n"
    готово.append((r, новое, имя))

print(f"\nк правке: {len(готово)}")
for r, новое, имя in готово:
    print("=" * 70)
    print(f"#{r['id']} {str(r['company_name'])[:32]} -> {r['email']} "
          f"| имя: {имя or '(нет)'}")
    print("  " + новое[:90].replace("\n", " "))
    print("  ...")
    print("  " + новое[-260:].replace("\n", " "))

if not КАТИТЬ:
    print("\nсухой прогон. Катить - --katit")
    raise SystemExit(0)

поправлено = одобрено = 0
for r, новое, _имя in готово:
    try:
        # subject у метода обязателен: тему не меняем, отдаём ту же.
        store.confirm_update_letter(int(r["id"]),
                                    subject=str(r["subject"] or ""),
                                    body=новое)
        поправлено += 1
        ок = store.confirm_decide(int(r["id"]), status="approved",
                                  decided_by="разбор копий 20.08 (человек)")
        if ок is False:
            continue
        одобрено += 1
        rec = store.get_recipient(r["recipient_id"])
        if r["message_id"] and rec is not None:
            store.reschedule_message(
                int(r["message_id"]),
                next_slot(окно, recipient_tz_name(окно, rec), сейчас))
    except Exception as ex:                                      # noqa: BLE001
        print(f"  #{r['id']} сбой: {str(ex)[:100]}")
print(f"\nпоправлено: {поправлено} | в отправку: {одобрено}")
