# -*- coding: utf-8 -*-
"""Уточнение пропуска: адрес из очереди тоже не надо переписывать зря.

Первая правка пропускала строку, только если адреса нет в очереди. Но в
очереди 12 372 карточки, и почти все их адреса есть в файле работника —
то есть в боевом круге переписывалось бы 12 тысяч строк вместо тридцати.

Очередь важна не сама по себе: по вердикту «нет ящика», «нет MX» и
«неясно» надо снять письмо и закрыть адрес. По «есть», «принимает всё» и
«отказ пробе» после записи не делается НИЧЕГО. Значит пропускать можно и
адрес из очереди, если вердикт не из тех трёх.

А там, где вердикт из тех трёх и он не изменился, пропускаем только саму
запись: снятие письма и стоп-лист отрабатывают как раньше.

argv: --primenit чтобы записать.
"""
import io
import py_compile
import sys
import time

ФАЙЛ = r"C:\sender\sender\probe_sync.py"
ПРИМЕНИТЬ = "--primenit" in sys.argv

ЯКОРЬ = '''            if (стояло and str(стояло.get("verdict") or "") == вердикт
                    and адрес not in по_почте):
                без_изменений += 1
                свод[вердикт] = свод.get(вердикт, 0) + 1
                continue
            легло = self.probe._save(адрес, вердикт, з.get("code"),
                                     str(з.get("answer") or ""),
                                     str(з.get("mx") or ""))
'''
ЗАМЕНА = '''            то_же = (стояло is not None
                     and str(стояло.get("verdict") or "") == вердикт)
            # Очередь важна не сама по себе: по «нет ящика», «нет MX» и
            # «неясно» ниже снимается письмо и закрывается адрес, по
            # остальным вердиктам после записи не делается ничего. Поэтому
            # адрес из очереди с безобидным вердиктом пропускаем наравне с
            # прочими, а там, где вердикт из этих трёх, пропускаем только
            # саму запись — снятие письма и стоп-лист идут как раньше.
            if то_же and (адрес not in по_почте
                          or вердикт not in (НЕТ_ЯЩИКА, НЕТ_MX, НЕЯСНО)):
                без_изменений += 1
                свод[вердикт] = свод.get(вердикт, 0) + 1
                continue
            легло = True if то_же else self.probe._save(
                адрес, вердикт, з.get("code"), str(з.get("answer") or ""),
                str(з.get("mx") or ""))
'''

т = io.open(ФАЙЛ, encoding="utf-8").read()
уже = "Очередь важна не сама по себе" in т
print("файл: %s (%d байт), уточнение уже стоит: %s"
      % (ФАЙЛ, len(т), "да" if уже else "нет"))
if уже:
    raise SystemExit("уточнение уже применено")
n = т.count(ЯКОРЬ)
print("   якорь: вхождений %d" % n)
if n != 1:
    raise SystemExit("НЕ ТРОГАЕМ: якорь не сошёлся")

новый = т.replace(ЯКОРЬ, ЗАМЕНА, 1)
print("   стало байт: %d (+%d)" % (len(новый), len(новый) - len(т)))
if not ПРИМЕНИТЬ:
    print("")
    print("=" * 74)
    print("=== ПОКАЗ БЕЗ ЗАПИСИ (нужен --primenit) ===")
    raise SystemExit(0)

бэкап = ФАЙЛ + ".bak-%d" % int(time.time())
io.open(бэкап, "w", encoding="utf-8").write(т)
io.open(ФАЙЛ, "w", encoding="utf-8").write(новый)
try:
    py_compile.compile(ФАЙЛ, doraise=True)
    итог = "записано, компилируется"
except Exception as ex:                                         # noqa: BLE001
    io.open(ФАЙЛ, "w", encoding="utf-8").write(т)
    итог = "НЕ КОМПИЛИРУЕТСЯ, откатили: %s" % str(ex)[:160]
print("")
print("=" * 74)
print("=== УТОЧНЕНИЕ ПРОПУСКА ===")
print("   бэкап: %s" % бэкап)
print("   итог:  %s" % итог)
