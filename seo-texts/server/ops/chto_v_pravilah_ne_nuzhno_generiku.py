"""Сколько в правилах написано про режим NEWS, когда все письма GENERIC.

Замер 19.08 по кандидатам: новость-повод есть у 0 из 150 компаний, то есть
все письма идут от профиля. Если правила подробно описывают работу с
новостью, эта часть возится в каждом вызове зря - и по деньгам (запись кэша
1.25 ставки), и по вниманию модели.

Режем правила по заголовкам пунктов и смотрим, где сидит новость.
"""
import re
import sys

sys.path.insert(0, r"C:\sender")
from sender import ai_letter as AI                               # noqa: E402

НОВОСТНОЕ = re.compile(r'(?i)новост|news|повод|инфоповод|событи')

for div in ("kc", "meyer"):
    т = AI.RULES_BY_DIVISION[div]
    строки = т.split("\n")
    # блок = от строки, начинающейся с номера/буквы пункта, до следующей такой
    блоки, текущий = [], ["(шапка)", []]
    for s in строки:
        if re.match(r'^\s{0,3}(\d{1,2}\.|[а-я]\)|-{1,2}\s|[А-Я]{4,})', s):
            if текущий[1]:
                блоки.append((текущий[0], "\n".join(текущий[1])))
            текущий = [s.strip()[:70], [s]]
        else:
            текущий[1].append(s)
    if текущий[1]:
        блоки.append((текущий[0], "\n".join(текущий[1])))

    всего = len(т)
    новостных = sum(len(b) for _, b in блоки if НОВОСТНОЕ.search(b))
    print(f"\n== {div}: {всего} знаков, блоков {len(блоки)} ==")
    print(f"  блоков со словом «новость/повод»: "
          f"{sum(1 for _, b in блоки if НОВОСТНОЕ.search(b))}")
    print(f"  знаков в них: {новостных} = {100.0 * новостных / всего:.0f}%")
    print("  самые крупные блоки правил:")
    for имя, b in sorted(блоки, key=lambda x: -len(x[1]))[:8]:
        метка = " [новость]" if НОВОСТНОЕ.search(b) else ""
        print(f"    {len(b):>6} знаков  {имя}{метка}")
