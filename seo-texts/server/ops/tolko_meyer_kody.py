# -*- coding: utf-8 -*-
"""Оставить в задании только мейеровские коды.

Meyer — фотосепараторы и рентген-инспекция: сортировка зерна, крупы, семечки,
орехов, овощей, кофе и контроль посторонних включений в готовой еде. Значит
покупатель — тот, кто ВЫРАЩИВАЕТ, ХРАНИТ, ПЕРЕРАБАТЫВАЕТ или ФАСУЕТ пищевое
сырьё, плюс те, кто им торгует оптом.

Берём разделы:
    01  сельское хозяйство      03  рыболовство
    10  пищевые продукты        11  напитки
    46  опт — ТОЛЬКО пищевой и сельхозный (46.11, 46.2, 46.3, 46.6х по с/х)
    52.10  хранение и складирование (элеваторы)
    82.92  услуги по упаковыванию      22.22  пластиковая упаковка
Прочее (строительство, аренда, металл, консультирование, розница, ремонт,
НИР) — не наш покупатель, даже если у пары компаний такой основной код.
"""
import io
import os
import re
import sys

ФАЙЛ = r"C:\seostat\Parser2\data\okved-agro.txt"
ПИСАТЬ = "--zapisat" in sys.argv
ОПТ_ПИЩЕВОЙ = ("46.11", "46.2", "46.3", "46.6", "46.9")   # с/х сырьё, продукты
ПРОЧЕЕ_МЕЙЕР = ("52.10", "82.92", "22.22")


def мейер(к):
    if re.match(r"^(01|03|10|11)(\.|$)", к):
        return True
    if к.startswith(ОПТ_ПИЩЕВОЙ):
        # 46.6 — машины; оставляем только сельхозмашины 46.61
        if к.startswith("46.6") and not к.startswith("46.61"):
            return False
        # 46.9 — неспециализированный опт, пищёвка там основная
        return True
    return к.startswith(ПРОЧЕЕ_МЕЙЕР)


список = [с.strip() for с in io.open(ФАЙЛ, encoding="utf-8") if с.strip()]
берём = [к for к in список if мейер(к)]
уходят = [к for к in список if not мейер(к)]
print("было кодов: %d → остаётся %d, убираем %d"
      % (len(список), len(берём), len(уходят)))
print("\nОСТАЮТСЯ (порядок сохранён, он по числу покупателей):")
for i in range(0, len(берём), 10):
    print("   %s" % ", ".join(берём[i:i + 10]))
print("\nУБИРАЕМ:")
for i in range(0, len(уходят), 10):
    print("   %s" % ", ".join(уходят[i:i + 10]))
if ПИСАТЬ:
    with io.open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(берём) + "\n")
        f.flush()
        os.fsync(f.fileno())
    print("\nзаписано в %s: %d кодов" % (ФАЙЛ, len(берём)))
else:
    print("\n(с --zapisat перезапишу файл)")
