# -*- coding: utf-8 -*-
"""Род деятельности из extra, когда карточки обогащения нет.

ЗАЧЕМ. `_request` заполняет activity ТОЛЬКО из enrich.company, а карточка
обогащения есть лишь у компаний с российским ИНН. Участнику выставки из
каталога ProdExpo карточки нет и не будет: письмо писалось бы, не зная,
чем компания занимается, хотя строка «переработка масличных культур и
производство растительных масел» лежит рядом, в extra получателя.

ХИРУРГИЧЕСКИ. Каталог C:\\sender\\sender делят несколько сессий — правим
один кусок по якорю, сверяя, что якорь ровно один, с .bak и компиляцией.

Сухой прогон по умолчанию. Катить: --katit
"""
import io
import os
import py_compile
import sys
import time

ФАЙЛ = r"C:\sender\sender\ai_quota.py"
КАТИТЬ = "--katit" in sys.argv

ЯКОРЬ = "        # МЕТКА НАПРАВЛЕНИЯ. Без неё target_division не может применить правило"
ВСТАВКА = '''        # РОД ДЕЯТЕЛЬНОСТИ БЕЗ КАРТОЧКИ ОБОГАЩЕНИЯ. `activity` до сих пор
        # приходил ТОЛЬКО из enrich.company, а карточка есть лишь у компаний
        # с российским ИНН. Зарубежному участнику выставки (каталог ProdExpo,
        # 25.08) карточки нет и не будет — и письмо писалось бы, не зная, чем
        # компания занимается, хотя строка «переработка масличных культур»
        # лежит рядом в extra. Берём её как запасной источник: карточка, если
        # есть, по-прежнему главнее.
        if not activity:
            activity = str(extra.get("activity") or "").strip()

'''

текст = io.open(ФАЙЛ, encoding="utf-8").read()
if "РОД ДЕЯТЕЛЬНОСТИ БЕЗ КАРТОЧКИ ОБОГАЩЕНИЯ" in текст:
    print("правка уже на месте")
    raise SystemExit(0)
n = текст.count(ЯКОРЬ)
print("якорь найден раз: %d" % n)
if n != 1:
    raise SystemExit("якорь должен быть ровно один")
новый = текст.replace(ЯКОРЬ, ВСТАВКА + ЯКОРЬ)
print("было %d знаков, станет %d" % (len(текст), len(новый)))
if not КАТИТЬ:
    print("сухой прогон. Катить: --katit")
    raise SystemExit(0)
копия = "%s.bak-%d" % (ФАЙЛ, int(time.time()))
io.open(копия, "w", encoding="utf-8", newline="").write(текст)
print(".bak: %s" % os.path.basename(копия))
with io.open(ФАЙЛ, "w", encoding="utf-8", newline="") as f:
    f.write(новый)
    f.flush()
    os.fsync(f.fileno())
py_compile.compile(ФАЙЛ, doraise=True)
print("записан и скомпилирован")
