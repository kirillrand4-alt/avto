# -*- coding: utf-8 -*-
"""Как название компании выглядит в письме. Одна правда для очереди и проверки.

Разбор моделью (ops/imena_agro.py) снимает юрформу и чинит регистр, но
оставляет внутренние кавычки: «Агрофирма «Дружба»», «Агрокомплекс "Ейский"».
Обернуть такое ещё раз - получить ««Агрофирма «Дружба»»». Поэтому здесь
решается, ЧТО именно станет подлежащим первой фразы письма.
"""
import re

КАВЫЧКИ = r'"«»„“”‘’'
_В_КАВЫЧКАХ = re.compile(r'[«"„‘]\s*([^«»"„“”‘’]{2,})\s*[»"“’]')
_ФОРМА = re.compile(
    r'(?i)^\s*(ООО|ОАО|ЗАО|ПАО|НАО|АО|СПК|СХПК|СХК|КФХ|К/Х|КХ|ТНВ|ПК|'
    r'общество с ограниченной ответственностью|акционерное общество)\s+')
# Фамилия с инициалами или полное ФИО. Скобка ОБЯЗАТЕЛЬНА: пока она была
# необязательной, под «человека» попадало любое одиночное слово с заглавной
# — «Дружба», «Юг» — и письмо шло с «Ваше хозяйство» вместо названия.
_ЛИЦО = re.compile(r"^[А-ЯЁ][а-яё]+(\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.?"
                   r"|\s+[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+)$")
ПРЕДЕЛ_ДЛИНЫ = 45


def итоговое_имя(разобранное, человек=False):
    """Вернуть (подлежащее для письма, пометка).

    Пометка: 'название' | 'хозяйство' - во втором случае вместо названия
    в письме стоит «Ваше хозяйство».
    """
    имя = " ".join(str(разобранное or "").split())
    if человек:
        return "Ваше хозяйство", "хозяйство"
    # Собственное имя внутри кавычек - это и есть название: «Агрофирма
    # «Дружба»» в письме должна стать «Дружба», как «Новый путь» в образце
    # владельца. Родовое слово (агрофирма, колхоз, племзавод) остаётся за
    # скобками - оно и так звучит в самой фразе про зерновые.
    м = _В_КАВЫЧКАХ.search(имя)
    if м and len(м.group(1).strip()) >= 3:
        имя = м.group(1).strip()
    имя = " ".join(re.sub("[" + КАВЫЧКИ + "]", " ", имя).split())
    имя = _ФОРМА.sub("", имя).strip()
    if not имя:
        return "Ваше хозяйство", "хозяйство"
    # Длинное название хозяйства - это почти всегда «Крестьянское хозяйство
    # Пахомова Сергея Ивановича». В кавычках посреди фразы оно нечитаемо.
    if len(имя) > ПРЕДЕЛ_ДЛИНЫ:
        return "Ваше хозяйство", "хозяйство"
    if _ЛИЦО.match(имя):
        return "Ваше хозяйство", "хозяйство"
    return "«%s»" % имя, "название"
