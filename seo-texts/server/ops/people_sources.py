def провайдер(промпт, максимум=2000):
    """Один вызов провайдерского API. Стриминг обязателен.

    Шлюз рубит поток примерно на 35-й секунде, поэтому текст режется на куски
    ВЫЗЫВАЮЩЕЙ стороной, а не здесь: длинный промпт гарантированно оборвётся.
    """
    key = os.environ.get('PROVIDER_API_KEY', '')
    if not key:
        return ''
    base = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
    тело = json.dumps({'model': 'claude-fable-5', 'max_tokens': максимум,
                       'stream': True,
                       'messages': [{'role': 'user', 'content': промпт}]},
                      ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(
        base + '/v1/messages', data=тело, method='POST',
        headers={'x-api-key': key, 'anthropic-version': '2023-06-01',
                 'content-type': 'application/json',
                 'accept': 'text/event-stream', 'User-Agent': 'curl/8.5.0'})
    куски = []
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            for сырая in r:
                стр = сырая.decode('utf-8', 'replace').strip()
                if not стр.startswith('data:'):
                    continue
                try:
                    ev = json.loads(стр[5:].strip())
                except Exception:  # noqa: BLE001
                    continue
                if ev.get('type') == 'content_block_delta':
                    куски.append((ev.get('delta') or {}).get('text', ''))
    except Exception:  # noqa: BLE001
        return ''.join(куски)
    return ''.join(куски)


def люди_из_текста(текст, имя):
    """Пары «должность + ФИО» из текста. Режем на куски: шлюз рвёт длинный поток."""
    из, видано = [], set()
    for i in range(0, min(len(текст), 24000), 2800):
        кусок = текст[i:i + 2800]
        if len(кусок) < 120:
            continue
        ответ = провайдер(_ПРОМПТ.format(имя=имя[:80], текст=кусок))
        m = re.search(r'\{.*\}', ответ or '', re.S)
        if not m:
            continue
        try:
            люди = (json.loads(m.group(0)).get('люди') or [])
        except Exception:  # noqa: BLE001
            continue
        for ч in люди:
            if not isinstance(ч, dict):
                continue
            фио = (ч.get('фио') or '').strip()
            должн = (ч.get('должность') or '').strip()
            ключ = (фио.lower(), должн.lower())
            if not (фио and должн) or ключ in видано:
                continue
            видано.add(ключ)
            из.append({'фио': фио, 'должность': должн,
                       'тел': (ч.get('тел') or '').strip(),
                       'почта': (ч.get('почта') or '').lower().strip(),
                       'дата': (ч.get('дата') or '').strip()})
    return из


def текст_страницы(url):
    """Текст страницы или документа. Графику режем ДО разбора.

    Без `без_графики` координаты inline-SVG читаются как телефоны: сегодня так
    записалось 3815 «номеров», и каждый выглядел рабочим.
    """
    try:
        if _ДОК.search(url):
            return EC.doc_text(url) or ''
        html, _m, _t = EC._fetch_site(url)
        html = EC.без_графики(html or '')
        html = re.sub(r'<(script|style)[^>]*>.*?</\1>', ' ', html, flags=re.S | re.I)
        return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', ' ', html))
    except Exception:  # noqa: BLE001
        return ''


def наша_страница(текст, inn, имя):
    """Рубеж принадлежности: страница обязана доказать, что она про НАШУ компанию.

    Закрыт по умолчанию. Совпадение куска названия не доказывает ничего — на
    этом уже потеряли шесть телефонов чужого завода, а сегодня по ссылке с
    сайта в базу поехал спонсируемый хоккейный клуб. Доказательством считаем
    ИНН на странице либо все значимые токены имени.
    """
    if inn and inn in re.sub(r'\D', '', текст):
        return 'inn'
    низ = текст.lower()
    токены = [t for t in re.findall(r'[а-яёa-z]{4,}', (имя or '').lower())][:3]
    if токены and all(t in низ for t in токены[:2]):
        return 'name'
    return ''


def цели():
    if ОДИН:
        r = e.execute('SELECT inn, name FROM companies WHERE inn=?',
                      (ОДИН,)).fetchone()
        return [{'inn': ОДИН, 'name': (r[1] if r else '') or ''}]
    сделано = set()
    if os.path.exists(ПОТОК):
        for ln in io.open(ПОТОК, encoding='utf-8', errors='replace'):
            try:
                j = json.loads(ln)
            except Exception:  # noqa: BLE001
                continue
            if not j.get('err'):
                сделано.add(str(j.get('inn')))
    из = []
    # revenue_rub, а не pxr: pxr пуста у всех, и сортировка по ней даёт
    # порядок rowid под видом «сверху вниз по выручке»
    for inn, name in e.execute(
            'SELECT inn, name FROM companies WHERE name IS NOT NULL '
            'ORDER BY COALESCE(revenue_rub,0) DESC'):
        if str(inn) in сделано:
            continue
        из.append({'inn': str(inn), 'name': name or ''})
        if len(из) >= ЛИМИТ:
            break
    return из


def режимы():
    return list(ЗАПРОСЫ) if РЕЖИМ == 'all' else [РЕЖИМ]


def main():
    todo = цели()
    out = {'режим': РЕЖИМ, 'целей': len(todo), 'пройдено': 0, 'страниц': 0,
           'страниц_наших': 0, 'людей': 0, 'технических': 0, 'телефонов': 0,
           'почт': 0, 'запросов_в_выдачу': 0, 'ошибок': 0,
           'режим_записи': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
           'примеры': []}
    # раннер отдаёт stdout ХВОСТОМ — счётчики печатаем и в начале, и в конце
    print(json.dumps({'старт': True, **{k: v for k, v in out.items()
                                        if not isinstance(v, list)}},
                     ensure_ascii=False))
    ф = io.open(ПОТОК, 'a', encoding='utf-8')
    for c in todo:
        if time.time() - НАЧАЛО > БЮДЖЕТ:
            break
        inn, имя = c['inn'], c['name']
        итог = {'inn': inn, 'страниц': 0, 'людей': 0}
        адреса = []
        try:
            for м in режимы():
                for шаб in ЗАПРОСЫ[м]:
                    if time.time() - НАЧАЛО > БЮДЖЕТ:
                        break
                    out['запросов_в_выдачу'] += 1
                    адреса += [(u, м) for u in EC._serp_urls(
                        шаб.format(имя=имя[:90]), n=5)]
        except Exception as ex:  # noqa: BLE001
            out['ошибок'] += 1
            итог['err'] = f'{type(ex).__name__}:{str(ex)[:80]}'
        видано_url = set()
        for url, м in адреса:
            if time.time() - НАЧАЛО > БЮДЖЕТ:
                break
            if url in видано_url:
                continue
            видано_url.add(url)
            текст = текст_страницы(url)
            out['страниц'] += 1
            итог['страниц'] += 1
            if len(текст) < 300:
                continue
            как = наша_страница(текст, inn, имя)
            if not как:
                continue
            out['страниц_наших'] += 1
            for ч in люди_из_текста(текст, имя):
                роль = EDB.EnrichDB._canon_role(ч['должность'])
                out['людей'] += 1
                итог['людей'] += 1
                if роль in ТЕХ:
                    out['технических'] += 1
                    if len(out['примеры']) < 16:
                        out['примеры'].append(
                            {'инн': inn, 'фио': ч['фио'],
                             'должность': ч['должность'][:60], 'роль': роль,
                             'тел': ч['тел'], 'почта': ч['почта'],
                             'дата': ч['дата'], 'источник': м,
                             'ссылка': url[:90]})
                if ПРИМЕНИТЬ:
                    db.add_person(inn, ч['фио'], post=ч['должность'],
                                  phone=ч['тел'], email=ч['почта'],
                                  source='источник:' + м, source_url=url)
                    if ч['тел'] and db.add_phone(
                            inn, ч['тел'], person=ч['фио'], role=роль,
                            source='источник:' + м, source_url=url):
                        out['телефонов'] += 1
                    if ч['почта']:
                        db.add_email(inn, ч['почта'], role=роль,
                                     person=ч['фио'], source='источник:' + м,
                                     source_url=url)
                        out['почт'] += 1
        if ПРИМЕНИТЬ:
            try:
                e.execute('INSERT OR REPLACE INTO stage_log(inn, stage, detail, ts) '
                          'VALUES(?,?,?,datetime("now"))',
                          (inn, 'people_src_' + РЕЖИМ,
                           f"страниц={итог['страниц']} людей={итог['людей']}"))
                e.commit()
            except Exception:  # noqa: BLE001
                pass
        out['пройдено'] += 1
        ф.write(json.dumps(итог, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())
    ф.close()
    print(json.dumps({'примеры': out.pop('примеры')}, ensure_ascii=False)[:2000])
    print(json.dumps(out, ensure_ascii=False))


if __name__ == '__main__':
    main()
