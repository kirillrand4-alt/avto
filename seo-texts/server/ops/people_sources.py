"""Технические ЛПР из трёх источников, где человека называют по должности.

Зачем. За сутки измерено больше десяти источников — ЕИС и архив закупок,
ТЭК-Торг, Tender.pro, агрегаторы, патенты, раскрытие АО, группы ВК,
справочники, checko, hh, 2ГИС, новости о капексе. Вывод одинаковый: они дают
снабженцев, администрацию и пресс-службу, но НЕ технических руководителей.
Причина структурная — главного инженера ни в один государственный реестр не
вносят. Найти его можно только там, где о нём НАПИСАЛИ по своей воле.

Три таких места, все три предложены владельцем и ни одно не пробовалось:

  conf   — программы конференций и выставок. Строка программы это готовая
           тройка «ФИО, должность, предприятие», часто с почтой докладчика.
           На одной компании глубокий пробой дал 6 человек и 3 технарей там,
           где остальные источники давали ноль. По базе не гнали ни разу.
  assoc  — отраслевые ассоциации и союзы: членские списки и составы
           технических комитетов.
  ot     — коллективные договоры и составы комиссий по охране труда. Договор
           со стороны работодателя часто подписывает технический директор, а
           в комиссию по охране труда по закону входят главный инженер и
           главный энергетик — то есть ровно наши роли, названные должностью.

Все три устроены одинаково: запрос в выдачу -> страница или документ ->
извлечение пар «должность + ФИО» -> запись через общего писателя. Поэтому
один скрипт, а не три.

ПОЧЕМУ СКРИПТ, А НЕ АГЕНТ. Правило владельца: тяжёлое — через провайдерский
API, токенами сессии только оркестрация. Агент это полный цикл рассуждений на
сессии; здесь же логика детерминированная, а к модели уходит только разбор
текста. Прогон крутится на сервере сам и сессии не стоит ничего.

Резюмируемо: поток с fsync, повторный запуск продолжает с места остановки.
По умолчанию СУХОЙ ПРОГОН.
Запуск: python people_sources.py <conf|assoc|ot|all> [бюджет_сек] [--apply]
        [--limit N] [--inn ИНН]
"""
