# -*- coding: utf-8 -*-
"""Чистка мусора из phone_contacts: регэксп цеплял ОГРН/ИНН/счета и заглушки.

ПЕРЕПИСАНО 29.07 — прежняя версия удаляла ЖИВЫЕ номера, причём необратимо:

1. Требовала, чтобы сырая строка была «отформатирована» (+7, скобки, дефисы).
   Но номер из ссылки `tel:+74951234567` приходит слитно, а `(495) 123-45-67`
   начинается со скобки — оба считались мусором. Между тем `tel:` это самый
   надёжный источник телефона на странице.
2. Считала цифры во ВСЕЙ строке, поэтому «+7 495 123-45-67 доб. 205» давало
   14 цифр и вылетало целиком — вместе с добавочным, который и есть прямой
   номер человека.
3. Правило «в хвосте больше одной разной цифры» убивало 8-800-555-55-55 и
   495-777-77-77 — номера крупных компаний.
4. Удаляла молча и без следа: телефоны не дублируются ни в один jsonl, в
   rebuild не участвуют, восстановить можно было только новым обходом.

Теперь: валидность считается по НОРМАЛИЗОВАННЫМ цифрам основной части номера,
добавочный отделяется и не мешает; формат сырой строки не требуется вовсе;
по умолчанию СУХОЙ ПРОГОН, удаление только с --apply, и удаляемое сперва
пишется в phones_removed.jsonl с fsync.

Запуск: python phones_clean.py [--apply]
"""
import io
import json
import os
import re
import sys

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ПРИМЕНИТЬ = '--apply' in sys.argv
ЖУРНАЛ = r'C:\seostat\drop\phones_removed.jsonl'

e = EDB.EnrichDB().cx

_ДОБ = re.compile(r'(?:доб|вн|внутр|ext)\.?\s*[:№]?\s*(\d{1,5})', re.I)
# заглушки, которые встречаются в шаблонах сайтов
_ПУСТЫШКИ = {'0000000000', '1234567890', '9999999999', '1111111111',
             '0123456789', '1234512345'}


def основная_часть(сырой):
    """Цифры номера БЕЗ добавочного: «+7 495 123-45-67 доб. 205» -> 4951234567."""
    s = str(сырой or '').strip()
    d = _ДОБ.search(s)
    ц = re.sub(r'\D', '', s[:d.start()] if d else s)
    if len(ц) == 11 and ц[0] in '78':
        ц = ц[1:]
    return ц


def валиден(сырой):
    ц = основная_часть(сырой)
    if len(ц) != 10:
        return False
    if ц[0] == '0' or ц[:3] == '000':
        return False
    if ц in _ПУСТЫШКИ:
        return False
    # все цифры одинаковые — заглушка; «в хвосте одна цифра» НЕ проверяем:
    # под это правило подпадали 8-800-555-55-55 и 495-777-77-77
    if len(set(ц)) == 1:
        return False
    # последовательность 0123456789 в любом сдвиге — тоже шаблонная заглушка
    if ц in '01234567890123456789':
        return False
    return True


def починить(сырой):
    """Попытка спасти строку вместо удаления. Возвращает исправленный номер или ''.

    Смотрю на то, что реально лежит в базе: «74112408009 1216» и
    «7-916-6064994-4291» — это НОМЕР ПЛЮС ДОБАВОЧНЫЙ, слипшиеся без метки
    «доб.». Удалять такое — терять прямой телефон человека, а он ценнее
    общего. Берём первые 11 цифр как номер, хвост в 1–5 цифр как добавочный.
    «7499 (499) 5178888» — задвоенный код города, лечится тем же правилом.
    """
    s = str(сырой or '')
    ц = re.sub(r'\D', '', s)
    if len(ц) < 12 or len(ц) > 16:
        return ''
    осн, хвост = ц[:11], ц[11:]
    if осн[0] not in '78' or not (1 <= len(хвост) <= 5):
        return ''
    к = осн[1:]
    if len(к) != 10 or к[0] == '0' or к[:3] == '000' or len(set(к)) == 1:
        return ''
    номер = f'+7 ({к[:3]}) {к[3:6]}-{к[6:8]}-{к[8:]}'
    return f'{номер} доб.{хвост}'


def main():
    строки = list(e.execute(
        'SELECT rowid, inn, phone, person, role, source, source_url '
        'FROM phone_contacts'))
    плохие, чинимые = [], []
    for r in строки:
        if валиден(r[2]):
            continue
        исправлен = починить(r[2])
        зап = dict(zip(('rowid', 'inn', 'phone', 'person', 'role', 'source',
                        'source_url'), r))
        if исправлен and валиден(исправлен):
            зап['стало'] = исправлен
            чинимые.append(зап)
        else:
            плохие.append(зап)
    out = {'всего': len(строки), 'чинится': len(чинимые),
           'невалидных_после_починки': len(плохие),
           'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой прогон (применить: --apply)',
           'примеры_починки': [{'было': x['phone'], 'стало': x['стало']}
                               for x in чинимые[:10]],
           'примеры_удаления': [{'тел': x['phone'], 'источник': x['source']}
                                for x in плохие[:10]]}
    if ПРИМЕНИТЬ and чинимые:
        for x in чинимые:
            e.execute('UPDATE phone_contacts SET phone=? WHERE rowid=?',
                      (x['стало'], x['rowid']))
        e.commit()
        out['починено'] = len(чинимые)
    if ПРИМЕНИТЬ and плохие:
        os.makedirs(os.path.dirname(ЖУРНАЛ), exist_ok=True)
        with io.open(ЖУРНАЛ, 'a', encoding='utf-8') as f:
            for x in плохие:
                f.write(json.dumps(x, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())
        e.executemany('DELETE FROM phone_contacts WHERE rowid=?',
                      [(x['rowid'],) for x in плохие])
        e.commit()
        out['удалено'] = len(плохие)
        out['журнал'] = ЖУРНАЛ
        out['осталось'] = e.execute(
            'SELECT COUNT(*) FROM phone_contacts').fetchone()[0]
    print(json.dumps(out, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
