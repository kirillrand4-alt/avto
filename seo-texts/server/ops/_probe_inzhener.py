# -*- coding: utf-8 -*-
"""Сколько «гл.инженеров» в базе получены голыми ключами «инженер» и «техни».

В `_ROLE_CANON` последнее инженерное правило содержит ключи `'инженер'` и
`'техни'` без уточнений. Значит «Инженер по метрологии», «Ведущий инженер»,
«Техник» и «Отдел технического контроля» становятся главными инженерами, то
есть техническими ЛПР. Прежде чем править канон, которым пользуется вся база
и панель, надо знать цену вопроса в живых строках.

Ничего не меняем — только считаем и показываем должности глазами.
"""
import json
import sys
from collections import Counter

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ТОЧНЫЕ = ('гл.инженер', 'гл. инженер', 'главный инженер', 'главн. инженер',
          'главного инженер', 'главному инженер', 'главным инженер')


def main():
    cx = EDB.EnrichDB().cx
    строки = cx.execute(
        "SELECT COALESCE(post,''),COALESCE(role,''),COUNT(*) FROM people "
        "GROUP BY 1,2").fetchall()
    точно = широко = 0
    д_точно = Counter()
    д_широко = Counter()
    for пост, роль, n in строки:
        if роль != 'гл.инженер':
            continue
        п = пост.lower()
        if any(т in п for т in ТОЧНЫЕ):
            точно += n
            д_точно[пост[:60]] += n
        else:
            широко += n
            д_широко[пост[:60]] += n

    # то же по телефонам: там роль тоже канонизируется
    тел = cx.execute(
        "SELECT COALESCE(role,''),COUNT(*) FROM phone_contacts GROUP BY 1"
    ).fetchall()

    print(json.dumps({
        'людей_с_ролью_гл.инженер': точно + широко,
        'из_них_подпись_реально_главный_инженер': точно,
        'из_них_получены_голым_инженер_техни': широко,
        'частые_должности_широкого_захвата': д_широко.most_common(25),
        'частые_должности_точного': д_точно.most_common(6),
        'телефоны_по_ролям': sorted(тел, key=lambda r: -r[1])[:10],
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
