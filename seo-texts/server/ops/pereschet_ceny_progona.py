# -*- coding: utf-8 -*-
"""Пересчитать цену последнего прогона по ФАКТИЧЕСКОЙ ставке модели.

Журнал хранит цену, посчитанную ставкой, действовавшей на момент прогона.
Для чужих моделей она была опусовой (5/25) — это ошибка выбора тарифа, а не
данных: токены в журнале верные, пересчитать можно.
"""
import io
import json
import sys
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
МОДЕЛЬ = sys.argv[1] if len(sys.argv) > 1 else "gpt-5.6-luna"
СТАВКИ = {"gpt-5.6-luna": (0.11, 0.67), "claude-opus-4-8": (5.0, 25.0),
          "claude-sonnet-4-6": (3.0, 15.0), # ФАКТИЧЕСКАЯ ставка deepseek выведена из журнала СПИСАНИЙ шлюза, а не из
          # его прайса: 8622 вход / 4000 выход -> $0.045634, и так восемь строк
          # подряд. Прайс не сходится ни первой колонкой ($0.0055), ни второй
          # ($0.0894). При соотношении вход:выход 1:3 (одинаковом в обеих
          # колонках) это даёт $2.21/$6.64.
          "deepseek-v4-flash": (2.21, 6.64),
          "claude-sonnet-5": (3.0, 15.0), "claude-fable-5": (10.0, 50.0)}
# ПОСЛЕДНИЕ N. Журнал накопительный: по опусу там тысячи строк со всей
# партии, а сравнивать надо СВЕЖИЙ прогон в тех же условиях.
ПОСЛЕДНИХ = int(next((a for a in sys.argv[2:] if a.isdigit()), "0"))
ПРОВЕРКИ = (3.0, 15.0)                       # проверки идут на sonnet-4-6

вх_ст, вых_ст = СТАВКИ.get(МОДЕЛЬ, (5.0, 25.0))
строки = []
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    # ТОЛЬКО ЭТАП «итог»: на письмо приходится две строки журнала, и обе
    # несут цену. Без этого фильтра прогон из 10 попыток выглядит как 20, а
    # сумма удваивается (доли за попытку и за письмо при этом уцелели бы —
    # удвоились и числитель, и знаменатель, — но абсолютная сумма врёт).
    if (str(z.get("модель") or "") == МОДЕЛЬ
            and z.get("цена_$") is not None
            and z.get("этап") == "итог"):
        строки.append(z)

if ПОСЛЕДНИХ:
    строки = строки[-ПОСЛЕДНИХ:]
if not строки:
    print(f"строк модели {МОДЕЛЬ} в журнале нет"); raise SystemExit(1)

ц = Counter()
годных = 0
for z in строки:
    ц["как_было"] += float(z.get("цена_$") or 0)
    ц["письмо_было"] += float(z.get("цена_письма_$") or 0)
    ц["проверки"] += float(z.get("цена_проверок_$") or 0)
    if z.get("тело"):
        годных += 1
n = len(строки)
# цена письма считалась по опусовой ставке 5/25 -> приводим к фактической
доля = (вх_ст + вых_ст) / (5.0 + 25.0)
письмо_факт = ц["письмо_было"] * доля
итого = письмо_факт + ц["проверки"]

print(f"== {МОДЕЛЬ}: попыток {n}, годных {годных} "
      f"({годных/n*100:.0f}%) ==")
print(f"  как посчитал журнал (опусовая ставка): ${ц['как_было']:.2f} "
      f"= ${ц['как_было']/n:.4f} за попытку")
print(f"  ПО ФАКТИЧЕСКОЙ СТАВКЕ {вх_ст}/{вых_ст}:")
print(f"    письмо   ${письмо_факт:.4f}")
print(f"    проверки ${ц['проверки']:.4f}  (sonnet-4-6, ставка не менялась)")
print(f"    ИТОГО    ${итого:.4f} = ${итого/n:.4f} за попытку")
if годных:
    print(f"    ЗА ГОДНОЕ ПИСЬМО: ${итого/годных:.4f}")
print("\n  (приведение по доле ставок — точное для входа и выхода в равной"
      "\n   пропорции; точный пересчёт потребовал бы токенов по каждому вызову,"
      "\n   их журнал не хранит раздельно)")
