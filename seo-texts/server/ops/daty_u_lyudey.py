# -*- coding: utf-8 -*-
"""Дата события у каждого человека и подпись, ЧТО это за дата.

Поправка владельца, переданная второй сессией: связку «человек — роль» гасить
по сроку НЕЛЬЗЯ («иногда и 120 месяцев»), надо показывать продавцу дату и
давать ему решать. Двадцать месяцев были нашим замером на одной выборке, а
правило из него вывели шире доказанного.

Что здесь важно и чего у меня не было. В базе есть `observed_at`, и это дата
НАШЕГО НАБЛЮДЕНИЯ на источнике, а не дата события. Выгрузить её без подписи
хуже, чем не выгружать вовсе: «12.03.2024» продавец прочитает как «человек
занял должность тогда-то», а на деле это день, когда мы зашли на страницу.
Поэтому дата всегда идёт ПАРОЙ с подписью, что это за дата.

Порядок предпочтения, от самого сильного к самому слабому:
  1. дата закупки, в карточке которой человек назван (Тендер.Про, ЕИС);
  2. дата предостережения/проверки, где человек назван (ЕРКНМ);
  3. дата новости о назначении;
  4. дата вакансии hh, если человек взят из вакансии;
  5. дата нашего наблюдения — помечается дословно так и не выдаётся за событие;
  6. «даты нет: источник её не публикует» — пустую ячейку не оставляю, пустое
     читается как «не искали».

Сперва СЧИТАЕТ, что есть, и только потом пишет: я не знаю заранее, у скольких
людей дата события вообще достижима, а придумывать покрытие нельзя.

Запуск: python daty_u_lyudey.py            (только замер)
        python daty_u_lyudey.py --export   (замер + CSV на дроп)
"""
import csv
import io
import os
import re
import sys
from collections import Counter

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ДРОП = r'C:\seostat\drop\drop-storage'
ПАПКА = r'C:\sender\server'
ИМЯ = 'LYUDI-1-SESSIYA-s-datami.csv'
ЭКСПОРТ = '--export' in sys.argv

_ДАТА = re.compile(r'(\d{2})[.\-/](\d{2})[.\-/](\d{4})|(\d{4})-(\d{2})-(\d{2})')


def норм_дата(т):
    """Любая дата к ISO. Пустая строка, если даты нет."""
    м = _ДАТА.search(str(т or ''))
    if not м:
        return ''
    if м.group(1):
        return f'{м.group(3)}-{м.group(2)}-{м.group(1)}'
    return f'{м.group(4)}-{м.group(5)}-{м.group(6)}'


def клч(ф):
    """Ключ ФИО: ё и регистр уже один раз стоили мне пропущенного дубля
    (Головачев / Головачёв при одном ИНН). Сравниваю нормализованно."""
    return re.sub(r'\s+', ' ', str(ф or '').strip().lower()).replace('ё', 'е')


def на_дроп(путь, имя):
    import urllib.request
    урл = os.environ.get('DROP_URL', 'https://parsercompressor.online/drop')
    зпр = urllib.request.Request(
        урл.rstrip('/') + '/' + имя, data=open(путь, 'rb').read(), method='PUT',
        headers={'X-Drop-Token': os.environ.get('DROP_TOKEN', '')})
    with urllib.request.urlopen(зпр, timeout=180) as о:
        return о.read()[:200]


def читать(имя):
    п = os.path.join(ДРОП, имя)
    if not os.path.exists(п):
        return []
    return list(csv.DictReader(
        io.StringIO(open(п, encoding='utf-8-sig', errors='replace').read()),
        delimiter=';'))


def main():
    db = EDB.EnrichDB()
    q = db.cx.execute
    тех = set(EDB.EnrichDB.TECH_ROLES)

    # --- справочник дат закупок Тендер.Про: tender_id -> дата
    # Колонка НЕ угадывается по списку имён: в выгрузке дата создания закупки
    # лежит в `sozdan`, и первый прогон вернул ноль дат именно поэтому. Ноль
    # был поломкой моего чтения, а не отсутствием дат в источнике. Поэтому
    # теперь имя колонки ищется по содержимому — берём первую колонку, в
    # которой у большинства строк распознаётся дата, — и печатается.
    ряды_сп = читать('tp-spisok.csv')
    поле_даты = ''
    if ряды_сп:
        проба = ряды_сп[:200]
        лучшее = 0
        for к in ряды_сп[0].keys():
            n = sum(1 for r in проба if норм_дата(r.get(к)))
            if n > лучшее:
                лучшее, поле_даты = n, к
        print(f'дата закупки взята из колонки «{поле_даты}» '
              f'({лучшее} из {len(проба)} проб распознались)')
    даты_закупок = {}
    for r in ряды_сп:
        д = норм_дата(r.get(поле_даты)) if поле_даты else ''
        т = (r.get('tender_id') or '').strip()
        if т and д:
            даты_закупок[т] = д
    # человек -> tender_id (через lica + inn)
    инн_по_ид = {r['company_id']: r['inn'].strip()
                 for r in читать('tp-inn.csv') if (r.get('inn') or '').strip()}
    дата_чел = {}
    for r in читать('tp-lica.csv'):
        инн = инн_по_ид.get(r.get('company_id') or '')
        фио = (r.get('imya') or '').strip()
        д = даты_закупок.get((r.get('tender_id') or '').strip(), '')
        if инн and фио and д:
            к = (инн, клч(фио))
            if д > дата_чел.get(к, ''):
                дата_чел[к] = д          # самая свежая закупка человека
    print(f'дат закупок в справочнике: {len(даты_закупок)}')
    print(f'людей Тендер.Про с датой закупки: {len(дата_чел)}')

    # --- даты из сигналов предприятия (ЕРКНМ, hh, новости)
    # У `signals` нет `observed_at` — есть `ts` (наша запись) и текст `what`,
    # в котором дата события обычно и стоит. Первый прогон упал на этом молча
    # и напечатал ноль. Дата ИЗ ТЕКСТА события сильнее нашей `ts`, и подпись у
    # них разная: путать их — ровно то, от чего предостерегает поправка.
    сигналы = {}
    из_текста = из_ts = 0
    for инн, ист, тип, что, ts in q(
            "SELECT inn, COALESCE(source,''), COALESCE(event_type,''), "
            "COALESCE(what,''), COALESCE(ts,'') FROM signals").fetchall():
        м = (ист + ' ' + тип + ' ' + что).lower()
        д = норм_дата(что)
        if д:
            из_текста += 1
            подпись = ('дата предостережения ЕРКНМ' if 'предостереж' in м
                       or 'еркнм' in м
                       else 'дата вакансии hh' if 'hh' in м or 'ваканс' in м
                       else 'дата новости' if 'новост' in м or 'news' in м
                       else 'дата события у предприятия')
        else:
            д = норм_дата(ts)
            if not д:
                continue
            из_ts += 1
            подпись = 'дата, когда МЫ записали событие предприятия, не дата события'
        п = сигналы.get(инн)
        if not п or д > п[0]:
            сигналы[инн] = (д, подпись)
    print(f'предприятий с датой в сигналах: {len(сигналы)} '
          f'(дата из текста события {из_текста}, только наша ts {из_ts})')

    ряды = q(
        "SELECT p.inn, COALESCE(c.name,''), p.person, COALESCE(p.post,''), "
        "COALESCE(p.role,''), COALESCE(p.phone,''), COALESCE(p.email,''), "
        "COALESCE(p.source,''), COALESCE(p.source_url,''), "
        "COALESCE(p.observed_at,'') FROM people p "
        'LEFT JOIN companies c ON c.inn = p.inn ORDER BY p.inn').fetchall()

    строки = []
    подписи = Counter()
    подписи_тех = Counter()
    for инн, комп, фио, пост, роль, тел, поч, ист, урл, набл in ряды:
        д = дата_чел.get((инн, клч(фио)), '')
        подпись = 'дата закупки, в карточке которой человек назван' if д else ''
        if not д and инн in сигналы:
            д, подпись = сигналы[инн]
        if not д and норм_дата(набл):
            д = норм_дата(набл)
            подпись = 'дата НАШЕГО наблюдения на источнике, не дата события'
        if not д:
            подпись = 'даты нет: источник её не публикует'
        подписи[подпись] += 1
        if роль in тех or роль == 'техконтакт':
            подписи_тех[подпись] += 1
        строки.append([инн, комп[:70], фио, пост[:100], роль,
                       'да' if роль in тех else 'нет', тел, поч, д, подпись,
                       ист, урл])

    print()
    print(f'=== ЧТО ЗА ДАТА У ЧЕЛОВЕКА (всего людей {len(строки)}) ===')
    for п, n in подписи.most_common():
        print(f'  {n:>5}  ({round(100 * n / max(1, len(строки))):>2}%)  {п}')
    тл = sum(подписи_тех.values())
    print(f'--- то же по техническим ({тл}) ---')
    for п, n in подписи_тех.most_common():
        print(f'  {n:>5}  ({round(100 * n / max(1, тл)):>2}%)  {п}')

    if not ЭКСПОРТ:
        print()
        print('замер, файл не писал (запуск с --export)')
        return

    путь = os.path.join(ПАПКА, ИМЯ)
    with open(путь, 'w', encoding='utf-8-sig', newline='') as ф:
        в = csv.writer(ф, delimiter=';')
        в.writerow(['inn', 'kompaniya', 'fio', 'dolzhnost', 'rol', 'tehLPR',
                    'telefon', 'pochta', 'data_sobytiya', 'chto_za_data',
                    'istochnik', 'ssylka_na_istochnik'])
        в.writerows(строки)
        ф.flush()
        os.fsync(ф.fileno())

    # число перечитыванием файла
    вс = сдатой = 0
    with open(путь, encoding='utf-8-sig', newline='') as ф:
        for r in csv.DictReader(ф, delimiter=';'):
            вс += 1
            if r['data_sobytiya'].strip():
                сдатой += 1
    print()
    print('=== ПЕРЕЧИТЫВАНИЕМ ФАЙЛА ===')
    print(f'  строк {вс}, с проставленной датой {сдатой}, '
          f'у остальных подпись «даты нет»')
    try:
        на_дроп(путь, ИМЯ)
        print(f'  на дропе: {ИМЯ}')
    except Exception as e:  # noqa: BLE001
        print(f'  на дроп НЕ легло: {str(e)[:120]}')
    print(f'строк {вс}, с датой {сдатой}')


if __name__ == '__main__':
    main()
