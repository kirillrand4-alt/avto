# -*- coding: utf-8 -*-
"""Тысяча писем проверенным конвейером, писатель — sonnet.

Замер 24.08 на двенадцати письмах: конвейер + sonnet даёт 83% годных по
$0.225 за годное письмо, против 97% и $0.67 у опуса и против 8-16% и $0.86
у моей механической схемы. Механика проиграла потому, что за годное письмо
платятся все неудачные попытки.

Гоняем блоками по 250, между блоками — сверка расхода с потолком. Владелец
дал $250 остатка, поэтому потолок жёсткий: перед каждым блоком смотрим, во
что обошёлся предыдущий, и не начинаем новый, если денег на него не хватит.
"""
import io
import json
import os
import re
import subprocess
import time

ПИТОН = r"C:\Program Files\Python311\python.exe"
КАТАЛОГ = r"C:\sender\_ops"
ОТЧЁТ = os.path.join(КАТАЛОГ, "tysyacha-sonnet.jsonl")
БЮДЖЕТ = 230.0
БЛОК = 250
НАПРАВЛЕНИЯ = ["kc", "kc", "meyer", "kc"]


def записать(с):
    with io.open(ОТЧЁТ, "a", encoding="utf-8") as ф:
        ф.write(json.dumps(с, ensure_ascii=False) + "\n")
        ф.flush()
        os.fsync(ф.fileno())


потрачено = 0.0
записать({"этап": "старт", "бюджет": БЮДЖЕТ, "блок": БЛОК, "ts": time.time()})
for н, напр in enumerate(НАПРАВЛЕНИЯ, 1):
    if потрачено + 60 > БЮДЖЕТ:
        print("СТОП по бюджету: потрачено $%.2f из $%.2f" % (потрачено, БЮДЖЕТ))
        записать({"этап": "стоп_бюджет", "потрачено": round(потрачено, 2)})
        break
    лог = os.path.join(КАТАЛОГ, "tysyacha-blok%d-%s.log" % (н, напр))
    print("\n=== БЛОК %d: %d писем %s ===" % (н, БЛОК, напр.upper()), flush=True)
    записать({"этап": "блок_старт", "блок": н, "направление": напр,
              "потрачено_до": round(потрачено, 2), "ts": time.time()})
    with io.open(лог, "w", encoding="utf-8") as ф:
        код = subprocess.call(
            [ПИТОН, os.path.join(КАТАЛОГ, "partiya_gen.py"), str(БЛОК),
             "9000", напр, "0", "porog=2.50", "model=claude-sonnet-4-6"],
            stdout=ф, stderr=subprocess.STDOUT, cwd=КАТАЛОГ)
    итог = ""
    цена = 0.0
    try:
        строки = io.open(лог, encoding="utf-8", errors="replace").readlines()
        итог = next((с.strip() for с in reversed(строки)
                     if с.startswith("итог:")), "")
        м = re.search(r"\$([\d.]+)", итог)
        if м:
            цена = float(м.group(1))
    except Exception as e:  # noqa: BLE001
        итог = "лог не прочитан: %s" % e
    потрачено += цена
    print("  блок %d: %s | всего потрачено $%.2f" % (н, итог, потрачено),
          flush=True)
    записать({"этап": "блок_конец", "блок": н, "код": код, "итог": итог,
              "цена_блока": цена, "потрачено": round(потрачено, 2),
              "ts": time.time()})

записать({"этап": "конец", "потрачено": round(потрачено, 2), "ts": time.time()})
print("\nвсего потрачено: $%.2f" % потрачено)
