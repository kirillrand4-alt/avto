# -*- coding: utf-8 -*-
"""СУХОЙ ЗАМЕР: скольким фактам можно проставить среду ИЗ ИХ ЖЕ ЦИТАТЫ.

ОТКУДА. 3-я сессия нашла класс дефекта: в цитате факта прямым текстом стоит
«турбокомпрессора ВОЗДУШНОГО», а поле `medium` пусто или «не названа». Замер
1-й сессии: таких фактов 1057. Среда — главный признак отбора («наша машина /
не наша»), поэтому пустое поле при говорящей цитате это не косметика.

ЧТО СЧИТАЕТ. Берём факты `centrifugal.db.fact`, у которых среда НЕ проставлена
(пусто, прочерк, «не названа/не указана/не определена/неизвестно»), и смотрим
ТОЛЬКО в цитату по строгим правилам владельца задачи:

  воздух  — в цитате «воздушн», «воздуха», «сжатого воздуха», «атмосферн»
            И НЕТ ни одного газового признака;
  газ     — в цитате «природного газа», «попутного газа», «газоперекачивающ»,
            «ГПА», «магистральн* газопровод», «дожимн*»;
  не трогать — в цитате есть И воздух, И газ (честная неопределённость
            источника, 3-я сессия прямо просила это не трогать), либо нет
            ничего из перечисленного.

Правила НАРОЧНО уже боевых `centro_medium`: это не переклассификация базы, а
перенос уже написанного в документе в пустое поле.

ОТДЕЛЬНО: у скольких ПРЕДПРИЯТИЙ это меняет вывод «наша машина / не наша».
Вывод считается боевым гейтом `centro_medium.rejection_reason`: предприятие
«наше», если у него остаётся хотя бы один непроотсеянный факт. Гейт уже читает
цитату, поэтому проставленный «воздух» вывод обычно НЕ двигает, а «газ» в поле
среды включает `is_definitely_non_air_medium` и может убрать факт. Считаем
до и после по одному и тому же гейту, чтобы разница была честной.

НИЧЕГО НЕ ПИШЕТ. Открывает базу в режиме ro, ключа --apply нет намеренно.

Запуск: python sreda_iz_citaty_wf.py
"""
import json
import os
import re
import sqlite3
import sys
from collections import Counter

sys.path.insert(0, r'C:\seostat')
try:
    from app.services import centro_medium as CM  # noqa: E402
except Exception as e:  # noqa: BLE001
    CM = None
    _CM_ERR = str(e)
else:
    _CM_ERR = ''

БАЗА = os.getenv('CENTRIFUGAL_DB') or r'C:\seostat\data\centrifugal.db'

# --- строгие правила из задачи ---------------------------------------------
_ВОЗДУХ = re.compile(r'воздушн|воздуха|сжат\w*\s+воздух|атмосферн', re.I)
_ГАЗ = re.compile(
    r'природн\w*\s+газ|попутн\w*\s+газ|газоперекачивающ|\bГПА\b|'
    r'магистральн\w*\s+газопровод|дожимн\w*', re.I)

# среда считается НЕ проставленной
_ПУСТО = re.compile(
    r'^\s*$|^\s*[-—–]+\s*$|не\s*назван|не\s*указан|не\s*определ|'
    r'неизвест|нет\s*данн', re.I)

# ДИАГНОСТИКА ПРОМАХОВ строгих правил. Строгий воздух не ловит голое слово
# «воздух» в именительном/творительном («Воздух КИП», «воздухом»), а строгий
# газ ловит «дожимн*» в НАЗВАНИИ ЗДАНИЯ («дожимная компрессорная»), где среда
# машины вовсе не газ. Считаем эти случаи отдельно, чтобы правило не поехало
# в базу вслепую.
_ВОЗДУХ_ШИРОКО = re.compile(r'воздух\w*|воздуш\w*', re.I)
_ПРИЗНАКИ_ГАЗА = (
    ('природного_газа', re.compile(r'природн\w*\s+газ', re.I)),
    ('попутного_газа', re.compile(r'попутн\w*\s+газ', re.I)),
    ('газоперекачивающ', re.compile(r'газоперекачивающ', re.I)),
    ('ГПА', re.compile(r'\bГПА\b', re.I)),
    ('магистральный_газопровод', re.compile(r'магистральн\w*\s+газопровод', re.I)),
    ('дожимн', re.compile(r'дожимн\w*', re.I)),
)


# --- ВАРИАНТ Б: те же правила, но с двумя заплатами по итогам прогона ------
# 1) воздух ловится в любой форме: строгий шаблон не видит «Воздух КИП» и
#    «Технический воздух» (именительный), и такие цитаты уезжали в газ;
# 2) «дожимн*» само по себе НЕ признак газа — это чаще имя здания («Дожимная
#    компрессорная», «трубопровод воды в дожимной компрессорной»). Требуем
#    рядом газ или ДКС.
_ВОЗДУХ_Б = _ВОЗДУХ_ШИРОКО
_ГАЗ_Б = re.compile(
    r'природн\w*\s+газ|попутн\w*\s+газ|газоперекачивающ|\bГПА\b|'
    r'магистральн\w*\s+газопровод|'
    r'дожимн\w*(?:\s+\w+){0,3}\s*(?:газ\w*|\bДКС\b)|\bДКС\b\s*[-–]?\s*\d*\s*газ',
    re.I)


def из_цитаты_б(цитата):
    ц = str(цитата or '')
    в = bool(_ВОЗДУХ_Б.search(ц))
    г = bool(_ГАЗ_Б.search(ц))
    if в and г:
        return ''
    return 'воздух' if в else ('газ' if г else '')


def среда_не_проставлена(значение):
    return bool(_ПУСТО.search(str(значение or '')))


def из_цитаты(цитата):
    """'воздух' | 'газ' | '' (не трогать)."""
    ц = str(цитата or '')
    в = bool(_ВОЗДУХ.search(ц))
    г = bool(_ГАЗ.search(ц))
    if в and г:
        return ''          # оба названы — честная неопределённость
    if в:
        return 'воздух'
    if г:
        return 'газ'
    return ''              # цитата молчит


def наше(факт):
    """Оставляет ли боевой гейт этот факт (True = наша машина)."""
    if CM is None:
        return True
    try:
        return not CM.rejection_reason(факт)
    except Exception:  # noqa: BLE001
        return True


def main():
    cx = sqlite3.connect(f'file:{БАЗА}?mode=ro', uri=True, timeout=30)
    cx.row_factory = sqlite3.Row
    кол = {c[1] for c in cx.execute('PRAGMA table_info("fact")')}
    нужны = ['inn', 'status', 'model', 'equipment_type', 'medium',
             'evidence', 'quote', 'source']
    выб = ', '.join(f"COALESCE({к},'') AS {к}" if к in кол else f"'' AS {к}"
                    for к in нужны)
    строки = [dict(r) for r in cx.execute(f'SELECT rowid AS rid, {выб} FROM fact')]
    cx.close()

    итог = Counter()
    примеры = {'воздух': [], 'газ': [], 'не_трогать_оба': [],
               'не_трогать_молчит': [], 'гейт_поменял_ответ': [],
               'промах_газ_но_воздух': []}
    правки = {}                       # rid -> новая среда
    предпр_с_правкой = set()
    по_предпр_было = {}               # inn -> bool «наша машина»
    по_предпр_стало = {}

    for ф in строки:
        инн = str(ф['inn'])
        было_наше = наше(ф)
        по_предпр_было[инн] = по_предпр_было.get(инн, False) or было_наше

        стало_наше = было_наше
        if среда_не_проставлена(ф['medium']):
            итог['фактов_среда_пуста'] += 1
            ц = ф['quote']
            в = bool(_ВОЗДУХ.search(ц))
            г = bool(_ГАЗ.search(ц))
            б = из_цитаты_б(ц)
            итог['Б_' + (б or 'не_трогать')] += 1
            новая = из_цитаты(ц)
            if новая:
                итог[f'ПРОСТАВИТЬ_{новая}'] += 1
                правки[ф['rid']] = новая
                предпр_с_правкой.add(инн)
                if len(примеры[новая]) < 5:
                    примеры[новая].append({'инн': инн, 'модель': ф['model'][:40],
                                           'цитата': ' '.join(ц.split())[:160]})
                после = dict(ф)
                после['medium'] = новая
                стало_наше = наше(после)
                if стало_наше != было_наше:
                    итог['ФАКТОВ_гейт_менял_ответ'] += 1
                    итог['факт_был_наш_стал_НЕ' if было_наше
                         else 'факт_был_НЕ_стал_наш'] += 1
                    if len(примеры['гейт_поменял_ответ']) < 5:
                        примеры['гейт_поменял_ответ'].append({
                            'инн': инн, 'новая_среда': новая,
                            'было': 'наша' if было_наше else 'не наша',
                            'цитата': ' '.join(ц.split())[:140]})
                if новая == 'газ':
                    for имя, рег in _ПРИЗНАКИ_ГАЗА:
                        if рег.search(ц):
                            итог['газ_по_' + имя] += 1
                    if _ВОЗДУХ_ШИРОКО.search(ц):
                        итог['ПРОМАХ_газ_а_в_цитате_есть_воздух'] += 1
                        if len(примеры['промах_газ_но_воздух']) < 5:
                            примеры['промах_газ_но_воздух'].append({
                                'инн': инн,
                                'цитата': ' '.join(ц.split())[:140]})
            else:
                ключ = 'не_трогать_оба' if (в and г) else 'не_трогать_молчит'
                итог[ключ] += 1
                if len(примеры[ключ]) < 5:
                    примеры[ключ].append({'инн': инн, 'модель': ф['model'][:40],
                                          'цитата': ' '.join(ц.split())[:160]})
        else:
            итог['фактов_среда_есть'] += 1

        по_предпр_стало[инн] = по_предпр_стало.get(инн, False) or стало_наше

    сменили = [и for и in по_предпр_было
               if по_предпр_было[и] != по_предпр_стало.get(и)]
    стали_не_наши = [и for и in сменили if по_предпр_было[и]]
    стали_наши = [и for и in сменили if not по_предпр_было[и]]

    # --primery: только примеры и покороче. Полный вывод не влезает в хвост
    # stdout раннера, а примеры нужны глазами — печатаем их отдельным прогоном.
    if '--primery' in sys.argv:
        сжато = {к: [{'инн': п['инн'], 'цитата': п['цитата'][:110]} for п in v]
                 for к, v in примеры.items()}
        print(json.dumps(сжато, ensure_ascii=False, indent=1))
        return

    print(json.dumps({
        'РЕЖИМ': 'СУХОЙ ПРОГОН, база открыта только на чтение',
        'боевой_гейт': 'centro_medium.rejection_reason' if CM else f'НЕДОСТУПЕН: {_CM_ERR}',
        'фактов_всего': len(строки),
        'фактов_среда_пуста': итог['фактов_среда_пуста'],
        'ПРОСТАВИТЬ_воздух': итог['ПРОСТАВИТЬ_воздух'],
        'ПРОСТАВИТЬ_газ': итог['ПРОСТАВИТЬ_газ'],
        'НЕ_ТРОГАТЬ_оба_названы': итог['не_трогать_оба'],
        'НЕ_ТРОГАТЬ_цитата_молчит': итог['не_трогать_молчит'],
        'ВАРИАНТ_Б_воздух': итог['Б_воздух'],
        'ВАРИАНТ_Б_газ': итог['Б_газ'],
        'ВАРИАНТ_Б_не_трогать': итог['Б_не_трогать'],
        'ФАКТОВ_гейт_менял_ответ': итог['ФАКТОВ_гейт_менял_ответ'],
        'факт_был_наш_стал_НЕ': итог['факт_был_наш_стал_НЕ'],
        'факт_был_НЕ_стал_наш': итог['факт_был_НЕ_стал_наш'],
        'ПРОМАХ_газ_а_в_цитате_есть_воздух':
            итог['ПРОМАХ_газ_а_в_цитате_есть_воздух'],
        'разбивка_признаков_газа': {
            и: итог['газ_по_' + и] for и, _ in _ПРИЗНАКИ_ГАЗА},
        'предприятий_всего_с_фактами': len(по_предпр_было),
        'предприятий_получат_хоть_одну_правку': len(предпр_с_правкой),
        'предприятий_вывод_меняется': len(сменили),
        'из_них_стали_НЕ_наши': len(стали_не_наши),
        'из_них_стали_наши': len(стали_наши),
        'ИНН_стали_НЕ_наши': стали_не_наши[:40],
        'ИНН_стали_наши': стали_наши[:40],
        'примеры': {} if '--kratko' in sys.argv else примеры,
    }, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
