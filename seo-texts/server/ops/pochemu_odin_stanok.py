# -*- coding: utf-8 -*-
"""Почему в письме остался один станок: у компании нет задачи или модель не вняла.

Смотрим на то, ЧТО за продукт у получателя: если сырьё сортировать нечего
(мясные полуфабрикаты, розлив, фасовка чужого), один станок - правильный
ответ, и виноват мой детектор «пищевого профиля», а не правило.
"""
import re
import sys

sys.path.insert(0, r"C:\sender")
from sender.config import Config                                 # noqa: E402
from sender.store import Store                                   # noqa: E402

РЕНТГЕН = re.compile(r'(?i)рентген|инспекци\w*\s+упаков|металлодетект')
ФОТО = re.compile(r'(?i)фотосепарат|оптическ\w*\s+сортиров|'
                  r'сортировк\w*\s+(сырь|зерн|орех|крупы)')
# СЫПУЧЕЕ СЫРЬЁ, А НЕ «ЛЮБАЯ ЕДА». Первая редакция считала пищевым
# профилем и мясные полуфабрикаты, и рыбу - и записала в промахи шесть
# писем, где один рентген был правильным ответом: филе лосося и фарш
# фотосепаратором не сортируют. Ловим только то, где поток сыпучий.
ПИЩЕВОЙ = re.compile(
    r'(?i)кондитер|выпечк|хлебобулочн|мука|муком|крупа|крупян|зерн|'
    r'орех|сухофрукт|мюсли|батончик|шоколад|конфет|пряник|печенье|'
    r'снек|семечк|бобов|специ|чай\b|кофе|какао|сухие\s+смеси|'
    r'сыпуч|комбикорм|солод')

cfg = Config.load(r"C:\sender\sender.yaml")
store = Store(cfg.get("service.db_path", r"C:\sender\sender.db"))
with store._lock:
    ряды = store._conn.execute(
        "SELECT id, COALESCE(edited_body, body, '') FROM confirm_reviews "
        "WHERE status='pending' AND campaign_id IN (7,8,9,11)").fetchall()
for rid, тело in ряды:
    т = str(тело or "")
    if not ПИЩЕВОЙ.search(т):
        continue
    if bool(РЕНТГЕН.search(т)) == bool(ФОТО.search(т)):
        continue
    абз = [a for a in т.split("\n\n") if a.strip()]
    # третий абзац - тот, где описан продукт получателя
    продукт = абз[2][:260] if len(абз) > 2 else т[:260]
    станок = "рентген" if РЕНТГЕН.search(т) else "фотосепаратор"
    print(f"#{rid}  назван: {станок}")
    print(f"   {продукт}\n")
