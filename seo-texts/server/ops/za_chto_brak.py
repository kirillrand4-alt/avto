# -*- coding: utf-8 -*-
"""За что именно бракуются письма — по логам сегодняшних прогонов."""
import glob
import io
import os
import re
import time
from collections import Counter

# Хвост у строк разный: у годной «$0.212 #9595», у брака «$0.212 | причина».
# Первая версия требовала конец строки сразу после цены — и ни одной годной
# не засчитала, отчего брак везде выходил «100%».
СТРОКА = re.compile(
    r"\[(\d+)/(\d+)\]\s+(ОК|брак)\s+(\S+)\s+(.*?)\s+(\d+)с\s+\$(\d+\.\d+)"
    r"(?:\s*\|\s*(.*))?")

ГРУППЫ = [
    ("профиль компании (не наш покупатель)",
     ("инженерная линза", "не наш адресат", "вне профиля", "не покупатель",
      "поставщик оборудования", "дистрибу", "не производство")),
    ("факт не подтверждён сайтом",
     ("не подтверждён сайтом", "этих слов нет ни на сайте", "домысел",
      "не подтвержда")),
    ("заход/зацепка",
     ("заход", "зацепк", "псевдо-новост", "предприятие не названо")),
    ("стиль и текст",
     ("тавтология", "мы-корпоратив", "предлагаем", "реклама", "человечност",
      "редактор", "штамп", "канцеляр")),
]


def группа(причина):
    п = (причина or "").lower()
    for имя, слова in ГРУППЫ:
        if any(с in п for с in слова):
            return имя
    return "прочее"


логи = []
for ш in (r"C:\sender\_ops\partiya_gen-*.log", r"C:\sender\_ops\ochered*.log"):
    логи.extend(glob.glob(ш))
логи = [п for п in логи if os.path.isfile(п) and os.path.getsize(п) > 500]
логи.sort(key=os.path.getmtime)
сегодня = time.strftime("%Y-%m-%d")

for п in логи:
    if time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(п))) != сегодня:
        continue
    т = io.open(п, encoding="utf-8", errors="replace").read()
    ок = 0
    причины = Counter()
    примеры = {}
    for с in т.splitlines():
        м = СТРОКА.search(с.strip())
        if not м:
            continue
        if м.group(3) == "ОК":
            ок += 1
            continue
        пр = (м.group(8) or "").strip()
        г = группа(пр)
        причины[г] += 1
        примеры.setdefault(г, пр[:120])
    брак = sum(причины.values())
    if not (ок + брак):
        continue
    print("==== %s: ок %d, брак %d (%.0f%%) ===="
          % (os.path.basename(п)[:40], ок, брак,
             100.0 * брак / (ок + брак)))
    for г, n in причины.most_common():
        print("   %-38s %4d   %s" % (г, n, примеры.get(г, "")[:80]))
    print("")
