def отрасль(okved, сегмент, otrasl):
    т = " ".join(str(x or "") for x in (okved, сегмент, otrasl)).lower()
    for рег, val in ОТРАСЛИ:
        if re.search(рег, str(okved or "")) or re.search(рег, т):
            return val
    return ("производственными", "производственных")


def чистое_имя(name, email, inn):
    н = re.sub(r"&quot;|[\"«»]", "", str(name or ""))
    н = re.sub(r"(?i)^(общество с ограниченной ответственностью|акционерное общество|"
               r"публичное акционерное общество|ооо|оао|зао|пао|ао|нао)\s+", "", н).strip()
    if re.match(r"(?i)^ип\s", н) or len(str(inn or "")) == 12:
        дом = str(email or "").split("@")[-1].split(".")[0]
        return дом.capitalize() if дом and дом not in ("mail", "gmail", "yandex", "bk", "list", "inbox", "ya") else None
    if re.fullmatch(r"[\w.-]+\.(ru|com|рф|net)", н, re.I):
        н = н.split(".")[0]
    if н.isupper() and len(н) > 4:
        н = "-".join(w.capitalize() for w in н.title().split("-"))
    return н or None


def собрать(rec, имя_отправителя="ИМЯ_ОТПРАВИТЕЛЯ"):
    """rec: dict(inn, email, company_name, okved, segment, otrasl, revenue, contact_name)."""
    ключ = sum(ord(c) for c in str(rec.get("inn") or rec.get("email") or ""))
    к = чистое_имя(rec.get("company_name"), rec.get("email"), rec.get("inn"))
    отр, отр_р = отрасль(rec.get("okved"), rec.get("segment"), rec.get("otrasl"))
    крупный = float(rec.get("revenue") or 0) >= 1e9
    if к:
        тема = ТЕМЫ[ключ % len(ТЕМЫ)].format(к=к)
        вопрос = ВОПРОСЫ[(ключ // 7) % len(ВОПРОСЫ)].format(к=к)
    else:
        тема = "Сжатый воздух на вашем производстве"
        вопрос = "Подскажите, актуален ли сейчас для вашего производства вопрос обновления компрессорного оборудования?"
    пул = О_КОМПАНИИ_КРУПНЫМ if крупный else О_КОМПАНИИ
    имя_к = str(rec.get("contact_name") or "").split()
    обращение = "Добрый день, %s!" % имя_к[1] if len(имя_к) >= 2 else ("Добрый день, %s!" % имя_к[0] if len(имя_к) == 1 else "Добрый день!")
    тело = "\n\n".join([
        обращение,
        ПРЕДСТАВЛЕНИЯ[(ключ // 3) % len(ПРЕДСТАВЛЕНИЯ)].format(имя=имя_отправителя, отр=отр, отр_р=отр_р),
        пул[(ключ // 5) % len(пул)],
        вопрос + " " + ПРОСЬБЫ[(ключ // 11) % len(ПРОСЬБЫ)],
        "С уважением,",
    ])
    return тема, тело


