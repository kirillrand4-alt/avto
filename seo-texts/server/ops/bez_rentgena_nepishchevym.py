import py_compile
import shutil
import sys
import time

ПУТЬ = r"C:\sender\sender\ai_letter.py"
т = io.open(ПУТЬ, encoding="utf-8").read()
if "НЕПИЩЕВЫЕ ОТРАСЛИ — БЕЗ РЕНТГЕНА" in т:
    print("=== БЕЗ РЕНТГЕНА: УЖЕ БЫЛО ===")
    sys.exit(0)
ЯКОРЬ1 = "MEYER_ГРАДАЦИИ = ('meyer_foto', 'meyer_rentgen')\n"
СТАР = '        lines.append(f"ГЛАВНЫЙ СТАНОК ПАРТИИ — {станок}: его разворачивай "\n                     f"подробно. Второй станок Meyer ({другой}) допустим ОДНОЙ "\n                     "фразой и только если профиль этой компании даёт для него "\n                     "явную задачу; не даёт — не упоминай.")\n'
НОВ = '        # НЕПИЩЕВЫЕ ОТРАСЛИ — БЕЗ РЕНТГЕНА (12.10). Лесопилке, лому и\n        # металлу письмо писалось про сортировку, но модель дописывала фразу\n        # про «рентген упакованного паркета», и линза покупателя браковала\n        # всё письмо как «не покупатель». Рентген-детектор Meyer — для\n        # пищевой упаковки; у этих отраслей второго станка нет.\n        _отр = str(_rec_field(rec, \'otrasl\', \'segment\') or \'\').lower()\n        if градация == \'meyer_foto\' and any(\n                м in _отр for м in _НЕПИЩЕВЫЕ_ОТРАСЛИ):\n            lines.append(f"ГЛАВНЫЙ СТАНОК ПАРТИИ — {станок}: его разворачивай "\n                         "подробно. Это НЕПИЩЕВАЯ отрасль: рентген-детектор, "\n                         "рентген-инспекцию и контроль упаковки НЕ упоминай "\n                         "вовсе — пиши только про сортировку их сырья или "\n                         "отходов фотосепаратором.")\n        else:\n            lines.append(f"ГЛАВНЫЙ СТАНОК ПАРТИИ — {станок}: его разворачивай "\n                         f"подробно. Второй станок Meyer ({другой}) допустим "\n                         "ОДНОЙ фразой и только если профиль этой компании "\n                         "даёт для него явную задачу; не даёт — не упоминай.")\n'
КОНСТ = "# Отрасли книг, где у Meyer только фотосепаратор: рентген-детектор ищет\n# включения в пищевой упаковке, а у них её нет (стоп-брак 12.10).\n_НЕПИЩЕВЫЕ_ОТРАСЛИ = ('пластик', 'стекло', 'горнодобыч', 'вторсыр', 'лес и',\n                      'деревообраб', 'металлург', 'химия')\n"
if т.count(ЯКОРЬ1) != 1 or т.count(СТАР) != 1:
    print("якоря: %d %d" % (т.count(ЯКОРЬ1), т.count(СТАР)))
    print("=== БЕЗ РЕНТГЕНА: НЕ ПРИМЕНЕНО ===")
    sys.exit(0)
