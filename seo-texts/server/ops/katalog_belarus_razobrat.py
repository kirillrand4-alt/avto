# -*- coding: utf-8 -*-
"""Разобрать каталог белорусских предприятий: скан -> карточки компаний.

Каталог пришёл сканом: 90 страниц, текстового слоя нет вовсе. Значит путь
один — рендерить страницу в картинку и отдавать модели глазами. Тяжёлая
работа идёт через провайдерский API (правило владельца), своими токенами
сессии — только запуск и разбор итогов.

РЕЗЮМИРУЕМОСТЬ. На каждую страницу пишем строку в durable-журнал с fsync.
Повторный запуск пропускает уже разобранные: прогон переживает рестарт
контейнера и обрыв сети, а платить второй раз за ту же страницу незачем.

ЧТО СОБИРАЕМ. Название, город, сайт, почта, телефон и чем занимается —
ровно то, из чего потом строится письмо. Ничего не выдумываем: чего на
странице нет, то остаётся пустым.

    pl_run.py katalog_belarus_razobrat.py [сколько_страниц]
"""
import base64
import glob
import io
import json
import os
import sys
import time

sys.path.insert(0, r"C:\sender\seo-texts")
sys.path.insert(0, r"C:\sender")

КАТАЛОГ = r"C:\sender\_ops\belarus"
КАРТИНКИ = os.path.join(КАТАЛОГ, "pages")
ЖУРНАЛ = os.path.join(КАТАЛОГ, "katalog-razbor.jsonl")
МОДЕЛЬ = os.environ.get("KATALOG_MODEL", "claude-fable-5")
СКОЛЬКО = int(sys.argv[1]) if len(sys.argv) > 1 else 0   # 0 — все

ЗАДАНИЕ = """На картинке страница печатного каталога предприятий Беларуси.

Выпиши КАЖДУЮ компанию, карточка которой видна на странице. На страницу их
бывает от одной до нескольких.

Верни ТОЛЬКО JSON без пояснений:
{"компании": [{"название": "", "город": "", "сайт": "", "почта": "",
"телефон": "", "чем_занимается": "", "продукция": ""}]}

Правила:
- переписывай ровно то, что напечатано; не додумывай и не переводи;
- сайт и почту приводи как есть, без http:// и без пробелов;
- «чем_занимается» — одна фраза своими словами по тексту карточки;
- «продукция» — перечисление через запятую, если оно есть на странице;
- если на странице нет ни одной карточки компании (обложка, оглавление,
  реклама), верни {"компании": []}."""


def записать(строка):
    with io.open(ЖУРНАЛ, "a", encoding="utf-8") as ф:
        ф.write(json.dumps(строка, ensure_ascii=False) + "\n")
        ф.flush()
        os.fsync(ф.fileno())


разобрано = set()
if os.path.exists(ЖУРНАЛ):
    for с in io.open(ЖУРНАЛ, encoding="utf-8", errors="replace"):
        try:
            з = json.loads(с)
        except Exception:  # noqa: BLE001
            continue
        # Страницы, разобранные СЛОМАННОЙ версией (ноль компаний из-за
        # str(_Msg)), считаем неразобранными: иначе резюм закрепит пустоту.
        if (з.get("страница") and з.get("этап") == "готово"
                and з.get("компаний")):
            разобрано.add(int(з["страница"]))
print("уже разобрано страниц: %d" % len(разобрано))

import fitz  # noqa: E402
from gen_provider import call, make_client  # noqa: E402

файл = glob.glob(os.path.join(КАТАЛОГ, "*.pdf"))[0]
док = fitz.open(файл)
клиент = make_client()
os.makedirs(КАРТИНКИ, exist_ok=True)
всего_компаний = 0
сделано = 0

for н in range(док.page_count):
    номер = н + 1
    if номер in разобрано:
        continue
    if СКОЛЬКО and сделано >= СКОЛЬКО:
        break
    т0 = time.time()
    путь = os.path.join(КАРТИНКИ, "p%03d.png" % номер)
    if not os.path.exists(путь):
        док.load_page(н).get_pixmap(dpi=150).save(путь)
    b64 = base64.b64encode(open(путь, "rb").read()).decode()
    сообщения = [{"role": "user", "content": [
        {"type": "image", "source": {"type": "base64",
                                     "media_type": "image/png", "data": b64}},
        {"type": "text", "text": ЗАДАНИЕ}]}]
    try:
        ответ = call(клиент, сообщения, model=МОДЕЛЬ, attempts=3,
                     thinking=False)
    except Exception as ex:  # noqa: BLE001
        записать({"страница": номер, "этап": "сбой", "ошибка": str(ex)[:200],
                  "ts": time.time()})
        print("  стр.%3d СБОЙ: %s" % (номер, str(ex)[:90]), flush=True)
        continue
    # ТЕКСТ ИЗ ОТВЕТА, А НЕ str() ОБЪЕКТА. call() возвращает _Msg, и
    # str() от него давал «<gen_provider._Msg object at 0x...>»: JSON не
    # находился, и все страницы честно отчитывались нулём компаний.
    if isinstance(ответ, str):
        сырой = ответ
    else:
        сырой = "".join(б.text for б in getattr(ответ, "content", [])
                        if getattr(б, "type", "") == "text")
    начало, конец = сырой.find("{"), сырой.rfind("}")
    компании = []
    if начало >= 0 and конец > начало:
        try:
            компании = json.loads(сырой[начало:конец + 1]).get("компании") or []
        except Exception:  # noqa: BLE001
            pass
    записать({"страница": номер, "этап": "готово", "компаний": len(компании),
              "компании": компании, "сек": int(time.time() - т0),
              "модель": МОДЕЛЬ, "ts": time.time()})
    всего_компаний += len(компании)
    сделано += 1
    print("  стр.%3d: компаний %2d за %2dс" % (номер, len(компании),
                                               time.time() - т0), flush=True)

print("\nразобрано страниц за прогон: %d, компаний найдено: %d"
      % (сделано, всего_компаний))
