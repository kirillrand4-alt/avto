# -*- coding: utf-8 -*-
"""Сколько на самом деле стоит одно ГОТОВОЕ письмо.

Цена строки в логе — это цена ПОПЫТКИ. Брак тоже оплачен, поэтому честная
себестоимость письма = все деньги прогона, делённые на письма, которые
дошли до очереди. Считаем по логам прогонов: и так, и так.
"""
import glob
import io
import os
import re
import time
from collections import defaultdict

СТРОКА = re.compile(r"\[(\d+)/(\d+)\]\s+(ОК|брак)\s+(\S+)\s+.*?\$(\d+\.\d+)")
ИТОГ = re.compile(r"итог: вышло (\d+) из (\d+) \| \$(\d+\.\d+)")

логи = []
for шаблон in (r"C:\sender\_ops\partiya_gen-*.log", r"C:\sender\_ops\ochered*.log"):
    логи.extend(glob.glob(шаблон))
логи = [п for п in логи if os.path.isfile(п) and os.path.getsize(п) > 500]
логи.sort(key=os.path.getmtime)
сегодня = time.strftime("%Y-%m-%d")

всего = defaultdict(lambda: {"ок": 0, "брак": 0, "деньги": 0.0, "деньги_ок": 0.0})
print("%-38s %6s %6s %9s %9s %9s" % ("прогон", "ок", "брак", "всего $",
                                     "$/готовое", "$/попытку"))
for п in логи[-14:]:
    дата = time.strftime("%Y-%m-%d", time.localtime(os.path.getmtime(п)))
    if дата != сегодня:
        continue
    т = io.open(п, encoding="utf-8", errors="replace").read()
    модель = "sonnet" if "claude-sonnet" in т else ("opus" if "opus" in т else "?")
    ок = брак = 0
    деньги = деньги_ок = 0.0
    # Направление берём по СТРОКАМ прогона, а не по упоминанию слова в
    # файле: в шапке КЦ-прогона слово meyer тоже встречается, и проверка
    # «есть ли оно в тексте» приписала 1870 компрессорных писем мейеру.
    напр_счёт = defaultdict(int)
    for м in СТРОКА.finditer(т):
        напр_счёт[м.group(4)] += 1
    напр = max(напр_счёт, key=напр_счёт.get) if напр_счёт else "?"
    for м in СТРОКА.finditer(т):
        ц = float(м.group(5))
        деньги += ц
        if м.group(3) == "ОК":
            ок += 1
            деньги_ок += ц
        else:
            брак += 1
    if not (ок + брак):
        continue
    к = всего[(напр, модель)]
    к["ок"] += ок
    к["брак"] += брак
    к["деньги"] += деньги
    к["деньги_ок"] += деньги_ок
    print("%-38s %6d %6d %9.2f %9.3f %9.3f"
          % (os.path.basename(п)[:38], ок, брак, деньги,
             деньги / ок if ок else 0, деньги / (ок + брак)))

print("")
print("=== свод по направлению и модели (сегодня) ===")
print("%-16s %6s %6s %9s %10s %10s %8s"
      % ("что", "ок", "брак", "всего $", "$/готовое", "$/попытку", "брака %"))
и_ок = и_брак = 0
и_деньги = 0.0
for (напр, модель), к in sorted(всего.items()):
    ок, брак, д = к["ок"], к["брак"], к["деньги"]
    и_ок += ок
    и_брак += брак
    и_деньги += д
    print("%-16s %6d %6d %9.2f %10.3f %10.3f %7.0f%%"
          % ("%s/%s" % (напр, модель), ок, брак, д,
             д / ок if ок else 0, д / (ок + брак) if (ок + брак) else 0,
             100.0 * брак / (ок + брак) if (ок + брак) else 0))
print("%-16s %6d %6d %9.2f %10.3f %10.3f %7.0f%%"
      % ("ИТОГО", и_ок, и_брак, и_деньги, и_деньги / и_ок if и_ок else 0,
         и_деньги / (и_ок + и_брак) if (и_ок + и_брак) else 0,
         100.0 * и_брак / (и_ок + и_брак) if (и_ок + и_брак) else 0))

print("")
print("=== итоговые строки прогонов (как их считает сам прогон) ===")
for п in логи[-14:]:
    т = io.open(п, encoding="utf-8", errors="replace").read()
    for м in ИТОГ.finditer(т):
        вышло, из, деньги = int(м.group(1)), int(м.group(2)), float(м.group(3))
        print("   %-38s вышло %d из %d, $%.2f → $%.3f за письмо"
              % (os.path.basename(п)[:38], вышло, из, деньги,
                 деньги / вышло if вышло else 0))
