# -*- coding: utf-8 -*-
"""Снять с компаний попытки, сгоревшие на пустом кошельке провайдера.

17.08, ~19:20 и повторно ~20:21: у провайдера кончился баланс ($0.0254 при
нужных $0.08 на письмо), и КАЖДЫЙ вызов стал отдавать HTTP 403. Конвейер
честно записал это в журнал как неудачу генерации - и тем самым израсходовал
компаниям попытки: резюм считает попыткой любую строку «сгенерировано», а на
четвёртой ИНН выбывает насовсем («исчерпал 3 попытки»).

Урон не в деньгах - вызовы с 403 бесплатны, - а в том, что компании
выбрасываются из партии по причине, к ним не относящейся.

Чиним честно: дописываем строку «отмена_попытки» на каждую сгоревшую.
Резюм читает журнал целиком и вычитает такие строки. Ничего не удаляем.

ДВА ПОДВОХА, ОБА ПОЙМАНЫ НА ЖИВОМ ЖУРНАЛЕ 17.08:

1. ПОВТОРНЫЙ ЗАПУСК НЕ ДОЛЖЕН ОТМЕНЯТЬ ДВАЖДЫ. Первая редакция писала
   отмены на все 403-строки подряд, и второй прогон продублировал 187 отмен.
   Теперь на каждый ИНН считаем, сколько отмен уже лежит, и дописываем
   только недостающие.
2. СЧЁТЧИК «НА ГРАНИ» НЕ ДОЛЖЕН СЧИТАТЬ САМ СЕБЯ. Он брал все строки, кроме
   «итог», - а это включало наши же «отмена_попытки», и число компаний на
   грани выросло с 6 до 78 из-за собственной записи скрипта.

Без аргумента - только считает. Пишет при `--снять`.

    python zapusk_svoego_skripta.py ops/otkatit_403_popytki.py
    python zapusk_svoego_skripta.py ops/otkatit_403_popytki.py --снять
"""
import io
import json
import os
import sys
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ПРИЗНАК = ("credit wallet quota insufficient", "HTTP 403")
СНИМАТЬ = "--снять" in sys.argv


def _403(z) -> bool:
    т = json.dumps(z.get("брак") or [], ensure_ascii=False)
    return any(п in т for п in ПРИЗНАК)


сгорело = Counter()      # инн -> сколько попыток убито 403
отменено = Counter()     # инн -> сколько отмен уже дописано
попыток = Counter()      # инн -> настоящих попыток (без отмен)
образец = {}
if os.path.exists(ЖУРНАЛ):
    for s in io.open(ЖУРНАЛ, encoding="utf-8"):
        try:
            z = json.loads(s)
        except Exception:                                       # noqa: BLE001
            continue
        inn = str(z.get("inn") or "")
        if not inn:
            continue
        этап = z.get("этап")
        if этап == "отмена_попытки":
            отменено[inn] += 1
            continue
        if этап == "итог":
            continue
        попыток[inn] += 1
        if _403(z):
            сгорело[inn] += 1
            образец.setdefault(inn, z)

надо = {i: сгорело[i] - отменено[i] for i in сгорело
        if сгорело[i] > отменено[i]}
всего_надо = sum(надо.values())
чистых = {i: попыток[i] - отменено[i] for i in попыток}
на_грани = [i for i in сгорело if чистых.get(i, 0) >= 3]

print(f"компаний, у которых 403 сжёг попытки: {len(сгорело)}")
print(f"  сгоревших попыток всего:            {sum(сгорело.values())}")
print(f"  отмен уже дописано:                 {sum(отменено.values())}")
print(f"  НЕДОСТАЮЩИХ отмен:                  {всего_надо} "
      f"у {len(надо)} компаний")
print(f"компаний, у которых ЧИСТЫХ попыток 3 и больше (выбыли бы): "
      f"{len(на_грани)}")

if not СНИМАТЬ:
    print("\nсухой прогон: журнал не тронут. Снять - аргумент --снять")
    raise SystemExit(0)
if not всего_надо:
    print("\nвсё уже отменено, дописывать нечего")
    raise SystemExit(0)

with io.open(ЖУРНАЛ, "a", encoding="utf-8") as f:
    for inn, сколько in надо.items():
        z = образец.get(inn) or {}
        for _ in range(сколько):
            f.write(json.dumps({
                "inn": inn, "recipient_id": z.get("recipient_id"),
                "имя": z.get("имя"), "этап": "отмена_попытки",
                "почему": "провайдер вернул 403: кончился баланс кошелька, "
                          "к компании претензий нет",
                "ок": False}, ensure_ascii=False) + "\n")
    f.flush()
    os.fsync(f.fileno())
print(f"\nдописано отмен: {всего_надо}")
print("Резюм в ops/partiya_gen.py вычитает «отмена_попытки» из счётчика.")
