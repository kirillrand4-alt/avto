"""Сколько в правилах письма ИНСТРУКЦИЙ, а сколько объяснений для нас.

Правила писались по живым инцидентам, и вместе с самим правилом в промпт
попадала его история: «замер 17.08 показал…», «редактор вычеркнула 14.08»,
«владелец сказал…», «живой брак #1054». Модели эта история не нужна - ей
нужно правило. А платим мы за неё на каждом вызове (запись кэша 1.25
ставки) и, что важнее, разбавляем ей контекст: чем длиннее промпт, тем
слабее модель держит инструкции.

Считаем строки-объяснения по признакам: дата инцидента, ссылка на замер,
ссылка на человека, номер письма.
"""
import re
import sys

sys.path.insert(0, r"C:\sender")
from sender import ai_letter as AI                               # noqa: E402

ПРИЗНАКИ = re.compile(
    r'(?i)\b\d{2}\.\d{2}\b|замер|прогон|инцидент|редактор|владелец|'
    r'проверка глазами|живой брак|#\d{3,}|поймано|история|раньше стояло|'
    r'до \d{2}\.\d{2}|было\b.{0,20}стало|причина в том|потому что мы')

for div in ("kc", "meyer"):
    т = AI.RULES_BY_DIVISION[div]
    строки = т.split("\n")
    объясн = [s for s in строки if ПРИЗНАКИ.search(s)]
    зн_всего = len(т)
    зн_объясн = sum(len(s) + 1 for s in объясн)
    print(f"\n== {div}: {зн_всего} знаков, {len(строки)} строк ==")
    print(f"  строк с объяснениями: {len(объясн)} из {len(строки)}")
    print(f"  знаков в них: {зн_объясн} = {100.0 * зн_объясн / зн_всего:.0f}%")
    print("  примеры:")
    for s in объясн[:6]:
        print(f"    {s.strip()[:96]}")
