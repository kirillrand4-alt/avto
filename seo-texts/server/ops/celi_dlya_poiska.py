def регион_по_инн(инн):
    return РЕГИОНЫ.get(str(инн)[:2], "")


def город(адрес):
    ч = [x.strip() for x in str(адрес or "").split(",")]
    for x in ч:
        if x and not x[0].isdigit() and "обл" not in x.lower() \
                and "респ" not in x.lower() and "край" not in x.lower():
            return x[:60]
    return ч[1][:60] if len(ч) > 1 else ""


