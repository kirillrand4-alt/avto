# -*- coding: utf-8 -*-
"""Схлопнуть дубли фактов, НЕ стирая повторные покупки (находка 3-й сессии).

ЧТО УВИДЕЛА 3-я СЕССИЯ ГЛАЗАМИ: у Газпром метанола одно заключение ЭПБ
№ 68-ТУ-05539-2024 с одинаковой цитатой показано дважды — раз «тип не
установлен (марка не опознана)», раз «центробежная». Продавец видит 31 факт
там, где машин вдвое меньше.

ПОЧЕМУ ЕЁ КЛЮЧ «inn + quote» БРАТЬ НЕЛЬЗЯ, хотя дефект настоящий. Замер по
базе: из 6 010 таких групп у 2 306 РАЗНЫЙ ИСТОЧНИК, у 1 510 РАЗНАЯ ДАТА. Один и
тот же текст закупки в январе и в марте, в плане 223-ФЗ и на Росэлторге, — это
ПОВТОРНАЯ ПОКУПКА, самый ценный сигнал для продавца («берут регулярно»), а не
дубль. Схлопнув по её ключу, мы стёрли бы 7 670 строк и вместе с ними
регулярность закупок. Поэтому схлопываем только то, где потерять нечего:

  А. ПОЛНЫЙ ПОВТОР — совпали ИНН, цитата, источник, дата И ссылка. Одна и та же
     строка, занесённая дважды разными прогонами. Лишние удаляем (2 799).
  Б. ОДИН ДОКУМЕНТ, РАЗНЫЙ РАЗБОР — совпали ИНН, цитата и ССЫЛКА (то есть это
     буквально один документ), но тип разобран по-разному. Ничего не удаляем
     «по количеству»: гасим только строки «тип не установлен / марка не
     опознана», если по этому же документу есть строка с НАЗВАННЫМ типом.
     Документ остаётся, разбор остаётся сильнейший (2 452 строки).

Что НЕ трогаем: группы, где отличается источник или дата (повторные закупки), и
группы, где оба типа названы по-разному и ни один не «не установлен» — там надо
разбираться, а не выбирать молча.

DURABILITY: `fact` живёт в centrifugal.db и пересборкой панели НЕ трогается
(билд дропает только company/contact/signal/person), поэтому правка здесь
переживает пересборку. Перед удалением — .bak, как в доливке.

По умолчанию СУХОЙ ПРОГОН. Запуск: python chistka_dubley_faktov.py [--apply]
"""
import json
import os
import re
import shutil
import sqlite3
import sys
import time
from collections import defaultdict

БАЗА = os.getenv('CENTRIFUGAL_DB') or r'C:\seostat\data\centrifugal.db'
ПРИМЕНИТЬ = '--apply' in sys.argv
_НЕ_РАЗОБРАН = re.compile(r'не установлен|не опознан|не определ', re.I)


def ключ_цитаты(ц):
    return re.sub(r'\s+', ' ', str(ц or '')).strip().lower()


def main():
    cx = sqlite3.connect(f'file:{БАЗА}?mode=ro', uri=True, timeout=20)
    всего = cx.execute('SELECT COUNT(*) FROM fact').fetchone()[0]
    полн = defaultdict(list)
    документ = defaultdict(list)
    for rid, инн, цит, тип, ист, у, дата in cx.execute(
            "SELECT rowid, inn, COALESCE(quote,''), COALESCE(equipment_type,''), "
            "COALESCE(source,''), COALESCE(source_url,''), "
            "COALESCE(event_date,'') FROM fact"):
        ц = ключ_цитаты(цит)
        if len(ц) < 25:
            continue
        полн[(str(инн), ц, str(ист), str(дата), str(у))].append((rid, str(тип)))
        if str(у).strip():
            документ[(str(инн), ц, str(у))].append((rid, str(тип)))

    # А: полный повтор — оставляем строку с ЛУЧШИМ РАЗБОРОМ, а не первую.
    # Здесь была моя ошибка, пойманная до применения: ключ группы не включает
    # тип, поэтому в одну группу попадают и «центробежная», и «тип не
    # установлен». Правило «оставить наименьший rowid» выбросило бы разобранную
    # строку всякий раз, когда неразобранная занеслась раньше, — то есть
    # чистка дублей молча ухудшала бы разбор. Сортируем: сперва названный тип,
    # потом длина типа (подробнее — лучше), потом rowid для устойчивости.
    удалить_А = []
    for _к, ряды in полн.items():
        if len(ряды) < 2:
            continue
        по_качеству = sorted(
            ряды,
            key=lambda рт: (bool(_НЕ_РАЗОБРАН.search(рт[1]) or not рт[1].strip()),
                            -len(рт[1]), рт[0]))
        удалить_А.extend(r for r, _т in по_качеству[1:])

    # Б: один документ, разобран и «никак», и по-настоящему
    удалить_Б = []
    ужеА = set(удалить_А)
    for _к, ряды in документ.items():
        if len(ряды) < 2:
            continue
        названные = [r for r, т in ряды if not _НЕ_РАЗОБРАН.search(т) and т.strip()]
        пустые = [r for r, т in ряды if _НЕ_РАЗОБРАН.search(т) or not т.strip()]
        # гасим «не установлен» ТОЛЬКО если у того же документа есть названный тип
        if названные and пустые:
            удалить_Б.extend(r for r in пустые if r not in ужеА)

    к_удалению = sorted(set(удалить_А) | set(удалить_Б))
    print(json.dumps({
        'фактов_всего': всего,
        'А_полный_повтор_лишних': len(удалить_А),
        'Б_неразобранный_дубль_документа': len([r for r in удалить_Б]),
        'ВСЕГО_К_УДАЛЕНИЮ': len(к_удалению),
        'останется': всего - len(к_удалению),
        'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
    }, ensure_ascii=False, indent=1))
    cx.close()
    if not ПРИМЕНИТЬ or not к_удалению:
        if not ПРИМЕНИТЬ:
            print('сухой прогон. Повторить с --apply')
        return

    коп = БАЗА + '.bak-' + str(int(time.time()))
    shutil.copy2(БАЗА, коп)
    print(f'бэкап: {os.path.basename(коп)}')
    cx = sqlite3.connect(БАЗА, timeout=120)
    cx.execute('PRAGMA busy_timeout=120000')
    было = cx.execute('SELECT COUNT(*) FROM fact').fetchone()[0]
    cx.executemany('DELETE FROM fact WHERE rowid=?', [(r,) for r in к_удалению])
    cx.commit()
    стало = cx.execute('SELECT COUNT(*) FROM fact').fetchone()[0]

    # перепроверка ИЗ БАЗЫ, а не по счётчику прогона
    полн2 = defaultdict(int)
    for инн, цит, ист, у, дата in cx.execute(
            "SELECT inn, COALESCE(quote,''), COALESCE(source,''), "
            "COALESCE(source_url,''), COALESCE(event_date,'') FROM fact"):
        ц = ключ_цитаты(цит)
        if len(ц) >= 25:
            полн2[(str(инн), ц, str(ист), str(дата), str(у))] += 1
    осталось_повторов = sum(n - 1 for n in полн2.values() if n > 1)
    cx.close()
    print(json.dumps({'было': было, 'стало': стало, 'удалено': было - стало,
                      'полных_повторов_осталось': осталось_повторов},
                     ensure_ascii=False))


if __name__ == '__main__':
    main()
