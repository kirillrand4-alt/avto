# -*- coding: utf-8 -*-
"""Что кэш дал деньгами по НАСТОЯЩИМ прогонам, а не по пробе на двух вызовах.

Журнал пишет вход_кэш_запись / вход_кэш_чтение на каждое письмо (этап
«итог»). Запись тарифицируется 1.25 обычного входа, чтение 0.10 — значит
кэш без чтения не экономит, а удорожает. Считаем оба числа и разницу.
"""
import io
import json
import os
import sys
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ДЕНЬ = sys.argv[1] if len(sys.argv) > 1 else ""

if not os.path.exists(ЖУРНАЛ):
    print("нет журнала"); raise SystemExit(1)

итог = Counter()
по_дням = {}
писем = 0
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    зап = int(z.get("вход_кэш_запись") or 0)
    чт = int(z.get("вход_кэш_чтение") or 0)
    if not (зап or чт):
        continue
    писем += 1
    итог["зап"] += зап
    итог["чт"] += чт
    итог["цена_письма"] += float(z.get("цена_письма_$") or 0)
    итог["цена_проверок"] += float(z.get("цена_проверок_$") or 0)
    итог["цена"] += float(z.get("цена_$") or 0)

print(f"строк с разбивкой кэша: {писем}")
print(f"  записано в кэш: {итог['зап']:>12,} токенов")
print(f"  прочитано из кэша: {итог['чт']:>9,} токенов")
print(f"  отношение чтение/запись: {итог['чт']/max(1,итог['зап']):.2f}")
print(f"\n  потрачено по журналу: ${итог['цена']:,.2f}"
      f"  (письма ${итог['цена_письма']:,.2f} + "
      f"проверки ${итог['цена_проверок']:,.2f})")

# Что было бы БЕЗ кэша: те же токены прошли бы обычным входом (ставка 1.0)
# вместо 1.25 за запись и 0.10 за чтение. Разницу считаем по обеим ставкам,
# потому что письма пишет opus, а проверки — sonnet.
for имя, вх in (("если всё это opus ($15/M)", 15.0),
                ("если всё это sonnet ($3/M)", 3.0)):
    факт = (1.25 * итог["зап"] + 0.10 * итог["чт"]) / 1e6 * вх
    альт = (итог["зап"] + итог["чт"]) / 1e6 * вх
    д = альт - факт
    print(f"\n  {имя}:")
    print(f"    кэш стоил      ${факт:,.2f}")
    print(f"    без кэша стоил ${альт:,.2f}")
    print(f"    {'экономия' if д > 0 else 'ПЕРЕПЛАТА'}: ${abs(д):,.2f}")
