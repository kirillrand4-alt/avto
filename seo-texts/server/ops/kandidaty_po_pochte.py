# -*- coding: utf-8 -*-
"""Принять кандидата в сайты по ДОМЕНУ ПОЧТЫ, когда ИНН на страницах не нашёлся.

Поиск сайтов оставил 105 компаний в `cand_site`: домен найден и на агрегатор
не похож, но ИНН не нашёлся ни на главной, ни на восьми страницах реквизитов.
Требовать ИНН на сайте — рубеж честный, но у части предприятий реквизитов на
сайте нет вовсе, и тогда мы бракуем живой сайт.

Второй независимый признак принадлежности — **домен корпоративной почты**.
Если у компании в базе есть почта `@tn.ru`, а кандидат в сайты `tn.ru` — это
та же организация, и доказательство здесь не слабее ИНН: почту мы взяли из
её же карточки закупки или с её страницы.

Рубеж остаётся fail-closed:
  * бесплатные домены (mail.ru, yandex.ru, gmail) не считаются доказательством
    ВООБЩЕ — они ничего не привязывают;
  * домен должен совпасть точно или по второму уровню (`zavod.ru` и
    `mail.zavod.ru` — одно, `zavod.ru` и `zavod-torg.ru` — разное);
  * совпало — переносим `cand_site` в `site`; не совпало — оставляем
    кандидатом, ничего не теряем.

Запуск: python kandidaty_po_pochte.py [--apply]
"""
import re
import sys

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ПРИМЕНИТЬ = '--apply' in sys.argv
# бесплатные и почтовые сервисы — принадлежности не доказывают
_СВОБОДНЫЕ = {
    'mail.ru', 'inbox.ru', 'list.ru', 'bk.ru', 'internet.ru', 'yandex.ru',
    'ya.ru', 'yandex.com', 'gmail.com', 'googlemail.com', 'rambler.ru',
    'lenta.ru', 'autorambler.ru', 'ro.ru', 'icloud.com', 'me.com', 'mail.com',
    'outlook.com', 'hotmail.com', 'live.com', 'bk.com', 'narod.ru',
}


def домен(строка):
    """Голый домен без схемы, www и пути."""
    д = re.sub(r'^https?://', '', (строка or '').strip().lower())
    д = re.sub(r'^www\.', '', д)
    return д.split('/')[0].split('?')[0].strip().strip('.')


def второй_уровень(д):
    """`mail.zavod.ru` → `zavod.ru`. Двухсоставные зоны учтены грубо, но верно
    для РФ: com.ru, org.ru, net.ru, spb.ru и подобные оставляем как есть."""
    части = д.split('.')
    if len(части) <= 2:
        return д
    if части[-2] in ('com', 'org', 'net', 'edu', 'gov', 'co') and len(части) >= 3:
        return '.'.join(части[-3:])
    return '.'.join(части[-2:])


def main():
    db = EDB.EnrichDB()
    q = db.cx.execute
    ряды = q("SELECT inn, cand_site FROM companies "
             "WHERE cand_site IS NOT NULL AND cand_site != '' "
             "AND (site IS NULL OR site = '')").fetchall()
    print(f'кандидатов в сайты: {len(ряды)}')
    if not ряды:
        return

    принято, нет_почты, только_свободные, разошлось = 0, 0, 0, 0
    примеры_за, примеры_против = [], []
    for инн, канд in ряды:
        д_канд = второй_уровень(домен(канд))
        почты = [r[0] for r in q('SELECT email FROM emails WHERE inn=?',
                                 (инн,)).fetchall()]
        if not почты:
            нет_почты += 1
            continue
        домены = set()
        for э in почты:
            if '@' not in (э or ''):
                continue
            д = второй_уровень((э.split('@')[1] or '').strip().lower())
            if д and д not in _СВОБОДНЫЕ:
                домены.add(д)
        if not домены:
            только_свободные += 1
            continue
        if д_канд in домены:
            принято += 1
            if len(примеры_за) < 8:
                # печатаем СОВПАВШИЙ домен, а не первый по алфавиту: первая
                # версия показывала «almaztd.ru принят при почте
                # @agro-shop.ru» и выглядела как ошибка привязки, хотя решение
                # принималось по другому, совпавшему домену. Печать обязана
                # показывать основание решения, иначе проверка глазами врёт.
                примеры_за.append((инн, канд, д_канд,
                                   len(домены), sorted(домены - {д_канд})[:2]))
            if ПРИМЕНИТЬ:
                db.upsert_company(инн, site=канд)
        else:
            разошлось += 1
            if len(примеры_против) < 6:
                примеры_против.append((инн, д_канд, sorted(домены)[:2]))

    print(f'  ПРИНЯТО по совпадению домена почты: {принято}')
    print(f'  почты в базе нет вовсе: {нет_почты}')
    print(f'  почта есть, но только бесплатная: {только_свободные}')
    print(f'  домен почты РАЗОШЁЛСЯ с кандидатом: {разошлось}')
    print()
    print('=== ПРИНЯТЫЕ (примеры) ===')
    for инн, канд, д, всего, прочие in примеры_за:
        хвост = f'  (ещё доменов: {всего - 1} — {прочие})' if всего > 1 else ''
        print(f'  {инн}  {канд[:34]:<34} СОВПАЛО @{д}{хвост}')
    print()
    print('=== ОТКЛОНЁННЫЕ — домен не тот (примеры) ===')
    for инн, дк, дп in примеры_против:
        print(f'  {инн}  кандидат {дк:<28} почта {дп}')

    стало = q("SELECT COUNT(*) FROM companies WHERE site IS NOT NULL "
              "AND site != ''").fetchone()[0]
    print()
    print('=== ИЗ БАЗЫ ===')
    print(f'  компаний с подтверждённым сайтом: {стало}')
    print(f'кандидатов {len(ряды)}, принято {принято}, разошлось {разошлось}')


if __name__ == '__main__':
    main()
