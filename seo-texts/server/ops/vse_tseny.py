# -*- coding: utf-8 -*-
"""Полный расход по моделям: сколько потрачено, а не только цена годного.

Прежняя таблица показывала «$0.0000 за годное» там, где годных не вышло
вовсе — и это скрывало, что деньги всё равно потрачены. Считаем и то, и
другое.
"""
import io
import json
from collections import defaultdict

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
по_модели = defaultdict(lambda: {"попыток": 0, "годных": 0, "цена": 0.0,
                                 "сек": 0.0})
всего = {"попыток": 0, "годных": 0, "цена": 0.0}
за_сутки = defaultdict(lambda: {"попыток": 0, "годных": 0, "цена": 0.0})

for с in io.open(ЖУРНАЛ, encoding="utf-8"):
    с = с.strip()
    if not с:
        continue
    try:
        з = json.loads(с)
    except Exception:  # noqa: BLE001
        continue
    if з.get("этап") != "итог" or з.get("цена_$") is None:
        continue
    м = str(з.get("модель") or "(без модели: механическая схема)")
    ц = float(з.get("цена_$") or 0)
    д = по_модели[м]
    д["попыток"] += 1
    д["цена"] += ц
    д["сек"] += float(з.get("сек") or 0)
    if з.get("ок"):
        д["годных"] += 1
    всего["попыток"] += 1
    всего["цена"] += ц
    всего["годных"] += 1 if з.get("ок") else 0

print("%-34s %7s %7s %6s %9s %9s %9s"
      % ("модель", "попыток", "годных", "%", "ПОТРАЧЕНО", "за попытку", "за годное"))
print("-" * 92)
for м, д in sorted(по_модели.items(), key=lambda x: -x[1]["цена"]):
    print("%-34s %7d %7d %5.0f%% %9.2f$ %9.4f$ %9s"
          % (м[:34], д["попыток"], д["годных"],
             100.0 * д["годных"] / д["попыток"] if д["попыток"] else 0,
             д["цена"], д["цена"] / д["попыток"] if д["попыток"] else 0,
             ("%.4f$" % (д["цена"] / д["годных"])) if д["годных"]
             else "— ни одного"))
print("-" * 92)
print("%-34s %7d %7d %5.0f%% %9.2f$ %9.4f$ %9.4f$"
      % ("ИТОГО ПО ЖУРНАЛУ", всего["попыток"], всего["годных"],
         100.0 * всего["годных"] / всего["попыток"] if всего["попыток"] else 0,
         всего["цена"], всего["цена"] / всего["попыток"] if всего["попыток"] else 0,
         всего["цена"] / всего["годных"] if всего["годных"] else 0))

print("\n=== ДЕНЬГИ, ПОТРАЧЕННЫЕ ВПУСТУЮ (модели без годных писем) ===")
впустую = sum(д["цена"] for д in по_модели.values() if not д["годных"])
for м, д in sorted(по_модели.items(), key=lambda x: -x[1]["цена"]):
    if not д["годных"]:
        print("  %-34s %d попыток, $%.2f" % (м[:34], д["попыток"], д["цена"]))
print("  ---- всего впустую: $%.2f" % впустую)

print("\n=== БРАК: СКОЛЬКО СТОИЛИ НЕУДАЧНЫЕ ПОПЫТКИ ===")
for м, д in sorted(по_модели.items(), key=lambda x: -x[1]["цена"])[:6]:
    брак = д["попыток"] - д["годных"]
    if not д["попыток"]:
        continue
    доля = д["цена"] * брак / д["попыток"]
    print("  %-34s брак %5d из %5d, в деньгах ~$%.2f"
          % (м[:34], брак, д["попыток"], доля))
