"""Когда кэш перестал читаться на опусе — и во что это обошлось.

По всей партии отношение чтение/запись 0.88, по последней сотне — 0.00, а
цена попытки выросла с $0.21 до $0.68. Значит кэш РАБОТАЛ и сломался, а не
«недоступен в принципе». Ищем окно, где он пропал.

Идём по журналу подряд окнами и печатаем отношение и цену. Порядок строк в
журнале = порядок прогонов, этого достаточно.
"""
import io
import json
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ОКНО = 250

строки = []
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    if z.get("вход_кэш_запись") is None and z.get("вход_кэш_чтение") is None:
        continue
    строки.append(z)

print(f"строк с разбивкой кэша: {len(строки)}, окно {ОКНО}\n")
print(f"{'окно':>12} {'запись/поп':>11} {'чтение/поп':>11} {'чт/зап':>7} "
      f"{'$/попытку':>10} {'модель':>18}")
for i in range(0, len(строки), ОКНО):
    кусок = строки[i:i + ОКНО]
    ц = Counter()
    модели = Counter()
    for z in кусок:
        ц["зап"] += int(z.get("вход_кэш_запись") or 0)
        ц["чт"] += int(z.get("вход_кэш_чтение") or 0)
        ц["цена"] += float(z.get("цена_$") or 0)
        модели[str(z.get("модель") or "?")] += 1
    n = len(кусок)
    м = модели.most_common(1)[0][0].replace("claude-", "")
    print(f"{i:>6}-{i+n:<5} {ц['зап']/n:>11,.0f} {ц['чт']/n:>11,.0f} "
          f"{ц['чт']/max(1,ц['зап']):>7.2f} {ц['цена']/n:>10.4f} {м:>18}")
