# -*- coding: utf-8 -*-
"""Взять страницу предприятия, переживая российские сертификаты НУЦ Минцифры.

ЗАЧЕМ ОТДЕЛЬНЫЙ ХОДОК. 2-я сессия нашла упор: целый класс сайтов заводов отдаёт
`Privacy error`, и это читалось как «сайт не открылся». Причина не в сайтах —
российские предприятия перешли на сертификаты НУЦ Минцифры, корня которого в
Chromium нет. Закрывать такое предприятие как «людей на сайте нет» нельзя: это
ложный ноль.

РЕШЕНИЕ УЖЕ ЛЕЖАЛО В НАШЕМ КОДЕ. У `browser_probe` есть параметр
`ignore_https_errors`, он передаётся в `new_context`. Ставить патч и трогать
allowlist раннера не нужно вовсе. Проверено на её же целях:

    alrosa.ru      Privacy error → 200, «АЛРОСА | Корпоративный сайт»
    uacrussia.ru   Privacy error → 200, «Объединенная авиастроительная корпорация»
    kurganpribor.ru  503 и с флагом, и без — там ДРУГАЯ беда: домен не на хостинге

ПОЧЕМУ ФЛАГ ВТОРОЙ ПОПЫТКОЙ, А НЕ ВСЕГДА. `ignore_https_errors` выключает
проверку подлинности сервера. Для чтения публичной страницы ради имени и
должности это приемлемо — данные всё равно принимаются только с цитатой и
ссылкой, — но включать его на всех подряд значит терять признак подмены там,
где он работает. Поэтому: сначала честно, и только на `ERR_CERT_AUTHORITY_INVALID`
второй заход с флагом. В ответе всегда видно, каким путём страница взята.

ТРЕТИЙ СЛУЧАЙ НЕ ЛЕЧИТСЯ ФЛАГОМ и это важно: `kurganpribor.ru` отдаёт 503
«сайт не добавлен на хостинг». Тут сайт правда не работает по этому адресу, и
предприятие надо искать другим путём, а не записывать в «сертификат виноват».

Использование из другого опа:
    import vzyat_stranicu as V
    от = V.взять('https://alrosa.ru/')
    от['html'], от['kak'], от['status']
"""
import sys

sys.path.insert(0, r'C:\sender\server')

_ПРИЗНАК_СЕРТИФИКАТА = ('ERR_CERT_AUTHORITY_INVALID', 'ERR_CERT_', 'Privacy error',
                        'SEC_ERROR', 'CERT_')


def взять(url, wait_ms=6000, screenshot=False, **прочее):
    """Вернуть {'html','text','title','status','kak','error'}.

    `kak` — «обычно» либо «с отключённой проверкой сертификата». Это поле
    обязано доезжать до журнала: путь, которым взята страница, — часть
    провенанса, а не деталь реализации.
    """
    import browser_probe as BP

    базовые = {'url': url, 'wait_ms': wait_ms, 'screenshot': screenshot}
    базовые.update(прочее)

    def один(флаг):
        args = dict(базовые)
        args['ignore_https_errors'] = флаг
        try:
            return BP.probe(args) or {}
        except Exception as ex:  # noqa: BLE001
            return {'error': f'{type(ex).__name__}: {str(ex)[:200]}'}

    от = один(False)
    беда = str(от.get('error') or '') + ' ' + str(от.get('title') or '')
    если_сертификат = any(п in беда for п in _ПРИЗНАК_СЕРТИФИКАТА)
    как = 'обычно'
    if если_сертификат:
        от2 = один(True)
        if not от2.get('error'):
            от, как = от2, 'с отключённой проверкой сертификата (НУЦ Минцифры)'
        else:
            как = 'не открылась даже с отключённой проверкой'
    return {'html': от.get('html') or '',
            'text': от.get('text_snippet') or '',
            'title': от.get('title') or '',
            'status': от.get('http_status'),
            'kak': как,
            'error': от.get('error')}


if __name__ == '__main__':
    import json
    for u in sys.argv[1:] or ['https://alrosa.ru/']:
        р = взять(u)
        print(json.dumps({'url': u, 'status': р['status'], 'title': р['title'][:60],
                          'kak': р['kak'], 'знаков': len(р['text']),
                          'error': str(р['error'])[:80]}, ensure_ascii=False))
