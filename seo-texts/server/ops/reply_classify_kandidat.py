_базовый = RC.classify_reply
_КОРОТКИЙ_ОТКАЗ = re.compile(r"^\W*(?:добрый день|здравствуйте|доброе утро)?\W*(?:нет|спасибо,?\s*нет|нет,?\s*спасибо)\b[^?]{0,60}$", re.I)
_ВОПРОС_ЗАКРЫТ = re.compile(r"вопрос\w*.{0,60}закрыт|вопросов.{0,50}\bнет\b", re.I)
_ПОДПИСЬ = re.compile(r"^\s*(?:--|с уважением|отправлено из|best regards)", re.I)


def _свой_текст(body):
    свой = RC.bez_citaty(body)
    строки = []
    for с in свой.splitlines():
        if _ПОДПИСЬ.search(с):
            break
        строки.append(с)
    return "\n".join(строки).strip() or свой


def classify_reply(subject, body, headers=None):
    свой = _свой_текст(body)
    сжатый = re.sub(r"\s+", " ", свой).strip()
    if _КОРОТКИЙ_ОТКАЗ.match(сжатый):
        return RC.ReplySignal(kind='not_interested', confidence=0.9, phone=None,
                              contact_hint=None, matched=('короткий_отказ',))
    if _ВОПРОС_ЗАКРЫТ.search(сжатый) and not re.search(r"\?", сжатый[:300]):
        return RC.ReplySignal(kind='not_interested', confidence=0.85, phone=None,
                              contact_hint=None, matched=('вопрос_закрыт',))
    р = _базовый(subject, свой, headers)
    # вопрос в СВОЁМ тексте (без подписи) — интерес, если правила ничего другого не нашли
    if р.kind == 'neutral' and '?' in сжатый[:400]:
        return RC.ReplySignal(kind='interested', confidence=0.6, phone=р.phone,
                              contact_hint=р.contact_hint, matched=('вопрос_в_своём_тексте',))
    return р
