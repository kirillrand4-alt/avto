# -*- coding: utf-8 -*-
"""ЕРКНМ как канал: имя и должность технического работника из текстов надзора.

ЗАЧЕМ КАНАЛ ВООБЩЕ. Тексты предостережений и актов Ростехнадзора называют
технических работников ПОИМЁННО и с должностью: «главный энергетик Казаков
Алексей Григорьевич», «заместитель главного механика Латыпов Артур Индусович».
Замер на том, что уже было в базе: 94 человека, 83 из них технические,
**телефонов ноль**. То есть канал даёт не звонок, а КЛЮЧ ПОИСКА: имя + роль +
предприятие, по которому обратный ход 3-й сессии и hh ищут личный номер.

ОГРАНИЧЕНИЕ ВЛАДЕЛЬЦА, ради которого оп и написан отдельно от «прогнать всё»:
«1573 = не надо, надо только те которые отображаются в базе». Цели берём из
`erknm-celi.csv` (видимые в панели и БЕЗ технического человека по имени — таким
канал реально что-то добавляет). Их 385, а не 1573.

ПРАВИЛО, КОТОРОЕ НЕЛЬЗЯ НАРУШАТЬ (слова 2-й сессии, я с ними согласен):
**повод для звонка отсюда брать НЕЛЬЗЯ.** Человек назван в предостережении
потому, что НЕ ПРОШЁЛ проверку знаний. Берём только «кто занимает роль».
Поэтому в запись идут имя, должность и ссылка — и НИКОГДА текст нарушения.

ДОЛГОВЕЧНОСТЬ. Каждое предприятие пишется строкой в серверный поток
`C:\\seostat\\drop\\erknm_stream.jsonl` с fsync СРАЗУ, а не копится в памяти.
Перезапуск продолжает с того места, где встал: уже разобранные ИНН читаются из
потока и пропускаются. Урок рестарта 25.07: то, что вернулось только в JSON
задания, при откате песочницы теряется.

Запуск:  python erknm_sbor.py [--limit N] [--celi ФАЙЛ] [--apply]
"""
import json
import os
import re
import sys
import time
from collections import Counter

ПОТОК = r'C:\seostat\drop\erknm_stream.jsonl'
ЦЕЛИ = (sys.argv[sys.argv.index('--celi') + 1] if '--celi' in sys.argv
        else os.path.join(r'C:\seostat\drop\drop-storage', 'erknm-celi.csv'))
ЛИМИТ = int(sys.argv[sys.argv.index('--limit') + 1]) if '--limit' in sys.argv else 0

# Должности, ради которых канал и берётся. Директор и бухгалтер тут не нужны:
# их мы и так знаем из ЕГРЮЛ, а звонить по компрессору надо не им.
ТЕХ = ('энергетик', 'механик', 'главный инженер', 'технический директор',
       'начальник цеха', 'начальник участка', 'начальник службы',
       'начальник отдела', 'мастер', 'инженер', 'ответственн')
# Роль всегда стоит ПЕРЕД фамилией: «главный энергетик Казаков А.Г.»
ЛИЦО = re.compile(
    r'(?P<dolzh>(?:[а-яё]+\s+){0,3}(?:' + '|'.join(ТЕХ) + r')[а-яё\s]{0,24}?)\s+'
    r'(?P<fio>[А-ЯЁ][а-яё]+(?:ов|ев|ин|ын|ко|ий|ая|ва|на|юк|ук|ян|дзе|швили)?\s+'
    r'(?:[А-ЯЁ][а-яё]+\s+[А-ЯЁ][а-яё]+|[А-ЯЁ]\.\s?[А-ЯЁ]\.))',
    re.I)


def лица_из_текста(текст):
    """Имя + должность из текста надзорного документа. Текст НЕ сохраняем."""
    найдено = {}
    for м in ЛИЦО.finditer(re.sub(r'\s+', ' ', текст or '')):
        долж = м.group('dolzh').strip(' ,;:').lower()
        фио = re.sub(r'\s+', ' ', м.group('fio')).strip()
        # мусорные захваты: «инженер» без имени, «ответственный за» без ФИО
        if len(фио.split()) < 2 or not any(к in долж for к in ТЕХ):
            continue
        найдено.setdefault(фио, долж)
    return [{'chelovek': ф, 'dolzhnost': д} for ф, д in найдено.items()]


def уже_разобрано():
    """Резюм строится по СЕРВЕРНОМУ потоку, а не по локальному чекпоинту."""
    было = set()
    if os.path.exists(ПОТОК):
        with open(ПОТОК, encoding='utf-8', errors='replace') as ф:
            for строка in ф:
                try:
                    было.add(str(json.loads(строка).get('inn') or ''))
                except Exception:  # noqa: BLE001
                    continue
    return было


def записать(запись):
    with open(ПОТОК, 'a', encoding='utf-8') as ф:
        ф.write(json.dumps(запись, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())


def цели():
    import csv
    csv.field_size_limit(10 ** 7)
    сп = []
    with open(ЦЕЛИ, encoding='utf-8-sig', errors='replace', newline='') as ф:
        for r in csv.DictReader(ф, delimiter=';'):
            и = re.sub(r'\D', '', str(r.get('inn') or ''))
            if len(и) in (10, 12):
                сп.append((и, str(r.get('name') or '')))
    return сп


def main():
    from erknm_istochnik import мероприятия_po_inn  # форма запроса — отдельно

    список = цели()
    было = уже_разобрано()
    осталось = [(и, н) for и, н in список if и not in было]
    if ЛИМИТ:
        осталось = осталось[:ЛИМИТ]
    print(f'целей {len(список)}, уже разобрано {len(было)}, '
          f'в этот заход {len(осталось)}')

    стат = Counter()
    for н, (инн, имя) in enumerate(осталось, 1):
        запись = {'inn': инн, 'name': имя, 'ts': int(time.time()), 'lica': []}
        try:
            меры = мероприятия_po_inn(инн)
        except Exception as e:  # noqa: BLE001
            запись['error'] = str(e)[:200]
            стат['ошибка запроса'] += 1
            записать(запись)
            continue
        запись['meropriyatiy'] = len(меры)
        стат['мероприятий всего'] += len(меры)
        for м in меры:
            текст = ' '.join(str(м.get(к) or '') for к in
                             ('description', 'violations', 'result', 'subject',
                              'text', 'measures'))
            for л in лица_из_текста(текст):
                л['ssylka'] = м.get('url') or ''
                л['data'] = м.get('date') or ''
                л['organ'] = m_organ(м)
                запись['lica'].append(л)
        # дубли по имени внутри предприятия
        видел = set()
        запись['lica'] = [л for л in запись['lica']
                          if not (л['chelovek'] in видел or видел.add(л['chelovek']))]
        стат['ЛИЦ НАЙДЕНО'] += len(запись['lica'])
        if запись['lica']:
            стат['предприятий с лицами'] += 1
        записать(запись)
        if н % 25 == 0:
            print(f'  {н}/{len(осталось)}  лиц {стат["ЛИЦ НАЙДЕНО"]}', flush=True)

    print(json.dumps(стат.most_common(), ensure_ascii=False, indent=1))


def m_organ(м):
    return str(м.get('organ') or м.get('authority') or '')[:120]


if __name__ == '__main__':
    main()
