# -*- coding: utf-8 -*-
"""ЕРКНМ как канал: суточный архив надзора → наши предприятия → имена и роли.

ЧТО ЭТО ЗА ИСТОЧНИК И ПОЧЕМУ ОН ВЗЯТ ТАК. Поиск на сайте требует капчу на
каждый запрос, а открытые данные — нет. Форма выгрузки:
    манифест   /blob/erknm-opendata/7710146102-inspection-<год>-<мес>.xml
    в нём 257 суточных версий ОДНОГО И ТОГО ЖЕ месяца, каждая — полный срез;
    берём ПОСЛЕДНЮЮ: .../<год>/<мес>/data-<ГГГГММДД>-structure-20220125.zip
Вес одной версии — 338 МБ (июнь 2026), качается за ~9 минут через socks5;
серверный адрес площадку не видит вовсе, нужен прокси.

ЧТО ВНУТРИ, ПРОВЕРЕНО НА ПЕРВЫХ 40 МБ. Записи `INSPECTION` с `SUBJECT INN`,
и в них два разных сорта людей, которые НЕЛЬЗЯ путать:
  * `INSPECTOR_FULL_NAME` — проверяющий ОТ НАДЗОРА (Роспотребнадзор и т.п.).
    Нам он не нужен вообще: это не сотрудник предприятия;
  * текст `WARNING_CONTENT` (предостережения, 1438 штук на 40 МБ) — вот там
    называют работников предприятия с должностями.
Поэтому имена берём ТОЛЬКО из текстов, а `INSPECTOR` явно пропускаем. Без этого
различения канал выдал бы нам сотни инспекторов вместо технических ЛПР.

ОГРАНИЧЕНИЕ ВЛАДЕЛЬЦА: «1573 = не надо, надо только те которые отображаются в
базе». Цели — из `erknm-celi.csv` (видимые и без техчеловека), их 385.

ПРАВИЛО, КОТОРОЕ НЕЛЬЗЯ НАРУШАТЬ (2-я сессия, я согласен): **повод для звонка
отсюда брать НЕЛЬЗЯ.** Человека назвали в предостережении потому, что он НЕ
ПРОШЁЛ проверку знаний. Берём «кто занимает роль», повод — из состояния машины.

ДОЛГОВЕЧНОСТЬ. Каждое найденное предприятие пишется строкой в серверный поток
`C:\\seostat\\drop\\erknm_stream.jsonl` с fsync сразу. Разобранные месяцы
отмечаются там же, поэтому перезапуск не качает заново то, что уже прошло.

Запуск: python erknm_sbor.py --god 2026 --mes 6 [--vse]
"""
import io
import json
import os
import re
import sys
import time
import zipfile
from collections import Counter
from xml.etree import ElementTree as ET

ПОТОК = r'C:\seostat\drop\erknm_stream.jsonl'
# ВНЕ БАЗЫ — отдельное хранилище, по прямому слову владельца: «не выкидывай их,
# потом пригодятся». Это технические руководители заводов, которых в нашей
# панели НЕТ: Ростехнадзор называет их поимённо, потому что у предприятия есть
# опасный производственный объект — то есть профиль ровно тот, что покупает
# компрессоры. В панель они НЕ идут (это решение владельца, не моё), но и
# теряться не должны: собрать их заново стоит 9 минут закачки на каждый месяц.
ПОТОК_ВНЕ = r'C:\seostat\drop\erknm_vne_bazy.jsonl'
ЦЕЛИ = os.path.join(r'C:\seostat\drop\drop-storage', 'erknm-celi.csv')
# Архив КЭШИРУЕТСЯ по месяцу: 338 МБ качаются 9 минут, и качать их
# повторно ради новой догадки — расточительство, уже допущенное дважды.
def кэш(год, мес):
    return fr'C:\seostat\drop\_erknm_{год}_{мес}.zip'
# Ростехнадзор пишется по-разному: коротким именем, полным «по
# экологическому, технологическому и атомному надзору» и через предмет
# «промышленная безопасность». Ловим по любому признаку — узкий фильтр
# дал бы ноль, неотличимый от пустого источника.
РТН = re.compile(r'ростехнадзор|технологическому и атомному надзору|'
                 r'промышленной безопасност|энергетическ(ий|ого) надзор',
                 re.I)


def арг(имя, поум=None):
    try:
        return sys.argv[sys.argv.index(имя) + 1]
    except (ValueError, IndexError):
        return поум


ГОД = арг('--god', '2026')
МЕС = арг('--mes', '6')
ВСЕ = '--vse' in sys.argv          # брать все предприятия, а не только цели
ЗАНОВО = '--zanovo' in sys.argv    # перегнать месяц новым правилом разбора

ТЕХ = ('энергетик', 'механик', 'главный инженер', 'технический директор',
       'начальник цеха', 'начальник участка', 'начальник службы',
       'начальник отдела', 'инженер', 'ответственн', 'мастер')
# Должность и ФИО стоят в ЛЮБОМ порядке: «Боголюбов Василий Владимирович —
# главный энергетик» и «допуск неаттестованного работника: Грошева Андрея
# Олеговича, инженера-конструктора». Строгое правило «должность перед фамилией»
# на живом тексте дало 2 имени против 16 у мягкого — поэтому мягкое.
ЛИЦО = re.compile(
    r'(?:(?P<d1>' + '|'.join(ТЕХ) + r')[^.;]{0,60}?'
    r'(?P<f1>[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}))'
    r'|(?:(?P<f2>[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,})'
    r'[^.;]{0,60}?(?P<d2>' + '|'.join(ТЕХ) + r'))')
# Отчество — вот что отличает человека от учреждения. Без этой проверки в улов
# шло «Правительства Российской Федерации» (три слова с заглавных, стоящие
# рядом со словом «электроэнергетики») — три ложных имени из пяти на живом
# прогоне. Требуем окончание отчества у ТРЕТЬЕГО слова.
ОТЧЕСТВО = re.compile(r'(ович|евич|ьич|овича|евича|овна|евна|ична|овны|евны)$',
                      re.I)
# рядом стоит проверяющий или орган — это не работник предприятия
ЧУЖОЙ = re.compile(r'государственн\w+\s+инспектор|инспектор по городу|'
                   r'специалист-эксперт|прокурат|Правительств|'
                   r'Российской Федерации|руководител\w+ управлени', re.I)


def лица_из_текста(текст):
    """Имя + должность из текста надзорного документа. Сам текст не храним."""
    т = re.sub(r'\s+', ' ', текст or '')
    найдено = {}
    for м in ЛИЦО.finditer(т):
        фио = (м.group('f1') or м.group('f2') or '').strip()
        долж = (м.group('d1') or м.group('d2') or '').strip().lower()
        слова = фио.split()
        if len(слова) != 3 or not ОТЧЕСТВО.search(слова[2]):
            continue
        окно = т[max(0, м.start() - 90):м.end() + 90]
        if ЧУЖОЙ.search(окно):
            continue
        найдено.setdefault(фио, долж[:80])
    return [{'chelovek': ф, 'dolzhnost': д} for ф, д in найдено.items()]


def цели():
    import csv
    csv.field_size_limit(10 ** 7)
    из = {}
    if os.path.exists(ЦЕЛИ):
        with open(ЦЕЛИ, encoding='utf-8-sig', errors='replace', newline='') as ф:
            for r in csv.DictReader(ф, delimiter=';'):
                и = re.sub(r'\D', '', str(r.get('inn') or ''))
                if len(и) in (10, 12):
                    из[и] = str(r.get('name') or '')
    return из


def прокси():
    import urllib.request
    d = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    зпр = urllib.request.Request(
        os.environ.get('DROP_URL', '').rstrip('/') + '/dolphin-proxies.txt',
        headers={'X-Drop-Token': os.environ.get('DROP_TOKEN', '')})
    из = []
    for l in d.open(зпр, timeout=30).read().decode('utf-8', 'replace').splitlines():
        l = l.strip()
        m = (re.match(r'(?:([^:@]+):([^@]*)@)?([^:/]+):(\d+)', l)
             if l and not l.startswith('#') else None)
        if m:
            u, pw, h, _ = m.groups()
            из.append('socks5://%s:%s@%s:3001' % (u, pw, h))
    return из


def записать(запись, куда=None):
    with open(куда or ПОТОК, 'a', encoding='utf-8') as ф:
        ф.write(json.dumps(запись, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())


def месяц_пройден(год, мес):
    if not os.path.exists(ПОТОК):
        return False
    метка = f'{год}-{мес}'
    for стр in open(ПОТОК, encoding='utf-8', errors='replace'):
        try:
            з = json.loads(стр)
        except Exception:  # noqa: BLE001
            continue
        if з.get('vid') == 'месяц-закрыт' and з.get('mesyac') == метка:
            return True
    return False


def скачать(url, PX, путь):
    import requests
    for i, px in enumerate(PX[:10]):
        t0 = time.time()
        try:
            r = requests.get(url, proxies={'http': px, 'https': px}, timeout=120,
                             stream=True, headers={'User-Agent': 'Mozilla/5.0'})
            if r.status_code >= 400:
                continue
            всего = 0
            with open(путь, 'wb') as ф:
                for кусок in r.iter_content(1 << 20):
                    ф.write(кусок)
                    всего += len(кусок)
            r.close()
            print(f'скачано {всего} б за {time.time() - t0:.0f} с (прокси #{i})',
                  flush=True)
            return всего
        except Exception as e:  # noqa: BLE001
            print(f'  прокси #{i}: {str(e)[:70]}', flush=True)
    return 0


def текст_записи(эл):
    """Все тексты предостережений и решений записи — БЕЗ имён инспекторов.

    INSPECTOR выкидывается целиком: там сотрудники надзора, а не предприятия.
    Их попадание в выход и было бы главной ошибкой этого канала.
    """
    куски = []
    for под in эл.iter():
        имя = под.tag.rsplit('}', 1)[-1]
        if имя.startswith('INSPECTOR'):
            continue
        if под.text and под.text.strip():
            куски.append(под.text.strip())
        for к, v in под.attrib.items():
            if к in ('VALUE', 'CAPTION', 'CONTENT', 'NAME') and len(str(v)) > 25:
                куски.append(str(v))
    return ' '.join(куски)


def main():
    # ЗАНОВО. Резюм по потоку правильный, пока правила разбора не менялись; но
    # когда меняешь сам разбор (я добавил фильтр по Ростехнадзору, проверку
    # отчества и расширил цели с 385 до 692), старая отметка «месяц закрыт»
    # начинает врать: она говорит «сделано», а сделано другим правилом.
    if ЗАНОВО:
        print('--zanovo: отметка о закрытии месяца игнорируется')
    elif месяц_пройден(ГОД, МЕС):
        print(f'месяц {ГОД}-{МЕС} уже разобран — пропуск')
        return
    цел = цели()
    print(f'целей в списке: {len(цел)}'
          + ('  (режим --vse: фильтр по целям выключен)' if ВСЕ else ''))
    PX = прокси()
    import requests
    манифест = ('https://proverki.gov.ru/blob/erknm-opendata/'
                f'7710146102-inspection-{ГОД}-{МЕС}.xml')
    ман = None
    for px in PX[:8]:
        try:
            ман = requests.get(манифест, proxies={'http': px, 'https': px},
                               timeout=60,
                               headers={'User-Agent': 'Mozilla/5.0'}).text
            break
        except Exception:  # noqa: BLE001
            continue
    ссылки = re.findall(r'<source>([^<]+)</source>', ман or '')
    if not ссылки:
        print('манифест пуст или не открылся')
        return
    print(f'версий за месяц {len(ссылки)}, берём последнюю', flush=True)
    ФАЙЛ = кэш(ГОД, МЕС)
    if os.path.exists(ФАЙЛ) and os.path.getsize(ФАЙЛ) > 10_000_000:
        print('архив уже на диске:', os.path.getsize(ФАЙЛ), 'б', flush=True)
    elif not скачать(ссылки[-1], PX, ФАЙЛ):
        print('архив не скачался')
        return

    стат = Counter()
    найдено_по_инн = {}
    вне_по_инн = {}
    try:
        z = zipfile.ZipFile(ФАЙЛ)
        имя_вн = z.namelist()[0]
        with z.open(имя_вн) as поток:
            for событие, эл in ET.iterparse(io.BufferedReader(поток, 1 << 20),
                                            events=('end',)):
                if not эл.tag.endswith('INSPECTION'):
                    continue
                стат['записей прочитано'] += 1
                инн = ''
                орган = ''
                for под in эл.iter():
                    т = под.tag.rsplit('}', 1)[-1]
                    if т == 'SUBJECT' and not инн:
                        инн = re.sub(r'\D', '', под.get('INN') or '')
                    elif т in ('KNO_ORGANIZATION', 'KIND_CONTROL') and not орган:
                        орган = под.get('VALUE') or под.get('NAME') or ''
                # Имена работников предприятия называет РОСТЕХНАДЗОР — у него
                # предмет промышленная безопасность. Санэпиднадзор и пожарный
                # надзор в июне 2026 дали 4,5 млн знаков текста и НИ ОДНОГО
                # технического имени: там ИП, молоко и маркировка.
                if not РТН.search(орган):
                    стат['не Ростехнадзор — пропуск'] += 1
                    эл.clear()
                    continue
                стат['ростехнадзорских'] += 1
                наш = bool(инн) and (ВСЕ or инн in цел)
                if инн and not наш:
                    # НЕ наше предприятие — но человека сохраняем отдельно.
                    т = текст_записи(эл)
                    лица = лица_из_текста(т)
                    if лица:
                        стат['лиц ВНЕ базы'] += len(лица)
                        вне_по_инн.setdefault(инн, {
                            'inn': инн, 'lica': [], 'daty': [],
                            'organ': орган[:120]})
                        з_в = вне_по_инн[инн]
                        д_в = эл.get('START_DATE') or ''
                        if д_в and д_в not in з_в['daty']:
                            з_в['daty'].append(д_в)
                        видел_в = {л['chelovek'] for л in з_в['lica']}
                        for л in лица:
                            if л['chelovek'] not in видел_в:
                                л['erpid'] = эл.get('ERPID') or ''
                                л['data'] = д_в
                                з_в['lica'].append(л)
                                видел_в.add(л['chelovek'])
                if наш:
                    стат['ЗАПИСЕЙ ПО НАШИМ'] += 1
                    т = текст_записи(эл)
                    лица = лица_из_текста(т)
                    з = найдено_по_инн.setdefault(
                        инн, {'inn': инн, 'name': цел.get(инн, ''),
                              'meropriyatiy': 0, 'lica': [], 'daty': []})
                    з['meropriyatiy'] += 1
                    д = эл.get('START_DATE') or ''
                    if д and д not in з['daty']:
                        з['daty'].append(д)
                    видел = {л['chelovek'] for л in з['lica']}
                    for л in лица:
                        if л['chelovek'] not in видел:
                            л['erpid'] = эл.get('ERPID') or ''
                            л['data'] = д
                            з['lica'].append(л)
                            видел.add(л['chelovek'])
                эл.clear()
                if стат['записей прочитано'] % 50000 == 0:
                    print(f'  прочитано {стат["записей прочитано"]}, '
                          f'наших {стат["ЗАПИСЕЙ ПО НАШИМ"]}', flush=True)
    finally:
        # архив НЕ удаляем: он кэш месяца. Чистка — отдельным решением, когда
        # месяц закрыт и перепроверять его больше незачем.
        pass

    лиц = 0
    for з in найдено_по_инн.values():
        з['mesyac'] = f'{ГОД}-{МЕС}'
        з['vid'] = 'предприятие'
        з['ts'] = int(time.time())
        лиц += len(з['lica'])
        записать(з)
    лиц_вне = 0
    for з in вне_по_инн.values():
        з['mesyac'] = f'{ГОД}-{МЕС}'
        з['vid'] = 'вне-базы'
        з['ts'] = int(time.time())
        лиц_вне += len(з['lica'])
        записать(з, ПОТОК_ВНЕ)
    записать({'vid': 'месяц-закрыт', 'mesyac': f'{ГОД}-{МЕС}',
              'ts': int(time.time()),
              'zapisey': стат['записей прочитано'],
              'nashih': стат['ЗАПИСЕЙ ПО НАШИМ'],
              'predpriyatiy': len(найдено_по_инн), 'lic': лиц,
              'vne_bazy_predpriyatiy': len(вне_по_инн), 'vne_bazy_lic': лиц_вне})
    print(json.dumps({'записей в архиве': стат['записей прочитано'],
                      'записей по нашим предприятиям': стат['ЗАПИСЕЙ ПО НАШИМ'],
                      'предприятий найдено': len(найдено_по_инн),
                      'ЛИЦ ИЗВЛЕЧЕНО': лиц,
                      'вне базы: предприятий': len(вне_по_инн),
                      'вне базы: ЛИЦ (сохранены отдельно)': лиц_вне},
                     ensure_ascii=False, indent=1))
    for з in list(найдено_по_инн.values())[:10]:
        if з['lica']:
            print(f"  {з['inn']} {з['name'][:34]:34} "
                  + '; '.join(f"{л['dolzhnost'][:22]}: {л['chelovek']}"
                              for л in з['lica'][:3]))


if __name__ == '__main__':
    main()
