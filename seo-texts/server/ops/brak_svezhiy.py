# -*- coding: utf-8 -*-
"""Почему письма перестали появляться в панели: разбор СВЕЖЕГО брака.

Владелец: «в панели перестали появляться письма». Сверка показала, что
генерация идёт и деньги тратятся, но доля брака подскочила: за последний
отрезок доехало 5 писем, забраковано 10. Значит письма пишутся и гибнут на
гейте, а не теряются.

Печатаем последние N записей журнала с причинами брака и их долей - причина
почти всегда одна и та же, и по ней сразу видно, какое правило слишком
строгое или какой заход сломался.

    python zapusk_svoego_skripta.py ops/brak_svezhiy.py 80
"""
import io
import json
import os
import sys
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
СКОЛЬКО = int(sys.argv[1]) if len(sys.argv) > 1 else 80

строки = []
if os.path.exists(ЖУРНАЛ):
    for s in io.open(ЖУРНАЛ, encoding="utf-8"):
        try:
            z = json.loads(s)
        except Exception:                                       # noqa: BLE001
            continue
        if z.get("этап") == "итог":
            строки.append(z)

свежие = строки[-СКОЛЬКО:]
ок = sum(1 for z in свежие if z.get("ок"))
print(f"последние {len(свежие)} итогов: ок {ок}, брак {len(свежие) - ок} "
      f"({100.0 * (len(свежие) - ок) / max(1, len(свежие)):.0f}%)")

причины = Counter()
for z in свежие:
    if z.get("ок"):
        continue
    for б in (z.get("брак") or [])[:1]:
        т = str(б)
        # причина = первые слова до двоеточия или кавычки
        ключ = т.split(":")[0].split("«")[0].strip()[:60]
        причины[ключ] += 1
print("\nпричины брака:")
for k, n in причины.most_common(12):
    print(f"  {n:>3}  {k}")

print("\nпоследние 12 браков целиком:")
показано = 0
for z in reversed(свежие):
    if z.get("ок") or показано >= 12:
        continue
    показано += 1
    print(f"  {str(z.get('имя'))[:34]:<36} {str((z.get('брак') or [''])[0])[:120]}")

# Разбивка по времени: когда доля брака поднялась.
print("\nпо кругам (каждые 20 итогов):")
for i in range(0, len(строки), 20):
    часть = строки[i:i + 20]
    о = sum(1 for z in часть if z.get("ок"))
    print(f"  итоги {i:>4}-{i + len(часть):>4}: ок {о:>2} брак {len(часть) - о:>2}")
