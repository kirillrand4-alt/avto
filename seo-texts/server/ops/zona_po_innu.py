"""Часовая зона получателя по коду региона в ИНН. Одна правда для загрузчиков.

Окно отправки считается по зоне получателя (panel_settings.sending_window,
by_recipient_tz). Пока в загрузчике стояло tz="Europe/Moscow" для всех,
хозяйство в Алтайском крае получало бы письмо в 09:00 МСК, то есть в 13:00
по себе - при окне 09:00-14:00 у него оставался час. Так были заведены
3038 компаний партии «Агро зерно 2026»; 1049 из них пришлось переставлять.
"""
ЗОНЫ = {}


def _пометить(зона, коды):
    for к in коды.split():
        ЗОНЫ[к.strip()] = зона


_пометить("Europe/Kaliningrad", "39")
