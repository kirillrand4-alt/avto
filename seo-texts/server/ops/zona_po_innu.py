ПО_УМОЛЧАНИЮ = "Europe/Moscow"


def зона_по_inn(инн, по_умолчанию=ПО_УМОЛЧАНИЮ):
    """«2260002518» -> «Asia/Barnaul». Код не узнан - московская зона.

    Московская по умолчанию, а не пустая: пустую зону окно трактует как UTC,
    и письмо уедет на три часа раньше, чем следует.
    """
    ц = "".join(c for c in str(инн or "") if c.isdigit())
    return ЗОНЫ.get(ц[:2], по_умолчанию) if len(ц) >= 2 else по_умолчанию
