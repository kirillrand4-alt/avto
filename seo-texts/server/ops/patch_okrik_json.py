# -*- coding: utf-8 -*-
"""Повтор после ответа без JSON — с окриком, а не тем же промптом.

ЗАЧЕМ. Три попытки разбора были и раньше, но все три уходили СЛОВО В СЛОВО
одинаковыми. Модель, решившая порассуждать вместо ответа, рассуждала
трижды — и письмо уходило в брак «нет JSON в ответе», оплаченное трижды.
Замер 25.08 по логам: 25 из 47 браков мейеровского блока и 57 из 180
компрессорного — ровно этот случай.

ХИРУРГИЧЕСКИ. Каталог C:\\sender\\sender делят несколько сессий: правим два
куска по якорям, каждый обязан встретиться ровно один раз, с .bak и
компиляцией. Сухой прогон по умолчанию, катить: --katit
"""
import io
import os
import py_compile
import sys
import time

ФАЙЛ = r"C:\sender\sender\ai_letter.py"
КАТИТЬ = "--katit" in sys.argv

ЯКОРЬ_КОНСТ = "def _parse_json(text: str, tag: str):"
КОНСТ = '''# Окрик на повторной попытке: предыдущий ответ пришёл без JSON. Держим
# рядом с разбором, чтобы правка формата схемы и правка окрика лежали в
# одном месте.
ОКРИК_JSON = (
    '\\n\\nПРЕДЫДУЩИЙ ОТВЕТ БЫЛ ОТКЛОНЁН: в нём не было JSON. '
    'Ответь ТОЛЬКО JSON-объектом по схеме выше. Никаких вступлений, '
    'рассуждений, пояснений и текста до или после JSON.')


'''

ЯКОРЬ_ASK = """        for t in range(self.json_tries):
            try:
                return _parse_json(зов(prompt), tag)
            except Exception as e:  # noqa: BLE001 - битый JSON/обрыв → ретрай
                last = f'{tag}: {e} (попытка {t + 1})'
        raise RuntimeError(last)"""
НОВЫЙ_ASK = """        for t in range(self.json_tries):
            try:
                # ПОВТОР С ОКРИКОМ, А НЕ ТОТ ЖЕ ПРОМПТ. Три попытки были и
                # раньше, но все три уходили СЛОВО В СЛОВО одинаковыми — и
                # модель, решившая порассуждать вместо ответа, рассуждала
                # трижды. Замер 25.08 по логам: из 47 браков мейеровского
                # блока 25 - «нет JSON в ответе», ответ начинался с «Профиль
                # получателя…»; в компрессорном блоке так же ушло 57 писем
                # из 180 браков. Каждая такая попытка оплачена и выброшена.
                #
                # На повторе прикладываем окрик: он короткий, кэш промпта не
                # ломает (добавка в хвосте), а модели напоминает формат.
                return _parse_json(зов(prompt if not t else prompt + ОКРИК_JSON),
                                   tag)
            except Exception as e:  # noqa: BLE001 - битый JSON/обрыв → ретрай
                last = f'{tag}: {e} (попытка {t + 1})'
        raise RuntimeError(last)"""

текст = io.open(ФАЙЛ, encoding="utf-8").read()
if "ОКРИК_JSON" in текст:
    print("правка уже на месте")
    raise SystemExit(0)
for имя, як in (("константа", ЯКОРЬ_КОНСТ), ("_ask", ЯКОРЬ_ASK)):
    n = текст.count(як)
    print("якорь %-10s найден раз: %d" % (имя, n))
    if n != 1:
        raise SystemExit("якорь должен быть ровно один")
новый = текст.replace(ЯКОРЬ_КОНСТ, КОНСТ + ЯКОРЬ_КОНСТ).replace(ЯКОРЬ_ASK, НОВЫЙ_ASK)
print("было %d знаков, станет %d" % (len(текст), len(новый)))
if not КАТИТЬ:
    print("сухой прогон. Катить: --katit")
    raise SystemExit(0)
копия = "%s.bak-%d" % (ФАЙЛ, int(time.time()))
io.open(копия, "w", encoding="utf-8", newline="").write(текст)
print(".bak: %s" % os.path.basename(копия))
with io.open(ФАЙЛ, "w", encoding="utf-8", newline="") as f:
    f.write(новый)
    f.flush()
    os.fsync(f.fileno())
py_compile.compile(ФАЙЛ, doraise=True)
print("записан и скомпилирован")
