"""Уровень шума в дневных долях ответов и отбивок.

Прежде чем говорить «на больших объёмах отвечают хуже», надо знать, различима
ли разница вообще. При доле ответов около 2% и тысяче писем в день случайный
разброс сам по себе даёт ±0.4-0.9 процентного пункта — то есть день с 1.56% и
день с 2.06% могут быть одним и тем же процессом.

Считаем по КОГОРТАМ: письмо приписано дню ОТПРАВКИ, ответ засчитан, если
пришёл в течение 72 часов после него. Дни, которым не исполнилось 72 часа,
помечены как незрелые и в проверки не идут.

Математика без внешних библиотек: доверительный интервал Уилсона (он честен
на малых долях, в отличие от нормального), однородность — хи-квадрат с
p-значением через неполную гамма-функцию.
"""
import math
import sqlite3
import sys
import time
from collections import defaultdict

БАЗА = r"C:\sender\sender.db"
ОКНО_ЧАСОВ = int(sys.argv[1]) if len(sys.argv) > 1 else 72


def _сек(ts):
    т = str(ts or "")[:19].replace("T", " ")
    try:
        return time.mktime(time.strptime(т, "%Y-%m-%d %H:%M:%S"))
    except Exception:
        return 0.0


def уилсон(k, n, z=1.96):
    """Доверительный интервал доли. На малых долях нормальный врёт."""
    if n == 0:
        return 0.0, 0.0, 0.0
    p = k / n
    зн = 1 + z * z / n
    центр = (p + z * z / (2 * n)) / зн
    полу = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / зн
    return p, max(0.0, центр - полу), min(1.0, центр + полу)


def _гамма_p(s, x):
    """Регуляризованная нижняя неполная гамма — для p-значения хи-квадрат."""
    if x <= 0:
        return 0.0
    if x < s + 1:
        сл, ч, зн = 1.0 / s, 1.0 / s, s
        for _ in range(500):
            зн += 1
            ч *= x / зн
            сл += ч
            if abs(ч) < abs(сл) * 1e-14:
                break
        return сл * math.exp(-x + s * math.log(x) - math.lgamma(s))
    # непрерывная дробь для верхней части
    крошка = 1e-300
    b, c, d = x + 1 - s, 1 / крошка, 1 / (x + 1 - s)
    h = d
    for i in range(1, 500):
        an = -i * (i - s)
        b += 2
        d = an * d + b
        if abs(d) < крошка:
            d = крошка
        c = b + an / c
        if abs(c) < крошка:
            c = крошка
        d = 1 / d
        дельта = d * c
        h *= дельта
        if abs(дельта - 1) < 1e-14:
            break
    верх = math.exp(-x + s * math.log(x) - math.lgamma(s)) * h
    return 1.0 - верх


def p_хи2(х, df):
    return max(0.0, min(1.0, 1.0 - _гамма_p(df / 2.0, х / 2.0)))


def двe_doli(k1, n1, k2, n2):
    """z-критерий для двух долей; возвращает разницу, z и p (двусторонний)."""
    if not n1 or not n2:
        return 0.0, 0.0, 1.0
    p1, p2 = k1 / n1, k2 / n2
    p = (k1 + k2) / (n1 + n2)
    зн = math.sqrt(p * (1 - p) * (1 / n1 + 1 / n2))
    if зн == 0:
        return p1 - p2, 0.0, 1.0
    z = (p1 - p2) / зн
    p_знач = math.erfc(abs(z) / math.sqrt(2))
    return p1 - p2, z, p_знач


c = sqlite3.connect("file:%s?mode=ro" % БАЗА, uri=True, timeout=60)
c.row_factory = sqlite3.Row
письма = [(r["recipient_id"], str(r["sent_at"]))
          for r in c.execute("SELECT recipient_id, sent_at FROM messages "
                             " WHERE sent_at IS NOT NULL AND status='sent'")]
события = defaultdict(list)
for r in c.execute("SELECT recipient_id, event_type, event_ts FROM events "
                   " WHERE event_type IN ('reply','bounce') "
                   "   AND recipient_id IS NOT NULL"):
    события[(r["recipient_id"], r["event_type"])].append(_сек(r["event_ts"]))
c.close()

когорты = defaultdict(lambda: {"n": 0, "reply": 0, "bounce": 0})
for rid, когда in письма:
    день = когда[:10]
    т0 = _сек(когда)
    к = когорты[день]
    к["n"] += 1
    for вид in ("reply", "bounce"):
        for т in события.get((rid, вид), ()):
            if т0 <= т <= т0 + ОКНО_ЧАСОВ * 3600:
                к[вид] += 1
                break

сейчас = time.time()
зрелые = []
print("=== КОГОРТЫ: письмо считается за день ОТПРАВКИ, ответ — за 72 часа ===")
