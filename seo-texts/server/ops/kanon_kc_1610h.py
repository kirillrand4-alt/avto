"""КЦ 16.10: ИП — не по фамилии (владелец: «ИП он странно обзывает», тема
«…на производстве «Симонян»»). Брать название с сайта/домена («Селигер-Лес»),
нет — «на вашем производстве» без названия. Бэкап .bak-kc1610h-*."""
import io, py_compile, shutil, sys, time
П = r"C:\sender\sender\ai_letter.py"
т = io.open(П, encoding="utf-8").read()
if "ИП - НЕ ПО ФАМИЛИИ" in т:
    print("=== КЦ 1610h: УЖЕ БЫЛО ==="); sys.exit()
С = """    в) НАЗВАНИЕ КОМПАНИИ - как его пишет сама компания, каждое слово с
       заглавной: «АГД Даймондс», «Астрал-Дизайн», «Века Рус», не «АГД
       даймондс». Аббревиатуры - заглавными."""
Н = С + """
       ИП - НЕ ПО ФАМИЛИИ (владелец 16.10): «на производстве «Симонян»»
       звучит странно. У ИП бери название бизнеса с сайта или из домена почты
       («seliger-les.ru» -> «Селигер-Лес»); нет такого - в теме «на вашем
       производстве» без названия, в вопросе «для вашего производства»."""
if т.count(С) != 1:
    print("якорь:", т.count(С)); print("=== КЦ 1610h: НЕ ПРИМЕНЕНО ==="); sys.exit()
б = П + ".bak-kc1610h-%d" % int(time.time()); shutil.copy2(П, б)
io.open(П, "w", encoding="utf-8").write(т.replace(С, Н))
try:
    py_compile.compile(П, doraise=True)
except Exception as е:
    shutil.copy2(б, П); print("откат:", е); sys.exit()
print("бэкап:", б); print("=== КЦ 1610h: ПРИМЕНЕНО ===")
