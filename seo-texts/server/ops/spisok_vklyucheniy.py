import io
import py_compile
import shutil
import sys
import time
ПУТЬ = r"C:\\sender\\sender\\ai_letter.py"
т = io.open(ПУТЬ, encoding="utf-8").read()
if "ТЕ ЖЕ ПЯТЬ, НО НЕ ОДНОЙ СТРОКОЙ" in т:
    print("=== СПИСОК ВКЛЮЧЕНИЙ: УЖЕ БЫЛО ===")
    sys.exit(0)
СТАР = '   упакованный продукт». Читателю важен результат, принцип работы уводит письмо\n   в техпаспорт.\n'
НОВ = '   упакованный продукт». Читателю важен результат, принцип работы уводит письмо\n   в техпаспорт.\n   СПИСОК ВКЛЮЧЕНИЙ - ТЕ ЖЕ ПЯТЬ, НО НЕ ОДНОЙ СТРОКОЙ (владелец 12.10). Слепая\n   оценка 20 писем: дословный «металл, стекло, керамику, камень, силикон и\n   прочие плотные включения» в каждом письме - главный признак шаблона. Состав\n   не меняй (это правило 12.08: только заведомо видимое), меняй ПОРЯДОК и\n   ПОДАЧУ: начни с того, что ближе их продукту (стекло - у фасовки в стекло,\n   камень - у овощей и зерна, металл - у мяса и линий с ножами), и строй фразу\n   по-своему: «стекло, металл, камни, керамику и силикон», «от металлической\n   стружки до осколков стекла и камней, а также керамику и силикон»,\n   «металл, а также стекло, камень, керамику, силикон». Хвост «и прочие\n   плотные включения» - не в каждом письме.\n'
if т.count(СТАР) != 1:
    print("якорь: %d" % т.count(СТАР))
    print("=== СПИСОК ВКЛЮЧЕНИЙ: НЕ ПРИМЕНЕНО ===")
    sys.exit(0)
бэкап = ПУТЬ + ".bak-%d" % int(time.time())
shutil.copy2(ПУТЬ, бэкап)
