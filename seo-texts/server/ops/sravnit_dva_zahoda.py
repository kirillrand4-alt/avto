"""Прямое сравнение пар заходов: z-тест двух долей, без округлений на глаз."""
import math

ПАРЫ = (("наблюдение о них", 3294, 96, "от площадки", 774, 13),
        ("наблюдение о них", 3294, 96, "прочее", 1066, 19),
        ("наблюдение о них", 3294, 96, "представление себя", 330, 8),
        ("прочее", 1066, 19, "от площадки", 774, 13))


def norm_p(z):
    return math.erfc(abs(z) / math.sqrt(2))          # двусторонний p


print("=== ПАРНЫЕ СРАВНЕНИЯ ===")
for a, na, ka, b, nb, kb in ПАРЫ:
    p = (ka + kb) / float(na + nb)
    se = math.sqrt(p * (1 - p) * (1.0 / na + 1.0 / nb))
    d = ka / float(na) - kb / float(nb)
    z = d / se if se else 0
    print("   %-20s %.2f%%  против  %-20s %.2f%%   разница %+.2f п.п.  z=%.2f  p=%.3f%s"
          % (a, 100.0 * ka / na, b, 100.0 * kb / nb, 100 * d, z, norm_p(z),
             "  ЗНАЧИМО" if norm_p(z) < 0.05 else ""))

print("\n=== СКОЛЬКО НУЖНО ПИСЕМ, ЧТОБЫ УВИДЕТЬ РАЗНИЦУ ===")
базовая = 0.0242
for эффект in (0.005, 0.010, 0.015, 0.020):
    p1, p2 = базовая, базовая + эффект
    p_ = (p1 + p2) / 2
    n = ((1.96 * math.sqrt(2 * p_ * (1 - p_))
          + 0.84 * math.sqrt(p1 * (1 - p1) + p2 * (1 - p2))) ** 2
         / (эффект ** 2))
    print("   разница %.1f п.п. (%.1f%% против %.1f%%): нужно по %d писем на заход"
          % (100 * эффект, 100 * p1, 100 * p2, int(math.ceil(n))))

print("\n=== ИТОГ ===")
print("ни одно парное сравнение не проходит порог значимости с запасом;")
print("самое сильное — «наблюдение о них» против «прочего», и оно держится")
print("на волоске, а при поправке на четыре сравнения рассыпается.")
