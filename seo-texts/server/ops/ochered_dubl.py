# -*- coding: utf-8 -*-
"""Очередь «Дубль» по логике «Компания не понравилась».

ЗАЧЕМ. Просьба владельца: чтобы компании, с которыми УЖЕ работают, можно было
отсеять — не как отказ («не понравилась»), а отдельной причиной. Смешивать их
нельзя: «не понравилась» это суждение продавца о компании, «дубль» — факт про
нас самих. Слитые в один статус, они испортят и статистику отказов, и возврат
к компании через полгода.

КАК СДЕЛАНО. Ровно теми же тремя точками, что и «не понравилась»:
  * `CALL_RESULT_*` — набор разрешённых, словарь показа, словарь выбора;
  * ссылка-очередь в `centro.html`.
Ничего нового в схеме базы не нужно: статус лежит в том же поле.

БЭКАП И ПРОВЕРКА: каждый файл сохраняется рядом, после записи текст
перечитывается и печатается число вхождений — если ноль, правка не легла.

Запуск: python ochered_dubl.py [--apply]
"""
import io, os, shutil, sys, time

ПРИМЕНИТЬ = '--apply' in sys.argv
КОД = r'C:\seostat\app\services\centro_sales.py'
ШАБ = r'C:\seostat\app\templates\centro.html'
ЯРЛЫК = 'Дубль — уже работают'

правки = [
    (КОД,
     '    "v_rabote",\n    "ne_ponravilas",\n}',
     '    "v_rabote",\n    "ne_ponravilas",\n    "dubl",\n}'),
    (КОД,
     '    "v_rabote": "Взял в работу",\n    "ne_ponravilas": "Компания не понравилась",\n}\n\n# ЧТО ПРЕДЛАГАЕТСЯ В ФОРМЕ',
     f'    "v_rabote": "Взял в работу",\n    "ne_ponravilas": "Компания не понравилась",\n'
     f'    "dubl": "{ЯРЛЫК}",\n}}\n\n# ЧТО ПРЕДЛАГАЕТСЯ В ФОРМЕ'),
    (КОД,
     'CALL_RESULT_CHOICES = {\n    "v_rabote": "Взял в работу",\n    "ne_ponravilas": "Компания не понравилась",\n}',
     'CALL_RESULT_CHOICES = {\n    "v_rabote": "Взял в работу",\n'
     '    "ne_ponravilas": "Компания не понравилась",\n'
     f'    # Дубль — не суждение о компании, а факт про нас: с ней уже работают.\n'
     f'    # Отдельной причиной, чтобы не портить статистику отказов.\n'
     f'    "dubl": "{ЯРЛЫК}",\n}}'),
    (ШАБ,
     '<a href="{{ base_path }}/centro?call_status=ne_ponravilas">Компания не понравилась</a>',
     '<a href="{{ base_path }}/centro?call_status=ne_ponravilas">Компания не понравилась</a>\n'
     f'<a href="{{{{ base_path }}}}/centro?call_status=dubl">{ЯРЛЫК}</a>'),
]

тексты = {}
for файл, старое, новое in правки:
    if файл not in тексты:
        тексты[файл] = io.open(файл, encoding='utf-8', errors='replace').read()
    # ЗАСЛОН ПРОВЕРЯЕТ СВОЮ ПРАВКУ, А НЕ СЛОВО В ФАЙЛЕ. Первая версия смотрела,
    # есть ли где-нибудь «dubl», и после первой же правки считала выполненными
    # остальные две: в файл попала одна строка из трёх.
    if новое in тексты[файл]:
        print(f'{os.path.basename(файл)}: эта правка уже стоит')
        continue
    if старое not in тексты[файл]:
        print(f'ОСТАНОВ: в {os.path.basename(файл)} не найден образец:')
        print('   ', старое.replace('\n', ' ⏎ ')[:120])
        raise SystemExit
    тексты[файл] = тексты[файл].replace(старое, новое, 1)

for файл, т in тексты.items():
    print(f'{os.path.basename(файл):22} вхождений "dubl" после правки: {т.count("dubl")}')

if not ПРИМЕНИТЬ:
    print('СУХОЙ ПРОГОН — ничего не записано')
    raise SystemExit

метка = time.strftime('%Y%m%d-%H%M%S')
for файл, т in тексты.items():
    shutil.copy2(файл, файл + '.bak-' + метка)
    io.open(файл, 'w', encoding='utf-8').write(т)
    сверка = io.open(файл, encoding='utf-8', errors='replace').read()
    print(f'{os.path.basename(файл):22} записан, "dubl" в файле: {сверка.count("dubl")}, '
          f'бэкап .bak-{метка}')
