# -*- coding: utf-8 -*-
"""Мера ТЗ, разделённая по силе должности. Не складывать разное в одно число.

131 строки «технарь + личный мобильный» состоят из двух разных вещей:

  ДОЛЖНОСТЬ С ПРЕДПРИЯТИЯ   «главный энергетик», «инженер-энергетик»,
                            «ведущий инженер ОМТС» — человек так называется
                            на работе;
  РОЛЬ ИЗ ЗАПРОСА           «контактное лицо по техническим вопросам»,
                            «консультации по техническим вопросам» — так его
                            назвала КАРТОЧКА ЗАКУПКИ на конкретную процедуру.
                            Кем он работает, отсюда неизвестно: это может быть
                            и главный инженер, и специалист отдела закупок.

Я сам писал 3-й сессии, что должность из запроса нельзя считать должностью
человека. Значит и себе нельзя. Считаю раздельно; складывать буду только с
оговоркой.
"""
import re, sys
from collections import Counter
sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB

ТЕХ = ('инженер', 'механик', 'энергетик', 'технич', 'производств', 'кипиа',
       'метролог', 'технолог')
НЕ_ТЕХ = ('по продажам', 'по сбыту', 'менеджер по прод')
ИЗ_ЗАПРОСА = re.compile(
    r'контактн\w* лиц|консультаци|по вопросам|по техническ\w* вопрос|'
    r'ответственн\w* за процедур|контакт по', re.I)

db = EDB.EnrichDB()
c = Counter()
фирмы_долж, фирмы_запрос = set(), set()
живые = []
for инн, чел, пост, роль, тел, не_личный, урл in db.cx.execute(
        "SELECT inn, COALESCE(person,''), COALESCE(post,''), COALESCE(role,''), "
        "COALESCE(phone,''), COALESCE(nomer_ne_lichnyy,''), COALESCE(source_url,'') "
        "FROM people WHERE COALESCE(phone,'')<>''"):
    подпись = f'{пост} {роль}'.casefold()
    if not any(т in подпись for т in ТЕХ) or any(н in подпись for н in НЕ_ТЕХ):
        continue
    ц = ''.join(x for x in str(тел) if x.isdigit())[-10:]
    if not (len(ц) == 10 and ц[0] == '9') or не_личный:
        continue
    из_запроса = bool(ИЗ_ЗАПРОСА.search(str(пост)))
    if из_запроса:
        c['роль из карточки закупки (кем работает — неизвестно)'] += 1
        фирмы_запрос.add(str(инн))
    else:
        c['ДОЛЖНОСТЬ С ПРЕДПРИЯТИЯ'] += 1
        фирмы_долж.add(str(инн))
        живые.append((str(инн), str(чел), str(пост), str(тел), str(урл)))

print('ТЕХНАРЬ + ЛИЧНЫЙ МОБИЛЬНЫЙ, разложено по силе должности')
for к, v in c.items():
    print(f'   {к:52} {v:5}')
print()
print(f'   предприятий с настоящей должностью              {len(фирмы_долж):5}')
print(f'   предприятий только с ролью из запроса           {len(фирмы_запрос - фирмы_долж):5}')
print()
print('ВСЕ СТРОКИ С НАСТОЯЩЕЙ ДОЛЖНОСТЬЮ:')
for инн, чел, пост, тел, урл in живые:
    print(f'   {инн:12} {чел[:26]:26} {пост[:30]:30} {тел[:18]:18} {урл[:38]}')
