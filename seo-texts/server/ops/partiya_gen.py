def _с_ожиданием(зовём):
    """Повторить вызов, пока база занята. Возвращает (значение, сбой).

    25 потоков генерации плюс работник проб пишут в одну sqlite, и
    «database is locked» прилетает регулярно. Письмо уже оплачено, терять
    его из-за занятой базы нельзя. Ошибку не про блокировку пробуем трижды
    и сдаёмся: сама она не рассосётся.
    """
    посл = None
    for поп in range(6):
        try:
            return зовём(), None
        except Exception as ex:                               # noqa: BLE001
            посл = ex
            if "locked" not in str(ex).lower() and поп >= 2:
                break
            time.sleep(2 + поп * 3)
    return None, посл


