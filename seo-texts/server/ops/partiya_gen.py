def _цена(расход, тариф):
    """Вход + кэш по их ставкам. Запись в кэш дороже обычного входа (1.25),
    чтение почти даром (0.1) - и оба не входят в input_tokens, поэтому без
    них журнальная цена показывала копейки там, где счётчик шлюза показывал
    десятки долларов."""
    вход = (расход.get("in", 0)
            + 1.25 * расход.get("cw", 0)
            + 0.10 * расход.get("cr", 0))
    return вход / 1e6 * тариф[0] + расход.get("out", 0) / 1e6 * тариф[1]
