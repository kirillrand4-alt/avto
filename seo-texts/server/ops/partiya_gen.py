def _разобрать_предкласс(текст):
    """{"firmy":[...]} из ответа, ДАЖЕ ЕСЛИ он оборван на полуслове.

    Обрыв - это не пустой ответ: в нём уже есть вердикты по большинству
    фирм пачки, и терять их значит платить за письмо тому, кого модель
    успела отклонить. Сначала пробуем честный json.loads, а если он
    спотыкается - собираем пары «инн + направление» регуляркой.
    """
    if not текст:
        return {}
    мм = re.search(r"\{.*\}", текст, re.S)
    if мм:
        try:
            return json.loads(мм.group(0))
        except Exception:                                     # noqa: BLE001
            pass
    пары = re.findall(
        r'"inn"\s*:\s*"(\d[\d\s]*)"\s*,\s*"napravlenie"\s*:\s*"([^"]+)"',
        текст)
    if not пары:
        return {}
    return {"firmy": [{"inn": и, "napravlenie": н} for и, н in пары]}


