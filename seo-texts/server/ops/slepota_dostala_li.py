"""Дошла ли слепота SQL до продавца: проверка на тех самых невидимых строках.

Замер показал 8 088 строк, которых SQL не видит. Само по себе это НЕ значит,
что продавец что-то потерял: важно, каким кодом принимаются решения. Признак
«технарь» ставит `EnrichDB._canon_role`, а он питоновский (`.lower()` знает
кириллицу), фильтр продавца идёт через `casefold()`. Значит теория такая:
пострадали только ОТЧЁТНЫЕ числа, а данные в карточке целы.

Теорию проверяю не чтением кода, а на самих пострадавших строках: беру людей,
чья должность содержит «главный инженер / энергетик / механик» ТОЛЬКО в
написании, невидимом для SQL, и смотрю, стоит ли у них `is_tech`. Если стоит —
продавец их видит, и цена находки равна ошибке в моих отчётах. Если не стоит —
цена другая, и это дыра в выдаче.

Запуск: python slepota_dostala_li.py
"""
import os
import sqlite3
from collections import Counter

БАЗЫ = [('центробежка', r'C:\seostat\data\centrifugal.db'),
        ('P25', r'C:\seostat\data\p25.db')]
СЛОВА = ('главный инженер', 'главный энергетик', 'главный механик',
         'главный технолог')


def main():
    стат = Counter()
    примеры = []
    for имя, путь in БАЗЫ:
        if not os.path.exists(путь):
            continue
        цб = sqlite3.connect(f'file:{путь}?mode=ro', uri=True)
        колонки = {r[1] for r in цб.execute('PRAGMA table_info(person)')}
        если_тех = 'is_tech' in колонки
        строки = цб.execute(
            "SELECT inn, COALESCE(person,''), COALESCE(position,''), "
            "COALESCE(role,''), " + ('COALESCE(is_tech,0)' if если_тех else '0') +
            " FROM person WHERE COALESCE(position,'')<>''").fetchall()
        цб.close()
        for инн, чел, пост, роль, тех in строки:
            низ = пост.lower()
            попал = next((с for с in СЛОВА if с in низ), '')
            if not попал:
                continue
            невидим = попал not in пост  # SQL LIKE такую строку не найдёт
            ключ = f'{имя}: невидимых для SQL' if невидим else f'{имя}: видимых для SQL'
            стат[ключ] += 1
            стат[f'{ключ} — С признаком технаря'] += 1 if тех else 0
            if невидим and not тех and len(примеры) < 10:
                примеры.append(f'{имя} {инн} {чел[:28]:28} {пост[:34]:34} роль={роль}')

    print('НЕВИДИМЫЕ ДЛЯ SQL И БЕЗ ПРИЗНАКА ТЕХНАРЯ (если пусто — продавец их видит):')
    for п in примеры:
        print('   ', п)
    if not примеры:
        print('    ни одной')

    print()
    for к, v in sorted(стат.items()):
        print(f'{к:58} {v:6}')


if __name__ == '__main__':
    main()
