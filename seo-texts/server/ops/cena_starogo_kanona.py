# -*- coding: utf-8 -*-
"""Цена отставшего канона ролей: сколько людей записаны НЕ ТОЙ ролью.

ЧТО НАШЛОСЬ. На сервере одна копия `enrich_db.py` — 27 385 байт, без
`TECH_ROLES` и без регулярки «начальник ЛЮБОГО цеха». В репозитории лежит
64 110 байт с обеими правками. То есть коммиты «канон инженеров» и «правка
канона ролей» в производство не доехали, и всё это время роли писались старой
логикой. Проверено прямым опросом сервера:

    канон('ГЛАВНЫЙ ЭНЕРГЕТИК')             старый → гл.инженер   новый → гл.энергетик
    канон('начальник компрессорного цеха')  старый → общий        новый → нач.цеха

ВТОРАЯ ОШИБКА ХУЖЕ ПЕРВОЙ. «Гл.инженер вместо гл.энергетика» — путаница внутри
технических, продавец всё равно звонит технарю. А «общий» вместо «нач.цеха»
уводит человека из технических ВООБЩЕ: начальник компрессорного цеха — самый наш
собеседник, и он уезжал вниз выгрузки.

ЧТО СЧИТАЮ. Не «сколько строк не найдёт LIKE», а сколько людей в живых базах
имеют должность одного класса и роль другого. Это и есть цена, и она либо
оправдывает выкладку общего модуля, либо нет.

Запуск: python cena_starogo_kanona.py
"""
import os
import re
import sqlite3
import sys
from collections import Counter

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

БАЗЫ = [('центробежка', r'C:\seostat\data\centrifugal.db', 'person'),
        ('P25', r'C:\seostat\data\p25.db', 'person')]
ЭНЕРГЕТИК = re.compile(r'энергетик', re.I)
МЕХАНИК = re.compile(r'механик', re.I)
НАЧ_ЦЕХА = re.compile(r'начальник\s+[^,;]{0,40}цех|нач\.?\s*цех', re.I)


def main():
    стат = Counter()
    примеры = []

    # 1) как считает СТАРЫЙ канон, стоящий на сервере
    for п in ('Главный энергетик', 'Главный механик', 'начальник компрессорного цеха',
              'Начальник цеха №5', 'Главный инженер'):
        стат[f'старый канон: {п!r} → {EDB.EnrichDB._canon_role(п)!r}'] += 1

    # 2) цена в живых базах
    for имя, путь, табл in БАЗЫ:
        if not os.path.exists(путь):
            continue
        цб = sqlite3.connect(f'file:{путь}?mode=ro', uri=True)
        поля = {r[1] for r in цб.execute(f'PRAGMA table_info({табл})')}
        if not {'position', 'role'} <= поля:
            цб.close()
            continue
        for инн, чел, пост, роль in цб.execute(
                f"SELECT inn, COALESCE(person,''), COALESCE(position,''), "
                f"COALESCE(role,'') FROM {табл} WHERE COALESCE(position,'')<>''"):
            р = роль.lower()
            беда = ''
            if ЭНЕРГЕТИК.search(пост) and 'энергетик' not in р:
                беда = 'энергетик записан как ' + (роль or 'пусто')
            elif МЕХАНИК.search(пост) and 'механик' not in р:
                беда = 'механик записан как ' + (роль or 'пусто')
            elif НАЧ_ЦЕХА.search(пост) and ('общий' in р or not р.strip()):
                беда = 'начальник цеха записан как ' + (роль or 'пусто')
            if беда:
                стат[f'{имя}: {беда.split(" записан")[0]}'] += 1
                if len(примеры) < 12:
                    примеры.append(f'{имя} {инн} {чел[:24]:24} {пост[:34]:34} → {роль}')
        цб.close()

    print('ЛЮДИ, ЗАПИСАННЫЕ НЕ ТОЙ РОЛЬЮ:')
    for п in примеры:
        print('   ', п)
    if not примеры:
        print('    ни одного')

    print()
    for к, v in sorted(стат.items()):
        print(f'{к:72} {v:6}')


if __name__ == '__main__':
    main()
