ПРИМЕНИТЬ = '--apply' in sys.argv

НЕ_ФАМИЛИЯ = {'уважаемый', 'уважаемая', 'контактное', 'лицо', 'отдел', 'служба',
              'приёмная', 'приемная', 'фио', 'тел', 'телефон', 'директор',
              'менеджер', 'специалист', 'секретарь'}
# «по вопросам» дословно НЕ ловится в «по техническим вопросам» — между
# предлогом и существительным стоит слово. Первый шаблон это пропускал, и роль
# из карточки закупки уезжала в поле должности предприятия: «Пантелеймонов
# Дмитрий, по техническим вопросам» встал как должность и закрыл предприятие
# по мере ТЗ, чего быть не должно.
ИЗ_ЗАПРОСА = re.compile(r'контактн\w* лиц|консультаци|по\s+(?:\w+\s+){0,2}вопрос|'
                        r'для уточнени|ответственн\w* за процедур|контакт по|'
                        r'^по\s|обращат|уточнени', re.I)
ТЕХ = ('инженер', 'механик', 'энергетик', 'технич', 'производств', 'кипиа',
       'метролог', 'технолог')
СНАБЖ = ('материально-техническ', 'снабжени', 'закупк', 'омтс', 'логистик',
         'бухгалтер', 'склад')


def чисто(з):
    return ' '.join(str(з or '').split())


def фамилия_годна(имя):
    с = чисто(имя).split()
    if len(с) < 2:
        return 'в имени одно слово'
    if с[0].casefold().strip('.,') in НЕ_ФАМИЛИЯ:
        return 'обращение или должность вместо фамилии'
    if not re.match(r'^[А-ЯЁ][а-яё\-]+$', с[0]):
        return 'первое слово не похоже на фамилию'
    return ''


_ОТЧЕСТВО = re.compile(r'(?:ович|евич|овна|евна|ична|инична|ьич)$', re.I)


def фамилию_вперёд(имя):
    """«Алексей Бурдо» → «Бурдо Алексей». Порядок слов в карточках закупки гуляет."""
    с = чисто(имя).split()
    if len(с) == 3 and _ОТЧЕСТВО.search(с[1]) and not _ОТЧЕСТВО.search(с[2]):
        return f'{с[2]} {с[0]} {с[1]}'
    if len(с) == 2 and not _ОТЧЕСТВО.search(с[1]):
        # «Алексей Бурдо»: если второе слово длиннее и не отчество, оно фамилия.
        # Признак слабый, поэтому решает только вместе с ключом ниже.
        return имя
    return имя


def _слова_имени(имя):
    return [x.strip('.,') for x in чисто(имя).split() if x.strip('.,')]


def склеить_написания(записи):
    """Свести написания одного человека в пределах предприятия.

    ДЛИНА СЛОВА ФАМИЛИЮ НЕ ОПРЕДЕЛЯЕТ — на этом сломался первый ключ: в «Бурдо
    Алексей» он счёл фамилией «Алексей», и строка не склеилась с «Бурдо А.М.».
    Поэтому два правила, оба точные, без догадок о порядке слов:

      1. одинаковый НАБОР слов — «Бурдо Алексей» и «Алексей Бурдо»;
      2. общая фамилия и совпавшая первая буква имени — «Бурдо Алексей» и
         «Бурдо А.М.», где фамилией считается первое слово самого длинного
         написания в уже собранной группе.

    Три строки на одного человека для продавца — это три звонка одному и тому
    же лицу, поэтому склейка важнее осторожности здесь.
    """
    группы = {}
    for з in записи:
        к = (з['inn'], frozenset(x.casefold() for x in _слова_имени(з['person'])))
        группы.setdefault(к, []).append(з)

    по_фамилии = {}
    for (инн, _), сп in группы.items():
        полное = max((з['person'] for з in сп), key=len)
        слова = _слова_имени(полное)
        фам = слова[0].casefold() if слова else ''
        буква = слова[1][:1].casefold() if len(слова) > 1 else ''
        по_фамилии.setdefault((инн, фам, буква), []).extend(сп)

    склеено = 0
    for сп in по_фамилии.values():
        полное = max((з['person'] for з in сп), key=len)
        for з in сп:
            if з['person'] != полное:
                склеено += 1
                з['person'] = полное
    return склеено, len(по_фамилии)


def норм_тел(т):
    ц = re.sub(r'\D', '', str(т or ''))
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    elif len(ц) == 10:
        ц = '7' + ц
    else:
        return ''
    return '+' + ц


def main():
    if not os.path.exists(ПОТОК_ВХ):
        print('нет потока разбора:', ПОТОК_ВХ)
        return
    строки = []
    for s in io.open(ПОТОК_ВХ, encoding='utf-8', errors='replace'):
        s = s.strip()
        if not s:
            continue
        try:
            строки.append(json.loads(s))
        except Exception:
            continue

    цб = sqlite3.connect(P25, timeout=30)
    поля_p = {r[1] for r in цб.execute('PRAGMA table_info(person)')}
    поля_c = {r[1] for r in цб.execute('PRAGMA table_info(contact)')}
    наши = {str(и) for и, in цб.execute('SELECT inn FROM company')}

    стат = Counter()
    к_записи = []
    чужие = []
    for з in строки:
        инн = re.sub(r'\D', '', str(з.get('inn') or ''))
        if инн not in наши:
            # НЕ выбрасываю: предприятие может быть в центробежке или в
            # enrich.companies. Складываю отдельным файлом, чтобы отдать туда,
            # где оно есть, а не терять разбор, за который заплачено.
            стат['ИНН вне P25 — уйдёт отдельным файлом'] += 1
            чужие.append(з)
            continue
        свежесть = str(з.get('свежесть') or '')
        for л in (з.get('lyudi') or []):
            фио = чисто(л.get('fio'))
            цитата = чисто(л.get('citata'))
            if not цитата:
                стат['ОТКЛОНЕНО: нет цитаты'] += 1
                continue
            беда = фамилия_годна(фио)
            if беда:
                стат[f'ОТКЛОНЕНО: {беда}'] += 1
                continue
            должность = чисто(л.get('dolzhnost'))
            роль_зак = чисто(л.get('rol_v_zakupke'))
            if должность and ИЗ_ЗАПРОСА.search(должность):
                роль_зак = роль_зак or должность
                должность = ''
                стат['должность оказалась ролью из запроса — перенесена'] += 1
            тел = норм_тел(л.get('telefon'))
            почта = чисто(л.get('pochta')).lower()
            if not тел and not почта:
                стат['ОТКЛОНЕНО: ни телефона, ни почты'] += 1
                continue
            подпись = f'{должность}'.casefold()
            тех = (1 if any(x in подпись for x in ТЕХ)
                   and not any(x in подпись for x in СНАБЖ) else 0)
            фио = фамилию_вперёд(фио)
            стат['ПРИНЯТО'] += 1
            стат['   с должностью предприятия' if должность
                 else '   только роль в закупке'] += 1
            if тех:
                стат['   технических по должности'] += 1
            if свежесть == 'устаревший':
                стат['   карточка 2–3 лет: помечено возрастом'] += 1
            к_записи.append({
                'inn': инн, 'person': фио, 'position': должность,
                'role': роль_зак or ('технический круг' if тех else ''),
                'phone': тел, 'email': почта,
                'dob': re.sub(r'\D', '', чисто(л.get('dobavochnyy'))),
                'is_tech': тех, 'url': str(з.get('url') or ''),
                'date': str(з.get('дата') or ''), 'quote': цитата[:400],
                'source': f'tender.pro, карточка закупки'
                          + (' (2–3 года назад)' if свежесть == 'устаревший' else ''),
            })

    склеено, разных = склеить_написания(к_записи)
    стат['написаний склеено к самому полному'] = склеено
    стат['различных людей после склейки'] = разных

    print('ПРИМЕРЫ ПРИНЯТЫХ С ДОЛЖНОСТЬЮ:')
    н = 0
    for з in к_записи:
        if з['position'] and н < 10:
            print(f"   {з['inn']:12} {з['person'][:26]:26} {з['position'][:30]:30} "
                  f"{з['phone'][:14]}")
            н += 1

    if not ПРИМЕНИТЬ:
        print()
        print('=== ЧИСЛА ===')
        for к, v in sorted(стат.items()):
            print(f'   {к:48} {v:5}')
        print(f'   {"к записи":48} {len(к_записи):5}')
        print('СУХОЙ ПРОГОН')
        цб.close()
        return

    ts = time.strftime('%Y-%m-%dT%H:%M:%S')
    до_p = цб.execute('SELECT COUNT(*) FROM person').fetchone()[0]
    до_c = цб.execute('SELECT COUNT(*) FROM contact').fetchone()[0]
    до_s = цб.execute('SELECT COUNT(*) FROM contact_source').fetchone()[0]
    for з in к_записи:
        поля = {'inn': з['inn'], 'person': з['person'], 'position': з['position'],
                'role': з['role'], 'phone': з['phone'], 'email': з['email'],
                'is_tech': з['is_tech'], 'source': з['source'],
                'source_url': з['url']}
        имена = [к for к in поля if к in поля_p]
        цб.execute(f"INSERT OR IGNORE INTO person ({','.join(имена)}) "
                   f"VALUES ({','.join('?' * len(имена))})", [поля[к] for к in имена])
        for вид, значение in (('phone', з['phone']), ('email', з['email'])):
            if not значение:
                continue
            стб = {'inn': з['inn'], 'person': з['person'], 'kind': вид,
                   'value': значение, 'source': з['source'],
                   'source_url': з['url']}
            if вид == 'phone' and з['dob'] and 'dobavochnyy' in поля_c:
                стб['dobavochnyy'] = з['dob']
            имена_c = [к for к in стб if к in поля_c]
            цб.execute(f"INSERT OR IGNORE INTO contact ({','.join(имена_c)}) "
                       f"VALUES ({','.join('?' * len(имена_c))})",
                       [стб[к] for к in имена_c])
            цб.execute(
                "INSERT OR IGNORE INTO contact_source(inn, contact_value, person, "
                "source, source_url, date_observed, quote, added_at) "
                "VALUES(?,?,?,?,?,?,?,?)",
                (з['inn'], значение, з['person'], з['source'], з['url'],
                 з['date'], з['quote'], ts))
    цб.commit()
    после = [цб.execute(f'SELECT COUNT(*) FROM {т}').fetchone()[0]
             for т in ('person', 'contact', 'contact_source')]
    цб.close()

    with io.open(ПОТОК, 'a', encoding='utf-8') as ф:
        for з in к_записи:
            ф.write(json.dumps({**з, 'ts': ts}, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())

    print()
    print('=== ЧИСЛА ===')
    for к, v in sorted(стат.items()):
        print(f'   {к:48} {v:5}')
    print(f'   person:     {до_p} → {после[0]}')
    print(f'   contact:    {до_c} → {после[1]}')
    print(f'   наблюдений: {до_s} → {после[2]}')


if __name__ == '__main__':
    main()
