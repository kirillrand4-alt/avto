# -*- coding: utf-8 -*-
"""Очередь генерации в порядке, заданном владельцем 24.08.

  250 Meyer -> 600 КЦ -> 300 Meyer -> 700 КЦ

Внутри каждого блока partiya_gen сам ставит вперёд компании с самым полным
паспортом сайта, а среди равных — именные адреса выше ролевых (правка того
же дня). Блоки идут ПОДРЯД одним процессом: между ними резюм по журналу
сам исключает уже написанное, поэтому второй блок Meyer продолжает с того
места, где кончился первый, а не повторяет его.

Остаток пула (~6700 компаний) этот драйвер НЕ трогает: он стоит около
$4600, и запускать его надо отдельной командой владельца.

Запускать отцеплённо: pustit_otceplenno.py ochered_vladeltsa.py
"""
import io
import json
import os
import subprocess
import sys
import time

ПИТОН = r"C:\Program Files\Python311\python.exe"
КАТАЛОГ = r"C:\sender\_ops"
ОТЧЁТ = os.path.join(КАТАЛОГ, "ochered-vladeltsa.jsonl")

# (потолок писем, направление, лимит секунд на блок)
БЛОКИ = [(250, "meyer", 5400),
         (600, "kc", 10800),
         (300, "meyer", 6300),
         (700, "kc", 12600)]
ПОРОГ = "porog=2.50"   # ЛАТИНИЦЕЙ И БЕЗ ДЕФИСОВ: разбор берёт только
                      # «имя=значение» без ведущего «-», а кириллические ключи
                      # не переживают дорогу через PowerShell Start-Process.


def записать(строка):
    """Durable: результат блока ложится на сервер сразу, с fsync."""
    with io.open(ОТЧЁТ, "a", encoding="utf-8") as ф:
        ф.write(json.dumps(строка, ensure_ascii=False) + "\n")
        ф.flush()
        os.fsync(ф.fileno())


записать({"этап": "старт", "блоков": len(БЛОКИ),
          "писем_всего": sum(б[0] for б in БЛОКИ), "ts": time.time()})

for н, (потолок, направление, лимит) in enumerate(БЛОКИ, 1):
    начало = time.time()
    лог = os.path.join(КАТАЛОГ, "ochered-blok%d-%s.log" % (н, направление))
    print("\n=== БЛОК %d/%d: %d писем %s (лимит %d с) ==="
          % (н, len(БЛОКИ), потолок, направление.upper(), лимит), flush=True)
    аргументы = [ПИТОН, os.path.join(КАТАЛОГ, "partiya_gen.py"),
                 str(потолок), str(лимит), направление, "0", ПОРОГ]
    записать({"этап": "блок_старт", "блок": н, "потолок": потолок,
              "направление": направление, "ts": time.time()})
    with io.open(лог, "w", encoding="utf-8") as ф:
        код = subprocess.call(аргументы, stdout=ф, stderr=subprocess.STDOUT,
                              cwd=КАТАЛОГ)
    # Итоговую строку прогона вытаскиваем из его же лога — она durable.
    итог = ""
    try:
        строки = io.open(лог, encoding="utf-8", errors="replace").readlines()
        итог = next((с.strip() for с in reversed(строки)
                     if с.startswith("итог:")), строки[-1].strip() if строки else "")
    except Exception as e:  # noqa: BLE001
        итог = "лог не прочитан: %s" % e
    прошло = time.time() - начало
    print("  блок %d кончился за %.0f мин, код %d | %s"
          % (н, прошло / 60.0, код, итог), flush=True)
    записать({"этап": "блок_конец", "блок": н, "код": код,
              "минут": round(прошло / 60.0, 1), "итог": итог,
              "ts": time.time()})

записать({"этап": "конец", "ts": time.time()})
print("\nвсе блоки отработаны", flush=True)
