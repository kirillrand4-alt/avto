# -*- coding: utf-8 -*-
"""ЕРКНМ, срез по Ростехнадзору: даёт ли он имя технического ЛПР.

ЧТО УЖЕ ИЗВЕСТНО ТОЧНО. Разбор исправен, пусто в источнике: на 4,5 млн знаков
предостережений июня 2026 мягкое выражение нашло 16 имён, и все — ИП и торговля
(молочная маркировка, лесозаготовки, аптеки). А «главные инженеры», что там
попадаются, — это `главный государственный инженер-инспектор`, то есть
проверяющий ОТ НАДЗОРА, не сотрудник завода.

ГИПОТЕЗА, КОТОРУЮ ПРОВЕРЯЕМ. Технических работников поимённо называет не всякий
надзор, а Ростехнадзор — у него предмет проверки промышленная безопасность, и в
предостережении пишут, кто отвечает за опасный объект. В июньском срезе таких
записей мало, потому что месяц целиком — санэпиднадзор и маркировка.

СТОИТ ЭТО НОЛЬ ЗАПРОСОВ: архив уже лежит на диске (338 МБ, кэш от разбора нуля),
качать нечего. Поэтому проверка честная и дешёвая: если Ростехнадзор даст имена
— канал живой, и тогда есть смысл тянуть остальные месяцы. Если не даст и здесь
— канал закрываем и говорим это прямо, не потратив ни минуты сверх.

Печатает: сколько записей у каждого органа надзора, сколько ростехнадзорских по
нашим целям, и ВСЕ имена, найденные в их предостережениях, с должностью и ИНН.

Запуск: python _probe_erknm_rtn.py [ГОД МЕСЯЦ]
"""
import io
import os
import re
import sys
import zipfile
from collections import Counter
from xml.etree import ElementTree as ET

ГОД = sys.argv[1] if len(sys.argv) > 1 else '2026'
МЕС = sys.argv[2] if len(sys.argv) > 2 else '6'
КЭШ = fr'C:\seostat\drop\_erknm_{ГОД}_{МЕС}.zip'
ЦЕЛИ_Ф = os.path.join(r'C:\seostat\drop\drop-storage', 'erknm-celi.csv')

# «Ростехнадзор» в выгрузке пишется по-разному: и коротким именем органа, и
# полным «Федеральная служба по экологическому, технологическому и атомному
# надзору», и через предмет «федеральный государственный надзор в области
# промышленной безопасности». Ловим по любому из признаков.
РТН = re.compile(r'ростехнадзор|технологическому и атомному надзору|'
                 r'промышленной безопасност|энергетическ(ий|ого) надзор', re.I)

ТЕХ = ('энергетик', 'механик', 'главный инженер', 'технический директор',
       'начальник цеха', 'начальник участка', 'начальник службы',
       'начальник отдела', 'ответственн', 'мастер', 'инженер')
# мягкое: должность и ФИО в любом порядке, до 60 знаков между ними
МЯГКО = re.compile(
    r'(?:(?P<d1>' + '|'.join(ТЕХ) + r')[^.;]{0,60}?'
    r'(?P<f1>[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}))'
    r'|(?:(?P<f2>[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ][а-яё]{2,})'
    r'[^.;]{0,60}?(?P<d2>' + '|'.join(ТЕХ) + r'))')
# слова, за которыми прячется НЕ человек предприятия, а инспектор или орган
ЧУЖОЙ = re.compile(r'государственн\w+\s+инспектор|инспектор по городу|'
                   r'специалист-эксперт|прокурат|руководител\w+ управлени', re.I)


def цели():
    import csv
    csv.field_size_limit(10 ** 7)
    из = {}
    if os.path.exists(ЦЕЛИ_Ф):
        with open(ЦЕЛИ_Ф, encoding='utf-8-sig', errors='replace', newline='') as ф:
            for r in csv.DictReader(ф, delimiter=';'):
                и = re.sub(r'\D', '', str(r.get('inn') or ''))
                if len(и) in (10, 12):
                    из[и] = str(r.get('name') or '')
    return из


def тексты(эл):
    """Только тексты документов: CAPTION и длинные текстовые узлы.

    INSPECTOR пропускаем целиком — там сотрудники надзора.
    """
    куски = []
    for под in эл.iter():
        имя = под.tag.rsplit('}', 1)[-1]
        if имя.startswith('INSPECTOR'):
            continue
        if под.text and len(под.text.strip()) > 40:
            куски.append(под.text.strip())
        for к, v in под.attrib.items():
            if k_дл(к) and len(str(v)) > 40:
                куски.append(str(v))
    return ' '.join(куски)


def k_дл(к):
    return к in ('CAPTION', 'CONTENT', 'VALUE', 'TEXT', 'DESCRIPTION')


def main():
    if not os.path.exists(КЭШ):
        raise SystemExit(f'нет кэша {КЭШ} — сначала прогнать _probe_erknm_lica.py')
    цел = цели()
    z = zipfile.ZipFile(КЭШ)
    имя_вн = z.namelist()[0]
    органы = Counter()
    стат = Counter()
    находки = []
    with z.open(имя_вн) as поток:
        for _соб, эл in ET.iterparse(io.BufferedReader(поток, 1 << 20),
                                     events=('end',)):
            if not эл.tag.endswith('INSPECTION'):
                continue
            стат['всего записей'] += 1
            орган = ''
            инн = ''
            for под in эл.iter():
                т = под.tag.rsplit('}', 1)[-1]
                if т == 'KNO_ORGANIZATION' and not орган:
                    орган = под.get('VALUE') or под.get('NAME') or ''
                elif т == 'KIND_CONTROL' and not орган:
                    орган = под.get('VALUE') or ''
                elif т == 'SUBJECT' and not инн:
                    инн = re.sub(r'\D', '', под.get('INN') or '')
            органы[орган[:60]] += 1
            ртн = bool(РТН.search(орган))
            if ртн:
                стат['ростехнадзорских'] += 1
                if инн in цел:
                    стат['  из них по НАШИМ целям'] += 1
            if not ртн:
                эл.clear()
                continue
            т = тексты(эл)
            if not т:
                эл.clear()
                continue
            стат['ростехнадзорских с текстом'] += 1
            for м in МЯГКО.finditer(т):
                фио = м.group('f1') or м.group('f2')
                долж = м.group('d1') or м.group('d2')
                окно = т[max(0, м.start() - 90):м.end() + 90]
                if ЧУЖОЙ.search(окно):
                    стат['отброшено: это инспектор/орган'] += 1
                    continue
                находки.append((инн, цел.get(инн, ''), долж, фио,
                                re.sub(r'\s+', ' ', окно)[:200],
                                'НАША ЦЕЛЬ' if инн in цел else 'вне целей'))
            эл.clear()

    print('органы надзора (верх):')
    for о, н in органы.most_common(12):
        print(f'  {н:6}  {о}')
    print('\n', dict(стат))
    print(f'\nНАЙДЕНО ИМЁН в ростехнадзорских предостережениях: {len(находки)}')
    наши = [н for н in находки if н[5] == 'НАША ЦЕЛЬ']
    print(f'из них по НАШИМ предприятиям: {len(наши)}')
    for н in (наши or находки)[:20]:
        print(f'  {н[0]} {н[1][:26]:26} [{н[2]}] {н[3]}')
        print(f'      … {н[4]}')


if __name__ == '__main__':
    main()
