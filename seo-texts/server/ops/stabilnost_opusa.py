"""Стал ли опус нестабильнее — по журналу, окнами, а не по ощущению.

Владелец: «почему у нас такой не стабильный опус стал?». Журнал хранит на
каждое письмо число вызовов и число СРЫВОВ (когда модель отдала гору
токенов выхода и почти ничего видимого). Идём окнами по порядку прогонов.
"""
import io
import json
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ОКНО = 300

строки = []
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    if z.get("этап") != "итог":
        continue
    if z.get("вызовов") is None:
        continue
    строки.append(z)

print(f"писем с учётом вызовов: {len(строки)}, окно {ОКНО}\n")
print(f"{'окно':>12} {'модель':>18} {'вызовов/письмо':>15} "
      f"{'срывов/письмо':>14} {'доля срывов':>12} {'годных':>8}")
for i in range(0, len(строки), ОКНО):
    к = строки[i:i + ОКНО]
    c = Counter()
    м = Counter()
    for z in к:
        c["выз"] += int(z.get("вызовов") or 0)
        c["срыв"] += int(z.get("срывов") or 0)
        c["ок"] += 1 if z.get("тело") else 0
        м[str(z.get("модель") or "?")] += 1
    n = len(к)
    имя = м.most_common(1)[0][0].replace("claude-", "")
    доля = c["срыв"] / max(1, c["выз"]) * 100
    print(f"{i:>6}-{i+n:<5} {имя:>18} {c['выз']/n:>15.1f} "
          f"{c['срыв']/n:>14.2f} {доля:>11.1f}% {c['ок']/n*100:>7.0f}%")
