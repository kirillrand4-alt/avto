# -*- coding: utf-8 -*-
"""Читает ли шлюз кэш вообще: два вызова с байт-в-байт одинаковым system.

Журнал партии 24.08 на каждом письме показывает вход_кэш_запись ~11 тысяч
токенов на вызов и вход_кэш_чтение РОВНО НОЛЬ при пяти вызовах подряд с
одинаковым префиксом. Запись тарифицируется по 1.25 ставки, чтение по 0.1
— то есть письмо платит за один и тот же префикс пять раз по повышенной
ставке. Цена письма из-за этого $0.62-1.15 вместо ожидавшихся центов.

По коду префикс не может отличаться: gen_prompt кладёт в статику шапку
направления, правила и блок фактов, а всё про компанию — после маркера
«ПОЛУЧАТЕЛИ:». Значит вопрос не к нам, а к шлюзу, и его надо задать
прямо: два одинаковых вызова подряд, смотрим usage второго.
"""
import sys
import time

sys.path.insert(0, r"C:\sender\sender")
sys.path.insert(0, r"C:\sender")
import gen_provider                                            # noqa: E402

# Префикс должен быть заведомо длиннее нижнего порога кэша у шлюза.
СИСТЕМА = ("Ты помощник, который отвечает одним словом.\n"
           + ("Это неизменяемая часть промпта, нужная только для того, "
              "чтобы проверить работу кэша шлюза. Она одинакова в обоих "
              "вызовах байт в байт.\n") * 400)
ЗАПРОС = [{"role": "user", "content": "Ответь одним словом: готов"}]

print("длина системного блока: %d знаков" % len(СИСТЕМА))
for н in (1, 2, 3):
    т0 = time.time()
    try:
        m = gen_provider._raw_stream(ЗАПРОС, "claude-sonnet-4-6", 32,
                                     thinking=False, system=СИСТЕМА)
        u = getattr(m, "usage", None)
        print("вызов %d: %5.1f c | вход=%s запись_кэша=%s чтение_кэша=%s выход=%s"
              % (н, time.time() - т0,
                 getattr(u, "input_tokens", "?"),
                 getattr(u, "cache_creation_input_tokens", "?"),
                 getattr(u, "cache_read_input_tokens", "?"),
                 getattr(u, "output_tokens", "?")))
    except Exception as e:                                     # noqa: BLE001
        print("вызов %d: СБОЙ %5.1f c %s: %s"
              % (н, time.time() - т0, type(e).__name__, str(e)[:150]))
    time.sleep(2)
