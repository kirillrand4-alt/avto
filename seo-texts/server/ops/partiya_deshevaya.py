def _чисто(т):
    """Убрать цифры и то, что после них осталось мусором.

    Гейт разрешает числа только из блока ФАКТЫ, поэтому паспортные («DCS-60»,
    «14 700 м²») вычищаем. Но огрызок «dcs» модель честно вставит в письмо -
    замер 24.08 дал «с фасовочно-упаковочной линией dcs». Поэтому кусок, от
    которого после чистки осталось меньше четырёх букв или одни согласные,
    выбрасываем целиком.
    """
    т = re.sub(r"\d[\d\s.,%-]*", " ", str(т))
    т = re.sub(r"[«»\"]+", "", т)
    т = re.sub(r"\s{2,}", " ", т).strip(" ,;-–—")
    буквы = re.sub(r"[^а-яёa-z]", "", т.lower())
    if len(буквы) < 4 or not re.search(r"[аеёиоуыэюя]", буквы):
        return ""
    return т


def _поле(v, n=2):
    if not v:
        return ""
    сп = v if isinstance(v, list) else [x.strip() for x in str(v).split(";")]
    к = [_чисто(x) for x in сп if str(x).strip()]
    return ", ".join([x for x in к if x][:n]).lower()


