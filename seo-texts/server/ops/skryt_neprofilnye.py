"""Убрать из панели школы, детсады, ДК, МФЦ и прочее непроизводственное.

Владелец прислал снимок списка: подряд идут «средняя общеобразовательная
школа», «физкультурно-оздоровительный комплекс», «МФЦ Домодедово», «ДК имени
Леонова», «управление делами», «центр содействия семейному воспитанию».
Воздушного центробежного компрессора там нет и быть не может — это чистый
мусор в списке обзвона, и он дороже, чем кажется: продавец теряет доверие к
панели целиком, если через одну строку видит школу.

ТРИ ЗАЩИТЫ, чтобы вместе с мусором не убить живые цели.

1. НИКОГДА не скрываем предприятие, у которого есть факт с ОПОЗНАННОЙ
   центробежной маркой. Арбитр — `centro_marki.razobrat`, тот же справочник
   обозначений, что рисует карточку характеристик: он отвечает «центробежная»
   по семейству (К-250, ЦК, 43ВЦ, ТВ), а не по слову в тексте. Доказательство
   маркой перевешивает любое подозрение по названию.

2. Водоканалы, тепловые сети, ЖКХ, очистные — НЕ трогаем даже при
   «муниципальном» названии. На очистных стоят воздуходувки, и это наш прямой
   клиент; именно там центробежные машины и работают.

3. Больницы и вузы — тоже не трогаем. У них бывают компрессорные станции
   (медгазы, лаборатории, опытные производства). Их непрофильность спорна, а
   правило про несимметричную цену ошибки здесь работает так же: скрытая
   живая цель дороже показанной сомнительной.

Скрываем, а не удаляем: причина и автор пишутся, возврат одним нажатием.

По умолчанию СУХОЙ ПРОГОН. Запуск: python skryt_neprofilnye.py [--apply]
"""
