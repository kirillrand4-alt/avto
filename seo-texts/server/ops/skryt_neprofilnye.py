sys.path.insert(0, r'C:\seostat')
from app.services import centro_marki as CMK  # noqa: E402

ЦБ = os.getenv('CENTRIFUGAL_DB') or r'C:\seostat\data\centrifugal.db'
ПР = os.getenv('CENTRO_SALES_DB') or r'C:\seostat\data\centro_sales.db'
ПРИМЕНИТЬ = '--apply' in sys.argv
КТО = 'admin'

# Непроизводственное по названию. Каждый шаблон — из снимка владельца или из
# того же ряда: образование, культура, спорт, госуправление, соцсфера.
НЕПРОФИЛЬ = (
    ('образование', re.compile(
        r'общеобразовательн|средн\w*\s+школ|\bшкол\w*\b|гимнази|лице[йя]|'
        r'детск\w*\s+сад|дошкольн|дополнительн\w*\s+образован|'
        r'образовательн\w*\s+учрежден|детск\w*\s+музыкальн|'
        r'детск\w*\s+юношеск|интернат', re.I)),
    ('культура и спорт', re.compile(
        r'\bдом\w*\s+культур|дворец\s+культур|\bдк\b|культурно[-\s]досуг|'
        r'библиотек|музе[йя]|театр|филармони|концертн|'
        r'физкультурно|спортивн\w*\s+школ|спорткомплекс|стадион|'
        r'оздоровительн\w*\s+комплекс|парк\w*\s+культур', re.I)),
    ('госуправление', re.compile(
        r'\bмфц\b|многофункциональн\w*\s+центр|управлени\w*\s+делами|'
        r'администраци\w*\s+(?:город|район|сельск|муниципальн)|'
        r'\bкомитет\b|департамент|служб\w*\s+сопровожден|'
        r'управлени\w*\s+капитальн\w*\s+строительств|'
        r'казначейств|избирательн', re.I)),
    ('соцсфера', re.compile(
        r'содействи\w*\s+семейн|социальн\w*\s+обслуживан|соцзащит|'
        r'реабилитационн|дом\w*\s+престарел|пансионат\w*\s+для|'
        r'центр\w*\s+помощи\s+детям|опек', re.I)),
)

# Ни при каких названиях НЕ трогаем: там воздуходувки и есть.
ЗАЩИЩЕНО = re.compile(
    r'водоканал|водоснабжен|водоотведен|очистн|канализац|'
    r'теплосет|теплоснабжен|тепловы\w*\s+сет|котельн|энергосбыт|'
    r'\bжкх\b|жилищно[-\s]коммунальн|водопроводно|'
    r'больниц|госпитал|клиник|медицинск|здравоохранен|'
    r'университет|институт|академи|научно[-\s]исследовательск', re.I)


def инн_кл(т):
    return re.sub(r'\D', '', str(т or ''))[:12]


def центробежная_марка(марка):
    """Опознана ли марка как центробежная СЕМЕЙСТВОМ, а не словом в тексте."""
    for кусок in re.split(r'[|;]|,(?!\d)', str(марка or '')):
        к = кусок.strip()
        if not к:
            continue
        try:
            р = CMK.razobrat(к)
        except Exception:  # noqa: BLE001
            р = None
        # `nash_profil`, а не слово в типе: с 03.08 справочник знает
        # газовые центробежные семейства (Н-370, НЦ-16, ТГ) — по слову
        # они прошли бы как наши машины. Признак учитывает среду.
        if р and р.get('nash_profil'):
            return к
    return ''


def main():
    цб = sqlite3.connect(f'file:{ЦБ}?mode=ro', uri=True, timeout=20)
    кол = [c[1] for c in цб.execute('PRAGMA table_info("company")')]
    имя_к = next((k for k in ('predpriyatie', 'name', 'name_full', 'name_short')
                  if k in кол), None)
    if not имя_к:
        raise SystemExit(f'в company нет колонки имени, есть: {кол}')
    компании = {инн_кл(и): (н or '') for и, н in
                цб.execute(f'SELECT inn, "{имя_к}" FROM company')}
    # доказательства маркой — по всем фактам разом, чтобы не ходить в базу
    # по одному предприятию
    доказано = {}
    for и, м in цб.execute("SELECT inn, COALESCE(model,'') FROM fact"):
        и = инн_кл(и)
        if и in доказано or not м.strip():
            continue
        нашлось = центробежная_марка(м)
        if нашлось:
            доказано[и] = нашлось
    цб.close()

    пр = sqlite3.connect(ПР, timeout=20)
    пр.execute('PRAGMA busy_timeout=20000')
    уже = {str(r[0]) for r in
           пр.execute("SELECT inn FROM hidden_item WHERE kind='company'")}

    к_скрытию, классы, спасено = {}, Counter(), Counter()
    примеры = []
    for инн, имя in компании.items():
        if инн in уже:
            continue
        класс = next((к for к, рег in НЕПРОФИЛЬ if рег.search(имя)), '')
        if not класс:
            continue
        if ЗАЩИЩЕНО.search(имя):
            спасено['защищённое название (водоканал, больница, вуз)'] += 1
            continue
        if инн in доказано:
            спасено[f'есть опознанная марка: {доказано[инн][:20]}'] += 1
            continue
        к_скрытию[инн] = класс
        классы[класс] += 1
        if len(примеры) < 12:
            примеры.append({'inn': инн, 'имя': имя[:64], 'класс': класс})

    print(json.dumps({
        'предприятий_на_панели': len(компании),
        'уже_скрыто': len(уже),
        'НАЙДЕНО_непрофильных': len(к_скрытию),
        'по_классам': классы.most_common(),
        'НЕ_тронуто_защитой': спасено.most_common(6),
        'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
    }, ensure_ascii=False, indent=1))
    for э in примеры:
        print(f'  {э["inn"]} [{э["класс"]:<16}] {э["имя"]}')

    if not ПРИМЕНИТЬ or not к_скрытию:
        if not ПРИМЕНИТЬ:
            print('\nсухой прогон. Повторить с --apply')
        return
    сейчас = time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime())
    пр.executemany(
        'INSERT OR REPLACE INTO hidden_item'
        '(inn, kind, value, reason, username, created_at) VALUES(?,?,?,?,?,?)',
        [(и, 'company', и,
          f'непроизводственная организация: {к} — воздушного центробежного '
          f'компрессора там нет'[:200], КТО, сейчас)
         for и, к in к_скрытию.items()])
    пр.commit()
    стало = {str(r[0]) for r in
             пр.execute("SELECT inn FROM hidden_item WHERE kind='company'")}
    пр.close()
    print(json.dumps({
        'скрыто_всего': len(стало),
        'видимых_осталось': len(компании) - len(стало & set(компании)),
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
