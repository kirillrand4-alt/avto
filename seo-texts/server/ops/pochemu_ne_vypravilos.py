# -*- coding: utf-8 -*-
"""Почему письмо не выправилось: пустой сайт или расхождение по существу.

Владелец спросил прямо: «сайт пустой?». Отвечаем замером, а не догадкой:
сколько знаков сняли с сайта у неисправимых, и что именно осталось не так.
"""
import io
import json
import re
import sys
from collections import Counter

Ж = r"C:\sender\_ops\perepisano-po-recenzii.jsonl"
N = int(next((a for a in sys.argv[1:] if a.isdigit()), "3"))

записи = {}
for s in io.open(Ж, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                             # noqa: BLE001
        continue
    записи[int(z["id"])] = z          # последняя запись по письму — итоговая
плохие = [z for z in записи.values() if "не годно" in str(z.get("итог") or "")]
print(f"неисправимых: {len(плохие)}\n")

# длину сайта журнал не хранит — но хранит претензии; разберём их по типу
ТИПЫ = (
    ("другой род занятий", r"(?i)(другой род|компания (является|это) |"
                           r"сайт (показывает|говорит|принадлежит)|"
                           r"разные организац|не производ|дистрибь|поставщик)"),
    ("конкретика, которой нет", r"(?i)(числ|модел|размер|тонн|штук|парк|"
                                r"мощност|объ[её]м|состав)"),
    ("процесс не подтверждён", r"(?i)(пневмоинструмент|продувк|сварк|покрас|"
                               r"раскро|формовк|упаковочн|сжатый воздух)"),
)
вёдра = Counter()
примеры = {}
for z in плохие:
    пр = z.get("pretenzii") or []
    т = "; ".join(str(x) for x in пр) if isinstance(пр, list) else str(пр)
    ведро = "прочее"
    for имя, rx in ТИПЫ:
        if re.search(rx, т):
            ведро = имя
            break
    вёдра[ведро] += 1
    примеры.setdefault(ведро, (z["id"], т))
for в, n in вёдра.most_common():
    i, т = примеры[в]
    print(f"  {n:>4}  {в}")
    print(f"        #{i}: {т[:190]}")

print(f"\n== по {N} писем целиком ==")
for z in плохие[:N]:
    пр = z.get("pretenzii") or []
    print(f"\n{'='*70}\n#{z['id']}")
    print("ПРЕТЕНЗИИ:", "; ".join(str(x) for x in пр)[:400])
    print(f"\nТЕКСТ ПОСЛЕ ПРАВКИ:\n{str(z.get('тело') or '')[:900]}")
