# -*- coding: utf-8 -*-
"""Долить в панель факты, которые моложе снимка базы, без пересборки.

ЗАЧЕМ ИМЕННО ТАК. Третья сессия нашла 63 предприятия, чья карточка обещает
центробежную машину, которую не подтверждает ни один её факт, и предположила
потерю в отборщике. Замер (`poteryannye_63.py`) это опроверг: из 699 фактов
этих предприятий отборщик не выбросил ни одного. Настоящая причина — возраст
снимка: база собрана 02.08 в 17:03, а вторая сессия влила Фабрикант, референс
НЗЛ и Сбербанк-АСТ 03.08 в 03:52. Этих строк в панели просто нет.

ПОЧЕМУ НЕ ПЕРЕСБОРКА. Сухой прогон `pereobrat_panel.py` на свежих файлах даёт
886 предприятий против 1573 живых и 2641 человека против 4638: свежая лента —
только доказанные, а недоказанные в неё не входят. Пересборка принесла бы 79
недостающих строк ценой 210 видимых предприятий и двух тысяч людей. Доливка
даёт то же приобретение без потерь и без остановки службы.

ЧТО ЛЬЁМ, А ЧТО НЕТ. В выгрузке 13 412 новых строк по нашим предприятиям, и
большинство — мусор по разметке самой второй сессии: турбокомпрессор КАМАЗ,
трубопроводы, здания цехов. Льём только то, что проходит боевой
`centro_medium.rejection_reason`, плюс класс `ne_centrobezhnaya` — вихревые и
Рутс не мусор, это НАШ товар другого типа, и панель их показывает отдельной
плашкой. Отсеянное не пропадает: оно лежит в файле второй сессии и доливается
одной правкой, если решение изменится. Число отсеянного печатаем — молчаливый
отсев неотличим от пустого источника.

ДЕДУП по (ИНН, ссылка, марка), а НЕ по (ИНН, ссылка). Одно заключение ЭПБ
описывает несколько машин, и ключ без марки схлопнул бы их в одну строку —
продавец увидел бы один компрессор там, где их три.

По умолчанию СУХОЙ ПРОГОН. Запуск: python dolivka_faktov.py [--apply] [--vse]
"""
import csv
import json
import os
import re
import shutil
import sqlite3
import sys
import time
from collections import Counter

sys.path.insert(0, r'C:\seostat')
from app.services import centro_medium as CM   # noqa: E402
from app.services import centro_marki as CMK   # noqa: E402

БАЗА = os.getenv('CENTRIFUGAL_DB') or r'C:\seostat\data\centrifugal.db'
ДРОП = r'C:\seostat\drop\drop-storage'
ФАЙЛ = 'SVOD-tri-sostoyaniya.csv'
ПРИМЕНИТЬ = '--apply' in sys.argv
ЛИТЬ_ВСЁ = '--vse' in sys.argv          # включая мусорные классы
# вихревые и Рутс — наш товар другого принципа, панель показывает их отдельно
ПУСКАЕМ = {'', 'ne_centrobezhnaya'}

# ЯРЛЫК ИСТОЧНИКА ВАЖНЕЕ МОЕГО ТЕКСТОВОГО РАЗБОРА, и вот почему. Наш
# `rejection_reason` читает только текст факта и ничего не знает про колонку
# `obekt`, которую вторая сессия заполняет своим классификатором. Строка
# «Здание цеха наполнения баллонов азотно-кислородной станции» с ярлыком
# «не машина» проходит мой отбор насквозь: в тексте нет ни насоса, ни
# турбины, ни садового инструмента — отбраковывать нечего.
#
# Замер до правки: из строк, прошедших мой отборщик, 573 помечены источником
# «не машина» и 545 «не наша машина». Это 1118 записей, которые доливка занесла
# бы продавцу под видом доказательств — ровно тот мусор, который велено убрать.
#
# «не установлено» (1354 строки) НЕ отсекаем: это незнание, а не мусор. Такие
# факты несут цитату и ссылку, продавец видит «тип не установлен» и судит сам;
# третья сессия по той же причине не трогала их при чистке.
ОБЪЕКТ_МУСОР = ('не машина', 'не наша машина')


def инн_кл(т):
    return re.sub(r'\D', '', str(т or ''))[:12]


def ключ_марки(т):
    return re.sub(r'\s+', ' ', str(т or '').strip().lower())[:80]


def марка_центробежная(марка):
    """Опознана ли марка как центробежная СЕМЕЙСТВОМ обозначения.

    Третья сессия доказала на трёх карточках подряд, что ярлык «центробежная»
    у источника ставится ПО СЛОВУ: «воздуходувка RRF-350» это Рутс, «ГАЦ-28-6М3»
    рабочее колесо вентилятора АВО, «Воздуходувка WORTEX BB 2536-D» ручной
    инструмент за пару тысяч. Во всех трёх в тексте стоит слово «воздуходувка»,
    и этого хватало. Мой оп ярлык источника просто ПЕРЕНОСИТ — то есть занёс бы
    ту же ошибку в панель.

    Арбитром берём `centro_marki.razobrat` — тот же справочник обозначений, что
    рисует карточку характеристик. Он отвечает по семейству (К-250, ЦК, 43ВЦ,
    ТВ), а не по слову рядом.
    """
    for кусок in re.split(r'[|;]|,(?!\d)', str(марка or '')):
        к = кусок.strip()
        if not к:
            continue
        try:
            р = CMK.razobrat(к)
        except Exception:  # noqa: BLE001
            р = None
        if р and 'центробежн' in str(р.get('tip', '')).lower():
            return True
    return False


def main():
    csv.field_size_limit(10 ** 7)
    путь = os.path.join(ДРОП, ФАЙЛ)
    if not os.path.exists(путь):
        raise SystemExit(f'нет {ФАЙЛ} на дропе')

    cx = sqlite3.connect(f'file:{БАЗА}?mode=ro', uri=True, timeout=20)
    на_панели = {инн_кл(r[0]) for r in cx.execute('SELECT inn FROM company')}
    было_фактов = cx.execute('SELECT COUNT(*) FROM fact').fetchone()[0]
    есть = set()
    for и, у, м in cx.execute(
            "SELECT inn, COALESCE(source_url,''), COALESCE(model,'') FROM fact"):
        есть.add((инн_кл(и), у, ключ_марки(м)))
    cx.close()
    print(f'в панели: предприятий {len(на_панели)}, фактов {было_фактов}')

    новые = []
    отсев = Counter()
    вид_нового = Counter()
    предпр = set()
    прочитано = 0
    with open(путь, encoding='utf-8-sig', errors='replace', newline='') as ф:
        for r in csv.DictReader(ф, delimiter=';'):
            прочитано += 1
            и = инн_кл(r.get('inn'))
            if и not in на_панели:
                continue
            ссылка = (r.get('ssylka') or '').strip()
            марка = (r.get('marki') or '').strip()
            if (и, ссылка, ключ_марки(марка)) in есть:
                continue
            факт = {
                'status': (r.get('sostoyanie') or '').strip(),
                'model': марка,
                'equipment_type': (r.get('tip_mashiny') or '').strip(),
                'medium': (r.get('sreda_mashiny') or r.get('sreda') or '').strip(),
                'evidence': (r.get('chem_dokazano') or '').strip(),
                'quote': (r.get('tekst') or '').strip(),
            }
            причина = CM.rejection_reason(факт)
            if причина not in ПУСКАЕМ and not ЛИТЬ_ВСЁ:
                отсев[причина or 'без причины'] += 1
                continue
            объект = (r.get('obekt') or '').strip().lower()
            if объект in ОБЪЕКТ_МУСОР and not ЛИТЬ_ВСЁ:
                отсев[f'ярлык источника: {объект}'] += 1
                continue
            есть.add((и, ссылка, ключ_марки(марка)))
            предпр.add(и)
            вид_нового[причина or 'чистый факт'] += 1
            новые.append((
                и, факт['status'][:80], факт['model'][:120],
                факт['equipment_type'][:80], факт['medium'][:60],
                (r.get('data') or '').strip()[:40],
                факт['evidence'][:200], факт['quote'][:600],
                ссылка[:400], (r.get('istochnik') or '').strip()[:120]))

    # Факт без марки И без цитаты — это ссылка, а не доказательство: продавец
    # откроет карточку и увидит пустую строку с датой. Считаем отдельно, чтобы
    # решение «лить или не лить такие» принималось по числу, а не на глаз.
    пустых = sum(1 for с in новые if not с[2].strip() and not с[7].strip())
    print(json.dumps({
        'строк_прочитано': прочитано,
        'НОВЫХ_к_доливке': len(новые),
        'из_них_без_марки_и_без_цитаты': пустых,
        'предприятий_затронуто': len(предпр),
        'что_за_новые': вид_нового.most_common(),
        'отсеяно_как_мусор': отсев.most_common(10),
        'отсеяно_всего': sum(отсев.values()),
        'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
    }, ensure_ascii=False, indent=1))
    for с in новые[:5]:
        print(f'  {с[0]} [{с[2][:26]:<26}] {с[3][:24]:<24} {с[7][:60]}')

    if not ПРИМЕНИТЬ or not новые:
        if not ПРИМЕНИТЬ:
            print('\nсухой прогон. Повторить с --apply')
        return

    коп = БАЗА + '.bak-' + str(int(time.time()))
    shutil.copy2(БАЗА, коп)
    print(f'копия базы: {os.path.basename(коп)}')
    cx = sqlite3.connect(БАЗА, timeout=60)
    try:
        cx.executemany(
            'INSERT INTO fact (inn, status, model, equipment_type, medium, '
            'event_date, evidence, quote, source_url, source) '
            'VALUES (?,?,?,?,?,?,?,?,?,?)', новые)
        cx.execute("INSERT OR REPLACE INTO import_info (key, value) "
                   "VALUES ('dolito_faktov_1_sessiey', ?)",
                   (time.strftime('%Y-%m-%dT%H:%M:%S'),))
        cx.commit()
    finally:
        cx.close()

    # числа ПЕРЕЧИТЫВАНИЕМ базы, а не по длине списка
    cx = sqlite3.connect(f'file:{БАЗА}?mode=ro', uri=True, timeout=20)
    стало = cx.execute('SELECT COUNT(*) FROM fact').fetchone()[0]
    с_фактом = cx.execute(
        'SELECT COUNT(DISTINCT inn) FROM fact').fetchone()[0]
    cx.close()
    print(json.dumps({
        'фактов_было': было_фактов, 'фактов_стало': стало,
        'прирост': стало - было_фактов,
        'предприятий_с_хотя_бы_одним_фактом': с_фактом,
    }, ensure_ascii=False))


if __name__ == '__main__':
    main()
