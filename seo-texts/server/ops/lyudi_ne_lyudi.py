# -*- coding: utf-8 -*-
"""В поле «человек» лежит организация — вычистить перед заливкой на панель.

Сухой прогон доливки в панель показал строки вида
«человек: 7704784450 ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ… директор».
Это не человек. Так получилось у меня же: ЕГРЮЛ в поле руководителя отдаёт
УПРАВЛЯЮЩУЮ КОМПАНИЮ, если управление передано юрлицу, а `dadata_dlya_celey`
писал это поле в `add_person` как есть.

Продавцу такая строка бесполезна и вредна: он видит «директор» с названием
конторы вместо имени и не понимает, кого спрашивать. Владелец просил базу без
мусора — значит вычистить надо до заливки, а не после.

Что считаем НЕ человеком:
  * есть организационно-правовая форма или слово «общество/предприятие/
    учреждение/компания» — это юрлицо;
  * в имени цифры или кавычки — у людей их не бывает;
  * одно слово короче четырёх букв — не имя.
Фамилия без имени («Семенова») человеком СЧИТАЕТСЯ: это неполная запись, а не
чужая сущность, и телефон при ней может быть настоящим. Такие только помечаем
числом в отчёте.

По умолчанию СУХОЙ ПРОГОН. Запуск: python lyudi_ne_lyudi.py [--apply]
"""
import json
import re
import sys
from collections import Counter

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

ПРИМЕНИТЬ = '--apply' in sys.argv

_ЮРЛИЦО = re.compile(
    r'\b(ООО|ОАО|ЗАО|АО|ПАО|НАО|МУП|ГУП|ФГУП|ФГБУ|ГБУ|МБУ|АУ|БУ|КУ|ФБУ|НПО|'
    r'НПП|СПК|ТСЖ|УК)\b|общество|предприяти|учреждени|компани|организаци|'
    r'ограниченной\s+ответственностью|акционерн|унитарн|товариществ|'
    r'кооператив|фонд\b|филиал', re.I)
_ЦИФРЫ_КАВЫЧКИ = re.compile(r'[0-9"«»]')


def не_человек(имя):
    т = (имя or '').strip()
    if not т:
        return 'пусто'
    if _ЮРЛИЦО.search(т):
        return 'это юрлицо'
    if _ЦИФРЫ_КАВЫЧКИ.search(т):
        return 'цифры или кавычки в имени'
    слова = т.split()
    if len(слова) == 1 and len(т) < 4:
        return 'слишком коротко'
    return ''


def main():
    db = EDB.EnrichDB()
    cx = db.cx
    строки = cx.execute(
        "SELECT rowid, inn, person, COALESCE(role,''), COALESCE(source,'') "
        'FROM people').fetchall()
    убрать, причины, ист = [], Counter(), Counter()
    примеры = []
    одно_слово = 0
    for rid, инн, чел, роль, источник in строки:
        п = не_человек(чел)
        if п:
            убрать.append(rid)
            причины[п] += 1
            ист[источник[:40]] += 1
            if len(примеры) < 10:
                примеры.append({'inn': инн, 'было_в_поле_человека': (чел or '')[:60],
                                'роль': роль, 'источник': источник[:40]})
        elif len((чел or '').split()) == 1:
            одно_слово += 1

    # телефоны, привязанные к таким «людям», тоже надо отвязать: номер может
    # быть верным, а вот подпись под ним — нет
    имена = {(и, (ч or '').strip()) for _r, и, ч, _рл, _ис in строки
             if не_человек(ч)}
    тел_чинить = [rid for rid, и, ч in cx.execute(
        "SELECT rowid, inn, COALESCE(person,'') FROM phone_contacts "
        "WHERE COALESCE(person,'')<>''") if (и, ч.strip()) in имена]

    итог = {
        'людей_всего': len(строки),
        'НЕ_людей': len(убрать),
        'причины': причины.most_common(),
        'источники': ист.most_common(8),
        'телефонов_с_такой_подписью': len(тел_чинить),
        'человек_из_одного_слова_ОСТАВЛЯЕМ': одно_слово,
        'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
        'примеры': примеры,
    }
    if ПРИМЕНИТЬ and убрать:
        cx.executemany('DELETE FROM people WHERE rowid=?',
                       [(r,) for r in убрать])
        if тел_чинить:
            # НОМЕР НЕ УДАЛЯЕМ: он принадлежит предприятию и полезен. Снимаем
            # только ложную подпись — иначе продавец решит, что звонит
            # названному человеку.
            cx.executemany("UPDATE phone_contacts SET person='', role='' "
                           'WHERE rowid=?', [(r,) for r in тел_чинить])
        cx.commit()
        итог['удалено_людей'] = len(убрать)
        итог['подписей_снято_с_телефонов'] = len(тел_чинить)
        итог['людей_осталось'] = cx.execute(
            'SELECT COUNT(*) FROM people').fetchone()[0]
    print(json.dumps(итог, ensure_ascii=False, indent=1)[:3000])


if __name__ == '__main__':
    main()
