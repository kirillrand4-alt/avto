# -*- coding: utf-8 -*-
"""20 последних мейеровских отказов: за что сняли и что из этого спорно.

Владелец: «разбери 20 ошибок мейера, сколько это снимает». Считаем по
журналу генерации, а не по ощущению: берём последние мейеровские браки и
печатаем причину целиком, чтобы видеть, где линза права, а где нет.
"""
import io
import json
import re
import sys
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
N = int(next((a for a in sys.argv[1:] if a.isdigit()), "20"))

строки = []
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if (z.get("этап") == "итог" and z.get("направление") == "meyer"
            and not z.get("тело") and z.get("брак")):
        строки.append(z)
строки = строки[-N:]
print(f"мейеровских браков разбираю: {len(строки)}\n")

ТИПЫ = (
    ("линза: не наш профиль", r"(?i)инженерная линза"),
    ("квота заходов", r"(?i)заход .* израсходован|анти-?штамп"),
    ("цех не подтверждён сайтом", r"(?i)цех не подтверждён"),
    ("объём", r"(?i)объ[её]м \d+ слов"),
    ("канцелярит", r"(?i)канцелярит"),
    ("предприятие не названо", r"(?i)не названо"),
)
вёдра = Counter()
линза = []
for z in строки:
    б = z.get("брак")
    т = б if isinstance(б, str) else "; ".join(str(x) for x in (б or []))
    ведро = "прочее"
    for имя, rx in ТИПЫ:
        if re.search(rx, т):
            ведро = имя
            break
    вёдра[ведро] += 1
    if ведро == "линза: не наш профиль":
        линза.append((z.get("имя"), т))

for в, n in вёдра.most_common():
    print(f"  {n:>3}  {в}")

print(f"\n== отказы линзы поимённо ({len(линза)}) ==")
for имя, т in линза:
    хвост = re.sub(r"(?i)^.*инженерная линза[^:]*:\s*", "", т)
    print(f"\n  {имя}")
    print(f"    {хвост[:300]}")
