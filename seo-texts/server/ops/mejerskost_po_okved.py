# -*- coding: utf-8 -*-
"""Какие ОКВЭД дают годные МЕЙЕРОВСКИЕ письма — по журналу генерации.

Это прямой замер: берём попытки с направлением meyer, подтягиваем ОКВЭД
компании и считаем долю удачных писем по классам. В отличие от кэша гейта
здесь направление известно точно, и КЦ-суждения не мешают.
"""
import io
import json
import sqlite3
from collections import Counter, defaultdict

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
НАЗВАНИЯ = {
    "10": "производство пищевых продуктов", "11": "производство напитков",
    "01": "сельское хозяйство", "03": "рыболовство",
    "46": "оптовая торговля", "47": "розничная торговля",
    "52": "склады и хранение", "22": "изделия из пластмасс",
    "82": "упаковывание", "20": "химия", "25": "металлоизделия",
    "28": "машины и оборудование", "41": "строительство",
}


def цифры(з):
    return "".join(c for c in str(з or "") if c.isdigit())


e = sqlite3.connect("file:%s?mode=ro" % r"C:\sender\enrich.db", uri=True,
                    timeout=120)
оквэд = {}
for и, к in e.execute("SELECT inn, okved FROM companies"):
    ц = цифры(и)
    if ц:
        оквэд[ц] = str(к or "").strip()
e.close()

по_классу = defaultdict(Counter)
причины = defaultdict(Counter)
всего, без_кода = 0, 0
for стр in io.open(ЖУРНАЛ, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(стр)
    except Exception:                                          # noqa: BLE001
        continue
    if z.get("этап") != "итог":
        continue
    if str(z.get("направление") or "") != "meyer":
        continue
    инн = цифры(z.get("inn"))
    код = оквэд.get(инн) or ""
    всего += 1
    if not код:
        без_кода += 1
        continue
    кл = код.split(".")[0]
    по_классу[кл]["ок" if z.get("ок") else "брак"] += 1
    if not z.get("ок"):
        б = (z.get("брак") or [""])[0]
        причины[кл][str(б)[:46]] += 1

строки = []
for кл, с in по_классу.items():
    н = с["ок"] + с["брак"]
    строки.append((н, кл, с["ок"], с["брак"]))
строки.sort(reverse=True)

print("=== ГОДНОСТЬ МЕЙЕРОВСКОГО ПИСЬМА ПО КЛАССАМ ОКВЭД ===")
for н, кл, ок, брак in строки:
    if н < 15:
        continue
    print("   %-4s попыток %5d  годных %5d (%4.1f%%)  %s"
          % (кл, н, ок, 100.0 * ок / н, НАЗВАНИЯ.get(кл, "")))

print("")
print("=== ПОЧЕМУ БРАКУЮТ ТОРГОВЛЮ (класс 46) ===")
for п, н in причины.get("46", Counter()).most_common(6):
    print("   %4d  %s" % (н, п))

ядро = сум_ок = торг = торг_ок = сх = сх_ок = 0
for н, кл, ок, брак in строки:
    if кл in ("10", "11", "03"):
        ядро += н
        сум_ок += ок
    elif кл in ("46", "47", "52"):
        торг += н
        торг_ок += ок
    elif кл == "01":
        сх += н
        сх_ок += ок

print("")
print("=" * 68)
print("=== СВОДКА ===")
print("мейеровских попыток в журнале: %d, из них без ОКВЭД в базе: %d"
      % (всего, без_кода))
print("")
def строка(имя, н, ок):
    if not н:
        print("   %-34s замеров нет" % имя)
        return
    print("   %-34s попыток %5d  годных %5d (%4.1f%%)"
          % (имя, н, ок, 100.0 * ок / н))
строка("производство (10/11/03)", ядро, сум_ок)
строка("сельское хозяйство (01)", сх, сх_ок)
строка("торговля и склады (46/47/52)", торг, торг_ок)
