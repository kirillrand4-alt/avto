"""В автоотправку - ТОЛЬКО письма, прочитанные глазами и сверенные с сайтом.

Владелец 18.08: «100 штук посмотри глазами, с проверкой источника, и
перекати в автоотправку если там всё нормально», затем «второе включай для
тех кого прочитал».

Отличие от ops/partiya_v_avtootpravku.py: тот отбирает по признаку (адрес
проверен работником) и катит пачкой. Здесь список ИМЕННОЙ - каждое письмо
прочитано целиком, сайт компании открыт с сервера, утверждения сверены.
Правила нет, есть решение по каждому.

Кого НЕ включил и почему - записано ниже в НЕ_ВКЛЮЧЕНЫ, чтобы владельцу было
видно, что именно осталось за бортом.
"""
