# -*- coding: utf-8 -*-
"""Банк абзацев из уже отправленных писем: сколько годится к переиспользованию.

Владелец 24.08: «а мы не можем разные варианты дать для механической?
вырезать из отправленных». У нас 3281 письмо опуса. Режем их на абзацы и
считаем, сколько абзацев НЕ привязаны к конкретной компании — только такие
можно ставить в чужое письмо.

Привязка выдаёт себя: название компании, кавычки-ёлочки с именем, слова
«вы/ваш» с конкретикой, цифры не из блока ФАКТЫ.
"""
import io
import json
import re
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
письма = {}
for с in io.open(ЖУРНАЛ, encoding="utf-8"):
    с = с.strip()
    if not с:
        continue
    try:
        з = json.loads(с)
    except Exception:  # noqa: BLE001
        continue
    if з.get("этап") == "итог" and з.get("ок") and з.get("тело"):
        письма[str(з.get("inn"))] = з
print("писем в корпусе: %d" % len(письма))

ИМЯ_В_КАВЫЧКАХ = re.compile(r"«[^»]{2,40}»")
ЦИФРА = re.compile(r"\d")


def привязан(абзац, имя):
    """Абзац привязан к компании — в чужое письмо не годится."""
    a = абзац.lower()
    корень = (имя or "").lower().strip('«»"" ')
    корень = корень[:-1] if len(корень) >= 4 else корень
    if корень and корень in a:
        return "название компании"
    if ИМЯ_В_КАВЫЧКАХ.search(абзац):
        return "имя в кавычках"
    if ЦИФРА.search(абзац):
        return "цифры"
    return ""


куски = {"вступление": [], "наблюдение": [], "связка": [], "вопрос": [],
         "просьба": []}
свод = Counter()
для_примеров = {}
for inn, з in письма.items():
    абзацы = [a.strip() for a in str(з.get("тело") or "").split("\n\n")
              if a.strip()]
    имя = str(з.get("имя") or "")
    for i, a in enumerate(абзацы):
        низ = a.lower()
        if низ.startswith(("добрый день", "здравствуйте")) or a == "С уважением,":
            continue
        if "?" in a:
            вид = "вопрос"
        elif "перешл" in низ or "перенаправ" in низ or "коллег" in низ:
            вид = "просьба"
        elif "меня зовут" in низ or "я веду" in низ or "представляю" in низ \
                or "занимаюсь" in низ:
            вид = "вступление"
        elif i <= 2:
            вид = "наблюдение"
        else:
            вид = "связка"
        п = привязан(a, имя)
        свод["%s: %s" % (вид, п or "ГОДЕН")] += 1
        if not п:
            куски[вид].append(a)
            для_примеров.setdefault(вид, []).append(a)

print("\n=== ЧТО НАШЛОСЬ ===")
for вид in ("вступление", "наблюдение", "связка", "вопрос", "просьба"):
    годных = len(куски[вид])
    уник = len(set(куски[вид]))
    print("  %-12s годных абзацев %5d, из них РАЗНЫХ %5d" % (вид, годных, уник))

print("\n=== ПОЧЕМУ ОСТАЛЬНЫЕ НЕ ГОДЯТСЯ ===")
for к, н in свод.most_common(14):
    print("  %-40s %5d" % (к, н))

print("\n=== ПРИМЕРЫ ГОДНЫХ (по три на вид) ===")
for вид in ("вступление", "связка", "вопрос", "просьба"):
    ун = list(dict.fromkeys(для_примеров.get(вид, [])))
    print("\n  --- %s (разных %d) ---" % (вид.upper(), len(ун)))
    for a in ун[:3]:
        print("    • %s" % a.replace("\n", " ")[:200])
