def один(модель, напр):
    try:
        m = GP._raw_stream([{"role": "user", "content": ЗАДАНИЕ.format(пример=ПРИМЕРЫ[напр])}],
                           модель, 3000, thinking=False, effort="low")
        т = m if isinstance(m, str) else "".join(getattr(b, "text", "") for b in getattr(m, "content", []) or [])
        нач, кон = т.find("{"), т.rfind("}")
        return модель, напр, json.loads(т[нач:кон + 1], strict=False).get("varianty") or [], None
    except Exception as ex:  # noqa: BLE001
        return модель, напр, [], str(ex)[:200]


задачи = [(м, н) for м in МОДЕЛИ for н in ("meyer", "kc")]
with ThreadPoolExecutor(max_workers=len(задачи)) as пул:
    итоги = list(пул.map(lambda x: один(*x), задачи))
вых = []
for напр in ("meyer", "kc"):
    вых.append("=" * 70 + "\n" + ("MEYER" if напр == "meyer" else "КЦ") + "\n" + "=" * 70)
    for модель, н, варианты, ош in итоги:
        if н != напр:
            continue
        вых.append("\n--- %s: %s" % (модель, "сбой: " + ош if ош else "%d вариантов" % len(варианты)))
        for i, в in enumerate(варианты, 1):
            вых.append("%2d. %s" % (i, re.sub(r"\s+", " ", str(в)).strip()))
текст = "\n".join(вых) + "\n"
io.open(r"C:\sender\_ops\zahody-napominaniy.txt", "w", encoding="utf-8").write(текст)
requests.put(os.environ.get("DROP_URL", "https://parsercompressor.online/drop").rstrip("/") + "/zahody-napominaniy.txt",
             data=текст.encode("utf-8"), headers={"X-Drop-Token": os.environ.get("DROP_TOKEN", "")}, timeout=60)
print("\n".join("%s %s: %s" % (м, н, ош or len(в)) for м, н, в, ош in итоги))
