def похоже_на_график(url):
    имя = urllib.parse.unquote(url.rsplit('/', 1)[-1])
    if _НЕ_ГРАФИК.search(имя):
        return False
    return bool(_ГРАФИК.search(имя) and _ЕСТЬ_ДАТА.search(имя))
# Дата в ИМЕНИ файла — у РТН она стоит именно там: «ЭБ на 03.03.2026»,
# «el_nn_30_03_22.pdf». Из-за того что её не читали, треть записей прошлого
# замера ушла в «дата не определена».
_ДАТА = [re.compile(r'(\d{2})[._-](\d{2})[._-](20\d{2})'),
         re.compile(r'(\d{2})[._-](\d{2})[._-](\d{2})(?!\d)'),
         re.compile(r'(20\d{2})[._-](\d{2})[._-](\d{2})')]

