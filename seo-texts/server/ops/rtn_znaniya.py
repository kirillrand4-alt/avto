_ОТЧЕСТВО = re.compile(
    r'([а-яё]+(?:ович|евич|ьич|инич|овна|евна|ична|инична))\s+(.+)$')


def починить_отчество(фио, должн):
    """Отчество со строчной буквы вернуть в ФИО из начала должности.

    В графиках отчество встречается набранным с маленькой («Голумбевский
    Александр владимирович»), а шаблон ФИО ждёт заглавную — поэтому отчество
    уезжало в НАЧАЛО должности, и в базе оказывались «владимирович
    гл.энергетик» и человек без отчества. Переносим обратно, только если слово
    и правда похоже на отчество, и только когда в ФИО ровно две части.

    Вызывается И при разборе, И при сведении: разобранные строки уже лежат в
    потоке со старой ошибкой, а перекачивать ради этого 521 файл незачем.
    """
    фио = (фио or '').strip()
    должн = (должн or '').strip()
    м = _ОТЧЕСТВО.match(должн)
    if м and len(фио.split()) == 2:
        return фио + ' ' + м.group(1).capitalize(), м.group(2).strip(' .,;')
    return фио, должн


def строки_регуляркой(текст):
    """Пары «ФИО + должность + организация» из графика без обращения к модели."""
    из, видано = [], set()
    for m in _СТРОКА.finditer(текст or ''):
        фио = re.sub(r'\s+', ' ', m.group(1)).strip()
        должн = re.sub(r'\s+', ' ', m.group(2)).strip(' .,;')
        орг = re.sub(r'\s+', ' ', m.group(3)).strip(' .,;')
        фио, должн = починить_отчество(фио, должн)
        if len(фио.split()) < 2 or len(должн) < 3 or len(орг) < 4:
            continue
        ключ = (фио.lower(), орг.lower())
        if ключ in видано:
            continue
        видано.add(ключ)
        из.append({'фио': фио, 'должность': должн, 'организация': орг,
                   'роль': EDB.EnrichDB._canon_role(должн)})
    return из


