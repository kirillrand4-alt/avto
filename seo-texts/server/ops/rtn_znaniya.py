def _разделить_должн_орг(ячейка):
    """«Главный энергетик,ОБЛАСТНОЕ ... УЧРЕЖДЕНИЕ» -> должность и организация.

    Часть управлений печатает одну колонку на двоих — в шапке она названа
    «Предприятие, должность», а в данных лежит «должность,организация», то
    есть В ОБРАТНОМ ПОРЯДКЕ к названию. Полагаться на порядок из шапки тут
    нельзя, поэтому решаем по содержимому: где стоит организационно-правовая
    форма, там организация.

    Если по обе стороны запятой формы нет, НЕ ГАДАЕМ: возвращаем всё как
    должность и пустую организацию. Такая строка просто не сматчится — это
    честнее, чем приписать человека наугад выбранному юрлицу.
    """
    т = (ячейка or '').strip()
    if ',' not in т:
        return т, ''
    for разрез in [м.start() for м in re.finditer(r',', т)]:
        лево, право = т[:разрез].strip(' .,;'), т[разрез + 1:].strip(' .,;')
        if not лево or not право:
            continue
        л_орг = bool(_ЮРФОРМА.search(лево))
        п_орг = bool(_ЮРФОРМА.search(право))
        if п_орг and not л_орг:
            return лево, право
        if л_орг and not п_орг:
            return право, лево
    return т, ''


# ОДНОБУКВЕННЫЕ ЛАТИНСКИЕ ДВОЙНИКИ. В документах встречается «Cоловьев» с
# латинской C: глазами не отличить, а шаблон ФИО (кириллица) такую строку
# отвергает, и человек теряется молча. Заменяем только те латинские буквы, у
# которых есть кириллический двойник, и только внутри слова, где остальные
# буквы кириллические.
_ЛАТ_КИР = str.maketrans('ACBEHKMOPTXYacepxyo', 'АСВЕНКМОРТХУасерхуо')


def _починить_латиницу(s):
    if not s or not re.search(r'[A-Za-z]', s):
        return s
    вышло = []
    for слово in s.split(' '):
        кир = len(re.findall(r'[А-Яа-яЁё]', слово))
        лат = len(re.findall(r'[A-Za-z]', слово))
        вышло.append(слово.translate(_ЛАТ_КИР) if кир and лат and кир > лат
                     else слово)
    return ' '.join(вышло)


