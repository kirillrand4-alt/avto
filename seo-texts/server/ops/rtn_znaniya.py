def провайдер(промпт, максимум=2500):
    key = os.environ.get('PROVIDER_API_KEY', '')
    if not key:
        return ''
    with _сем_пров:
        return _провайдер_зов(промпт, максимум, key)


def _провайдер_зов(промпт, максимум, key):
    base = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
    тело = json.dumps({'model': 'claude-fable-5', 'max_tokens': максимум,
                       'stream': True,
                       'messages': [{'role': 'user', 'content': промпт}]},
                      ensure_ascii=False).encode('utf-8')
    req = urllib.request.Request(
        base + '/v1/messages', data=тело, method='POST',
        headers={'x-api-key': key, 'anthropic-version': '2023-06-01',
                 'content-type': 'application/json',
                 'accept': 'text/event-stream', 'User-Agent': 'curl/8.5.0'})
    куски = []
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            for сырая in r:
                с = сырая.decode('utf-8', 'replace').strip()
                if not с.startswith('data:'):
                    continue
                try:
                    ev = json.loads(с[5:].strip())
                except Exception:  # noqa: BLE001
                    continue
                if ev.get('type') == 'content_block_delta':
                    куски.append((ev.get('delta') or {}).get('text', ''))
    except Exception:  # noqa: BLE001
        return ''.join(куски)
    return ''.join(куски)



# РАЗБОР БЕЗ МОДЕЛИ. Формат строки графика оказался жёстко регулярным:
#   «7 Асабин Евгений Александрович главный инженер,ООО "ЛИНПАРК" ПТ. НПР...»
# то есть номер, ФИО из трёх слов, должность, запятая, организация. Регулярка
# читает это точнее и на порядок дешевле модели — и, главное, НЕ ЗАВИСИТ ОТ
# ДОСТУПНОСТИ ШЛЮЗА. Здесь я дважды ошибся в объяснении, и обе ошибки стоит
# помнить. Сперва решил, что шлюз с сервера не работает вовсе; проверил
# коротким промптом, увидел ответ за 5,5 секунды и объявил, что работает.
# Потом получил таймаут на промпте в 2800 символов и решил, что дело в длине.
# Ни то, ни другое: владелец объяснил, что шлюз периодически занят
# параллельной сессией. То есть доступность плавает по времени, а не по
# размеру запроса, и строить на ней разбор regular-формата незачем.
_СТРОКА = re.compile(
    r'(?:^|\s)\d{1,4}\s+'
    r'([А-ЯЁ][а-яё\-]+\s+[А-ЯЁ][а-яё\-]+(?:\s+[А-ЯЁ][а-яё\-]+)?)\s+'
    r'([а-яё][^,;]{2,60}?)\s*,\s*'
    r'([^\n]{3,110}?)(?=\s+(?:ПТ|ПН|ВТ|СР|ЧТ|ПТ|СБ|ВС)\.|\s+\d{1,2}[:.]\d{2}|\s+\d{1,4}\s+[А-ЯЁ][а-яё]|$)')


def строки_регуляркой(текст):
    """Пары «ФИО + должность + организация» из графика без обращения к модели."""
    из, видано = [], set()
    for m in _СТРОКА.finditer(текст or ''):
        фио = re.sub(r'\s+', ' ', m.group(1)).strip()
        должн = re.sub(r'\s+', ' ', m.group(2)).strip(' .,;')
        орг = re.sub(r'\s+', ' ', m.group(3)).strip(' .,;')
        if len(фио.split()) < 2 or len(должн) < 3 or len(орг) < 4:
            continue
        ключ = (фио.lower(), орг.lower())
        if ключ in видано:
            continue
        видано.add(ключ)
        из.append({'фио': фио, 'должность': должн, 'организация': орг,
                   'роль': EDB.EnrichDB._canon_role(должн)})
    return из


def дата_из_имени(url):
    имя = urllib.parse.unquote(url.rsplit('/', 1)[-1])
    for i, ре in enumerate(_ДАТА):
        m = ре.search(имя)
        if not m:
            continue
        a, b, c = m.groups()
        if i == 2:
            return f'{a}-{b}-{c}'
        год = c if len(c) == 4 else ('20' + c)
        return f'{год}-{b}-{a}'
    return ''


def _поток_читан(путь, ключ='url'):
    было = set()
    if os.path.exists(путь):
        for ln in io.open(путь, encoding='utf-8', errors='replace'):
            try:
                было.add(json.loads(ln).get(ключ))
            except Exception:  # noqa: BLE001
                pass
    return было


def найти():
    """Разведка: собрать ссылки на файлы графиков по территориальным управлениям."""
    # Целим в САМ график с людьми. Прошлые запросы вели в раздел «Аттестация»,
    # где лежит обвязка — бланки, перечни вопросов, образцы удостоверений.
    запросы = [
        'site:gosnadzor.ru "ЭБ на" график',
        'site:gosnadzor.ru график проверки знаний 2026',
        'site:gosnadzor.ru график проверки знаний 2025 организация должность',
        'gosnadzor.ru "график проверки знаний" список работников',
        'gosnadzor.ru график аттестации 2026 главный энергетик',
        'site:gosnadzor.ru "график" "проверки знаний" xlsx',
    ]
    было = _поток_читан(П_ССЫЛКИ)
    ф = io.open(П_ССЫЛКИ, 'a', encoding='utf-8')
    из = {'запросов': 0, 'страниц': 0, 'файлов_новых': 0}
    for з in запросы:
        if time.time() - НАЧАЛО > БЮДЖЕТ:
            break
        из['запросов'] += 1
        for u in EC._serp_urls(з, n=10):
            if time.time() - НАЧАЛО > БЮДЖЕТ:
                break
            # сама ссылка уже может быть файлом
            кандидаты = [u] if (_ФАЙЛ.search(u) and похоже_на_график(u)) else []
            if not кандидаты:
                из['страниц'] += 1
                try:
                    html, _m, _t = EC._fetch_site(u)
                except Exception:  # noqa: BLE001
                    continue
                база = u.rsplit('/', 1)[0]
                for м in re.finditer(r'href=["\']([^"\']+)["\']', html or ''):
                    ссыл = м.group(1)
                    if not _ФАЙЛ.search(ссыл):
                        continue
                    полн = (ссыл if ссыл.startswith('http')
                            else urllib.parse.urljoin(база + '/', ссыл))
                    if похоже_на_график(полн):
                        кандидаты.append(полн)
            for к in кандидаты:
                if к in было:
                    continue
                было.add(к)
                из['файлов_новых'] += 1
                ф.write(json.dumps({'url': к, 'дата': дата_из_имени(к),
                                    'откуда': u[:90]}, ensure_ascii=False) + '\n')
                ф.flush()
                os.fsync(ф.fileno())
    ф.close()
    print(json.dumps({**из, 'всего_в_потоке': len(было), 'поток': П_ССЫЛКИ},
                     ensure_ascii=False))


def собрать():
    """Скачать файлы и вытащить из них строки «ФИО + должность + организация»."""
    файлы = []
    if os.path.exists(П_ССЫЛКИ):
        for ln in io.open(П_ССЫЛКИ, encoding='utf-8', errors='replace'):
            try:
                файлы.append(json.loads(ln))
            except Exception:  # noqa: BLE001
                pass
    сделано = _поток_читан(П_СТРОКИ, 'файл')
    todo = [x for x in файлы if x.get('url') not in сделано][:ЛИМИТ]
    из = {'файлов': len(todo), 'прочитано': 0, 'пустых': 0, 'символов': 0,
          'строк': 0, 'технических': 0}
    print(json.dumps({'старт': True, **из}, ensure_ascii=False))
    ф = io.open(П_СТРОКИ, 'a', encoding='utf-8')

    def один(x):
        if time.time() - НАЧАЛО > БЮДЖЕТ:
            return
        try:
            текст = EC.doc_text(x['url']) or ''
        except Exception:  # noqa: BLE001
            текст = ''
        if len(текст) < 200:
            with _замок:
                из['пустых'] += 1
                ф.write(json.dumps({'файл': x['url'], 'пусто': True},
                                   ensure_ascii=False) + '\n')
                ф.flush()
                os.fsync(ф.fileno())
            return
        строки = строки_регуляркой(текст)
        with _замок:
            из['прочитано'] += 1
            из['символов'] += len(текст)
            из['строк'] += len(строки)
            из['технических'] += sum(1 for с in строки if с['роль'] in ТЕХ)
            ф.write(json.dumps({'файл': x['url'], 'дата': x.get('дата', ''),
                                'строк': len(строки), 'строки': строки},
                               ensure_ascii=False) + '\n')
            ф.flush()
            os.fsync(ф.fileno())

    with ThreadPoolExecutor(max_workers=ПОТОКОВ) as пул:
        list(пул.map(один, todo))
    ф.close()
    print(json.dumps(из, ensure_ascii=False))


def _норм(s):
    s = re.sub(r'["«»\']', '', (s or '').lower())
    s = re.sub(r'\b(ооо|оао|зао|ао|пао|нао|гуп|муп|фгуп|фгбу|гбу|мбу|ип|'
               r'общество|акционерное|публичное|непубличное|с ограниченной '
               r'ответственностью|государственное|муниципальное|унитарное|'
               r'предприятие|федеральное|бюджетное|филиал|обособленное|'
               r'подразделение)\b', ' ', s)
    return re.sub(r'[^а-яёa-z0-9 ]', ' ', re.sub(r'\s+', ' ', s)).strip()


def свести():
    """Сматчить организации из графиков с базой и записать людей.

    Рубеж закрыт по умолчанию: пишем ТОЛЬКО при полном совпадении
    нормализованного названия. Частичное совпадение не доказывает ничего — на
    этом уже уехали контакты чужого завода.
    """
    наши = {}
    for inn, name in e.execute('SELECT inn, name FROM companies WHERE name IS NOT NULL'):
        к = _норм(name)
        if len(к) >= 4:
            наши.setdefault(к, str(inn))
    из = {'файлов': 0, 'строк': 0, 'сматчено': 0, 'не_наши': 0,
          'записано': 0, 'технических': 0,
          'режим': 'ПРИМЕНЕНИЕ' if ПРИМЕНИТЬ else 'сухой (--apply)',
          'примеры': []}
    чужие = {}
    if os.path.exists(П_СТРОКИ):
        for ln in io.open(П_СТРОКИ, encoding='utf-8', errors='replace'):
            try:
                d = json.loads(ln)
            except Exception:  # noqa: BLE001
                continue
            из['файлов'] += 1
            for с in (d.get('строки') or []):
                из['строк'] += 1
                inn = наши.get(_норм(с.get('организация')))
                if not inn:
                    из['не_наши'] += 1
                    чужие[с.get('организация', '')[:60]] = чужие.get(
                        с.get('организация', '')[:60], 0) + 1
                    continue
                из['сматчено'] += 1
                роль = с.get('роль') or ''
                if роль in ТЕХ:
                    из['технических'] += 1
                    if len(из['примеры']) < 14:
                        из['примеры'].append(
                            {'инн': inn, 'фио': с['фио'],
                             'должность': с['должность'][:56], 'роль': роль,
                             'дата': d.get('дата', ''),
                             'ссылка': (d.get('файл') or '')[:88]})
                if ПРИМЕНИТЬ:
                    db.add_person(inn, с['фио'], post=с['должность'],
                                  source='РТН: проверка знаний',
                                  source_url=d.get('файл') or '',
                                  observed_at=(d.get('дата') or '')[:10] or '')
                    из['записано'] += 1
    из['частых_чужих'] = sorted(чужие.items(), key=lambda x: -x[1])[:12]
