# -*- coding: utf-8 -*-
"""Разбор снятых «никуда»: за что сняли и нет ли среди них живых целей.

551 компанию сняли из работы по вердикту модели. Проверяем не выборкой, а
целиком: раскладку по поводам и отдельно — подозрительные, где в самом
объяснении звучит производство или пищёвка.
"""
import io
import json
import re
import sqlite3
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\predprosev-meyer.jsonl"

# Последнее слово за компанией: журнал накопительный, пересуды идут поверх.
итог = {}
for с in io.open(ЖУРНАЛ, encoding="utf-8", errors="replace"):
    с = с.strip()
    if not с:
        continue
    try:
        з = json.loads(с)
    except Exception:                                         # noqa: BLE001
        continue
    if з.get("инн"):
        итог[з["инн"]] = з
снятые = [з for з in итог.values() if з.get("вердикт") == "никуда"]
print("снятых «никуда» (последнее слово): %d" % len(снятые))

ПОВОДЫ = [
    ("торговля и дистрибуция", r"торгов|дистриб|оптов|магазин|маркетплейс|"
                              r"поставщик|продаж|дилер|ритейл|закупк"),
    ("логистика и склад", r"логист|склад|фулфилмент|терминал|перевоз|"
                          r"транспорт|доставк|хранени"),
    ("услуги и посредничество", r"услуг|аренд|консалт|экспертиз|оценк|"
                                r"проектир|инжиниринг|подряд|монтаж|сервис|"
                                r"ремонт|аутсорс"),
    ("госорган, банк, клиника", r"госкорпор|министер|администрац|банк|"
                                r"клиник|больниц|университет|институт|фонд"),
    ("сельхоз без переработки", r"выращива|растениеводств|животноводств|"
                                r"фермер|разведен|посев"),
]
ПИЩА = re.compile(
    r"мясо|мясн|молок|молочн|хлеб|зерн|мук[аи]|крупа|круп|кондитер|пиво|"
    r"винодел|масл|консерв|кофе|чай|снек|орех|семен|сухофрукт|рыб|птиц|"
    r"овощ|фрукт|сахар|специ|пищев|продукт питания|комбикорм|элеватор",
    re.I)
ЦЕХ = re.compile(r"производств|завод|цех|фабрик|комбинат|линия|линии|"
                 r"розлив|фасовк|экструз|обжиг", re.I)
ОТРИЦ_Л = re.compile(r"\b(не|нет|без|отсутству\w*)\b\s*\S*\s*$", re.I)
ОТРИЦ_П = re.compile(r"^\w*\s+(не|нет|отсутству\w*)\b", re.I)


def без_отрицания(т, рег):
    for м in рег.finditer(т or ""):
        if (not ОТРИЦ_Л.search(т[max(0, м.start() - 20):м.start()])
                and not ОТРИЦ_П.search(т[м.end():м.end() + 16])):
            return True
    return False


повод = Counter()
подозрительные = []
for з in снятые:
    п = str(з.get("почему") or "")
    метка = "прочее"
    for имя, рег in ПОВОДЫ:
        if re.search(рег, п, re.I):
            метка = имя
            break
    повод[метка] += 1
    if без_отрицания(п, ПИЩА) or без_отрицания(п, ЦЕХ):
        подозрительные.append(з)

print("")
print("=== за что сняли ===")
for имя, n in повод.most_common():
    print("   %-28s %d" % (имя, n))

print("")
print("=== ПОДОЗРИТЕЛЬНЫЕ: в объяснении звучит цех или пищёвка ===")
print("таких: %d" % len(подозрительные))
for з in подозрительные[:25]:
    print("   %-40s %s" % (str(з.get("имя"))[:40], str(з.get("почему"))[:95]))

print("")
print("=== «прочее» — двадцать штук глазами ===")
прочие = [з for з in снятые
          if not any(re.search(р, str(з.get("почему") or ""), re.I)
                     for _и, р in ПОВОДЫ)]
for з in прочие[:20]:
    print("   %-40s %s" % (str(з.get("имя"))[:40], str(з.get("почему"))[:95]))

# Насколько вердикт был осведомлён: был ли у компании текст сайта
c = sqlite3.connect(r"C:\sender\sender.db", timeout=60)
c.row_factory = sqlite3.Row
с_текстом = без_текста = 0
for з in снятые:
    r = c.execute("SELECT COALESCE(extra_json,'') e FROM recipients WHERE id=?",
                  (з.get("rid"),)).fetchone()
    т = (r["e"] if r else "") or ""
    if "site_text" in т or "site_facts" in т:
        с_текстом += 1
    else:
        без_текста += 1
c.close()
print("")
print("судили по тексту сайта: %d, только по названию и ОКВЭД: %d"
      % (с_текстом, без_текста))
