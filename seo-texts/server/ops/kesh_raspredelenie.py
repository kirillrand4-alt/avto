# -*- coding: utf-8 -*-
"""Как чтение кэша распределено по ходу партии.

Сумма говорит 41% чтения, выборка последних записей — 0.6%. Значит доля
не постоянна. Если шлюз раскидывает запросы по нескольким апстрим-ключам,
при плотном потоке префикс успевает прогреться у многих, а при редких
вызовах не попадает никуда. Тогда доля чтения должна РАСТИ по ходу
прогона и падать в паузах. Проверяем прямо по журналу.
"""
import io
import json

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
записи = []
for с in io.open(ЖУРНАЛ, encoding="utf-8"):
    с = с.strip()
    if not с:
        continue
    try:
        з = json.loads(с)
    except Exception:  # noqa: BLE001
        continue
    if з.get("вход_кэш_запись") is not None:
        записи.append(з)
print("записей с кэш-счётчиками: %d" % len(записи))

def доля(куски):
    зап = sum(int(з.get("вход_кэш_запись") or 0) for з in куски)
    чт = sum(int(з.get("вход_кэш_чтение") or 0) for з in куски)
    всего = зап + чт
    return зап, чт, (100.0 * чт / всего if всего else 0)

зап, чт, п = доля(записи)
print("всего: запись %d, чтение %d — доля чтения %.1f%%" % (зап, чт, п))

print("\n=== ПО ДЕСЯТКАМ ПИСЕМ (последние 600 записей) ===")
хвост = записи[-600:]
for i in range(0, len(хвост), 50):
    кусок = хвост[i:i + 50]
    зап, чт, п = доля(кусок)
    полоса = "#" * int(п / 4)
    print("  письма %4d-%4d  запись %8d чтение %8d  чтение %5.1f%% %s"
          % (i + 1, i + len(кусок), зап, чт, п, полоса))

print("\n=== СКОЛЬКО ПИСЕМ ВООБЩЕ НИЧЕГО НЕ ПРОЧЛИ ===")
нули = [з for з in хвост if int(з.get("вход_кэш_чтение") or 0) < 1000]
полные = [з for з in хвост if int(з.get("вход_кэш_чтение") or 0) >= 1000]
print("  чтение почти ноль (<1000): %d писем" % len(нули))
print("  чтение заметное (>=1000):  %d писем" % len(полные))
if полные:
    зап, чт, п = доля(полные)
    print("  у «читающих» доля чтения: %.1f%%" % п)
if нули:
    зап, чт, п = доля(нули)
    print("  у «нечитающих» доля чтения: %.1f%%" % п)

print("\n=== ПОСЛЕДНИЕ 15 ЗАПИСЕЙ ПОДРЯД ===")
for з in записи[-15:]:
    print("  %-34s запись %7s чтение %7s  вызовов %s+%s"
          % (str(з.get("имя") or "")[:34], з.get("вход_кэш_запись"),
             з.get("вход_кэш_чтение"), з.get("вызовов"),
             з.get("вызовов_проверок")))
