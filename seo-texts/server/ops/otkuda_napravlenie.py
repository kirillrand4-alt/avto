# -*- coding: utf-8 -*-
"""Чем на самом деле решается направление письма — по журналу, а не по коду.

Владелец: «а направление ты как знаешь до генерации?». В коде лестница из
шести правил, но важно другое — какое из них СРАБАТЫВАЕТ чаще. Журнал
пишет причину на каждое письмо (поле «напр_почему»).
"""
import io
import json
from collections import Counter

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ПОЯСНЕНИЯ = {
    "явное": "оператор/кампания задали направление руками",
    "explicit": "оператор/кампания задали направление руками",
    "news": "новостной повод однозначно про одно направление",
    "news_over_needs": "новость про одно, потребность про другое — взяли новость",
    "needs": "колонка «Все категории оборудования» в базе обзвона",
    "base_label": "метка направления в базе обзвона",
    "profile": "ОКВЭД и описание деятельности",
    "fallback": "ничего не разрулило -> КЦ по умолчанию",
    "default_both_needs": "потребность в ОБОИХ направлениях -> КЦ, помечено",
}

причины = Counter()
по_напр = Counter()
пары = Counter()
for s in io.open(ЖУРНАЛ, encoding="utf-8"):
    try:
        z = json.loads(s)
    except Exception:                                                  # noqa: BLE001
        continue
    if z.get("этап") != "итог":
        continue
    п = str(z.get("напр_почему") or "—")
    н = str(z.get("направление") or "—")
    причины[п] += 1
    по_напр[н] += 1
    пары[(н, п)] += 1

всего = sum(причины.values())
print(f"писем с записанной причиной: {всего}\n")
print("== чем решилось направление ==")
for п, n in причины.most_common():
    print(f"  {n:>5} ({n/всего*100:>4.1f}%)  {п:<20} {ПОЯСНЕНИЯ.get(п, '')}")

print("\n== по направлениям ==")
for н, n in по_напр.most_common():
    print(f"  {н}: {n}")

print("\n== разрез: направление x причина ==")
for (н, п), n in пары.most_common(12):
    print(f"  {н:<7} {п:<20} {n}")
