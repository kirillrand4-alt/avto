# -*- coding: utf-8 -*-
"""Самое ценное в «не годно»: письмо ушло НЕ ТОЙ компании или не в ту отрасль.

Придирка к формулировке — полбеды, её видно и правится текстом. Хуже, когда
письмо построено на чужом сайте или адресовано отрасли, которой сжатый
воздух не нужен вовсе: это промах отбора, а не редактуры.
"""
import io
import json
import sys
from collections import Counter

ЧУЖОЙ_САЙТ = ("принадлежит", "другая организац", "другой компании", "тёзк",
              "несоответств", "иное юрлицо", "другое юрлицо", "не та компан")
НЕ_ТА_ОТРАСЛЬ = ("онлайн", "совсем не тот", "профиль совсем", "не нужен",
                 "школ", "обучен", "консалт", "турист", "недвижим",
                 "юридическ", "бухгалтер", "рекламн", "торговая сеть")

последний = {}
for s in io.open(r"C:\sender\_ops\rezenzii-pisem.jsonl", encoding="utf-8",
                 errors="replace"):
    try:
        z = json.loads(s)
        последний[int(z["id"])] = z
    except Exception:                                            # noqa: BLE001
        continue
плохие = [z for z in последний.values()
          if str(z.get("verdict") or "") == "не годно"]

свод = Counter()
находки = {"чужой сайт в карточке": [], "не та отрасль": []}
for z in плохие:
    т = " ".join(str(x) for x in (z.get("pretenzii") or [])).lower()
    if any(w in т for w in ЧУЖОЙ_САЙТ):
        свод["чужой сайт в карточке"] += 1
        находки["чужой сайт в карточке"].append(z)
    elif any(w in т for w in НЕ_ТА_ОТРАСЛЬ):
        свод["не та отрасль"] += 1
        находки["не та отрасль"].append(z)

print(f"всего «не годно»: {len(плохие)}")
for к, n in свод.most_common():
    print(f"  {n:>4}  {к}")
for к, список in находки.items():
    print(f"\n=== {к}")
    for z in список[:8]:
        print(f"  #{z.get('id')} {str(z.get('фирма'))[:38]:<40} "
              f"{z.get('url') or '(нет сайта)'}")
        print(f"      {str((z.get('pretenzii') or [''])[0])[:200]}")
