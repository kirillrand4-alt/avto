"""Честный счёт длинного поиска ЛПР — из ПОТОКА, а не из хвоста stdout.

Зачем отдельный скрипт. Прогон печатает сводку по ролям в конце пачки, а
раннер отдаёт мне только последние 6000 символов вывода. Я по этому хвосту
свёл роли и получил таблицу, в которой НЕ БЫЛО пяти главных ролей —
гл.инженер, гл.энергетик, гл.механик, гл.технолог, гл.конструктор, — потому
что они печатаются первыми и обрезаются. Свод по обрезанному выводу выглядел
полным: колонки на месте, числа правдоподобные, итог посчитан.

Это тот же класс, что сломанный счётчик «выдача: 0», только злее: там ноль
хотя бы виден как ноль, а здесь недостающие строки просто отсутствуют, и
отсутствие ничем себя не выдаёт.

Поэтому счёт берётся из `lpr_stream.jsonl` — по записи на предприятие, пишется
с fsync сразу, обрезать нечего.

Запуск: python lpr_status.py
"""
