ШАПКА = ("Добрый день!\n\nМеня зовут ИМЯ_ОТПРАВИТЕЛЯ, представляю компанию "
         "«Руспром Meyer». %s")
СПИСОК_ЗАГОЛОВОК = "Среди задач, которые решают фотосепараторы Meyer:"


def _числа(инн, сколько):
    """Устойчивый набор чисел из ИНН: одно письмо - один и тот же вариант."""
    h = hashlib.sha1(str(инн or "").encode("utf-8")).digest()
    return [h[i] for i in range(сколько)]


def тема(инн):
    return ТЕМЫ[_числа(инн, 1)[0] % len(ТЕМЫ)]


def письмо(инн, кто, регион=None):
    """Собрать тело письма. `кто` - ««Дубрава»» или «Ваше хозяйство»."""
    ч = _числа(инн, 8)
    где = РЕГИОН_ГДЕ.get(str(регион or "").strip(), "")
    зачин = ЗАЧИН[ч[1] % 3].format(кто=кто, регион=где)
    # Порядок примеров произволен по смыслу, а байты меняет: сдвигаем список
    # по кругу и берём его целиком.
    сдвиг = ч[7] % len(СПИСОК)
    список = СПИСОК[сдвиг:] + СПИСОК[:сдвиг]
    блоки = [
        ШАПКА % ПРЕДСТАВЛЕНИЕ[ч[0] % 3],
        зачин,
        ЧТО_ДЕЛАЕТ[ч[2] % 3],
        СПИСОК_ЗАГОЛОВОК + "\n\n" + "\n".join("- " + с + ";" for с in список[:-1])
        + "\n- " + список[-1] + ".",
        ВЫГОДА[ч[3] % 3],
        ДОКАЗАТЕЛЬСТВО[ч[4] % 3],
        ТЕСТ[ч[5] % 3],
        ПРИЗЫВ[ч[6] % 3],
    ]
    тело = "\n\n".join(блоки)
    assert "—" not in тело, "длинное тире в собранном письме"
    return тело


def сколько_сочетаний():
    return len(ТЕМЫ) * 3 ** 7 * len(СПИСОК)
