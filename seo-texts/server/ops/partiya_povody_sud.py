# -*- coding: utf-8 -*-
"""Суд над новостными поводами: своя новость или однофамилец.

Владелец 17.08 показал Обуховский мясокомбинат (Старый Оскол, свинина),
которому подставили новость про мусорный комплекс «Обухово» ГК «Первый
Спецтранс» в Петербурге, и велел проверить глазами ВСЕ поводы группы.

Механическая сверка имени такое не ловит: у неё совпала основа «обухов»,
и повод прошёл. Поэтому судит модель, у которой перед глазами и профиль
компании, и текст новости, и ссылка: она видит, что мясокомбинат и мусорный
полигон - разные предприятия, даже когда слово в названии одно.

Приговор «чужая» не удаляет сигнал, а ставит ему suspect=1 - штатный
карантин, который _digest уже умеет обходить стороной. Ничего не теряется,
и решение обратимо.

Durable и резюмируемо: каждый приговор пишется строкой в jsonl с fsync,
повторный запуск пропускает уже осуждённые.

argv: [потоков=12] [лимит_секунд=1600]  |  применение - отдельным опом.
"""
import io
import json
import os
import sys
import threading
import time
from collections import Counter
from concurrent.futures import ThreadPoolExecutor

sys.path.insert(0, r"C:\sender")
import gen_provider                                            # noqa: E402

ОПИСЬ = r"C:\sender\_ops\povody-opis.json"
ПРИГОВОРЫ = r"C:\sender\_ops\povody-prigovory.jsonl"
МОДЕЛЬ = "claude-fable-5"
ПОТОКОВ = int(sys.argv[1]) if len(sys.argv) > 1 else 12
ЛИМИТ_СЕК = (int(sys.argv[2]) if len(sys.argv) > 2 else 1600) - 120
СТАРТ = time.time()

опись = json.load(io.open(ОПИСЬ, encoding="utf-8"))
судимые = set()
if os.path.exists(ПРИГОВОРЫ):
    for s in io.open(ПРИГОВОРЫ, encoding="utf-8"):
        try:
            судимые.add(str(json.loads(s).get("inn")))
        except Exception:                                      # noqa: BLE001
            pass
ждут = [з for з in опись if str(з.get("inn")) not in судимые]
print(f"поводов всего {len(опись)} | уже осуждено {len(судимые)} | "
      f"ждут суда {len(ждут)}")
if not ждут:
    raise SystemExit(0)

замок = threading.Lock()
счёт = Counter()
готово = [0]

ЗАДАЧА = """Ты проверяешь, ОТНОСИТСЯ ЛИ НОВОСТЬ К ЭТОМУ ПРЕДПРИЯТИЮ.

Мы пишем холодное письмо и хотим сослаться на событие у получателя. Если
новость на самом деле про ДРУГУЮ организацию с похожим названием, письмо
соврёт человеку - это худшее, что может случиться.

ПРЕДПРИЯТИЕ-ПОЛУЧАТЕЛЬ
Название: {имя}
ИНН: {инн}
Регион: {регион}
Сайт: {сайт}

НОВОСТЬ, КОТОРУЮ ЕМУ ХОТЯТ ПРИПИСАТЬ
Тип: {тип}
Текст: {текст}
Сумма: {сумма}
Ссылка: {ссылка}

Реши одно: это событие ИМЕННО ЭТОГО юрлица (или его группы/завода), или
однофамилец - другое предприятие, другой город, другая отрасль.

Ориентиры, по которым отличают:
- отрасль новости против отрасли получателя (мясокомбинат и мусорный
  полигон - разные предприятия, даже если в названии общее слово);
- город и регион (Петербург против Старого Оскола);
- в тексте прямо названа другая компания или другая группа;
- ссылка ведёт на сайт/страницу другой организации.
Совпадение одного слова в названии - НЕ доказательство.

Сомневаешься - считай чужой: лучше письмо без повода, чем письмо с враньём.

Ответь ТОЛЬКО JSON, без пояснений вокруг:
{{"своя": true|false, "уверенность": "высокая"|"средняя"|"низкая",
  "почему": "одно предложение по-русски"}}"""


def _записать(зап):
    with замок:
        with io.open(ПРИГОВОРЫ, "a", encoding="utf-8") as f:
            f.write(json.dumps(зап, ensure_ascii=False) + "\n")
            f.flush()
            os.fsync(f.fileno())


def _разобрать(текст):
    т = str(текст or "").strip()
    н, к = т.find("{"), т.rfind("}")
    if н < 0 or к <= н:
        return None
    try:
        return json.loads(т[н:к + 1])
    except Exception:                                          # noqa: BLE001
        return None


def _один(з):
    if time.time() - СТАРТ > ЛИМИТ_СЕК:
        return
    prompt = ЗАДАЧА.format(
        имя=з.get("имя") or "", инн=з.get("inn") or "",
        регион=з.get("регион") or "не указан",
        сайт=з.get("сайт") or "не указан",
        тип=з.get("news_type") or "",
        текст=str(з.get("news_detail") or "")[:1200],
        сумма=з.get("news_sum") or "не указана",
        ссылка=з.get("news_url") or "нет")
    ответ = None
    for поп in range(3):
        try:
            т = gen_provider.call(None, [{"role": "user", "content": prompt}],
                                  model=МОДЕЛЬ, attempts=2, effort="low")
            ответ = _разобрать(т)
            if ответ is not None:
                break
        except Exception as ex:                                # noqa: BLE001
            ответ = {"ошибка": str(ex)[:120]}
            time.sleep(3 + поп * 4)
    зап = dict(з)
    зап["приговор"] = ответ or {"ошибка": "ответ не разобран"}
    зап["своя"] = bool((ответ or {}).get("своя")) if ответ else None
    _записать(зап)
    with замок:
        готово[0] += 1
        if ответ and "своя" in ответ:
            счёт["СВОЯ" if ответ["своя"] else "ЧУЖАЯ"] += 1
            счёт[f"уверенность {ответ.get('уверенность')}"] += 1
        else:
            счёт["не разобрано"] += 1
        n = готово[0]
    if not (ответ or {}).get("своя", True):
        print(f"  ЧУЖАЯ: {str(з.get('имя'))[:40]:<42} | "
              f"{str((ответ or {}).get('почему'))[:90]}")
    if n % 25 == 0:
        print(f"  [{n}/{len(ждут)}] {dict(счёт)} {int(time.time()-СТАРТ)}с")


def безопасно(з):
    try:
        _один(з)
    except Exception as ex:                                    # noqa: BLE001
        print(f"  поток упал на {з.get('inn')}: {str(ex)[:100]}")


with ThreadPoolExecutor(max_workers=ПОТОКОВ) as pool:
    list(pool.map(безопасно, ждут))

print(f"\nосуждено за проход: {готово[0]} из {len(ждут)}")
for k, n in счёт.most_common():
    print(f"  {k:<26} {n}")
print(f"приговоры: {ПРИГОВОРЫ}")
