# -*- coding: utf-8 -*-
"""Анатомия цены: сколько вызовов модели стоит одно письмо и почём.

В журнале есть цена_$ и число вызовов на попытку. Отсюда видно главное:
письмо это не один запрос к модели, а круг из нескольких (генерация,
судья, линзы проверки, починка). Дешевить надо там, где вызовов больше.
"""
import io
import json
from collections import Counter, defaultdict

Ж = r"C:\sender\_ops\gen-partiya-935.jsonl"
цены = []
вызовов = Counter()
срывов = Counter()
по_этапам = defaultdict(lambda: [0, 0.0])   # этап -> [строк, деньги]
удачные_цены = []
всего = 0.0
for s in io.open(Ж, encoding="utf-8", errors="replace"):
    try:
        z = json.loads(s)
    except Exception:                                            # noqa: BLE001
        continue
    if z.get("этап") in ("итог", "отмена_попытки"):
        continue
    ц = float(z.get("цена_$") or 0)
    всего += ц
    цены.append(ц)
    if z.get("ок"):
        удачные_цены.append(ц)
    вызовов[int(z.get("вызовов") or 0)] += 1
    срывов[int(z.get("срывов") or 0)] += 1
    э = str(z.get("этап") or "(без этапа)")
    по_этапам[э][0] += 1
    по_этапам[э][1] += ц

цены.sort()
удачные_цены.sort()
print(f"строк: {len(цены)}, суммарно ${всего:.2f}")
print(f"цена строки: медиана ${цены[len(цены)//2]:.4f}, "
      f"90-й процентиль ${цены[int(len(цены)*0.9)]:.4f}, макс ${цены[-1]:.4f}")
if удачные_цены:
    print(f"цена УДАЧНОЙ попытки: медиана ${удачные_цены[len(удачные_цены)//2]:.4f}")
print(f"на одно готовое письмо (всё делённое на удачные): "
      f"${всего/max(1,len(удачные_цены)):.4f}")

print("\nвызовов модели на попытку:")
for k in sorted(вызовов):
    print(f"  {k:>3} вызов(ов): {вызовов[k]:>5} попыток")
print("\nсрывов (ретраи внутри попытки):")
for k in sorted(срывов):
    print(f"  {k:>3}: {срывов[k]:>5}")
print("\nпо этапам:")
for э, (n, д) in sorted(по_этапам.items(), key=lambda x: -x[1][1]):
    print(f"  {э:<24} строк {n:>5}  ${д:>8.2f}  ${д/max(1,n):.4f}/строка")
