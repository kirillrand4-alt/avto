import re

ПЕРЕФРАЗ = """Ты редактор деловых писем Компрессор Центра (компрессоры, осушители, фильтры, свой сервисный центр) бывшим
клиентам. Перескажи абзацы письма своими словами, чтобы текст не совпадал дословно с исходным, но смысл, тон и длина
(±20%) остались прежними. Пиши просто, по-деловому, по-русски, без канцелярита.
СОХРАНИ без изменений: год, марку и модель оборудования, что именно мы делали (поставка, ТО, ремонт, пусконаладка),
имя менеджера и «Компрессор Центр», заказчиков (РУСАЛ, РЖД, «Северсталь», «Алроса» — тех же трёх), смысл вопроса
про планы на ближайшие месяцы. Первое предложение второго абзаца — о том, что мы для клиента делали; затем «немного
напомню о нас…» (своими словами) и заказчики.
ДОПИШИ, если фраза о прошлой работе неполная и не сказано, чего она касалась («наш инженер выполнял пусконаладку»):
по названиям сделок ниже — «пусконаладку вашего компрессора». Если из сделок не ясно — «пусконаладку оборудования».
НЕЛЬЗЯ: новые факты, цифры, обещания, цены, сроки; «бесплатно», «скидка», «акция», «выгодно»; восклицательные знаки;
длинное тире; просить переслать письмо (мы пишем именно этому контакту).
Ответ СТРОГО JSON: {"a1": "...", "a2": "...", "a3": "..."} — столько ключей, сколько абзацев дано."""

ЛИНЗЫ = """Ты проверяешь письмо менеджера Компрессор Центра бывшему клиенту сервисного центра тремя независимыми взглядами.
Рядом даны успешные сделки клиента с нами (дата | воронка | название) — из них взята фраза о прошлой работе.
1) tehnolog — инженер компрессорного оборудования: фраза о прошлой работе технически осмысленна? Не перепутано
   оборудование и работа (осушитель ТО не «поставляют на пусконаладку»; ресивер не «ремонтируют фильтром»), марка
   и модель как в сделках, нет выдумки сверх сделок. Общее «обращались в наш сервисный центр» — верно.
2) filolog — редактор-филолог деловой переписки: грамматика и согласование, недосказанность («выполнял пусконаладку» —
   чего?), тавтологии, канцелярит, штампы, ритм, стыки абзацев, естественность. Ошибка — только если фраза
   неграмотна, непонятна или звучит странно; мелкая шероховатость — «сомнительно».
3) doverie — скептичный главный инженер, которому каждый день пишут поставщики: похоже ли на шаблонный спам,
   нет ли преувеличений, рекламных слов, давления; правдоподобно ли, что пишет тот, кто с нами уже работал.
Подпись и реквизиты добавит система — их отсутствие не ошибка. «Бюджеты на следующий год» в ноябре — верно.
Каждое pochemu — не длиннее 20 слов.
Ответ СТРОГО JSON: {"tehnolog": {"verdict": "верно|сомнительно|ошибка", "pochemu": ""}, "filolog": {...}, "doverie": {...}}"""


def _сделки_текст(сд):
    return "\n".join("   %s | %s | %s" % (x["d"], x["v"], x["t"][:160]) for x in сд[:8]) or "   (нет)"


def perefraz(абзацы, сд, зов):
    """абзацы: список абзацев БЕЗ приветствия (первый абзац начинается с «Меня зовут…»). → новые абзацы или None."""
    т = "Сделки клиента:\n%s\n\n%s" % (_сделки_текст(сд), "\n".join("Абзац %d: %s" % (i + 1, а) for i, а in enumerate(абзацы)))
    д = зов(т, "a1", ПЕРЕФРАЗ, 2000) or {}
    нов = [(д.get("a%d" % (i + 1)) or "").strip().replace("—", "-") for i in range(len(абзацы))]
    if not all(нов) or "!" in "".join(нов) or re.search(r"(?i)бесплатн|скидк|акци|выгодн|перешл|передайте|передадите", "".join(нов)):
        return None
    исх = " ".join(абзацы)
    for год in re.findall(r"\b20\d\d\b", исх):            # год и латинские марки должны сохраниться
        if год not in " ".join(нов): return None
    for м in re.findall(r"\b[A-Z][A-Za-z0-9\-\.]{2,}\b", исх):
        if м not in " ".join(нов): return None
    return нов


def linzy(письмо, тема, сд, зов):
    д = зов("Сделки клиента:\n%s\n\nПисьмо:\nТема: %s\n\n%s" % (_сделки_текст(сд), тема, письмо), "tehnolog", ЛИНЗЫ, 1500) or {}
    return {к: (д.get(к) if isinstance(д.get(к), dict) else {"verdict": "нет ответа"}) for к in ("tehnolog", "filolog", "doverie")}


def oshibka(вер):
    return any(v.get("verdict") == "ошибка" for v in вер.values())
