# -*- coding: utf-8 -*-
"""Как просьба перенаправить была написана в ушедших письмах КЦ.

Владелец: «в ранних отправлениях например по металлообработке кц мы писали
перенаправление». Значит формулировку надо брать из тех писем, а не
сочинять. Заодно смотрим, кому они уходили: есть ли связь с ролью адресата
и признаком ЛПР — от этого зависит, как формулировать правило.

База только на чтение.
"""
import io
import json
import os
import re
import sqlite3
import urllib.request
from collections import Counter

БАЗА = r"C:\sender\sender.db"
ОТЧЁТ = r"C:\sender\_ops\PERENAPRAVLENIE-KC.md"

# СТРОГО - копия боевого _prosba_perenapravit: прямой глагол пересылки, глагол
# передачи, вопрос «к кому обратиться».
ПРЯМО = re.compile(r"(?i)перенаправ|перешл|переслат")
ГЛАГОЛ = re.compile(r"(?i)переда(й|йте|ть)\b")
ВОПРОС = re.compile(r"(?i)(к кому|с кем)\s+(мне\s+)?(лучше\s+)?"
                    r"(обратиться|поговорить|связаться)")

# ШИРОКО. Владелец: «она могла быть в другой формулировке» - и это не догадка.
# В его же письме О'КЕЙ концовка «Если вопрос находится в зоне ответственности
# другого коллеги, буду признателен за контакт» строгим детектором НЕ ловится:
# ни глагола пересылки, ни вопроса «к кому». Значит счёт по строгому детектору
# занижен, а боевой гейт, построенный на нём, забракует такие письма.
ШИРОКО = [
    re.compile(r"(?i)перенаправ|перешл|переслат"),
    re.compile(r"(?i)переда(й|йте|ть)\b"),
    re.compile(r"(?i)(к кому|с кем)\s+(мне\s+)?(лучше\s+)?"
               r"(обратиться|поговорить|связаться|обсудить)"),
    re.compile(r"(?i)зон[аеы]\s+ответственности"),
    re.compile(r"(?i)признателен|признательна|буду рад(а)?\s+контакт"),
    re.compile(r"(?i)друг(ой|ому)\s+специалист"),
    re.compile(r"(?i)коллег"),
    re.compile(r"(?i)не по адресу"),
    re.compile(r"(?i)кто отвечает за"),
    re.compile(r"(?i)профильн\w+\s+специалист"),
    re.compile(r"(?i)ответственн\w+\s+за"),
]

conn = sqlite3.connect(f"file:{БАЗА}?mode=ro", uri=True, timeout=30)
conn.row_factory = sqlite3.Row

С = []


def п(s=""):
    С.append(s)


def просьба(т):
    """Строгий детектор — ровно тот, что стоит в боевом гейте."""
    return bool(ПРЯМО.search(т or "") or ГЛАГОЛ.search(т or "")
                or ВОПРОС.search(т or ""))


def просьба_широко(т):
    return any(p.search(т or "") for p in ШИРОКО)


def фраза(т, широко=False):
    """Само предложение с просьбой - его и надо цитировать."""
    чем = просьба_широко if широко else просьба
    for пр in re.split(r"(?<=[.!?])\s+", т or ""):
        if чем(пр):
            return пр.strip()
    return ""


строки = list(conn.execute(
    "SELECT id, campaign_id, recipient_id, email, subject, body, "
    "edited_body, panel_json, status, created_at FROM confirm_reviews "
    "WHERE campaign_id IN (9, 10) ORDER BY id"))

с_просьбой, без = [], []
роли = Counter()
роли_с = Counter()
формулировки = Counter()
мимо_гейта = []
лпр_с = Counter()
лпр_без = Counter()

for r in строки:
    b = r["edited_body"] or r["body"] or ""
    try:
        panel = json.loads(r["panel_json"] or "{}")
    except Exception:                                          # noqa: BLE001
        panel = {}
    контакт = panel.get("contact") or {}
    лпр = контакт.get("lpr")
    роль = str(контакт.get("role") or контакт.get("dolzhnost") or "")
    роли[роль or "(нет роли)"] += 1
    if просьба_широко(b):
        с_просьбой.append(r)
        роли_с[роль or "(нет роли)"] += 1
        лпр_с[str(лпр)] += 1
        ф = фраза(b, широко=True)
        if ф:
            формулировки[ф[:150]] += 1
        # ловится ли она БОЕВЫМ гейтом - вот что решает, можно ли на него
        # опереться в новом правиле
        if not просьба(b):
            мимо_гейта.append(ф or b[:120])
    else:
        без.append(r)
        лпр_без[str(лпр)] += 1

п("# Просьба перенаправить в письмах КЦ (кампании 9 и 10)")
п()
строгих = sum(1 for r in строки if просьба(
    r["edited_body"] or r["body"] or ""))
п(f"писем всего {len(строки)}")
п()
п(f"* просьба есть (**широкий** невод): **{len(с_просьбой)}** "
  f"({100 * len(с_просьбой) // max(1, len(строки))}%)")
п(f"* её ловит БОЕВОЙ гейт (строгий детектор): **{строгих}**")
п(f"* **мимо боевого гейта: {len(мимо_гейта)}** — эти письма новое правило "
  f"забракует, хотя просьба в них есть")
п(f"* просьбы нет вовсе: {len(без)}")
п()
п("## Как это было написано")
п()
for ф, n in формулировки.most_common(14):
    п(f"* ({n}) {ф}")
if not формулировки:
    п("ни в одном письме КЦ просьбы нет")
п()
п("## Формулировки, которые боевой гейт НЕ ловит")
п()
for ф in list(dict.fromkeys(мимо_гейта))[:12]:
    п(f"* {ф}")
if not мимо_гейта:
    п("таких нет — строгий детектор ловит всё, что нашёл широкий")
п()
п("## Связь с ролью адресата и признаком ЛПР")
п()
п(f"| | с просьбой | без просьбы |")
п("|---|---|---|")
все_лпр = set(лпр_с) | set(лпр_без)
for л in sorted(все_лпр):
    п(f"| panel.contact.lpr = {л} | {лпр_с.get(л, 0)} | {лпр_без.get(л, 0)} |")
п()
п("роли адресатов у писем С просьбой:")
for р, n in роли_с.most_common(12):
    п(f"  {р:<40} {n}")
п()
п("роли по всем письмам КЦ:")
for р, n in роли.most_common(12):
    п(f"  {р:<40} {n}")

п()
п("## Примеры писем с просьбой (первые три целиком)")
п()
for r in с_просьбой[:3]:
    b = r["edited_body"] or r["body"] or ""
    п(f"### #{r['id']} — {r['email']} ({r['status']}, {r['created_at'][:10]})")
    п()
    п(f"**Тема:** {r['subject']}")
    п()
    п("```")
    п(b.strip())
    п("```")
    п()

текст = "\n".join(С) + "\n"
try:
    with io.open(ОТЧЁТ, "w", encoding="utf-8") as f:
        f.write(текст)
    rq = urllib.request.Request(
        os.environ["DROP_URL"].rstrip("/") + "/PERENAPRAVLENIE-KC.md",
        data=текст.encode("utf-8"), method="PUT",
        headers={"X-Drop-Token": os.environ["DROP_TOKEN"]})
    with urllib.request.urlopen(rq, timeout=120) as r:
        r.read()
    print("отчёт на дропе: PERENAPRAVLENIE-KC.md")
except Exception as ex:                                        # noqa: BLE001
    print("на дроп не уехал:", str(ex)[:160])

print(f"писем КЦ {len(строки)}, с просьбой {len(с_просьбой)}, без {len(без)}")
print("формулировок разных:", len(формулировки))
