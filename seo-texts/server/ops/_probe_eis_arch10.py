r"""ПРОБА 10: те же два теста на брак — но уже к тому, что записал Я.

Прежний источник провалил оба: 57 записей из 236 носят «имя» вида «Опросы
Статистика Карта» (кусок вёрстки), а номер 4999494740 висит на девяти разных
компаниях, то есть это телефон самого сайта, а не компании. Свою выгрузку надо
проверять тем же инструментом, иначе отчёт будет самооправданием.

Тест 1: имя — не кусок вёрстки.
Тест 2: один номер не размазан по многим ИНН.
Тест 3: у каждой записи есть дата и она внутри трёх лет (условие владельца).
Тест 4: source_url действительно самая свежая закупка человека (запасная
        ссылка обязана быть СТАРШЕ основной).
"""
import json
import re
import sys

sys.path.insert(0, r'C:\sender\server')
import enrich_db as EDB  # noqa: E402

МУСОР = re.compile(
    r'опрос|статистик|карта сайта|преимуществ|органам контрол|отчет о|главная'
    r'|версия для|личный кабинет|обратная связь|документац|извещен|закупк', re.I)


def main():
    db = EDB.EnrichDB()
    e = db.cx
    out = {}
    строки = list(e.execute(
        'SELECT inn,person,phone,email,proc_date,freshness,source_url,alt_url,'
        'alt_date,n_procs FROM eis_arch'))
    out['всего'] = len(строки)

    # 1) имя как вёрстка
    битые = [r for r in строки if r[1] and МУСОР.search(r[1])]
    out['тест1_имя_это_вёрстка'] = len(битые)
    out['тест1_примеры'] = [{'инн': r[0], 'кто': r[1]} for r in битые[:5]]
    # заодно: ФИО без отчества и без инициалов — подозрительная форма
    без_иниц = [r for r in строки if r[1] and not re.search(
        r'[А-ЯЁ]\.|ович|евич|ьич|овна|евна|ична', r[1])]
    out['тест1_имя_без_инициалов_и_отчества'] = len(без_иниц)
    out['тест1_примеры2'] = [{'инн': r[0], 'кто': r[1]} for r in без_иниц[:5]]

    # 2) один номер на многих ИНН
    част = {}
    for r in строки:
        ц = re.sub(r'\D', '', (r[2] or '').split(' доб.')[0])[-10:]
        if ц:
            част.setdefault(ц, set()).add(r[0])
    топ = sorted(част.items(), key=lambda kv: -len(kv[1]))[:5]
    out['тест2_топ_номеров'] = [{'номер': k, 'компаний': len(v)} for k, v in топ]
    out['тест2_номеров_у_2+_компаний'] = sum(1 for _k, v in част.items() if len(v) > 1)

    # 3) дата и рубеж трёх лет
    из_даты = [r for r in строки if not r[4]]
    out['тест3_без_даты'] = len(из_даты)
    out['тест3_свежесть'] = {r[0]: r[1] for r in e.execute(
        'SELECT freshness, COUNT(*) FROM eis_arch GROUP BY freshness')}
    старьё = e.execute(
        "SELECT COUNT(*) FROM eis_arch WHERE proc_date < date('now','-1095 day')"
    ).fetchone()[0]
    out['тест3_старше_3_лет_в_базе'] = старьё

    # 4) запасная ссылка обязана быть старше основной
    плохой_порядок = [r for r in строки
                      if r[7] and r[8] and r[8] > r[4]]
    out['тест4_запасная_свежее_основной'] = len(плохой_порядок)
    out['тест4_с_запасной'] = sum(1 for r in строки if r[7])
    # согласованность: n_procs>1 => должна быть запасная ссылка
    out['тест4_много_закупок_без_запасной'] = sum(
        1 for r in строки if (r[9] or 0) > 1 and not r[7])

    # 5) люди без единого контакта — их в обзвон не отдашь
    out['без_телефона_и_почты'] = sum(
        1 for r in строки if not (r[2] or '').strip() and not (r[3] or '').strip())
    print('ПРОБА10 ' + json.dumps(out, ensure_ascii=False, indent=1)[:4000], flush=True)


if __name__ == '__main__':
    main()
