"""Мёртвый груз в префиксе: то, что мы шлём и чем запрещено пользоваться.

Правило 5 блока правил: «ПРО ОПУБЛИКОВАННЫЕ КЕЙСЫ И ПРОЕКТЫ В ПЕРВОМ
ПИСЬМЕ НЕ ПИСАТЬ ВООБЩЕ (решение владельца 19.08)». А блок фактов при этом
везёт список проектов по сотне регионов — на каждом вызове, за деньги.
Считаем точно.
"""
import re
import sys

sys.path.insert(0, r"C:\sender\sender")
sys.path.insert(0, r"C:\sender")

from sender.ai_letter import facts_block, load_facts           # noqa: E402

ВЫЗОВОВ = 4496
СТАВКА = 6.25 / 1_000_000
ЗНАКОВ_НА_ТОКЕН = 1.8


def цена(знаков):
    return знаков / ЗНАКОВ_НА_ТОКЕН * СТАВКА * ВЫЗОВОВ


факты = facts_block(load_facts(division="kc"), "kc")
строки = факты.split("\n")
print("блок фактов: %d знаков, %d строк, ~$%.0f в день"
      % (len(факты), len(строки), цена(len(факты))))

# регионы: строки вида «  - Город: N проектов»
регионы = [с for с in строки if re.match(r"\s+-\s+.+:\s*\d+\s+проект", с)]
знаков_регионы = sum(len(с) + 1 for с in регионы)
print("\n  из них список проектов по регионам: %d строк, %d знаков, ~$%.0f в день"
      % (len(регионы), знаков_регионы, цена(знаков_регионы)))
print("  первые: %s" % "; ".join(с.strip() for с in регионы[:4]))
print("  последние: %s" % "; ".join(с.strip() for с in регионы[-4:]))
хвост = [с for с in регионы if re.search(r":\s*([1-3])\s+проект", с)]
print("  из них с 1-3 проектами (совсем мелочь): %d строк, %d знаков, ~$%.0f в день"
      % (len(хвост), sum(len(с) + 1 for с in хвост),
         цена(sum(len(с) + 1 for с in хвост))))

прочее = [с for с in строки if с not in регионы]
print("\n  остальное в фактах: %d строк, %d знаков"
      % (len(прочее), sum(len(с) + 1 for с in прочее)))
for с in прочее[:25]:
    print("    | %s" % с[:110])
if len(прочее) > 25:
    print("    | … ещё %d строк" % (len(прочее) - 25))
