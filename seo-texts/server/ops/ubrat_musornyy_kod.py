"""Убрать 46.90 из списка: 86 254 компании на 32 покупателя.

«Торговля оптовая неспециализированная» — код-помойка: под ним сидит кто
угодно, и он один съедает больше квоты, чем весь зерновой блок. Правку делаем
в файле, прогон её подхватит на следующем заходе (файл читается при старте) —
перезапускать нельзя: сборщик не помнит пройденные страницы и при рестарте
заново листает всё с начала, а это и сожгло пул ключей.
"""
import io
import os
import sys

ФАЙЛ = r"C:\seostat\Parser2\data\okved-agro.txt"
УБРАТЬ = {"46.90", "46.9"}
ПИСАТЬ = "--zapisat" in sys.argv
список = [с.strip() for с in io.open(ФАЙЛ, encoding="utf-8") if с.strip()]
остаток = [к for к in список if к not in УБРАТЬ]
print("было %d, станет %d; убираем: %s"
      % (len(список), len(остаток),
         ", ".join(к for к in список if к in УБРАТЬ) or "нечего"))
if ПИСАТЬ and len(остаток) != len(список):
    with io.open(ФАЙЛ, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(остаток) + "\n")
        f.flush()
        os.fsync(f.fileno())
    print("записано")
elif not ПИСАТЬ:
    print("(с --zapisat запишу)")
