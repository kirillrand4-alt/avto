# -*- coding: utf-8 -*-
"""Вернуть компаниям попытки, сожжённые поломкой шлюза 31.08.

Приём не новый: 17.08, когда у провайдера кончился баланс, ops/
otkatit_403_popytki.py уже дописывал в журнал строку «отмена_попытки» —
она вычитается резюмом (partiya_gen: этап == «отмена_попытки» →
попыток_инн -= 1). Ничего не удаляем, только дописываем.

Признак «виноват шлюз, а не компания»: попытка не вернула ТЕЛА. Если модель
написала текст и его забраковали по существу — это честная попытка, её не
возвращаем. Если тела нет вовсе (обрыв стрима, отказ, JSON не разобрался) —
компания за это платить не должна.
"""
import io
import json
import os
import sys
import time
from collections import Counter, defaultdict

ЖУРНАЛ = r"C:\sender\_ops\gen-partiya-935.jsonl"
ПРИМЕНИТЬ = "--primenit" in sys.argv
ДЕНЬ = "2026-08-31"


def цифры(з):
    return "".join(c for c in str(з or "") if c.isdigit())


попыток = Counter()
пустых_попыток = defaultdict(list)
есть_тело = set()
готово = set()
with io.open(ЖУРНАЛ, encoding="utf-8") as f:
    строки = f.readlines()
for с in строки:
    try:
        z = json.loads(с)
    except Exception:                                         # noqa: BLE001
        continue
    и = цифры(z.get("inn"))
    if not и:
        continue
    э = str(z.get("этап") or "")
    if э == "отмена_попытки":
        попыток[и] = max(0, попыток[и] - 1)
        continue
    if z.get("тело"):
        есть_тело.add(и)
    if z.get("ок") or z.get("тело"):
        готово.add(и)
    if э != "итог":
        попыток[и] += 1
        if not z.get("тело") and str(z.get("день") or "") == ДЕНЬ:
            пустых_попыток[и].append(z)

выбыли = [и for и in попыток
          if попыток[и] >= 3 and и not in готово]
вернуть = {и: пустых_попыток[и] for и in выбыли if пустых_попыток.get(и)}
всего_строк = sum(len(v) for v in вернуть.values())

print("=== СОСТОЯНИЕ ЖУРНАЛА ===")
print("   строк: %d; фирм с попытками: %d; фирм с готовым письмом: %d"
      % (len(строки), len(попыток), len(готово)))
print("\n=== ВЫБЫВШИЕ ПО ЛИМИТУ ТРЁХ ПОПЫТОК ===")
print("   всего таких фирм: %d" % len(выбыли))
print("   из них есть пустые попытки за %s: %d" % (ДЕНЬ, len(вернуть)))
print("   строк отмены к дописыванию: %d" % всего_строк)
print("\n   сколько попыток вернём каждой:")
for n, ск in Counter(len(v) for v in вернуть.values()).most_common():
    print("      по %d попытке — %d фирм" % (n, ск))
станет = Counter()
for и in вернуть:
    станет[попыток[и] - len(вернуть[и])] += 1
print("\n   останется попыток после отмены:")
for n, ск in sorted(станет.items()):
    print("      %d попыток — %d фирм %s"
          % (n, ск, "(вернутся в отбор)" if n < 3 else "(всё ещё выбывшие)"))

if not ПРИМЕНИТЬ:
    print("\n[сухой прогон] дописать отмены — с ключом --primenit")
    raise SystemExit(0)

записано = 0
with io.open(ЖУРНАЛ, "a", encoding="utf-8") as f:
    for и, попытки in вернуть.items():
        for _ in попытки:
            f.write(json.dumps(
                {"inn": и, "этап": "отмена_попытки", "день": ДЕНЬ,
                 "причина": "стрим шлюза лежал 31.08, генерация не вернула "
                            "тела — попытка не по вине компании",
                 "кем": "avto-a5", "ts": int(time.time())},
                ensure_ascii=False) + "\n")
            записано += 1
    f.flush()
    os.fsync(f.fileno())
print("\n=== ИТОГ ===")
print("дописано строк отмены: %d по %d фирмам" % (записано, len(вернуть)))
print("они вернутся в отбор следующим прогоном")
