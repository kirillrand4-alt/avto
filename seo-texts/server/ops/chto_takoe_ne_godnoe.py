# -*- coding: utf-8 -*-
"""Что именно рецензент назвал «не годным» — и насколько твёрдо основание.

Претензии бывают двух разных сортов, и мешать их нельзя:
  ПРОТИВОРЕЧИЕ — сайт говорит ДРУГОЕ, чем письмо («письмо: производство,
      сайт: торговля»). Основание твёрдое: утверждение опровергнуто.
  УМОЛЧАНИЕ   — сайта просто не касается темы («сайт не упоминает
      покраску»). Основание слабое: отсутствие упоминания не есть
      отсутствие процесса, сайт вообще не обязан перечислять цеха.
Плюс отдельно ловим суждения по ОКВЭД: рецензенту прямо сказано судить по
сайту, а не по коду вида деятельности.

    python zapusk_svoego_skripta.py ops/chto_takoe_ne_godnoe.py
"""
import io
import json
import re
import sys
from collections import Counter

sys.path.insert(0, r"C:\sender")

ПРОТИВОРЕЧИЕ = ("сайт говорит", "сайт показыва", "а сайт", "на сайте —",
                "позиционируется", "сайт описывает", "речь о", "вместо",
                "торгу", "продаж", "дилер", "монтаж", "перепрода",
                "поставщик", "дистрибь")
УМОЛЧАНИЕ = ("не упомина", "нет ни слова", "не указан", "не подтвержда",
             "нет данных", "не найдено", "не сказано", "отсутству",
             "нет информации", "не описан", "ничего о", "нет упомин")
ОКВЭД = ("оквэд", "код вида", "квэд")

последний = {}
for s in io.open(r"C:\sender\_ops\rezenzii-pisem.jsonl", encoding="utf-8",
                 errors="replace"):
    try:
        z = json.loads(s)
        последний[int(z["id"])] = z
    except Exception:                                            # noqa: BLE001
        continue

плохие = [z for z in последний.values()
          if str(z.get("verdict") or "") == "не годно"]
print(f"писем «не годно»: {len(плохие)}")

вид = Counter()
по_видам = {}
без_сайта = 0
for z in плохие:
    т = " ".join(str(x) for x in (z.get("pretenzii") or [])).lower()
    if not int(z.get("сайт_знаков") or 0):
        без_сайта += 1
    if any(w in т for w in ОКВЭД):
        к = "судил по ОКВЭД, а не по сайту"
    elif any(w in т for w in ПРОТИВОРЕЧИЕ):
        к = "ПРОТИВОРЕЧИЕ: сайт говорит другое"
    elif any(w in т for w in УМОЛЧАНИЕ):
        к = "умолчание: сайт темы не касается"
    else:
        к = "прочее"
    вид[к] += 1
    по_видам.setdefault(к, []).append(z)

print(f"  из них вердикт вынесен БЕЗ текста сайта: {без_сайта}")
print()
for к, n in вид.most_common():
    print(f"  {n:>4}  {к}")

for к in ("умолчание: сайт темы не касается", "судил по ОКВЭД, а не по сайту",
          "ПРОТИВОРЕЧИЕ: сайт говорит другое", "прочее"):
    примеры = по_видам.get(к) or []
    if not примеры:
        continue
    print(f"\n=== {к} — примеры")
    for z in примеры[:5]:
        п = (z.get("pretenzii") or [""])[0]
        print(f"  #{z.get('id')} {str(z.get('фирма'))[:34]:<36} "
              f"{z.get('url') or '(нет сайта)'}")
        print(f"      {str(п)[:230]}")
