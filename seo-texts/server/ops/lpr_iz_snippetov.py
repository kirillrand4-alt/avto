# ФИО: «Фамилия Имя Отчество». Инициалы не берём: в сниппете «Иванов И.И.»
# без должности рядом это чаще подпись документа, чем человек предприятия.
_ФИО = re.compile(
    r'\b([А-ЯЁ][а-яё]{2,}(?:-[А-ЯЁ][а-яё]{2,})?)\s+'
    r'([А-ЯЁ][а-яё]{2,})\s+([А-ЯЁ][а-яё]{2,}(?:вич|вна|ична|инична))\b')

# Должность рядом с именем. Порядок важен: длинные варианты раньше коротких,
# иначе «главный инженер» схлопнется в «инженер».
_ДОЛЖН = re.compile(
    r'(и\.?\s?о\.?\s+|заместител[ья]\s+|зам\.?\s*)?'
    r'(главн\w+\s+(?:инженер\w*|энергетик\w*|механик\w*|технолог\w*|'
    r'конструктор\w*|специалист\w*)|'
    r'техническ\w+\s+директор\w*|директор\w*\s+по\s+производств\w+|'
    r'директор\w*\s+по\s+техническ\w+\s+\w+|'
    r'начальник\w*\s+(?:производств\w+|цеха|компрессорн\w+|котельн\w+|'
    r'энергослужб\w+|отдела\s+главн\w+\s+\w+|ОГЭ|ОГМ|КИПиА|АСУ\s?ТП)|'
    r'главн\w+\s+диспетчер\w*)', re.I)


# СТРАНИЦА О ПРОШЛОМ, А НЕ О НЫНЕШНЕЙ ДОЛЖНОСТИ. Даже с привязкой по окну
# выход заполнили списки «Выдающиеся выпускники» нефтяного института: там у
# каждого рядом стоит и должность, и завод, и формально всё сходится. Только
# должность эта может быть тридцатилетней давности, а человек давно на пенсии.
# Ложный «главный инженер» стоит продавцу пустого звонка и доверия к панели,
# поэтому такие строки отделяем и в базу не отдаём — они идут отдельным
# файлом как кандидаты на проверку.
# Признаки ищем И В ЛАТИНИЦЕ: адрес страницы транслитерирован, и кириллическая
# проверка его не видит. Первая версия пропустила `vydayushchiesya-vypuskniki`
# насквозь именно поэтому — регулярка была права, но смотрела не туда.
_ИСТОРИЯ = re.compile(
    r'выпускник|выдающи|ветеран|музе|истори|юбиле|поздрав|памяти|некролог|'
    r'окончил|годы\s+работы|альбом|доска\s+почёта|доска\s+почета|'
    r'\b19\d\d\b|в\s+прошлом|бывш\w+|'
    r'vypuskn|vydayush|veteran|muze[ykj]|istori|yubile|pozdrav|pamyat|'
    r'nekrolog|doska[-_]poch|alumni|graduates|vospomin', re.I)


def историческая(url, текст):
    return bool(_ИСТОРИЯ.search(f'{url} {текст}'))


def ядро(имя):
    try:
        return L.ядро_имени(имя or '')
    except Exception:  # noqa: BLE001
        return (имя or '').strip()


def токены(имя):
    return [т for т in re.split(r'[\s"«»,.\-()]+', ядро(имя).lower())
            if len(т) > 3]


def привязано(текст, имя, полное):
    """Чем доказано, что человек из ЭТОГО предприятия.

    Возвращает уровень, который принимает штатный `apply`: «полное_имя» или
    «ядро». Если ни одного значащего токена имени в тексте нет — не привязано,
    и такую строку мы не отдаём вовсе.
    """
    т = (текст or '').lower()
    for п in (полное, имя):
        я = ядро(п).lower()
        if len(я) > 4 and я in т:
            return 'полное_имя'
    тк = токены(имя) or токены(полное)
    if тк and sum(1 for x in тк if x in т) >= max(1, len(тк) - 1):
        return 'ядро'
    return ''


def людей_из_текста(текст, имя, полное):
    """Тройки (ФИО, должность, цитата) — с привязкой В ТОМ ЖЕ ОКНЕ.

    Окно, а не вся строка: в сниппете «Ибрагимов … главный инженер … Зимакова
    … начальник ОПК» одна общая строка дала бы обоим одну должность.

    ПРИВЯЗКА ТОЖЕ ПО ОКНУ, и это главное. Первая версия проверяла имя
    предприятия по всему сниппету, и первый же прогон выдал десяток «главных
    инженеров Синтез-Каучука» со страницы `rusoil.net/vydayushchiesya-vypuskniki`
    — это список ВЫДАЮЩИХСЯ ВЫПУСКНИКОВ вуза, где название завода стоит один
    раз, а люди работают кто где. Страница проходила привязку целиком, и все
    её фамилии доставались одному предприятию.

    Требуем, чтобы название предприятия стояло рядом с человеком — в тех же
    двух сотнях знаков, что и должность. Тогда «Ибрагимов … главный инженер
    ОАО «Синтез-Каучук»» проходит, а список выпускников — нет.
    """
    сп = list(_ФИО.finditer(текст or ''))
    if not сп:
        return []
    # ДОЛЖНОСТЬ ДОЛЖНА ПРИМЫКАТЬ К ИМЕНИ. Три предыдущие попытки — окно ±100
    # знаков, участок «до следующего имени» и «ближайшая должность» — все три
    # отдали Зимаковой чужой титул на одном и том же сниппете:
    #   «Ибрагимов … технический директор-главный инженер ОАО «Синтез-Каучук»
    #    Зимакова Наталья Владимировна-начальник ОПК»
    # У Ибрагимова две должности подряд, вторая физически ближе к Зимаковой,
    # а её собственная — «начальник ОПК» — в наш список технических ролей не
    # входит вовсе. Любая метрика «кто ближе» тут проигрывает.
    #
    # Берём только то, что стоит ВПЛОТНУЮ: между именем и должностью
    # допускаются лишь пробелы, дефис, запятая, двоеточие и скобки. Человек
    # без примыкающей должности пропускается — пустая строка честнее чужого
    # титула, за который продавец заплатит звонком.
    ЗАЗОР = r'[\s\-–—:,()«»"]{0,3}'
    из = []
    for м in сп:
        фио = f'{м.group(1)} {м.group(2)} {м.group(3)}'
        после = текст[м.end():м.end() + 90]
        до = текст[max(0, м.start() - 90):м.start()]
        д = re.match(ЗАЗОР + r'(?:' + _ДОЛЖН.pattern + r')', после, re.I)
        если_справа = bool(д)
        if не_пусто(д):
            должн = д.group(0)
            лев, прав = м.start(), м.end() + д.end()
        else:
            д = re.search(r'(?:' + _ДОЛЖН.pattern + r')' + ЗАЗОР + r'$',
                          до, re.I)
            if not д:
                continue
            должн = д.group(0)
            лев, прав = max(0, м.start() - 90) + д.start(), м.end()
        участок = текст[max(0, лев - 60):прав + 80]
        ур = привязано(участок, имя, полное)
        if not ур:
            continue
        должн = re.sub(r'\s+', ' ', должн).strip(' -–—:,()«»"')
        if len(должн) < 6:
            continue
        из.append((фио, должн, re.sub(r'\s+', ' ', участок).strip(), ур))
    return из


def не_пусто(м):
    return m_ok(м)


def m_ok(м):
    return bool(м) and bool((м.group(0) or '').strip(' -–—:,()«»"'))
def main():
    if not os.path.exists(ПОТОК):
        raise SystemExit(f'нет потока {ПОТОК}')
    люди, истор, видел = [], [], set()
    сч = Counter()
    записей = 0
    with open(ПОТОК, encoding='utf-8', errors='replace') as ж:
        for стр in ж:
            try:
                r = json.loads(стр)
            except Exception:  # noqa: BLE001
                continue
            if ТЕГ and r.get('тег') != ТЕГ:
                continue
            if РЕЖИМ and r.get('режим') != РЕЖИМ:
                continue
            записей += 1
            инн = str(r.get('inn') or '')
            имя = r.get('имя') or r.get('krat') or ''
            полное = r.get('poln') or ''
            for с in (r.get('страницы') or []):
                сч['страниц'] += 1
                текст = ' '.join(x for x in (с.get('title') or '',
                                             с.get('passage') or '') if x)
                for о in (с.get('окна') or []):
                    if о.get('т'):
                        текст += ' ' + о['т']
                if not текст.strip():
                    сч['страница без сниппета'] += 1
                    continue
                найдено = людей_из_текста(текст, имя, полное)
                if not найдено:
                    сч['нет пары ФИО+должность рядом с именем завода'] += 1
                    continue
                for фио, должн, цитата, ур in найдено:
                    к = (инн, фио.lower())
                    if к in видел:
                        сч['повтор'] += 1
                        continue
                    видел.add(к)
                    стар = историческая(с.get('url') or '', цитата)
                    сч['историческая страница' if стар else 'ЧЕЛОВЕК'] += 1
                    (истор if стар else люди).append({
                        'inn': инн, 'person': фио, 'post': должн,
                        'url': с.get('url') or '', 'date': с.get('дата') or '',
                        'свежесть': с.get('свежесть') or 'дата?',
                        'привязка': ур, 'quote': цитата[:400],
                        'режим': r.get('режим') or 'b',
                        'источник': 'поиск-ЛПР: сниппет выдачи',
                    })

    буф = io.BytesIO()
    with gzip.GzipFile(fileobj=буф, mode='wb') as z:
        z.write(json.dumps({'люди': люди}, ensure_ascii=False).encode('utf-8'))
    п = os.path.join(ХРАН, ВЫХОД)
    with open(п, 'wb') as ф:
        ф.write(буф.getvalue())
        ф.flush()
        os.fsync(ф.fileno())

    if истор:
        import csv
        import urllib.request
        имя_и = f'KANDIDATY-istoricheskie-{ТЕГ or "vse"}.csv'
        пи = os.path.join(r'C:\sender\server', имя_и)
        with open(пи, 'w', encoding='utf-8-sig', newline='') as ф:
            в = csv.writer(ф, delimiter=';')
            в.writerow(['inn', 'fio', 'dolzhnost', 'privyazka', 'ssylka', 'citata'])
            for x in истор:
                в.writerow([x['inn'], x['person'], x['post'], x['привязка'],
                            x['url'], x['quote'][:300]])
        try:
            урл = os.environ.get('DROP_URL', 'https://parsercompressor.online/drop')
            urllib.request.urlopen(urllib.request.Request(
                урл.rstrip('/') + '/' + имя_и, data=open(пи, 'rb').read(),
                method='PUT',
                headers={'X-Drop-Token': os.environ.get('DROP_TOKEN', '')}),
                timeout=300).read()
            print(f'исторические кандидаты на дропе: {имя_и} ({len(истор)})')
        except Exception as e:  # noqa: BLE001
            print(f'{имя_и} на дроп не ушёл: {e}')

    роли = Counter(x['post'].lower()[:34] for x in люди)
    print(json.dumps({
        'записей_потока': записей,
        'ЛЮДЕЙ_ИЗ_СНИППЕТОВ': len(люди),
        'отложено_как_историческое': len(истор),
        'предприятий': len({x['inn'] for x in люди}),
        'должности': роли.most_common(12),
        'почему_остальное_не_взято': сч.most_common(),
        'пачка': ВЫХОД,
        'применить': f'lpr_serp.py apply --file {ВЫХОД}',
    }, ensure_ascii=False, indent=1))
    for x in люди[:15]:
        print(f'  {x["inn"]} {x["person"][:30]:<30} {x["post"][:34]:<34} '
              f'{x["привязка"]:<11} {x["url"][:52]}')


if __name__ == '__main__':
    main()
