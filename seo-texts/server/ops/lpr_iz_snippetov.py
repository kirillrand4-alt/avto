"""Достать людей из СНИППЕТОВ выдачи, а не только из скачанных страниц.

ЧТО СЛОМАНО. `lpr_serp` платит за запрос, получает сниппет, скачивает страницу
и ищет ФИО с должностью В ТЕКСТЕ СТРАНИЦЫ. Если страница не отдалась (защита,
редирект, пустое тело) — запись остаётся с `символов: 11`, привязка «нет», и
человек теряется. При этом ОТВЕТ УЖЕ ЕСТЬ в самом сниппете:

    «Ибрагимов Азат Нажипович-технический директор-главный инженер
     ОАО «Синтез-Каучук» Зимакова Наталья Владимировна-начальник ОПК»

Это готовый технический ЛПР по одному из девяти предприятий с истёкшей
экспертизой ЭПБ — ровно то, что мы ищем, и оно было оплачено и выброшено.

ВТОРАЯ ПОЛОМКА, РЯДОМ. `apply` в `lpr_serp` ждёт файл вида `{'люди': [...]}`,
а `pack` кладёт СПИСОК КОМПАНИЙ со страницами. Такого файла не производит ни
один шаг опа — то есть записи найденного в базу не было вовсе. Этот оп
закрывает разрыв: он и есть недостающий производитель `{'люди': [...]}`.

ПРИВЯЗКА СТРОГАЯ. Сниппет короткий, соблазн «раз имя компании в запросе, значит
человек оттуда» велик, но так в базу попадут преподаватели профильного вуза и
однофамильцы с чужих заводов. Требуем, чтобы ядро имени предприятия стояло в
самом тексте сниппета или заголовка, и пишем, чем именно доказана привязка.

Ничего не пишет в базы сам: кладёт пачку, которую применяет штатный
`lpr_serp.py apply --file <имя>`.

Запуск: python lpr_iz_snippetov.py [--tag T] [--mode b] [--out ИМЯ]
"""
