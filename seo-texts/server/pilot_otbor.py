def по_префиксу(код, таблица):
    лучший = ''
    for п, имя in таблица:
        if код.startswith(п) and len(п) > len(лучший):
            лучший, итог = п, имя
    return итог if лучший else ''


def сегм_meyer(осн, все):
    """-> (сегмент, как): как = 'основной' | 'доп' | 'критик' | 'исключён' | ''."""
    if not осн:
        return '', ''
    if ИСКЛ.match(осн):
        return 'исключён владельцем (%s)' % осн, 'исключён'
    с = по_префиксу(осн, СЕГМ)
    if с:
        return с, 'основной'
    к = по_префиксу(осн, КРИТИК)
    for доп in все or []:
        if доп != осн and not ИСКЛ.match(доп):
            сд = по_префиксу(доп, СЕГМ)
            if сд:
                return сд, 'доп' if not к else 'критик+доп'
    if к:
        return к, 'критик'
    return '', ''


