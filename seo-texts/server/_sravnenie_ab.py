# -*- coding: utf-8 -*-
"""Сравнение агентов Luna и Sol (pilot-ab-*.jsonl) на общих компаниях. Запуск раннером, итог — JSON после ===ИТОГ===."""
import io
import json
import os

D = r'C:\sender\server'
ЛПР = {'директор', 'технический директор', 'главный инженер', 'главный механик', 'главный энергетик', 'инженер',
       'производство', 'закупки', 'главный технолог', 'технолог', 'качество'}
ВЫДУМКА = ('номера нет на странице', 'агент не открывал эту страницу', 'не номер')


def читать(м):
    п = os.path.join(D, 'pilot-ab-%s.jsonl' % м)
    return {з['inn']: з for з in (json.loads(s) for s in io.open(п, encoding='utf-8')) if з.get('итог') == 'ok'} if os.path.exists(п) else {}


def метрики(зз):
    n = len(зз) or 1
    ном = [н for з in зз for н in з.get('номера') or []]
    сн = [с for з in зз for с in з.get('снято') or []]
    return {
        'компаний': len(зз),
        'с номером, %': round(100 * sum(1 for з in зз if з.get('номера')) / n),
        'с номером ЛПР, %': round(100 * sum(1 for з in зз if any(н.get('класс') in ЛПР for н in з.get('номера') or [])) / n),
        'номеров принято': len(ном),
        'из них ЛПР': sum(1 for н in ном if н.get('класс') in ЛПР),
        'с ФИО': sum(1 for н in ном if (н.get('фио') or '').strip()),
        'свой сайт подтверждён, %': round(100 * sum(1 for з in зз if з.get('сайт_завода_чей')) / n),
        'холдинг подтверждён, %': round(100 * sum(1 for з in зз if з.get('холдинг_подтверждён')) / n),
        'номеров снято': len(сн),
        'из них выдумка (нет на странице / не открывал)': sum(1 for с in сн if any(с.get('причина', '').startswith(в) for в in ВЫДУМКА)),
        'сек на компанию': round(sum(з.get('сек', 0) for з in зз) / n),
        'шагов': round(sum(з.get('шагов', 0) for з in зз) / n, 1),
    }


def main():
    л, с = читать('gpt-6-luna'), читать('gpt-6-sol')
    общие = sorted(set(л) & set(с))
    тот_же_сайт = sum(1 for i in общие if л[i].get('сайт_завода_чей') and с[i].get('сайт_завода_чей')
                      and л[i]['сайт_завода'].split('/')[2:3] == с[i]['сайт_завода'].split('/')[2:3])
    только_с = [i for i in общие if с[i].get('номера') and not л[i].get('номера')]
    только_л = [i for i in общие if л[i].get('номера') and not с[i].get('номера')]
    print('===ИТОГ===')
    print(json.dumps({
        'всего': {'luna': len(л), 'sol': len(с)}, 'общих': len(общие),
        'luna (общие)': метрики([л[i] for i in общие]), 'sol (общие)': метрики([с[i] for i in общие]),
        'luna (все)': метрики(list(л.values())), 'sol (все)': метрики(list(с.values())),
        'оба нашли свой сайт, один и тот же': тот_же_сайт,
        'номер только у Sol': len(только_с), 'номер только у Luna': len(только_л),
        'примеры только у Sol': [(с[i]['имя'], [н['номер'] + ' ' + н.get('класс', '') for н in с[i]['номера']][:3]) for i in только_с[:6]],
        'примеры только у Luna': [(л[i]['имя'], [н['номер'] + ' ' + н.get('класс', '') for н in л[i]['номера']][:3]) for i in только_л[:6]],
        'пояснения Luna без номера (5)': [(л[i]['имя'], л[i].get('пояснение', '')[:200]) for i in общие if not л[i].get('номера')][:5],
    }, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
