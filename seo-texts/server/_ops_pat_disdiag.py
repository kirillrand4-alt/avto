# -*- coding: utf-8 -*-
"""Почему раскрытие дало нули: провайдер или окна?

Пять компаний упали с RemoteDisconnected — это ОТКАЗ ВЫЗОВА МОДЕЛИ, а не
пустой источник. Ещё у части людей ноль без ошибки. Разбираем по частям:
  A) жив ли провайдер на коротком промпте, на 10к и на 26к символов;
  B) есть ли вообще окна с должностями в уже найденных документах.
"""
import io
import json
import os
import re
import sys
import time

sys.path.insert(0, r'C:\sender\server')
sys.path.insert(0, r'C:\sender\_ops')
sys.argv = [sys.argv[0]]
import _ops_pat_disclosure as D   # noqa: E402

print('### A. провайдер на разных размерах')
основа = ('Ниже кусок документа. Верни СТРОГО JSON {"people":[{"person":"..",'
          '"post":".."}]}\n\n')
проба = ('Совет директоров АО «Пример»: 1. Иванов Иван Иванович 2. Петров Пётр '
         'Петрович. Главный инженер — Сидоров Сидор Сидорович. ')
for размер in (0, 10000, 26000):
    п = основа + (проба * (max(1, размер // len(проба)) if размер else 1))
    т0 = time.time()
    ответ, беда = D.провайдер(п, 800)
    print('  промпт %6d симв -> %5.1fс | беда=%r | ответ[0:150]=%r'
          % (len(п), time.time() - т0, беда, (ответ or '')[:150]))

print('### B. окна в уже найденных документах')
рек = {}
п = r'C:\sender\_ops\pat_disclosure.jsonl'
for ln in io.open(п, encoding='utf-8', errors='replace'):
    try:
        x = json.loads(ln)
    except Exception:  # noqa: BLE001
        continue
    рек[x['имя']] = x
for имя in ('ПАО «Криогенмаш»', 'АО «Уралхиммаш»', 'АО «Кремний»'):
    x = рек.get(имя)
    if not x:
        continue
    print(' ', имя, '| источников', len(x.get('источники') or []),
          '| символов_модели', x.get('символов_модели'),
          '| прочитано', x.get('прочитано'), '| пустые', len(x.get('пустые') or []))
    for u in (x.get('источники') or [])[:3]:
        _u, t, как = D.текст_дока(u)
        ок = D.окна(t)
        print('    %s | %s | символов=%d | окон=%d' % (u[-52:], как, len(t or ''), len(ок)))
        if ок:
            print('      ОКНО:', repr(re.sub(r'\s+', ' ', ок[0])[:260]))
        elif t:
            print('      БЕЗ ОКОН, текст[0:200]:', repr(re.sub(r'\s+', ' ', t)[:200]))
print('ДИСДИАГ ЗАВЕРШЕНА')
