def писать(r):
    with _лок:
        with io.open(СЫРЬЁ, 'a', encoding='utf-8') as f:
            f.write(json.dumps(r, ensure_ascii=False) + '\n'); f.flush(); os.fsync(f.fileno())


def одна(з):
    м, т, к = з
    for п in range(3):
        try:
            t = VC._provider_call_stdlib(ВОПРОС.format(биз=БИЗ, тема=ТЕМЫ[т], кому=КОМУ[к]), model=м) or ''
            мм = re.search(r'\{.*\}', t, re.S)
            j = json.loads(мм.group(0)) if мм else None
            if isinstance(j, dict) and j:
                писать({'модель': м, 'тема': т, 'кому': к, 'ответ': j}); return 'ок'
        except Exception:  # noqa: BLE001
            pass
        time.sleep(10 * (п + 1))
    писать({'модель': м, 'тема': т, 'кому': к, 'ошибка': 1}); return 'сбой'


def main():
    готово = set()
    if os.path.exists(СЫРЬЁ):
        for s in io.open(СЫРЬЁ, encoding='utf-8', errors='replace'):
            try:
                y = json.loads(s)
                if y.get('ответ'): готово.add((y['модель'], y['тема'], y['кому']))
            except ValueError:
                pass
    # 30 вызовов: каждая тема × направление (8) × модели по кругу, ~4 модели на пару; меркурий — только Meyer и КЦ-пищевка
    задачи = []
    for i, (т, к) in enumerate((т, к) for т in ТЕМЫ for к in КОМУ):
        for j in range(4):
            задачи.append((МОДЕЛИ[(i + j) % len(МОДЕЛИ)], т, к))
    задачи = [з for з in задачи[:32] if з not in готово]
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(8) as ex:
        рез = list(ex.map(одна, задачи))
    сводка = collections.defaultdict(lambda: collections.defaultdict(collections.Counter))
    for s in io.open(СЫРЬЁ, encoding='utf-8', errors='replace'):
        y = json.loads(s)
        for ф, сп in (y.get('ответ') or {}).items():
            for п in сп if isinstance(сп, list) else []:
                сводка['%s|%s' % (y['тема'], y['кому'])][ф][' '.join(str(п).lower().split())[:160]] += 1
    out = {k: {ф: c.most_common() for ф, c in v.items()} for k, v in сводка.items()}
    with io.open(СВОДКА, 'w', encoding='utf-8') as f:
        json.dump(out, f, ensure_ascii=False, indent=0); f.flush(); os.fsync(f.fileno())
    for п in (СЫРЬЁ, СВОДКА):
        shutil.copyfile(п, os.path.join(ДРОП, os.path.basename(п)))
    print('===ИТОГ===', collections.Counter(рез), {k: {ф: len(c) for ф, c in v.items()} for k, v in out.items()})


if __name__ == '__main__':
    main()
