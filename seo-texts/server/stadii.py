# Границы здравого смысла: год вне диапазона — это не дата, а мусор (номер
# документа, цена, id лота). Верх — «сегодня + 6 лет»: в базе есть законные
# будущие даты вроде плана закупок «2027-04», но не 2099.
_MIN_YEAR = 1990
_MAX_YEAR = datetime.date.today().year + 6

# Месяцы: русские (полные, родительный падеж и сокращения) + английские
# (RFC-822 из RSS). Ключ — начало слова, поэтому «янв», «января», «январь»
# ловятся одним правилом.
_MONTHS = {
    'янв': 1, 'jan': 1, 'фев': 2, 'feb': 2, 'мар': 3, 'mar': 3,
    'апр': 4, 'apr': 4, 'май': 5, 'мая': 5, 'may': 5, 'июн': 6, 'jun': 6,
    'июл': 7, 'jul': 7, 'авг': 8, 'aug': 8, 'сен': 9, 'sep': 9,
    'окт': 10, 'oct': 10, 'ноя': 11, 'nov': 11, 'дек': 12, 'dec': 12,
}

# Границы «не цифра» вместо \b: в '2026-07-29T17:00:16' после дня стоит буква,
# и \b там не срабатывает — ISO со временем терялся.
_RE_ISO_DAY = re.compile(r'(?<!\d)(\d{4})-(\d{1,2})-(\d{1,2})(?!\d)')
_RE_ISO_MONTH = re.compile(r'^\s*(\d{4})-(\d{1,2})\s*$')
_RE_COMPACT = re.compile(r'^\s*(\d{4})(\d{2})(\d{2})\s*$')
_RE_DOT_DAY = re.compile(r'(?<!\d)(\d{1,2})[.\-/](\d{1,2})[.\-/](\d{2,4})(?!\d)')
_RE_DOT_MONTH = re.compile(r'^\s*(\d{1,2})[.\-/](\d{4})\s*$')
_RE_TXT_DAY = re.compile(r'\b(\d{1,2})\s+([A-Za-zА-Яа-яЁё]{3,})\.?\s+(\d{4})\b')
# Устаревшая форма RFC-822 с ДВУЗНАЧНЫМ годом: 'Wed, 08 Jul 26 08:00:28 +0300'.
# В боевой базе таких 12 строк — все 12 «непарсящихся» до этого правила.
# Двузначный год берём только когда следом стоит время: иначе '5 мая 20'
# из текста новости превратилось бы в дату.
_RE_RFC_2Y = re.compile(r'\b(\d{1,2})\s+([A-Za-zА-Яа-яЁё]{3,})\.?\s+(\d{2})\s+\d{1,2}:\d{2}')
_RE_TXT_MONTH = re.compile(r'\b([A-Za-zА-Яа-яЁё]{3,})\.?\s+(\d{4})\b')
_RE_YEAR = re.compile(r'^\s*(\d{4})\s*(?:г\.?|год[ауе]?)?\s*$')


def _mon(word):
    """Номер месяца по слову. Не месяц — None."""
    w = (word or '').lower().replace('ё', 'е')[:3]
    return _MONTHS.get(w)


def _mk(y, m, d):
    """Собрать 'YYYY-MM-DD' с проверкой календаря и границ года. Брак — None."""
    try:
        y, m, d = int(y), int(m), int(d)
    except (TypeError, ValueError):
        return None
    if not (_MIN_YEAR <= y <= _MAX_YEAR) or not (1 <= m <= 12):
        return None
    try:
        return datetime.date(y, m, d).isoformat()
    except ValueError:              # 31 февраля и прочая арифметика источника
        return None


def _mk_month(y, m):
    """Месячная точность: якорим на 1-е число. Это ОГРУБЛЕНИЕ, не выдумка:
    день источник не дал, а 1-е число — самая ранняя (то есть самая
    консервативная для «сколько дней прошло») точка месяца."""
    return _mk(y, m, 1)


def normalize_date_full(raw):
    """Разбор даты с указанием точности.

    Возврат: `(дата 'YYYY-MM-DD' | None, точность 'day'|'month'|'year'|None)`.

    Понимает всё, что реально лежит в `signals.ts`, плюс обычные текстовые
    формы из тела новости:

        'Wed, 29 Jul 2026 23:40:41 +0500' -> ('2026-07-29', 'day')
        'Sun, 28 Jun 2026 03:18:57 GMT'   -> ('2026-06-28', 'day')
        '2026-07-26'                      -> ('2026-07-26', 'day')
        '2026-07-29 17:00:16'             -> ('2026-07-29', 'day')
        '13.07.2026'                      -> ('2026-07-13', 'day')
        '12 августа 2026'                 -> ('2026-08-12', 'day')
        '2026-07'                         -> ('2026-07-01', 'month')
        'август 2026'                     -> ('2026-08-01', 'month')
        '2026 г.'                         -> ('2026-01-01', 'year')
        '', 'вчера', 'id1159966'          -> (None, None)

    Часовой пояс НЕ пересчитывается: берём дату так, как её написал источник
    ('29 Jul 2026 23:40 +0500' -> 29 июля). Для «сколько дней назад» разница
    в пределах суток роли не играет, а перевод в UTC сдвинул бы половину
    вечерних новостей на день назад.

    Относительные слова ('вчера', 'на прошлой неделе') сознательно НЕ
    поддержаны: их смысл зависит от момента разбора, а не от источника.
    """
    s = str(raw or '').strip()
    if not s:
        return (None, None)

    m = _RE_ISO_DAY.search(s)                       # ISO и ISO+время
    if m:
        d = _mk(m.group(1), m.group(2), m.group(3))
        if d:
            return (d, 'day')
        d = _mk_month(m.group(1), m.group(2))       # день битый — грубее
        if d:
            return (d, 'month')

    m = _RE_COMPACT.match(s)                        # 20260729
    if m:
        d = _mk(m.group(1), m.group(2), m.group(3))
        if d:
            return (d, 'day')

    m = _RE_TXT_DAY.search(s)                       # RFC-822 и '12 августа 2026'
    if m:
        mon = _mon(m.group(2))
        if mon:
            d = _mk(m.group(3), mon, m.group(1))
            if d:
                return (d, 'day')

    m = _RE_RFC_2Y.search(s)                        # 'Wed, 08 Jul 26 08:00:28 +0300'
    if m:
        mon = _mon(m.group(2))
        if mon:
            yy = int(m.group(3))
            d = _mk(2000 + yy if yy < 70 else 1900 + yy, mon, m.group(1))
            if d:
                return (d, 'day')

    m = _RE_DOT_DAY.search(s)                       # 13.07.2026 / 13-07-26
    if m:
        a, b, y = int(m.group(1)), int(m.group(2)), m.group(3)
        if len(y) == 2:                             # 26 -> 2026, 98 -> 1998
            y = ('20' if int(y) < 70 else '19') + y
        if a > 12 >= b or a <= 12:                  # РФ-порядок: день первым
            d = _mk(y, b, a)
            if d:
                return (d, 'day')
        d = _mk(y, a, b)                            # источник дал MM.DD.YYYY
        if d:
            return (d, 'day')
        d = _mk_month(y, b if 1 <= b <= 12 else a)  # '31.02.2026' — день битый
        if d:
            return (d, 'month')

    m = _RE_ISO_MONTH.match(s)                      # '2026-07' (обрезка)
    if m:
        d = _mk_month(m.group(1), m.group(2))
        if d:
            return (d, 'month')

    m = _RE_DOT_MONTH.match(s)                      # '07.2026'
    if m:
        d = _mk_month(m.group(2), m.group(1))
        if d:
            return (d, 'month')

    m = _RE_TXT_MONTH.search(s)                     # 'август 2026'
    if m:
        mon = _mon(m.group(1))
        if mon:
            d = _mk_month(m.group(2), mon)
            if d:
                return (d, 'month')

    m = _RE_YEAR.match(s)                           # '2026', '2026 г.'
    if m:
        d = _mk(m.group(1), 1, 1)
        if d:
            return (d, 'year')

    return (None, None)


def normalize_date(raw):
    """'YYYY-MM-DD' или None. Тонкая обёртка над `normalize_date_full`.

    Ничего не выдумывает: нет года — нет даты (в '12 августа' года нет,
    подставлять текущий нельзя, новость может быть трёхлетней)."""
    return normalize_date_full(raw)[0]


def event_date_of(ts, updated_at='', published=''):
    """Что положить в `signals.event_date`. Возврат `(дата|None, origin)`.

    origin: 'ts' — разобрана дата источника (то, что нужно);
            'published' — дата из соседнего поля новости (news_scan.rec);
            'updated_at' — источник даты не дал, взята дата ЗАПИСИ в базу;
            '' — не удалось ничего.

    Порядок именно такой, потому что `ts` у 76% строк пуст (замер 16.09), а
    сортировать и считать свежесть по чему-то надо. Дата записи — верхняя
    оценка возраста события (новость не может быть моложе своей записи), и
    поле origin не даёт выдать её за дату события: `stage_ts`/отчёты должны
    показывать её отдельно."""
    for raw, origin in ((ts, 'ts'), (published, 'published'), (updated_at, 'updated_at')):
        d = normalize_date(raw)
        if d:
            return (d, origin)
    return (None, '')


