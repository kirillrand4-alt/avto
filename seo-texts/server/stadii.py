# «новый завод» без текстовых маркеров: 855 строк в базе, и это самый спорный
# тип. Ставим 2 (стройка), а не 1: новость про новый завод почти всегда выходит,
# когда стройка уже идёт (это и есть вывод части 2 ТЗ — поток поздний).
# Поменять одно число здесь — поменять поведение на всей базе.
NEW_PLANT_DEFAULT = 2

_RE_TYPE = None   # собирается лениво в _compile()
_RE_TEXT = None


def _compile():
    global _RE_TYPE, _RE_TEXT
    if _RE_TEXT is None:
        _RE_TEXT = [(st, re.compile(pat)) for st, pat in TEXT_RULES]
    if _RE_TYPE is None:
        _RE_TYPE = TYPE_RULES


def _norm(s):
    """Нижний регистр, ё->е, кавычки и пунктуация -> пробел, схлопывание."""
    s = str(s or '').lower().replace('ё', 'е')
    s = re.sub(r'[«»"\'`„“”‘’]', ' ', s)
    s = re.sub(r'[^0-9a-zа-я\-]+', ' ', s)
    return re.sub(r'\s+', ' ', s).strip()


def stage_of(event_type, what=''):
    """Стадия объекта: 0 не определена, 1 проект/анонс, 2 стройка, 3 пуск,
    4 действующее/расширение.

    Порядок решения:
      1. текст `what` по TEXT_RULES (первое совпадение) — факт сильнее ярлыка;
      2. тип события по TYPE_RULES (префикс);
      3. 0 — если ни одно правило не сработало. Ноль честный: лучше пустая
         стадия, чем красивая и неверная.

    Тип может быть составным ('новый завод|модернизация') — разбираем по '|'
    и берём МАКСИМАЛЬНУЮ стадию: если объект уже модернизируют, он работает.
    """
    _compile()
    t = _norm(what)
    # «проектная мощность» — характеристика действующего объекта, а не стадия
    # «проектирование». Убираем до матчинга, иначе правило (а) даст ложную 1.
    t = re.sub(r'проектн\w*\s+мощност\w*', ' ', t)
    for st, rx in _RE_TEXT:
        if rx.search(t):
            return st

    et = _norm(event_type)
    best = 0
    for part in et.split('|'):
        part = part.strip()
        if not part:
            continue
        for pref, st in _RE_TYPE:
            if part.startswith(pref):
                if pref == 'новый завод':
                    st = NEW_PLANT_DEFAULT
                best = max(best, st)
                break
    return best


def stage_name(stage):
    return STAGE_NAMES.get(int(stage or 0), STAGE_NAMES[0])


