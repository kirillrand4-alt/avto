    (1, r'разрешени\w*\s+на\s+строительств|выделен\w*\s+участок|земельн\w*\s+участок\s+под'),
    (1, r'намерение\s+совершить|крупн\w*\s+сделк'),
    # (б) СВЕРШИВШИЙСЯ ПУСК — только прошедшие/фактические формы.
    (3, r'введ[её]н\w*\s+в\s+эксплуатац|ввод\w*\s+в\s+эксплуатац|сдан\s+в\s+эксплуатац'),
    (3, r'запустил|запущен|запуск\b|пусконаладк|пусков\w*\s+комплекс'),
    (3, r'начал\w*\s+(выпуск|производств|работу)|выпустил\w*\s+перв|перв\w*\s+продукци'),
    (3, r'открыл\w*\s+(завод|цех|производств|лини)|состоялось\s+открытие|торжественн\w*\s+открыт'),
    # (в) СТРОЙКА идёт.
    (2, r'строительств|строится|строят|возвед|ведутся\s+строительн|смонтирован'),
