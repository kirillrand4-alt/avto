    (4, r'модерниз|техперевооружен|перевооружен|реконструкц|капитальн\w*\s+ремонт'),
    (4, r'расширен|расширя|наращива|увеличит\w*\s+мощност|увеличени\w*\s+мощност'),
    (4, r'ремонт|замен\w*\s+(шкаф|оборудован|узл|вал)|обновлени\w*\s+парка|дооснащ|оснащен'),
