"""Стадия объекта, ключ объекта и нормальная дата события (ТЗ, задачи 5 и 6).

Чистая библиотека: НИЧЕГО не пишет, в сеть не ходит, провайдера не зовёт,
зависимостей кроме стандартной библиотеки нет. Её зовут:

* `news_scan._persist_event` — на записи нового события (см. STADII-VEDENIE.md);
* `migraciya_stadii.py` — на разовой простановке задним числом;
* `lead_scoring.py` — чтобы свежесть считалась по `event_date`, а не по грязному `ts`.

Замер боевой базы 16.09.2026 (3 725 строк `signals`), на который опираются
правила ниже:

    ts: пусто 2848 | RFC-822 c +0300 329 | RFC-822 c GMT 151 |
        YYYY-MM-DD 144 | YYYY-MM 129 | DD.MM.YYYY 118 | 'YYYY-MM-DD HH:MM:SS' 6
    updated_at: 3725 из 3725 в виде YYYY-MM-DDTHH:MM:SS (дата ЗАПИСИ, не события)
    event_type: 40 различных значений, не 8 (в ТЗ сведены в группы)

То есть непустых `ts` всего 877, и это ШЕСТЬ разных форм. Отсюда два разных
понятия, которые важно не путать:

* `normalize_date` — честный разбор ОДНОЙ строки. Не разобралось — None,
  выдумывать дату нельзя (иначе свежесть соврёт, а по свежести звонят).
* `event_date_of` — что положить в колонку `event_date`: дата из `ts`, а если
  её нет — дата записи из `updated_at`, и тогда об этом говорит второе
  возвращаемое значение (origin). Подмена молча — запрещена.
"""
