def задачи():
    out = []
    for сегм, тт in ТИПЫ.items():
        for ш in ОБЩИЕ:
            out.append((сегм, 'РФ', ш.format(т=ПРОДУКЦИЯ[сегм])))
    for рег in РЕГИОНЫ:            # сначала регион целиком по всем сегментам: при обрыве бюджета охват ровнее
        for сегм, тт in ТИПЫ.items():
            for т in тт:
                out.append((сегм, рег, '%s %s' % (т, рег)))
    return out


def записать(з):
    with _лок:
        with io.open(ВЫХОД, 'a', encoding='utf-8') as f:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())


def чист(s):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', s or '')).strip()


СТОП = {'стоп': ''}
СЧЁТ = {'запросов': 0}


def один(сегм, рег, q):
    if СТОП['стоп']:
        return
    with _лок:
        if СЧЁТ['запросов'] >= ЛИМИТ:
            СТОП['стоп'] = 'лимит прогона %d' % ЛИМИТ
            return
        СЧЁТ['запросов'] += 1
    url = ('http://xmlriver.com/search_yandex/xml?user=%s&key=%s&groupby=100&query=%s'
           % (urllib.parse.quote(U), urllib.parse.quote(K), urllib.parse.quote(q)))
    xml, ошибка = '', ''
    for попытка in range(3):
        try:
            with НП.open(url, timeout=120) as r:
                xml = r.read(2000000).decode('utf-8', 'replace')
        except Exception as e:  # noqa: BLE001
            ошибка = repr(e)[:80]
            time.sleep(5)
            continue
        ош = re.search(r'<error[^>]*>(.*?)</error>', xml, re.S)
        ошибка = чист(ош.group(1)) if ош else ''
        if 'закончились средства' in ошибка:
            СТОП['стоп'] = ошибка
            return
        if 'перезапрос' in ошибка or 'свободных каналов' in ошибка:
            time.sleep(4)
            continue
        break
    доки = []
    for блок in re.findall(r'<doc>(.*?)</doc>', xml, re.S):
        u = чист((re.search(r'<url>(.*?)</url>', блок, re.S) or [None, ''])[1])
        т = чист((re.search(r'<title>(.*?)</title>', блок, re.S) or [None, ''])[1])
        п = чист((re.search(r'<passage>(.*?)</passage>', блок, re.S) or [None, ''])[1])
        if u:
            доки.append({'url': u, 'title': т[:160], 'текст': п[:300]})
    записать({'запрос': q, 'сегм': сегм, 'регион': рег, 'доки': доки,
              'итог': 'ok' if доки or not ошибка else 'ошибка', 'ошибка': ошибка})


def main():
    сделано = set()
    if os.path.exists(ВЫХОД):
        for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(s)
                if з.get('итог') == 'ok':
                    сделано.add(з['запрос'])
            except ValueError:
                pass
    очередь = [з for з in задачи() if з[2] not in сделано]
    print('запросов в матрице', len(задачи()), 'в очереди', len(очередь), flush=True)
    t0 = time.time()
    n = [0]

    def шаг(з):
        один(*з)
        n[0] += 1
        if n[0] % 100 == 0:
            print('%d/%d за %d мин' % (n[0], len(очередь), (time.time() - t0) / 60), flush=True)

    with ThreadPoolExecutor(ПОТОКОВ) as ex:
        list(ex.map(шаг, очередь))
    shutil.copyfile(ВЫХОД, os.path.join(r'C:\seostat\drop\drop-storage', 'poisk-serp.jsonl'))
    print('готово', json.dumps({'запросов': СЧЁТ['запросов'], 'стоп': СТОП['стоп']}, ensure_ascii=False), flush=True)


if __name__ == '__main__':
    main()
