r"""Каждому статусу — своя очередь, общая лента только для работы.

Владелец 24.08: «для всех остальных тоже своя очередь, чтобы раскидать общую
очередь». В ленте должно оставаться то, что ждёт действия: новый, назначен,
взят, позвонил, квалифицирован (его ещё надо отдать в Битрикс). Всё
остальное — результат или пауза: отдали в Bitrix, не квалифицирован, в
отпуске, автоответ, не интересно, закрыт. Они не удаляются, а живут своей
очередью, и над лентой стоит счётчик каждой со ссылкой.
"""
import json
import re

d = {}
п = r'C:\sender\sender\store.py'
т = open(п, encoding='utf-8').read()
старое = """            # «Отдали в Bitrix» прячем по той же причине (владелец 24.08):
            # лид ушёл в отдел продаж, в общей ленте ему делать нечего.
            sql.append("AND status NOT IN ('deleted', 'not_interested', "
                       "'in_bitrix')")"""
новое = """            # У КАЖДОГО СТАТУСА СВОЯ ОЧЕРЕДЬ (владелец 24.08: «для всех
            # остальных тоже своя очередь, чтобы раскидать общую»). В ленте
            # остаётся только то, что ждёт действия; результат и пауза уходят
            # в свои очереди и достаются фильтром по статусу.
            sql.append("AND status NOT IN (%s)"
                       % ",".join("'%s'" % s for s in СКРЫТЫЕ_ИЗ_ЛЕНТЫ))"""
if 'СКРЫТЫЕ_ИЗ_ЛЕНТЫ' in т:
    d['store'] = 'уже стояло'
elif старое in т:
    т = т.replace(старое, новое, 1)
    # сам список — рядом с классом, чтобы правился в одном месте
    маркер = 'class Store'
    i = т.index(маркер)
    список = ('''# Статусы, которых нет в общей ленте: у каждого своя очередь.
# «deleted» — убранные оператором, они не в счёт вообще; остальные пять —
# результат работы или пауза, и висеть среди неразобранных им незачем.
СКРЫТЫЕ_ИЗ_ЛЕНТЫ = ('deleted', 'not_interested', 'in_bitrix', 'unqualified',
                    'v_otpuske', 'avtootvet', 'closed')


''')
    т = т[:i] + список + т[i:]
    open(п, 'w', encoding='utf-8', newline='').write(т)
    d['store'] = 'заменено'
else:
    d['store'] = 'НЕ НАШЁЛ'
try:
    compile(т, п, 'exec')
    d['синтаксис_store'] = 'ок'
except SyntaxError as e:
    d['синтаксис_store'] = str(e)[:150]

# ---- фронт: строка счётчиков по всем спрятанным статусам
ф = r'C:\sender\_tmp\web-pravki\screens\Leads.tsx'
т2 = open(ф, encoding='utf-8').read()
ст = """  const скрытоНеинтересно = поСтатусам["not_interested"] || 0;
  // «Отдали в Bitrix» лента тоже прячет: лид ушёл в отдел продаж. Счётчик
  // рядом — чтобы спрятанное не выглядело пропажей (владелец 24.08).
  const скрытоBitrix = поСтатусам["in_bitrix"] || 0;"""
но = """  // СВОЯ ОЧЕРЕДЬ У КАЖДОГО СТАТУСА (владелец 24.08). Лента показывает только
  // то, что ждёт действия; остальные статусы — своими счётчиками со ссылкой,
  // чтобы спрятанное не выглядело пропажей. Список ПОВТОРЯЕТ store.СКРЫТЫЕ_ИЗ_ЛЕНТЫ
  // минус «deleted»: удалённые оператором в счёт работы не идут.
  const СВОИ_ОЧЕРЕДИ = ["in_bitrix", "qualified_hidden_placeholder",
                        "unqualified", "v_otpuske", "avtootvet",
                        "not_interested", "closed"]
    .filter((k) => k !== "qualified_hidden_placeholder");"""
if 'СВОИ_ОЧЕРЕДИ' in т2:
    d['front_список'] = 'уже стояло'
elif ст in т2:
    т2 = т2.replace(ст, но, 1)
    d['front_список'] = 'вставлено'
else:
    d['front_список'] = 'НЕ НАШЁЛ'

ст2 = re.search(r'\n\s*\{!mine && !status && скрытоНеинтересно > 0 && \('
                r'[\s\S]*?\n\s*\)\}\n\s*\{!mine && !status && скрытоBitrix > 0 && \('
                r'[\s\S]*?\n\s*\)\}', т2)
но2 = """
          {!mine && !status && СВОИ_ОЧЕРЕДИ.map((k) => {
            const n = поСтатусам[k] || 0;
            if (!n) return null;
            return (
              <span key={k}>
                {" · "}
                <button className="btn-link" title="показать их очередь"
                        onClick={() => setStatus(k)}>
                  {(ПОДПИСЬ[k] || k)}: {n}
                </button>
              </span>
            );
          })}"""
if ст2:
    т2 = т2[:ст2.start()] + но2 + т2[ст2.end():]
    d['front_счётчики'] = 'заменено'
elif 'СВОИ_ОЧЕРЕДИ.map' in т2:
    d['front_счётчики'] = 'уже стояло'
else:
    d['front_счётчики'] = 'НЕ НАШЁЛ блок кнопок'
if 'вставлено' in str(d.values()) or d.get('front_счётчики') == 'заменено':
    open(ф, 'w', encoding='utf-8', newline='').write(т2)
print(json.dumps(d, ensure_ascii=False, indent=1))
