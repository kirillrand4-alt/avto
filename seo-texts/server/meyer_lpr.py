def сторонний(з, сайт):
    """Контакт снят со страницы чужого сайта (справочник, новости, сайт партнёра)?"""
    url = з['Ссылка на источник']
    if not url:
        return ''
    дс = домен(url)
    if дс in РЕЕСТРЫ:
        return ''
    свой = домен(сайт) if сайт else ''
    if свой and (дс == свой or дс.split('.')[0] == свой.split('.')[0]):
        return ''
    дп = домен(з['E-mail']) if з['E-mail'] else ''
    if дп and дп not in ПУБЛИЧНЫЕ and дп.split('.')[0] == дс.split('.')[0]:
        return ''  # страница на домене самой почты (сайт холдинга/группы)
    return 'проверить: контакт со стороннего сайта (%s)' % дс


def витрина(п, комп):
    """Строки «дозвона» 2-й сессии (PARK-MEYER-DOZVON-2S.csv: витрина ЛПР, резюме, PDF
    договоров, карточки 223-ФЗ) — в формат контакта. Номер, стоящий в цитате ДО ФИО,
    помечается: обычно он соседа по тексту. Закупка старше 2023 г. — пометка «устарело?»."""
    out = []
    with open(п, encoding='utf-8-sig', newline='') as f:
        for x in csv.DictReader(f, delimiter=';'):
            к = комп.get(x['inn'])
            if not к:
                continue
            сырой = x['mobilnyy'] or x['rabochiy_telefon']
            if x.get('dobavochnyy'):
                сырой += ' доб. ' + x['dobavochnyy']
            номера = телефоны(сырой)
            if not номера:
                continue
            норм, тип, доб = номера[0]
            ярл, _ = роль(x['dolzhnost'])
            пров = []
            цит = x.get('citata') or ''
            фам = (x['fio'] or '').split()[0] if x['fio'] else ''
            ц = re.sub(r'\D', '', сырой.split('доб')[0])[-7:]
            м = re.search(r'\D{0,3}'.join(ц), цит) if ц else None
            if фам and м and фам in цит and м.start() < цит.find(фам):
                пров.append('номер в источнике стоит до ФИО — может быть соседа по тексту')
            if 'номера нет в цитате' in цит:
                пров.append('номер взят не рядом с ФИО')
            г = re.search(r'regNumber=3(\d\d)', x['ssylka'] or '')
            if г and 2000 + int(г.group(1)) < 2023:
                пров.append('контакт из закупки %d г. — мог устареть' % (2000 + int(г.group(1))))
            out.append({'Название': к['Название'], 'ИНН': x['inn'], 'Регион': к['Регион'], 'Сайт': к['Сайт'],
                        'Основной ОКВЭД': к['Основной ОКВЭД'], 'Выручка, руб': к['Выручка, руб'],
                        'Сегмент': к['Сегмент'], 'Попадание': к['Попадание'], 'ФИО': x['fio'],
                        'Должность': x['dolzhnost'], 'Роль': ярл, 'Приоритет': '1',
                        'Мобильный': норм if тип == 'мобильный' else '',
                        'Рабочий': (норм + ' доб. ' + доб) if тип == 'рабочий' and доб else (норм if тип == 'рабочий' else ''),
                        'Добавочный': доб, 'Номер не личный': '', 'E-mail': '',
                        'Источник': 'витрина ЛПР 2-й сессии: ' + (x['otkuda'] or '')[:60],
                        'Ссылка на источник': x['ssylka'], 'Проверка': '; '.join(пров)})
    return out


# Роль по подписи на странице (сверка 05.10): узкие формулировки — раньше общего «директор»,
# иначе региональный/финансовый директор, руководитель проекта и приёмная директора
# становятся «директором».
РОЛЬ_ПО_СТРАНИЦЕ = [
    (r'приёмн|приемн|секретар', 'общий/приёмная'),
    (r'общ(ий|ие|его) (номер|контакт|телефон)|без подписи|нет подписи|при[её]м заяв|консультац|диспетчер',
     'общий/приёмная'),
    (r'качеств|\bотк\b|лаборатор', 'качество'),
    (r'(?<!вод)(?<!водо)(?<!газо)(?<!тепло)(?<!электро)(?<!энерго)снабж|закуп|\bомто\b|\bмтс\b|поставщикам',
     'закупки'),
    (r'продаж|сбыт|тендерн|дилер|менеджер|отруб|маркет|клиент', 'продажи'),
    (r'финанс|бухгалт|экономи', 'бухгалтерия'),
    (r'персонал|кадр', 'кадры'),
    (r'региональн|развити|транспорт|логист|безопасн|юри|правов|проект|направлени|офиса|мероприят|'
     r'строител|капитальн|информац|связ(и|ям) с', 'прочее'),
    (r'главн\w* инженер|гл\.\s*инженер', 'главный инженер'),
    (r'технич\w* директор|техдиректор|тех\.\s*директор', 'технический директор'),
    (r'коммерческ\w* директор', 'коммерческий директор'),
    (r'главн\w* технолог|гл\.\s*технолог', 'главный технолог'),
    (r'технолог', 'технолог'),
    (r'главн\w* агроном|агроном', 'агроном'),
    (r'производств|\bцех', 'производство'),
    (r'инженер|механик|энергетик', 'инженер/механик'),
    (r'генеральн\w* директор|заместитель\s+(генерального\s+)?директора|^\s*директор|\bдиректор\b',
     'директор/руководитель'),
]
РОЛЬ_ПО_СТРАНИЦЕ_RX = [(re.compile(rx, re.I), ярл) for rx, ярл in РОЛЬ_ПО_СТРАНИЦЕ]
НЕ_ИМЯ = re.compile(r'^(Главн|Директор|Отдел|Руковод|Начальн|Заместит|Регион|Финанс|Менеджер|Специал|'
                    r'Инженер|Производ|Телефон|Приём|Прием|Бухгалт|Дирекц|Служб|Номер|Общий|Отдел|'
                    r'Коммерч|Техническ|Генеральн|Мастер|Ведущ|Старш|Зав)', re.I)


def роль_по_странице(т):
    for rx, ярл in РОЛЬ_ПО_СТРАНИЦЕ_RX:
        if rx.search(т or ''):
            return ярл
    return 'не указана'


def фио_из(т):
    """ФИО из подписи «Иванов Иван Иванович, Главный инженер» / «Директор: Петров П.П.»."""
    for м in re.finditer(r'[А-ЯЁ][а-яё]+(?:[ \u00a0]+(?:[А-ЯЁ][а-яё]+|[А-ЯЁ]\.\s?[А-ЯЁ]\.)){1,2}', т or ''):
        слова = м.group(0).split()
        if not any(НЕ_ИМЯ.match(с) for с in слова):
            return м.group(0)
    return ''


def сверка(п):
    """meyer-proverka.jsonl: последняя запись на номер (id = ИНН|номер|доб)."""
    out = {}
    with open(п, encoding='utf-8') as f:
        for s in f:
            try:
                з = json.loads(s)
            except ValueError:
                continue
            out[з['id']] = з
    return out


ЖУРНАЛ_СВЕРКИ = []


def применить_сверку(з, п, отсев_сверки):
    """Поправить контакт по живой странице. Вернёт False, если контакт надо убрать."""
    номер = з['Мобильный'] or з['Рабочий'].split(' доб.')[0]
    v = п.get('%s|%s|%s' % (з['ИНН'], номер, з.get('Добавочный') or ''))
    дата = time.strftime('%d.%m')
    if not v:
        з['Сверка'] = 'не сверялся'
        return True
    з['_id'] = v['id']
    ЖУРНАЛ_СВЕРКИ.append({
        '_id': v['id'], 'Название': з['Название'], 'ИНН': з['ИНН'],
        'Номер': (з['Мобильный'] or з['Рабочий']),
        'У нас было: ФИО': з['ФИО'], 'У нас было: должность': з['Должность'],
        'По странице: чей номер': v.get('кому', ''), 'Вердикт': v.get('вердикт', 'не сверен'),
        'Страница этой компании': v.get('компания_та', ''), 'Пояснение': v.get('почему', ''),
        'Проверено по': v.get('проверено_по', '') or ('живая страница' if v.get('страница') == 'ok'
                                                      else v.get('страница', ''))[:120],
        'Ссылка': v.get('url', '')})
    if 'вердикт' not in v:
        з['Сверка'] = 'не удалось сверить: ' + (v.get('страница') if v.get('страница') != 'ok'
                                                  else 'номера нет на странице')[:60]
        return True
    if v.get('компания_та') == 'нет':
        отсев_сверки['страница другой компании'] += 1
        return False
    if v.get('есть') is False:
        отсев_сверки['номера нет во фрагменте страницы'] += 1
        return False
    кому = (v.get('кому') or '').strip()
    фио = фио_из(кому)
    if v['вердикт'] == 'верно':
        if not з['ФИО'] and фио:
            з['ФИО'] = фио
        з['Сверка'] = 'сверено со страницей %s: верно' % дата
        return True
    было = з['Должность']
    з['Роль'] = роль_по_странице(кому)
    з['Должность'] = (re.sub(re.escape(фио), '', кому).strip(' ,—-:') if фио else кому)[:120] or з['Роль']
    з['ФИО'] = фио
    з['Сверка'] = 'исправлено по странице %s (было: %s)' % (дата, было[:40])
    return True


def main(п_комп, п_конт, п_out, *доп):
    комп = {к['ИНН']: к for к in читать(п_комп)}
    убраны_сделки = collections.Counter()  # компаний базы; из файла номеров — ниже
    по_инн = collections.defaultdict(list)
    доп_строки, пров = [], {}
    for п in доп:
        if п.endswith('.json'):
            сд = сделки(п)
            for инн in list(комп):
                if инн in сд:
                    убраны_сделки[сд[инн]] += 1
                    del комп[инн]
        elif п.endswith('.jsonl'):
            пров = сверка(п)
        else:
            доп_строки += витрина(п, комп)
    отсев_сверки = collections.Counter()
    видели = {}
    for з in читать(п_конт) + доп_строки:
        if (з['Мобильный'] and з.get('Номер не личный') != 'да') or (з['Рабочий'] and з.get('Добавочный')):
            ключ = (з['ИНН'], з['Мобильный'] or з['Рабочий'])
            if ключ in видели:  # тот же номер из второго источника: дописываем ФИО и должность
                б = видели[ключ]
                if not б['ФИО'] and з['ФИО'] and not б.get('Сверка', '').startswith(('сверено', 'исправлено')):
                    б.update({к: з[к] for к in ('ФИО', 'Должность', 'Роль', 'Источник',
                                                'Ссылка на источник', 'Проверка')})
                continue
            видели[ключ] = з
            if пров and not применить_сверку(з, пров, отсев_сверки):
                continue
            по_инн[з['ИНН']].append(з)

    оставлено, отсев = [], collections.Counter()
    for инн, строки in по_инн.items():
        к = комп.get(инн)
        if not к:
            continue
        сегм = к['Сегмент'].split(' | ')
        можно = set()
        for с in сегм:
            можно |= РОЛИ.get(с, set())
        for з in строки:
            if not з['Проверка']:
                з['Проверка'] = сторонний(з, к['Сайт'])
        прямые = [з for з in строки if з['Роль'] in можно]
        for з in прямые:
            з['Тип контакта'] = 'ЛПР по списку'
        # запасной выход через сотрудника — только настоящим элеваторам (по основному ОКВЭД)
        if not прямые and '4 элеваторы' in к['Сегмент по основному ОКВЭД']:
            прямые = [з for з in строки if з['Роль'] in ЗАПАСНЫЕ_ЭЛЕВАТОР
                      or (з['Роль'] == 'не указана' and з['ФИО'])]
            for з in прямые:
                з['Тип контакта'] = 'элеватор: выход на ЛПР через сотрудника'
        for з in строки:
            if з not in прямые:
                отсев[з['Роль']] += 1
        оставлено.extend(прямые)

    инн_ост = {з['ИНН'] for з in оставлено}
    компании = [комп[i] for i in инн_ост]
    for к in компании:
        к['В какой базе обзвона'] = БАЗА.get(к['В какой базе обзвона'], 'нет в базе обзвона')
    компании.sort(key=lambda к: (ПОРЯДОК.get(к['Попадание'], 9), к['Сегмент'].split(' | ')[0],
                                -float(к['Выручка, руб'] or 0)))
    место = {к['ИНН']: i for i, к in enumerate(компании)}
    оставлено.sort(key=lambda з: (место[з['ИНН']], not з.get('Сверка', '').startswith(('сверено', 'исправлено')),
                                  bool(з['Проверка']), int(з['Приоритет'] or 9), not з['ФИО'], not з['Мобильный']))

    # лучший контакт компании — первый после сортировки
    лучший, число = {}, collections.Counter()
    for з in оставлено:
        лучший.setdefault(з['ИНН'], з)
        число[з['ИНН']] += 1
    for к in компании:
        з = лучший[к['ИНН']]
        к.update({'ЛПР: ФИО': з['ФИО'], 'ЛПР: должность': з['Должность'], 'ЛПР: мобильный': з['Мобильный'],
                  'ЛПР: рабочий с добавочным': з['Рабочий'], 'ЛПР: источник': з['Источник'],
                  'ЛПР: ссылка': з['Ссылка на источник'], 'ЛПР: проверка': з['Проверка'],
                  'ЛПР: сверка со страницей': з.get('Сверка', ''),
                  'Контактов ЛПР': число[к['ИНН']],
                  'Тип контакта': з['Тип контакта']})

    сегм_счёт = collections.Counter()
    for к in компании:
        for с in к['Сегмент'].split(' | '):
            сегм_счёт[с] += 1
    роли = collections.Counter(з['Роль'] for з in оставлено)
    с_фио = sum(1 for з in оставлено if з['ФИО'])
    комп_с_фио = len({з['ИНН'] for з in оставлено if з['ФИО']})
    с_моб = sum(1 for з in оставлено if з['Мобильный'])
    с_доб = sum(1 for з in оставлено if з['Добавочный'])
    со_ссылкой = sum(1 for з in оставлено if з['Ссылка на источник'])
    провер = sum(1 for з in оставлено if з['Проверка'])
    отсев_после_сверки = sum(1 for стр in по_инн.values() for з in стр
                             if з.get('Сверка', '').startswith('исправлено') and з not in оставлено)
    все_пров = sum(1 for к in компании if лучший[к['ИНН']]['Проверка'])
    запасных = len({з['ИНН'] for з in оставлено if з['Тип контакта'].startswith('элеватор')})

    wb = Workbook(write_only=True)
    ws = wb.create_sheet('Сводка')
    ws.column_dimensions['A'].width = 70
    ws.column_dimensions['B'].width = 14
    b = Font(bold=True)

    def ж(т):
        cell = WriteOnlyCell(ws, value=т)
        cell.font = b
        return cell

    def текст(т):
        cell = WriteOnlyCell(ws, value=т)
        cell.alignment = Alignment(wrap_text=True, vertical='top')
        ws.append([cell])
    ws.append([ж('База под Meyer — ЛПР с мобильным или рабочим с добавочным (на %s)'
                 % time.strftime('%d.%m.%Y'))])
    ws.append(['Компаний с хотя бы одним контактом ЛПР', len(компании)])
    if убраны_сделки:
        ws.append(['  (из базы убраны компании, где идёт сделка: %s)' % ', '.join(
            '%s — %d' % (к, n) for к, n in убраны_сделки.most_common())])
    ws.append(['  из них элеваторы, где есть только сотрудник для выхода на ЛПР', запасных])
    ws.append(['  из них есть ЛПР с ФИО', комп_с_фио])
    ws.append(['Контактов ЛПР всего', len(оставлено)])
    ws.append(['  с ФИО', с_фио])
    ws.append(['  мобильных', с_моб])
    ws.append(['  рабочих с добавочным', с_доб])
    ws.append(['  со ссылкой на источник', со_ссылкой])
