# -*- coding: utf-8 -*-
"""База под Meyer: оставить только ЛПР по списку ролей коллеги (05.10).

Берёт CSV из meyer_baza.py и оставляет контакты, у которых есть МОБИЛЬНЫЙ или
РАБОЧИЙ С ДОБАВОЧНЫМ (решение владельца 05.10: только номера, ведущие к нужному
человеку; почты и городские без добавочного — нет) и роль входит в список своего
сегмента. Мобильный с пометкой базы «номер не личный» не считается. Общие номера, приёмные и номера
без роли убираются. Элеваторы: если прямых ЛПР нет — допускаются другие
сотрудники (бухгалтерия, продажи, инженеры, кадры, именные без роли), но не
приёмная. Компании без единого такого контакта в базу не попадают.

    python meyer_lpr.py meyer-kompanii-ДДММ.csv meyer-kontakty-ДДММ.csv out.xlsx
"""
import collections
import sys
import time

from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Alignment, Font

from meyer_baza import ПУБЛИЧНЫЕ, домен
from meyer_xlsx import БАЗА, ПОРЯДОК, описание_источника, лист, читать

ДИР = {'директор/руководитель', 'генеральный директор'}
ПИЩЕВЫЕ = ДИР | {'главный инженер', 'технический директор', 'директор по производству',
                 'производство', 'главный технолог', 'технолог', 'качество', 'закупки'}
ЭЛЕВАТОРЫ = ДИР | {'главный инженер', 'главный технолог', 'заведующий элеватором/производством',
                   'производство', 'агроном', 'главный агроном', 'закупки'}
СЕМЕНОВОДЫ = ДИР | {'главный агроном', 'агроном', 'производство', 'директор по производству',
                    'семеноводство', 'главный инженер', 'закупки'}
# «руководитель, коммерческий директор, закупки, производство, качество, агрономы
#  и другие доступные ЛПР» — все ЛПР-роли
ЭКСПОРТЁРЫ = ПИЩЕВЫЕ | ЭЛЕВАТОРЫ | СЕМЕНОВОДЫ | {'коммерческий директор'}
РОЛИ = {
    '1 экспортёры': ЭКСПОРТЁРЫ,
    '2 семеноводы': СЕМЕНОВОДЫ,
    '3 пищевые': ПИЩЕВЫЕ,
    '4 элеваторы': ЭЛЕВАТОРЫ,
    # для орехов и ягод отдельного списка нет: переработка — как пищевые, плюс агрономы садов
    '5 орехи': ПИЩЕВЫЕ | {'агроном', 'главный агроном'},
    '6 ягоды': ПИЩЕВЫЕ | {'агроном', 'главный агроном'},
    '7 доп. ОКВЭД (предложено)': ЭКСПОРТЁРЫ,
}
ЗАПАСНЫЕ_ЭЛЕВАТОР = {'бухгалтерия', 'продажи', 'инженер/механик', 'кадры'}
# реестры и площадки: контакт оттуда привязан к компании по ИНН, это не сторонний сайт
РЕЕСТРЫ = {'zakupki.gov.ru', 'checko.ru', 'nalog.ru', 'list-org.com', 'rusprofile.ru', 'tender.pro',
           'gosnadzor.ru', 'roseltorg.ru', 'etpgpb.ru', 'b2b-center.ru', 'fabrikant.ru', 'zakupki360.ru'}


def сторонний(з, сайт):
    """Контакт снят со страницы чужого сайта (справочник, новости, сайт партнёра)?"""
    url = з['Ссылка на источник']
    if not url:
        return ''
    дс = домен(url)
    if дс in РЕЕСТРЫ:
        return ''
    свой = домен(сайт) if сайт else ''
    if свой and (дс == свой or дс.split('.')[0] == свой.split('.')[0]):
        return ''
    дп = домен(з['E-mail']) if з['E-mail'] else ''
    if дп and дп not in ПУБЛИЧНЫЕ and дп.split('.')[0] == дс.split('.')[0]:
        return ''  # страница на домене самой почты (сайт холдинга/группы)
    return 'проверить: контакт со стороннего сайта (%s)' % дс


def main(п_комп, п_конт, п_out):
    комп = {к['ИНН']: к for к in читать(п_комп)}
    по_инн = collections.defaultdict(list)
    for з in читать(п_конт):
        if (з['Мобильный'] and з.get('Номер не личный') != 'да') or (з['Рабочий'] and з.get('Добавочный')):
            по_инн[з['ИНН']].append(з)

    оставлено, отсев = [], collections.Counter()
    for инн, строки in по_инн.items():
        к = комп.get(инн)
        if not к:
            continue
        сегм = к['Сегмент'].split(' | ')
        можно = set()
        for с in сегм:
            можно |= РОЛИ.get(с, set())
        for з in строки:
            if not з['Проверка']:
                з['Проверка'] = сторонний(з, к['Сайт'])
        прямые = [з for з in строки if з['Роль'] in можно]
        for з in прямые:
            з['Тип контакта'] = 'ЛПР по списку'
        # запасной выход через сотрудника — только настоящим элеваторам (по основному ОКВЭД)
        if not прямые and '4 элеваторы' in к['Сегмент по основному ОКВЭД']:
            прямые = [з for з in строки if з['Роль'] in ЗАПАСНЫЕ_ЭЛЕВАТОР
                      or (з['Роль'] == 'не указана' and з['ФИО'])]
            for з in прямые:
                з['Тип контакта'] = 'элеватор: выход на ЛПР через сотрудника'
        for з in строки:
            if з not in прямые:
                отсев[з['Роль']] += 1
        оставлено.extend(прямые)

    инн_ост = {з['ИНН'] for з in оставлено}
    компании = [комп[i] for i in инн_ост]
    for к in компании:
        к['В какой базе обзвона'] = БАЗА.get(к['В какой базе обзвона'], 'нет в базе обзвона')
    компании.sort(key=lambda к: (ПОРЯДОК.get(к['Попадание'], 9), к['Сегмент'].split(' | ')[0],
                                -float(к['Выручка, руб'] or 0)))
    место = {к['ИНН']: i for i, к in enumerate(компании)}
    оставлено.sort(key=lambda з: (место[з['ИНН']], bool(з['Проверка']), int(з['Приоритет'] or 9),
                                  not з['ФИО'], not з['Мобильный']))

    # лучший контакт компании — первый после сортировки
    лучший, число = {}, collections.Counter()
    for з in оставлено:
        лучший.setdefault(з['ИНН'], з)
        число[з['ИНН']] += 1
    for к in компании:
        з = лучший[к['ИНН']]
        к.update({'ЛПР: ФИО': з['ФИО'], 'ЛПР: должность': з['Должность'], 'ЛПР: мобильный': з['Мобильный'],
                  'ЛПР: рабочий с добавочным': з['Рабочий'], 'ЛПР: источник': з['Источник'],
                  'ЛПР: ссылка': з['Ссылка на источник'], 'ЛПР: проверка': з['Проверка'],
                  'Контактов ЛПР': число[к['ИНН']],
                  'Тип контакта': з['Тип контакта']})

    сегм_счёт = collections.Counter()
    for к in компании:
        for с in к['Сегмент'].split(' | '):
            сегм_счёт[с] += 1
    роли = collections.Counter(з['Роль'] for з in оставлено)
    с_фио = sum(1 for з in оставлено if з['ФИО'])
    комп_с_фио = len({з['ИНН'] for з in оставлено if з['ФИО']})
    с_моб = sum(1 for з in оставлено if з['Мобильный'])
    с_доб = sum(1 for з in оставлено if з['Добавочный'])
    со_ссылкой = sum(1 for з in оставлено if з['Ссылка на источник'])
    провер = sum(1 for з in оставлено if з['Проверка'])
    все_пров = sum(1 for к in компании if лучший[к['ИНН']]['Проверка'])
    запасных = len({з['ИНН'] for з in оставлено if з['Тип контакта'].startswith('элеватор')})

    wb = Workbook(write_only=True)
    ws = wb.create_sheet('Сводка')
    ws.column_dimensions['A'].width = 70
    ws.column_dimensions['B'].width = 14
    b = Font(bold=True)

    def ж(т):
        cell = WriteOnlyCell(ws, value=т)
        cell.font = b
        return cell

    def текст(т):
        cell = WriteOnlyCell(ws, value=т)
        cell.alignment = Alignment(wrap_text=True, vertical='top')
        ws.append([cell])
    ws.append([ж('База под Meyer — ЛПР с мобильным или рабочим с добавочным (на %s)'
                 % time.strftime('%d.%m.%Y'))])
    ws.append(['Компаний с хотя бы одним контактом ЛПР', len(компании)])
    ws.append(['  из них элеваторы, где есть только сотрудник для выхода на ЛПР', запасных])
    ws.append(['  из них есть ЛПР с ФИО', комп_с_фио])
    ws.append(['Контактов ЛПР всего', len(оставлено)])
    ws.append(['  с ФИО', с_фио])
    ws.append(['  мобильных', с_моб])
    ws.append(['  рабочих с добавочным', с_доб])
    ws.append(['  со ссылкой на источник', со_ссылкой])
    ws.append(['  с пометкой «проверить» (чужой домен почты или сторонний сайт)', провер])
    ws.append(['Компаний, где все контакты ЛПР с пометкой «проверить»', все_пров])
    ws.append([])
    ws.append([ж('Сегмент'), ж('Компаний')])
    for с in sorted(сегм_счёт):
        ws.append([с, сегм_счёт[с]])
    ws.append([])
    ws.append([ж('Роль'), ж('Контактов')])
    for р, n in роли.most_common():
        ws.append([р, n])
    ws.append([])
    ws.append([ж('Убрано (мобильные и добавочные, не прошедшие по роли)'), ж('Контактов')])
    for р, n in отсев.most_common():
        ws.append([р, n])
    ws.append([])
    ws.append([ж('Правила отбора')])
    for т in (
            'Пищевые: директор/гендиректор, гл. инженер, техдиректор, директор/начальник производства, '
            'гл. технолог/технолог, качество, закупки.',
            'Элеваторы: директор, гл. инженер, гл. технолог, заведующий элеватором/производством, '
            'начальник производства, агроном, закупки. Если таких нет — другие сотрудники (бухгалтерия, '
            'продажи, инженеры, кадры, сотрудники с ФИО), но не приёмная и не общий номер. Запасной '
            'вариант — только для элеваторов по основному ОКВЭД.',
            '«Проверить»: почта на чужом домене или контакт снят со стороннего сайта (справочник, '
            'новость, сайт партнёра). Часто это сайт холдинга и контакт верный, но бывает и чужой. '
            'Такие контакты стоят последними внутри компании.',
            'Семеноводы: директор, гл. агроном/агроном, руководитель производства, семеноводство, '
            'гл. инженер, закупки.',
            'Экспортёры: все ЛПР-роли из списков выше плюс коммерческий директор.',
            'Орехи и ягоды (отдельного списка не было): как пищевые плюс агрономы.',
            'Компания из нескольких сегментов — объединение ролей её сегментов.',
            'Только мобильные и рабочие с добавочным. Почты и городские номера без добавочного убраны, '
            'даже если подписаны нужной должностью.',
            'Номер должен вести к нужному человеку: роль или ФИО взяты из того же места, где номер '
            '(подпись на сайте, карточка закупки, справочник). Мобильные без роли убраны.',
            'Мобильный с пометкой базы «номер не личный» убран.'):
        текст(т)

    поля_комп = ['Название', 'ИНН', 'Регион', 'Город', 'Сайт', 'Основной ОКВЭД', 'Доп. ОКВЭД',
                 'Описание', 'Выручка, руб', 'Год выручки', 'Сегмент', 'Сегмент по основному ОКВЭД',
                 'Попадание', 'В какой базе обзвона', 'ЛПР: ФИО', 'ЛПР: должность', 'ЛПР: мобильный',
                 'ЛПР: рабочий с добавочным', 'ЛПР: источник', 'ЛПР: ссылка', 'ЛПР: проверка',
                 'Контактов ЛПР', 'Тип контакта']
    лист(wb, 'Компании', поля_комп, компании,
         [34, 12, 20, 14, 22, 9, 30, 40, 15, 7, 22, 18, 16, 14, 26, 20, 16, 24, 20, 34, 30, 9, 20])
    поля_конт = ['Название', 'ИНН', 'Регион', 'Сайт', 'Основной ОКВЭД', 'Выручка, руб', 'Сегмент',
                 'Попадание', 'ФИО', 'Должность', 'Роль', 'Тип контакта', 'Мобильный',
                 'Рабочий с добавочным', 'Источник', 'Ссылка на источник', 'Проверка']
    for з in оставлено:
        з['Рабочий с добавочным'] = з['Рабочий']
    лист(wb, 'Контакты', поля_конт, оставлено,
         [34, 12, 20, 22, 9, 15, 22, 16, 26, 22, 20, 20, 16, 24, 22, 40, 30])
    wi = wb.create_sheet('Источники')
    wi.column_dimensions['A'].width = 44
    wi.column_dimensions['C'].width = 80
    wi.append(['Источник (как в колонке)', 'Контактов', 'Что это'])
    for ист, n in collections.Counter(з['Источник'] for з in оставлено).most_common():
        wi.append([ист, n, описание_источника(ист)])
    wb.save(п_out)
    print('компаний', len(компании), 'контактов', len(оставлено), 'с ФИО', с_фио, 'комп с ФИО', комп_с_фио,
          'моб', с_моб, 'доб', с_доб, 'ссылка', со_ссылкой, 'проверить', провер, 'все_пров', все_пров,
          'элев-запасных', запасных)
    print('сегменты', dict(sorted(сегм_счёт.items())))
    print('роли', роли.most_common())
    print('убрано', отсев.most_common(12))


if __name__ == '__main__':
    main(*sys.argv[1:4])
