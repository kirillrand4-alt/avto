def токены(s):
    return [w for w in re.split(r'[^0-9a-zа-яё]+', (s or '').lower()) if w]


def свой(обладатель, ключи):
    """Патентообладатель — ЭТА компания?

    Требуем полного вхождения одного из ключей ОТДЕЛЬНЫМИ СЛОВАМИ. Так
    отсекается и однофамилец, и география: «Калужский НИИ» больше не проходит
    как «Калужский турбинный завод», а «микронасос» — как «Микрон».
    """
    т = set(токены(обладатель))
    if not т:
        return False, 'патентообладатель пуст'
    for k in ключи:
        нужно = токены(k)
        if нужно and all(w in т for w in нужно):
            return True, 'в поле патентообладателя стоит «%s»' % k
    return False, 'нет совпадения'


def выдача(запрос, стр=0, n=10):
    """Как EC._serp_urls, но с постраничностью — своего поиска у баз нет."""
    user = os.environ.get('XMLRIVER_USER', '')
    key = os.environ.get('XMLRIVER_KEY', '')
    if not (user and key):
        return []
    u = ('http://xmlriver.com/search_yandex/xml?user=' + urllib.parse.quote(user)
         + '&key=' + urllib.parse.quote(key) + '&domain=ru&device=desktop'
         + ('&page=%d' % стр if стр else '')
         + '&query=' + urllib.parse.quote(запрос))
    try:
        xml = EC._DIRECT.open(u, timeout=35).read().decode('utf-8', 'replace')
    except Exception:  # noqa: BLE001
        return []
    return [x.strip().replace('&amp;', '&')
            for x in re.findall(r'<url>(.*?)</url>', xml, re.S)][:n]


_ПАТСТР = re.compile(r'freepatent\.ru/patents/\d+|findpatent\.ru/patent/\d+/\d+',
                     re.I)
_АВТ = re.compile(r'Автор(?:\(ы\)|ы)?\s*:\s*(.{2,900}?)\s*'
                  r'(?:Патентооблад|Заявител|Приоритет)', re.S | re.I)
_ОБЛ = re.compile(r'Патентооблад\w*(?:\(и\))?\s*:\s*(.{2,600}?)\s*'
                  r'(?:Приоритет|Изобретен|Реферат|Формула|Полезная|Устройство|$)',
                  re.S | re.I)
_ЧИСТ = re.compile(r'\((?:RU|SU|US|DE|UA|BY|KZ|FR|GB|JP|CH|IT|SE)\)|&#\d+;')
_ЧЕЛ = re.compile(r'^([А-ЯЁ][а-яё\-]{2,})\s+([А-ЯЁ][а-яё]+|[А-ЯЁ]\.)\s*'
                  r'([А-ЯЁ][а-яё]+|[А-ЯЁ]\.)?$')


def разобрать(t):
    """([авторы], патентообладатель, сырой_блок_авторов) со страницы базы."""
    ma = _АВТ.search(t or '')
    mo = _ОБЛ.search(t or '')
    обл = re.sub(r'\s+', ' ', _ЧИСТ.sub(' ', mo.group(1))).strip() if mo else ''
    сыро = re.sub(r'\s+', ' ', ma.group(1))[:300] if ma else ''
    авторы = []
    if ma:
        for кус in re.split(r'[,;]| и ', _ЧИСТ.sub(' ', ma.group(1))):
            кус = re.sub(r'\s+', ' ', кус).strip(' .')
            if 5 < len(кус) < 70 and _ЧЕЛ.match(кус):
                авторы.append(кус)
    return авторы, обл, сыро


def читать(u):
    try:
        h, m, _meta = EC._fetch_site(u)
    except Exception as ex:  # noqa: BLE001
        return u, '', 'ИСКЛ ' + type(ex).__name__, 0
    t = EC._текст(h or '')
    return u, t, m, len(h or '')


def сделано():
    было = set()
    if os.path.exists(ПОТОК):
        for ln in io.open(ПОТОК, encoding='utf-8', errors='replace'):
            try:
                было.add(str(json.loads(ln).get('inn')))
            except Exception:  # noqa: BLE001
                pass
    return было


def компания(inn, имя, ключи):
    out = {'inn': inn, 'имя': имя, 'ссылок': 0, 'прочитано': 0,
           'пустых_страниц': 0, 'свои_патенты': [], 'чужих_отсеяно': 0,
           'авторы': [], 'примеры': [], 'отсеянные_примеры': [],
           'авторов_на_чужих': 0}
    соб = []
    for з in (f'site:freepatent.ru "{имя}"', f'site:findpatent.ru "{имя}"'):
        for x in выдача(з):
            if _ПАТСТР.search(x) and x not in соб:
                соб.append(x)
        time.sleep(0.3)
    if len(соб) < 6:
        for x in выдача(f'"{имя}" патентообладатель патент авторы изобретения'):
            if _ПАТСТР.search(x) and x not in соб:
                соб.append(x)
    соб = соб[:12]
    out['ссылок'] = len(соб)
    страницы = []
    if соб:
        with ThreadPoolExecutor(max_workers=6) as п:
            страницы = list(п.map(читать, соб))
    было = set()
    for u, t, режим, дл in страницы:
        if not t or len(t) < 400:
            out['пустых_страниц'] += 1
            out.setdefault('пример_пустой',
                           {'url': u[:90], 'html': дл, 'текст': len(t or ''),
                            'режим': режим, 'начало': (t or '')[:120]})
            continue
        out['прочитано'] += 1
        авторы, обл, сыро = разобрать(t)
        да, почему = свой(обл, ключи)
        if not да:
            out['чужих_отсеяно'] += 1
            out['авторов_на_чужих'] += len(авторы)
            if len(out['отсеянные_примеры']) < 3:
                out['отсеянные_примеры'].append(
                    {'url': u[:80], 'обладатель': обл[:100],
                     'авторов_на_странице': len(авторы), 'сырой_блок': сыро[:140]})
            continue
        out['свои_патенты'].append(u[:90])
        for ч in авторы:
            ключ = ч.lower().replace('.', '').replace(' ', '')
            if ключ in было:
                continue
            было.add(ключ)
            out['авторы'].append(ч)
            if len(out['примеры']) < 8:
                out['примеры'].append({'фио': ч, 'обладатель': обл[:100],
                                       'основание': почему, 'ссылка': u[:90]})
    out['авторов'] = len(out['авторы'])
    return out


def main():
    # сверка обладателя менялась — накопленное по старому правилу негодно
    if '--сброс' in sys.argv and os.path.exists(ПОТОК):
        os.remove(ПОТОК)
        print('поток сброшен')
    гот = сделано()
    ф = io.open(ПОТОК, 'a', encoding='utf-8')
    прошло = 0
    for inn, имя, ключи in ВЫБОРКА:
        if inn in гот:
            continue
        if time.time() - НАЧАЛО > БЮДЖЕТ:
            break
        try:
            r = компания(inn, имя, ключи)
        except Exception as ex:  # noqa: BLE001
            r = {'inn': inn, 'имя': имя,
                 'ошибка': '%s: %s' % (type(ex).__name__, str(ex)[:90])}
        ф.write(json.dumps(r, ensure_ascii=False) + '\n')
        ф.flush()
        os.fsync(ф.fileno())
        прошло += 1
        print('OK %-32s ссылок=%d прочит=%d своих=%d чужих=%d авторов=%d %s'
              % (имя[:32], r.get('ссылок', 0), r.get('прочитано', 0),
                 len(r.get('свои_патенты') or []), r.get('чужих_отсеяно', 0),
                 r.get('авторов', 0), r.get('ошибка') or ''))
    ф.close()
    print('ПРОГРЕСС: за проход %d, всего %d из %d'
          % (прошло, len(сделано()), len(ВЫБОРКА)))


if __name__ == '__main__':
    main()
