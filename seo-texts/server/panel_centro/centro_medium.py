"""Правила отбора фактов для базы центробежных воздушных компрессоров."""
from __future__ import annotations

import re

# Любое явное упоминание воздуха важнее других слов: записи вроде
# «газ и воздух» или «газовоздушная смесь» сохраняются.
_AIR_RE = re.compile(r"(?:воздух\w*|воздуш\w*|\bair\b)", re.I)

# Пустые и неопределённые значения не считаются доказательством нецелевой среды.
_UNKNOWN_RE = re.compile(
    r"(?:неизвест|не\s*указ|не\s*назван|не\s*определ|нет\s*данн|"
    r"данн\w*\s*нет|информац\w*\s*нет|среда\s+не\s+названа|"
    r"^\s*[-—–]+\s*$)",
    re.I,
)

# Отсекаются только явно не воздушные среды. Запись всё равно сохраняется,
# когда одновременно найден воздух.
_NON_AIR_RE = re.compile(
    r"(?:\bгаз\w*|азот\w*|кислород\w*|водород\w*|метан\w*|пропан\w*|"
    r"бутан\w*|этилен\w*|ацетилен\w*|аммиак\w*|аргон\w*|гелий\w*|"
    r"неон\w*|фреон\w*|хладагент\w*|сероводород\w*|углекисл\w*|"
    r"диоксид\s+углерод\w*|\bco2\b|хлор\w*|водян\w*\s+пар\w*|"
    r"\bпар\w*|\bвод\w*|жидк\w*|нефт\w*)",
    re.I,
)

# Выявление газового компрессора в тексте нужно для строк, где поле среды
# пустое или нормализовано как «среда не названа».
_GAS_COMPRESSOR_RE = re.compile(
    r"(?:газов\w*\s+компрессор\w*|компрессор\w*.{0,80}(?:природн\w*\s+газ|"
    r"метан\w*|пропан\w*|бутан\w*|водород\w*|азот\w*|кислород\w*))",
    re.I | re.S,
)

# Насосы не относятся к базе компрессоров. Сильным признаком считается слово
# «насос» в модели/типе/статусе. В длинном тексте оно исключает строку только
# тогда, когда там нет одновременного упоминания компрессора.
_PUMP_RE = re.compile(r"насос\w*", re.I)

# КЛАССЫ МУСОРА, найденные тремя сессиями на живых данных. Каждый из них
# проходил прежний фильтр: слово похоже на наше, а машина чужая.
#   * садовая и ранцевая воздуходувка — 482 факта, инструмент, а не машина.
#     Ловится и «уборочная техника … для содержания территории»: именно эта
#     формулировка провела мимо отсева закупку МБУ допобразования;
#   * паровая турбина и турбоагрегат ТЭЦ — 2067 фактов: «турбоагрегат
#     ПТ 60-90/13» это турбина с генератором, а не компрессор;
#   * вентилятор и дымосос — 104;
#   * вихревая воздуходувка — 64: принцип не центробежный;
#   * тепловозный турбокомпрессор ТК-23С — надув дизеля тепловоза;
#   * двигатель внутреннего сгорания (ДВС КАМАЗ и подобное).
_JUNK_RULES = (
    ("garden", re.compile(
        r"(?:садов\w*|ранцев\w*|бензинов\w*\s+воздуходувк\w*|"
        r"снегоуборщик\w*|газонокосилк\w*|мотокос\w*|"
        r"уборочн\w*\s+техник\w*|содержани\w*\s+территори\w*|"
        r"благоустройств\w*\s+территори\w*)", re.I)),
    ("steam_turbine", re.compile(
        r"(?:паров\w*\s+турбин\w*|турбоагрегат\w*\s*(?:пт|тп|к|р|т)[\s-]?\d|"
        r"\bпт[\s-]?\d{2,3}[/-]|турбогенератор\w*)", re.I)),
    # ДЫМОСОСЫ. Голый шаблон «ДН-\d\d» пришлось убрать: он снял живую
    # компанию, у которой в той же строке стоит НАША турбовоздуходувка ТВ-200,
    # а «ДН-500» там — дозатор весовой, не дымосос. Марка из двух букв слишком
    # дешева как признак; настоящий дымосос называет себя словом или маркой ВДН.
    ("fan", re.compile(r"(?:дымосос\w*|вентилятор\w*\s+(?:дутьев|осев|радиальн)\w*|"
                       r"\bвдн[\s-]?\d)", re.I)),
    # ВИХРЕВЫЕ И РУТС — НЕ МУСОР. Поправка третьей сессии, и она права: у неё
    # 2355 объёмных машин, которые панель показывала как центробежные, а я
    # вихревые вовсе отправлял в мусор. Для «Компрессор Центра» винтовые,
    # поршневые, вихревые и Рутс — профильный товар (родной Enger и
    # дружественные марки в основном винтовые). Они не мусор, они ДРУГОЙ ТИП,
    # и путать эти два ответа нельзя: первый убирает клиента из работы,
    # второй уточняет, что ему предлагать.
    ("ne_centrobezhnaya", re.compile(
        # между «вихревая» и «воздуходувка» бывает третье слово
        # («вихревая ПРОМЫШЛЕННАЯ воздуходувка») — тест это и поймал
        r"(?:вихрев\w*(?:\s+\w+){0,2}\s+(?:воздуходувк|нагнетател|компрессор)\w*|"
        r"\bрутс\b|roots|\bERB[\s-]?\d|воздуходувк\w*\s+рутс)", re.I)),
    ("locomotive", re.compile(r"(?:тк[\s-]?23|тепловоз\w*|тгм\d|дизел\w*\s+тепловоз)", re.I)),
    ("engine", re.compile(r"(?:двигател\w*\s+внутренн|\bдвс\b|камаз|"
                          r"коленчат\w*\s+вал)", re.I)),
)
_COMPRESSOR_RE = re.compile(r"(?:компресс\w*|турбокомпресс\w*|нагнетател\w*)", re.I)


def _text(*values: object) -> str:
    return " | ".join(" ".join(str(value or "").strip().split()) for value in values)


def has_air(*values: object) -> bool:
    """Есть ли явное упоминание воздуха хотя бы в одном поле."""
    return bool(_AIR_RE.search(_text(*values)))


def is_definitely_non_air_medium(value: object, *, context: object = "") -> bool:
    """True только для явно не воздушной среды без упоминания воздуха.

    ``context`` позволяет сохранить строку «газ и воздух», даже когда поле
    ``sreda`` было предварительно сведено к категории «газ или иная среда».
    """
    medium = _text(value)
    combined = _text(value, context)
    if not medium:
        return False
    if _AIR_RE.search(combined):
        return False
    if _UNKNOWN_RE.search(medium):
        return False
    return bool(_NON_AIR_RE.search(medium))


def is_pump_fact(
    *,
    status: object = "",
    model: object = "",
    equipment_type: object = "",
    evidence: object = "",
    quote: object = "",
) -> bool:
    """True, когда строка описывает насос, а не компрессор."""
    identity = _text(status, model, equipment_type)
    if _PUMP_RE.search(identity):
        return True

    context = _text(evidence, quote)
    return bool(_PUMP_RE.search(context) and not _COMPRESSOR_RE.search(context))


def rejection_reason(fact: dict) -> str:
    """Вернуть причину исключения или пустую строку для сохраняемого факта."""
    if is_pump_fact(
        status=fact.get("status"),
        model=fact.get("model"),
        equipment_type=fact.get("equipment_type"),
        evidence=fact.get("evidence"),
        quote=fact.get("quote"),
    ):
        return "pump"

    context = _text(
        fact.get("status"),
        fact.get("model"),
        fact.get("equipment_type"),
        fact.get("evidence"),
        fact.get("quote"),
    )
    if is_definitely_non_air_medium(fact.get("medium"), context=context):
        return "non_air"

    # При неопределённом поле среды исключаем только явную конструкцию
    # «газовый компрессор» или компрессор конкретного газа.
    combined = _text(fact.get("medium"), context)
    if not _AIR_RE.search(combined) and _GAS_COMPRESSOR_RE.search(combined):
        return "non_air"

    # Мусорные классы. Явное упоминание компрессора НЕ спасает запись: у
    # тепловозного ТК-23С и турбоагрегата ТЭЦ слово «компрессор» стоит прямо
    # в названии, поэтому здесь важнее конкретная машина, а не общее слово.
    # Наша машина, названная прямо, перевешивает слово-подозрение рядом.
    # Исключения — тепловозный ТК-23С и паровой турбоагрегат: они САМИ
    # называют себя компрессором и турбиной, и общее слово там не спасает.
    наша = re.search(r"(?:турбовоздуходувк\w*|центробежн\w*\s+компрессор\w*|"
                     r"\bцк[\s-]?\d|\bк-?\d{3}-\d{2}|\b\d{2}вц[\s-]?\d)",
                     combined, re.I)
    for имя, правило in _JUNK_RULES:
        if правило.search(combined):
            if наша and имя in ("fan", "garden", "engine"):
                continue
            return имя

    return ""


def keep_fact(fact: dict) -> bool:
    """Оставить воздушный или неопределённый компрессорный факт."""
    return not rejection_reason(fact)
