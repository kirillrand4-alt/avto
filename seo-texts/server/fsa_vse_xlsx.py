def строки(wb, лист):
    it = wb[лист].iter_rows(values_only=True)
    ш = list(next(it))
    for r in it:
        yield dict(zip(ш, r))


def склей(v, n=12, длина=600):
    if isinstance(v, list):
        v = '; '.join(str(x) for x in v[:n] if x)
    return (v or '')[:длина] if isinstance(v, str) else v


def сделки(путь):
    сд = collections.defaultdict(list)
    for x in csv.DictReader(io.open(путь, encoding='utf-8-sig'), delimiter=';'):
        инн = re.sub(r'\D', '', x.get('INN') or '')
        if инн:
            сд[инн].append(x)
    return сд


def опис(x):
    return '№%s %s / %s (%s)' % (x['DEAL_ID'], x.get('ВОРОНКА', ''), x.get('СТАДИЯ', ''), (x.get('DATE_CREATE') or '')[:10])


def main(D, M, м7_xlsx, путь_meyer, путь_кц, выход, путь_класса=None, путь_кц1=None):
    ots = {y['инн']: y for y in jl(os.path.join(D, 'fsa-meyer-otsev.jsonl'))}
    к2 = {y['инн']: y for y in jl(os.path.join(D, 'fsa-meyer-kontakty2.jsonl'))}
    чк = {y['inn']: y for y in jl(os.path.join(D, 'fsa-meyer-checko.jsonl')) if y.get('итог') == 'ok' and len(y.get('inn', '')) == 10}
    дд = {y['инн']: y for y in jl(os.path.join(D, 'fsa-meyer-dadata.jsonl'))}
    св = {y['инн']: y for y in jl(os.path.join(D, 'fsa-meyer-decl-svod.jsonl'))}
    пасп = {y['inn']: y['паспорт'] for y in jl(os.path.join(M, 'meyer7-pasport.jsonl')) if y.get('inn')}
    м7 = set(json.load(open(os.path.join(M, 'meyer7-spisok.json'), encoding='utf-8'))['компании'])
    акт = {}
    for s in open(os.path.join(M, 'meyer7-sdelki-aktivnye.tsv'), encoding='utf-8'):
        ч = s.rstrip('\n').split('\t')
        if len(ч) > 2 and ч[2] == 'ИНН':
            акт[ч[0]] = ч[1]
    сд_м, сд_к = сделки(путь_meyer), сделки(путь_кц)
    # Цербер: объекты реестра -> ИНН, сверенный по самому реестру (cerber_inn_proverka.py)
    инн2 = {(y['юрлицо'], y['рег']): y.get('инн') for y in jl(os.path.join(D, 'cerber-meyer-inn2.jsonl'))}

    def рег(a):
        m = re.search(r'Российская Федерация, ([^,]+)', a or '')
        return (m.group(1) if m else '').replace('обл.', '').replace('край', '').replace('Респ.', '').strip().lower()[:12]
    цб = collections.defaultdict(list)
    for x in jl(os.path.join(D, 'cerber-meyer.jsonl')):
        инн = x.get('номер') and инн2.get((x['юрлицо'], рег(x.get('юр_адрес') or x.get('адрес'))))
        if инн:
            цб[инн].append(x)

    изг = [z for z in jl(os.path.join(D, 'fsa-meyer-izg.jsonl'))]
    кп, кт = collections.Counter(), collections.Counter()
    for z in изг:
        к = к2.get(z['инн']) or {}
        for a in set(к.get('почты') or z['почты']):
            кп[a] += 1
        for t in set(к.get('телефоны') or z['телефоны']):
            кт[re.sub(r'\D', '', t)[-10:]] += 1

    # отбор как в FSA-CERBER-MEYER «Изготовители»: не «нет» у модели и не ликвидирована
    def статус_(инн):
        с, д = чк.get(инн) or {}, дд.get(инн) or {}
        return с.get('статус') or {'ACTIVE': 'Действующая', 'LIQUIDATED': 'Ликвидирована', 'LIQUIDATING': 'Ликвидируется',
                                   'BANKRUPT': 'Банкротство', 'REORGANIZING': 'Реорганизация'}.get(д.get('статус'), д.get('статус') or '')

    def ответ(инн):
        a = (ots.get(инн) or {}).get('ответ', '')
        return {'da': 'да', '可能': 'возможно', '是': 'да'}.get(a, a)
    изг = [z for z in изг if not МЁРТВ.search(статус_(z['инн']) or '') and ответ(z['инн']) != 'нет']
    кл = {y['инн']: y for y in jl(путь_класса)} if путь_класса else {}
    if кл:
        изг = [z for z in изг if len(z['инн']) == 10 and (кл.get(z['инн']) or {}).get('класс') in ('M', 'К')]
    # «находили поиском»: Meyer-7 и КЦ-1, происхождение «поиск…»/«допоиск…»
    поиском = {i for i, b in json.load(open(os.path.join(M, 'meyer7-spisok.json'), encoding='utf-8'))['компании'].items()
               if str(b.get('откуда') or '').startswith(('поиск', 'допоиск'))}
    if путь_кц1:
        поиском |= {i for i, b in json.load(open(путь_кц1, encoding='utf-8'))['компании'].items()
                    if str(b.get('откуда') or '').startswith(('поиск', 'допоиск'))}
    наши = {z['инн'] for z in изг}

    wb7 = openpyxl.load_workbook(м7_xlsx, read_only=True)
    м7к = {}
    for r in строки(wb7, 'Компании'):
        инн = re.sub(r'\D', '', str(r.get('ИНН / УНП') or ''))
        if инн in наши and инн not in м7к:
            м7к[инн] = r
    шаги = collections.defaultdict(list)
    for лист, кол, почему in М7_ШАГИ:
        for r in строки(wb7, лист):
            инн = re.sub(r'\D', '', str(r.get(кол) or ''))
            if инн in наши:
                шаги[инн].append('%s: %s' % (лист, (r.get(почему) or '')[:120]))
    снято = collections.Counter()
    for r in строки(wb7, 'Снято'):
        снято[re.sub(r'\D', '', str(r.get('ИНН / УНП') or ''))] += 1
    конт_ш, конт = None, []
    it = wb7['Контакты'].iter_rows(values_only=True)
    конт_ш = list(next(it))
    ик = конт_ш.index('ИНН / УНП')
    for r in it:
        if re.sub(r'\D', '', str(r[ик] or '')) in наши:
            конт.append(r)

    H = (['ИНН', 'Изготовитель', 'Направление (Sol)', 'Уверенность', 'Почему (направление)',
          'Уникальная (не находил поиск Meyer/КЦ)', 'Статус', 'Регион', 'Адрес (из декларации)', 'Новая для Meyer (нет в базе)',
          'ОКВЭД основной', 'ОКВЭД доп. (с карточки)', 'Выручка, руб', 'Год выручки', 'Откуда выручка', 'Руководитель',
          'Госзакупок (checko)', 'Проверок (checko)', 'Карточка checko',
          'Деклараций (по нашим основам)', 'Первая декларация', 'Последняя декларация', 'Действуют сейчас', 'За 6 мес.', 'За 12 мес.',
          'Позиций продукции', 'Продукция (из деклараций по нашим основам)', 'Товарные знаки', 'Происхождение продукции', 'Тип заявителя',
          'Подано через другого заявителя', 'Адрес производства', 'Найдена по основам', 'Последняя декларация (ссылка)',
          'Почты (из деклараций)', 'Мобильные (из деклараций)', 'Городские (из деклараций)',
          'Посредник? (контакт у 5+ компаний)', 'Сайт (из декларации)', 'Сайт (по домену почты)',
          'Оценка модели (под Meyer)', 'Почему',
          'Прошёл конвейер Meyer-7', 'Конвейер: результат']
         + ['Конвейер: ' + k for k in М7_КОЛ] + ['Контактов снято проверкой']
         + ['Паспорт: ' + k for _, k in ПАСП] + ['Паспорт: КЦ-признак (воздух/газы)']
         + ['Цербер: объектов', 'Цербер: виды предприятий', 'Цербер: номера в реестре',
            'Битрикс Meyer: активная сделка', 'Битрикс Meyer: всего сделок', 'Битрикс Meyer: последние',
            'Битрикс КЦ/СЦ: активные', 'Битрикс КЦ/СЦ: всего сделок'])
    wb = Workbook(write_only=True)
    sv = wb.create_sheet('Сводка')
    w1 = wb.create_sheet('Компании')
    w2 = wb.create_sheet('Контакты с сайта')
    жирн, фон, красн = Font(bold=True), PatternFill('solid', fgColor='DDEBF7'), PatternFill('solid', fgColor='F8CBAD')

    def шапка(w, h):
        cc = []
        for v in h:
            c = WriteOnlyCell(w, value=v)
            c.font, c.fill = жирн, фон
            cc.append(c)
        w.append(cc)
    шапка(w1, H)
    сч = collections.Counter()
    rows = []
    for z in изг:
        инн = z['инн']
        y = ots.get(инн) or {}
        к, с, д, s = к2.get(инн) or {}, чк.get(инн) or {}, дд.get(инн) or {}, св.get(инн) or {}
        почты_все = к.get('почты') if к else z['почты']
        тел_все = к.get('телефоны') if к else z['телефоны']
        почты = [a for a in почты_все or [] if кп[a] < ПОР]
        тел = [t for t in тел_все or [] if кт[re.sub(r'\D', '', t)[-10:]] < ПОР]
        поср = [a for a in почты_все or [] if кп[a] >= ПОР] + [t for t in тел_все or [] if кт[re.sub(r'\D', '', t)[-10:]] >= ПОР]
        выр, год, откуда = f(с.get('выручка')), с.get('выручка_год') or '', 'checko' if с.get('выручка') else ''
        if not выр and f(z.get('выручка')):
            выр, год, откуда = f(z['выручка']), '', 'база обзвона'
        оквэд = с.get('оквэд') or д.get('оквэд') or z.get('оквэд') or ''
        доп = [x for x in (с.get('оквэд_все') or []) if x != оквэд]
        рук = ' — '.join(x for x in ((с.get('руководитель') or д.get('руководитель') or ''),
                                     (с.get('должность') or д.get('должность') or '')) if x)
        r7 = м7к.get(инн)
        if r7:
            итог = 'контакты с сайта — лист «Контакты с сайта»' if r7.get('Номеров') or r7.get('Почт') else 'в списке, контактов с сайта нет'
        elif шаги.get(инн):
            итог = ' | '.join(шаги[инн][:3])
        else:
            итог = 'в списке конвейера, сайт не найден' if инн in м7 else ''
        п = пасп.get(инн) or {}
        кц = п.get('разбор_КЦ') or {}
        кц_т = '; '.join((кц.get('воздух_точно') or []) + (кц.get('воздух_вероятно') or []) + (кц.get('газы_технические') or []))[:300]
        об = цб.get(инн) or []
        дм, дк = сд_м.get(инн) or [], сд_к.get(инн) or []
        дм.sort(key=lambda x: x.get('DATE_CREATE') or '', reverse=True)
        кк_акт = [x for x in дк if (x.get('АКТИВНА') or '').strip().lower() == 'да']
        y3 = кл.get(инн) or {}
        r = ([инн, z['имя'], {'M': 'Meyer', 'К': 'КЦ'}.get(y3.get('класс'), ''), y3.get('уверенность', ''), y3.get('почему', ''),
              '' if инн in поиском else 'да', статус_(инн), с.get('регион') or д.get('регион') or z.get('регион') or '', z['адрес'],
              '' if z['в_базе_meyer'] else 'да', оквэд, ', '.join(доп[:15]), выр or None, год, откуда, рук,
              с.get('госзакупки') or None, с.get('проверки') or None, с.get('ссылка', ''),
              s.get('деклараций') or z['деклараций'], s.get('первая', ''), s.get('последняя') or z['последняя'],
              s.get('действуют'), s.get('за_6_мес'), s.get('за_12_мес'), s.get('позиций'), (s.get('продукция') or '')[:1000],
              ', '.join(s.get('знаки') or []), ', '.join('%s %s' % (k or '—', v) for k, v in (s.get('происхождение') or {}).items()),
              ', '.join('%s %s' % (k or '—', v) for k, v in (s.get('тип_заявителя') or {}).items()), s.get('заявитель_другой') or None,
              ' | '.join(s.get('адреса') or []), ', '.join(s.get('основы') or z.get('слова') or []),
              ФСА % s['последняя_id'] if s.get('последняя_id') else (ФСА % к['id'] if к.get('id') else ''),
              ', '.join(почты), ', '.join(t for t in тел if моб(t)), ', '.join(t for t in тел if not моб(t)), ', '.join(поср),
              ', '.join(к.get('сайты') or []),
              ', '.join(sorted({a.split('@')[-1] for a in почты if a.split('@')[-1] not in БЕСПЛ})),
              ответ(инн), y.get('почему', ''), 'да' if инн in м7 else '', итог]
             + [склей((r7 or {}).get(k)) for k in М7_КОЛ] + [снято.get(инн) or None]
             + [склей(п.get(k)) for k, _ in ПАСП] + [кц_т]
             + [len(об) or None, ', '.join(sorted({x.get('вид') or '' for x in об}))[:300], ', '.join(x['номер'] for x in об[:10]),
                акт.get(инн, ''), len(дм) or None, ' ; '.join(опис(x) for x in дм[:3]), ' ; '.join(опис(x) for x in кк_акт[:3]),
                len(дк) or None])
        rows.append((-выр, -f(r[H.index('Деклараций (по нашим основам)')]), r, bool(акт.get(инн))))
        сч['компаний'] += 1
        сч['направление: ' + (r[2] or '—')] += 1
        сч['уникальные (не находил поиск)'] += инн not in поиском
        сч['уникальные Meyer от 500 млн'] += инн not in поиском and y3.get('класс') == 'M' and выр >= 5e8
        сч['новые для Meyer'] += not z['в_базе_meyer']
        сч['юрлица'] += len(инн) == 10
        сч['карточка checko'] += инн in чк
        сч['выручка известна'] += выр > 0
        сч['выручка от 100 млн'] += выр >= 1e8
        сч['декларация за последние 12 мес.'] += bool(s.get('за_12_мес'))
        сч['есть действующие декларации'] += bool(s.get('действуют'))
        сч['почта из деклараций'] += bool(почты)
        сч['телефон из деклараций'] += bool(тел)
        сч['сайт известен (декларация/домен почты/конвейер)'] += bool(r[H.index('Сайт (из декларации)')] or r[H.index('Сайт (по домену почты)')] or (r7 or {}).get('Сайт'))
        сч['прошли конвейер Meyer-7'] += инн in м7
        сч['контакты с сайта (конвейер)'] += bool(r7 and (r7.get('Номеров') or r7.get('Почт')))
        сч['ЛПР найден на сайте'] += bool(r7 and r7.get('ЛПР: ФИО'))
        сч['паспорт с сайта заполнен'] += any(п.get(k) for k, _ in ПАСП if k not in ('уверенность', 'источники'))
        сч['Цербер: есть объекты'] += bool(об)
        сч['Битрикс Meyer: активная сделка'] += bool(акт.get(инн))
        сч['Битрикс Meyer: были сделки'] += bool(дм)
        сч['Битрикс КЦ/СЦ: были сделки'] += bool(дк)
        сч['Битрикс КЦ/СЦ: активная'] += bool(кк_акт)
    rows.sort(key=lambda t: (t[0], t[1]))
    for _, _, r, красная in rows:
        r = чист(r)
        if красная:
            cc = []
            for v in r:
                c = WriteOnlyCell(w1, value=v)
                c.fill = красн
                cc.append(c)
            w1.append(cc)
        else:
            w1.append(r)
    порядок = {r[0]: i for i, (_, _, r, _) in enumerate(rows)}
    конт.sort(key=lambda r: порядок.get(re.sub(r'\D', '', str(r[ик] or '')), 10 ** 9))
    шапка(w2, конт_ш)
