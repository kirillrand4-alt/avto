          'Письмо: должность', 'Письмо: ступень лесенки', 'Номеров', 'Почт', 'Из них ЛПР', 'Мобильных', 'Где найдены контакты',
          'Тех. службы (наша база)', 'База обзвона: директор', 'База обзвона: телефоны', 'База обзвона: почты',
