def лесенка_строк(строки_, сегм, сайт, кц):
    """Сводка контактов компании как в pilot_xlsx (ЛПР-телефон, ЛПР-почта, письмо по лесенке Meyer / КЦ) — для
    находок агентов у компаний вне наборов конвейера."""
    мод = КЦЛ if кц else ML

    def лес(r, почта=True):
        к_ = мод.ключ(r['Роль'], сегм or '', r['Должность (как на сайте)'], r['E-mail'] if почта else '', r['ФИО'],
                      r['ЛПР по оборудованию'], сайт)
        return None if к_ is None else (к_, r['_п'])
    тел = [r for r in строки_ if r['Мобильный'] or r['Рабочий']]
    почты = [r for r in строки_ if r['E-mail']]
    лучший = min((r for r in тел if r['ЛПР по оборудованию'] == 'да'), key=lambda r: лес(r, False) or ((99,), r['_п']), default={})
    годные = sorted((r for r in почты if лес(r)), key=лес)
    лп = next((r for r in годные if r['ЛПР по оборудованию'] == 'да'), {})
    п = годные[0] if годные else {}
    return {'ЛПР: ФИО': лучший.get('ФИО', ''), 'ЛПР: должность': лучший.get('Должность (как на сайте)', ''),
            'ЛПР: роль': лучший.get('Роль', ''), 'ЛПР: телефон': лучший.get('Мобильный') or лучший.get('Рабочий', ''),
            'ЛПР: e-mail': лп.get('E-mail', ''), 'Письмо: e-mail': п.get('E-mail', ''),
            'Письмо: кому (ФИО)': п.get('ФИО', '') if п and лес(п)[0][2] == 0 else '',
            'Письмо: должность': п.get('Должность (как на сайте)', ''),
            'Письмо: ступень лесенки': мод.название(лес(п)[0][0]) if п else '',
            'Номеров': len(тел), 'Почт': len(почты), 'Из них ЛПР': sum(1 for r in строки_ if r['ЛПР по оборудованию'] == 'да'),
            'Мобильных': sum(1 for r in тел if r['Мобильный'])}


