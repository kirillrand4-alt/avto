# -*- coding: utf-8 -*-
"""База из таблицы BAZA-KONTAKTY-CC (Common Crawl) по живому обходу сайтов (cc_obhod.py).

Как третий файл Meyer: номер в основном листе — только если стоит на ЖИВОЙ странице сайта
компании сейчас. Плюс (владелец 07.10): если рядом с номером на странице есть ФИО или
должность — номер помечен ими; номера идут по ЛПР-приоритетам (роли ТЗ по сегменту), внутри —
мобильные первыми. ИНН: из таблицы, иначе со страниц сайта (контрольная сумма), иначе по домену
из нашей базы. Без компаний со сделками, конкурентов и ликвидированных.

    python cc_baza.py cc-vhod.json cc-obhod.jsonl cc-inn-info.json sdelki-inn.json out.xlsx
"""
import collections
import json
import re
import sys
import time

from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Alignment, Font

from meyer_baza import СЕГМЕНТЫ, коды, попадает, попадает_осн
from meyer_lpr import РОЛИ
from meyer_xlsx import лист, сделки

СЕГМ_ТАБЛ = {'Экспортёры': '1 экспортёры', 'Семеноводы': '2 семеноводы', 'Пищевые': '3 пищевые',
             'Элеваторы': '4 элеваторы', 'Орехи': '5 орехи', 'Ягоды': '6 ягоды'}
КЛАСС_В_РОЛЬ = {'директор': 'директор/руководитель', 'главный инженер': 'главный инженер',
                'технический директор': 'технический директор', 'производство': 'производство',
                'главный технолог': 'главный технолог', 'технолог': 'технолог', 'качество': 'качество',
                'закупки': 'закупки', 'агроном': 'агроном', 'семеноводство': 'семеноводство',
                'элеватор': 'заведующий элеватором/производством', 'коммерческий директор': 'коммерческий директор',
                'продажи': 'продажи', 'бухгалтерия': 'бухгалтерия', 'кадры': 'кадры', 'инженер': 'инженер/механик',
                'приёмная': 'общий/приёмная', 'общий': 'общий/приёмная', 'другое': 'другое'}


def норм(s):
    ц = re.sub(r'\D', '', s or '')
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    return ц


def main(п_вх, п_обх, п_инн, п_сд, п_out):
    вход = {о['домен']: о for о in json.load(open(п_вх, encoding='utf-8'))}
    обход = {}
    with open(п_обх, encoding='utf-8') as f:
        for s in f:
            з = json.loads(s)
            обход[з['домен']] = з
    инфо = {к: v for к, v in json.load(open(п_инн, encoding='utf-8')).items() if v.get('название') or v.get('оквэд')}
    сд = сделки(п_сд)

    компании, номера, люди, пропали = [], [], [], []
    убрано = collections.Counter()
    for дом, о in вход.items():
        з = обход.get(дом, {'страницы': [], 'номера': [], 'инн_живой': [], 'инн_база': [], 'люди': []})
        # ИНН: таблица -> сайт -> наша база по домену
        if о['инн']:
            инн, откуда_инн = о['инн'], 'таблица' + (' (есть на сайте)' if о['инн'] in з['инн_живой'] else '')
        elif len(з['инн_живой']) == 1:
            инн, откуда_инн = з['инн_живой'][0], 'сайт (реквизиты)'
        elif з['инн_живой']:
            общ = [i for i in з['инн_живой'] if i in з['инн_база']]
            инн = общ[0] if общ else з['инн_живой'][0]
            откуда_инн = 'сайт: несколько ИНН (группа) — %s' % ', '.join(з['инн_живой'][:5])
        elif len(з['инн_база']) == 1:
            инн, откуда_инн = з['инн_база'][0], 'наша база по домену'
        elif з['инн_база']:
            инн, откуда_инн = '', 'наша база: домен у нескольких ИНН — %s' % ', '.join(з['инн_база'][:5])
        else:
            инн, откуда_инн = '', 'не найден'
        все_инн = {i for i in [инн] + з['инн_живой'] + з['инн_база'] if i}
        if все_инн & set(сд):
            убрано['идёт сделка'] += 1
            continue
        и = инфо.get(инн, {})
        if str(и.get('конкурент', 0)) == '1':
            убрано['конкурент'] += 1
            continue
        if 'ликвид' in (и.get('статус') or '').lower():
            убрано['ликвидирована'] += 1
            continue
        # сегмент: по таблице (по заголовку сайта) и по ОКВЭД, если ИНН известен
        сегм_т = [СЕГМ_ТАБЛ.get(x.strip(), x.strip()) for x in (о['сегменты'] or '').split(',') if x.strip()]
        ок = и.get('оквэд') or о['оквэд']
        осн = коды(ок)[:1]
        все = коды(ок, и.get('оквэд_все', ''))
        сегм_о = [с for с, пр in СЕГМЕНТЫ if попадает_осн(осн[0] if осн else '', все, пр)] if все else []
        сегм_о_доп = [с for с, пр in СЕГМЕНТЫ if попадает(все, пр) and с not in сегм_о] if все else []
        можно = set()
        for с in сегм_т + сегм_о:
            можно |= РОЛИ.get(с, set())
        имя = о['название'] or и.get('название') or ''
        выр = о['доход'] or и.get('выручка') or ''
        база_комп = {
            'Домен': дом, 'Сайт': о['сайт'], 'ИНН': инн, 'Откуда ИНН': откуда_инн, 'Название': имя,
            'Регион': и.get('регион', ''), 'Основной ОКВЭД': осн[0] if осн else '',
            'Сегмент (по таблице)': ' | '.join(сегм_т),
            'Сегмент по основному ОКВЭД': ' | '.join(сегм_о) if все else ('ОКВЭД неизвестен' if not инн else ''),
            'Сегмент только по доп. ОКВЭД': ' | '.join(сегм_о_доп),
            'Выручка, руб': выр, 'Заголовок сайта': о['заголовок'], 'Откуда сайт': о['откуда'],
            'Новизна vs старые базы': о['новизна'], 'В нашей базе обзвона': и.get('база', '')}
        табл = {норм(x) for x in о['телефоны']}
        живые = set()
        строки = []
        for н in з['номера']:
            живые.add(норм(н['номер']))
            роль = КЛАСС_В_РОЛЬ.get(н.get('класс') or '', '')
            фио, должн = н.get('фио', ''), н.get('должность', '')
            if роль and роль in можно:
                пр, тип_к = (1 if фио else 2), 'ЛПР по списку'
            elif роль == 'общий/приёмная':
                пр, тип_к = 5, 'общий номер / приёмная'
            elif фио or должн:
                пр, тип_к = 3, 'другая должность'
            else:
                пр, тип_к = 4, 'без подписи'
            строки.append(dict(база_комп, **{
                'Тип номера': н['тип'], 'Номер': н['номер'] + ((' доб. ' + н['доб']) if н['доб'] else ''),
                'ФИО': фио, 'Должность': должн, 'Роль (класс)': роль, 'Тип контакта': тип_к, 'Приоритет': пр,
                'Номер из таблицы CC': 'да' if н['из_таблицы'] else 'нет, найден на сайте сейчас',
                'Страница': н['страницы'][0] if н['страницы'] else '', 'Как стоит на странице': н['контекст'],
                'Проверено': time.strftime('%d.%m.%Y')}))
        строки.sort(key=lambda x: (x['Приоритет'], x['Тип номера'] != 'мобильный',
                                    x['Тип номера'] != 'городской + доб.'))
        номера += строки
        for x in о['телефоны']:
            if норм(x) not in живые:
                пропали.append(dict(база_комп, **{'Номер': x, 'Почему': (
                    'сайт не открылся' if not any(p[1] == 'ok' for p in з['страницы'])
                    else 'на живых страницах сайта номера сейчас нет (был в архиве Common Crawl)')}))
        for л in з['люди']:
            тел = норм(л['телефон'])
            люди.append(dict(база_комп, **{
                'ФИО': л['фио'], 'Должность': л['должность'], 'Телефон рядом (таблица)': л['телефон'],
                'E-mail рядом (таблица)': л['почта'], 'Страница-источник': л['страница'],
                'ФИО на живой странице': 'да' if л['фио_на_живой'] else ('страница не открылась' if not л['страница_живая'] else 'нет'),
                'Телефон есть на живом сайте': ('да' if тел and тел in живые else ('нет' if тел else ''))}))
        лпр = [x for x in строки if x['Приоритет'] <= 2]
        лучший = (лпр or строки or [{}])[0]
        компании.append(dict(база_комп, **{
            'Номеров на живом сайте': len(строки), 'Из них ЛПР': len(лпр),
            'Номеров из таблицы подтверждено': len(табл & живые), 'Номеров таблицы нет на сайте': len(табл - живые),
            'Лучший номер': лучший.get('Номер', ''), 'Его ФИО': лучший.get('ФИО', ''),
            'Его должность': лучший.get('Должность', ''), 'Сайт открылся': 'да' if any(p[1] == 'ok' for p in з['страницы']) else 'нет'}))

    компании.sort(key=lambda к: (-к['Из них ЛПР'], not к['Номеров на живом сайте'], -float(к['Выручка, руб'] or 0)))
    место = {к['Домен']: i for i, к in enumerate(компании)}
    номера.sort(key=lambda x: (место[x['Домен']], x['Приоритет'], x['Тип номера'] != 'мобильный'))

    wb = Workbook(write_only=True)
    ws = wb.create_sheet('Сводка')
    ws.column_dimensions['A'].width = 80
    ws.column_dimensions['B'].width = 14
    b = Font(bold=True)

    def ж(т):
        c = WriteOnlyCell(ws, value=т)
        c.font = b
        return c

    def текст(т):
        c = WriteOnlyCell(ws, value=т)
        c.alignment = Alignment(wrap_text=True, vertical='top')
        ws.append([c])
    ws.append([ж('База CC (Common Crawl) — номера, подтверждённые на живых сайтах (на %s)' % time.strftime('%d.%m.%Y'))])
    ws.append(['Компаний в таблице', len(вход)])
    for п, n in убрано.most_common():
        ws.append(['  убрано: ' + п, n])
    ws.append(['Компаний в файле', len(компании)])
    ws.append(['  с номером на живом сайте', sum(1 for к in компании if к['Номеров на живом сайте'])])
    ws.append(['  с ЛПР по списку', sum(1 for к in компании if к['Из них ЛПР'])])
    ws.append(['  с ИНН', sum(1 for к in компании if к['ИНН'])])
    ws.append(['Номеров на живых сайтах (лист «Номера»)', len(номера)])
    for т, n in collections.Counter(x['Тип контакта'] for x in номера).most_common():
        ws.append(['  ' + т, n])
    for т, n in collections.Counter(x['Тип номера'] for x in номера).most_common():
        ws.append(['  ' + т, n])
    ws.append(['  с ФИО', sum(1 for x in номера if x['ФИО'])])
    ws.append(['  с должностью/отделом', sum(1 for x in номера if x['Должность'])])
    ws.append(['  из таблицы CC', sum(1 for x in номера if x['Номер из таблицы CC'] == 'да')])
    ws.append(['  новые (найдены на сайте сейчас, в таблице не было)', sum(1 for x in номера if x['Номер из таблицы CC'] != 'да')])
    ws.append(['Номера таблицы, которых нет на живом сайте (лист «Нет на сайте»)', len(пропали)])
    ws.append([])
    ws.append([ж('Правила')])
    for т in (
            'Номер в листе «Номера» — только если стоит на живой странице сайта компании сейчас (главная, '
            '«Контакты», «О компании», «Реквизиты», страницы людей из таблицы). Колонка «Как стоит на '
            'странице» — текст вокруг номера.',
            'ФИО и должность — если рядом с номером на странице есть подпись; кому принадлежит номер, по '
            'фрагменту страницы определила модель (подпись обычно перед номером). Без подписи — пусто.',
            'Порядок внутри компании: 1 — ЛПР по списку ТЗ для сегмента с ФИО, 2 — ЛПР без ФИО, 3 — другая '
            'должность, 4 — без подписи, 5 — общий номер/приёмная; при равенстве мобильные первыми.',
            'Сегмент (по таблице) — по заголовку сайта, точность ~55–65% (из пояснений таблицы). Если ИНН '
            'известен — рядом сегмент по ОКВЭД: по нему видно нецелевые строки.',
            'ИНН: из таблицы; если нет — со страниц сайта (рядом со словом «ИНН», с контрольной суммой); если '
            'нет — по домену из нашей базы. Убраны компании, где идёт сделка (панель), конкуренты и '
            'ликвидированные.'):
        текст(т)
    поля_к = ['Домен', 'Сайт', 'ИНН', 'Откуда ИНН', 'Название', 'Регион', 'Основной ОКВЭД', 'Сегмент (по таблице)',
              'Сегмент по основному ОКВЭД', 'Сегмент только по доп. ОКВЭД', 'Выручка, руб', 'Номеров на живом сайте',
              'Из них ЛПР', 'Лучший номер', 'Его ФИО', 'Его должность', 'Номеров из таблицы подтверждено',
              'Номеров таблицы нет на сайте', 'Сайт открылся', 'Заголовок сайта', 'Откуда сайт',
              'Новизна vs старые базы', 'В нашей базе обзвона']
    лист(wb, 'Компании', поля_к, компании,
         [22, 26, 12, 22, 34, 18, 9, 20, 20, 18, 15, 9, 8, 18, 26, 26, 9, 9, 8, 40, 18, 20, 12])
    поля_н = ['Домен', 'Название', 'ИНН', 'Регион', 'Сегмент (по таблице)', 'Сегмент по основному ОКВЭД',
              'Выручка, руб', 'Тип номера', 'Номер', 'ФИО', 'Должность', 'Роль (класс)', 'Тип контакта', 'Приоритет',
              'Номер из таблицы CC', 'Страница', 'Как стоит на странице', 'Проверено']
    лист(wb, 'Номера', поля_н, номера,
         [22, 30, 12, 18, 18, 18, 15, 14, 20, 26, 26, 18, 16, 8, 16, 40, 60, 11])
    лист(wb, 'Люди', ['Домен', 'Название', 'ИНН', 'ФИО', 'Должность', 'Телефон рядом (таблица)',
                      'E-mail рядом (таблица)', 'ФИО на живой странице', 'Телефон есть на живом сайте',
                      'Страница-источник'], люди, [22, 30, 12, 28, 26, 18, 26, 12, 12, 40])
    лист(wb, 'Нет на сайте', ['Домен', 'Название', 'ИНН', 'Номер', 'Почему'], пропали, [22, 30, 12, 18, 60])
    wb.save(п_out)
    print('компаний', len(компании), 'номеров', len(номера), 'убрано', dict(убрано), 'нет на сайте', len(пропали),
          'людей', len(люди))
    print(collections.Counter(x['Тип контакта'] for x in номера))


if __name__ == '__main__':
    main(*sys.argv[1:6])
