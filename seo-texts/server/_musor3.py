# -*- coding: utf-8 -*-
"""Две разные кучи: без компании (работать нельзя) и с компанией, но без деталей."""
import json, sqlite3

БЕЗ_КОМПАНИИ = ('заказчик в тексте не назван', 'конкретный заказчик не', 'заказчик не назван',
                'компания не названа', 'название компании отсутствует', 'компания-инвестор не',
                'контекст не уточнён')
БЕЗ_ДЕТАЛЕЙ = ('текст обрезан', 'текст новости обрезан', 'подробности обрезаны',
               'конкретное действие не указано', 'конкретика отсутствует', 'детали не указаны',
               'детали о проекте, этапе или инвестициях в тексте отсутствуют',
               'информация не раскрывается', 'уточните полный фрагмент')
c = sqlite3.connect(r'file:C:\sender\enrich.db?mode=ro', uri=True, timeout=40)
всего = c.execute('select count(*) from signals').fetchone()[0]
строки = c.execute(
    "select s.inn, coalesce(cmp.name,''), s.what, s.source_url from signals s "
    'left join companies cmp on cmp.inn=s.inn').fetchall()
c.close()
a=b=0; пр_a=[]; пр_b=[]
for inn, имя, what, url in строки:
    t=(what or '').lower()
    if any(p in t for p in БЕЗ_КОМПАНИИ):
        a+=1
        if len(пр_a)<4: пр_a.append({'компания_в_базе': (имя or '')[:34] or '(нет)', 'что': (what or '')[:100]})
    elif any(p in t for p in БЕЗ_ДЕТАЛЕЙ):
        b+=1
        if len(пр_b)<4: пр_b.append({'компания_в_базе': (имя or '')[:34] or '(нет)', 'что': (what or '')[:100]})
print('===ИТОГ===')
print(json.dumps({'всего': всего,
                  'А_без_компании': a, 'Б_с_компанией_но_без_деталей': b,
                  'примеры_А': пр_a, 'примеры_Б': пр_b}, ensure_ascii=False, indent=1)[:3200])
