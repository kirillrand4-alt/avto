def лпр_по_умолчанию(роль, сегм):
    с = (сегм or '').lower()
    if роль in РОЛИ_ЛПР:
        return 'да'
    if роль == 'Агрономия / семеноводство':
        return 'да' if re.search(r'семен|элеват|ягод|орех|\((2|4|5|6)[)/]', с) else 'возможно'
    if роль == 'Хранение / элеватор / склад':
        return 'да' if re.search(r'элеват|хранени|\(4\)', с) else 'возможно'
    if роль == 'Обогащение / горное':
        return 'да' if re.search(r'руд|угол|нерудн|песок|камень|\((9|22)\)', с) else 'возможно'
    if роль in ('Коммерция / ВЭД', 'Прочее'):
        return 'возможно'
    return 'нет'


def роль_по_должности(п):
    for rx, р in ДОЛЖН_РОЛЬ:
        if re.search(rx, п or '', re.I):
            return р
    return ''


def ном(н):
    ц = re.sub(r'\D', '', н or '')
    if len(ц) == 11 and ц.startswith('80'):
        ц = '375' + ц[2:]
    if len(ц) == 12 and ц.startswith('375'):
        return '+375 %s %s-%s-%s' % (ц[3:5], ц[5:8], ц[8:10], ц[10:12])
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    elif len(ц) == 10:
        ц = '7' + ц
    if len(ц) != 11 or ц[1] in '012':
        return ''
    return '+7 %s %s-%s-%s' % (ц[1:4], ц[4:7], ц[7:9], ц[9:11])


def мобильный(номер, доб):
    if доб or not номер:
        return False
    if номер.startswith('+7 9'):
        return True
    return bool(re.match(r'\+375 (25|29|33|44) ', номер))


def порядок(лпр, роль, фио, моб, доб):
    if лпр == 'да':
        п = 1 if фио else 2
    elif лпр == 'возможно':
        п = 3
    elif роль == 'Общий номер / приёмная':
        п = 5
    else:
        п = 4
    return (п, 0 if (моб or доб) else 1)


def jl(п):
    out = {}
    if os.path.exists(п):
        for s in open(п, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(s)
            except ValueError:
                continue
            if з.get('inn'):
                out[з['inn']] = з
    return out


