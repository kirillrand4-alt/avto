def подпись_перед(кт, номер, почта):
    """11.10, ревизия (2-05): подпись отдела на странице «Контакты» («Отдел снабжения: +7…») не доходила до роли —
    модель не ответила или ответила «общий» (≈150 номеров снабжения/ОТК/производства у ~100 компаний). Подпись — в
    своём куске контекста (после предыдущего контакта), последние 80 знаков перед контактом."""
    кт = (кт or '').lower().replace('ё', 'е')
    if почта:
        п = кт.find(почта.split('@')[0])
