def jl(п):
    out = {}
    if os.path.exists(п):
        for s in open(п, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(s)
            except ValueError:
                continue
            if з.get('inn'):
                out[з['inn']] = з
    return out


