def ном(н):
    ц = re.sub(r'\D', '', н or '')
    if len(ц) == 11 and ц.startswith('80'):
        ц = '375' + ц[2:]
    if len(ц) == 12 and ц.startswith('375'):
        return '+375 %s %s-%s-%s' % (ц[3:5], ц[5:8], ц[8:10], ц[10:12])
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    elif len(ц) == 10:
        ц = '7' + ц
    if len(ц) != 11 or ц[1] in '012':
        return ''
    return '+7 %s %s-%s-%s' % (ц[1:4], ц[4:7], ц[7:9], ц[9:11])


