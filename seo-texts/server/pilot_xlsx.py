def скелет(с):
    """Согласные транслита: ardashev / ardashev / ardachev → «rdsv» (варианты sh/sch/kh/ts/zh сводятся)."""
    с = (с or '').lower()
    for а, б in (('shch', 's'), ('sch', 's'), ('kh', 'h'), ('ts', 'c'), ('tc', 'c'), ('zh', 'j'), ('ch', 'c'), ('sh', 's'),
                 ('w', 'v'), ('x', 'ks'), ('q', 'k')):
        с = с.replace(а, б)
    return re.sub(r'[^a-z]|[aeiouy]', '', с)


