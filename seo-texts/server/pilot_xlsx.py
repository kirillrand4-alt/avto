def фио_чисто(фио, контекст=None):
    """Несколько человек в одном поле («Иванов И.И., Петров П.П.», «Иванов и Петров») — ФИО не ставим.
    11.10: и не человек / демо-люди шаблона / ФИО, которого нет в тексте вокруг контакта (съехало от соседа)."""
    ф = re.sub(r'\s+', ' ', фио or '').strip()
    ф = _ФИО_ХВОСТ.sub('', ф).strip()
    if not ф:
        return ''
    if re.search(r'[,;/]|\s+и\s+[А-ЯЁ]', ф) or len(ф.split()) > 4:
        return ''
    if _ФИО_НЕ_ЧЕЛОВЕК.search(ф) or ф.lower().replace('ё', 'е') in {x.replace('ё', 'е') for x in ДЕМО_ФИО}:
        return ''
    if контекст is not None and контекст.strip():
        кн = контекст.lower().replace('ё', 'е')
        слова = [w for w in re.findall(r'[А-Яа-яЁё]{4,}', ф.lower().replace('ё', 'е'))]
        if слова and not any(w[:-1] in кн for w in слова):  # без последней буквы — падежи
            return ''
    return ф


def плохой_номер(номер):
    """10.10, ревизия номеров: заглушки шаблонов (+7 999 999-99-99, 900 000-00-00), коды 5xx/6xx (в России нет —
    ошибка разбора: ОКПО, номер СТО, 10 цифр без кода), 7xx — Казахстан или сбитый номер."""
    ц = re.sub(r'\D', '', номер or '')
    if re.search(r'(\d)\1{6}', ц[1:]) or re.search(r'1234567|7654321', ц):
        return 'заглушка (повтор цифр)'
    if len(ц) == 11 and ц[0] == '7':
        if ц[1] in '56':
            return 'кода %s в России нет — ошибка разбора' % ц[1:4]
        if ц[1] == '7':
            return 'код %s — Казахстан или сбитый номер' % ц[1:4]
        if ц[1:3] in ('88', '89'):
            return 'кода %s в России нет — ошибка разбора' % ц[1:4]
    return ''


