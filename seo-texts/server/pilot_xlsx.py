def основа_домена(д):
    """Основа домена для сравнения: без www/зоны, без дефисов и точек, кириллица — транслитом (строгонов.рф ~ strogonov.ru)."""
    д = re.sub(r'^www\.', '', (д or '').lower())
    if д.startswith('xn--') or '.xn--' in д:
        try:
            д = д.encode('ascii').decode('idna')
        except Exception:  # noqa: BLE001
            pass
    метки = д.split('.')
    осн = метки[-2] if len(метки) >= 2 else метки[0]
    осн = ''.join(_ТРАНСЛИТ.get(ч, ч) for ч in осн)
    return re.sub(r'[^a-z0-9]', '', осн)


def домены_похожи(д1, д2):
    import difflib
    а, б = основа_домена(д1), основа_домена(д2)
    return bool(а and б) and (а == б or (min(len(а), len(б)) >= 5 and difflib.SequenceMatcher(None, а, б).ratio() >= 0.82))


