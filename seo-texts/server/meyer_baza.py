def роль(*поля):
    т = ' '.join(str(p or '') for p in поля)
    for rx, ярл, пр in РОЛИ_RX:
        if rx.search(т):
            return ярл, пр
    return 'не указана', 4


def приоритет(ярл, базовый, фио, сегменты):
    """1 — ЛПР сегмента с ФИО, 2 — ЛПР без ФИО, 3-4 — прочие, 5 — общий/приёмная."""
    топ = set()
    for с in сегменты:
        топ |= ТОП.get(с, set())
    if ярл in топ:
        п = 1
    elif базовый <= 3:
        п = 3
    else:
        п = базовый
    if not фио and п <= 3:
        п += 1
    return п


def коды(*строки):
    вс = []
    for s in строки:
        for к in re.findall(r'\d{2}(?:\.\d{1,2}){0,3}', s or ''):
            if к not in вс:
                вс.append(к)
    return вс


def попадает(вс, префиксы):
    for к in вс:
        for п in префиксы:
            if (п.endswith('.') and к.startswith(п)) or к == п or к.startswith(п + '.'):
                return True
    return False


def попадает_осн(осн, все, префиксы):
    """Основной ОКВЭД часто записан классом (10.39), а сегмент задан подклассом (10.39.2):
    считаем попаданием по основному, если основной — родитель кода сегмента и сам
    подкласс у компании тоже есть в списке."""
    if not осн:
        return False
    if попадает([осн], префиксы):
        return True
    for п in префиксы:
        if not п.endswith('.') and п.startswith(осн + '.') and попадает(все, (п,)):
            return True
    return False


