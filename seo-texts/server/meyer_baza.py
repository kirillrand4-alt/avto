def домен(s):
    s = (s or '').strip().lower()
    s = s.split('@')[-1] if '@' in s else re.sub(r'^[a-z]+://', '', s).split('/')[0]
    s = s.split(':')[0]
    if s.startswith('www.'):
        s = s[4:]
    части = s.split('.')
    if len(части) >= 3 and части[-2] in ('com', 'spb', 'msk', 'org', 'net', 'co', 'nsk', 'ekb', 'pp'):
        return '.'.join(части[-3:])
    return '.'.join(части[-2:]) if len(части) >= 2 else s


def имя_чисто(s):
    s = re.sub(r'"{2,}', '"', str(s or '')).strip().strip(',')
    for полн, кор in (('ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ', 'ООО'),
                      ('НЕПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО', 'АО'),
                      ('ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО', 'ПАО'),
                      ('АКЦИОНЕРНОЕ ОБЩЕСТВО', 'АО'),
                      ('ИНДИВИДУАЛЬНЫЙ ПРЕДПРИНИМАТЕЛЬ', 'ИП'),
                      ('СЕЛЬСКОХОЗЯЙСТВЕННЫЙ ПРОИЗВОДСТВЕННЫЙ КООПЕРАТИВ', 'СПК'),
                      ('КРЕСТЬЯНСКОЕ (ФЕРМЕРСКОЕ) ХОЗЯЙСТВО', 'КФХ'),
                      ('КРЕСТЬЯНСКОЕ ФЕРМЕРСКОЕ ХОЗЯЙСТВО', 'КФХ')):
        if s.upper().startswith(полн):
            s = кор + s[len(полн):]
            break
    if s.count('"') % 2:
        s += '"'
    return re.sub(r'\s+', ' ', s)


def телефон(t):
    ц = re.sub(r'\D', '', t or '')
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    elif len(ц) == 10:
        ц = '7' + ц
    if len(ц) != 11 or ц[1] in '012':
        return '', ''
    норм = '+7 %s %s-%s-%s' % (ц[1:4], ц[4:7], ц[7:9], ц[9:11])
    return норм, ('мобильный' if ц[1] == '9' else 'рабочий')


def выручка(v):
    try:
        f = float(str(v).replace(',', '.'))
    except (TypeError, ValueError):
        return ''
    return int(f) if f > 0 else ''


