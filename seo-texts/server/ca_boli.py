def поиск(промпт):
    """Gemini с Google Search через провайдера (родной generateContent). -> (текст, источников)"""
    ключ = os.environ.get('PROVIDER_API_KEY', '')
    база = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
    тело = {'contents': [{'role': 'user', 'parts': [{'text': промпт}]}], 'tools': [{'google_search': {}}]}
    з = urllib.request.Request('%s/v1beta/models/%s:generateContent' % (база, os.environ.get('GEMINI_MODEL', 'gemini-3.8-flash')),
                               data=json.dumps(тело, ensure_ascii=False).encode('utf-8'), headers={'x-goog-api-key': ключ, 'Authorization': 'Bearer ' + ключ,
                                                                        'Content-Type': 'application/json', 'User-Agent': 'curl/8.5.0'})
    for попытка in range(5):
        try:
            d = json.loads(urllib.request.urlopen(з, timeout=300).read().decode('utf-8', 'replace'))
            c = (d.get('candidates') or [{}])[0]
            г = c.get('groundingMetadata') or {}
            текст = ''.join(p.get('text', '') for p in (c.get('content') or {}).get('parts') or [])
            ист = [ч.get('web', {}).get('uri', '') for ч in г.get('groundingChunks') or []]
            return текст, ист
        except Exception as e:  # noqa: BLE001
            print('сбой gemini', repr(e)[:120], flush=True)
            time.sleep(20 * (попытка + 1))
    return '', []


def наши_данные():
    """Категория -> что видно на сайтах: сигналы (ca-signaly-itog.json) и поле «газы» паспортов."""
    out = collections.defaultdict(dict)
    п = os.path.join(ПАПКА, 'ca-signaly-itog.json')
    if os.path.exists(п):
        for к, v in json.load(open(п, encoding='utf-8')).get('по_категориям', {}).items():
            out[к]['сигналы_на_сайтах'] = v
    сп = json.load(io.open(os.path.join(DIR, 'ca-spisok.json'), encoding='utf-8'))['компании']
    газы = collections.defaultdict(collections.Counter)
    for s in io.open(os.path.join(DIR, 'ca-pasport.jsonl'), encoding='utf-8', errors='replace'):
        try:
            з = json.loads(s)
        except ValueError:
            continue
        к = сп.get(str(з.get('inn'))) or {}
        пас = з.get('паспорт') or {}
        for кат in (к.get('сегм') or '').split(', '):
            if кат and isinstance(пас, dict):
                газы[кат]['паспортов'] += 1
                газы[кат]['паспорт: газы заполнены'] += bool(пас.get('газы'))
                газы[кат]['паспорт: упаковка/фасовка'] += bool(пас.get('упаковка_фасовка'))
    for кат, v in газы.items():
        out[кат]['паспорта'] = dict(v)
    return out


