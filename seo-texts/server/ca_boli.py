def одна(кат, сделано, наши):
    газ_, статус, назв, коды, _пор, поясн = ca_cel.КАТ[кат]
    газ = 'кислорода' if газ_ == 'O2' else 'азота'
    станция = 'кислородная станция' if газ_ == 'O2' else 'азотная станция'
    рез = {r: сделано[(кат, r)] for r in ('тех', 'пров', 'скеп', 'прод', 'суд') if (кат, r) in сделано}
    if 'тех' not in рез:
        рез['тех'] = модель(ПР_ТЕХ.format(назв=назв, коды=', '.join(коды), поясн=поясн, enger=ENGER, газ=газ), 'claude-fable-5')
        записать({'кат': кат, 'роль': 'тех', 'модель': 'claude-fable-5', 'текст': рез['тех']})
    if 'пров' not in рез:
        утв = re.search(r'"утверждения_для_проверки"\s*:\s*\[(.*?)\]', рез['тех'], re.S)
        # 11.11: маршрут сервера до шлюза рвёт большие одно-POST тела (>~2 КБ, SSLEOF) — утверждений не больше ~600 символов, тело без \\u-эскейпов
        т, ист = поиск(ПР_ПОИСК.format(газ=газ, назв=назв, утв=(утв.group(1) if утв else рез['тех'])[:600]))
        рез['пров'] = т
        записать({'кат': кат, 'роль': 'пров', 'модель': 'gemini+google', 'текст': т, 'источники': ист[:15]})
    if 'скеп' not in рез:
        рез['скеп'] = модель(ПР_СКЕП.format(назв=назв, станция=станция, enger=ENGER, тех=рез['тех'][:3500]), 'gpt-6-sol')
        записать({'кат': кат, 'роль': 'скеп', 'модель': 'gpt-6-sol', 'текст': рез['скеп']})
    if 'прод' not in рез:
        рез['прод'] = модель(ПР_ПРОД.format(назв=назв, enger=ENGER, тех=рез['тех'][:3000], скеп=рез['скеп'][:2000], газ=газ), 'gpt-6-sol')
        записать({'кат': кат, 'роль': 'прод', 'модель': 'gpt-6-sol', 'текст': рез['прод']})
    if 'суд' not in рез:
        рез['суд'] = модель(ПР_СУД.format(назв=назв, газ=газ, кат=кат, статус=статус, тех=рез['тех'][:2500], пров=рез['пров'][:2500],
                                          скеп=рез['скеп'][:1500], прод=рез['прод'][:2000],
                                          наши=json.dumps(наши.get(кат, {}), ensure_ascii=False)[:800]), 'claude-fable-5')
        записать({'кат': кат, 'роль': 'суд', 'модель': 'claude-fable-5', 'текст': рез['суд'], 'пров_был': bool(рез['пров'])})
    print('готово', кат, flush=True)
    return кат, рез


def main():
    сделано = {}
    if os.path.exists(ВЫХОД):
        for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(s)
            except ValueError:
                continue
            if з.get('текст') and not (з['роль'] == 'суд' and not з.get('пров_был', False)):
                сделано[(з['кат'], з['роль'])] = з['текст']  # судья без проверки поиском — пересчитать
    наши = наши_данные()
    кат_ = [к for к, v in ca_cel.КАТ.items() if v[1] != 'не брать']
    print('категорий', len(кат_), 'уже ролей', len(сделано), flush=True)
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(4) as ex:
        итоги = dict(ex.map(lambda к: одна(к, сделано, наши), кат_))
    # сводка: карточки судей + источники проверки
    источники = collections.defaultdict(list)
    for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
        з = json.loads(s)
        if з.get('роль') == 'пров':
            источники[з['кат']] = з.get('источники') or []
    строки = ['# Боли и проверка физики по отраслям ЦА O2/N2', '',
              'Спор моделей через провайдера (технолог, проверка с поиском Google, скептик, продажник, судья); '
              'судья учитывал наши данные по сайтам компаний. %s.' % time.strftime('%d.%m.%Y'), '']
    for к in кат_:
        газ_, статус, назв = ca_cel.КАТ[к][:3]
        строки += ['## %s %s (%s, сейчас: %s)' % (газ_, назв, к, статус), '', итоги[к].get('суд') or '(нет ответа судьи)', '']
        if источники.get(к):
            строки += ['Источники проверки: ' + ', '.join(источники[к][:8]), '']
    п = os.path.join(ПАПКА, 'CA-BOLI.md')
    with io.open(п, 'w', encoding='utf-8') as f:
        f.write('\n'.join(строки))
        f.flush()
        os.fsync(f.fileno())
    import shutil
    shutil.copyfile(п, os.path.join(ДРОП, 'CA-BOLI.md'))
    shutil.copyfile(ВЫХОД, os.path.join(ДРОП, 'ca-boli.jsonl'))
    print('готово всё', flush=True)


