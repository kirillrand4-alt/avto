# -*- coding: utf-8 -*-
r"""Полный разбор отказов «домен занят другим ИНН» — куда уходит каждый пятый ответ.

Владелец 20.08: «разберись подробно». Заслон отбрасывает 210–222 находки из
каждых 500, и это не мелочь: запрос уже оплачен, а компания списана в
«не нашли» целиком.

Считаем по ВСЕМУ журналу поиска, а не по хвосту, и делим отказы на три сорта,
потому что лечатся они по-разному:

  СПРАВОЧНИК   поиск вернул этот домен для МНОГИХ РАЗНЫХ компаний — значит
               он отвечает на любой запрос, то есть агрегатор. Лечится списком.
  ГРУППА       вернулся для нескольких компаний, и они действительно связаны
               (общий сайт холдинга). Заслон прав, площадкой это не назвать.
  ТЁЗКА        вернулся для одной-двух компаний. Поиск нашёл однофамильца,
               списком это не лечится вовсе.

ВАЖНО про мерку. Первая версия сортировала по тому, за сколькими ИНН домен
ЗАКРЕПЛЁН в базе, — и это оказалось бессмысленно: закрепить его заслон как раз
и не давал. check.tochka.com получил 258 отказов, а закреплён всего за тремя
ИНН, и попал в «группы». Считать надо, скольким РАЗНЫМ компаниям поиск его
вернул, — это и есть признак агрегатора.
"""
import json
import os
import re
import sqlite3
import sys

sys.path.insert(0, r'C:\sender\server')
import ploshchadki as PL  # noqa: E402

ЛОГ = r'C:\sender\poisk_saytov.jsonl'
BD = r'C:\sender\enrich.db'
ПОРОГ_СПРАВОЧНИКА = 4          # столько чужих ИНН — уже не группа компаний


def главное():
    c = sqlite3.connect('file:%s?mode=ro' % BD.replace('\\', '/'), uri=True)
    занятые, имена = {}, {}
    for инн, s, cs, имя in c.execute(
            "select inn, coalesce(site,''), coalesce(cand_site,''), "
            "coalesce(name,'') from companies "
            "where coalesce(site,'')<>'' or coalesce(cand_site,'')<>''"):
        имена[str(инн)] = имя
        for u in (s, cs):
            д = PL.домен(u) if u else ''
            if д:
                занятые.setdefault(д, set()).add(str(инн))
    c.close()

    счёт, кто, примеры = {}, {}, {}
    всего = занято = 0
    if os.path.exists(ЛОГ):
        with open(ЛОГ, encoding='utf-8', errors='replace') as f:
            for s in f:
                try:
                    d = json.loads(s)
                except Exception:  # noqa: BLE001
                    continue
                if not d.get('site'):
                    continue
                всего += 1
                инн = str(d.get('inn') or '')
                дом = PL.домен(d['site'])
                чьи = занятые.get(дом) or set()
                чужие = чьи - {инн}
                if not чужие:
                    continue
                занято += 1
                счёт.setdefault(дом, set()).add(инн)   # РАЗНЫХ компаний
                кто[дом] = len(чьи)                    # закреплено в базе
                примеры.setdefault(дом, []).append(
                    {'инн': инн, 'имя': (d.get('name') or '')[:34]})

    сорта = {'справочник': [], 'группа': [], 'тёзка': []}
    for дом, инны in счёт.items():
        n = len(инны)
        сорт = ('справочник' if n >= ПОРОГ_СПРАВОЧНИКА
                else 'тёзка' if n <= 2 else 'группа')
        сорта[сорт].append((дом, n, кто.get(дом, 0)))
    for к in сорта:
        сорта[к].sort(key=lambda x: -x[1])

    итог = {
        'находок_в_журнале': всего,
        'отбито_как_занято': занято,
        'доменов_в_отказах': len(счёт),
        'доля_%': round(100.0 * занято / max(1, всего), 1),
        'по_сортам': {к: {'доменов': len(v), 'компаний_потеряно': sum(x[1] for x in v)}
                      for к, v in сорта.items()},
        'справочников_уже_в_списке': sum(
            1 for д, _n, _k in сорта['справочник'] if PL.из_списка(д)),
        'компаний_спасёт_список': sum(
            n for д, n, _k in сорта['справочник'] if not PL.из_списка(д)),
    }
    итог['СПРАВОЧНИКИ_добавить'] = [
        {'домен': д, 'разных_компаний': n, 'закреплён_за_инн': k,
         'в_списке': bool(PL.из_списка(д)),
         'примеры_компаний': [x['имя'] for x in примеры[д][:2]]}
        for д, n, k in сорта['справочник'][:25] if not PL.из_списка(д)]
    итог['ГРУППЫ_не_трогать'] = [
        {'домен': д, 'разных_компаний': n, 'инн': k}
        for д, n, k in сорта['группа'][:10]]
    итог['ТЁЗКИ_списком_не_лечатся'] = [
        {'домен': д, 'разных_компаний': n} for д, n, k in сорта['тёзка'][:10]]
    print(json.dumps(итог, ensure_ascii=False, indent=1)[:6000])
    # свод печатаем ПОСЛЕДНИМ: раннер обрезает вывод по хвосту
    print(json.dumps({'СВОД': {k: v for k, v in итог.items()
                               if not isinstance(v, list)}}, ensure_ascii=False))


главное()
