def один(номер, сегменты, client):
    п = os.path.join(ВЫХОД, 'agent-%02d.json' % номер)
    if os.path.exists(п):
        return json.load(open(п, encoding='utf-8'))
    if сегменты:
        промпт = ПРОМПТ.format(блок='\n'.join('- %s' % СЕГМЕНТЫ[x] for x in сегменты))
    else:
        промпт = ПРОМПТ_СКВОЗНОЙ.format(все='; '.join(СЕГМЕНТЫ[x].split(':')[0].split(' (')[0] for x in СЕГМЕНТЫ))
    for попытка in range(3):
        msg = call(client, [{'role': 'user', 'content': промпт}], 'claude-fable-5')
        текст = ''.join(b.text for b in msg.content if b.type == 'text')
        м = re.search(r'\{.*\}', текст, re.S)
        try:
            рез = json.loads(м.group(0))
            break
        except Exception:  # noqa: BLE001
            time.sleep(5)
    else:
        рез = {'ошибка': 'не разобран JSON'}
    рез['_агент'] = номер
    рез['_сегменты'] = сегменты
    with open(п, 'w', encoding='utf-8') as f:
        json.dump(рез, f, ensure_ascii=False, indent=1)
        f.flush()
        os.fsync(f.fileno())
    print('агент %02d готов (%s)' % (номер, сегменты or 'сквозной'), flush=True)
    return рез


def норм(q):
    return re.sub(r'\s+', ' ', q.strip().lower().replace('ё', 'е'))


def main():
    os.makedirs(ВЫХОД, exist_ok=True)
    client = make_client()
    задачи = АГЕНТЫ + [(25, [])]
    with ThreadPoolExecutor(10) as ex:
        результаты = list(ex.map(lambda x: один(x[0], x[1], client), задачи))
    каталог = {}
    for р in результаты:
        осн = (р['_сегменты'] or ['сквозной'])[0]
        for поле, знач in р.items():
            if поле.startswith('_') or not isinstance(знач, list):
                continue
            for q in знач:
                if not isinstance(q, str) or not q.strip():
                    continue
                к = (поле, норм(q))
                з = каталог.setdefault(к, {'запрос': q.strip(), 'вид': поле, 'сегменты': [], 'агенты': []})
                if осн not in з['сегменты']:
                    з['сегменты'].append(осн)
                if р['_агент'] not in з['агенты']:
                    з['агенты'].append(р['_агент'])
    записи = sorted(каталог.values(), key=lambda з: (з['вид'], str(з['сегменты'][0]), з['запрос']))
    with open(os.path.join(ВЫХОД, 'katalog.json'), 'w', encoding='utf-8') as f:
        json.dump({'сегменты': СЕГМЕНТЫ, 'агенты': АГЕНТЫ, 'запросы': записи}, f, ensure_ascii=False, indent=1)
    вид = {}
    for з in записи:
        вид[з['вид']] = вид.get(з['вид'], 0) + 1
    print(json.dumps({'агентов': len(результаты), 'ошибок': sum(1 for р in результаты if р.get('ошибка')),
                      'уникальных_записей': len(записи), 'по_видам': вид}, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main()
