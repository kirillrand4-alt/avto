# --- ПОДПИСЬ РЯДОМ С НОМЕРОМ (правка 24.08.2026) ---------------------------
# Метка обрывается на СОСЕДНЕМ КОНТАКТЕ. В таблице «Приемная +7 (846) 953-77-00
# Отдел снабжения +7 (846) 953-74-54» текст слева от второго номера кончается
# первым номером, и всё, что до него, — чужая строка, а не подпись.
_ОКНО_МЕТКИ = 140          # сколько знаков смотрим в каждую сторону
_ПРЕДЕЛ_МЕТКИ = 80         # длиннее — это уже абзац, а не подпись

# Разделитель сразу после номера означает, что подпись справа относится ИМЕННО
# К НЕМУ: «8 (905) 123-80-33 - Отдел продаж», «+7 8442 97-07-48 (Приемная)».
# Без этого признака правая метка в табличном списке — подпись СЛЕДУЮЩЕЙ строки.
_РАЗДЕЛИТЕЛИ = ('-', '–', '—', '(', ':')
_ЗАЗОР = 40                # сколько знаков смотрим до первого значащего

# Двоеточие вплотную слева — САМОЕ СИЛЬНОЕ доказательство принадлежности, и
# именно на нём стояло прежнее правило (сверка 388 живых строк: 96,6% верных).
# Без него новое «молчим, когда роль называют обе стороны» съедало ровно те
# подписи, которые прежняя версия брала верно: в списке «Отдел продаж:
# +7 (812) 438-75-87 Приемная: +7 (812) 295-10-97» роль первого номера доказана
# двоеточием, а не отдана на спор с подписью соседней строки. На замере это
# 82 роли из 386 — пятая часть уже проверенной разметки.
#
# Пробелы считаем не окном фиксированной длины, а rstrip/lstrip: снятие тегов
# оставляет между подписью и номером цепочку переводов строки, и «двоеточие в
# восьми знаках» не находилось там, где оно на странице стоит вплотную.


def _dvoetochie_sleva(текст, начало):
    """Текст слева кончается двоеточием — подпись доказанно принадлежит номеру."""
    return текст[max(0, начало - 90):начало].rstrip(' \t\r\n\u00a0').endswith(':')


def _razdelitel_sprava(текст, конец):
    """Сразу за номером стоит тире, скобка или двоеточие — подпись справа его."""
    хвост = текст[конец:конец + _ЗАЗОР].lstrip(' \t\r\n\u00a0')
    return хвост[:1] in _РАЗДЕЛИТЕЛИ

# Улица «Техническая» и проезд «Слесарный» — адрес, а не роль: без этого канон
# производит «ул. Техническая, д. 9» в технический контакт.
# ФЛАГ re.I НА ВСЁ ВЫРАЖЕНИЕ СТАВИТЬ НЕЛЬЗЯ: он же обесценивает [А-ЯЁ], и
# «Отдел Снабжения» терял хвост — «наб» внутри слова совпадало с набережной, а
# следом шла строчная «ж», которую [А-ЯЁ] под re.I принимал за заглавную. Роль
# «снабжение/закупки» после этого не опознавалась вовсе. Регистронезависима
# только сама вывеска улицы, и она же взята в границы слова.
_УЛИЦА = re.compile(r'(?i:\b(?:ул|улиц\w*|пр-?кт|проспект|проезд|переул\w*|пер'
                    r'|наб|шоссе|б-р|бульвар)\b\.?)\s*[А-ЯЁ][\w-]*')

# Подпись есть, а роли в ней нет: «Телефон:», «Факс:», «Контакты».
_МЕТКА_ПУСТЫШКА = re.compile(
    r'^(тел|телефон\w*|факс|моб\w*|мобильный телефон|контакт\w*|адрес|e-?mail'
    r'|email|почт\w*|звоните|позвоните|номер\w*|т|phone|tel)[\s./:]*$', re.I)

# Реквизит рядом с «номером» — значит это не номер. Прежде отсев шёл по
# короткой подписи до двоеточия, а метка теперь длинная, поэтому ключи взяты
# в границы слова: без них «инн» ловится внутри «инновационного отдела», а
# «счет» — внутри «расчетного», и живые телефоны выбрасывались бы вместе с
# расчётными счетами. Смотрим только вплотную к номеру: дальше стоит уже
# другой текст.
_РЕКВИЗИТ = re.compile(
    r'\b(инн|огрн|огрнип|кпп|бик|окпо|октмо|окато|сч[её]т|индекс|лицензи\w*'
    r'|свидетельств\w*)\b|р/с|к/с', re.I)
_ХВОСТ_РЕКВИЗИТА = 30      # знаков слева от номера, где ищем реквизит

# Канон ролей общий на всю базу (enrich_db._ROLE_CANON), и трогать его ради
# телефонов нельзя: он же размечает почты и людей. Двух живых подписей он не
# знает, поэтому добираем ЗДЕСЬ и только когда канон уже сказал «общий».
# «Диспетчерская» — не выдумка: это значение роли уже живёт в phone_contacts,
# его ставит другой путь. На замере она закрывает 15 потерь из 16 «канонных».
_ДОБОР_КАНОНА = (('диспетчер', 'диспетчерская'),)


# Кусок из одних знаков препинания — не подпись, а осколок вёрстки. Встречается
# сплошь и рядом: подпись стоит в своём теге, а двоеточие уезжает в начало
# строки с номером («Коммерческий отдел\n: +7 (8412) 28-01-37»), и «последний
# кусок слева» оказывается голым двоеточием. Такие куски пропускаем и берём
# следующий за ними — иначе подпись, стоящая вплотную, теряется целиком.
_ТОЛЬКО_ЗНАКИ = re.compile(r'^[\s\u00a0:;,.\-–—()·•|]*$')


def _сырой_кусок(текст, справа=False):
    """Ближайшая к номеру значащая строка текста, как она написана.

    Пустые куски пропускаем намеренно: снятие тегов оставляет между подписью и
    номером цепочку пустых строк, и «последний кусок» без этого всегда пустой —
    на этом первая версия замера потеряла шесть седьмых находок.
    """
    т = _УЛИЦА.sub(' ', текст or '')
    куски = [x.strip(' \t\r\n\u00a0') for x in re.split(r'[\n;|•·\u2022]+', т)]
    куски = [x for x in куски if x and not _ТОЛЬКО_ЗНАКИ.match(x)]
    if not куски:
        return ''
    return куски[0] if справа else куски[-1]


def _кусок(текст, справа=False):
    """То же, но без краевых знаков препинания и в пределах длины подписи."""
    к = _сырой_кусок(текст, справа).strip(' \t\r\n\u00a0:-–—,.()')
    return к[:_ПРЕДЕЛ_МЕТКИ] if справа else к[-_ПРЕДЕЛ_МЕТКИ:]


def _метка_слева(текст, начало):
    """Текст слева от номера, обрезанный по предыдущему телефону или почте."""
    окно = текст[max(0, начало - _ОКНО_МЕТКИ):начало]
    край = 0
    for m in LS._ТЕЛ_В_ТЕКСТЕ.finditer(окно):
        край = max(край, m.end())
    for m in LS._ПОЧТА_В_ТЕКСТЕ.finditer(окно):
        край = max(край, m.end())
    return _кусок(окно[край:])


def _метка_справа(текст, конец):
    """(метка, чужая) — текст справа, обрезанный по следующему контакту.

    «чужая» значит, что метка стоит ВПЛОТНУЮ К СЛЕДУЮЩЕМУ НОМЕРУ и принадлежит
    ему: «Секретарь 8 (846) 953-77-00 Отдел снабжения 8 (846) 953-74-54» —
    подпись между номерами всегда подпись ВТОРОГО. Без этого правила первый
    номер получал чужой отдел, а на замере оно же вернуло верную роль там, где
    прежде приходилось молчать. Проверку отменяет разделитель сразу за нашим
    номером («N — Отдел продаж»): в таком списке подпись идёт ПОСЛЕ номера.
    """
    окно = текст[конец:конец + _ОКНО_МЕТКИ]
    край, рядом_номер = len(окно), False
    m = LS._ТЕЛ_В_ТЕКСТЕ.search(окно)
    if m:
        край, рядом_номер = m.start(), True
    m = LS._ПОЧТА_В_ТЕКСТЕ.search(окно)
    if m and m.start() < край:
        край, рядом_номер = m.start(), False
    сырое = окно[:край]
    # ДВОЕТОЧИЕ В КОНЦЕ СМОТРИТ ВПЕРЁД. В столбце «+7 (991) 360 77 21
    # Бухгалтерия: +7 (991) 360 81 96» подпись «Бухгалтерия:» принадлежит
    # СЛЕДУЮЩЕМУ номеру, а не нашему, и без этого правила бухгалтерию получал
    # предыдущий. «Отдел продаж: внутр. 7701» после номера двоеточием не
    # кончается — эта подпись остаётся при своём номере.
    # Спрашиваем ИМЕННО первый кусок, а не весь хвост окна: окно обрывается по
    # счёту знаков, и двоеточие на его срезе не значит ничего (на замере такая
    # проверка молча съела двадцать верных находок).
    кусок = _сырой_кусок(сырое, справа=True)
    if not кусок:
        return '', False
    # ДВОЕТОЧИЕ ПОСЛЕ ПОДПИСИ СМОТРИТ ВПЕРЁД, где бы оно ни стояло — сразу за
    # словом («Бухгалтерия: +7…») или отдельной строкой после него, как его
    # оставляет вёрстка. Такая подпись принадлежит СЛЕДУЮЩЕМУ номеру.
    хвост = сырое.split(кусок, 1)[-1] if кусок in сырое else ''
    вперёд = ':' in хвост and bool(_ТОЛЬКО_ЗНАКИ.match(хвост))
    if кусок.endswith(':') or вперёд:
        return '', False
    чужая = bool(рядом_номер and
                 сырое.rstrip(' \t\r\n\u00a0·•|;,').endswith(кусок))
    return _кусок(сырое, справа=True), чужая


def _канон(метка):
    """Роль по метке или '' — «общий» ролью не считаем, псевдороли не выдаём."""
    м = (метка or '').strip()
    if not м or _МЕТКА_ПУСТЫШКА.match(м):
        return ''
    роль = EnrichDB._canon_role(м)
    if роль and роль != 'общий':
        return роль
    низ = м.lower()
    for ключ, знач in _ДОБОР_КАНОНА:
        if ключ in низ:
            return знач
    return ''


def подпись_номера(текст, начало, конец):
    """(роль, метка, сторона) для номера в позиции [начало:конец].

    Порядок разбора и почему он такой (проверено на 428 живых строках потерь
    и на 386 строках уже проверенной разметки):
      1. роль слева И вплотную двоеточие — берём левую: «Отдел продаж: +7…».
         Двоеточие доказывает принадлежность, спорить с соседней строкой не о
         чем. Это правило прежней версии, и оно обязано стоять ПЕРВЫМ;
      2. роль справа И сразу после номера разделитель — берём правую: это
         формат «номер — Отдел», и в нём левая метка принадлежит соседу;
      3. роль слева — берём левую, ЕСЛИ справа роли нет; если роль называют
         обе стороны и ни одна не доказана знаком препинания, это табличный
         список, и чья подпись — неизвестно: молчим;
      4. роль справа при пустой или пустышечной левой метке («Телефон:») —
         берём правую: спорить не с чем.
    Правая метка, приклеенная к следующему номеру, ролью не считается вовсе —
    см. _метка_справа.
    """
    слева = _метка_слева(текст, начало)
    справа, чужая_справа = _метка_справа(текст, конец)
    двоеточие = _dvoetochie_sleva(текст, начало)
    разделитель = _razdelitel_sprava(текст, конец)
    рл = _канон(слева)
    рс = _канон(справа) if (разделитель or not чужая_справа) else ''
    if рл and двоеточие:
        return рл, слева, 'слева'
    if рс and разделитель:
        return рс, справа, 'справа'
    if рл:
        return ('', '', 'спор') if рс else (рл, слева, 'слева')
    if рс and (not слева or _МЕТКА_ПУСТЫШКА.match(слева)):
        return рс, справа, 'справа'
    if рс:
        return '', '', 'спор'
    return '', '', ''


def _номера_со_страниц(страницы):
    """{последние 10 цифр: {'kak','rol','metka','storona','stranicy'}}.

    Своя версия LS._kontakty_so_stranic: та отдаёт подписи списком строк, а
    здесь нужны ПОЗИЦИИ номера в тексте — иначе вправо не посмотреть. Пределы
    и порядок страниц взяты оттуда же, чтобы разбор не разъезжался с остальными
    потребителями кэша.
    """
    отобранные = sorted(
        страницы or [],
        key=lambda п: 0 if any(к in str(п[0]).lower() for к in LS._КОНТАКТНЫЕ) else 1
    )[:LS._ПРЕДЕЛ_СТРАНИЦ]
    найдено = {}
    for url, html in отобранные:
        текст = LS._tekst_stranicy(str(html or '')[:LS._ПРЕДЕЛ_ЗНАКОВ])
        for m in LS._ТЕЛ_В_ТЕКСТЕ.finditer(текст):
            цифры = LS._цифры(m.group(0))
            if not LS._pohozh_na_telefon(цифры):
                continue
            ключ = цифры[-10:]
            if LS._fiktivnyy(ключ):
                continue
            если_реквизит = текст[max(0, m.start() - _ХВОСТ_РЕКВИЗИТА):m.start()]
            if _РЕКВИЗИТ.search(если_реквизит):
                continue          # это ИНН или расчётный счёт, а не телефон
            узел = найдено.setdefault(ключ, {'kak': m.group(0).strip(), 'rol': '',
                                             'metka': '', 'storona': '',
                                             'stranicy': []})
            if url not in узел['stranicy']:
                узел['stranicy'].append(url)
            if узел['rol']:
                continue          # роль уже нашли на более контактной странице
            роль, метка, сторона = подпись_номера(текст, m.start(), m.end())
            if роль:
                узел['rol'] = роль
                узел['metka'] = метка[:60]
                узел['storona'] = сторона
    return найдено


def _журнал(запись):
    """Durable-след: строка с fsync. Песочница откатывается, сервер — нет."""
    try:
        os.makedirs(os.path.dirname(ЖУРНАЛ), exist_ok=True)
        with open(ЖУРНАЛ, 'a', encoding='utf-8') as f:
            f.write(json.dumps(запись, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())
    except Exception:  # noqa: BLE001 - журнал не должен ронять прогон
        pass


def _с_повтором(f, *а, **кв):
    """«database is locked» — не ошибка компании, а очередь к файлу базы.

    Первый прогон 21.08 потерял 8604 компании именно так: в enrich.db в это же
    время пишут мост Зенки, поиск сайтов и цикл фактов, а тридцати секунд
    ожидания хватало не всегда. Ждём и повторяем, а не выбрасываем компанию.
    """
    import sqlite3 as _sq
    for попытка in range(4):
        try:
            return f(*а, **кв)
        except _sq.OperationalError as e:
            if 'locked' not in str(e).lower() or попытка == 3:
                raise
            time.sleep(2.0 * (попытка + 1))


_БУФЕР = []
_СБРОС = 100


def _сбросить_собранное():
    """Сбросить накопленное на диск одним разом, с fsync."""
    if not _БУФЕР:
        return
    os.makedirs(os.path.dirname(СОБРАНО), exist_ok=True)
    with open(СОБРАНО, 'a', encoding='utf-8') as f:
        f.write(''.join(_БУФЕР))
        f.flush()
        os.fsync(f.fileno())
    _БУФЕР.clear()


def _строка_собранного(запись):
    """Собранное со страниц пишем в файл, а не в базу: база занята боевыми.

    fsync на КАЖДУЮ компанию оказался дороже самого разбора: диск занят Зенкой
    и антивирусом, и один сброс стоил секунды — 42 компании за пять минут
    против пятисот за минуту у прежнего варианта. Копим сотню и пишем разом:
    в худшем случае после падения пересмотрим сто компаний, это секунды.
    """
    _БУФЕР.append(json.dumps(запись, ensure_ascii=False) + '\n')
    if len(_БУФЕР) >= _СБРОС:
        _сбросить_собранное()


def _уже_собрано():
    """ИНН, прочитанные со страниц ТЕКУЩЕЙ версией разбора.

    Строки прежних версий пройденными не считаются: правило подписи менялось,
    и старый результат надо пересобрать, а не унаследовать. Старые строки при
    этом не трогаем — файл дописывается, а не переписывается.
    """
    было = set()
    if not os.path.exists(СОБРАНО):
        return было
    with open(СОБРАНО, encoding='utf-8', errors='replace') as f:
        for s in f:
            try:
                з = json.loads(s)
            except Exception:  # noqa: BLE001
                continue
            if int(з.get('v') or 1) == ВЕРСИЯ:
                было.add(str(з.get('inn')))
    return было


def sliyanie(porciya=400, pauza=0.4):
    """Перенести собранное в базу ПАКЕТАМИ, своим соединением.

    Первая версия звала EnrichDB.add_phone на каждый номер, а он делает три
    чтения и свой commit — сорок тысяч отдельных запросов на блокировку. При
    живых мосте, цикле фактов и поиске сайтов это выродилось в сплошное
    «database is locked», хотя короткая запись со стороны проходит мгновенно:
    мешал не чужой замок, а собственная манера долбить его по одному разу на
    строку. Теперь одна транзакция на четыреста строк.

    Правила записи повторяют add_phone, потому что они не косметические:
      * номер приводится к десяти цифрам, иначе не номер;
      * реквизиты компании (её ИНН и ОГРН) телефоном не считаются;
      * роль канонизируется той же таблицей;
      * номер, уже записанный за ДРУГИМ предприятием, роли не получает —
        это коммутатор, а не прямой телефон;
      * непустая роль не понижается до общей, непустое ФИО не затирается.
    """
    import re as _re
    import sqlite3 as _sq
    if not os.path.exists(СОБРАНО):
        return {'нечего сливать': True}
    записи = []
    with open(СОБРАНО, encoding='utf-8', errors='replace') as f:
        for s in f:
            try:
                з = json.loads(s)
            except Exception:  # noqa: BLE001
                continue
            # Строки прежних версий разбора не сливаем: их роли собраны старым
            # правилом, и текущий прогон те же компании пересобирает заново.
            if int(з.get('v') or 1) == ВЕРСИЯ:
                записи.append(з)

    c = _sq.connect(os.environ.get('ENRICH_DB', r'C:\sender\enrich.db'),
                    timeout=60)
    c.execute('PRAGMA busy_timeout=60000')
    сделано = {str(r[0]) for r in c.execute(
        "select inn from stage_log where stage=? and coalesce(detail,'')=?",
        (СТАДИЯ, ДЕТАЛЬ))}
    реквизиты = {}
    for инн, огрн in c.execute("select inn, coalesce(ogrn,'') from companies"):
        реквизиты[str(инн)] = str(огрн or '')
    чей_номер = {}
    for инн, тел in c.execute("select inn, phone from phone_contacts"):
        d = _re.sub(r'\D', '', str(тел or ''))
        if len(d) == 11 and d[0] in '78':
            d = d[1:]
        if len(d) == 10:
            чей_номер.setdefault(d, set()).add(str(инн))

    СТРОКА = ('INSERT INTO phone_contacts(inn,phone,person,role,source,'
              'source_url,updated_at) VALUES(?,?,?,?,?,?,?) '
              'ON CONFLICT(inn,phone,source_url) DO UPDATE SET '
              "role=CASE WHEN excluded.role NOT IN ('','общий') THEN excluded.role "
              'ELSE phone_contacts.role END, '
              'updated_at=excluded.updated_at')
    теперь = time.strftime('%Y-%m-%dT%H:%M:%S')
    ст = {'компаний': 0, 'строк': 0, 'с_ролью': 0, 'реквизитов_отсеяно': 0,
          'общих_номеров': 0, 'пакетов': 0, 'сбоев_пакета': 0}
    пакет, инны = [], []
    for з in записи:
        инн = str(з.get('inn') or '')
        if not инн or инн in сделано:
            continue
        сделано.add(инн)
        ст['компаний'] += 1
        for т in з.get('tel') or []:
            d = _re.sub(r'\D', '', str(т.get('nomer') or ''))
            if len(d) == 11 and d[0] in '78':
                d = d[1:]
            if len(d) != 10:
                continue
            огрн = реквизиты.get(инн, '')
            if d and (d in инн or (огрн and d in огрн)):
                ст['реквизитов_отсеяно'] += 1
                continue
            # РОЛЬ НЕ КАНОНИЗИРУЕМ ПОВТОРНО. progon уже вернул каноническое
            # имя, а второй проход по таблице роняет обратно в «общий» всё,
            # чего в ней нет отдельным ключом: «диспетчерская» и «техконтакт»
            # каноном не опознаются как СВОИ ЖЕ выходные значения, и роль,
            # честно снятую со страницы, съедало собственное слияние.
            роль = (т.get('rol') or '').strip()
            if роль == 'общий':
                роль = ''
            чужие = чей_номер.get(d, set()) - {инн}
            if роль and чужие:
                ст['общих_номеров'] += 1
                роль = ''
            чей_номер.setdefault(d, set()).add(инн)
            if роль:
                ст['с_ролью'] += 1
            пакет.append((инн, str(т.get('nomer') or '')[:60], '', роль,
                          ИСТОЧНИК, т.get('url') or '', теперь))
        инны.append(инн)
        if len(пакет) >= porciya:
            ст['строк'] += _пакетом(c, СТРОКА, пакет, инны, ст, теперь)
            пакет, инны = [], []
            time.sleep(pauza)
    if пакет or инны:
        ст['строк'] += _пакетом(c, СТРОКА, пакет, инны, ст, теперь)
    c.close()
    _журнал({'слияние_итог': ст})
    return ст


def _пакетом(c, СТРОКА, пакет, инны, ст, теперь):
    """Одна транзакция: строки телефонов и отметки о пройденных компаниях."""
    from datetime import datetime, timezone
    метка = datetime.now(timezone.utc).isoformat(timespec='seconds')
    for попытка in range(5):
        try:
            c.execute('BEGIN IMMEDIATE')
            if пакет:
                c.executemany(СТРОКА, пакет)
            if инны:
                c.executemany(
                    'INSERT INTO stage_log(inn, stage, detail, ts) VALUES(?,?,?,?) '
                    'ON CONFLICT(inn, stage) DO UPDATE SET ts=excluded.ts',
                    [(и, СТАДИЯ, ДЕТАЛЬ, метка) for и in инны])
            c.commit()
            ст['пакетов'] += 1
            return len(пакет)
        except Exception as e:  # noqa: BLE001
            try:
                c.rollback()
            except Exception:  # noqa: BLE001
                pass
            if попытка == 4:
                ст['сбоев_пакета'] += 1
                _журнал({'пакет': str(e)[:120], 'строк': len(пакет)})
                return 0
            time.sleep(2.0 * (попытка + 1))
    return 0


def progon(predel=None, primenit=False):
    db = EnrichDB()
    свои = {str(r[0]) for r in db.cx.execute('select inn from companies')}
    # Пройденной считается компания, разобранная ТЕКУЩЕЙ версией правила.
    # Отметки прежней версии не в счёт: там подпись искали только слева и
    # только через двоеточие, и роль у этих компаний надо снять заново.
    сделано = {str(r[0]) for r in db.cx.execute(
        "select inn from stage_log where stage=? and coalesce(detail,'')=?",
        (СТАДИЯ, ДЕТАЛЬ))}
    db.cx.close()
    сделано |= _уже_собрано()
    файлы = [n for n in os.listdir(КЕШ) if n.endswith('.json.gz')]
    очередь = [n for n in файлы
               if n.split('.')[0] in свои and n.split('.')[0] not in сделано]
    if predel:
        очередь = очередь[:int(predel)]

    ст = {'компаний': 0, 'со_страницами': 0, 'номеров': 0, 'записано': 0,
          'с_ролью': 0, 'слева': 0, 'справа': 0, 'ошибок': 0}
    роли = {}
    начало = time.time()
    for i, имя in enumerate(очередь, 1):
        инн = имя.split('.')[0]
        ст['компаний'] += 1
        try:
            страницы = LS._stranicy_kesha(инн)
            if not страницы:
                if primenit:
                    _строка_собранного({'inn': инн, 'tel': [], 'v': ВЕРСИЯ})
                continue
            ст['со_страницами'] += 1
            найдено = _номера_со_страниц(страницы)
            собрано = []
            for ключ, узел in найдено.items():
                ст['номеров'] += 1
                канон = узел.get('rol') or ''
                if канон:
                    ст['с_ролью'] += 1
                    ст[узел['storona']] = ст.get(узел['storona'], 0) + 1
                    роли[канон] = роли.get(канон, 0) + 1
                url = (LS._luchshie_stranicy(узел.get('stranicy')) or [''])[0]
                собрано.append({'nomer': узел.get('kak') or ключ,
                                'rol': канон, 'url': url,
                                'podpis': узел.get('metka') or ''})
            if primenit:
                # строку пишем ВСЕГДА, даже когда телефонов не нашлось: файл
                # служит отметкой «эту компанию уже смотрели», и без неё
                # компания без номеров просматривалась бы каждый круг заново
                _строка_собранного({'inn': инн, 'tel': собрано, 'v': ВЕРСИЯ})
                ст['записано'] += len(собрано)
        except Exception as e:  # noqa: BLE001 - одна компания не рушит прогон
            ст['ошибок'] += 1
            _журнал({'инн': инн, 'ошибка': str(e)[:160]})
        if i % 500 == 0:
            _сбросить_собранное()
            скорость = i / max(1e-6, time.time() - начало)
            _журнал({'сделано': i, 'из': len(очередь), 'ст': dict(ст),
                     'в_час': int(скорость * 3600)})
            print(time.strftime('%H:%M:%S'), i, 'из', len(очередь),
                  json.dumps(ст, ensure_ascii=False), flush=True)
    _сбросить_собранное()
    ст['роли'] = dict(sorted(роли.items(), key=lambda x: -x[1])[:14])
    ст['очередь'] = len(очередь)
    ст['секунд'] = round(time.time() - начало)
    ст['режим'] = 'ЗАПИСЬ' if primenit else 'сухой'
    _журнал({'итог': ст})
    return ст


