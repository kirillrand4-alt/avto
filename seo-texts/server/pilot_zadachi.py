# -*- coding: utf-8 -*-
"""Пилот плана Meyer (владелец 08.10: «протестируй все слабые места плана… до результата с эксель»).

Баланс xmlriver на старте пилота — 95 ₽ (≈3,8 тыс. запросов), поэтому пилот — выборка, а не весь каталог
на 3 региона (~20 тыс.). Резерв ~35 ₽ — поиск сайтов, агенты, опровергатели. Каждая группа задач
проверяет одно слабое место:
  K1  Краснодарский край, пищевые «тип × регион», Яндекс; у шаблонов от ≥2 агентов — страницы 1–3
      ПРИНУДИТЕЛЬНО (тест глубины), у остальных — правило насыщения.
  K2  те же шаблоны от ≥2 агентов + 50 одиночных — Google стр. 1 (сравнение движков).
  K3  Краснодар: «продукция × регион» от ≥2 агентов + запросы критика для пробелов — Яндекс (дают ли новое).
  K4  Краснодар: «намерение» (снабжение/технолог) — 30 шт., Яндекс (ведут ли к предприятиям).
  S1  Свердловская область, непищевые «тип × регион» (все) + «продукция» от ≥2 — Яндекс; тип от ≥2 — Google.
  B1  Минская область: белорусские шаблоны — Яндекс и Google; российские пищевые «тип» от ≥2 — Яндекс
      (нужны ли отдельные белорусские формулировки).
  X1  без региона: косвенные признаки (тендеры, вакансии, кейсы, реестры, выставки, операторы) — Яндекс.
Выход: pilot-zadachi.json -> дроп (сервер читает из drop-storage).

    python3 pilot_zadachi.py          # первый прогон (выборка под баланс 95 ₽)
    python3 pilot_zadachi.py полный   # полный тест (после пополнения xmlriver 08.10)
"""
import json
import os
import random
import re
import sys

DIR = os.path.dirname(os.path.abspath(__file__))
НЕПИЩ = {'провайдер-%02d' % i for i in range(16, 25)} | {'сессия-2'}
КОСВЕННЫЕ = ('тендеры', 'вакансии_признак', 'кейсы_поставщиков', 'реестры', 'выставки_и_союзы', 'операторы_поиска',
             'инвестпроекты')


РЫБА = re.compile(r'рыб|краб|морепрод|икр[аыу]|лосос|минтай|сельд|аквакульт|форел|осетр|креветк|кальмар', re.I)


def полный():
    """Полный тест (владелец 08.10: «хмл ривер пополнил — запусти тест полный»; «рыба не нужна»): весь каталог
    на 3 региона. Яндекс — 3 страницы у шаблонов (у «намерения» — 1), Google — 1 страница; плюс замеры: Яндекс стр. 4–5
    на 100 шаблонах «тип × регион», Google стр. 2 на 300 шаблонах. Запросы про рыбу выкинуты."""
    random.seed(18)
    к = [з for з in json.load(open(os.path.join(DIR, 'meyer-zaprosy', 'katalog.json'), encoding='utf-8'))['записи']
         if з['это_запрос'] and not РЫБА.search(з['запрос'])]
    РР = ['Краснодарский край', 'Свердловская область', 'Минская область']
    КОД = {'Краснодарский край': 'K', 'Свердловская область': 'S', 'Минская область': 'M', '': 'X'}
    задачи = []
    for з in к:
        рр = (['Минская область'] if з['вид'].startswith('беларусь_') else РР) if з['шаблон'] else ['']
        for рег in рр:
            q = ' '.join(з['запрос'].replace('{регион}', рег).replace('{отрасль}', '').split())
            стр = 1 if (not з['шаблон'] or з['вид'] == 'шаблоны_намерение_регион') else 3
            задачи.append({'q': q, 'вид': з['вид'], 'рег': рег, 'агентов': len(з['источники']), 'группа': 'F-' + КОД[рег],
                           'движки': ['yandex', 'google'], 'страниц': стр, 'страниц_g': 1})
    тип = [т for т in задачи if т['вид'] == 'шаблоны_тип_регион']
    for т in random.sample(тип, 100):
        т['страниц'] = 5
        т['замер'] = 'Яндекс стр. 4–5'
    for т in random.sample([т for т in задачи if т['страниц'] == 3], 300):
        т['страниц_g'] = 2
        т.setdefault('замер', 'Google стр. 2')
    # сначала то, что не успело в первом прогоне: косвенные, намерение, Свердловская/Минская
    порядок = {'F-X': 0, 'F-S': 1, 'F-M': 2, 'F-K': 3}
    задачи.sort(key=lambda т: (порядок[т['группа']], -т['агентов']))
    with open(os.path.join(DIR, 'pilot-zadachi.json'), 'w', encoding='utf-8') as f:
        json.dump(задачи, f, ensure_ascii=False, separators=(',', ':'))
    y = sum(т['страниц'] for т in задачи)
    g = sum(т['страниц_g'] for т in задачи)
    print(len(задачи), 'Яндекс', y, 'Google', g, '≈ ₽', round((y + g) * 0.025))


def main():
    random.seed(8)
    к = [з for з in json.load(open(os.path.join(DIR, 'meyer-zaprosy', 'katalog.json'), encoding='utf-8'))['записи']
         if з['это_запрос']]

    def непищ(з):
        return set(з['источники']) <= НЕПИЩ

    def n(з):
        return len(з['источники'])

    задачи = []

    def доб(группа, з, рег, движки, страниц):
        q = ' '.join(з['запрос'].replace('{регион}', рег).replace('{отрасль}', '').split())
        задачи.append({'q': q, 'вид': з['вид'], 'рег': рег, 'агентов': n(з), 'группа': группа,
                       'движки': движки, 'страниц': страниц})

    кр, св, мн = 'Краснодарский край', 'Свердловская область', 'Минская область'
    тип_пищ = [з for з in к if з['вид'] == 'шаблоны_тип_регион' and not непищ(з)]
    for з in тип_пищ:
        доб('K1', з, кр, ['yandex'], 3 if n(з) >= 2 else 0)
    одиночные = [з for з in тип_пищ if n(з) < 2]
    for з in [з for з in тип_пищ if n(з) >= 2] + random.sample(одиночные, 50):
        доб('K2', з, кр, ['google'], 1)
    for з in к:
        if (з['вид'] == 'шаблоны_продукция_регион' and not непищ(з) and n(з) >= 2) or з['вид'] == 'шаблоны_пробелы_регион':
            доб('K3', з, кр, ['yandex'], 0)
    for з in random.sample([з for з in к if з['вид'] == 'шаблоны_намерение_регион' and not непищ(з)], 30):
        доб('K4', з, кр, ['yandex'], 1)
    for з in к:
        if з['вид'] == 'шаблоны_тип_регион' and непищ(з):
            доб('S1', з, св, ['yandex', 'google'] if n(з) >= 2 else ['yandex'], 0)
        elif з['вид'] == 'шаблоны_продукция_регион' and непищ(з) and n(з) >= 2:
            доб('S1', з, св, ['yandex'], 0)
        elif з['вид'] in ('беларусь_шаблоны_тип_регион', 'беларусь_шаблоны_продукция_регион'):
            доб('B1', з, мн, ['yandex', 'google'] if з['вид'] == 'беларусь_шаблоны_тип_регион' else ['yandex'], 0)
        elif з['вид'] in КОСВЕННЫЕ and not з['шаблон']:
            доб('X1', з, '', ['yandex'], 0)
    for з in тип_пищ:
        if n(з) >= 2:
            доб('B1r', з, мн, ['yandex'], 0)
    with open(os.path.join(DIR, 'pilot-zadachi.json'), 'w', encoding='utf-8') as f:
        json.dump(задачи, f, ensure_ascii=False, separators=(',', ':'))
    сч = {}
    for з in задачи:
        сч[з['группа']] = сч.get(з['группа'], 0) + len(з['движки']) * max(1, з['страниц'])
    print(len(задачи), 'запросов минимум ~', sum(сч.values()), сч)


if __name__ == '__main__':
    полный() if 'полный' in sys.argv[1:] else main()
