def _slova(imya):
    t = re.sub(r'^(ООО|АО|ЗАО|ПАО|ОАО|ИП|АКЦИОНЕРНОЕ ОБЩЕСТВО|'
               r'ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ)\s*', '',
               (imya or '').upper()).strip(' "«»')
    return [w for w in re.split(r'[\s"«»,\-]+', t) if len(w) > 3]


