def _ne_iskali(src):
    """Отказ был поломкой канала, а не ответом поиска?"""
    s = str(src or '')
    return any(м in s for м in _НЕ_ИСКАЛИ)


def _с_повтором(c, дело, попыток=4):
    """Выполнить запрос, коротко пересиживая занятую базу.

    Попыток было сорок с паузами до десяти секунд — до семи минут на один
    запрос. Это имело смысл, пока замок считался случайным. Он не случайный:
    сверки по расписанию держат базу по четверти часа, и столько ждать нечего.
    Теперь четыре коротких попытки, а не вышло — находка уходит в копилку
    (`_отложить`) и переливается следующим кругом. Возврат: ('ок', значение)
    либо ('занято', None) — вызывающий обязан различать.
    """
    for i in range(попыток):
        try:
            return 'ок', дело()
        except sqlite3.OperationalError as e:
            if 'locked' not in str(e).lower() and 'busy' not in str(e).lower():
                raise
            try:
                c.rollback()
            except Exception:  # noqa: BLE001
                pass
            time.sleep(1 + i)
    return 'занято', None


def _отложить(записи):
    """Сложить незаписанные находки в копилку на диск, с fsync."""
    if not записи:
        return 0
    with open(ОЖИДАЮТ, 'a', encoding='utf-8') as f:
        for з in записи:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
        f.flush()
        os.fsync(f.fileno())
    return len(записи)


def _прочесть_копилку():
    из = []
    if not os.path.exists(ОЖИДАЮТ):
        return из
    with open(ОЖИДАЮТ, encoding='utf-8', errors='replace') as f:
        for s in f:
            if not s.strip():
                continue
            try:
                из.append(json.loads(s))
            except Exception:  # noqa: BLE001
                pass
    return из


def _переписать_копилку(остаток):
    """Атомарно: пишем во временный и подменяем, чтобы обрыв не стёр копилку."""
    врем = ОЖИДАЮТ + '.tmp'
    with open(врем, 'w', encoding='utf-8') as f:
        for з in остаток:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
        f.flush()
        os.fsync(f.fileno())
    os.replace(врем, ОЖИДАЮТ)


def _слить_копилку(c):
    """Перелить накопленное в базу. Что не прошло — остаётся ждать дальше."""
    копилка = _прочесть_копилку()
    if not копилка:
        return {}
    легло, осталось = 0, []
    for з in копилка:
        если = _записать_находку(c, з)
        if если:
            легло += 1
        else:
            осталось.append(з)
    _переписать_копилку(осталось)
    return {'из_копилки_легло': легло, 'в_копилке_осталось': len(осталось)}


def _записать_находку(c, з):
    """Одна находка в companies. True — легла, False — база занята."""
    состояние, есть = _с_повтором(
        c, lambda: c.execute('select 1 from companies where inn=?',
                             (з['inn'],)).fetchone())
    if состояние == 'занято':
        return False
    if not есть:
        состояние, _ = _с_повтором(c, lambda: c.execute(
            'INSERT INTO companies(inn, name, region, updated_at) VALUES(?,?,?,?)',
            (з['inn'], (з.get('name') or '')[:200], (з.get('city') or '')[:80],
             time.strftime('%Y-%m-%dT%H:%M:%S'))))
        if состояние == 'занято':
            return False
    if з.get('verdikt'):
        состояние, _ = _с_повтором(c, lambda: c.execute(
            'update companies set site=?, site_source=?, updated_at=? where inn=?',
            (з['site'], з['verdikt'], time.strftime('%Y-%m-%dT%H:%M:%S'), з['inn'])))
    else:
        состояние, _ = _с_повтором(c, lambda: c.execute(
            "update companies set cand_site=?, updated_at=? where inn=? "
            "and coalesce(site,'')=''",
            (з['site'], time.strftime('%Y-%m-%dT%H:%M:%S'), з['inn'])))
    if состояние == 'занято':
        return False
    состояние, _ = _с_повтором(c, c.commit)
    return состояние == 'ок'


def цели(skolko, dolya=None):
    """База обзвона по убыванию выручки: у кого сайта нет нигде и кого ещё не искали.

    Доля была 30%: начинали с верха по выручке, чтобы проверить саму затею и не
    жечь деньги вслепую. Затея проверена — 29 пачек, 351 рубль, — и владелец
    17.08 сказал брать всех. Порядок остаётся по выручке: крупные ищутся первыми,
    и если прогон остановить, остановится он на менее ценных.
    """
    dolya = float(os.environ.get('POISK_DOLYA', '1.0')) if dolya is None else dolya
    # СПИСОК ЦЕЛЕЙ ФАЙЛОМ. Владелец 28.08: «запускай под хмл под мейер, выручка
    # не известна либо от 30 млн». Поиск платный, и гнать его по всей базе,
    # когда просили одно направление, — это чужие деньги на ветер. Файл с ИНН
    # по строке в POISK_SPISOK сужает цели до него, порядок по выручке
    # сохраняется. Нет переменной — поведение прежнее, вся база.
    #
    # ФАЙЛА НЕТ — ЭТО ОТКАЗ, А НЕ «ищем всех». 28.08 я перезапустил прогон,
    # подставив выдуманное имя списка; файла не оказалось, сужение молча
    # снялось, и платный поиск ушёл по всей базе вместо мейера. Просили одно
    # направление — значит без списка не искать вовсе. Та же порода ошибки, что
    # no-xmlriver-key: тихий откат к поведению «как будто ничего не просили».
    только = None
    путь_списка = os.environ.get('POISK_SPISOK', '')
    if путь_списка:
        if not os.path.exists(путь_списка):
            raise SystemExit('POISK_SPISOK указан, но файла нет: ' + путь_списка)
        только = set()
        with open(путь_списка, encoding='utf-8', errors='replace') as f:
            for стр in f:
                и = ''.join(ch for ch in стр.strip() if ch.isdigit())
                if и:
                    только.add(и)
        if not только:
            raise SystemExit('POISK_SPISOK пуст: ' + путь_списка)
    o = sqlite3.connect(OBZVON)
    строки = []
    for inn, sites, rev, ns, nf, reg in o.execute(
            "select inn, coalesce(sites,''), coalesce(revenue,''), coalesce(name_short,''), "
            "coalesce(name_full,''), coalesce(region,'') from obzvon"):
        i = str(inn or '').strip()
        if not i:
            continue
        строки.append((выручка(rev), i, (sites or '').strip(), ns or nf, reg))
    o.close()
    строки.sort(reverse=True)
    порог_шт = int(len(строки) * dolya)
    верх = строки[:порог_шт]

    c = sqlite3.connect(BD)
    est = {str(r[0]) for r in c.execute(
        "select inn from companies where coalesce(site,'')<>'' or coalesce(cand_site,'')<>''")}
    c.close()
    уже, несостоялось = set(), set()
    if os.path.exists(LOG):
        with open(LOG, encoding='utf-8') as f:
            for s in f:
                try:
                    d = json.loads(s)
                except Exception:  # noqa: BLE001
                    continue
                i = d.get('inn')
                if not i:
                    continue
                if d.get('site') or not _ne_iskali(d.get('src')):
                    уже.add(i)
                else:
                    несостоялось.add(i)
    # запись о НЕСОСТОЯВШЕМСЯ поиске «уже искали» не значит: 19.08 в логе нашлось
    # 73 303 строки «no-xmlriver-key» — прогон 17.08 стартовал без ключа в
    # окружении, каждой компании записал отказ и тем самым вычеркнул её из целей
    # навсегда. Поэтому запись-неудача снимается, если она была не приговором
    # поиска, а поломкой канала; настоящее «искали и не нашли» остаётся.
    #
    # НО ТОЛЬКО ЕСЛИ ВСЕ ЗАПИСИ КОМПАНИИ — ОТКАЗЫ. Здесь стояло
    # `уже -= несостоялось`, и одна запись про отказ канала снимала компанию с
    # «уже искали» даже тогда, когда рядом лежала запись с найденным сайтом.
    # В 2019-м это было безобидно: у компаний с no-xmlriver-key других записей
    # не существовало. А 28.08 прогон на десяти каналах отдал 37–55% отказов, и
    # тысячи компаний получили по такой записи — после чего возвращались в
    # очередь каждый круг и обыскивались заново за наши деньги. Замер: в
    # последних 600 строках журнала 194 записи с сайтом, но всего 45 разных
    # доменов, один ИНН встречается по восемь раз.
    несостоялось -= уже
    уже -= несостоялось
    из = []
    for rev, i, sites, name, reg in верх:
        if только is not None and i not in только:
            continue
        if sites or i in est or i in уже:
            continue
        из.append({'inn': i, 'name': name, 'city': reg, 'revenue': rev})
        if len(из) >= skolko:
            break
    return из, (верх[-1][0] if верх else 0), len(верх)


