# -*- coding: utf-8 -*-
"""Третий файл базы Meyer (владелец 06.10): номера без ролей, «но номер точно должен быть
на странице». Собирается из meyer-nalichie.jsonl (meyer_nalichie.py на сервере).

В основной лист идёт номер, только если он найден на ЖИВОЙ странице-источнике И страница
принадлежит этой компании (её сайт, её название или ИНН на странице). Отдельно, для
сведения: номер есть, но страница не подтверждена как своя; номер был при обходе, а сейчас
со страницы пропал. Внутри компании — мобильные первыми.

    python meyer_tretiy.py meyer-kompanii.csv meyer-kontakty.csv meyer-nalichie.jsonl sdelki.json out.xlsx
"""
import collections
import csv
import json
import sys
import time

from openpyxl import Workbook
from openpyxl.cell import WriteOnlyCell
from openpyxl.styles import Alignment, Font

from meyer_xlsx import БАЗА, ПОРЯДОК, лист, мусор, сделки, читать

csv.field_size_limit(10 ** 8)


def main(п_комп, п_конт, п_нал, п_сд, п_out):
    сд = сделки(п_сд)
    комп = {к['ИНН']: к for к in читать(п_комп) if к['ИНН'] not in сд}
    for к in комп.values():
        к['В какой базе обзвона'] = БАЗА.get(к['В какой базе обзвона'], 'нет в базе обзвона')
    # сведения о номере (тип, подпись в базе, источник) — из той же выгрузки, что и вход проверки
    свед = {}
    for з in читать(п_конт):
        if з['ИНН'] not in комп or not (з['Мобильный'] or з['Рабочий']):
            continue
        url = з['Ссылка на источник']
        if not url.startswith('http') or мусор(з):
            continue
        ном = з['Мобильный'] or з['Рабочий'].split(' доб.')[0]
        ключ = '%s|%s|%s' % (з['ИНН'], ном, з['Добавочный'] or '') + '|' + url
        свед.setdefault(ключ, з)
    подтв, чужие, пропали = [], [], []
    недоступно = collections.Counter()
    with open(п_нал, encoding='utf-8') as f:
        for s in f:
            р = json.loads(s)
            з = свед.get(р['id'] + '|' + р['url'])
            к = комп.get(р['inn'])
            if not з or not к:
                continue
            строка = {
                'Название': к['Название'], 'ИНН': к['ИНН'], 'Регион': к['Регион'], 'Сайт': к['Сайт'],
                'Основной ОКВЭД': к['Основной ОКВЭД'], 'Выручка, руб': к['Выручка, руб'],
                'Сегмент': к['Сегмент'], 'Попадание': к['Попадание'],
                'Тип номера': 'мобильный' if з['Мобильный'] else ('городской + доб.' if з['Добавочный'] else 'городской'),
                'Номер': з['Мобильный'] or з['Рабочий'],
                'Подпись в базе': '' if з['Роль'] == 'не указана' else з['Роль'],
                'Источник': з['Источник'], 'Ссылка на источник': р['url'],
                'Чья страница': р.get('компания_на_странице', ''),
                'Как стоит на странице': р.get('контекст', ''),
                'Проверено': time.strftime('%d.%m.%Y')}
            if р['страница'] != 'ok':
                недоступно[р['страница'][:40]] += 1
                if р.get('в_кэше_обхода'):
                    строка['Как стоит на странице'] = 'страница недоступна; при обходе номер был: ' + р['в_кэше_обхода']
                    пропали.append(строка)
            elif р['найден']:
                (подтв if строка['Чья страница'].startswith('да') else чужие).append(строка)
            elif р.get('в_кэше_обхода'):
                строка['Как стоит на странице'] = 'сейчас на странице нет; при обходе был: ' + р['в_кэше_обхода']
                пропали.append(строка)

    def порядок(строки):
        место = {}
        for к in sorted({x['ИНН'] for x in строки}, key=lambda i: (
                ПОРЯДОК.get(комп[i]['Попадание'], 9), комп[i]['Сегмент'].split(' | ')[0],
                -float(комп[i]['Выручка, руб'] or 0))):
            место[к] = len(место)
        строки.sort(key=lambda x: (место[x['ИНН']], x['Тип номера'] != 'мобильный',
                                    x['Тип номера'] != 'городской + доб.', bool(x['Подпись в базе'])))
        return строки
    for с in (подтв, чужие, пропали):
        порядок(с)

    компании = collections.OrderedDict()
    for x in подтв:
        к = компании.setdefault(x['ИНН'], dict(комп[x['ИНН']], **{'Номеров подтверждено': 0,
                                                                  'Мобильный': '', 'Городской': ''}))
        к['Номеров подтверждено'] += 1
        if x['Тип номера'] == 'мобильный' and not к['Мобильный']:
            к['Мобильный'] = x['Номер']
        if x['Тип номера'] != 'мобильный' and not к['Городской']:
            к['Городской'] = x['Номер']

    wb = Workbook(write_only=True)
    ws = wb.create_sheet('Сводка')
    ws.column_dimensions['A'].width = 80
    ws.column_dimensions['B'].width = 14
    b = Font(bold=True)

    def ж(т):
        c = WriteOnlyCell(ws, value=т)
        c.font = b
        return c

    def текст(т):
        c = WriteOnlyCell(ws, value=т)
        c.alignment = Alignment(wrap_text=True, vertical='top')
        ws.append([c])
    ws.append([ж('База под Meyer — номера без ролей, подтверждённые на странице (на %s)' % time.strftime('%d.%m.%Y'))])
    ws.append(['Компаний', len(компании)])
    ws.append(['Номеров подтверждено (лист «Номера»)', len(подтв)])
    тип = collections.Counter(x['Тип номера'] for x in подтв)
    for т, n in тип.most_common():
        ws.append(['  ' + т, n])
    чья = collections.Counter(x['Чья страница'] for x in подтв)
    for т, n in чья.most_common():
        ws.append(['  ' + т, n])
    ws.append([])
    ws.append([ж('Не вошли в основной лист')])
    ws.append(['Номер на странице есть, но страница не подтверждена как своя (лист «Страница не подтверждена»)', len(чужие)])
    ws.append(['Был на странице при обходе, сейчас нет или страница недоступна (лист «Пропали»)', len(пропали)])
    for т, n in недоступно.most_common(6):
        ws.append(['  страница не открылась: ' + т, n])
    ws.append([])
    ws.append([ж('Правила')])
    for т in (
            'Берутся номера со страниц (у номера есть ссылка на источник), которые не вошли в файлы ЛПР: '
            'без роли в исходной базе или с ролью не из ТЗ (общий, продажи, бухгалтерия и т.п. — она в '
            'колонке «Подпись в базе»).',
            'Номер засчитан, только если он найден на ЖИВОЙ странице-источнике в любом написании (в т.ч. '
            'в tel:-ссылке и слитно с 8) И страница принадлежит этой компании: её сайт, её название или '
            'ИНН на странице. Колонка «Как стоит на странице» — текст вокруг номера.',
            'Чужие страницы (справочник с другой компанией) отделены: во втором файле модель нашла 39 из '
            '195 номеров на страницах чужих компаний.',
            'Без компаний, где идёт сделка, и без номеров с заброшенных сайтов. Внутри компании — '
            'мобильные первыми, затем с добавочным, затем городские.'):
        текст(т)
    поля = ['Название', 'ИНН', 'Регион', 'Сайт', 'Основной ОКВЭД', 'Выручка, руб', 'Сегмент', 'Попадание',
            'Тип номера', 'Номер', 'Подпись в базе', 'Источник', 'Ссылка на источник', 'Чья страница',
            'Как стоит на странице', 'Проверено']
    ширины = [34, 12, 20, 22, 9, 15, 22, 16, 14, 18, 16, 20, 40, 24, 60, 11]
    поля_к = ['Название', 'ИНН', 'Регион', 'Город', 'Сайт', 'Основной ОКВЭД', 'Доп. ОКВЭД', 'Описание',
              'Выручка, руб', 'Год выручки', 'Сегмент', 'Сегмент по основному ОКВЭД', 'Попадание',
              'В какой базе обзвона', 'Номеров подтверждено', 'Мобильный', 'Городской']
    лист(wb, 'Компании', поля_к, list(компании.values()),
         [34, 12, 20, 14, 22, 9, 30, 40, 15, 7, 22, 18, 16, 14, 9, 18, 18])
    лист(wb, 'Номера', поля, подтв, ширины)
    лист(wb, 'Страница не подтверждена', поля, чужие, ширины)
    лист(wb, 'Пропали', поля, пропали, ширины)
    wb.save(п_out)
    print('компаний', len(компании), 'подтверждено', len(подтв), dict(тип), '| чужие', len(чужие),
          '| пропали', len(пропали))


if __name__ == '__main__':
    main(*sys.argv[1:6])
