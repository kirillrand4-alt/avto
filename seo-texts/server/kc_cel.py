def по_ящику(почта):
    лок = (почта or '').lower().split('@')[0]
    for кус in (лок, re.split(r'[._-]', лок)[0]):
        for rx, ст in _ЯЩИК:
            if rx.match(кус):
                return True, ст
    return False, None


def ступень(роль, сегмент='', должность='', почта='', фио=''):
    """-> int (меньше — писать раньше) или None (не писать никогда)."""
    по_ящ, ст_ящ = по_ящику(почта)
    if по_ящ and ст_ящ is НИКОГДА:
        return НИКОГДА
    if re.search(r'hotline|anticor|antikor|doverie|ethics|compliance', (почта or '').lower().split('@')[0]):
        return НИКОГДА
    if _ЗАПРЕТ_ЯЩИК.search((почта or '').lower().split('@')[0]) or _ЗАПРЕТ_ЯЩИК.search(должность or ''):
        return НИКОГДА
    if _ЗАПРЕТ_ТЕКСТ.search(должность or '') and роль not in ('Руководитель', 'Технолог', 'Производство',
                                                               'Техдиректор / главный инженер', 'Механик / энергетик / ремонт'):
        return НИКОГДА
    if роль in ПО_РОЛИ:
        ст = ПО_РОЛИ[роль]
        if ст is not НИКОГДА and ст >= 8 and по_ящ and ст_ящ is not НИКОГДА:
            ст = min(ст, ст_ящ)
        elif ст is not НИКОГДА and по_ящ and ст_ящ == 8:
            ст = max(ст, ст_ящ)
    elif по_ящ:
        ст = ст_ящ
    else:
        ст = 9 if фио else 8
    return ст if ст is not НИКОГДА else НИКОГДА


def ключ(роль, сегмент='', должность='', почта='', фио='', лпр='', сайт=''):
    """Ключ сортировки почт компании по лесенке; None — не писать."""
    ст = ступень(роль, сегмент, должность, почта, фио)
    if ст is НИКОГДА:
        return None
    дом = (почта or '').lower().split('@')[-1]
    сайт = re.sub(r'^(https?://)?(www\.)?', '', (сайт or '').lower()).split('/')[0]
    личный = bool(фио) and not (по_ящику(почта)[0] and роль == 'Общий номер / приёмная')
    return (ст, {'да': 0, 'возможно': 1}.get(лпр or '', 2), 0 if личный else 1,
            0 if сайт and (дом == сайт or дом.endswith('.' + сайт) or сайт.endswith('.' + дом)) else 1 if дом not in БЕСПЛАТНЫЕ else 2)


def название(ст):
    return НАЗВАНИЕ.get(ст, '')


