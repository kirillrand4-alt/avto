r"""Описание компании и «целевая ли для Meyer» по тексту живого сайта (владелец 07.10).

Для 460 компаний базы CC с ИНН: главная + «о компании»/«продукция» (до 4 страниц, список
из cc_obhod), текст -> модель (провайдерский API): описание деятельности/продукции в стиле
колонки «Описание» базы Meyer и вердикт, целевая ли компания для Meyer.

Вход: C:\seostat\drop\drop-storage\cc-opis-vhod.json. Выход (fsync, резюм по домену):
C:\sender\server\cc-opisanie.jsonl.
"""
import io
import json
import os
import re
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor

DIR = r'C:\sender\server'
sys.path.insert(0, DIR)
sys.path.insert(0, r'C:\sender')
os.chdir(DIR)
import meyer_proverka as MP  # noqa: E402
import meyer_nalichie as MN  # noqa: E402
import verify_company as VC  # noqa: E402

ВХОД = r'C:\seostat\drop\drop-storage\cc-opis-vhod.json'
ВЫХОД = os.path.join(DIR, 'cc-opisanie.jsonl')
_лок = threading.Lock()

ПРОМПТ = (
    'Компания: {название} (ИНН {инн}), сайт {домен}. Заголовок сайта: «{заголовок}». ОКВЭД основной: {оквэд}.\n'
    'Текст с сайта (главная, «о компании», продукция):\n«««{текст}»»»\n\n'
    'Meyer (направление ООО «Руспром») продаёт фотосепараторы (оптическую сортировку) и рентген-'
    'инспекцию. Целевые клиенты: те, кто САМ выращивает, хранит, перерабатывает, чистит, сортирует, '
    'фасует или экспортирует зерно, зернобобовые, масличные, семена (семеноводство), крупы, муку, '
    'орехи, сухофрукты, ягоды (в т.ч. заморозку), кофе, специи, а также любые пищевые производства '
    '(мясо, рыба, молочка, кондитерка, хлеб, снеки, корма, напитки с сырьём), где сортируют сырьё или '
    'проверяют продукцию на посторонние включения; элеваторы и хлебоприёмные предприятия.\n'
    'НЕ целевые: продавцы оборудования/упаковки/химии, сервис, логистика без склада зерна, розница и '
    'общепит, агрохолдинги-животноводы без переработки, СМИ, госорганы, не пищевые производства.\n'
    'Ответ — ТОЛЬКО JSON без markdown: {{"описание":"1–2 предложения: чем занимается и что '
    'производит/перерабатывает, по фактам с сайта, без рекламы","продукция":"через запятую, до 8 '
    'позиций","целевая":"да|нет|неясно","сегмент":"экспортёры|семеноводы|пищевые|элеваторы|орехи|'
    'ягоды|нет","почему":"до 15 слов"}}')


def записать(з):
    with _лок:
        with io.open(ВЫХОД, 'a', encoding='utf-8') as f:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())


def одна(о):
    кусочки, статусы = [], []
    for u in о['страницы'][:4]:
        ст, html, _ = MN.скачать(u)
        статусы.append([u, ст])
        if ст == 'ok':
            т = re.sub(r'\[tel:[^\]]*\]', ' ', MP.в_текст(html))
            т = re.sub(r'\n\s*\S{1,25}\s*(?=\n)', '\n', т)  # пункты меню и кнопки
            кусочки.append(re.sub(r'\s+', ' ', т)[:2600])
    з = {'домен': о['домен'], 'инн': о['инн'], 'страницы': статусы}
    if not кусочки:
        з['итог'] = 'сайт не открылся'
        записать(з)
        return
    промпт = ПРОМПТ.format(название=о['название'] or о['заголовок'][:80], инн=о['инн'], домен=о['домен'],
                           заголовок=о['заголовок'][:150], оквэд=о['оквэд'] or 'неизвестен',
                           текст='\n---\n'.join(кусочки)[:8000])
    for попытка in range(3):
        try:
            out = VC._provider_call_stdlib(промпт)
            з.update(json.loads(re.search(r'\{.*\}', out, re.S).group(0)))
            з['итог'] = 'ok'
            break
        except Exception as e:  # noqa: BLE001
            з['итог'] = 'ошибка модели: ' + repr(e)[:80]
            time.sleep(6 * (попытка + 1))
    записать(з)


def main():
    вход = json.load(io.open(ВХОД, encoding='utf-8'))
    сделано = set()
    if os.path.exists(ВЫХОД):
        for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
            try:
                з = json.loads(s)
                if з.get('итог') == 'ok' or з.get('итог') == 'сайт не открылся':
                    сделано.add(з['домен'])
            except ValueError:
                pass
    очередь = [о for о in вход if о['домен'] not in сделано]
    print('компаний', len(вход), 'в очереди', len(очередь), flush=True)
    with ThreadPoolExecutor(12) as ex:
        list(ex.map(одна, очередь))
    print('готово', flush=True)


if __name__ == '__main__':
    main()
