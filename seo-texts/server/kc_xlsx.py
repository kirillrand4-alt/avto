def порядок(класс, фио, моб):
    if класс in ПОКУПАТЕЛИ:
        п = 1 if фио else 2
    elif класс == 'директор':
        п = 3
    elif класс in ТЕХ:
        п = 4
    elif класс in ОБЩИЙ:
        п = 6
    else:
        п = 5
    return (п, 0 if моб else 1)


