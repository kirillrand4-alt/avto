def отличительные(имя):
    т = re.sub(r'[«»"\'()&;]|quot', ' ', имя or '').lower().replace('ё', 'е').replace('-', ' ')
    return {w for w in re.findall(r'[а-яa-z]{5,}', т) if w not in ОБЩИЕ_СЛОВА}


def лист(wb, имя, поля, строки, ширины):
    _лист(wb, имя, поля, [dict(zip(поля, r)) if isinstance(r, list) else r for r in строки], ширины)


def ном(н):
    ц = re.sub(r'\D', '', н or '')
    if len(ц) == 11 and ц[0] in '78':
        ц = '7' + ц[1:]
    elif len(ц) == 10:
        ц = '7' + ц
    if len(ц) != 11 or ц[1] in '012':
        return ''
    return '+7 %s %s-%s-%s' % (ц[1:4], ц[4:7], ц[7:9], ц[9:11])


def класс_должности(п):
    for rx, к in ДОЛЖН_КЛАСС:
        if re.search(rx, п or '', re.I):
            return к
    return ''


