def записать(з):
    with _лок:
        with io.open(ВЫХОД, 'a', encoding='utf-8') as f:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())


def поиск(q):
    U, K = os.environ.get('XMLRIVER_USER', ''), os.environ.get('XMLRIVER_KEY', '')
    url = ('http://xmlriver.com/search_yandex/xml?user=%s&key=%s&groupby=10&query=%s'
           % (urllib.parse.quote(U), urllib.parse.quote(K), urllib.parse.quote(q)))
    for _ in range(3):
        try:
            xml = urllib.request.build_opener(urllib.request.ProxyHandler({})).open(url, timeout=120).read().decode('utf-8', 'replace')
        except Exception:  # noqa: BLE001
            continue
        if 'перезапрос' in xml:
            continue
        out = []
        for блок in re.findall(r'<doc>(.*?)</doc>', xml, re.S)[:10]:
            ч = lambda t: re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', t or '')).strip()  # noqa: E731
            u = ч((re.search(r'<url>(.*?)</url>', блок, re.S) or [None, ''])[1])
            т = ч((re.search(r'<title>(.*?)</title>', блок, re.S) or [None, ''])[1])
            п = ч((re.search(r'<passage>(.*?)</passage>', блок, re.S) or [None, ''])[1])
            out.append('%s | %s | %s' % (u, т[:100], п[:200]))
        return '\n'.join(out) or 'пусто'
    return 'поиск не ответил'


def показать(текст):
    """Текст страницы для модели: начало + окна вокруг телефонов (подпись обычно перед номером)."""
    окна = []
    for м in list(CO.ТЕЛ.finditer(текст))[:25]:
        окна.append('…' + текст[max(0, м.start() - 160):м.end() + 30].replace('\n', ' ') + '…')
    return текст[:2500] + ('\n[телефоны на странице с подписями]\n' + '\n'.join(окна) if окна else '\n[телефонов на странице нет]')


def агент(к):
    история, открыто = [], {}
    поисков, откр = ПОИСКОВ, 10
    итог = None
    for шаг in range(ШАГОВ):
        промпт = ПРАВИЛА.format(поисков=поисков, открыть=откр, имя=к['имя'], инн=к['inn'], регион=к['регион'], осн=к['осн'],
                                сегм=к['сегм'], выр=round((к['выручка'] or 0) / 1e9, 1), отклонены=к.get('отклонены') or 'нет',
                                история='\n\n'.join(история)[-14000:] or '(пока ничего)')
        д = KK.модель(промпт, False) or {}
        a = д.get('действие')
        if a == 'готово' or (поисков <= 0 and откр <= 0):
            итог = д if a == 'готово' else None
            break
        if a == 'поиск' and поисков > 0:
            поисков -= 1
            q = (д.get('запрос') or '')[:200]
            история.append('ПОИСК «%s»:\n%s' % (q, поиск(q)))
        elif a == 'открыть' and откр > 0:
            откр -= 1
            u = (д.get('url') or '').strip()
            if not u.startswith('http'):
                u = 'http://' + u
            ст, html, _ = MN.скачать(u)
            т = MP.в_текст(html) if ст == 'ok' else ''
            открыто[u] = т
            история.append('ОТКРЫТ %s [%s]:\n%s' % (u, ст, показать(т) if т else '(не открылась)'))
        else:
            история.append('(неверное действие, повтори JSON)')
    if итог is None:  # бюджет кончился — попросить итог по собранному
        д = KK.модель(ПРАВИЛА.format(поисков=0, открыть=0, имя=к['имя'], инн=к['inn'], регион=к['регион'], осн=к['осн'],
                                     сегм=к['сегм'], выр=round((к['выручка'] or 0) / 1e9, 1), отклонены=к.get('отклонены') or 'нет',
                                     история='\n\n'.join(история)[-14000:]) + ' (лимит исчерпан — только «готово»)', False) or {}
        итог = д if д.get('действие') == 'готово' else {}
    return итог, открыто, история


def проверить(к, итог, открыто):
    """Скрипт проверяет итог агента по реально открытым страницам."""
    дом = lambda u: MN.домен(u) if u else ''  # noqa: E731
    текст_домена = {}
    for u, т in открыто.items():
        текст_домена.setdefault(дом(u), []).append(т.lower().replace('ё', 'е'))
    ядра = KS.ядра(к['имя'])

    def домен_чей(u):
        тт = ' '.join(текст_домена.get(дом(u), []))
        if not тт:
            return ''
        if к['inn'] in тт:
            return 'ИНН компании на сайте'
        for я in ядра:
            if я in тт:
                return 'название «%s» на сайте' % я
        return ''
    рез = {'пояснение': итог.get('пояснение', ''), 'холдинг': итог.get('холдинг', '')}
    сз = итог.get('сайт_завода') or ''
    рез['сайт_завода'] = сз
    рез['сайт_завода_чей'] = домен_чей(сз) if сз else ''
    сх = итог.get('сайт_холдинга') or ''
    рез['сайт_холдинга'] = сх
    дх = итог.get('доказательство_холдинга') or {}
    цит = re.sub(r'\s+', ' ', (дх.get('цитата') or '').lower().replace('ё', 'е')).strip(' .«»"')
    стр = re.sub(r'\s+', ' ', (открыто.get(дх.get('url') or '') or '').lower().replace('ё', 'е'))
    рез['холдинг_подтверждён'] = bool(цит and len(цит) >= 15 and (цит in стр or цит[:40] in стр))
    рез['доказательство_холдинга'] = дх
    годные_домены = set()
    if сз and рез['сайт_завода_чей']:
        годные_домены.add(дом(сз))
    if сх and рез['холдинг_подтверждён']:
        годные_домены.add(дом(сх))
    номера, снято = [], []
    for н in итог.get('номера') or []:
        u = (н.get('url') or '').strip()
        т = открыто.get(u) or открыто.get(u.rstrip('/')) or открыто.get(u + '/') or ''
        ц = re.sub(r'\D', '', н.get('номер') or '')
        if len(ц) == 11 and ц[0] in '78':
            ц = '7' + ц[1:]
        elif len(ц) == 10:
            ц = '7' + ц
        причина = ''
        if len(ц) != 11:
            причина = 'не номер'
        elif not т:
            причина = 'агент не открывал эту страницу'
        elif not MP.найти(т, ц[-10:]):
            причина = 'номера нет на странице'
        elif ЗАКУПКИ.search(u):
            if к['inn'] not in т:
                причина = 'на карточке закупки нет ИНН компании'
        elif дом(u) not in годные_домены:
            причина = 'страница не на подтверждённом сайте завода/холдинга (%s)' % дом(u)
        запись = dict(н, номер=ц, url=u)
        if причина:
            снято.append(dict(запись, причина=причина))
        else:
            номера.append(запись)
    рез['номера'], рез['снято'] = номера, снято
    return рез


def одна(к):
    итог, открыто, история = агент(к)
    рез = проверить(к, итог, открыто) if итог else {'пояснение': 'агент не дал итог', 'номера': [], 'снято': []}
    рез.update({'inn': к['inn'], 'итог': 'ok', 'страниц_открыто': len(открыто), 'шагов': len(история),
                'журнал': [h[:300] for h in история]})
    записать(рез)


def main():
    вход = json.load(io.open(ВХОД, encoding='utf-8'))  # {инн: {отклонены: ...}}
    сп = json.load(io.open(os.path.join(DIR, НАБОР + '-spisok.json'), encoding='utf-8'))['компании']
    сделано = set()
    if os.path.exists(ВЫХОД):
        for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
            try:
                сделано.add(json.loads(s)['inn'])
            except (ValueError, KeyError):
                pass
    задачи = [dict(сп[i], отклонены=v.get('отклонены', '')) for i, v in вход.items() if i in сп and i not in сделано]
    print('компаний', len(задачи), flush=True)
    n = [0]

    def шаг(к):
        try:
            одна(к)
        except Exception as e:  # noqa: BLE001
            записать({'inn': к['inn'], 'итог': 'сбой', 'ошибка': repr(e)[:150]})
        n[0] += 1
        if n[0] % 10 == 0:
            print('готово %d/%d' % (n[0], len(задачи)), flush=True)

    with ThreadPoolExecutor(10) as ex:
        list(ex.map(шаг, задачи))
    shutil.copyfile(ВЫХОД, os.path.join(ДРОП, НАБОР + '-glubokiy.jsonl'))
    print('готово', flush=True)


if __name__ == '__main__':
    main()
