def записать(з):
    with _лок:
        with io.open(ВЫХОД, 'a', encoding='utf-8') as f:
            f.write(json.dumps(з, ensure_ascii=False) + '\n')
            f.flush()
            os.fsync(f.fileno())


def улики(к, з):
    сайт = з['сайт']
    корень = 'https://' + MN.домен(сайт) + '/'
    urls = [u for u, ст in з.get('страницы', []) if ст == 'ok'][:5]
    urls += [корень + п for п in ТИПОВЫЕ if корень + п not in urls]
    тексты, места, все_инн = [], [], collections.Counter()
    for u in urls:
        if len(тексты) >= 7:
            break
        ст, html, _ = MN.скачать(u)
        if ст != 'ok':
            continue
        т = re.sub(r'\[tel:[^\]]*\]', ' ', MP.в_текст(html))
        тексты.append((u, re.sub(r'\s+', ' ', т)))
        for м in CO.ИНН_RX.finditer(т):
            if CO.инн_ок(м.group(1)):
                все_инн[м.group(1)] += 1
                if м.group(1) == к['inn'] and len(места) < 4:
                    окно = re.sub(r'\s+', ' ', т[max(0, м.start() - 300):м.end() + 300])
                    места.append({'url': u, 'плохой_путь': bool(ПЛОХОЙ_ПУТЬ.search(u)),
                                  'маркеры': sorted({x.group(0).lower() for x in МАРКЕРЫ.finditer(окно)})[:6], 'окно': окно})
    у = ['ИНН компании %s на сайте: %s.' % (к['inn'], ('НАЙДЕН %d раз' % все_инн[к['inn']]) if все_инн[к['inn']] else 'НЕ найден'),
         'Все ИНН на сайте (частота): %s.' % (', '.join('%s×%d' % x for x in все_инн.most_common(6)) or 'нет'),
         'Самый частый ИНН %s нашим.' % ('СОВПАДАЕТ с' if все_инн and все_инн.most_common(1)[0][0] == к['inn'] else 'НЕ совпадает с')]
    for м in места:
        у.append('Где стоит наш ИНН: %s%s; слова рядом: %s; окно: «%s»' % (
            м['url'], ' (ПЛОХОЙ ПУТЬ: новости/партнёры/портфолио)' if м['плохой_путь'] else '',
            ', '.join(м['маркеры']) or 'нет', м['окно'][:600]))
    return '\n'.join(у), тексты, все_инн, места


def одна(к, з, второй):
    у, тексты, все_инн, места = улики(к, з)
    текст = '\n---\n'.join('[%s] %s' % (u, т[:2200]) for u, т in тексты)[:9000]
    параметры = dict(имя=к['имя'], инн=к['inn'], регион=к['регион'], осн=к['осн'], сегм=к['сегм'],
                     выр=round((к.get('выручка') or 0) / 1e6), сайт=з['сайт'], улики=у, текст=текст)
    if not тексты:
        r = {'вердикт': 'сомневаюсь', 'ловушка': 'нет', 'почему': 'сайт не открылся'}
    else:
        r = KK.модель(ПРОМПТ.format(**параметры), False)
        if not r:
            return  # 10.10, ревизия: модель не ответила — не «сомневаюсь» навсегда, повторит следующий проход (резюм)
    рез = {'inn': к['inn'], 'сайт': з['сайт'], 'шаг1': r, 'инн_на_сайте': все_инн.get(к['inn'], 0),
           'инн_всего': len(все_инн), 'плохой_путь': any(м['плохой_путь'] for м in места)}
    в = r.get('вердикт') if r.get('вердикт') in ('подтверждаю', 'опровергаю', 'сомневаюсь') else 'сомневаюсь'
    if в == 'подтверждаю' and второй and тексты:
        r2 = KK.модель(ПРОМПТ_2.format(**параметры), False) or {}
        if not r2:
            return  # второй вызов не ответил — повторит следующий проход
        рез['шаг2'] = r2
        if r2.get('вердикт') != 'подтверждаю':
            в = 'сомневаюсь'
            рез['расхождение'] = 'второй вызов: %s — %s' % (r2.get('вердикт'), r2.get('почему', ''))
    рез['итог'] = в
    рез['почему'] = рез.get('расхождение') or r.get('почему', '')
    рез['ловушка'] = r.get('ловушка', '')
    рез['цитата'] = r.get('цитата', '')
    записать(рез)


def main():
    random.seed(9)
    сп = json.load(io.open(os.path.join(DIR, НАБОР + '-spisok.json'), encoding='utf-8'))['компании']
    конт = {}
    for s in io.open(os.path.join(DIR, НАБОР + '-kontakty.jsonl'), encoding='utf-8', errors='replace'):
        з = json.loads(s)
        if з.get('итог') == 'ok' and з.get('сайт'):
            конт[з['inn']] = з
    сделано = set()
    if os.path.exists(ВЫХОД):
        for s in io.open(ВЫХОД, encoding='utf-8', errors='replace'):
            try:
                x = json.loads(s)
                сделано.add((x['inn'], MN.домен(x.get('сайт') or '')))
            except (ValueError, KeyError):
                pass
    задачи = [(сп[i], з, random.random() < 0.2) for i, з in конт.items() if i in сп and (i, MN.домен(з['сайт'])) not in сделано
              and not i.startswith('САЙТ:')]  # без ИНН опровергать нечего — компания определена самим сайтом
    print('сайтов на опровержение', len(задачи), flush=True)
    n = [0]

    def шаг(x):
        try:
            одна(*x)
        except Exception as e:  # noqa: BLE001
            записать({'inn': x[0]['inn'], 'сайт': x[1]['сайт'], 'итог': 'сомневаюсь', 'почему': 'сбой: ' + repr(e)[:80]})
        n[0] += 1
        if n[0] % 25 == 0:
            print('опровергатели %d/%d' % (n[0], len(задачи)), flush=True)

    with ThreadPoolExecutor(int(os.environ.get('KC_POTOKOV_SHAGA', '10'))) as ex:  # 09.10: на полном прогоне 24
        list(ex.map(шаг, задачи))
    shutil.copyfile(ВЫХОД, os.path.join(r'C:\seostat\drop\drop-storage', НАБОР + '-oprov.jsonl'))
    сч = collections.Counter()
    for s in io.open(ВЫХОД, encoding='utf-8'):
        сч[json.loads(s).get('итог')] += 1
    print('готово', json.dumps(dict(сч), ensure_ascii=False), flush=True)


if __name__ == '__main__':
    main()
