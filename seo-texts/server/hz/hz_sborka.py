        р['_номера'], р['_факты'] = номера, фф
        if 'ликвид' in str(статус).lower() or 'банкрот' in str(статус).lower() or 'прекрат' in str(статус).lower():
            р['Причина'] = 'статус: %s' % статус
            мёртвые.append(р)
