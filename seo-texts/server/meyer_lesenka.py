# -*- coding: utf-8 -*-
"""Лесенка ЛПР Meyer — кому писать первым (владелец 12.10: «раньше была лесенка ЛПР и по ней почты распределялись»;
«даже наверное с технолога нужно начать и качества»; «для Meyer подумай, как лучше всего будет»).

Прежняя лесенка (`enrich_contacts._ROLE_RANK`) — компрессорная: главный инженер/энергетик/механик сверху, т.к. компрессор
выбирает служба главного инженера. У Meyer другая боль и другой хозяин боли:
  * рентген-инспекция готового продукта (кости, стекло, металл, камни в упаковке) — претензии сетей, ХАССП, отзывы
    партий: хозяин — служба качества; в фасованной пищевке (мясо, молоко, кондитерка, прочая пищевка) — первой;
  * фотосепаратор (зерно, крупы, орехи, семечка, кофе, вторсырьё, руда) — сорт и выход годного: хозяин — технолог
    (в горнодобыче — обогатитель, в семеноводстве — семеновод), качество — рядом;
  * производство — решает, встанет ли машина в поток; главный инженер/техдиректор — монтаж и бюджет, не инициатор;
  * руководитель (личный ящик) — подпись под капзатратой в средних компаниях; снабжение — оформляет решённое;
  * общий ящик — секретарь перешлёт; отдел продаж — читает заявки клиентов и не пересылает технологу (ниже общего);
  * кадры, бухгалтерия, пресс-служба, маркетинг, юристы — НИКОГДА (тупик и повод пометить письмо спамом).
Внутри ступени: ЛПР «да» > «возможно» > прочее; личный ящик (ФИО) > ящик отдела; корпоративный домен > бесплатная почта.
"""
import re

НИКОГДА = None
ПО_РОЛИ = {  # роль разметки -> ступень (меньше = раньше)
    'Технолог': 1, 'Качество / лаборатория': 2, 'Обогащение / горное': 3, 'Агрономия / семеноводство': 3,
    'Производство': 4, 'Техдиректор / главный инженер': 5, 'Хранение / элеватор / склад': 6, 'Руководитель': 7,
    'Механик / энергетик / ремонт': 8, 'Закупки / снабжение': 9, 'Закупки сырья / товара': 10, 'Коммерция / ВЭД': 11,
    'Прочее': 12, 'Общий номер / приёмная': 13, 'Продажи': 14,
    'Кадры': НИКОГДА, 'Финансы / бухгалтерия': НИКОГДА,
}
# фасованная пищевка (рентген готового продукта) — качество выше технолога; горнодобыча — обогатитель первым;
# семеноводство/зерно — семеновод/агроном сразу за технологом
_ФАСОВКА = re.compile(r'мясо|птиц|молок|молочн|свиновод|кондитерк|хлеб|пищев|фасовщик|корма|кофе|чай|специ|пряност|соки', re.I)
_ГОРНОЕ = re.compile(r'камень|известняк|доломит|песок|гравий|кварц|каолин|нерудн|карьер|уголь|руды|минерал|соль|химсырь', re.I)
_ЗАПРЕТ_ТЕКСТ = re.compile(r'кадр|персонал|подбор|ваканс|резюме|\bhr\b|бухгалт|финанс|экономист|казнач|пресс|сми\b|'
                           r'реклам|маркет|pr-|юрис|юридич|правов|секретар.{0,20}суд', re.I)
# роль по имени ящика (почты из базы обзвона/Checko без разметки; ящики «info@» с ФИО директора)
_ЯЩИК = (
    (re.compile(r'^(kadr|kadry|hr|personal|job|jobs|rabota|vakans|career|resume|ok)\d*$'), НИКОГДА),
    (re.compile(r'^(buh|buhg|bux|glavbuh|account|accounting|fin|finance|ekonom|kazna|nalog|zarplata)\w{0,6}$'), НИКОГДА),
    (re.compile(r'^(press|pr|smi|media|reklama|marketing|market|smm|ur|jur|legal|yurist)\d*$'), НИКОГДА),
    (re.compile(r'^(tehnolog|technolog|tech?nolog\w*|gl\.?tehnolog)\d*$'), 1),
    (re.compile(r'^(kachestvo|quality|qa|qc|otk|lab|lab\w+|haccp|okk|sluzhbakachestva)\d*$'), 2),
    (re.compile(r'^(proizv|proizvodstvo|production|prod|ceh|tseh)\d*$'), 4),
    (re.compile(r'^(gi|glinzh|glavinzh|engineer|ingener|tehdir|tech|teh|ogm|oge|meh|energ\w*|remont)\d*$'), 5),
    (re.compile(r'^(snab|snabzhenie|zakup\w*|tender\w*|purchase|procurement|omts)\d*$'), 9),
    (re.compile(r'^(ved|export|import|commerce|kommerc\w*|kd)\d*$'), 11),
    (re.compile(r'^(sales?|sbyt|opt|zakaz|order|shop|torg|realiz\w*|market)\d*$'), 14),
    (re.compile(r'^(info|office|mail|post|priem\w*|secretar\w*|reception|contact|kontakt|inbox|admin|general|gen|dir|'
                r'director|gendir|ofis|kanc)\d*$'), 13),
)
БЕСПЛАТНЫЕ = ('mail.ru', 'bk.ru', 'inbox.ru', 'list.ru', 'yandex.ru', 'ya.ru', 'yandex.by', 'gmail.com', 'rambler.ru',
              'internet.ru', 'icloud.com', 'outlook.com', 'tut.by', 'hotmail.com')
НАЗВАНИЕ = {1: 'технолог', 2: 'качество / лаборатория', 3: 'обогащение / семеноводство', 4: 'производство',
            5: 'техдиректор / главный инженер', 6: 'хранение / элеватор', 7: 'руководитель', 8: 'механик / энергетик',
            9: 'снабжение', 10: 'закупки сырья', 11: 'коммерция / ВЭД', 12: 'прочее (именной)', 13: 'общий ящик',
            14: 'отдел продаж'}


def по_ящику(почта):
    лок = (почта or '').lower().split('@')[0]
    for кус in (лок, re.split(r'[._-]', лок)[0]):
        for rx, ст in _ЯЩИК:
            if rx.match(кус):
                return True, ст
    return False, None


def ступень(роль, сегмент='', должность='', почта='', фио=''):
    """-> int (меньше — писать раньше) или None (не писать никогда)."""
    по_ящ, ст_ящ = по_ящику(почта)
    if по_ящ and ст_ящ is НИКОГДА:
        return НИКОГДА
    if _ЗАПРЕТ_ТЕКСТ.search(должность or '') and роль not in ('Руководитель', 'Технолог', 'Качество / лаборатория',
                                                               'Производство', 'Техдиректор / главный инженер'):
        return НИКОГДА
    if роль in ПО_РОЛИ:
        ст = ПО_РОЛИ[роль]
        # общий/прочий по разметке, а ящик говорит про отдел (kachestvo@, snab@) — верим ящику
        if ст is not НИКОГДА and ст >= 12 and по_ящ and ст_ящ is not НИКОГДА:
            ст = min(ст, ст_ящ)
        # и наоборот: ящик общий (reception@, info@, sales@) — письмо придёт секретарю/продажам, какой бы ни была роль
        # строки (reception@glanit.ru с должностью «директор»)
        elif ст is not НИКОГДА and по_ящ and ст_ящ in (13, 14):
            ст = max(ст, ст_ящ)
    elif по_ящ:
        ст = ст_ящ
    else:
        ст = 12 if фио else 13
    if ст is НИКОГДА:
        return НИКОГДА
    сегм = сегмент or ''
    if ст == 2 and _ФАСОВКА.search(сегм):
        ст = 0.5  # фасованная пищевка: качество — первым
    elif ст == 3 and роль == 'Обогащение / горное' and _ГОРНОЕ.search(сегм):
        ст = 0.5  # горнодобыча: обогатитель — первым
    return ст


def ключ(роль, сегмент='', должность='', почта='', фио='', лпр='', сайт=''):
    """Ключ сортировки почт компании по лесенке; None — не писать."""
    ст = ступень(роль, сегмент, должность, почта, фио)
    if ст is НИКОГДА:
        return None
    дом = (почта or '').lower().split('@')[-1]
    сайт = re.sub(r'^(https?://)?(www\.)?', '', (сайт or '').lower()).split('/')[0]
    личный = bool(фио) and not (по_ящику(почта)[0] and роль == 'Общий номер / приёмная')
    return (ст, {'да': 0, 'возможно': 1}.get(лпр or '', 2), 0 if личный else 1,
            0 if сайт and (дом == сайт or дом.endswith('.' + сайт) or сайт.endswith('.' + дом)) else 1 if дом not in БЕСПЛАТНЫЕ else 2)


def название(ст):
    return 'качество / лаборатория (фасовка — первым)' if ст == 0.5 else НАЗВАНИЕ.get(ст, '')


