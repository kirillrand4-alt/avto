def свести(г, ф, пункты):
    сп = '\n'.join('- %s (%s)' % (п, м) for м, п in пункты)
    for попытка in range(3):
        try:
            t = VC._provider_call_stdlib(СВ_ПР.format(ф=ф, г=г, сп=сп), model=СВОДЧИК) or ''
            м = re.search(r'\[.*\]', t, re.S)
            if м:
                return [x for x in json.loads(м.group(0)) if isinstance(x, dict) and x.get('пункт')]
        except Exception:  # noqa: BLE001
            pass
        time.sleep(10 * (попытка + 1))
    return None


def main():
    t0 = time.time()
    из = готовые()
    задачи = [(м, г, ч) for м in МОДЕЛИ for г in ГРУППЫ for ч in ЧАСТИ if (м, г, ч) not in из]
    print('вызовов к модели:', len(задачи), '| уже есть:', len(из), flush=True)
    from concurrent.futures import ThreadPoolExecutor
    with ThreadPoolExecutor(8) as ex:
        for r in ex.map(одна, задачи):
            if r[3] != 'ок':
                print('сбой', r, flush=True)
    из = готовые()
    сводка = {'модели_ответили': collections.Counter('%s' % м for (м, _, _) in из), 'группы': {}}
    свести_задачи = []
    for г in ГРУППЫ:
        по_ф = collections.defaultdict(list)
        for (м, гг, _), j in из.items():
            if гг != г:
                continue
            for ф, сп in j.items():
                if isinstance(сп, list):
                    по_ф[ф] += [(м, str(п).strip()) for п in сп if str(п).strip()]
        ок = collections.defaultdict(set)
        for м, п in по_ф.pop('оквэд', []):
            if код(п):
                ок[код(п)].add(м)
        сводка['группы'][г] = {'оквэд': sorted(([к, sorted(мм)] for к, мм in ок.items()), key=lambda x: (-len(x[1]), x[0]))}
        for ф, пункты in по_ф.items():
            свести_задачи.append((г, ф, пункты))
    with ThreadPoolExecutor(6) as ex:
        for (г, ф, пункты), рез in zip(свести_задачи, ex.map(lambda z: свести(*z), свести_задачи)):
            if рез is None:  # сводчик не ответил — сырой список без склейки
                рез = [{'пункт': п, 'модели': [м]} for м, п in пункты]
            сводка['группы'][г][ф] = рез
    with io.open(СВОДКА, 'w', encoding='utf-8') as f:
        json.dump(сводка, f, ensure_ascii=False, indent=1)
        f.flush(); os.fsync(f.fileno())
    for п in (СЫРЬЁ, СВОДКА):
        shutil.copyfile(п, os.path.join(ДРОП, os.path.basename(п)))
    итог = {г: {ф: '%d осн / %d проб' % (sum(1 for x in v if len(x[1] if ф == 'оквэд' else x.get('модели') or []) >= 2),
                                          sum(1 for x in v if len(x[1] if ф == 'оквэд' else x.get('модели') or []) < 2))
                for ф, v in д.items()} for г, д in сводка['группы'].items()}
    print('===ИТОГ===', json.dumps({'ответили': сводка['модели_ответили'], 'группы': итог}, ensure_ascii=False),
          'за %.1f мин' % ((time.time() - t0) / 60), flush=True)


if __name__ == '__main__':
    main()
