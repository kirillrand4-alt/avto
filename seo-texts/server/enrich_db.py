    @staticmethod
    def _requisite_not_phone(digits, inn, ogrn=''):
        """Десять цифр совпали с ИНН или легли внутрь ОГРН — это не номер.

        Поймано глазами в панели: у АО «Криогенмаш» среди телефонов висел
        «+7 (500) 100-00-66», то есть его собственный ИНН 5001000066,
        разложенный по маске телефона. Проверка длины не ловит — цифр ровно
        десять, и код начинается с пятёрки. Отличает только сверка с
        реквизитами САМОЙ компании.
        """
        if not digits:
            return False
        i = re.sub(r'\D', '', str(inn or ''))
        o = re.sub(r'\D', '', str(ogrn or ''))
        return bool((i and digits == i[:10]) or (o and digits in o))

    def add_phone(self, inn, phone, person='', role='', source='',
                  source_url='', ogrn=''):
        """ЕДИНСТВЕННАЯ точка записи телефона. Возвращает True, если записан.

        Появилась потому, что писателей телефона в проекте оказалось больше
        десятка, и у каждого свой SQL: `INSERT OR REPLACE`, `INSERT OR IGNORE`,
        голый `INSERT`. Последствия ровно те, на которых уже обжигались:
        `INSERT OR REPLACE` РОНЯЛ известную роль до «общий», а рубеж против
        реквизитов, поставленный в одном месте, остальные одиннадцать не
        видели — ИНН 5001000066 доехал до панели как «+7 (500) 100-00-66».

        Здесь собрано всё, что должен делать любой писатель:
          * нормализация к десяти цифрам и отсев мусора по длине;
          * сверка с реквизитами САМОЙ компании (ИНН/ОГРН), а не по форме;
          * канон роли;
          * непустая роль дополняет, но НЕ понижает уже известную до «общий»;
          * непустое ФИО не затирается пустым.
        """
        inn = str(inn or '').strip()
        сырой = (phone or '').strip()
        if not (inn and сырой):
            return False
        d = re.sub(r'\D', '', сырой)
        if len(d) == 11 and d[0] in '78':
            d = d[1:]
        if len(d) != 10:
            return False
        # ОГРН в схеме companies НЕ хранится, так что по умолчанию рубеж стоит
        # только на ИНН — а это как раз тот случай, который и был пойман живьём.
        # Кто ОГРН знает (реестровые загрузчики), передаёт его аргументом.
        if not ogrn:
            try:
                кол = {r[1] for r in self.cx.execute(
                    'PRAGMA table_info(companies)')}
                if 'ogrn' in кол:
                    r = self.cx.execute('SELECT ogrn FROM companies WHERE inn=?',
                                        (inn,)).fetchone()
                    ogrn = (r[0] if r else '') or ''
            except Exception:  # noqa: BLE001
                ogrn = ''
        if self._requisite_not_phone(d, inn, ogrn):
            return False
        role = self._canon_role(role)
        # ОБЩИЙ НОМЕР НЕ БЫВАЕТ ЛИЧНЫМ. Если эти десять цифр уже записаны за
        # ДРУГИМ предприятием или за другим человеком, то перед нами
        # коммутатор, колл-центр или страница-список, а не прямой номер
        # конкретного главного инженера.
        #
        # Замер, из которого это правило выросло: в базе нашлось 1 201 запись,
        # где один номер стоит у разных предприятий, и 438 — у разных людей
        # одного; 68 из них помечены личным техническим. Продавец звонит
        # «главному инженеру» и попадает на коммутатор, отданный ещё трём
        # заводам (номер 4957775500 стоял у четырёх ИНН).
        #
        # НЕ ОТКАЗЫВАЕМ в записи: номер предприятия — ценность, через него
        # дозваниваются. Снимаем ровно ложное утверждение — роль, по которой
        # считается фильтр «телефон с ролью». Имя человека остаётся: у
        # секретаря его спрашивают по фамилии.
        if role and role != 'общий':
            try:
                людей = (person or '').strip().lower()
                иных_инн = [r[0] for r in self.cx.execute(
                    "SELECT DISTINCT inn FROM phone_contacts WHERE inn<>? AND "
                    "replace(replace(replace(replace(replace(phone,' ',''),"
                    "'(',''),')',''),'-',''),'+','') LIKE ?",
                    (inn, '%' + d))]
                иных_людей = [r[0] for r in self.cx.execute(
                    "SELECT DISTINCT lower(person) FROM phone_contacts WHERE "
                    "COALESCE(person,'')<>'' AND lower(person)<>? AND "
                    "replace(replace(replace(replace(replace(phone,' ',''),"
                    "'(',''),')',''),'-',''),'+','') LIKE ?",
                    (людей, '%' + d))]
                if иных_инн or иных_людей:
                    сколько = (f'{len(иных_инн) + 1} предприятий' if иных_инн
                               else f'{len(иных_людей) + 1} человек')
                    source = ((source or '') + '; общий номер: ' + сколько)[:200]
                    role = ''
            except Exception:  # noqa: BLE001
                pass
        self.cx.execute(
            'INSERT INTO phone_contacts(inn,phone,person,role,source,'
            'source_url,updated_at) VALUES(?,?,?,?,?,?,?) '
            'ON CONFLICT(inn,phone,source_url) DO UPDATE SET '
            "role=CASE WHEN excluded.role NOT IN ('','общий') THEN excluded.role "
            'ELSE phone_contacts.role END, '
            "person=CASE WHEN excluded.person!='' THEN excluded.person "
            'ELSE phone_contacts.person END, '
            'updated_at=excluded.updated_at',
            (inn, сырой[:60], (person or '').strip()[:120], role or '',
             source or '', source_url or '', self.now))
        self.cx.commit()
        return True

    def add_person(self, inn, person, post='', phone='', email='',
                   source='', source_url='', observed_at='', recheck_days=365):
        """Человек с должностью — ДАЖЕ БЕЗ КОНТАКТОВ.

        Вопрос владельца 29.07: «ФИО инженера мы уже пишем, даже если контактов
        не нашлось?». До этой таблицы — нет: phone_contacts требует телефон,
        emails требует адрес, и «главный инженер Федоськин Михаил Петрович» без
        номера падал в никуда. А знать имя ценно и без телефона: продажник
        звонит в приёмную и спрашивает человека по имени.

        Непустое новое значение дополняет старое, пустое — не стирает.
        """
        if not (inn and (person or '').strip()):
            return
        role = self._canon_role(post)
        obs = observed_at or self.now[:10]
        try:
            rech = time.strftime(
                '%Y-%m-%d', time.gmtime(time.time() + recheck_days * 86400))
        except Exception:  # noqa: BLE001
            rech = ''
        self.cx.execute(
            'INSERT INTO people(inn,person,post,role,phone,email,source,'
            'source_url,observed_at,recheck_after,updated_at) '
            'VALUES(?,?,?,?,?,?,?,?,?,?,?) '
            'ON CONFLICT(inn,person,post) DO UPDATE SET '
            "role=CASE WHEN excluded.role NOT IN ('','общий') THEN excluded.role "
            'ELSE people.role END, '
            "phone=CASE WHEN excluded.phone!='' THEN excluded.phone ELSE people.phone END, "
            "email=CASE WHEN excluded.email!='' THEN excluded.email ELSE people.email END, "
            "source_url=CASE WHEN excluded.source_url!='' THEN excluded.source_url "
            'ELSE people.source_url END, '
            'observed_at=excluded.observed_at, recheck_after=excluded.recheck_after, '
            'updated_at=excluded.updated_at',
            (str(inn), (person or '').strip()[:120], (post or '').strip()[:160],
             role or '', (phone or '').strip()[:60], (email or '').strip().lower()[:120],
             source or '', source_url or '', obs, rech, self.now))
        self.cx.commit()

