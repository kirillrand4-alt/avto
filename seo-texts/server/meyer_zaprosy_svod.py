# -*- coding: utf-8 -*-
"""Сводный каталог поисковых запросов Meyer (владелец 08.10).

Источники: meyer-zaprosy/agent-NN.json (25 агентов через провайдерский API, meyer_zaprosy_gen.py) и
meyer-zaprosy/session-agent-N.json (5 агентов сессии: пищевые, непищевые, косвенные признаки, Беларусь,
критик плана). Плейсхолдеры {область}/{отрасль} приводятся к {регион}/{отрасль}; у Беларуси поля
получают префикс «беларусь_». Дедупликация по нормализованному тексту в пределах вида, у записи —
источники. Выход: meyer-zaprosy/katalog.json (машинный), katalog.csv (для Excel), KATALOG.md (сводка,
упущенные сегменты, ошибки поиска, проверка полноты).

    python3 meyer_zaprosy_svod.py
"""
import csv
import glob
import json
import os
import re

DIR = os.path.dirname(os.path.abspath(__file__))
ВХОД = os.path.join(DIR, 'meyer-zaprosy')

# приведение имён полей разных агентов к общим видам
ВИДЫ = {
    'реестры_и_рейтинги': 'реестры',
    'кейсы_и_новости': 'кейсы_поставщиков',
    'беларусь': 'запросы_беларусь',
    'запросы_для_пробелов': 'шаблоны_пробелы_регион',
}
НЕ_ЗАПРОСЫ = {'упущенное', 'упущенные_сегменты', 'ошибки_поиска_и_как_закрыть', 'проверка_полноты',
              'формы_собственности', 'источники_и_реестры', 'типы_предприятий', 'минус_слова'}


def норм(q):
    return re.sub(r'\s+', ' ', q.strip().lower().replace('ё', 'е'))


def текст(x):
    if isinstance(x, str):
        return x.strip()
    if isinstance(x, dict):
        return ' | '.join('%s: %s' % (k, v) for k, v in x.items() if v)
    return str(x)


def источники():
    for п in sorted(glob.glob(os.path.join(ВХОД, 'agent-*.json'))):
        д = json.load(open(п, encoding='utf-8'))
        имя = 'провайдер-%02d' % д.get('_агент', 0)
        yield имя, д, False
    for п in sorted(glob.glob(os.path.join(ВХОД, 'session-agent-*.json'))):
        д = json.load(open(п, encoding='utf-8'))
        номер = re.search(r'(\d+)', os.path.basename(п)).group(1)
        yield 'сессия-%s' % номер, д, 'беларусь' in str(д.get('агент', '')).lower()


def main():
    каталог = {}
    for имя, д, бел in источники():
        for поле, знач in д.items():
            if поле.startswith('_') or not isinstance(знач, list):
                continue
            вид = ВИДЫ.get(поле, поле)
            if бел and вид not in ('минус_слова', 'упущенное') and not вид.startswith('беларусь'):
                вид = 'беларусь_' + вид.replace('_область', '_регион')
            for x in знач:
                q = текст(x)
                if not q:
                    continue
                q = q.replace('{область}', '{регион}')
                к = (вид, норм(q))
                з = каталог.setdefault(к, {'вид': вид, 'запрос': q, 'источники': []})
                if имя not in з['источники']:
                    з['источники'].append(имя)
    записи = sorted(каталог.values(), key=lambda з: (з['вид'], -len(з['источники']), з['запрос']))
    for з in записи:
        з['это_запрос'] = з['вид'] not in НЕ_ЗАПРОСЫ and not з['вид'].startswith('беларусь_формы') \
            and 'источники_и_реестры' not in з['вид']
        з['шаблон'] = '{регион}' in з['запрос']
    # шаблоны «…_регион» без плейсхолдера — отметить (подставлять регион не нужно / агент ошибся)
    без_плейсхолдера = [з for з in записи if з['вид'].endswith('_регион') and not з['шаблон']]
    по_видам = {}
    for з in записи:
        по_видам[з['вид']] = по_видам.get(з['вид'], 0) + 1
    запросов = sum(1 for з in записи if з['это_запрос'])
    шаблонов = sum(1 for з in записи if з['это_запрос'] and з['шаблон'])
    бел_шаблонов = sum(1 for з in записи if з['это_запрос'] and з['шаблон'] and з['вид'].startswith('беларусь_'))
    # шаблоны Беларуси — только 6 областей + Минск, остальные — 89 регионов РФ + 7 РБ
    развёртка = (шаблонов - бел_шаблонов) * 96 + бел_шаблонов * 7 + (запросов - шаблонов)
    сводка = {'записей': len(записи), 'запросов_и_шаблонов': запросов, 'шаблонов_с_регионом': шаблонов,
              'без_региона': запросов - шаблонов,
              'развёртка_шаблонов_РФ89_РБ7': развёртка,
              'шаблонов_без_плейсхолдера': len(без_плейсхолдера), 'по_видам': по_видам}
    with open(os.path.join(ВХОД, 'katalog.json'), 'w', encoding='utf-8') as f:
        json.dump({'сводка': сводка, 'записи': записи}, f, ensure_ascii=False, indent=1)
    with open(os.path.join(ВХОД, 'katalog.csv'), 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.writer(f, delimiter=';')
        w.writerow(['Вид', 'Запрос / шаблон', 'Это поисковый запрос', 'С {регион}', 'Сколько агентов дали',
                    'Источники'])
        for з in записи:
            w.writerow([з['вид'], з['запрос'], 'да' if з['это_запрос'] else 'нет', 'да' if з['шаблон'] else '',
                        len(з['источники']), ', '.join(з['источники'])])
    md = ['# Каталог поисковых запросов Meyer (08.10)', '',
          '30 агентов: 25 через провайдерский API (по сегменту + соседний внахлёст, 25-й сквозной) и 5 агентов '
          'сессии (пищевые, непищевые, косвенные признаки, Беларусь, критик плана). Полный список — '
          '`katalog.json` / `katalog.csv`; `{регион}` подставляется для 89 регионов РФ и 6 областей РБ + Минск.', '',
          '## Сводка', '', '| Вид | Записей |', '|---|---|']
    md += ['| %s | %d |' % (в, н) for в, н in sorted(по_видам.items())]
    md += ['', 'Поисковых запросов и шаблонов: **%d** (с `{регион}`: %d, без региона: %d). Развёртка на '
           'регионы РФ+РБ ≈ **%d** запросов на поисковик (Яндекс и Google — каждый).' %
           (запросов, шаблонов, запросов - шаблонов, сводка['развёртка_шаблонов_РФ89_РБ7']), '']
    for вид, заголовок in (('упущенные_сегменты', 'Упущенные сегменты (критик плана)'),
                           ('ошибки_поиска_и_как_закрыть', 'Ошибки поиска и как закрыть'),
                           ('проверка_полноты', 'Проверка полноты'),
                           ('упущенное', 'Что агенты считают упущенным (дали ≥2 агента или агенты сессии)')):
        строки = [з for з in записи if з['вид'] == вид]
        if вид == 'упущенное':
            строки = [з for з in строки if len(з['источники']) >= 2
                      or any(и.startswith('сессия') for и in з['источники'])]
        if строки:
            md += ['## ' + заголовок, '']
            md += ['- %s _(%s)_' % (з['запрос'], ', '.join(з['источники'])) for з in строки]
            md.append('')
    with open(os.path.join(ВХОД, 'KATALOG.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(md))
    print(json.dumps(сводка, ensure_ascii=False, indent=1))
    for з in без_плейсхолдера[:10]:
        print('без {регион}:', з['вид'], '|', з['запрос'])


if __name__ == '__main__':
    main()
