# -*- coding: utf-8 -*-
"""Второй разбор выгрузки ЕГРЗ: чистка по образцам, увиденным глазами.

Первый разбор дал 366 «нашей темы», и это число было ЗАВЫШЕНО. Глаза на тридцати
случайных строках нашли четыре разных подделки:
  * «нагнетательная СКВАЖИНА» — слово «нагнетатель» поймало нефтяную скважину, а не
    нагнетатель газоперекачивающего агрегата. Таких строк большинство слова.
  * «Реконструкция здания компрессорной ПОД офис / под зал бокса / в расходный склад» —
    компрессорную РАЗБИРАЮТ, а не строят. Это отрицательный сигнал, а не положительный.
  * «Инновационный комплекс по выпуску деталей турбокомпрессоров» — изготовитель,
    то есть конкурент; первое правило про изготовителя эту форму не ловило.
  * «Транспортно-пересадочный узел Компрессорный» — топоним, как и обведённая владельцем
    «ул. Компрессорная, 1».
И наоборот, в «сомнительном» лежало нужное: «ПАО НЛМК. Кислородный цех. КРП-1.1»,
«азотнокислородное производство» — это наша машина, только названная иначе.

Ещё два слова оказались почти пустыми по отдаче и вычищены целыми классами:
  «пневмо»  — 78 строк, из них почти все «восстановление сетей методом пневмопробойника»;
  «дожимн»  — 19 строк, из них почти все «дожимная НАСОСНАЯ станция» (нефть, насос, не
              компрессор). Настоящая ДКС — «дожимная компрессорная» — остаётся в теме.
  «аммиачн» — 52 строки, из них почти все склады аммиачной СЕЛИТРЫ.
  «кислородн» — 99 строк, из них большинство это МЕДИЦИНСКИЙ кислород в больницах
              (концентраторы, рампы, газификационные станции ковидных времён).

Классы на выходе. Мусор не выбрасывается: у каждой строки написана причина.
"""
import collections
import io
import json
import os
import re

KAT = os.path.dirname(os.path.abspath(__file__))
# Пути можно передать аргументами: классификатор один на всю тему, и портфельная выгрузка
# обязана разбираться ТЕМИ ЖЕ правилами, иначе числа двух файлов несравнимы.
import sys  # noqa: E402
VHOD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(KAT, 'EGRZ-NASHA-TEMA.jsonl')
VYHOD = sys.argv[2] if len(sys.argv) > 2 else os.path.join(KAT, 'EGRZ-NASHA-TEMA-2.jsonl')

SLOVO = r'(?:компрессорн|кислородн|азотн|воздуходувн)'
# в именах подстанций и линий встречаются ещё «Аммиачная» и «Дожимная»
SLOVO_PS = r'(?:компрессорн|кислородн|азотн|воздуходувн|аммиачн|дожимн)'
TOPONIM = re.compile(
    r'(?:ул\.?|улиц\w*|пер\.?|переул\w*|проезд|шоссе|пр-?кт|проспект|б-?р|бульвар|наб\.?|'
    r'набережн\w*|мкр\.?|микрорайон|пос\.?|посёл\w*|посел\w*|тупик\w*|'
    r'транспортно-пересадочн\w+\s+узел|тпу)\s*[«"]?' + SLOVO
    + r'|(?:^|[\s(,:])[пгсд]\.\s*' + SLOVO
    # остановка и переход называются «Компрессор» — слово в кавычках и без продолжения
    + r'|(?:перехода|остановк\w*|станци\w*\s+метро)\s*[:\-]?\s*[«"]компрессор[»"]', re.I)
TOPONIM2 = re.compile(SLOVO + r'\w*\s*,\s*(?:д\.?\s*)?\d', re.I)
# «ПС Компрессорная-1» стоит без кВ рядом, а «ВЛ 110 кВ ... ПС Компрессорная» — за 60 знаков
# от киловольт. Поэтому два захода: с киловольтами поодаль и просто «ПС» перед словом.
PODSTANCIYA = re.compile(
    r'(?:пс|вл|кл|квл|эск|подстанц\w*)[\s\-]*[\d/,\s]*к[вВ][^.]{0,60}[«"]?' + SLOVO_PS
    + r'|(?:^|[\s(,«"])пс[\s\-]*[\d/]*\s*(?:кв)?\s*[«"]?' + SLOVO_PS
    + r'|подстанц\w*\s*[\d/\s]*(?:кв)?\s*[«"]' + SLOVO_PS, re.I)
# Первая версия правила про изготовителя требовала только «производств…» в шестидесяти
# знаках от слова «компрессор» — и отсеяла «Реконструкция нежилого здания
# ПРОИЗВОДСТВЕННОГО - КОМПРЕССОРНОЙ», то есть настоящую компрессорную. Теперь нужен
# предлог «по производству/выпуску» и родительный падеж: «компрессоров», «компрессорного».
IZGOTOVITEL = re.compile(
    r'компрессормаш|'
    r'(?:по\s+производству|по\s+выпуску|по\s+изготовлению)[^.]{0,60}'
    r'(?:компрессоров|компрессорного|турбокомпрессоров)|'
    r'испытательн\w+\s+(?:комплекс|стенд)[^.]{0,60}компрессор|'
    r'стенд\w*\s+(?:комплексных\s+)?испытаний[^.]{0,40}компрессор|'
    # «производство корпуса компрессоров авиадвигателей» — это деталь на продажу, не машина
    r'производств\w*[^.]{0,30}компрессоров\s+авиадвигател|корпус\w*\s+компрессоров|'
    r'пневмоавтоматик', re.I)
# «насосно-компрессорные трубы» — это НКТ для скважин, а не машина.
NKT = re.compile(r'насосно-?\s*компрессорн\w*\s+труб|\bнкт\b|труб\w*\s+нефтяного\s+сортамент', re.I)
MEDICINA = re.compile(
    r'гбуз|гауз|огбуз|кгбуз|огауз|гбу\s*рс|гау\s*рс|бюджетн\w+\s+учреждени\w+\s+здрав|'
    # «стационар» без границы ловил «АЗС стационарного типа» — три заправки уехали в медицину
    r'больниц|поликлиник|\bцрб\b|госпитал|медицин|стационар(?!н)|лечебн|диспансер|перинатал|'
    r'роддом|родильн|инфекционн\w+\s+(?:отделен|корпус|госпитал)|санитарн\w+\s+авиа|'
    r'кислородн\w+\s+концентратор|кислородн\w+\s+рамп|кислородн\w+\s+пункт|'
    r'кислородн\w*-?\s*газификацион|кислородн\w+\s+газификатор|газификационн\w+\s+станц|'
    r'кислородн\w+\s+подстанц|систем\w+\s+кислородного\s+обеспечен|'
    r'медицинск\w+\s+(?:газ|сжат)', re.I)
PEREPROFIL = re.compile(
    r'компрессорн\w*[^.]{0,30}\b(?:в|под)\b\s+(?:расходн|склад|офис|администрат|зал\b|'
    r'спортивн|гараж|магазин|жил\w|гостиниц|мастерск|музе)', re.I)
# Тот же класс, что обведённая владельцем строка, только хитрее: компрессорная названа
# ОРИЕНТИРОМ на местности. «автомобильная дорога Путятино - компрессорная станция - Унгор»,
# «берегоукрепление ... (ОТ КИСЛОРОДНОЙ СТАНЦИИ ДО улицы Чекистов)». Объект — дорога и
# набережная, а станция стоит вместо адреса.
LINEYN = re.compile(r'автомобильн\w+\s+дорог|электроосвещени|берегоукреплени|тротуар|'
                    r'водопроводн\w+\s+сет|канализационн\w+\s+сет|пешеходн\w+\s+дорож|'
                    r'освещени\w+\s+(?:улиц|дорог)', re.I)
ORIENTIR = re.compile(r'(?:от|до)\s+(?:компрессорн|кислородн)\w*\s+станц|'
                      r'[-–—]\s*(?:компрессорн|кислородн)\w*\s+станц\w*\s*[-–—]', re.I)
PNEVMOPROB = re.compile(r'пневмопробойник|пневмотир|пневмокаркас|пневмоопор|пневмоудар', re.I)
SKVAZHINA = re.compile(r'(?:водо|газо)?нагнетательн\w*\s+(?:скважин|скв\.|газопровод|водовод)|'
                       r'скважин\w*\s+(?:системы\s+)?ппд|нагнетательн\w+\s+ряд', re.I)
NASOSN = re.compile(r'дожимн\w*\s+насос|насосн\w*\s+дожимн|\bднс\b|нефтенасосн', re.I)
SELITRA = re.compile(r'аммиачн\w+\s+селитр|азотн\w+\s+удобрен|селитр\w+\s+аммиачн|нитрат\w*\s+аммония|'
                     r'аммиачн\w+\s+вод|карбамид', re.I)
AGNKS = re.compile(r'агнкс|газонаполнительн|газозаправочн|криогенн\w+\s+азс|\bкпг\b|'
                   r'компримированн\w+\s+природн', re.I)
SOC = re.compile(r'парк\s+культуры|пкио|каток|ледов\w+|депо|школ\w|детск\w+\s+сад|стадион|'
                 r'бассейн|жилой\s+дом|многоквартирн|дом\s+культуры|спортивн\w+\s+комплекс', re.I)
NASHA = re.compile(
    r'компрессорн\w*\s+(?:станц|установк|цех|отделен|хозяйств|блок|участок)|'
    r'станц\w*\s+компрессорн|газокомпрессорн|криогенно-компрессорн|холодильно-компрессорн|'
    r'\bдкс\b|дожимн\w*\s+компрессорн|'
    r'воздухораздел|\bвру\b|'
    r'кислородн\w*\s+(?:станц|цех|завод|производств|блок|установк)|станц\w*\s+кислородн|'
    r'производств\w*\s+кислорода|азотнокислородн|кислородно-азотн|азотно-воздушн|'
    r'азотн\w*\s+(?:станц|установк)|'
    # «сжатого воздуха» — редкое и честное слово: 12 записей на весь реестр. Медицина к этому
    # месту уже отобрана правилом выше, поэтому здесь его можно брать целиком.
    r'сжатого\s+воздуха|пневмотранспорт|пневмотрасс|пневмосет|пневмоснабжен|'
    r'отделени\w*\s+нагнетател|газоперекачива|турбокомпрессорн|воздуходувн|'
    r'аммиачн\w*[\s-]+(?:холодильн|компрессорн)|аммиачно-холодильн|'
    # «Северсталь. ТЭЦ-ЭВС-2. Здание ЭВД-4 с УСТАНОВКОЙ КОМПРЕССОРА» и «газодожимной
    # компрессор на Якутской ГРЭС» первое правило теряло: «компрессора» — это не
    # «компрессорная», основа другая. Обе строки настоящие, обе вернулись этими двумя ветками.
    r'установк\w*\s+компрессор|компрессор\w*\s+(?:установк|агрегат|оборудован)|газодожимн|'
    r'здани\w*\s+компрессорн|компрессорн\w*\b(?!\w)', re.I)
SMEZH = re.compile(r'азотн\w+\s+кислот|азотн\w+\s+удобрен|кислородно-щелочн|кислородно-?конвертерн|конвертерн\w+\s+цех|'
                   r'аммиак|метанол|карбамид|селитр|производств\w+\s+водород', re.I)

PRAVILA = [
    ('отсеяно: топоним', 'слово стоит в названии улицы, посёлка или узла, а не машины',
     lambda t: TOPONIM.search(t) or TOPONIM2.search(t)),
    ('отсеяно: имя подстанции', 'так называется электрическая подстанция',
     lambda t: PODSTANCIYA.search(t)),
    ('отсеяно: ориентир на местности', 'объект - дорога или набережная, а компрессорная '
     'названа вместо адреса: «от кислородной станции до улицы»',
     lambda t: LINEYN.search(t) and ORIENTIR.search(t)),
    ('отсеяно: насосно-компрессорные трубы', 'НКТ - труба для скважины, слово «компрессорн» '
     'попало в название трубы', lambda t: NKT.search(t)),
    ('отсеяно: изготовитель компрессоров', 'это конкурент или его площадка, а не покупатель',
     lambda t: IZGOTOVITEL.search(t)),
    ('отсеяно: компрессорную переделывают', 'здание компрессорной переводят под склад, офис '
     'или зал: машину убирают, а не ставят', lambda t: PEREPROFIL.search(t)),
    ('отсеяно: пневмопробойник и прочее «пневмо»', 'слово «пневмо» поймало способ ремонта '
     'канализации или надувную конструкцию', lambda t: PNEVMOPROB.search(t)),
    ('отсеяно: нагнетательная скважина', 'нефтяная скважина закачки, а не нагнетатель '
     'газоперекачивающего агрегата', lambda t: SKVAZHINA.search(t) and not NASHA.search(t)),
    ('отсеяно: насосная, а не компрессорная', 'дожимная НАСОСНАЯ станция нефти: насос, не '
     'компрессор', lambda t: NASOSN.search(t) and not NASHA.search(t)),
    ('не наша тема: медицинский кислород', 'кислород в больнице: концентратор, рампа, '
     'газификатор. Машина есть, но рынок другой', lambda t: MEDICINA.search(t)
     and not re.search(r'компрессорн\w*\s+(?:станц|цех)', t, re.I)),
    ('АГНКС и газозаправка', 'газонаполнительная станция: компрессор есть, но решает '
     'газовая компания, а не завод', lambda t: AGNKS.search(t)),
    # соцобъект проверяется ДО «нашей темы», иначе правило вообще не сработает: у депо и
    # катка в названии стоит та же «компрессорная станция». Машина там бывает настоящая,
    # поэтому это отдельный лист на просмотр, а не отсев.
    ('сомнительно: соцобъект и депо', 'парк, каток, депо, школа: покупатель муниципальный '
     'или транспортный, машина чаще бытовая. Смотреть глазами, не выбрасывать',
     lambda t: SOC.search(t)),
    ('НАША ТЕМА', '', lambda t: NASHA.search(t)),
    ('смежное: химия и металлургия', 'объект не компрессорная, но предприятие из наших '
     'отраслей и воздух ему нужен', lambda t: SMEZH.search(t)),
]


def klass(ob):
    t = re.sub(r'\s+', ' ', ob or '')
    for imya, prichina, pravilo in PRAVILA:
        if pravilo(t):
            return imya, prichina
    return 'сомнительно', 'ни одно правило не сработало уверенно'


stroki = [json.loads(s) for s in io.open(VHOD, encoding='utf-8') if s.strip()]
bylo = collections.Counter(s['klass'] for s in stroki)
for s in stroki:
    s['klass'], s['pochemu'] = klass(s['obekt'])
stalo = collections.Counter(s['klass'] for s in stroki)

with io.open(VYHOD, 'w', encoding='utf-8') as f:
    for s in stroki:
        f.write(json.dumps(s, ensure_ascii=False) + '\n')

print('########## СКОЛЬКО ЧЕГО СТАЛО (всего %d)' % len(stroki))
for k, n in stalo.most_common():
    print('    %-44s %5d' % (k, n))
nash = [s for s in stroki if s['klass'] == 'НАША ТЕМА']
print('  «наша тема»: строк %d, разных ИНН застройщика %d, разных проектировщиков %d'
      % (len(nash), len({s['zastroyshchik_inn'] for s in nash if s['zastroyshchik_inn']}),
         len({s['proektirovshchik_inn'] for s in nash if s['proektirovshchik_inn']})))
print('  было в первом разборе «НАША ТЕМА» %d, стало %d' % (bylo['НАША ТЕМА'], stalo['НАША ТЕМА']))

print('\n########## ПО ВОСЕМЬ ОБРАЗЦОВ КАЖДОГО КЛАССА')
for k, _n in stalo.most_common():
    print('\n--- %s' % k)
    for s in [x for x in stroki if x['klass'] == k][:8]:
        print('   %s' % s['obekt'][:118])
