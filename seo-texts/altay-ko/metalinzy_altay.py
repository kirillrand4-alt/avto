_lock = threading.Lock()


def _parse(msg):
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    text = re.sub(r'^```(?:json)?\s*|\s*```$', '', text)
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        m = re.search(r'\{.*\}', text, re.S)
        return json.loads(m.group(0))


def _append(path, rec):
    with _lock:
        with open(path, 'a', encoding='utf-8') as f:
            f.write(json.dumps(rec, ensure_ascii=False) + '\n')
            f.flush(); os.fsync(f.fileno())


def _load(path):
    if not os.path.exists(path):
        return []
    return [json.loads(l) for l in open(path, encoding='utf-8') if l.strip()]


def sprosit(client, prompt):
    msg = call(client, [{'role': 'user', 'content': prompt}], model=MODEL, attempts=3)
    return _parse(msg), msg.usage.output_tokens


def shag1(client, nitey):
    gotovo = {r['meta_id'] for r in _load(F_LINZY)}
    ochered = [m for m in METALINZY if m[0] not in gotovo]
    print(f'шаг 1: металинз {len(METALINZY)}, готово {len(gotovo)}, в очереди {len(ochered)}')

    def odna(m):
        mid, imya, ust = m
        t = time.time()
        d, tok = sprosit(client, PROMPT_METALINZA.format(ustanovka=ust, zadacha=ZADACHA,
                                                        imya=imya, n=LINZ_NA_METALINZU))
        linzy = d.get('linzy') or []
        if len(linzy) < 3:
            raise RuntimeError(f'{mid}: линз {len(linzy)} - мало')
        rec = {'meta_id': mid, 'meta': imya, 'linzy': linzy, 'tok': tok, 'sec': round(time.time() - t)}
        _append(F_LINZY, rec)
        return f'{mid} {imya}: линз {len(linzy)}, {tok} ток, {rec["sec"]} с'

    with ThreadPoolExecutor(nitey) as ex:
        futs = {ex.submit(odna, m): m[0] for m in ochered}
        for f in as_completed(futs):
            try:
                print('  ', f.result())
            except Exception as e:
                print('  СБОЙ', futs[f], repr(e)[:200])


def shag2(client, nitey):
    linzy = []
    for r in _load(F_LINZY):
        for i, l in enumerate(r['linzy'], 1):
            l = dict(l)
            # модель иногда портит имя ключа («установка», «estabelka»): берём любой третий ключ
            if 'ustanovka' not in l:
                lishnie = [k for k in l if k not in ('imya', 'fokus')]
                l['ustanovka'] = l.pop(lishnie[0]) if lishnie else ''
            l.setdefault('fokus', ''); l.setdefault('imya', f'линза {i}')
            linzy.append({'linza_id': f'{r["meta_id"]}-L{i}', 'meta_id': r['meta_id'], 'meta': r['meta'], **l})
    gotovo = {r['linza_id'] for r in _load(F_IDEI)}
    ochered = [l for l in linzy if l['linza_id'] not in gotovo]
    print(f'шаг 2: линз {len(linzy)}, готово {len(gotovo)}, в очереди {len(ochered)}')

    def odna(l):
        t = time.time()
        d, tok = sprosit(client, PROMPT_LINZA.format(ustanovka=l['ustanovka'], fokus=l.get('fokus', ''),
                                                    zadacha=ZADACHA, imya=l['imya'], meta=l['meta'],
                                                    n=IDEY_NA_LINZU))
        idei = d.get('idei') or []
        if len(idei) < 3:
            raise RuntimeError(f'{l["linza_id"]}: идей {len(idei)} - мало')
        rec = {**l, 'idei': idei, 'tok': tok, 'sec': round(time.time() - t)}
        _append(F_IDEI, rec)
        return f'{l["linza_id"]} {l["imya"][:50]}: идей {len(idei)}, {tok} ток, {rec["sec"]} с'

    with ThreadPoolExecutor(nitey) as ex:
        futs = {ex.submit(odna, l): l['linza_id'] for l in ochered}
        for f in as_completed(futs):
            try:
                print('  ', f.result())
            except Exception as e:
                print('  СБОЙ', futs[f], repr(e)[:200])


def svod():
    recs = _load(F_IDEI)
    n_idei = sum(len(r['idei']) for r in recs)
    metas = {r['meta_id'] for r in recs}
    print(f'СВОД: металинз с идеями {len(metas)}, линз {len(recs)}, идей {n_idei}')
    return recs


