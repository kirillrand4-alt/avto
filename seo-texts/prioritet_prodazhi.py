# -*- coding: utf-8 -*-
"""Приоритет обзвона: перемножение, а не сложение. Предложение 3-й сессии.

ЧТО НЕ ТАК С ТЕКУЩЕЙ ФОРМУЛОЙ. Она складывает признаки: покупают +40, срок истёк +30,
воздух +25, свежее +10, крупное +6. Сложение позволяет одному сильному слагаемому закрыть
дыру в другом — и это не теория, это измерено: верх очереди сейчас четыре предприятия с
важностью 81, у трёх из них НОЛЬ телефонов, а по всей базе из 238 предприятий с важностью
75 и выше номера нет у 208, то есть у 87 %. Продавец открывает лучшее и не может позвонить.

ПОЧЕМУ ПЕРЕМНОЖЕНИЕ. Продажа требует трёх вещей ОДНОВРЕМЕННО, и ни одна не заменяет другую:
    повод        — предприятию машина нужна СЕЙЧАС, и у этого есть дата;
    соответствие — машина действительно наша: центробежная и воздушная;
    досягаемость — есть кому и по чему позвонить.
Если любая из трёх около нуля, лид не стоит ничего, сколько бы ни было в остальных. Сложение
это скрывает, умножение показывает. Четвёртый множитель — доверие к доказательству: два
независимых источника весомее одного, а факт без ссылки слабее факта со ссылкой.

    приоритет = 100 × повод × соответствие × досягаемость × доверие × деньги

ЧТО ЭТО МЕНЯЕТ НА ПРАКТИКЕ. Предприятие с истёкшей ЭПБ на воздушной машине и личным мобильным
главного энергетика получает под сотню. Предприятие с той же машиной, но без единого контакта —
около десяти, и не потому, что оно плохое, а потому, что сегодня по нему нельзя сделать
звонок. Это не потеря: см. ниже про две очереди.

ДВЕ ОЧЕРЕДИ ВМЕСТО ОДНОЙ — главное предложение, важнее весов. Одно число не может обслуживать
две разные работы. Предприятие с сильным поводом и без контакта — это не плохой лид, это
ЗАДАЧА ДРУГОГО РОДА: не звонить, а добыть человека. Поэтому:
    «звонить сегодня»  — досягаемость 0.6 и выше, сортировка по приоритету;
    «добыть контакт»   — соответствие и повод высокие, досягаемость низкая; это рабочий список
                         для обратного хода и поиска ЛПР, отсортированный по тому, сколько мы
                         потеряем, если не найдём.
Сейчас они смешаны, и вторая очередь маскируется под первую.

НИЧЕГО НЕ ОБНУЛЯЕТСЯ. Ни один множитель не падает в ноль: газовая машина это 0.15, а не 0,
поршневая 0.1, «ни номера, ни имени» 0.1. Правило владельца «разделять, а не отсеивать»
относится и к весам: ноль означает «выбросить», а мы только откладываем.
"""
import re

# --- 1. ПОВОД: когда предприятие принимает решение -----------------------------------------
# Истёкшая экспертиза — самый близкий к сделке сигнал из всех, что у нас есть: по закону
# машину нельзя эксплуатировать до продления или замены, то есть решение уже назрело и у него
# есть дата. Сейчас он весит 30 против 40 у «покупают» — это перевёрнуто, потому что
# «покупают» выводится из карточки закупки, которой может быть три года.
POVOD = {
    'ЭПБ истекла в пределах года': 1.00,
    'активная закупка, приём предложений идёт': 1.00,
    'план закупки на текущий год': 0.85,
    'ЭПБ истекает в ближайшие два года': 0.70,
    'закупка завершена меньше года назад': 0.60,
    'ЭПБ истекла более трёх лет назад': 0.40,
    'покупали ранее, движения нет': 0.30,
    'машина есть, движения нет': 0.25,
    'ничего не известно': 0.15,
}

# --- 2. СООТВЕТСТВИЕ: наша ли это машина ---------------------------------------------------
SOOTVETSTVIE = {
    'центробежная и воздух, доказано текстом первоисточника': 1.00,
    'центробежная, среда не названа': 0.60,
    'признак производства: разделение воздуха, кислородная станция': 0.40,
    'центробежная, но газ': 0.15,   # владелец продаёт и их, просто цель сейчас другая
    'поршневая или винтовая': 0.10,  # при росте потребления их меняют на центробежную
    'тип не установлен': 0.30,
}

# --- 3. ДОСЯГАЕМОСТЬ: можно ли сегодня поговорить с человеком ------------------------------
# Общий номер — не ноль. Через коммутатор спрашивают по фамилии, и это рабочий ход; поэтому
# «имя есть, номера нет, но есть общий номер предприятия» стоит вдвое дороже, чем просто
# общий номер без имён.
DOSYAGAEMOST = {
    'личный мобильный технического ЛПР': 1.00,
    'личный мобильный любого ЛПР': 0.85,
    # МОБИЛЬНЫЙ ЕСТЬ, ЧЕЛОВЕК НЕ НАЗВАН. Степень добавлена по прямому вопросу владельца:
    # «добыть контакт 507 — там нет ни сайта, ничего, откуда мы могли бы добывать контакт?»
    # Замер ответил против меня: у 443 из 507 телефоны ЕСТЬ, и 328 из них мобильные. Лежали
    # они в колонке `company.telefony_checko`, которую модель не читала вовсе — досягаемость
    # считалась только по `person.phone`. То есть «звонить некому» было свойством моего
    # запроса, а не предприятия.
    # Вес между «личный любого ЛПР» и «имя известно, номер общий»: номер мобильный, значит
    # с большой вероятностью личный, но чей — мы не знаем и врать об этом не будем.
    'мобильный предприятия, человек не назван': 0.60,
    'имя техЛПР известно, номер только общий': 0.50,
    'общий номер, имён нет': 0.25,
    'ни номера, ни имени': 0.10,
}

# --- 4. ДОВЕРИЕ: чем доказано ---------------------------------------------------------------
# Провенанс у нас накапливается, и вес должен это отражать: факт, подтверждённый и закупкой,
# и реестром ЭПБ, надёжнее того же факта из одного места.
DOVERIE = {
    'два и более независимых источника': 1.20,
    'один источник, есть ссылка на первоисточник': 1.00,
    'один источник, ссылки нет': 0.70,
    'состояние держится на факте, который свёрнут как мусор': 0.60,
}

# --- 5. ДЕНЬГИ: слабый множитель, чтобы не перебивал существо -------------------------------
DENGI = [(50_000_000, 1.15), (10_000_000, 1.08), (1_000_000, 1.00), (0, 0.92)]


def dengi_mnozhitel(summa):
    for porog, m in DENGI:
        if (summa or 0) >= porog:
            return m
    return 0.92


def prioritet(povod, sootvetstvie, dosyagaemost, doverie, summa=0):
    """Ноль на выходе невозможен: каждый множитель имеет пол."""
    return round(100 * POVOD.get(povod, 0.15) * SOOTVETSTVIE.get(sootvetstvie, 0.30)
                 * DOSYAGAEMOST.get(dosyagaemost, 0.10) * DOVERIE.get(doverie, 0.70)
                 * dengi_mnozhitel(summa), 1)


def ochered(dosyagaemost, sootvetstvie, povod):
    """В какую из двух очередей попадает предприятие.

    Разделение важнее весов: «звонить» и «добыть контакт» — разная работа, и мерить их одним
    числом значит прятать вторую внутри первой.
    """
    if DOSYAGAEMOST.get(dosyagaemost, 0.10) >= 0.50:
        return 'звонить сегодня'
    if (SOOTVETSTVIE.get(sootvetstvie, 0.30) >= 0.60
            and POVOD.get(povod, 0.15) >= 0.60):
        return 'добыть контакт — повод сильный, звонить некому'
    return 'фон: копить данные'


# --- Разбор состояния предприятия в перечисленные выше степени ------------------------------
ISTEKLA = re.compile(r'ист[её]к', re.I)


def stepen_povoda(sostoyanie, epb_status, epb_let_nazad=None, plan_god=False):
    if epb_status and ISTEKLA.search(epb_status):
        if epb_let_nazad is not None and epb_let_nazad <= 1:
            return 'ЭПБ истекла в пределах года'
        if epb_let_nazad is not None and epb_let_nazad > 3:
            return 'ЭПБ истекла более трёх лет назад'
        return 'ЭПБ истекла в пределах года'
    s = (sostoyanie or '').lower()
    if 'приём предложений' in s or 'прием предложений' in s or 'подача заявок' in s:
        return 'активная закупка, приём предложений идёт'
    if plan_god:
        return 'план закупки на текущий год'
    if epb_status:
        return 'ЭПБ истекает в ближайшие два года'
    if 'покупа' in s:
        return 'закупка завершена меньше года назад'
    if 'планир' in s:
        return 'план закупки на текущий год'
    if 'есть' in s:
        return 'машина есть, движения нет'
    return 'ничего не известно'


def stepen_dosyagaemosti(lichnyh_tehnicheskih, lichnyh_vsego, imen_tehnicheskih, obshchih,
                         mobilnyh_predpriyatiya=0):
    """`mobilnyh_predpriyatiya` — мобильные из реквизитов компании, где человек не назван."""
    if lichnyh_tehnicheskih:
        return 'личный мобильный технического ЛПР'
    if lichnyh_vsego:
        return 'личный мобильный любого ЛПР'
    if mobilnyh_predpriyatiya:
        return 'мобильный предприятия, человек не назван'
    if imen_tehnicheskih and obshchih:
        return 'имя техЛПР известно, номер только общий'
    if obshchih:
        return 'общий номер, имён нет'
    return 'ни номера, ни имени'
