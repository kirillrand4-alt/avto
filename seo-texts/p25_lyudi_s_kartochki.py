# -*- coding: utf-8 -*-
"""Разобрать поимённо карточку предприятия, которую открыл владелец. Глазами, по базе.

Владелец отметил в карточке три вещи, и все три надо проверить по данным:
  * «Имя не установлено», начальник цеха — карточка человека БЕЗ ЧЕЛОВЕКА, с пометкой
    «имя разобрано неверно, было: Начальник А.А.»;
  * «Ахмадишин Фаиз Фаикович», главный инженер — без пометки о проверке привязки;
  * «Анисимов Сергей Александрович» — с пометкой «привязка проверена по ядру имени».

Прибор считает по ВСЕЙ базе, а не по одной карточке: сколько людей стоит без имени,
сколько с должностью вместо имени, и как это соотносится с пометками о привязке.

ПОЧЕМУ ПУСТОЕ ИМЯ ХУЖЕ ОТСУТСТВИЯ ЗАПИСИ. Карточка «Имя не установлено» занимает место
человека: показывается продавцу как ЛПР, звонить по ней некому, и она же считается в
«людей предприятия». Это не человек, а СЛЕД ошибки разбора, оставленный в витрине.
"""
import collections
import json
import re
import sqlite3

BAZA = 'file:C:/seostat/data/centrifugal.db?mode=ro'
NE_IMYA = re.compile(
    r'^(?:начальник|главн|директор|инженер|механик|энергетик|технолог|заместител|'
    r'руководител|специалист|ведущ|старш|мастер|бригадир|уважаем|контакт|ответственн|'
    r'исполняющ|сотрудник|представител)', re.I)
PUSTO = re.compile(r'^\s*(?:имя не установлено|не установлено|нет данных|—|-|\?)?\s*$', re.I)
INICIALY = re.compile(r'^[А-ЯЁ][а-яё]*\s+[А-ЯЁ]\.\s*[А-ЯЁ]\.\s*$')

b = sqlite3.connect(BAZA, uri=True)
polya = [r[1] for r in b.execute('pragma table_info(person)')]
print('колонки person: %s' % ', '.join(polya))

sch = collections.Counter()
primery = collections.defaultdict(list)
for r in b.execute('select %s from person' % ','.join(polya)):
    z = dict(zip(polya, r))
    ist = str(z.get('source') or '')
    if 'поиск-ЛПР' not in ist:
        continue
    sch['людей моего канала'] += 1
    # КОЛОНКА ИМЕНИ НАЗЫВАЕТСЯ `person`, А НЕ `name` И НЕ `fio`. Первый заход прочёл
    # несуществующие ключи и объявил «БЕЗ ИМЕНИ 2 769 из 2 769» — сто процентов, а такого
    # не бывает. Девятое угаданное имя поля за смену, и снова оно дало не ошибку, а
    # правдоподобное число. Спасло правило: большое число это повод проверить прибор.
    nm = str(z.get('person') or '').strip()
    pos = str(z.get('position') or '')
    vid = ''
    if PUSTO.match(nm):
        vid = 'БЕЗ ИМЕНИ'
    elif NE_IMYA.match(nm.split()[0] if nm.split() else ''):
        vid = 'вместо имени слово ДОЛЖНОСТИ'
    elif INICIALY.match(nm):
        vid = 'только инициалы — звонить можно, искать нельзя'
    if vid:
        sch[vid] += 1
        if len(primery[vid]) < 5:
            primery[vid].append((nm[:32], pos[:26], ist[:70]))
    # Что сказано о привязке.
    nizh = ist.lower()
    if 'привязка проверена' in nizh:
        sch['  привязка проверена явно'] += 1
    elif 'привязка снята' in nizh:
        sch['  привязка снята явно'] += 1
    elif 'разобрано неверно' in nizh:
        sch['  помечено «имя разобрано неверно»'] += 1
    else:
        sch['  о привязке ничего не сказано'] += 1

for vid, sp in primery.items():
    print('\n--- %s' % vid)
    for nm, pos, ist in sp:
        print('    «%-32s» %-26s ← %s' % (nm, pos, ist))
for k, v in sch.most_common():
    print('REC %s\t%d' % (k, v))
print('ИТОГ ' + json.dumps({'проверено по': 'centrifugal.person'}, ensure_ascii=False))
