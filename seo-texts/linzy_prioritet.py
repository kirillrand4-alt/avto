def stroki():
    rows = list(csv.DictReader(open(SVOD, encoding='utf-8-sig'), delimiter=';'))
    rows.sort(key=lambda r: -int(r['prioritet'] or 0))
    random.seed(5)
    seredina = rows[len(rows) // 2: len(rows) // 2 + 12]
    vyborka = rows[:22] + seredina + rows[-8:] + random.sample(rows, 12)
    t = 'КОЛОНКИ: ' + ' ; '.join(POKAZ) + '\n\n'
    for r in vyborka:
        t += ' | '.join(f'{k}={(r.get(k) or "")[:60]}' for k in POKAZ if (r.get(k) or '').strip()) + '\n'
    raspr = Counter('90+' if int(r['prioritet'] or 0) >= 90 else
                    '60-89' if int(r['prioritet'] or 0) >= 60 else
                    '30-59' if int(r['prioritet'] or 0) >= 30 else 'ниже 30' for r in rows)
    zapoln = {k: sum(1 for r in rows if (r.get(k) or '').strip()) for k in POKAZ}
    return t, len(rows), dict(raspr), zapoln


