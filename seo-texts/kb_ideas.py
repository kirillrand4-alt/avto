def run_lens(desc):
    prompt = desc + '\n\n' + BASE
    for _ in range(4):
        try:
            msg = G._raw_stream([{'role': 'user', 'content': prompt}], MODEL, 6000, thinking=False)
            txt = ''.join(b.text for b in msg.content if b.type == 'text')
            m = re.search(r'\{.*\}', txt, re.S)
            if m:
                return json.loads(m.group(0))
        except Exception:
            time.sleep(4)
    return {'error': 'no-output'}


def main():
    out = {}
    for name, desc in LENSES.items():
        print(f'линза «{name}» ...', flush=True)
        out[name] = run_lens(desc)
        n = len(out[name].get('ideas', [])) if isinstance(out[name], dict) else 0
        print(f'  -> {n} идей', flush=True)
    (SCR / 'kb_ideas_raw.json').write_text(json.dumps(out, ensure_ascii=False, indent=1))
    seen, merged = {}, []
    for lens, d in out.items():
        for s in (d.get('ideas') or []):
            key = re.sub(r'\s+', '', (s.get('name') or '').lower())[:36]
            if not key:
                continue
            if key in seen:
                seen[key]['by'].append(lens)
            else:
                seen[key] = {**s, 'by': [lens]}
                merged.append(seen[key])

    def score(s):
        return (len(s.get('by', [])), s.get('impact') == 'high', s.get('effort') == 'low')
    merged.sort(key=score, reverse=True)
    (SCR / 'kb_ideas_merged.json').write_text(json.dumps(merged, ensure_ascii=False, indent=1))
    print(f'\nИТОГ: {len(merged)} уникальных идей (5 линз fable)', flush=True)
    for s in merged[:30]:
        print(f"  [{len(s['by'])}✓ {s.get('impact','?')}/{s.get('effort','?')}] {s.get('name','')[:44]}"
              f" — {(s.get('use') or '')[:70]}", flush=True)


if __name__ == '__main__':
    main()
