# Признак «это про производство». Он побеждает упоминание склада/офиса рядом.
# `\bзавод` не годится: «авто-ЗАВОДЕ», «хлебо-ЗАВОД», «нефте-ЗАВОД» — граница слова стоит
# перед приставкой, и проба это поймала (провал 1 из 16 на «выпуск седана на автозаводе»).
PROIZVODSTVO = re.compile(
    r'\b\w*завод\w*|\bцех\w*|\bпроизводств\w*|\b\w*комбинат\w*|\bфабрик\w*|\bэлеватор\w*|'
    r'\bпроизводственн\w+|\bтехнологическ\w+\s+лини\w+|\bлини\w+\s+(?:по\s+)?(?:выпуск\w+|'
    r'производств\w+|розлив\w+|сборк\w+)|\bмощност\w+\s+\d|\bагрегат\w*|\bустановк\w+|'
    r'\bпереработк\w+|\bобогатительн\w+|\bметаллург\w+|\bхимическ\w+\s+производств\w*|'
    r'\bНПЗ\b|\bГОК\b|\bТЭЦ\b|\bГРЭС\b|\bкотельн\w+|\bдобыч\w+|\bрудник\w*|\bшахт\w+', re.I)

# Чужое. Границы слова обязательны — иначе «недвижи-МОСТИ» становится мостом.
CHUZHOE = re.compile(
    r'\bлогистическ\w+\s+(?:комплекс\w*|центр\w*)|\bсклад\w+\s+комплекс\w*|'
    r'\bторгов\w+\s+центр\w*|\bбизнес-центр\w*|\bжил\w+\s+(?:комплекс\w*|дом\w*|квартал\w*)|'
    r'\bдетск\w+\s+сад\w*|\bшкол\w+|\bбольниц\w+|\bполиклиник\w+|\bстадион\w*|'
    r'\bфельдшерск\w+|\bФАП\b|\bамбулатор\w+|\bдетск\w+\s+поликлиник\w+|'
    r'\bавтосалон\w*|\bдилерск\w+\s+центр\w*|\bседан\w*|\bкроссовер\w*|'
    r'\bофисн\w+\s+(?:здани\w+|помещени\w+|центр\w*)|\bблагоустройств\w+|'
    r'\bавтомобильн\w+\s+дорог\w+|\bдорожн\w+\s+(?:покрыти\w+|полотн\w+|работ\w+)|'
    r'\bмост\b|\bмоста\b|\bмосту\b|\bмостов\w*\s|\bпутепровод\w*|\bтротуар\w*|'
    r'\bпарк\w*\s+отдыха|\bнабережн\w+', re.I)


def uroven(t):
    """Порядок проверок и есть правило. Машина -> производство -> чужое -> косвенный."""
    t = t or ''
    m = MASHINA.search(t)
    if m:
        return 'ПРЯМОЙ', m.group(0)
    p = PROIZVODSTVO.search(t)
    if p:
        return 'КОСВЕННЫЙ', p.group(0)
    c = CHUZHOE.search(t)
    if c:
        return 'ЧУЖОЙ', c.group(0)
    return 'КОСВЕННЫЙ', ''


def staraya(t):
    """Прежнее правило — нужно, чтобы честно показать разницу до/после."""
    t = t or ''
    if re.search(MASHINA, t):
        return 'ПРЯМОЙ'
    if re.search(r'логистическ\w+\s+(?:комплекс\w*|центр\w*)|склад\w+\s+комплекс\w*|'
                 r'торгов\w+\s+центр\w*|бизнес-центр\w*|жил\w+\s+(?:комплекс\w*|дом\w*)|'
                 r'детск\w+\s+сад\w*|школ\w+|больниц\w+|поликлиник\w+|стадион\w*|'
                 r'автосалон\w*|дилерск\w+\s+центр\w*|седан\w*|кроссовер\w*|'
                 r'офисн\w+\s+(?:здани\w+|помещени\w+)|благоустройств\w+|'
                 r'дорог\w+|мост\w+|путепровод\w*|тротуар\w*', t, re.I):
        return 'ЧУЖОЙ'
    return 'КОСВЕННЫЙ'


