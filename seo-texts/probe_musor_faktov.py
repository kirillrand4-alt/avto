# -*- coding: utf-8 -*-
"""Сколько в фактах явного мусора и можно ли убрать его словарём — считаем, потом решаем.

ВОПРОС ВЛАДЕЛЬЦА: применив полный словарь моделей, выкинуть явный мусор из фактов, чтобы не
захламлять обзор. На двух его снимках видно два РАЗНЫХ вида мусора, и лечатся они по-разному:

  * 4ВМ10-50/71 — «поршневой оппозитный компрессор». Это МАШИНА, но не наша. Опознаётся
    словарём: марка известна, профиль чужой. Лечится словарём.
  * «баллон 400-200л рег. № 62898, зав. №419, цех № 12 (ацетиленовая и кислородная станция)» —
    это вообще не машина, а сосуд под давлением. Марки у него нет и не будет, словарь тут
    бессилен: опознаётся ТЕКСТОМ («баллон», «сосуд», «ресивер», «воздухосборник»).

Поэтому считаю оба вида порознь, а не одним числом.

И ГЛАВНОЕ ОГРАНИЧЕНИЕ, которое я закладываю в счёт: слово владельца — «разделять, а не
отсеивать». Удалять факт нельзя: сегодня «баллон» это шум, а завтра по нему видно, что у
предприятия есть кислородная станция, то есть и воздухоразделение, то есть наша машина рядом.
Поэтому считаю то, что можно СВЕРНУТЬ в карточке под счётчик «скрыто N — показать», а не
стереть. Механизм в панели уже есть: карточка сама пишет «Мусорных позиций у этой компании нет».
"""
import json
import re
import sqlite3

cx = sqlite3.connect(r'C:\seostat\data\centrifugal.db')

# Не машина вовсе — сосуды, трубопроводы, здания, арматура.
NE_MASHINA = re.compile(
    r'\bбаллон|сосуд(?:ы|ов)?\s+(?:под|работающ)|ресивер|воздухосборник|трубопровод|'
    r'газоход|дымов\w*\s+труб|резервуар|ёмкост|емкост|эстакад|здани|сооружени|'
    r'кран\s+шаров|задвижк|арматур|фильтр\b|теплообменник|колонн[аы]\b|сепаратор|'
    r'подъёмн\w+ сооружени|дымосос|вентилятор', re.I)
# Машина, но чужого типа.
NE_NASH_TIP = re.compile(r'поршнев|винтов|спиральн|мембранн|роторн|вихрев|шестерён|'
                         r'плунжерн|水', re.I)
# Наша машина.
NASH = re.compile(r'центробежн|турбокомпрессор|турбовоздуходувк|нагнетател|воздуходувк', re.I)

o = {'фактов_всего': cx.execute('select count(*) from fact').fetchone()[0]}
sch = {'не машина (сосуд, труба, арматура)': 0, 'машина чужого типа (поршневой, винтовой)': 0,
       'наша машина': 0, 'ничего не сказано': 0}
primery = {k: [] for k in sch}
po_tipu_polya = {}
for inn, tip, quote in cx.execute(
        "select inn, coalesce(equipment_type,''), coalesce(quote,'') from fact"):
    nash = bool(NASH.search(quote))
    if NE_NASH_TIP.search(quote) and not nash:
        k = 'машина чужого типа (поршневой, винтовой)'
    elif NE_MASHINA.search(quote) and not nash:
        k = 'не машина (сосуд, труба, арматура)'
    elif nash:
        k = 'наша машина'
    else:
        k = 'ничего не сказано'
    sch[k] += 1
    po_tipu_polya.setdefault(k, {}).setdefault(tip or '(пусто)', 0)
    po_tipu_polya[k][tip or '(пусто)'] += 1
    if len(primery[k]) < 3:
        primery[k].append(quote[:120])
o['по_видам'] = sch
o['примеры'] = primery
# Насколько это совпадает с тем, что панель уже проставила в equipment_type: если
# «не машина» уже помечена как «центробежная», сворачивать надо не по полю, а по тексту.
o['мусор_помеченный_центробежным'] = {
    k: v for k, v in po_tipu_polya.get('не машина (сосуд, труба, арматура)', {}).items()
    if 'центробежн' in k.lower()}
o['чужой_tip_pomechennyy_центробежным'] = {
    k: v for k, v in po_tipu_polya.get('машина чужого типа (поршневой, винтовой)', {}).items()
    if 'центробежн' in k.lower()}
# Компании, у которых ПОСЛЕ сворачивания не осталось бы ни одного факта нашей машины.
o['компаний_без_единого_нашего_факта'] = cx.execute("""
    select count(*) from (
      select inn from fact group by inn
      having sum(case when lower(coalesce(quote,'')) like '%центробежн%'
                        or lower(coalesce(quote,'')) like '%турбокомпрессор%'
                        or lower(coalesce(quote,'')) like '%нагнетател%'
                        or lower(coalesce(quote,'')) like '%воздуходувк%'
                      then 1 else 0 end) = 0)""").fetchone()[0]
print(json.dumps(o, ensure_ascii=False, indent=1))
