def _norm_marku(v):
    """Ключ марки: только буквы и цифры, верхний регистр.

    Одна и та же машина пишется «К-890-121-1», «К890-121-1» и «GM80L» против «GM-80L».
    Сравнивать написания бессмысленно — сравниваем состав.
    """
    return re.sub(r'[^0-9A-Za-zА-Яа-яЁё]', '', v or '').upper().replace('Ё', 'Е')


