# -*- coding: utf-8 -*-
"""Разметка мусорных фактов в карточках: что свернуть, чтобы не захламлять обзор.

ЗАДАЧА ВЛАДЕЛЬЦА: убрать из карточек явный мусор. На двух его примерах видно, что мусор
бывает двух РАЗНЫХ пород, и лечатся они по-разному:

    «баллон 400-200л рег. № 62898, зав. №419, цех № 12 (ацетиленовая и кислородная станция)»
        — не машина вовсе. Марки нет и не будет, словарь моделей бессилен, ловится текстом.
    «4ВМ10-50/71 — поршневой оппозитный компрессор»
        — машина, но чужого типа. Ловится словарём: марка известна, профиль не наш.

ГЛАВНОЕ ПРАВИЛО ЭТОГО МОДУЛЯ: НИЧЕГО НЕ УДАЛЯЕТСЯ. Слово владельца — «разделять, а не
отсеивать». Модуль ставит ярлык `musor_vid` и объяснение `pochemu`, а прятать или нет решает
показ. Сегодня «баллон» это шум, а завтра по нему видно, что у предприятия есть кислородная
станция, то есть воздухоразделение, то есть наша машина рядом. У 352 компаний из 1 573 вообще
нет ни одного факта нашей машины — жёсткая чистка оставила бы им пустую карточку.

ТРИ ЗАСЛОНА, каждый поставлен по конкретной ошибке, найденной на живых данных.

1. АВТОМОБИЛЬНОЕ И СЕЛЬХОЗНОЕ. Первый вариант правила считал нашим всё, где есть слово
   «турбокомпрессор», и в «наши машины» уехало «Поставка компрессоров кондиционера, стартеров,
   генераторов и турбокомпрессоров на сельскохозяйственную технику» — турбина трактора. Теперь
   автомобильный контекст отменяет признак нашей машины, а не добавляется к нему.

2. РАЗМЕТКА ПАНЕЛИ НЕ АВТОРИТЕТ. 197 фактов, где текст говорит «баллон», «трубопровод» или
   «здание», уже помечены в `equipment_type` как «центробежная» (114 прямо и 67 «по серии»).
   Свернуть по полю — оставить мусор на месте. Поэтому решает ТЕКСТ, а поле лишь показывается
   рядом, чтобы расхождение было видно человеку.

3. СЛОВО МАШИНЫ СИЛЬНЕЕ СЛОВА СОСУДА. В одном заключении часто перечислено и то и другое:
   «трубопровод сжатого воздуха узла воздуходувки 700.09». Если наша машина названа, факт не
   мусор, даже когда рядом стоит труба. Иначе теряются именно те заключения, которые доказывают
   наличие машины на опасном объекте.

ЧТО СЧИТАЕТСЯ И ЧТО НЕТ. Пустая цитата — не мусор, а отсутствие данных: сворачивать её нельзя,
потому что доказательство может лежать в других полях факта (номер заключения, ссылка). Она
получает свой ярлык, отдельный от мусора.

Использование:
    python3 musor_faktov.py --iz fakty.json.gz --out RAZMETKA.csv
    python3 musor_faktov.py --na-servere            # прогон по базе панели
    python3 musor_faktov.py --proverit RAZMETKA.csv --skolko 200   # суд дешёвой моделью
"""
import re

# Наша машина. Два разных признака, и смешивать их нельзя.
# ЯВНЫЕ — слово само по себе называет машину нашего класса.
NASH_YAVNO = re.compile(r'турбокомпрессор|турбовоздуходувк|турбогазодувк|воздуходувк|'
                        r'воздухонагнетат|нагнетател', re.I)
# СЛОВО «ЦЕНТРОБЕЖНЫЙ» САМО ПО СЕБЕ НИЧЕГО НЕ ЗНАЧИТ — это тип рабочего колеса, а не машины.
# Проверка на живых данных: «Поставка центробежных пылевых ВЕНТИЛЯТОРОВ для Бирского
# элеватора» первое правило записало в нашу машину. Центробежными бывают вентилятор, насос,
# дымосос, сепаратор, центрифуга — ничего из этого мы не продаём. Поэтому «центробежный»
# засчитывается ТОЛЬКО рядом с существительным нашей машины и в окне, где нет чужого.
CENTRO = re.compile(r'центробежн', re.I)
NASH_SUSHCH = re.compile(r'компрессор|нагнетател|воздуходувк|газодувк|турбоагрегат|'
                         r'компрессорн\w+\s+(?:установк|агрегат|машин)', re.I)
CHUZHOE_SUSHCH = re.compile(r'вентилятор|\bнасос|дымосос|сепаратор|центрифуг|мельниц|'
                            r'питател|конвейер|нори[яйи]|шнек', re.I)

# ОТМЕНА признака нашей машины: контекст, в котором те же слова означают другое.
# Марки инструмента здесь не украшение: «Поставка воздуходувки МОБИЛ К XBA90 ПРЕМИУМ 60В» —
# ручной листодув, и слово «воздуходувка» в нём настоящее. Без марок правило записывало его
# в нашу машину, что и показала проверка на контрольных примерах.
CHUZHOY_KONTEKST = re.compile(
    r'кондиционер|сельскохозяйствен|автомобил|грузов\w+ автом|трактор|комбайн|'
    r'New Holland|John Deere|Challenger|MacDon|IVECO|КАМАЗ|МАЗ\b|ГАЗель|SCANIA|MAN\b|ЯМЗ|'
    r'\bТКР\b|турбин\w+ дизел|стартер\w*,|садов|листодув|бытов|высоторез|триммер|'
    r'газонокосил|кусторез|аккумулятор\w*\s|\bМОБИЛ\b|STIHL|ECHO\b|HUSQVARNA|MAKITA|'
    r'\bBOSCH\b|CHAMPION|PATRIOT|\bDAEWOO\b|\bИНТЕРСКОЛ\b', re.I)

# НЕ МАШИНА, НО ПРИЗНАК НАШЕГО ПРОИЗВОДСТВА. «Строительные конструкции здания цеха разделения
# воздуха» — объект действительно не машина, но фраза доказывает, что на площадке есть
# воздухоразделение, а значит и центробежные машины. Свернуть её — потерять наводку. Такие
# факты помечаются отдельно и НЕ прячутся.
PRIZNAK_PROIZVODSTVA = re.compile(
    r'разделени\w*\s+воздуха|воздухоразделит|компрессорн\w+\s+(?:станци|цех|установк)|'
    r'кислородн\w+\s+станци|ацетиленов\w+\s+станци|азотн\w+\s+станци|'
    r'станци\w*\s+сжат\w+\s+воздуха|воздуходувн\w+\s+станци', re.I)

# Не машина вовсе: сосуды, трубы, строения, арматура, теплотехника.
NE_MASHINA = re.compile(
    r'\bбаллон|сосуд\w*\s+(?:под|работающ)|ресивер|воздухосборник|трубопровод|газоход|'
    r'дымов\w*\s+труб|резервуар|ёмкост|емкост|эстакад|\bздани|сооружени|кран\s+шаров|'
    r'задвижк|\bарматур|\bфильтр\b|теплообменник|\bколонн[аы]\b|сепаратор|'
    r'подъёмн\w+\s+сооружени|\bдымосос|\bвентилятор|\bнасос\b|электронасос|градирн|'
    r'котёл|котел\b|печь\b|автоклав|цистерн', re.I)

# Машина, но чужого типа.
NE_NASH_TIP = re.compile(r'поршнев|винтов|спиральн|мембранн|роторн|вихрев|шестерён|плунжерн|'
                         r'кольцев\w+\s+(?:вакуум|компрессор)|Рутс|\bRoots\b', re.I)

VID_NASH = 'наша машина'
VID_NE_MASHINA = 'не машина: сосуд, труба, строение, арматура'
VID_CHUZHOY_TIP = 'машина чужого типа: поршневая, винтовая, роторная'
VID_CHUZHOY_KONTEKST = 'не наша область: автомобильное, сельхоз, бытовое'
VID_NET_TEKSTA = 'текста нет — не мусор, а отсутствие данных'
VID_PRIZNAK = 'не машина, но признак нашего производства'
VID_NE_SKAZANO = 'о машине ничего не сказано'

SVORACHIVAT = {VID_NE_MASHINA, VID_CHUZHOY_TIP, VID_CHUZHOY_KONTEKST}


def _nasha_mashina(q):
    """Совпадение, доказывающее нашу машину, или None.

    Явное слово принимается сразу. «Центробежный» — только если в окне ±60 знаков стоит
    существительное нашей машины и НЕ стоит чужое: в «центробежный компрессор К-250» окно
    чистое, в «центробежных пылевых вентиляторов» — нет.
    """
    m = NASH_YAVNO.search(q)
    if m:
        return m
    for c in CENTRO.finditer(q):
        okno = q[max(0, c.start() - 60):c.start() + 60]
        if NASH_SUSHCH.search(okno) and not CHUZHOE_SUSHCH.search(okno):
            return c
    return None


def razobrat(quote, equipment_type=''):
    """Вид факта и объяснение словами. Ничего не удаляет, только называет.

    Порядок проверок — не вкусовщина, каждый шаг закрывает свою ошибку:
    сначала чужой контекст (он отменяет наши слова), потом наша машина (она сильнее сосуда),
    потом чужой тип, потом не-машина.
    """
    q = (quote or '').strip()
    if not q:
        return VID_NET_TEKSTA, 'цитаты нет; доказательство может лежать в других полях факта'
    chuzhoy = CHUZHOY_KONTEKST.search(q)
    nash = _nasha_mashina(q)
    if nash and chuzhoy:
        return (VID_CHUZHOY_KONTEKST,
                f'слово машины есть («{nash.group(0)}»), но контекст чужой '
                f'(«{chuzhoy.group(0)}») — это не промышленный компрессор')
    if nash:
        return VID_NASH, f'названа наша машина: «{nash.group(0)}»'
    if chuzhoy:
        return VID_CHUZHOY_KONTEKST, f'чужая область: «{chuzhoy.group(0)}»'
    tip = NE_NASH_TIP.search(q)
    if tip:
        return VID_CHUZHOY_TIP, f'тип машины назван и он не наш: «{tip.group(0)}»'
    pr = PRIZNAK_PROIZVODSTVA.search(q)
    if pr:
        return (VID_PRIZNAK,
                f'объект не машина, но названо «{pr.group(0)}» — это доказывает производство, '
                f'где наши машины стоят; не прячем')
    ne = NE_MASHINA.search(q)
    if ne:
        # Расхождение с разметкой панели называем прямо: по нему видно, где поле врёт.
        rashozhdenie = (f'; при этом в разметке стоит «{equipment_type}»'
                        if 'центробежн' in (equipment_type or '').lower() else '')
        return VID_NE_MASHINA, f'объект не машина: «{ne.group(0)}»{rashozhdenie}'
    return VID_NE_SKAZANO, 'ни слова машины, ни слова сосуда — судить не по чему'


def svorachivat(vid):
    """Прятать ли под счётчик. Отсутствие данных не прячется никогда."""
    return vid in SVORACHIVAT
