def _marka(q):
    """(марка, среда) из проверенного словаря, если она стоит рядом со словом машины.

    Требование соседства то же, что у слова «центробежный», и по той же причине: голая
    последовательность букв с цифрами встречается в текстах постоянно — инвентарный номер,
    позиция по схеме, номер цеха. Марка засчитывается, когда в окне ±80 знаков названа
    машина: «запасных частей к компрессору К-250-61-5» — засчитывается, «поз. ТВ-500 по
    схеме теплотрассы» — нет.
    """
    for m in KANDIDAT_MARKI.finditer(q):
        sreda = MARKI.get(_norm_marku(m.group(1)))
        if not sreda:
            continue
        okno = q[max(0, m.start() - 80):m.end() + 80]
        if NASH_SUSHCH.search(okno) and not CHUZHOE_SUSHCH.search(okno):
            return m.group(1), sreda
    return None, ''


def _nasha_mashina(q):
    """Совпадение, доказывающее нашу машину, или None.

    Явное слово принимается сразу. «Центробежный» — только если в окне ±60 знаков стоит
    существительное нашей машины и НЕ стоит чужое: в «центробежный компрессор К-250» окно
    чистое, в «центробежных пылевых вентиляторов» — нет.
    """
    m = NASH_YAVNO.search(q)
    if m:
        # НАШЕ СЛОВО В СКОБКАХ ПОСЛЕ ЧУЖОЙ МАШИНЫ — ЭТО ПОЯСНЕНИЕ К НЕЙ, А НЕ ОТДЕЛЬНАЯ
        # МАШИНА. Живой случай из реестра ЭПБ: «Радиальный вентилятор (воздуходувка) марки
        # BCSN542 DWDI» уходил в нашу машину по слову «воздуходувка», хотя объект —
        # радиальный вентилятор. Реестр так пишет синонимы, и синоним не меняет объекта.
        # Правило узкое нарочно: только скобка и только чужое существительное прямо перед
        # ней. Широкий вариант («любое чужое слово раньше нашего») отсекал бы перечисления
        # вроде «ремонт насосов и воздуходувок», где наша машина названа по-настоящему.
        do = q[:m.start()]
        if do.rstrip().endswith('(') and CHUZHOE_SUSHCH.search(do[-60:]):
            return None
        return m
    for c in CENTRO.finditer(q):
        okno = q[max(0, c.start() - 60):c.start() + 60]
        if NASH_SUSHCH.search(okno) and not CHUZHOE_SUSHCH.search(okno):
            return c
    return None


