def _marka(q):
    """(марка, среда) из проверенного словаря, если она стоит рядом со словом машины.

    Требование соседства то же, что у слова «центробежный», и по той же причине: голая
    последовательность букв с цифрами встречается в текстах постоянно — инвентарный номер,
    позиция по схеме, номер цеха. Марка засчитывается, когда в окне ±80 знаков названа
    машина: «запасных частей к компрессору К-250-61-5» — засчитывается, «поз. ТВ-500 по
    схеме теплотрассы» — нет.
    """
    for m in KANDIDAT_MARKI.finditer(q):
        sreda = MARKI.get(_norm_marku(m.group(1)))
        if not sreda:
            continue
        okno = q[max(0, m.start() - 80):m.end() + 80]
        if NASH_SUSHCH.search(okno) and not CHUZHOE_SUSHCH.search(okno):
            return m.group(1), sreda
        # РЕФЕРЕНС-ЛИСТ: существительного нет, потому что оно в шапке столбца. Строка
        # «К-905-61-1 Каустик Каустик 6 915 3 0,74 0,10 Электродвигатель Химическая Воздух»
        # читалась как «о машине ничего не сказано» — а это лучшее доказательство, какое у
        # нас есть: проверенная воздушная марка в перечне поставок Невского завода.
        # Засчитываем только проверенную ВОЗДУШНУЮ марку и только при слове «воздух» в
        # строке, где нет чужой машины: два условия вместо отсутствующего существительного.
        if (sreda == 'воздух' and re.search(r'воздух', q, re.I)
                and not CHUZHOE_SUSHCH.search(q)):
            return m.group(1), sreda
    return None, ''


def _nasha_mashina(q):
    """Совпадение, доказывающее нашу машину, или None.

    Явное слово принимается сразу. «Центробежный» — только если в окне ±60 знаков стоит
    существительное нашей машины и НЕ стоит чужое: в «центробежный компрессор К-250» окно
    чистое, в «центробежных пылевых вентиляторов» — нет.
    """
    m = NASH_YAVNO.search(q)
    if m and 'нагнетат' in m.group(0).lower() and NAGNETATEL_CHUZHOY.search(q):
        # Корень наш, машина чужая: ищем дальше — вдруг в строке есть и настоящая наша.
        m = next((x for x in NASH_YAVNO.finditer(q) if 'нагнетат' not in x.group(0).lower()),
                 None)
    if m:
        # НАШЕ СЛОВО В СКОБКАХ ПОСЛЕ ЧУЖОЙ МАШИНЫ — ЭТО ПОЯСНЕНИЕ К НЕЙ, А НЕ ОТДЕЛЬНАЯ
        # МАШИНА. Живой случай из реестра ЭПБ: «Радиальный вентилятор (воздуходувка) марки
        # BCSN542 DWDI» уходил в нашу машину по слову «воздуходувка», хотя объект —
        # радиальный вентилятор. Реестр так пишет синонимы, и синоним не меняет объекта.
        # Правило узкое нарочно: только скобка и только чужое существительное прямо перед
        # ней. Широкий вариант («любое чужое слово раньше нашего») отсекал бы перечисления
        # вроде «ремонт насосов и воздуходувок», где наша машина названа по-настоящему.
        do = q[:m.start()]
        if do.rstrip().endswith('(') and CHUZHOE_SUSHCH.search(do[-60:]):
            return None
        return m
    for c in CENTRO.finditer(q):
        okno = q[max(0, c.start() - 60):c.start() + 60]
        if NASH_SUSHCH.search(okno) and not CHUZHOE_SUSHCH.search(okno):
            return c
    return None


def razobrat(quote, equipment_type=''):
    """Вид факта и объяснение словами. Ничего не удаляет, только называет.

    Порядок проверок — не вкусовщина, каждый шаг закрывает свою ошибку:
    сначала чужой контекст (он отменяет наши слова), потом наша машина (она сильнее сосуда),
    потом чужой тип, потом не-машина.
    """
    q = (quote or '').strip()
    if not q:
        return VID_NET_TEKSTA, 'цитаты нет; доказательство может лежать в других полях факта'
    chuzhoy = CHUZHOY_KONTEKST.search(q)
    nash = _nasha_mashina(q)
    tip = NE_NASH_TIP.search(q)
    ne = NE_MASHINA.search(q)
    if nash and chuzhoy:
        return (VID_CHUZHOY_KONTEKST,
                f'слово машины есть («{nash.group(0)}»), но контекст чужой '
                f'(«{chuzhoy.group(0)}») — это не промышленный компрессор')
    # НАЗВАННЫЙ ТИП МАШИНЫ ОТМЕНЯЕТ НАШЕ СЛОВО, а не проверяется после него. Находка 2-й
    # сессии: «Воздуходувка ротационная РУТСА IRS-150L» уходила в «наша машина», потому что
    # слово «воздуходувка» стояло раньше в порядке проверок. Рутс — объёмная машина, мы её не
    # продаём, и то, что она называется воздуходувкой, ничего не меняет. Моя гипотеза про
    # «правило ломается на перечислениях» оказалась НЕВЕРНОЙ: дело в порядке, а не в списках.
    if nash and tip:
        return (VID_CHUZHOY_TIP,
                f'слово нашей машины есть («{nash.group(0)}»), но прямо назван чужой тип '
                f'(«{tip.group(0)}») — тип сильнее названия')
    # МАРКА СИЛЬНЕЕ РОДОВОГО СЛОВА, КОГДА ГОВОРИТ О СРЕДЕ. «Ремонт нагнетателя Н-370-18-1
    # ГПА-Ц-16» уходило в «наша машина», потому что «нагнетатель» стоит в списке наших слов.
    # Но Н-370-18-1 — нагнетатель газоперекачивающего агрегата, среда газ, и это не наша
    # продажа. То же правило, что у Рутса, только с другой стороны: конкретное сильнее
    # родового. Марка воздушная родовое слово не отменяет — она с ним согласна.
    if nash:
        ne_vozduh = SREDA_NE_VOZDUH.search(q)
        if ne_vozduh and not re.search(r'воздушн|сжат\w+\s+воздух|воздуходув', q, re.I):
            return (VID_SREDA_NE_VOZDUH,
                    f'машина наша («{nash.group(0)}»), но среда названа прямо: '
                    f'«{ne_vozduh.group(0)}» — это не воздух, а значит не наша продажа')
        mk_g, sreda_g = _marka(q)
        if sreda_g == 'газ':
            return (VID_MARKA_GAZ,
                    f'родовое слово наше («{nash.group(0)}»), но марка «{mk_g}» газовая — '
                    f'марка конкретнее слова; не мусор и не цель')
        return VID_NASH, f'названа наша машина: «{nash.group(0)}»'
    if chuzhoy:
        return VID_CHUZHOY_KONTEKST, f'чужая область: «{chuzhoy.group(0)}»'
    if tip:
        return VID_CHUZHOY_TIP, f'тип машины назван и он не наш: «{tip.group(0)}»'
    # МАРКА ПРОВЕРЯЕТСЯ ПОСЛЕ НАЗВАННОГО ТИПА, а не раньше. Порядок тот же, что у правила
    # Рутса: если в строке прямо написано «поршневой», спорить с этим маркой нельзя — там
    # либо опечатка в марке, либо перечисление разных машин, и в обоих случаях выигрывает
    # прямое слово. Зато против молчания марка сильнее всего: она называет конкретную машину.
    mk, sreda_mk = _marka(q)
    if mk:
        if sreda_mk == 'газ':
            return (VID_MARKA_GAZ,
                    f'марка «{mk}» из проверенного словаря — машина центробежная, но среда '
                    f'газовая; не мусор и не цель, повод понизить приоритет')
        if sreda_mk == 'среда неизвестна':
            return (VID_MARKA_SREDA,
                    f'марка «{mk}» из семьи центробежных — тип машины доказан, среда по этой '
                    f'марке не выносится; предприятие с учёта не снимать')
        # ФОРМУЛИРОВКА ВАЖНА: марка доказывает, что машина ЕСТЬ НА ПРЕДПРИЯТИИ, а не что
        # объект факта — она сама. Живой пример: «Маслохолодильник, поз. 51-3/1, зав. №6837,
        # компрессор К-1500-62-2 поз.1, цех №5» — объект здесь маслоохладитель, узел машины.
        # Для цели «у кого стоит наш компрессор» это доказательство даже сильнее закупки:
        # предприятие держит машину и обслуживает её. Но написать «названа наша машина» было
        # бы неправдой про объект, и карточка врала бы человеку, который её читает.
        return (VID_NASH_PO_MARKE,
                f'слова машины в тексте нет, но названа марка «{mk}» — по проверенному '
                f'словарю это центробежная воздушная машина; факт доказывает, что она есть '
                f'на предприятии (сам объект факта может быть её узлом)')
    # ПРИЗНАК ПРОИЗВОДСТВА — ТОЛЬКО КОГДА САМ ОБЪЕКТ НЕ ОПОЗНАН. Второй дефект оттуда же:
    # «Насос центробежный типа НК 200/370 (Площадка компрессорной станции Варьеганская)»
    # получал ярлык «признак производства» и оставался видимым, хотя объект — насос, а
    # «компрессорная станция» здесь просто АДРЕС. Это тот же класс, что чтение среды из имени
    # здания: свойство объекта нельзя выводить из обстоятельства места.
    # ПРИЗНАК ПРОИЗВОДСТВА ГЛУШИТСЯ ЧУЖОЙ МАШИНОЙ, А НЕ ЛЮБЫМ «не машина». Проверка на
    # контрольных примерах поймала регрессию: запрет `pr and not ne` заодно свернул «баллон …
    # (ацетиленовая и кислородная станция)» и «здание цеха разделения воздуха» — то есть ровно
    # те два случая, ради которых правило и писалось. Разница не в том, машина объект или нет,
    # а в том, СПОРИТ ли объект за смысл факта: баллон, здание и труба инертны и ничего не
    # утверждают о типе машины, а насос, вентилятор и дымосос — сами машины, и их имя решает,
    # о чём факт. Поэтому глушит только чужая МАШИНА.
    chuzhaya_mashina = CHUZHOE_SUSHCH.search(q)
    pr = PRIZNAK_PROIZVODSTVA.search(q)
    if pr and not chuzhaya_mashina:
        return (VID_PRIZNAK,
                f'объект не машина, но названо «{pr.group(0)}» — это доказывает производство, '
                f'где наши машины стоят; не прячем')
    if ne:
        # Расхождение с разметкой панели называем прямо: по нему видно, где поле врёт.
        rashozhdenie = (f'; при этом в разметке стоит «{equipment_type}»'
                        if 'центробежн' in (equipment_type or '').lower() else '')
        return VID_NE_MASHINA, f'объект не машина: «{ne.group(0)}»{rashozhdenie}'
    return VID_NE_SKAZANO, 'ни слова машины, ни слова сосуда — судить не по чему'


