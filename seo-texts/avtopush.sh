#!/bin/bash
# Коммит и пуш каждые 4 минуты. Контейнер откатывается примерно раз в час (21:15, 22:17,
# 23:16 — трижды подряд с шагом в час), и теряется всё, что не запушено. Ручной пуш после
# каждого шага не спасает: прогоны пишут в файлы непрерывно, а шаг у меня — десятки минут.
# Четыре минуты выбраны не круглым числом: столько идёт одна пачка разбора страниц, то есть
# между двумя пушами укладывается ровно один результат, и терять нечего.
cd /home/user/avto || exit 1
while true; do
  if [ -n "$(git status --porcelain)" ]; then
    git add -A >/dev/null 2>&1
    git commit -q -m "P25: автосохранение $(date -u +%H:%M) — прогоны пишут непрерывно" >/dev/null 2>&1
    git push -q origin claude/read-intro-section-hrstzj >/dev/null 2>&1 \
      && echo "$(date -u +%H:%M) запушено" \
      || echo "$(date -u +%H:%M) ПУШ НЕ ПРОШЁЛ"
  fi
  sleep 240
done
