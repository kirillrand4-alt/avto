# демонстратив «данный/данная/данное…» как замена «этот» — маркер F5 (не трогаем слово «данные»=data)
DANNYY = re.compile(r'\bданн(?:ый|ая|ое|ые|ого|ой|ым|ыми|ых|ому)\b')
# когезивные мосты, которые не баним совсем (бывают уместны), но караем за перебор
BRIDGES = ['кроме того', 'помимо этого', 'к тому же', 'при этом', 'тем не менее', 'между тем']
LINK_OK = re.compile(r'^(/catalog/vozdushnye-kompressory/po-tipu/vintovye/(dizelnye/enger/|elektricheskie_1/(enger/)?)|/services/uslugi/[a-z-]+_?/|/projects/[a-z0-9%.-]+/[^"]+|/company/reviews/|/company/staff/igor-volkov/|#)')

# Контекстные стоп-слова: подстрокой их ловить нельзя — «порядка» это и хеджирующее
# «порядка 100 бар» (запрещено: числа берём из payload, а не на глазок), и совершенно
# законный родительный падеж «чёткого порядка». Первый прогон волны 2 забраковал по
# нему нормальную фразу «требует соблюдения чёткого порядка», поэтому проверка стала
# регэкспом: хедж = слово перед числом.
BANNED_RX = [
    (r'порядка\s+\d', 'порядка <число> (хедж вместо точной цифры из payload)'),
    (r'около\s+\d', 'около <число> (хедж)'),
]


def banned_rx_hits(text):
    low = (text or '').lower()
    return [name for rx, name in BANNED_RX if re.search(rx, low)]


def refinement_check(low):
    """Мех-детекторы находок филолога/SEO/инженера (в цикл генерации, бесплатно). Возвращает issues."""
    out = []
    # канцелярский пассив (конкретные обороты)
    passives = re.findall(r'(поставка ведётся|отгрузка ведётся|замена выполняется|обслуживание проводится|'
                          r'расчёт ведётся|расчёт производится|подбор осуществляется|доставка осуществляется)', low)
    if passives:
        out.append(f'канцелярский пассив ({", ".join(sorted(set(passives)))}) - актив: «поставляем/отгружаем/меняют»')
    # «пневмоаудит» не чаще 1 раза
    na = low.count('пневмоаудит')
    if na > 1:
        out.append(f'«пневмоаудит» {na}× (норма ≤1) - варьируй: «замерим расход», «рассчитаем нагрузку»')
    # адсорбция как ХИМИЧЕСКИЙ процесс (она физическая)
    if re.search(r'адсорб[а-я]*[^.]{0,70}хими', low) or re.search(r'хими[а-я]*[^.]{0,25}(связыва|удержива)[а-я]*[^.]{0,20}(вод|влаг|пар)', low):
        out.append('адсорбция подана как ХИМИЧЕСКИЙ процесс - она ФИЗИЧЕСКАЯ (силы Ван-дер-Ваальса)')
    # инверсия давление/производительность
    if re.search(r'производительность[^.]{0,50}(сохраняется|не меняется|одинакова|неизменна)[^.]{0,40}давлени', low) \
       or re.search(r'сниж[а-я]* давлени[^.]{0,50}(падает|снижается|ниже)[^.]{0,20}(пропускн|производит)', low) \
       or re.search(r'(выше|повыш[а-я]*|больше) давлени[а-я]*[^.]{0,40}(выше|больше|растёт)[^.]{0,15}производит', low):
        out.append('НЕВЕРНАЯ зависимость давление/производительность (она ОБРАТНАЯ: выше давление - ниже производительность)')
    # неверная причинность «запас/лишний бар давления СНИЖАЕТ производительность» (паспортная х-ка, не «снижение»)
    if re.search(r'(запас|лишн[а-я]+|избыт[а-я]+)\s+(бар|давлени)[а-я]*[^.!?]{0,60}сниж[а-я]*[^.!?]{0,30}производит', low) \
       or re.search(r'лишн[а-я]+ бар[^.!?]{0,45}сниж[а-я]*[^.!?]{0,25}производит', low):
        out.append('неверная причинность «запас давления снижает производительность»: при фиксированной мощности '
                   'компрессор на большем давлении ПАСПОРТНО выдаёт меньше м³/мин - это не «снижение от запаса», а исходная характеристика')
    # (детектор «точка росы -40 без типа» снят как шумный: ловил риторические FAQ «можно ли -20
    #  рефрижераторным? нет» и адсорбционные страницы, где тип ясен из контекста. Осталось в промпте
    #  правилом + ловит инженер на каждой 6-й.)
    # цепочка подготовки воздуха: ресивер ПЕРЕД циклоном (нарушение канона) - ищем в предложении с маркером последовательности
    seq_mk = ('->', '→', 'затем', 'далее', 'следом', 'после чего', 'потом', 'сначала')
    for sent in re.split(r'[.!?;\n]', low):
        if not any(mk in sent for mk in seq_mk):
            continue
        pr = sent.find('ресивер')
        pcyc = min([sent.find(c) for c in ('циклон', 'сепаратор') if c in sent] or [10 ** 9])
        if 0 <= pr < pcyc < 10 ** 9:
            out.append('нарушен порядок цепочки подготовки воздуха: ресивер стоит ПЕРЕД циклонным сепаратором. '
                       'Канон: концевой охладитель -> циклон -> ресивер -> префильтр -> осушитель -> магистральный фильтр')
            break
    # усечённая цепочка: ресивер «(сразу) после компрессора» + осушитель есть, но во всём тексте нет ни
    # концевого охладителя, ни циклона/сепаратора (пропущены обязательные ступени перед ресивером)
    if re.search(r'ресивер[а-я]*[^.!?]{0,45}(сразу\s+)?(после|за)\s+компрессор', low) and 'осушит' in low \
       and 'охладит' not in low and not re.search(r'циклон|сепаратор', low):
        out.append('усечённая цепочка подготовки: ресивер стоит «после компрессора», пропущены концевой '
                   'охладитель и циклонный сепаратор. Канон: компрессор -> концевой охладитель -> циклон -> '
                   'ресивер -> префильтр -> осушитель -> магистральный фильтр')
    return out


def keyword_density_issue(html, text):
    """Кучность точного ключа H1 в первых 500 знаках (Баден-Баден)."""
    m = re.search(r'<h1[^>]*>(.*?)</h1>', html)
    h1 = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip().lower() if m else ''
    if not h1:
        # h1 может отсутствовать в блоке (он на странице отдельно) - берём первый H2 как якорь ключа
        m2 = re.search(r'<h2>(.*?)</h2>', html)
        h1 = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m2.group(1))).strip().lower() if m2 else ''
    if not h1 or len(h1.split()) < 2:
        return None
    key = ' '.join(h1.split()[:3])                 # ядро ключа (первые 3 слова)
    head = text[:500].lower()
    if head.count(key) >= 3:
        return f'кучность ключа «{key}» {head.count(key)}× в первых 500 знаках (Баден-Баден; переформулируй H2/интро)'
    return None


def naturalness(html, text, low):
    """Анти-детект «ритма»: равномерность абзацев, перебор мостов, демонстратив «данный».
    Пороги мягкие и срабатывают только на явных отклонениях (мало ложных срабатываний)."""
    import statistics as _st
    out = []
    words = max(len(text.split()), 1)
    # 12.14: равномерная длина абзацев (CV<0.30 = AI-ровно). Живой текст чередует короткие/длинные.
    paras = [re.sub(r'<[^>]+>', ' ', p).strip() for p in re.findall(r'<p[^>]*>(.*?)</p>', html, re.S)]
    plen = [len(p.split()) for p in paras if len(p.split()) >= 3]
    if len(plen) >= 4:
        cv = _st.pstdev(plen) / (_st.mean(plen) or 1)
        if cv < 0.30:
            out.append(f'абзацы одинаковой длины (CV={cv:.2f}<0.30, маркер AI) - сделай ритм рваным: '
                       f'часть абзацев в 1-2 предложения, часть развёрнутые')
    # 12.11: суммарный перебор когезивных мостов-паразитов
    nb = sum(low.count(b) for b in BRIDGES)
    if nb / (words / 500) > 3:
        out.append(f'когезивных мостов «при этом/кроме того/…» {nb} (>3 на 500 сл) - проредить, связь и так видна')
    # F5: демонстратив «данный» вместо «этот»
    nd = len(DANNYY.findall(low))
    if nd >= 2:
        out.append(f'«данный/данная…» {nd}× - канцелярит, заменить на «этот» или убрать')
    return out


