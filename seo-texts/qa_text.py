def check(d, min_price=None, price_known=True, expected_h1=None, proj_urls=None,
          category='compressor', banned_terms=None, allowed_links=None, require_links=None,
          typing=None, allowed_images=None, require_image=False):
    """d = {"slug","url","title","description","h1","text_html"} -> список претензий (пусто = чисто).
    category: ключ H2_TYPING для проверки полной типизации вводного H2 (по умолчанию compressor).
    banned_terms: дополнительные термины-ловушки для категории (напр. «удаляет масло» для осушителей)."""
    issues = []
    html = d.get('text_html', '')
    text = re.sub(r'<[^>]+>', ' ', html).replace('&nbsp;', ' ')
    text = re.sub(r'\s+', ' ', text).strip()
    low = text.lower()

    if not (2300 <= len(text) <= 5000):
        issues.append(f'объём {len(text)} знаков (норма 2300–5000)')

    hits = [b for b in BANNED if b in low]
    if hits:
        issues.append('стоп-слова: ' + ', '.join(hits))

    issues += naturalness(html, text, low)
    issues += refinement_check(low)          # инженер/филолог-детекторы (обратная зав-ть, цепочка, адсорбция, канцелярит)
    kd = keyword_density_issue(html, text)   # Баден-Баден: кучность ключа в интро
    if kd:
        issues.append(kd)

    inv = re.findall(r'в (?:раздел[а-я]*|каталог[а-я]*|ассортимент[а-я]*|линейк[а-я]+)[^.!?]{0,50}?(?:представлен|собран)[а-я]*|(?:представлен|собран)[а-я]*\s+(?:на|в)\s+(?:странице|разделе|каталоге)', low)
    if inv:
        issues.append('витринная конструкция: ' + ' | '.join(i[:60] for i in inv))

    # SEO-жаргон (границы слова, чтобы не ловить «категория»/«стратегия»)
    jarg = re.findall(r'\b(?:тег|тега|теге|тегу|тегом|тегах|теги|фасет[а-я]*|листинг[а-я]*|выдач[а-я]*)\b', low)
    if jarg:
        issues.append(f'SEO-жаргон в тексте ({len(jarg)}×: {", ".join(sorted(set(jarg)))}) — читатель-инженер его не поймёт')

    if re.search(r'(?:выполняет|решает|проводит расчёт|рассчитывает)\s+пневмоаудит|пневмоаудит\s+(?:выполняет|решает|рассчитывает)', low):
        issues.append('пневмоаудит как субъект действия - переформулировать: инженер проводит пневмоаудит')
    if ('в каталоге' in low or 'на сайте' in low or 'в продаже' in low) and not re.search(r'\bнаш|у нас\b', low):
        issues.append('«в каталоге/на сайте» без принадлежности - хотя бы раз написать «в нашем каталоге»')
    dash = text.count('—')
    if dash:
        issues.append(f'длинное тире « — » запрещено полностью ({dash} вхождений) — замени на дефис «-» или перестрой фразу')

    m = re.search(r'<h2>([^<]+)</h2>', html)
    h2 = (m.group(1) if m else '').lower()
    groups = typing or H2_TYPING.get(category, H2_TYPING['compressor'])
    groups = [tuple(g) if isinstance(g, (list, tuple)) else (g,) for g in groups]
    if not all(any(syn in h2 for syn in g) for g in groups):
        issues.append(f'вводный H2 без полной типизации ({category}): «{m.group(1) if m else "нет"}»')

    # фактические ловушки по категории (нарушение = ошибка предметной области)
    for phrase in (banned_terms or []):
        if phrase.lower() in low:
            issues.append(f'категорийная ловушка «{phrase}» - фактическая ошибка для этой категории')

    if '<ul' in html or '<li' in html:
        issues.append('списки <ul>/<li> запрещены: CSS сайта рисует маркеры длинным тире «—» (ИИ-паттерн). '
                      'Перечисления - короткими абзацами <p> или строками таблицы')
    fake = re.findall(r'<[^a-z/!][^>]{0,15}>', html)
    if fake:
        issues.append('псевдотеги/плейсхолдеры в HTML: ' + ', '.join(sorted(set(fake))[:5]))
    if '<script' in html or '<style' in html:
        issues.append('script/style в тексте запрещены')

    n_tog = html.count('data-toggle="collapse"')
    ids = re.findall(r'id="(accordion-[a-z0-9а-я_-]+)"', html)
    n_col = html.count('panel-collapse collapse')
    if not (n_tog == len(ids) == n_col and len(set(ids)) == len(ids) and n_tog >= 3):
        issues.append(f'аккордеон сломан: toggle={n_tog} ids={len(ids)}/{len(set(ids))} collapse={n_col}')

    imgset = set(allowed_images or [])
    for src in re.findall(r'<img[^>]+src="([^"]+)"', html):
        norm = src.replace('https://prokompressor.ru', '')
        if allowed_images is not None:
            # строгий режим: разрешены ТОЛЬКО фото из payload (иначе модель выдумывает путь -> битая картинка)
            if norm not in imgset:
                issues.append(f'картинка не из payload (выдуманный путь = битое фото на сайте): {src[:70]}')
        elif not (src.startswith('/upload/') or src.startswith('https://prokompressor.ru/upload/')):
            issues.append(f'картинка вне /upload/ сайта: {src[:60]}')
    if require_image and not re.search(r'<img', html):
        issues.append('на брендовой странице есть фото проекта в payload, а в тексте картинки нет - '
                      'вставь ОДНО фото проекта (photo_url из payload) в блок опыта поставок')
    # «сосуд» в контексте прочности/опрессовки — только «сосуд под давлением» (иначе неясно, какой сосуд)
    if re.search(r'сосуд', low) and not re.search(r'сосуд[а-я]*\s+под\s+давлением', low):
        issues.append('«сосуд» без уточнения - используй «сосуд(ы) под давлением» или «ёмкости» (неясно, какой сосуд)')
    # фраза-заглушка «стоимость/наличие смотрите в карточке» — очевидна и вводит в заблуждение
    if re.search(r'(стоимост|цен[аеуы]|наличи)[а-я]*[^.!?]{0,55}карточк|карточк[а-я]*[^.!?]{0,55}(стоимост|цен[аеуы]|наличи)', low):
        issues.append('заглушка «стоимость/наличие показывает карточка» - убрать: очевидно и вводит в '
                      'заблуждение (на цену влияют комплектация, объём, курс). Про цену - только качественно')
    allow = set(allowed_links or [])
    hrefs = re.findall(r'href="([^"]+)"', html)
    for href in hrefs:
        if href in allow or LINK_OK.match(href):
            if proj_urls and href.startswith('/projects/') and href not in proj_urls and href.replace('%20', ' ') not in proj_urls:
                issues.append(f'страница проекта не существует: {href}')
        else:
            issues.append(f'ссылка вне белого списка: {href}')
    # обязательная перелинковка: если payload дал смежные URL — хотя бы один должен стоять ссылкой
    if require_links:
        if not any(u in hrefs for u in require_links):
            issues.append('нет обязательной перелинковки: вставь ссылку минимум на одну смежную '
                          'категорию из related_urls (блок «место в системе»)')

    if expected_h1 and d.get('h1') != expected_h1:
        issues.append(f'h1 изменён: «{d.get("h1")}» (должен быть «{expected_h1}»)')

    dl = len(d.get('description', ''))
    if dl and not (110 <= dl <= 175):  # title/description с 15.07 не генерируются; проверяем только если есть
        issues.append(f'description {dl} знаков (норма 110–175)')

    m2 = re.search(r'от ([\d\s]+) ?₽', d.get('title', ''))
    if m2:
        tprice = int(m2.group(1).replace(' ', ''))
        if not price_known:
            issues.append(f'цена {tprice} ₽ в title, но у бренда цены «по запросу» — убери цену из title')
        elif min_price is not None and abs(tprice - min_price) > 1:
            issues.append(f'цена в title {tprice} ≠ минимальной цене {int(min_price)}')

    return issues
