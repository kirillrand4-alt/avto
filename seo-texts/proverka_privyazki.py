def защита(p, prichina, model=None):
    """Слой 3. Адверсариальная перепроверка отказа: пытается ОПРАВДАТЬ привязку.

    Без неё связка слишком свирепа: замер на размеченных 66 парах показал 15 пойманных мисматчей
    из 16, но 33 ложных отказа из 50 верных — модель-судья в одиночку отвергала даже привязки,
    где имя компании стоит прямо в тексте. В аудите точность (16 из 24 подозрений, 6 оправдано)
    дала именно вторая, оправдывающая ступень.
    """
    t = (p.get('src') or '').strip() or '(нет текста)'
    prompt = ПРОМПТ_ЗАЩИТА.format(inn=p.get('inn', ''), name=(p.get('name') or '')[:80],
                                  okved=(p.get('okved') or '')[:100], region=p.get('region') or '',
                                  what=(p.get('what') or '')[:300], src=t[:2500],
                                  prichina=prichina[:300])
    try:
        txt = _вызов(prompt, model)
    except Exception as e:  # noqa: BLE001
        return 'сбой', f'вызов не прошёл: {type(e).__name__}: {str(e)[:120]}'
    m = re.search(r'\{.*\}', txt, re.S)
    if not m:
        return 'остаётся_сомнительным', 'модель не вернула JSON'
    try:
        d = json.loads(m.group(0))
    except Exception:  # noqa: BLE001
        return 'остаётся_сомнительным', 'JSON не разобран'
    return d.get('itog') or 'остаётся_сомнительным', (d.get('obosnovanie') or '')[:300]


def проверить(p, model=None, model_zashchita=None, второе_мнение=ВТОРОЕ_МНЕНИЕ):
    """Три ступени плюс переспрос. Возвращает (в_рассылку: bool, уровень: str, причина: str).

    Уровень `ручная` означает «не отвергнуто, но и не доказано» — такие в рассылку не идут,
    но и не выбрасываются: их место в очереди на глаз человека (правило «разделять, а не
    отсеивать»).

    ПЕРЕСПРОС (`второе_мнение`). Замер пяти судей на тех же 66 парах: deepseek-v4-pro
    единственный ловит все 16 мисматчей, но платит за это осторожностью — 31 верную привязку
    из 50 он отправляет человеку, а не в рассылку, и 26 из них с ответом «сомнительно», то есть
    без разбора причины. Такой заслон на базе в тысячи адресов означает ручную очередь размером
    в половину базы — рассылка встанет.

    Поэтому уровень `ручная` (и только он) переспрашивается у ВТОРОЙ модели: если её собственный
    трёхступенчатый прогон говорит «отправлять» — отправляем. Кого ставить вторым, решил замер,
    а не цена: gemini-3.6-flash поднимает выход 19 → 40 писем из 50 при НУЛЕ ошибочных, а самая
    дорогая fable-5 на том же месте даёт лишь 30. Уровни `мисматч-подтверждён`,
    `оправдана-но-на-ручную` и `механика-отказ` НЕ переспрашиваются — там отказ обоснован
    разбором, и переспрос вернул бы ровно те письма, ради которых заслон и строился.
    """
    ок, ур, пр = _ступени(p, model, model_zashchita)
    if ок or ур != 'ручная' or not второе_мнение or второе_мнение == (model or MODEL):
        return ок, ур, пр
    ок2, ур2, пр2 = _ступени(p, второе_мнение, второе_мнение)
    if ок2:
        return True, f'второе-мнение:{ур2}', f'{пр} → переспрос {второе_мнение}: {пр2}'
    return False, 'ручная', f'{пр} → переспрос {второе_мнение}: {пр2}'


def _ступени(p, model=None, model_zashchita=None):
    """Механика → суд → адверсариальная защита. Один судья, без переспроса."""
    ур, почему = механика(p)
    if ур == 'доказана':
        return True, 'инн', почему
    if ур == 'отказ':
        return False, 'механика-отказ', почему
    v, pr = суд(p, model)
    if v == 'сбой':
        # Ни в рассылку, ни в «ручная»: отдельный уровень, чтобы прогон было видно как
        # сломанный. Иначе падение шлюза читается как аккуратная осторожная работа.
        return False, 'сбой-модели', pr
    if v == 'совпадает':
        return True, 'модель-подтвердила', pr
    if v == 'сомнительно':
        return False, 'ручная', pr
    itog, ob = защита(p, pr, model_zashchita or model)
    if itog == 'сбой':
        return False, 'сбой-модели', ob
    if itog == 'на_самом_деле_ок':
        # Оправдание НЕ даёт автоотправки. Замер: адверсариальный слой на дешёвой модели
        # оправдал 5 настоящих мисматчей из 16 (АУРУС, Моторика, Бурлак, Воллкрафт и др.).
        # Спорное письмо дороже пропущенного: такие уходят человеку, а не в рассылку.
        return False, 'оправдана-но-на-ручную', ob
    if itog == 'мисматч_подтверждён':
        return False, 'мисматч-подтверждён', ob
    return False, 'ручная', ob


proverit = проверить
