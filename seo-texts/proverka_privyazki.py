# -*- coding: utf-8 -*-
"""Проверка привязки новости к компании — заслон против матчинга «не с той компанией».

ЗАЧЕМ. Аудит 66 привязок кампании (третья сессия, 02.08.2026) дал 16 подтверждённых мисматчей:
тёзка 9, родитель-дочка 2, бывший-обанкроченный 1, дайджест-чужое-событие 1, имя-не-в-тексте 1,
профиль-несовпадение 1, другой-регион 1. Корень — в `newsco_op.привязка()`: уровень `ядро`
(совпало ядро имени) в самом коде помечен «тёзки!», но принимался в кампанию наравне с `инн` и
`полное_имя`.

ПОЧЕМУ ДВА СЛОЯ, А НЕ ОДИН. Механический гейт по тексту ловит только 3 мисматча из 16 — замерено
на размеченном корпусе. Тёзка («ООО ОЗОН» и маркетплейс), несовпадение профиля («Авангард-Агро»
и теплицы), родитель-дочка («Лада Ижевск») правилами по строкам не отличаются от верной привязки:
имя в тексте есть, событие рядом. Их видит только суждение о смысле. Поэтому: дешёвая механика
отсекает очевидное и бесплатно, модель судит остальное.

СЛОЙ 1 (механика, бесплатно):
  * ИНН компании найден в тексте → привязка ДОКАЗАНА, модель не нужна;
  * имени компании в тексте первоисточника нет вовсе → ОТКАЗ;
  * иначе → на слой 2.

СЛОЙ 2 (модель): судит по тексту первоисточника + профилю (ОКВЭД, регион). Модель по правилу
владельца — `deepseek-v4-pro` (свободный текст → факты; в 35 раз дешевле fable-5 при том же
результате). На спорных можно поднять до fable-5.

Использование:
    from proverka_privyazki import proverit
    ok, uroven, prichina = proverit({'inn':..,'name':..,'okved':..,'region':..,'what':..,'src':..})
"""
import json
import os
import re
import urllib.request

B = os.environ.get('PROVIDER_BASE_URL', 'https://router.cheap').rstrip('/')
K = os.environ.get('PROVIDER_API_KEY', '')
MODEL = os.environ.get('MODEL_PRIVYAZKA', 'deepseek-v4-pro')

_ОПФ = re.compile(r'^(ооо|оао|пао|ао|зао|гк|тд|нпо|апк|госкорпораци\w*|публичное|общество|'
                  r'акционерное|закрытое|открытое|ограниченной|ответственностью|научное|'
                  r'производственное|объединение|компания|фирма|группа|торговый|дом)$', re.I)


def ядро(имя):
    """Значащие слова названия: то, что в кавычках, без организационно-правовой формы."""
    m = re.findall(r'[«"”]([^«»"”]{2,})[»"”]', имя or '')
    s = m[0] if m else (имя or '')
    return [t for t in re.findall(r'[а-яёa-z0-9]{4,}', s.lower()) if not _ОПФ.match(t)]


def механика(p):
    """Слой 1. Возвращает 'доказана' | 'отказ' | 'на_суд' и причину."""
    текст = (p.get('src') or '').strip()
    есть_первоисточник = bool(текст)
    if not текст:
        текст = p.get('what') or ''
    инн = str(p.get('inn') or '')
    if инн and инн in текст:
        return 'доказана', 'ИНН компании найден в тексте первоисточника'
    я = ядро(p.get('name') or '')
    в_тексте = bool(я) and all(w[:6] in текст.lower() for w in я)
    if есть_первоисточник and not в_тексте:
        # НЕ отвергаем сами: имя в тексте часто написано иначе — сокращением, брендом,
        # расшифровкой аббревиатуры. Замер: «КСК МК» в посте назван «КСК Металлкомплект»,
        # и жёсткий механический отказ убивал 5 ВЕРНЫХ привязок из 50. Отдаём судье.
        return 'на_суд', 'имени компании нет в тексте дословно (возможна иная запись) — судить'
    if not есть_первоисточник:
        return 'на_суд', 'текста первоисточника нет — судить по краткому описанию'
    return 'на_суд', 'имя в тексте есть, но это не доказательство (тёзки)'


ПРОМПТ = """Ты проверяешь, действительно ли новостное событие относится ИМЕННО к этой компании.
Система холодной рассылки ищет новости ПО ИМЕНИ компании, поэтому часты ошибки: новость про
ТЁЗКУ (другое юрлицо того же названия), про материнскую или дочернюю структуру, про БЫВШЕЕ
(обанкроченное) предприятие того же имени, либо это ДАЙДЖЕСТ, где имя попало рядом с чужим
событием.

Компания: ИНН {inn}, «{name}»
ОКВЭД: {okved}
Регион: {region}

Событие: {what}

Текст первоисточника:
{src}

Признаки ошибки:
- в тексте назван другой город/регион, чем у компании;
- «на площадке бывшего X», «обанкротившегося X» — событие не про действующую компанию;
- профиль (ОКВЭД) не вяжется с событием (полеводство и теплицы, стройремонт и авиастроение);
- событие совершает другое названное юрлицо, а имя компании лишь рядом;
- имя короткое/родовое (ОЗОН, ЛАДА, ДСК, АУРУС), а событие — про известную крупную компанию.

Ответь строго JSON: {{"verdikt":"совпадает"|"не_совпадает"|"сомнительно","prichina":"коротко, с опорой на текст"}}"""


def _вызов(prompt, model=None, timeout=180):
    body = {'model': model or MODEL, 'messages': [{'role': 'user', 'content': prompt}],
            'max_tokens': 700}
    req = urllib.request.Request(
        B + '/v1/chat/completions', data=json.dumps(body).encode(),
        headers={'Authorization': f'Bearer {K}', 'Content-Type': 'application/json',
                 'User-Agent': 'curl/8.5.0'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        o = json.load(r)
    return o['choices'][0]['message']['content']


def суд(p, model=None):
    """Слой 2. Судит моделью. Возвращает (verdikt, prichina)."""
    t = (p.get('src') or '').strip() or '(нет текста, только краткое описание)'
    prompt = ПРОМПТ.format(inn=p.get('inn', ''), name=(p.get('name') or '')[:80],
                           okved=(p.get('okved') or '')[:100], region=p.get('region') or '',
                           what=(p.get('what') or '')[:300], src=t[:2500])
    try:
        txt = _вызов(prompt, model)
    except Exception as e:  # noqa: BLE001
        return 'сомнительно', f'сбой модели: {type(e).__name__}'
    m = re.search(r'\{.*\}', txt, re.S)
    if not m:
        return 'сомнительно', 'модель не вернула JSON'
    try:
        d = json.loads(m.group(0))
    except Exception:  # noqa: BLE001
        return 'сомнительно', 'JSON не разобран'
    return d.get('verdikt') or 'сомнительно', (d.get('prichina') or '')[:300]


ПРОМПТ_ЗАЩИТА = """Адверсариальная перепроверка привязки новости к компании.

Твоя задача — попытаться ОПРАВДАТЬ привязку: может ли событие всё-таки относиться именно к этой
компании? Отвергай только если убеждён, что речь о другом юрлице, другом регионе или ином профиле.

Компания: ИНН {inn}, «{name}», ОКВЭД {okved}, регион {region}
Событие: {what}
Текст первоисточника: {src}

Первичный отказ судьи: {prichina}

Учти частые ОШИБКИ ПЕРВИЧНОГО СУДЬИ:
- имя в тексте написано иначе (сокращение, аббревиатура, бренд вместо юрлица) — это НЕ повод отвергать;
- юрадрес компании в базе (Москва) может не совпадать с площадкой события — для холдингов это норма;
- в тексте назван завод/бренд, принадлежащий этой компании, — это ПОДТВЕРЖДЕНИЕ, а не опровержение.

Ответь строго JSON: {{"itog":"мисматч_подтверждён"|"на_самом_деле_ок"|"остаётся_сомнительным","obosnovanie":"коротко"}}"""


def защита(p, prichina, model=None):
    """Слой 3. Адверсариальная перепроверка отказа: пытается ОПРАВДАТЬ привязку.

    Без неё связка слишком свирепа: замер на размеченных 66 парах показал 15 пойманных мисматчей
    из 16, но 33 ложных отказа из 50 верных — модель-судья в одиночку отвергала даже привязки,
    где имя компании стоит прямо в тексте. В аудите точность (16 из 24 подозрений, 6 оправдано)
    дала именно вторая, оправдывающая ступень.
    """
    t = (p.get('src') or '').strip() or '(нет текста)'
    prompt = ПРОМПТ_ЗАЩИТА.format(inn=p.get('inn', ''), name=(p.get('name') or '')[:80],
                                  okved=(p.get('okved') or '')[:100], region=p.get('region') or '',
                                  what=(p.get('what') or '')[:300], src=t[:2500],
                                  prichina=prichina[:300])
    try:
        txt = _вызов(prompt, model)
    except Exception as e:  # noqa: BLE001
        return 'остаётся_сомнительным', f'сбой модели: {type(e).__name__}'
    m = re.search(r'\{.*\}', txt, re.S)
    if not m:
        return 'остаётся_сомнительным', 'модель не вернула JSON'
    try:
        d = json.loads(m.group(0))
    except Exception:  # noqa: BLE001
        return 'остаётся_сомнительным', 'JSON не разобран'
    return d.get('itog') or 'остаётся_сомнительным', (d.get('obosnovanie') or '')[:300]


def проверить(p, model=None, model_zashchita=None):
    """Три ступени. Возвращает (в_рассылку: bool, уровень: str, причина: str).

    Уровень `ручная` означает «не отвергнуто, но и не доказано» — такие в рассылку не идут,
    но и не выбрасываются: их место в очереди на глаз человека (правило «разделять, а не
    отсеивать»).
    """
    ур, почему = механика(p)
    if ур == 'доказана':
        return True, 'инн', почему
    if ур == 'отказ':
        return False, 'механика-отказ', почему
    v, pr = суд(p, model)
    if v == 'совпадает':
        return True, 'модель-подтвердила', pr
    if v == 'сомнительно':
        return False, 'ручная', pr
    itog, ob = защита(p, pr, model_zashchita or model)
    if itog == 'на_самом_деле_ок':
        # Оправдание НЕ даёт автоотправки. Замер: адверсариальный слой на дешёвой модели
        # оправдал 5 настоящих мисматчей из 16 (АУРУС, Моторика, Бурлак, Воллкрафт и др.).
        # Спорное письмо дороже пропущенного: такие уходят человеку, а не в рассылку.
        return False, 'оправдана-но-на-ручную', ob
    if itog == 'мисматч_подтверждён':
        return False, 'мисматч-подтверждён', ob
    return False, 'ручная', ob


proverit = проверить
