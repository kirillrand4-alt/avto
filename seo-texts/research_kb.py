def slugify(name):
    tr = {'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ж':'zh','з':'z','и':'i','й':'y','к':'k','л':'l','м':'m',
          'н':'n','о':'o','п':'p','р':'r','с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'c','ч':'ch','ш':'sh','щ':'sch',
          'ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya'}
    s = name.lower()
    s = ''.join(tr.get(ch, ch) for ch in s)
    return re.sub(r'[^a-z0-9]+', '-', s).strip('-')


def ask(client, prompt, out_path, model='claude-fable-5'):
    t0 = time.time()
    msg = call(client, [{'role': 'user', 'content': prompt}], model)
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    open(out_path, 'w').write(text + '\n')
    u = msg.usage
    return {'out': os.path.basename(out_path), 'sec': round(time.time() - t0, 1),
            'in': u.input_tokens, 'out_tok': u.output_tokens, 'chars': len(text)}


def main():
    client = make_client()
    log = open(os.path.join(KB, 'research.log'), 'a')
    total_in = total_out = 0
    jobs = [(BRAND_PROMPT.format(brand=b), os.path.join(KB, f'brand-{slugify(b)}.md')) for b in BRANDS]
    jobs += [(p, os.path.join(KB, f'{name}.md')) for name, p in FAQ_TASKS.items()]
    done_before = 0
    for prompt, out_path in jobs:
        if os.path.exists(out_path) and os.path.getsize(out_path) > 400:
            done_before += 1
            continue  # рестарт продолжает с места падения
        try:
            r = ask(client, prompt, out_path)
        except Exception as ex:
            print(f'FAIL {os.path.basename(out_path)}: {repr(ex)[:150]}', file=log, flush=True)
            print(f'FAIL {os.path.basename(out_path)}', flush=True)
            continue
        total_in += r['in']; total_out += r['out_tok']
        print(json.dumps(r, ensure_ascii=False), file=log, flush=True)
        print(f"OK {r['out']} {r['sec']}s {r['chars']} зн.", flush=True)
    print(f'ИТОГО: пропущено готовых {done_before}, токены in={total_in} out={total_out}', file=log, flush=True)
    print(f'БАЗА ЗНАНИЙ СОБРАНА (in={total_in}, out={total_out})', flush=True)


if __name__ == '__main__':
    main()
