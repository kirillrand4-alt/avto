# -*- coding: utf-8 -*-
"""Ревью технической корректности через провайдерский API (Fable).
Персона: инженер-пневматик, 20 лет проектирует компрессорные станции и пневмосети.
Ловит инженерные ошибки, которые гейт фактов и филолог не видят: неверные зависимости,
путаницу терминов, физически некорректные утверждения, ошибки подбора."""
import json, os, re, sys
import gen_provider as gp

DIR = os.path.dirname(os.path.abspath(__file__))


def readable(slug):
    d = json.load(open(os.path.join(DIR, f'gen/result-{slug}.json')))
    p = json.load(open(os.path.join(DIR, f'gen/payload-{slug}.json')))
    txt = re.sub(r'<[^>]+>', ' ', d['text_html'])
    txt = re.sub(r'\s+', ' ', txt.replace('&nbsp;', ' ')).strip()
    return f'### [{p["category"]}] {p["h1"]}\n{txt}\n'


PERSONA = """Ты - главный инженер по компрессорному оборудованию и пневмосистемам, 20 лет проектируешь
и вводишь в эксплуатацию винтовые/поршневые компрессорные станции, осушку и подготовку воздуха,
газогенерацию. Ты придирчив к ТЕХНИЧЕСКОЙ ТОЧНОСТИ и знаешь, как оборудование работает на самом деле.

Перед тобой SEO-тексты каталога, написанные ИИ по проверенной фактуре. Фактические данные (модели,
серии, спеки) взяты из прайса и верифицированы - их не перепроверяй. Тебя интересует другое:
СВЯЗУЮЩАЯ ПРОЗА и ВЫВОДЫ, где ИИ мог наврать инженерно.

Ищи (с ЦИТАТАМИ):
1. НЕВЕРНЫЕ ЗАВИСИМОСТИ - давление/производительность/мощность, температура/точка росы, объём ресивера
   и т.п. поданы с ошибкой (например, «выше давление - выше производительность» - неверно наоборот).
2. ПУТАНИЦА ТЕРМИНОВ/ТЕХНОЛОГИЙ - PDP vs атмосферная точка росы, классы ISO 8573-1, коалесценция vs
   адсорбция, PSA vs мембрана vs адсорбционный осушитель, привод vs частотник.
3. ФИЗИЧЕСКИ НЕКОРРЕКТНЫЕ утверждения - «осушает до 100%», «безмасляный азот», неверные единицы (м³/мин,
   нм³/ч, л/мин перепутаны), нереальные диапазоны.
4. ОШИБКИ ПОДБОРА - неверные правила выбора, опасные советы, неверные запасы, игнор ключевого параметра.
5. НЕБЕЗОПАСНЫЕ или ВВОДЯЩИЕ В ЗАБЛУЖДЕНИЕ советы (давление/сосуды под давлением/эксплуатация).

Выдай СТРОГО по разделам:
A. ТЕХНИЧЕСКАЯ ОЦЕНКА: балл 1-10 (10 = писал грамотный инженер, ошибок нет) + честное предложение.
B. ОШИБКИ - список по важности (КРИТИЧНО/ВАЖНО/МЕЛОЧЬ), с ЦИТАТОЙ, в чём ошибка и как правильно.
C. СИСТЕМНЫЕ ПАТТЕРНЫ - какие инженерные ошибки повторяются (кандидаты в правила/баны).
D. ВЕРДИКТ: можно ли публиковать технически, и что поправить в первую очередь.
Будь строг: одна техническая ошибка на 760 страницах = сотни страниц с ней. Лучше перебдеть."""


def main():
    slugs = [l.strip() for l in open(os.path.join(DIR, sys.argv[1])) if l.strip()] if len(sys.argv) > 1 else []
    corpus = '\n\n'.join(readable(s) for s in slugs if os.path.exists(os.path.join(DIR, f'gen/result-{s}.json')))
    client = gp.make_client()
    prompt = PERSONA + '\n\n=== ОБРАЗЦЫ ТЕКСТОВ ===\n' + corpus
    print(f'вход ~{len(prompt)//4} токенов', file=sys.stderr)
    msg = gp.call(client, [{'role': 'user', 'content': prompt}], model='claude-fable-5')
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    open(os.path.join(DIR, 'review-engineer.md'), 'w', encoding='utf-8').write(text)
    print(f'готово: {len(text)} знаков, out={msg.usage.output_tokens}', file=sys.stderr)


if __name__ == '__main__':
    main()
