def gen(client, prompt, cache_path):
    if os.path.exists(cache_path) and os.path.getsize(cache_path) > 300:
        sys.stderr.write(f"  кэш: {os.path.basename(cache_path)}\n")
        return open(cache_path, encoding="utf-8").read()
    messages = [{"role": "user", "content": CONTEXT + "\n\n" + prompt}]
    msg = G.call(client, messages, model="claude-fable-5", attempts=6)
    txt = "".join(b.text for b in msg.content if b.type == "text").strip()
    with open(cache_path, "w", encoding="utf-8") as f:
        f.write(txt)
    sys.stderr.write(f"  готово: {os.path.basename(cache_path)} ({len(txt)} симв)\n")
    return txt


def main():
    out = DIR
    if "--out" in sys.argv:
        out = sys.argv[sys.argv.index("--out") + 1]
    os.makedirs(out, exist_ok=True)
    client = G.make_client()
    lens_texts = {}
    for key, prompt in LENSES.items():
        t0 = time.time()
        sys.stderr.write(f"[линза {key}]\n"); sys.stderr.flush()
        lens_texts[key] = gen(client, prompt, os.path.join(out, f"lens-{key}.md"))
        sys.stderr.write(f"  за {time.time()-t0:.0f}с\n"); sys.stderr.flush()
    joined = "\n\n".join(f"--- ЛИНЗА {k} ---\n{v}" for k, v in lens_texts.items())
    sys.stderr.write("[СИНТЕЗ]\n"); sys.stderr.flush()
    syn = gen(client, SYNTHESIS.format(lenses=joined), os.path.join(out, "_SYNTHESIS.md"))
    # финальный отчёт
    report = os.path.join(out, "CENTRIFUGAL-CONTACTS-PLAN.md")
    with open(report, "w", encoding="utf-8") as f:
        f.write("# Центробежные компрессоры: план сбора самой ценной базы контактов\n\n")
        f.write("*Сгенерировано через провайдер (claude-fable-5), 6 линз + синтез*\n\n")
        f.write("## СВЕДЁННЫЙ ПЛАН\n\n" + syn + "\n\n---\n\n")
        for k, v in lens_texts.items():
            f.write(f"## Линза {k}\n\n{v}\n\n---\n\n")
    sys.stderr.write(f"ГОТОВО: {report}\n")
    print(json.dumps({"ok": True, "report": report, "lenses": list(lens_texts),
                      "synthesis_chars": len(syn)}, ensure_ascii=False))


if __name__ == "__main__":
    main()
