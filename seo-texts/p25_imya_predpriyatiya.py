"""Одна мерка на все скрипты: НАЗВАНО ЛИ на странице это предприятие.

Повод — число. Замер одним прибором (браузер, жребий 555) прочёл 48 страниц из 48, машину
увидел на 47, а «доказывает» насчитал 13. Вся разница легла в один вопрос: названо ли на
странице предприятие. Я собиралась чинить ссылки — сперва померила саму мерку:

    у 1 070 предприятий из 1 266 (85 %) ОБА первых корня длиной ≥7 букв — это
    организационная форма: ФЕДЕРАЛЬНОЕ, ГОСУДАРСТВЕННОЕ, АКЦИОНЕРНОЕ, БЮДЖЕТНОЕ.

То есть прежняя мерка брала «ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ …» и искала
на странице слово «ФЕДЕРАЛЬНОЕ». На карточке закупки пишут «ФГБУ „…“» — и мерка честно
отвечала «предприятия не видно». Ссылки при этом были в порядке.

ЧТО ЗДЕСЬ. Имя разбирается на СОБСТВЕННЫЕ слова: организационная форма и общие слова
отброшены, кавычки сняты. Совпадением считается:

    ИНН напечатан на странице                         — сильнейший признак, сразу да;
    найдено собственное слово длиной ≥6               — да;
    найдены два собственных слова длиной ≥4           — да;
    иначе                                             — нет.

Одно короткое общее слово (СЕВЕР, ЭНЕРГО) намеренно НЕ засчитывается: оно встречается на
чужих страницах, и такой «плюс» дороже пропуска.

ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ВСТРОЕН: запуск файла напрямую прогоняет проверки, среди которых
выдуманное имя обязано НЕ найтись в чужом тексте. Мерка, которая не умеет сказать «нет»,
не мерка — это правило уже стоило мне пачки ложных «доказано».
"""
import re

FORMA = re.compile(
    r'^(АКЦИОНЕРНОЕ|ОБЩЕСТВО|ОГРАНИЧЕННОЙ|ОТВЕТСТВЕННОСТЬЮ|ПУБЛИЧНОЕ|ЗАКРЫТОЕ|ОТКРЫТОЕ|'
    r'ФЕДЕРАЛЬНОЕ|ГОСУДАРСТВЕННОЕ|МУНИЦИПАЛЬНОЕ|УНИТАРНОЕ|ПРЕДПРИЯТИЕ|УЧРЕЖДЕНИЕ|'
    r'БЮДЖЕТНОЕ|АВТОНОМНОЕ|КАЗЁННОЕ|КАЗЕННОЕ|НЕПУБЛИЧНОЕ|ОРГАНИЗАЦИЯ|КОМПАНИЯ|ФИРМА|'
    r'ПРОИЗВОДСТВЕННЫЙ|ПРОИЗВОДСТВЕННОЕ|НАУЧНО|НАУЧНЫЙ|ОБРАЗОВАТЕЛЬНОЕ|ЗДРАВООХРАНЕНИЯ|'
    r'ВЫСШЕГО|ОБРАЗОВАНИЯ|ФИЛИАЛ|ОТДЕЛЕНИЕ|УПРАВЛЕНИЕ|ГРУППА|ЗАВОД|КОМБИНАТ|ХОЛДИНГ|'
    r'КОРПОРАЦИЯ|ООО|ОАО|ПАО|АО|ЗАО|ФГУП|ГУП|МУП|НАО|ФКУ|ФГБУ|ГБУ|МБУ|УК|НПО|НПП|ПК|СПК)$')


def sobstvennye_slova(imya):
    """Собственные слова названия: без организационной формы, без кавычек и предлогов."""
    slova = re.findall(r'[А-ЯЁA-Z]{3,}', (imya or '').upper().replace('Ё', 'Е'))
    return [w for w in slova if not FORMA.match(w.replace('Е', 'Е'))]


def nazvano(imya, inn, tekst):
    """Названо ли предприятие в тексте. Возвращает (да/нет, чем именно)."""
    t = (tekst or '').upper().replace('Ё', 'Е')
    if inn and str(inn) in re.sub(r'\D', '', tekst or ''):
        return True, 'ИНН напечатан на странице'
    sl = sobstvennye_slova(imya)
    dlinnye = [w for w in sl if len(w) >= 6 and w in t]
    if dlinnye:
        return True, 'слово названия: %s' % dlinnye[0]
    korotkie = [w for w in sl if len(w) >= 4 and w in t]
    if len(korotkie) >= 2:
        return True, 'два слова названия: %s' % ', '.join(korotkie[:2])
    return False, ('на странице нет ни ИНН, ни слов названия'
                   if not korotkie else
                   'нашлось лишь одно короткое слово «%s» — этого мало' % korotkie[0])


if __name__ == '__main__':
    proby = [
        # (имя, ИНН, текст страницы, ожидание)
        ('ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ "ЦЕНТРАЛЬНОЕ ЖКУ"', '7729314745',
         'Заказчик: ФГБУ «ЦЖКУ» Минобороны России, ИНН 7729314745', True),
        ('АКЦИОНЕРНОЕ ОБЩЕСТВО "ИНФРАСТРУКТУРНЫЕ ПРОЕКТЫ"', '1500004950',
         'Заказчик АКЦИОНЕРНОЕ ОБЩЕСТВО "ИНФРАСТРУКТУРНЫЕ ПРОЕКТЫ"', True),
        ('ПУБЛИЧНОЕ АКЦИОНЕРНОЕ ОБЩЕСТВО "ЮЖУРАЛЗОЛОТО ГРУППА КОМПАНИЙ"', '7424024375',
         'Организатор: ПАО «ЮЖУРАЛЗОЛОТО ГРУППА КОМПАНИЙ», Челябинская область', True),
        # ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ: выдуманное имя не должно найтись в чужом тексте
        ('ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "ЩВАРЦКОПФЪ"', '9999999999',
         'Заказчик ПАО «ГАЗПРОМ», закупка компрессора', False),
        # ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ 2: одна общая часть слова — не доказательство
        ('ОБЩЕСТВО С ОГРАНИЧЕННОЙ ОТВЕТСТВЕННОСТЬЮ "СЕВЕР ТРЕЙД"', '1234567890',
         'Компрессорная станция, север Тюменской области', False),
    ]
    horosho = 0
    for imya, inn, tekst, zhdem in proby:
        da, chem = nazvano(imya, inn, tekst)
        ok = (da == zhdem)
        horosho += ok
        print('%s  ждали %-5s вышло %-5s  %s | %s'
              % ('ок ' if ok else 'ПЛОХО', zhdem, da, imya[:44], chem))
    print('\nпроверок пройдено %d из %d' % (horosho, len(proby)))
