"""Одна мерка на все скрипты: НАЗВАНО ЛИ на странице это предприятие.

Повод — число. Замер одним прибором (браузер, жребий 555) прочёл 48 страниц из 48, машину
увидел на 47, а «доказывает» насчитал 13. Вся разница легла в один вопрос: названо ли на
странице предприятие. Я собиралась чинить ссылки — сперва померила саму мерку:

    у 1 070 предприятий из 1 266 (85 %) ОБА первых корня длиной ≥7 букв — это
    организационная форма: ФЕДЕРАЛЬНОЕ, ГОСУДАРСТВЕННОЕ, АКЦИОНЕРНОЕ, БЮДЖЕТНОЕ.

То есть прежняя мерка брала «ФЕДЕРАЛЬНОЕ ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ …» и искала
на странице слово «ФЕДЕРАЛЬНОЕ». На карточке закупки пишут «ФГБУ „…“» — и мерка честно
отвечала «предприятия не видно». Ссылки при этом были в порядке.

ЧТО ЗДЕСЬ. Имя разбирается на СОБСТВЕННЫЕ слова: организационная форма и общие слова
отброшены, кавычки сняты. Совпадением считается:

    ИНН напечатан на странице                         — сильнейший признак, сразу да;
    найдено собственное слово длиной ≥6               — да;
    найдены два собственных слова длиной ≥4           — да;
    иначе                                             — нет.

Одно короткое общее слово (СЕВЕР, ЭНЕРГО) намеренно НЕ засчитывается: оно встречается на
чужих страницах, и такой «плюс» дороже пропуска.

ОТРИЦАТЕЛЬНЫЙ КОНТРОЛЬ ВСТРОЕН: запуск файла напрямую прогоняет проверки, среди которых
выдуманное имя обязано НЕ найтись в чужом тексте. Мерка, которая не умеет сказать «нет»,
не мерка — это правило уже стоило мне пачки ложных «доказано».
"""
import re

FORMA = re.compile(
    r'^(АКЦИОНЕРНОЕ|ОБЩЕСТВО|ОГРАНИЧЕННОЙ|ОТВЕТСТВЕННОСТЬЮ|ПУБЛИЧНОЕ|ЗАКРЫТОЕ|ОТКРЫТОЕ|'
    r'ФЕДЕРАЛЬНОЕ|ГОСУДАРСТВЕННОЕ|МУНИЦИПАЛЬНОЕ|УНИТАРНОЕ|ПРЕДПРИЯТИЕ|УЧРЕЖДЕНИЕ|'
    r'БЮДЖЕТНОЕ|АВТОНОМНОЕ|КАЗЁННОЕ|КАЗЕННОЕ|НЕПУБЛИЧНОЕ|ОРГАНИЗАЦИЯ|КОМПАНИЯ|ФИРМА|'
    r'ПРОИЗВОДСТВЕННЫЙ|ПРОИЗВОДСТВЕННОЕ|НАУЧНО|НАУЧНЫЙ|ОБРАЗОВАТЕЛЬНОЕ|ЗДРАВООХРАНЕНИЯ|'
    r'ВЫСШЕГО|ОБРАЗОВАНИЯ|ФИЛИАЛ|ОТДЕЛЕНИЕ|УПРАВЛЕНИЕ|ГРУППА|ЗАВОД|КОМБИНАТ|ХОЛДИНГ|'
    r'КОРПОРАЦИЯ|ООО|ОАО|ПАО|АО|ЗАО|ФГУП|ГУП|МУП|НАО|ФКУ|ФГБУ|ГБУ|МБУ|УК|НПО|НПП|ПК|СПК)$')


def sobstvennye_slova(imya):
    """Собственные слова названия: без организационной формы, без кавычек и предлогов."""
    slova = re.findall(r'[А-ЯЁA-Z]{3,}', (imya or '').upper().replace('Ё', 'Е'))
    return [w for w in slova if not FORMA.match(w.replace('Е', 'Е'))]


# ИМЯ ПОЛЯ НЕ УГАДЫВАЕТСЯ. Разбор восемнадцати проб показал, что «предприятие не названо»
# выходило не из-за страниц: в `park_ingest_3b/3c` название лежит под ключом `organizaciya`,
# в `park_ingest_3` его нет вовсе, и только в `3d` оно зовётся `predpriyatie`. Мерка читала
# один ключ, получала пустоту и честно печатала «не названо» — 14 раз из 18. Страницы при
# этом заказчика называют: «Заказчик ПАО „НПО ИСКРА“», «Организатор конкурса: ОАО
# Соликамский магниевый завод». Поэтому имя берётся ПО ВСЕМ известным ключам.
KLYUCHI_IMENI = ('predpriyatie', 'organizaciya', 'zakazchik', 'nazvanie', 'company', 'name')


def imya_iz(o):
    for k in KLYUCHI_IMENI:
        v = (o.get(k) or '').strip() if isinstance(o, dict) else ''
        if v:
            return v
    return ''


# ПОДПИСЬ «ЗАКАЗЧИК» СИЛЬНЕЕ ВСЕЙ СТРАНИЦЫ. Поймано глазами на снимке
# DOKAZ-2457029066-9134986300.png: строка числилась проверенной за МУП Таймырского района,
# а на странице чёрным по белому «Заказчик: АО „Норильскгазпром“ — Шамов Иван Николаевич,
# руководитель проекта, тел. +7 (913) 498-63-00». Имя МУП «подтвердилось» словом
# «ТАЙМЫРСКОГО», которое на этой странице встречается как название района, а не заказчика.
# Ниже на той же странице стоит блок ИСПОЛНИТЕЛЯ (ООО «Терра-ЮГ») со своими людьми —
# то есть страница вообще про троих, и совпадение «где-то на странице» ничего не значит.
PODPIS = re.compile(r'(заказчик|организатор конкурса|информация об организаторе|'
                    r'сведения о заказчик)\s*[:\-—]?\s*', re.I)


def okno_zakazchika(tekst, dlina=110):
    """Имя сразу после подписи «Заказчик»/«Организатор», ОБРЕЗАННОЕ по концу фразы.

    Ширина окна — не мелочь. Первый вариант брал 200 знаков и втянул соседнее предложение
    («Администрация Таймырского Долгано-Ненецкого района»), из-за чего контроль снова
    подтвердил чужое предприятие словом «ТАЙМЫРСКОГО». Название заказчика редко длиннее
    сотни знаков и всегда кончается на границе фразы, поэтому окно режется по первому же
    разделителю: тире, точка с пробелом, точка с запятой, перевод строки.
    """
    out = []
    t = tekst or ''
    for m in PODPIS.finditer(t):
        kus = t[m.end():m.end() + dlina]
        kon = len(kus)
        for razdel in (' — ', ' – ', ' - ', '. ', '; ', '\n', ' Контактн', ' Комментар'):
            i = kus.find(razdel)
            if 0 <= i < kon:
                kon = i
        out.append(kus[:kon])
    return out


def nazvano(imya, inn, tekst):
    """Названо ли предприятие в тексте. Возвращает (да/нет, чем именно)."""
    # Если подпись «Заказчик» на странице ЕСТЬ — сравниваем только с тем, что стоит после
    # неё. Это снимает целый класс ложных «проверено»: совпадение с географическим словом,
    # с именем исполнителя, с соседним тендером в блоке «другие тендеры компании».
    okna = okno_zakazchika(tekst)
    if okna:
        t = ' | '.join(okna).upper().replace('Ё', 'Е')
        chem_hvost = ' (совпало в подписи «заказчик»)'
    else:
        t = (tekst or '').upper().replace('Ё', 'Е')
        chem_hvost = ' (подписи «заказчик» на странице нет, сравнение по всей странице)'
    if inn and str(inn) in re.sub(r'\D', '', tekst or ''):
        return True, 'ИНН напечатан на странице'
    sl = sobstvennye_slova(imya)
    dlinnye = [w for w in sl if len(w) >= 6 and w in t]
    if dlinnye:
        return True, 'слово названия: %s%s' % (dlinnye[0], chem_hvost)
    korotkie = [w for w in sl if len(w) >= 4 and w in t]
    if len(korotkie) >= 2:
        return True, 'два слова названия: %s%s' % (', '.join(korotkie[:2]), chem_hvost)
    return False, (('в подписи «заказчик» стоит другое предприятие' if okna else
                    'на странице нет ни ИНН, ни слов названия')
                   if not korotkie else
                   'нашлось лишь одно короткое слово «%s» — этого мало' % korotkie[0])


