def main():
    threads = int(sys.argv[sys.argv.index('--threads') + 1]) if '--threads' in sys.argv else 6
    os.makedirs(OUT, exist_ok=True)
    client = G.make_client()
    lock = threading.Lock()

    def odna(item):
        imya, zadacha = item
        try:
            out = G.call(client, [{'role': 'user',
                                   'content': ZAYAVLENIE + '\n\n' + zadacha}], model=MODEL)
            txt = ''.join(b.text for b in out.content if b.type == 'text').strip()
        except Exception as e:  # noqa: BLE001
            txt = f'ОШИБКА: {type(e).__name__}: {e}'
        p = os.path.join(OUT, f'lens-{imya}.md')
        with lock:
            open(p, 'w', encoding='utf-8').write(txt + '\n')
        return imya, len(txt)

    with ThreadPoolExecutor(max_workers=threads) as pool:
        for imya, n in pool.map(odna, LINZY.items()):
            print(f'  {imya}: {n} знаков', file=sys.stderr)
    print(f'готово → {OUT}', file=sys.stderr)


if __name__ == '__main__':
    main()
