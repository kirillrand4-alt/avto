# -*- coding: utf-8 -*-
"""Ревью «насколько по-русски написан текст» через провайдерский API (Fable).
Персона: редактор-филолог + копирайтер, носитель русского, технические/коммерческие B2B-тексты.
Задача: поймать кальки, канцелярит, неестественные коллокации, переводной синтаксис, тавтологию -
всё, что мех.QA не ловит, и что владелец ловит вручную. Выделить ПОВТОРЯЮЩИЕСЯ паттерны -> в правила."""
import json, os, re, sys
import gen_provider as gp

DIR = os.path.dirname(os.path.abspath(__file__))


def readable(slug):
    d = json.load(open(os.path.join(DIR, f'gen/result-{slug}.json')))
    p = json.load(open(os.path.join(DIR, f'gen/payload-{slug}.json')))
    txt = re.sub(r'<[^>]+>', ' ', d['text_html'])
    txt = re.sub(r'\s+', ' ', txt.replace('&nbsp;', ' ')).strip()
    return f'### [{p["category"]}] {p["h1"]}\n{txt}\n'


PERSONA = """Ты - опытный литературный редактор и корректор, НОСИТЕЛЬ русского языка, 20 лет правишь
технические и коммерческие B2B-тексты (промоборудование, инжиниринг). Твой единственный критерий:
насколько текст написан ЖИВЫМ, ЕСТЕСТВЕННЫМ РУССКИМ, а не «переводным»/машинным/канцелярским.

Перед тобой образцы SEO-текстов каталога (промышленные компрессоры и подготовка воздуха), написанные
ИИ. Тексты уже прошли механические фильтры (нет длинного тире, штампов, хеджей). Тебя интересует то,
что фильтры НЕ ловят - тонкая неестественность.

Что искать (с ЦИТАТАМИ из текстов):
1. КАЛЬКИ и переводной синтаксис - обороты, звучащие как перевод с англ/нем («в программе завода»,
   номинализации-цепочки, «является + сущ» вместо глагола, злоупотребление отглагольными).
2. КАНЦЕЛЯРИТ и казённость - там, где живой человек сказал бы проще.
3. НЕЕСТЕСТВЕННЫЕ КОЛЛОКАЦИИ - слова технически верны, но так не говорят («выполняет пневмоаудит»,
   «сосуды на прочность» без уточнения).
4. ТАВТОЛОГИЯ и водянистость - пустые фразы-заглушки, повторы смысла.
5. РЕГИСТРОВЫЕ СБОИ - скачки от казённого к разговорному, неровный тон.
6. «РОБОТНОСТЬ» на уровне интонации - которую носитель чувствует, а метрика нет.

Выдай СТРОГО по разделам:
A. ОБЩАЯ ОЦЕНКА «по-русски»: балл 1-10 (10 = неотличимо от хорошего живого редактора) + одно честное предложение.
B. КОНКРЕТНЫЕ НАХОДКИ - список с ЦИТАТОЙ, в чём неестественность, и как сказал бы носитель. Самые важные сверху.
C. ПОВТОРЯЮЩИЕСЯ ПАТТЕРНЫ - что встречается СИСТЕМНО (в 3+ текстах). Это кандидаты в правила/баны.
D. ВЕРДИКТ по ценности постоянного ревьюера-филолога: стоит ли, и в каком виде (семплер-критик,
   правила, или per-text гейт). Честно: если тексты и так хороши - так и скажи.
Пиши прямо, без комплиментов ради вежливости. Ты отвечаешь за то, чтобы текст читался как написанный человеком."""


def main():
    slugs = [l.strip() for l in open(os.path.join(DIR, sys.argv[1])) if l.strip()] if len(sys.argv) > 1 else []
    corpus = '\n\n'.join(readable(s) for s in slugs if os.path.exists(os.path.join(DIR, f'gen/result-{s}.json')))
    client = gp.make_client()
    prompt = PERSONA + '\n\n=== ОБРАЗЦЫ (14 текстов) ===\n' + corpus
    print(f'вход ~{len(prompt)//4} токенов', file=sys.stderr)
    msg = gp.call(client, [{'role': 'user', 'content': prompt}], model='claude-fable-5')
    text = ''.join(b.text for b in msg.content if b.type == 'text').strip()
    open(os.path.join(DIR, 'review-philolog.md'), 'w', encoding='utf-8').write(text)
    print(f'готово: {len(text)} знаков, out={msg.usage.output_tokens} ток', file=sys.stderr)


if __name__ == '__main__':
    main()
