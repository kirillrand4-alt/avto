def spisok_modeley():
    return [x.strip() for x in
            (sys.argv[sys.argv.index('--model') + 1] if '--model' in sys.argv
             else 'claude-fable-5').split(',')]


def main():
    G.env()
    modeli = spisok_modeley()
    zadaniya = [(rol, prompt, m) for rol, prompt in LINZY for m in modeli]
    lock = threading.Lock()
    otvety = []

    def odna(z):
        rol, rol_prompt, model = z
        msgs = [{'role': 'user', 'content': [{'type': 'text', 'text': rol_prompt + '\n\n' + ZADACHA}]}]
        try:
            t = time.time()
            tekst = G.call_model(model, msgs, max_tokens=6000)
            return {'rol': rol, 'model': model, 'sek': round(time.time() - t, 1),
                    'otvet': tekst, 'oshibka': ''}
        except Exception as e:  # noqa: BLE001
            return {'rol': rol, 'model': model, 'sek': 0, 'otvet': '',
                    'oshibka': f'{type(e).__name__}: {str(e)[:200]}'}

    with ThreadPoolExecutor(max_workers=3) as pool:
        for r in pool.map(odna, zadaniya):
            with lock:
                otvety.append(r)
                with open(SYROY, 'a', encoding='utf-8') as f:
                    f.write(json.dumps(r, ensure_ascii=False) + '\n')
                print(f'  {r["rol"]} / {r["model"]}: '
                      + (f'СБОЙ {r["oshibka"]}' if r['oshibka']
                         else f'{len(r["otvet"])} знаков за {r["sek"]} с'),
                      file=sys.stderr, flush=True)

    udalos = [r for r in otvety if r['otvet']]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('# Справочники ввезённых компрессоров: ответы шести линз\n\n')
        f.write('Вопрос владельца: есть ли справочники ввезённых в Россию компрессоров и кому '
                'они в итоге достались.\n\n')
        f.write('**Как читать.** Это ответы МОДЕЛИ, а не проверенные факты. Каждая линза сама '
                'делит ответ на «проверяемое» и «догадки», но и проверяемое надо проверять: '
                'источник считается существующим только после того, как мы сделаем к нему '
                'запрос и увидим данные. Ни одна строка отсюда не идёт в базу до проверки.\n\n')
        f.write(f'Линз: {len(LINZY)}, ответов получено: {len(udalos)} из {len(zadaniya)}.\n\n')
        for r in otvety:
            f.write(f'\n---\n\n## Линза: {r["rol"]} (модель {r["model"]})\n\n')
            f.write(r['oshibka'] and f'**СБОЙ:** {r["oshibka"]}\n' or r['otvet'] + '\n')
    print(f'\n→ {OUT}\n→ {SYROY}', file=sys.stderr)
    print('СЛЕДУЮЩИЙ ШАГ ОБЯЗАТЕЛЕН: назвать источники, которые встретились у ДВУХ И БОЛЕЕ '
          'линз независимо, и проверить их запросом. Совпадение независимых ролей — признак, '
          'что источник существует; одиночное упоминание — кандидат в выдумку.', file=sys.stderr)


if __name__ == '__main__':
    main()
