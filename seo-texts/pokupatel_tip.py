# -*- coding: utf-8 -*-
"""Кто покупатель: у школы «воздуходувка» — это ручной листодув, а у водоканала — наша машина.

ПОЧЕМУ ЭТОТ МОДУЛЬ ПОЯВИЛСЯ. Разметчик фактов я чинил весь день и довёл до 15 из 15 на
контрольных примерах. Потом прогнал его по 899 скрытым компаниям панели, и он сказал: у 667
доказана НАША МАШИНА, надо вернуть. Посмотрел, что именно он засчитал:

    МБОУ «СОШ № 4 г. Шатуры»                 «Поставка воздуходувки»
    Администрация города Смоленска           «Поставка воздуходувки»
    МБУ культуры                             «Поставка воздуходувки для содержания
                                              хоккейной коробки»
    Администрация города Мичуринска          «Поставка воздуходувки - измельчителя»

Это садовые листодувы. Слово «воздуходувка» в них настоящее, контекста «садовый» нет, марки
инструмента нет — текст ЧИСТ, и по тексту решить нельзя в принципе. Скрывшая их сессия была
права, а мой разметчик вернул бы в очередь продавца 600+ школ.

ВЫВОД, КОТОРЫЙ ДОРОЖЕ САМОГО СЛУЧАЯ: тип машины доказывается текстом, а вот МОЖЕТ ЛИ она
там стоять — доказывается покупателем. Это разные вопросы, и решать второй первым инструментом
нельзя. Центробежный воздушный компрессор — машина промышленной площадки: он стоит в
компрессорной станции, требует фундамента, охлаждения и энергохозяйства. Школа его не купит
никогда, и никакая цитата этого не изменит.

ЧЕГО ЗДЕСЬ НЕТ И БЫТЬ НЕ ДОЛЖНО: сплошного запрета на бюджетные организации. Водоканал,
очистные сооружения и теплосеть — тоже МУП и ГУП, и у них турбовоздуходувки СТОЯТ: аэрация
аэротенков это ровно наша ТВ-80/ТВ-150. Выкинуть их вместе со школами значит потерять лучший
сегмент. Поэтому список разрешающих признаков проверяется ПЕРВЫМ и сильнее запрещающих.

Модуль ничего не прячет и не удаляет — он называет тип покупателя, а решение принимает тот,
кто читает. Слово владельца: разделять, а не отсеивать.
"""
import re

# РАЗРЕШАЮЩИЕ признаки идут первыми и отменяют запрет: это бюджетные организации, у которых
# наша машина стоит по технологии. Аэрация сточных вод — крупнейший потребитель
# турбовоздуходувок после металлургии.
MOZHET = re.compile(
    r'водоканал|водоснабж|водопровод|канализ|очистн\w+\s+сооруж|аэраци|水|'
    r'теплосет|теплоснабж|тепловы\w+\s+сет|тэц|\bгрэс\b|котельн|энергосбыт|'
    r'горэлектросет|электросет|\bвода\b|акваснаб|спецавтохозяйств|'
    r'мусоросжиг|мусоропереработ|полигон|биологическ\w+\s+очистк', re.I)

# ЗАПРЕЩАЮЩИЕ: организации, у которых промышленной компрессорной нет и не бывает.
NE_MOZHET = re.compile(
    r'\bшкол|\bсош\b|\bмбоу\b|\bмаоу\b|\bмоу\b|\bгбоу\b|\bмкоу\b|\bмбдоу\b|\bгбдоу\b|'
    r'\bмадоу\b|\bдоу\b|детск\w+\s+сад|гимнази|лице[йя]|общеобразоват|дошкольн|'
    r'администраци\w*\s+(?:город|район|сельск|муниципальн|поселени)|\bсельсовет|'
    r'\bмуниципальн\w+\s+(?:округ|район)\b|управа\b|префектур|'
    r'учреждени\w*\s+культур|дворец\s+культур|\bбиблиотек|\bмузе[йя]|\bтеатр\b|'
    r'филармони|\bпарк\w*\s+культур|\bзоопарк|'
    r'спортивн\w+\s+(?:школ|комплекс|центр|сооружени)|физическ\w+\s+культур|\bстадион|'
    r'спорткомплекс|\bбассейн|ледов\w+\s+(?:дворец|аренa|арен)|\bфок\b|'
    r'\bбольниц|поликлиник|\bдиспансер|\bсанатор|госпитал|'
    r'\bлесничеств|\bзаповедник|национальн\w+\s+парк|'
    r'благоустройств|озеленени|\bкладбищ|ритуальн', re.I)


VID_MOZHET = 'промышленная или коммунальная площадка: наша машина стоять может'
VID_NE_MOZHET = 'не промышленная площадка: школа, администрация, культура, спорт, медицина'
VID_NEYASNO = 'по имени не определить'


def tip(imya):
    """(вид покупателя, объяснение). Разрешающий признак сильнее запрещающего."""
    v = imya or ''
    m = MOZHET.search(v)
    if m:
        return VID_MOZHET, f'коммунальная технология: «{m.group(0)}» — аэрация и сжатый воздух'
    n = NE_MOZHET.search(v)
    if n:
        return (VID_NE_MOZHET,
                f'«{n.group(0)}» — у такой организации промышленной компрессорной нет; '
                f'слово «воздуходувка» здесь означает ручной листодув')
    return VID_NEYASNO, 'имя не называет ни промышленности, ни бюджетной непромышленности'


def mozhet_stoyat(imya):
    """Может ли у такого покупателя стоять центробежный воздушный компрессор."""
    return tip(imya)[0] != VID_NE_MOZHET


if __name__ == '__main__':
    proby = [('МБОУ "СОШ № 4 Г. ШАТУРЫ"', False),
             ('АДМИНИСТРАЦИЯ ГОРОДА СМОЛЕНСКА', False),
             ('Муниципальное бюджетное учреждение культуры "Дворец культуры"', False),
             ('ГОСУДАРСТВЕННОЕ БЮДЖЕТНОЕ ДОШКОЛЬНОЕ ОБРАЗОВАТЕЛЬНОЕ УЧРЕЖДЕНИЕ', False),
             ('МУП "ВОДОКАНАЛ" Г. ПЕРМИ', True),
             ('МУП "Теплосеть" г. Клин', True),
             ('ГУП "Водоканал Санкт-Петербурга"', True),
             ('МУП «Очистные сооружения канализации»', True),
             ('АО "СПО "АРКТИКА"', True),
             ('ПАО "ЮНИПРО"', True),
             ('АО "РУСАЛ УРАЛ"', True),
             ('МУНИЦИПАЛЬНОЕ БЮДЖЕТНОЕ УЧРЕЖДЕНИЕ ГОРОДСКОГО ОКРУГА ДОМОДЕДОВО '
              '"СПОРТИВНЫЙ КОМПЛЕКС"', False)]
    for imya, ozhid in proby:
        v, poch = tip(imya)
        est = v != VID_NE_MOZHET
        print(f'{"OK  " if est == ozhid else "МИМО"} {imya[:52]:<52} {v[:38]}')
