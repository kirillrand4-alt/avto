    with open(put, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter=';', extrasaction='ignore')
        w.writeheader()
        w.writerows(rows)
    print(f'применено, копия до починки в {RAB}/VOZDUSHNYE-do-pochinki.csv', file=sys.stderr)


