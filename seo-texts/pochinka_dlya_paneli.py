def pochinit_istochnik(s):
    """Служебная пометка утекла продавцу 31 раз. Плюс `tender.pro` и `Тендер.Про` —
    один источник, показанный как два."""
    t = s or ''
    for a, b in ISTOCHNIK_ZAMENA:
        t = t.replace(a, b)
    kuski, vidno = [], set()
    for k in re.split(r'\s*;\s*', t):
        k = k.strip()
        if not k:
            continue
        norm = k.lower().replace('.', '').replace(' ', '')
        norm = 'tenderpro' if norm in ('tenderpro', 'тендерпро') else norm
        if norm in vidno:
            continue
        vidno.add(norm)
        kuski.append('Tender.pro' if norm == 'tenderpro' else k)
    return '; '.join(kuski)


