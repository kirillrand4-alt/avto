def run_lens(key):
    title, body = LENSES[key]
    prompt = f'{CONTEXT}\n\n{ZADACHA}\n\nТВОЯ МЕТА-ЛИНЗА: {title}\n{body}\n\n{FORMAT}'
    t0 = time.time()
    text, usage = ask(prompt)
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, f'meta-{key}.md')
    with open(path, 'w', encoding='utf-8') as f:
        f.write(f'# Мета-линза: {title}\n\n_{key}, {int(time.time() - t0)} с, '
                f'{usage["out"]} токенов_\n\n{text}\n')
    print(f'  готово: {key} ({usage["out"]} ток., {int(time.time() - t0)} с)', file=sys.stderr)
    return key, usage


def synthesize(keys):
    parts = []
    for k in keys:
        p = os.path.join(OUT, f'meta-{k}.md')
        if os.path.exists(p):
            parts.append(open(p, encoding='utf-8').read())
    prompt = (f'{CONTEXT}\n\n{ZADACHA}\n\n'
              'Ниже — предложения новых линз от нескольких мета-линз. Сведи их в один '
              'список, готовый к запуску.\n\n'
              'ТРЕБОВАНИЯ:\n'
              '- Убери дубли и то, что уже проверено.\n'
              '- Отранжируй по ожидаемой отдаче, честно: сначала те, где проверка за час '
              'даёт однозначный ответ.\n'
              '- Для каждой оставленной линзы дай готовый текст задания, который можно '
              'подать модели без правок.\n'
              '- Отдельным разделом: какие из предложенных линз противоречат уже '
              'измеренным ограничениям и почему их не надо запускать.\n'
              '- Отдельным разделом: три линзы, которые ты бы запустил первыми, и почему '
              'именно они.\n'
              '- 1200–1800 слов.\n\n'
              + '\n\n---\n\n'.join(parts))
    text, usage = ask(prompt, max_tokens=18000, min_len=1200)
    with open(os.path.join(OUT, 'SUMMARY-meta.md'), 'w', encoding='utf-8') as f:
        f.write(f'# Новые линзы: сводка по {len(parts)} мета-линзам\n\n'
                f'_{usage["out"]} токенов_\n\n{text}\n')
    print(f'  синтез готов ({usage["out"]} ток.)', file=sys.stderr)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', default='')
    ap.add_argument('--workers', type=int, default=6)
    ap.add_argument('--no-synth', action='store_true')
    a = ap.parse_args()
    keys = [k.strip() for k in a.only.split(',') if k.strip()] or list(LENSES)
    bad = [k for k in keys if k not in LENSES]
    if bad:
        sys.exit(f'нет таких линз: {bad}. Есть: {list(LENSES)}')
    os.makedirs(OUT, exist_ok=True)
    print(f'запускаю {len(keys)} мета-линз', file=sys.stderr)
    stats = {}
    with ThreadPoolExecutor(max_workers=a.workers) as ex:
        for fut in [ex.submit(run_lens, k) for k in keys]:
            try:
                k, u = fut.result()
                stats[k] = u
            except Exception as e:  # noqa: BLE001
                print(f'  ЛИНЗА УПАЛА: {e}', file=sys.stderr)
    with open(os.path.join(OUT, 'run-stats.json'), 'w', encoding='utf-8') as f:
        json.dump(stats, f, ensure_ascii=False, indent=1)
    if not a.no_synth:
        synthesize(keys)


if __name__ == '__main__':
    main()
