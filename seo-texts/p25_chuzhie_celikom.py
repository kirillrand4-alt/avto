"""Все 202 «ЧУЖИХ» подряд, с указанием, за что поставлен ярлык. Каждый неверный — потеря.

Первый заход напечатал их первыми, и хвост раннера (хранит КОНЕЦ вывода) их съел: я
увидела случайные образцы, а отбракованное — нет. Порядок печати это не оформление: то,
что напечатано раньше лимита, всё равно что не напечатано. Здесь чужие идут ПОСЛЕДНИМИ.

Уже на случайных образцах видна дыра в мере с ДРУГОЙ стороны:

    «В деревнях Березино и Приволье открыли два фельдшерско-акушерских пункта (ФАПа)…»
                                                          -> у меня вышло КОСВЕННЫЙ

Соцобъект должен быть ЧУЖИМ, а мой список чужого знает «больницу» и «школу» и не знает
«ФАП» и «фельдшерский». Значит мера дырявая в обе стороны, и правку я сделаю ОДНУ — после
того, как прочитаю всё отбракованное, а не по одному попавшемуся случаю.

Только чтение.
"""
import collections
import json
import os
import re
import sqlite3

BAZA = r'C:\sender\enrich.db'

MASHINA = re.compile(
    r'компрессор\w*|компрессорн\w+|турбокомпрессор\w*|газодувк\w+|газодувн\w+|'
    r'воздуходувк\w+|нагнетател\w+|бустер\w*|'
    r'воздухоразделен\w+|воздухоразделительн\w+|\bВРУ\b|\bКС\b|\bКСУ\b|'
    r'сжат\w+\s+воздух\w*|сжатого\s+газа|пневмат\w+|пневмосистем\w+|'
    r'осушител\w+\s+возду\w+|осушк\w+\s+возду\w+|'
    r'генератор\w*\s+(?:азота|кислорода)|азотн\w+\s+станци\w+|кислородн\w+\s+станци\w+|'
    r'\bазот\w*\b|\bкислород\w*\b|'
    r'холодильн\w+\s+машин\w+|чиллер\w*|'
    r'ресивер\w*|винтов\w+\s+компрессор\w*|поршнев\w+\s+компрессор\w*|'
    r'центробежн\w+\s+(?:компрессор\w*|машин\w+|нагнетател\w+)', re.I)

CHUZHOE = re.compile(
    r'логистическ\w+\s+(?:комплекс\w*|центр\w*)|склад\w+\s+комплекс\w*|'
    r'торгов\w+\s+центр\w*|бизнес-центр\w*|жил\w+\s+(?:комплекс\w*|дом\w*)|'
    r'детск\w+\s+сад\w*|школ\w+|больниц\w+|поликлиник\w+|стадион\w*|'
    r'автосалон\w*|дилерск\w+\s+центр\w*|седан\w*|кроссовер\w*|'
    r'офисн\w+\s+(?:здани\w+|помещени\w+)|благоустройств\w+|'
    r'дорог\w+|мост\w+|путепровод\w*|тротуар\w*', re.I)


def razbor(t):
    m = MASHINA.search(t or '')
    if m:
        return 'ПРЯМОЙ', m.group(0), m.start()
    c = CHUZHOE.search(t or '')
    if c:
        return 'ЧУЖОЙ', c.group(0), c.start()
    return 'КОСВЕННЫЙ', '', -1


cx = sqlite3.connect('file:%s?mode=ro' % BAZA.replace('\\', '/'), uri=True)
stroki = list(cx.execute('select rowid, inn, source, what, source_url from signals'))
cx.close()

chuzhie, za_chto = [], collections.Counter()
for rid, inn, ist, what, url in stroki:
    u, kusok, poz = razbor(what or '')
    if u == 'ЧУЖОЙ':
        chuzhie.append((rid, inn, ist, what or '', url or '', kusok, poz))
        za_chto[kusok.lower()] += 1

print('=== ЗА ЧТО поставлен ярлык ЧУЖОЙ (всего %d)' % len(chuzhie))
for k, n in za_chto.most_common():
    print('  %4d  «%s»' % (n, k[:56]))

print('\n\n########## ВСЕ ЧУЖИЕ ЦЕЛИКОМ')
for rid, inn, ist, what, url, kusok, poz in chuzhie:
    w = re.sub(r'\s+', ' ', what)
    print('\n%-6s ИНН %-11s [%s]  зацепилось за «%s» на позиции %d из %d'
          % (rid, inn, str(ist)[:22], kusok, poz, len(w)))
    print('   %s' % w[:900])
    if url:
        print('   %s' % str(url)[:120])

print('\nИТОГ ' + json.dumps({'чужих': len(chuzhie)}, ensure_ascii=False))
