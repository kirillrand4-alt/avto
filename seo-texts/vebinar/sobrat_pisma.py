def обращение(зап):
    """Как здороваемся. None - здороваемся без имени."""
    n = зап["строка"]
    if n in ОБРАЩЕНИЕ:
        return ОБРАЩЕНИЕ[n]
    имя = (зап["имя"] or "").strip()
    if not имя or re.search(r"[A-Za-z]", имя):
        return None
    # «елена» -> «Елена», «Елена Владимировна» оставляем как есть
    return " ".join(ч[:1].upper() + ч[1:] for ч in имя.split())


def письмо(зап, свой):
    """Собрать тело. свой=True - письмо уходит с ящика Ирины."""
    к = зап["_комбинация"]
    б = (Б_ИРИНА if свой else Б_ОБЩИЙ)[к[0] % 3]
    в = (В_ИРИНА if свой else В_ОБЩИЙ)[к[1] % 4]
    г = Г[к[2] % 3]
    д = Д[к[3] % 4]
    имя = обращение(зап)
    шапка = ("%s, добрый день!" % имя) if имя else "Добрый день!"
    return "\n\n".join([шапка, б, в, г, д, "С уважением,"])


def слов(т):
    return len(re.findall(r"[A-Za-zА-Яа-яЁё0-9_]+", т))


def собрать(данные):
    к_отправке = [x for x in данные if not x["стоп"]]
    # ящик Ирины забирает четверть базы, остальное уходит в общую ротацию
    доля_ирины = 45
    письма = []
    занято = {True: set(), False: set()}
    for i, зап in enumerate(к_отправке):
        свой = (i % 4 == 0) and sum(1 for p in письма if p["ящик"]) < доля_ирины
        # комбинация блоков: свой счётчик на каждый тип отправителя
        n = sum(1 for p in письма if bool(p["ящик"]) == свой)
        зап = dict(зап)
        # 3 x 4 x 3 x 4 = 144 комбинации; если тело всё равно совпало с уже
        # собранным для этого же типа отправителя (одинаковое имя плюс
        # одинаковая комбинация), сдвигаем комбинацию, пока не станет своим
        # шаг 53 взаимно прост со 144 и подобран так, чтобы у двух подряд
        # писем менялись в среднем все четыре блока, а не один соседний
        for сдвиг in range(144):
            m = (n * 53 + сдвиг) % 144
            зап["_комбинация"] = (m % 3, (m // 3) % 4, (m // 12) % 3, (m // 36) % 4)
            тело = письмо(зап, свой)
            if тело not in занято[свой]:
                break
        занято[свой].add(тело)
        письма.append({
            "строка": зап["строка"],
            "email": зап["email"],
            "inn": зап["inn"],
            "компания": зап["компания"],
            "обращение": обращение(зап),
            "ящик": ЯЩИК_ИРИНЫ if свой else None,
            "тема": ТЕМЫ[n % len(ТЕМЫ)],
            "тело": тело,
            "блоки": "Б%d В%d Г%d Д%d %s" % (зап["_комбинация"][0] % 3 + 1,
                                             зап["_комбинация"][1] % 4 + 1,
                                             зап["_комбинация"][2] % 3 + 1,
                                             зап["_комбинация"][3] % 4 + 1,
                                             "ирина" if свой else "общий"),
        })
    return письма


def проверить(письма):
    """Механический гейт: объём, вопросы, длинные тире, финал, повторы."""
    беды = []
    тела = {}
    for п in письма:
        т = п["тело"]
        n = слов(т)
        if not (45 <= n <= 200):
            беды.append("стр.%s объём %d" % (п["строка"], n))
        if т.count("?") > 2:
            беды.append("стр.%s вопросов %d" % (п["строка"], т.count("?")))
        if "—" in т or "–" in т:
            беды.append("стр.%s длинное тире" % п["строка"])
        if not т.rstrip().endswith("С уважением,"):
            беды.append("стр.%s нет финала" % п["строка"])
        if "<ul" in т or "<li" in т:
            беды.append("стр.%s список разметкой" % п["строка"])
        ключ = (п["ящик"] or "общий", т)
        тела.setdefault(ключ, []).append(п["строка"])
    for (ящик, _), стрк in тела.items():
        if len(стрк) > 1:
            беды.append("одинаковые тела в %s: %s" % (ящик, стрк[:6]))
    return беды


