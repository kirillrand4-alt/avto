# -*- coding: utf-8 -*-
"""Разбор выгрузки по словам производства: отрасль и отсев по образцам.

Классификатор компрессорных сюда не годится: там разбирались записи, где компрессорное
слово уже есть, а здесь его нет ни в одной. Поэтому правила свои, но принцип тот же:
мусор не выбрасывается, у каждой строки написана причина.

Два разных признака, и путать их нельзя:
  ОТРАСЛЬ  ставится по слову, которым запись найдена. Слов может быть несколько —
           тогда отрасль тоже составная, и это честнее, чем выбрать одну.
  КЛАСС    отвечает на другой вопрос: это вообще производственный объект или слово
           поймало ремонт крыши кирпичного дома. Отсев измерен образцами:
             «кирпичн»        673 записи, и почти все - капремонт жилого дома;
             «асфальтобетонн» 632, почти все - ремонт дорожного покрытия;
             «внеплощадочн»   616, это сети к жилым микрорайонам;
             «молоч» 1387 - молочно-товарные фермы, а не молокозаводы.
"""
import collections
import io
import json
import os
import re
import sys

KAT = os.path.dirname(os.path.abspath(__file__))
VHOD = sys.argv[1] if len(sys.argv) > 1 else os.path.join(KAT, 'PROIZVODSTVA-SYRYO.jsonl')
VYHOD = sys.argv[2] if len(sys.argv) > 2 else os.path.join(KAT, 'PROIZVODSTVA-RAZOBRANO.jsonl')

OTRASL = {
    'металлургия и горное': ['обогатительн', 'прокатн', 'доменн', 'ферросплав',
                             'электросталеплавильн', 'аглофабрик', 'кислородно-конвертер',
                             'литейн', 'цинкования', 'травильн', 'флотаци',
                             'дробильно-сортировочн', 'металлообрабатыва'],
    'химия и нефтехимия': ['химич', 'этилен', 'метанол', 'полиэтилен', 'полипропилен',
                           'полистирол', 'поливинилхлорид', 'пиролиз',
                           'каталитического крекинг', 'ректификац', 'лакокрас',
                           'лакокрасочн', 'пластмасс', 'экструзи', 'гранулирова'],
    'пищевая': ['молоч', 'молочн', 'птицефабрик', 'элеватор', 'комбикормов', 'пищев',
                'силос', 'кондитерск', 'маслоэкстракц', 'хлебозавод', 'пивовар',
                'мясокомбинат', 'мукомольн', 'молокозавод', 'рыбоперерабатыва',
                'хлебопек', 'розлив', 'укупор', 'шоковой заморозк', 'молокоперерабатыва',
                'варочн', 'холодильн', 'холодильник', 'фасов', 'фасовочн', 'асептическ'],
    'фармацевтика': ['фармацевт', 'фармацевтич', 'фармацевтическ', 'субстанц',
                     'стерилизаци', 'инъекц', 'таблетирова', 'лиофильн', 'биотехнолог'],
    'ЦБП и деревообработка': ['картон', 'картонн', 'картонно-бумажн', 'целлюлозн',
                              'целлюлозно', 'размол', 'фанер', 'фанерн',
                              'деревообрабатыва', 'лесопил', 'мебельн'],
    'стекольная': ['стекольн', 'стеклотар', 'листового стекл', 'флоат', 'стекловаренн'],
    'цементная': ['цемент', 'цементн', 'клинкер', 'вращающейся печ', 'помольн',
                  'бетоносмесительн'],
    'энергетика': ['газотурбинн', 'парогазов', 'котлотурбинн', 'золоудален', 'аэрац'],
    'машиностроение и обработка': ['сборочн', 'механосборочн', 'механообрабатыва',
                                   'инструментальн', 'испытательн', 'прессов',
                                   'штамповочн', 'сварочн', 'окрас', 'окрасочн',
                                   'покрасочн', 'порошков', 'гальванич', 'гальванопокрыт',
                                   'термич', 'термическ', 'формовочн', 'дробеструйн',
                                   'автоклав', 'пневмотранспорт'],
    'лёгкая': ['текстильн', 'прядильн', 'ткацк', 'трикотажн', 'обувн', 'кожевенн'],
    'стройматериалы и прочее': ['кирпичн', 'керамич', 'керамическ', 'сушильн',
                                'асфальтобетонн', 'внеплощадочн'],
}
SLOVO_OTRASL = {}
for o, ws in OTRASL.items():
    for w in ws:
        SLOVO_OTRASL[w] = o
PRIORITET = {'химия и нефтехимия', 'металлургия и горное', 'пищевая', 'фармацевтика',
             'ЦБП и деревообработка', 'энергетика', 'стекольная', 'цементная'}

ZHILYO = re.compile(r'многоквартирн|жилой\s+дом|жилого\s+дома|жилых\s+дом|благоустройств|'
                    r'дворов\w+\s+территор|детск\w+\s+(?:площадк|сад)|'
                    r'капитальн\w+\s+ремонт[^.]{0,60}(?:кровл|фасад|крыш|подъезд|'
                    r'фундамент|балкон|окон)', re.I)
DOROGA = re.compile(r'автомобильн\w+\s+дорог|дорожн\w+\s+покрыт|тротуар|путепровод|'
                    r'\bмост\b|улично-дорожн|проезд\w*\s+к\b|подъездн\w+\s+(?:дорог|путь)|'
                    r'наружн\w+\s+освещен|железнодорожн\w+\s+пут', re.I)
SOC = re.compile(r'школ\w|дошкольн|больниц|поликлиник|\bфап\b|стадион|бассейн|'
                 r'дом\s+культуры|библиотек|музе\w|храм|церк|кладбищ|'
                 r'физкультурно-оздоровительн', re.I)
SETI = re.compile(r'водопроводн\w+\s+сет|сет\w*\s+водоснабжен|канализац|тепловая\s+сет|'
                  r'теплотрасс|газопровод|\bвл[\s-]*\d|кабельн\w+\s+лини|'
                  r'внеплощадочн\w+\s+сет|очистн\w+\s+сооружен\w+\s+(?:хоз|быт|поверхн)', re.I)
PROIZV = re.compile(r'завод|цех\b|цеха|цеху|производств|комбинат|фабрик|'
                    r'технологическ\w+\s+лини|производственн\w+\s+(?:корпус|здани|комплекс|'
                    r'площадк|участок)|техническ\w+\s+перевооружен|промышленн', re.I)

stroki = [json.loads(s) for s in io.open(VHOD, encoding='utf-8') if s.strip()]
print('карточек на входе: %d' % len(stroki))

for x in stroki:
    t = re.sub(r'\s+', ' ', x['obekt'])
    slova = [w.strip() for w in (x.get('nayden_po') or '').split(',') if w.strip()]
    otr = sorted({SLOVO_OTRASL.get(w, 'прочее') for w in slova})
    x['otrasl'] = ' + '.join(otr)
    x['prioritetnaya'] = 'да' if any(o in PRIORITET for o in otr) else ''
    est_proizv = bool(PROIZV.search(t))
    if ZHILYO.search(t) and not est_proizv:
        x['klass'], x['pochemu'] = ('отсеяно: жильё и благоустройство',
                                    'слово производства попало в ремонт жилого дома '
                                    'или благоустройство двора')
    elif DOROGA.search(t) and not est_proizv:
        x['klass'], x['pochemu'] = ('отсеяно: дорога и линейный объект',
                                    'объект - дорога, путепровод или подъездной путь')
    elif SOC.search(t) and not est_proizv:
        x['klass'], x['pochemu'] = ('отсеяно: соцобъект',
                                    'школа, больница, спортивный объект')
    elif SETI.search(t) and not est_proizv:
        x['klass'], x['pochemu'] = ('отсеяно: инженерные сети',
                                    'водопровод, канализация, газопровод, кабельная линия')
    elif est_proizv:
        x['klass'], x['pochemu'] = 'ПРОИЗВОДСТВО', ''
    else:
        x['klass'], x['pochemu'] = ('сомнительно',
                                    'слово производства есть, а признака завода или цеха '
                                    'в названии нет - смотреть глазами')

with io.open(VYHOD, 'w', encoding='utf-8') as f:
    for x in stroki:
        f.write(json.dumps(x, ensure_ascii=False) + '\n')

c = collections.Counter(x['klass'] for x in stroki)
print('\n########## КЛАССЫ')
for k, n in c.most_common():
    print('    %-40s %6d' % (k, n))
prom = [x for x in stroki if x['klass'] == 'ПРОИЗВОДСТВО']
print('\n  ПРОИЗВОДСТВО: %d карточек, из них новых для нас %d'
      % (len(prom), len([x for x in prom if x['novaya_kartochka'] == 'да'])))
print('  разных ИНН застройщика в производстве: %d'
      % len({x['zastroyshchik_inn'] for x in prom if x['zastroyshchik_inn']}))
print('  в приоритетных отраслях: %d карточек, ИНН %d'
      % (len([x for x in prom if x['prioritetnaya']]),
         len({x['zastroyshchik_inn'] for x in prom if x['prioritetnaya'] and x['zastroyshchik_inn']})))
print('\n  ОТРАСЛИ внутри «производства»:')
for k, n in collections.Counter(x['otrasl'] for x in prom).most_common(14):
    print('    %-44s %5d' % (k[:44], n))
print('\n########## ПО ШЕСТЬ ОБРАЗЦОВ КАЖДОГО КЛАССА')
for k, _n in c.most_common():
    print('\n--- %s' % k)
    for x in [y for y in stroki if y['klass'] == k][:6]:
        print('   [%s] %s' % (x['nayden_po'][:22], x['obekt'][:104]))
