    otr = sorted({SLOVO_OTRASL.get(w, 'прочее') for w in slova})
    x['otrasl'] = ' + '.join(otr)
    x['prioritetnaya'] = 'да' if any(o in PRIORITET for o in otr) else ''
    # Два разных признака, и правила отсева гасит только СТРОГИЙ. Иначе «Магазин по
    # реализации оборудования пищевого ПРОИЗВОДСТВА» — та самая строка, которую обвёл
    # владелец, — снова уходит в производство: слово «производство» стоит рядом с
    # «пищевого», и мягкий признак срабатывает.
    silno_strogo = bool(SILNYY.search(t))
    silno = silno_strogo or silno_ryadom(t, slova)
    # Объект может быть вспомогательным (сеть, котельная, дорога), а завод в названии
    # всё-таки назван: «Котельная комбикормового завода». Предприятие настоящее, но повод
    # косвенный — такие идут в «вероятно производство», а не в «производство».
