# «завод» там нет, а производство настоящее. Признак сильный, если РЯДОМ с найденным
# словом стоит «производство», «участок», «цех», «комплекс» или «линия».
RYADOM = re.compile(r'производств|участ(?:ок|ка|ке)|цех|комплекс|лини|фабрик|завод|комбинат',
                    re.I)


def silno_ryadom(t, slova):
    tl = t.lower()
    for w in slova:
        i = 0
        while True:
            i = tl.find(w, i)
            if i < 0:
                break
            if RYADOM.search(t[max(0, i - 45):i + len(w) + 45]):
                return True
            i += len(w)
    return False


ADRES_MARKER = re.compile(r'(?:ул\.?|улиц\w*|пер\.?|переул\w*|проезд|шоссе|пр-?кт|проспект|'
                          r'б-?р|бульвар|наб\.?|набережн\w*|мкр\.?|микрорайон|пос\.?|'
                          r'посёл\w*|посел\w*|деревн\w*|\bс\.|\bд\.|тупик)\s*'
                          r'[«"]?[А-ЯЁа-яё-]{0,20}$', re.I)


def tolko_v_adrese(t, slova):
    """Правда ли, что КАЖДОЕ вхождение КАЖДОГО найденного слова стоит в адресе.

    «Многоквартирные жилые дома ... ул. Кирпичных заводов, 181» — слово «кирпичн» здесь
    только адрес. А «Строительство кирпичного завода по адресу: ул. Ленина» — нет.
    """
    tl = t.lower()
    bylo = False
    for w in slova:
        i = 0
        while True:
            i = tl.find(w, i)
            if i < 0:
                break
            bylo = True
            if not ADRES_MARKER.search(t[max(0, i - 24):i]):
                return False
            i += len(w)
    return bylo


