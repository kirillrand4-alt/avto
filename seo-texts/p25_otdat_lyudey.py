    t = f'{dolzh} {podrazd}'.strip()
    if not t:
        return ''
    if NE_NASHA_ZONA.search(t):
        return 'зона не наша'
    # СЕРВИС ПРОВЕРЯЕТСЯ РАНЬШЕ «ТЕХНИЧЕСКОЙ». Слово «технический» стоит и там и там, и у
    # Пожарского оно пришло даже не из должности, а из подразделения — «Служба технического
