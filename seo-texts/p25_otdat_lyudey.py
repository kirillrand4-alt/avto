    lyudi, daty, po_ploshchadkam = [], {}, {}
    for imya, fajl_lyudi, fajl_spiski in PLOSHCHADKI:
        spiski = chitat(os.path.join(L, fajl_spiski))
        for r in spiski:
            n = (r.get('nomer') or '').strip()
            if n:
                # (ИНН, номер процедуры) → дата. Тот же ключ, что у правила «один документ —
                # один факт», поэтому номера разных площадок не путаются между собой.
                daty.setdefault((r.get('inn', ''), n), (r.get('data') or '').strip())
        est = chitat(os.path.join(L, fajl_lyudi))
        for r in est:
            r['_ploshchadka'] = imya
        po_ploshchadkam[imya] = len(est)
        lyudi += est

    luchshee = {}
    bez_familii = bez_nomera = 0
    for r in lyudi:
        imya = (r.get('chelovek') or '').strip()
        f = familiya(imya)
        if not f:
            bez_familii += 1
            continue
        # `mobilnyy` — ФЛАГ («да»), А НЕ НОМЕР. Первая версия читала его как телефон, и в
        # 23 строках из 120 в поле телефона уехало бы слово «да». Мобильность считается по
        # самому номеру, а не по чужой пометке: 11 цифр с 7/8 и второй 9, либо 10 с первой 9.
        syroy = (r.get('telefon') or '').strip()
        m = DOB.search(syroy)
        dobav = m.group(1) if m else ''
        nomer_ch = DOB.sub('', syroy).strip()
        d10 = desyat(nomer_ch)
        if not d10 and not (r.get('pochta') or '').strip():
            bez_nomera += 1
            continue
        proc = (r.get('nomer') or '').strip()
        data = daty.get((r.get('inn', ''), proc), '')
        k = (r.get('inn', ''), f, d10)
        citata = (f'{r.get("_ploshchadka", "площадка")}, карточка закупки {proc}: '
                  f'контактное лицо «{imya}»')
        if nomer_ch:
            citata += f', телефон «{nomer_ch}»'
        if dobav:
            citata += f', добавочный {dobav}'
        stroka = {
            'inn': r.get('inn', ''),
            'chelovek': imya,
            'dolzhnost': '',        # площадка не отдаёт — см. шапку модуля
            'podrazdelenie': '',
            'telefon': nomer_ch,
            'pochta': (r.get('pochta') or '').strip(),
            'rol': '',
            'ssylka': (r.get('ssylka') or '').strip(),
            'data_nablyudeniya': data,
            'citata': citata,
        }
        if k not in luchshee or klyuch_daty(data) > klyuch_daty(luchshee[k]['data_nablyudeniya']):
            luchshee[k] = stroka

    # ВТОРОЙ ИСТОЧНИК — САЙТЫ ПРЕДПРИЯТИЙ. У него всё наоборот, чем у площадок: должность и
    # подразделение есть почти всегда, телефон почти никогда (страницы руководства прямых
    # номеров не публикуют). Поэтому он не заменяет площадки, а дополняет их — и склеивается
    # тем же ключом (ИНН, фамилия, 10 цифр номера). Человек без номера имеет пустой ключ по
    # номеру и с телефонной записью того же человека не сольётся: это намеренно, решение о
    # склейке принимает оп по правилу трёх исходов, а не я догадкой.
    s_sajtov = 0
    ne_lyudi = 0
    for r in chitat(SAJTY):
        imya = (r.get('chelovek') or '').strip()
        f2 = familiya(imya)
        if not f2 or NE_CHELOVEK.search(imya):
            ne_lyudi += 1
            continue
        nomer_ch = (r.get('telefon') or '').strip()
        d10 = desyat(nomer_ch)
        stranica = (r.get('stranica') or '').strip()
        k = (r.get('inn', ''), f2, d10)
        stroka = {
            'inn': r.get('inn', ''),
            'chelovek': imya,
            'dolzhnost': (r.get('dolzhnost') or '').strip(),
            'podrazdelenie': (r.get('podrazdelenie') or '').strip(),
            'telefon': nomer_ch,
            'pochta': (r.get('pochta') or '').strip(),
            'rol': rol_po_dolzhnosti(r.get('dolzhnost'), r.get('podrazdelenie')),
            'ssylka': stranica,
            # Даты у страницы сайта НЕТ, и выдумывать «сегодня» нельзя: сегодня — это когда мы
            # посмотрели, а не когда сведения верны. Пустая клетка честнее.
            'data_nablyudeniya': '',
            # Цитата — кусок самой страницы, если разбор его сохранил; иначе честно пишем,
            # что цитаты нет, а не пересказываем свои же поля.
            'citata': ((f'страница сайта, дословно: {r["kontekst"]}' if r.get('kontekst')
                        else f'страница сайта, цитата не сохранена при разборе: «{imya}»')
                       + (f' [почта: {chya_pochta(imya, (r.get("pochta") or "").strip())}]'
                          if (r.get('pochta') or '').strip() else '')),
        }
        if k not in luchshee:
            luchshee[k] = stroka
            s_sajtov += 1

    # ТРЕТИЙ ИСТОЧНИК — ЕИС. Единственный, где должность, полное имя и прямой телефон стоят
    # рядом и написаны самим заказчиком. Площадки должностей не отдают вовсе (проверено на
    # живой карточке ЭТП ГПБ: ноль должностных слов на всей странице), сайт есть не у всех.
    # Цитата у него дословная — кусок текста карточки, а не пересказ наших полей.
    s_eis = 0
    for r in chitat(os.path.join(L, 'P25-EIS-KONTAKTY.csv')):
        imya = (r.get('chelovek') or '').strip()
        f3 = familiya(imya)
        if not f3 or NE_CHELOVEK.search(imya):
            ne_lyudi += 1
            continue
        nomer_ch = (r.get('telefon') or '').strip()
        d10 = desyat(nomer_ch)
        k = (r.get('inn', ''), f3, d10)
        dobav = (r.get('dobavochnyy') or '').strip()
        # ДОБАВОЧНЫЙ ПИШЕТСЯ В САМ НОМЕР СЛОВОМ. В формате 1-й сессии колонки для него нет, а
        # без него номер бесполезен: владелец показал карточку ОАК, где продавец видит
        # +7 495 926-14-20 и попадает на коммутатор, тогда как в ЕИС стоит «7-495-9261420-8559»
        # и рабочий контакт — это 8559. Словом «доб.», а не цифрами подряд: слипшиеся цифры
        # дают несуществующий номер, это отдельное правило и оно остаётся в силе.
        if dobav and nomer_ch:
            nomer_ch = f'{nomer_ch} доб. {dobav}'
        stroka = {
            'inn': r.get('inn', ''),
            'chelovek': imya,
            'dolzhnost': (r.get('dolzhnost') or '').strip(),
            'podrazdelenie': '',
            'telefon': nomer_ch,
            'pochta': (r.get('pochta') or '').strip(),
            'rol': rol_po_dolzhnosti(r.get('dolzhnost'), r.get('po_voprosam')),
            'ssylka': (r.get('ssylka') or '').strip(),
            'data_nablyudeniya': (r.get('data') or '').strip(),
            'citata': (f'ЕИС, карточка {r.get("nomer_procedury")}, дословно: {r.get("citata")}'
                       + (f' [добавочный {dobav}]' if dobav else '')),
        }
        # ЕИС СИЛЬНЕЕ ПЛОЩАДКИ: там же имя без должности, здесь должность названа заказчиком.
        est = luchshee.get(k)
        # ДОБАВОЧНЫЙ — ТОЖЕ ПОВОД ЗАМЕНИТЬ СТРОКУ. Первая версия меняла только ради должности,
        # и восстановленные добавочные не доезжали: строка человека уже лежала, должности у неё
        # не было и у новой тоже, значит «не лучше» — и номер оставался обрезанным.
        if est is None or (not est.get('dolzhnost') and stroka['dolzhnost']) \
                or (dobav and 'доб.' not in (est.get('telefon') or '')):
            luchshee[k] = stroka
            s_eis += 1

    # ЧЕТВЁРТЫЙ ИСТОЧНИК — ПРИЦЕЛЬНО ДОБЫТЫЕ НОМЕРА ТЕХНАРЯМ. Канал ищет номер конкретному
    # человеку, у которого уже есть техническая должность, но нет мобильного. Он не добавляет
    # людей — он ДОПОЛНЯЕТ существующие записи, поэтому и склейка тут другая: ищем строку по
    # (ИНН + фамилия) и ставим номер, если своего не было. Без этого шага найденный мобильный
    # лежит в отдельном файле и в меру успеха не попадает — а мера считается по выкладке.
    dopolneno = 0
    po_familii = {}
    for k, v in luchshee.items():
        po_familii.setdefault((k[0], k[1]), []).append(k)
    for r in chitat(os.path.join(L, 'P25-NOMERA-TEHNARYAM.csv')):
        f4 = familiya(r.get('chelovek'))
        klyuchi = po_familii.get((r.get('inn', ''), f4)) or []
        nomer = (r.get('nomer') or '').strip()
        if not klyuchi or not nomer:
            continue
        # Ставим тому вхождению, у кого номера нет вовсе; мобильный сильнее городского.
        for k in klyuchi:
            est = luchshee[k]
            svoy_mob = desyat(est['telefon'])[:1] == '9'
            novyy_mob = desyat(nomer)[:1] == '9'
            if not est['telefon'] or (novyy_mob and not svoy_mob):
                est['telefon'] = nomer
                dob = (r.get('dobavochnyy') or '').strip()
                # ЦИТАТА ДОБЫТОГО НОМЕРА ИДЁТ ПЕРВОЙ, СТАРАЯ — ПОСЛЕ. Поймано на первом же
                # закрытом предприятии: у Ахмадуллина в строке стоял мобильный из документа
                # раскрытия, а цитата — со страницы руководства, где номер ДРУГОЙ, внутренний
                # 37-28-61. Продавец будет звонить по номеру из поля, а проверять по цитате;
                # если цитата про другой номер, она не подтверждает ничего и хуже пустой.
                est['citata'] = (f'номер добыт запросом «{r.get("zapros")}», дословно: '
                                 f'{r.get("citata", "")[:260]}'
                                 + (f' [добавочный {dob}]' if dob else '')
                                 + f' || должность оттуда же: {est["citata"][:160]}')
                # ССЫЛКА ИДЁТ ЗА НОМЕРОМ, А НЕ ОСТАЁТСЯ ПРЕЖНЕЙ. Поймано на втором закрытом
                # предприятии: у Кошилева («СИБЭЛЕКТРО», главный инженер) мобильный добыт с
                # карточки tender.pro, а в ссылке стояло `sibelectro.com/kontakty/` — старая,
                # со страницы должности. Продавец пойдёт проверять номер по ссылке и НЕ НАЙДЁТ
                # его там. Первоисточник поля — это источник того, что в поле лежит; прежний
                # адрес не теряется, он уезжает в хвост цитаты вместе со своей должностью.
                staraya = est['ssylka']
                if r.get('ssylka'):
                    est['ssylka'] = r['ssylka']
                    if staraya and staraya != r['ssylka']:
                        est['citata'] += f' || должность взята отсюда: {staraya}'
                else:
                    est['ssylka'] = staraya
                dopolneno += 1
                break

    rows = sorted(luchshee.values(), key=lambda x: (x['inn'], x['chelovek']))

    # ОТВЯЗКА ПО ФАЙЛУ-ПОПРАВКЕ. Групповая страница `segezha-group.com/providers/contacts/`
    # перечисляет контакты ПО ЗАВОДАМ, а разбор приписал все 22 строки одному ИНН —
    # АО «Лесосибирский ЛДК № 1». Перечитал страницу по заголовкам: его людей там ДВОЕ,
    # остальные с Онежского ЛДК, Галича, Вятского Фанерного, Сегежского ЦБК, Сегежской
    # упаковки и Тайрику. Правило владельца и 3-й сессии одно: РАЗДЕЛЯТЬ, А НЕ ОТСЕИВАТЬ —
    # строки остаются, но роль называет чужого работодателя, и в меру они не идут.
    otvyazat = {}
    for r in chitat(os.path.join(L, 'P25-OTVYAZAT-2S-001.csv')):
        otvyazat[(r['inn'], r['chelovek'].strip())] = r
    otvyazano = 0
    for x in rows:
        o = otvyazat.get((x['inn'], x['chelovek'].strip()))
        if not o:
            continue
        x['rol'] = 'другой работодатель'
        x['citata'] = (f'РАБОТАЕТ НЕ ЗДЕСЬ: {o["nastoyashchiy_rabotodatel"]}. '
                       f'{o["pochemu"]} || ' + (x['citata'] or ''))[:1200]
        otvyazano += 1
    if otvyazano:
        print(f'  отвязано от чужого предприятия по файлу-поправке: {otvyazano}',
              file=sys.stderr)

    # ВИД НОМЕРА ЕДЕТ ВМЕСТЕ С НОМЕРОМ. 3-я сессия посчитала по базе: 316 городских номеров
    # помечены «личный», 311 таких строк — из моих файлов. Метку ставил не тот, кто добывал:
    # выкладка несла только `chelovek` и `telefon`, и заливке приходилось угадывать. Гадание
    # убирается здесь, а не проверкой на той стороне: признак личного мобильного ровно один —
    # после нормализации номер начинается на 79, и знать его должен тот, у кого номер в руках.
    musornyh = 0
    for x in rows:
        if x['dolzhnost'] and MUSOR_DOLZHNOSTI.search(x['dolzhnost']):
            x['dolzhnost'] = ''
            x['rol'] = rol_po_dolzhnosti('', x.get('podrazdelenie', ''))
            musornyh += 1
    print(f'  должностей-мусора вычищено (телефон/часы приёма вместо должности): {musornyh}',
          file=sys.stderr)

    ne_razobrano = Counter()
    for x in rows:
        n = p25_nomer.razobrat(x['telefon'])
        if n.vid == p25_nomer.NE_RAZOBRAN and n.cifry:
            ne_razobrano[n.pochemu] += 1
        x['telefon'] = n.nomer or x['telefon']
        x['dobavochnyy'] = n.dobavochnyy
        x['vid_nomera'] = n.vid if x['telefon'] else ''
        # Колонку завела 1-я сессия — заполняю её я, потому что данные мои.
        x['nomer_ne_lichnyy'] = '' if n.lichnyy else ('да' if x['telefon'] else '')
        # ФОРМУЛА ПРИЁМКИ, А НЕ ДОВЕРИЕ К СЕБЕ. Поправка 3-й сессии: они трижды насчитали
        # закрытых больше, чем есть, потому что мера верила полю, а не тому, что за полем
        # стоит. Здесь проверяемо ровно одно и это главное: ЕСТЬ ЛИ ЦИФРЫ НОМЕРА В ЦИТАТЕ.
        # Если цитата номера не содержит, она его не подтверждает — чем бы она ни была.
        # Сверяем без кода страны: в тексте пишут и «8», и «+7», и слитно.
        x['citata_podtverzhdaet'] = ''
        if n.cifry and len(n.cifry) == 11:
            x['citata_podtverzhdaet'] = 'да' if n.cifry[1:] in re.sub(r'\D', '', x['citata'] or '') \
                else 'нет'

    # ИМЯ НА КАЖДЫЙ ЗАХОД СВОЁ, А НЕ ОДНО НА ВСЕ. Просьба 3-й сессии, и она подкреплена
    # потерей: их файл под постоянным именем сменился между двумя заливками соседа, и сорок
    # строк середины не попали в базу и на дропе их больше нет. Приёмка идёт по сторожу раз
    # в 25 минут — любая перезапись внутри окна теряет то, что не успело влиться.
    # Общий `P25-LYUDI-2S.csv` тоже пишется: по нему удобно смотреть текущее целое.
    nomer = 1
    while os.path.exists(os.path.join(L, f'P25-LYUDI-2S-{nomer:03d}.csv')):
        nomer += 1
    puti = [VYHOD, os.path.join(L, f'P25-LYUDI-2S-{nomer:03d}.csv')]
    for put in puti:
        with open(put, 'w', encoding='utf-8-sig', newline='') as f:
            w = csv.DictWriter(f, fieldnames=COLS, delimiter=';', extrasaction='ignore')
            w.writeheader()
            w.writerows(rows)

    # ОДИН НОМЕР У ДВОИХ — ЭТО ЛИБО ОДИН ЧЕЛОВЕК, ЛИБО НЕ ЛИЧНЫЙ НОМЕР. Увидено в панели
    # глазами, на карточках: пять мобильных стоят у двух разных людей каждый. Разобрано
    # поштучно — оказалось два разных случая, и оба важны.
    #   «Аксёнов Денис» и «Денис Аксенов Не» (ЭЙЧ ЭНД ЭН) — ОДИН человек, две карточки с
    #   разным порядком слов. Склеивается вложенностью множеств: лишнее слово «Не» равенству
    #   мешает, вложенности — нет.
    #   «Дукин Сергей» и «Черняев Владимир» (ТЯЖМАШ), отдел кадров Кировпейпера — РАЗНЫЕ люди
    #   с одним номером. Значит номер не человека, а бюро: его в карточку подставляют любому
    #   сотруднику. Признак «начинается на 79» отличает мобильный от городского, но НЕ личный
    #   от отдельского, и для меры ТЗ важно именно второе.
    po_nomeru = {}
    for x in rows:
        if x['telefon']:
            po_nomeru.setdefault((x['inn'], x['telefon']), []).append(x)
    skleeno = otdelskih = 0
    ubrat = set()
    for (_i, _t), gruppa in po_nomeru.items():
        zhivye = []
        for x in gruppa:
            k = klyuch_imeni(x['chelovek'])
            slit = None
            for y in zhivye:
                ky = klyuch_imeni(y['chelovek'])
                if k <= ky or ky <= k:
                    slit = y
                    break
            if slit is None:
                zhivye.append(x)
                continue
            # Оставляем ту запись, где больше известно: должность важнее длины имени.
            luchshaya, hudshaya = (slit, x) if (slit['dolzhnost'] or not x['dolzhnost']) \
                else (x, slit)
            for pole in ('dolzhnost', 'podrazdelenie', 'pochta', 'data_nablyudeniya'):
                luchshaya[pole] = luchshaya[pole] or hudshaya[pole]
            if len(hudshaya['chelovek']) > len(luchshaya['chelovek']):
                luchshaya['chelovek'] = hudshaya['chelovek']
            if luchshaya is x:
                zhivye[zhivye.index(slit)] = x
            ubrat.add(id(hudshaya))
            skleeno += 1
        if len(zhivye) > 1 and zhivye[0]['vid_nomera'] == p25_nomer.MOBILNYY:
            for x in zhivye:
                x['vid_nomera'] = 'мобильный отдела'
                x['nomer_ne_lichnyy'] = 'да'
                otdelskih += 1
    rows = [x for x in rows if id(x) not in ubrat]
    print(f'  склеено записей одного человека под одним номером: {skleeno}', file=sys.stderr)
    print(f'  мобильных, стоящих у РАЗНЫХ людей (номер отдела, не личный): {otdelskih}',
          file=sys.stderr)

    mob = sum(1 for x in rows if x['vid_nomera'] == p25_nomer.MOBILNYY)
    s_datoy = sum(1 for x in rows if x['data_nablyudeniya'])
    print(f'вход: {len(lyudi)} строк карточек по площадкам {po_ploshchadkam}', file=sys.stderr)
    print(f'  без разбираемой фамилии: {bez_familii}', file=sys.stderr)
    print(f'  без номера и без почты:  {bez_nomera}', file=sys.stderr)
    print(f'ВЫХОД: {len(rows)} человек на {len({x["inn"] for x in rows})} предприятиях',
          file=sys.stderr)
    vidy = Counter(x['vid_nomera'] for x in rows if x['vid_nomera'])
