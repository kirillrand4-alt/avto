TRANSLIT = {'а': ['a'], 'б': ['b'], 'в': ['v'], 'г': ['g'], 'д': ['d'], 'е': ['e', 'ye'],
            'ё': ['e', 'yo', 'io'], 'ж': ['zh', 'j', 'g'], 'з': ['z'], 'и': ['i'],
            'й': ['y', 'i', 'j'], 'к': ['k'], 'л': ['l'], 'м': ['m'], 'н': ['n'], 'о': ['o'],
            'п': ['p'], 'р': ['r'], 'с': ['s'], 'т': ['t'], 'у': ['u'], 'ф': ['f'],
            'х': ['h', 'kh', 'x'], 'ц': ['c', 'ts', 'tc'], 'ч': ['ch'], 'ш': ['sh'],
            'щ': ['sch', 'shch', 'sh'], 'ъ': [''], 'ы': ['y', 'i'], 'ь': ['', 'j'], 'э': ['e'],
            'ю': ['yu', 'iu', 'ju', 'u'], 'я': ['ya', 'ia', 'ja', 'a']}
# Обезличенные и служебные адреса. `omts` и `dzak` — не имена: это отдел
# материально-технического снабжения и дирекция по закупкам, встречены живьём.
OBEZLICHENNYE = re.compile(r'^(?:info|mail|office|post|secretar|priemnaya|priem|zakup|tender|'
                           r'otdel|sales|market|hr|job|contact|support|adm|general|reception|'
                           r'omts|omt|otiz|oks|ooo|zao|pto|dzak|snab|torg|shop|orders?|buh)',
                           re.I)


def latinicej(s):
    """Все правдоподобные написания фамилии латиницей. Возвращается СПИСОК: «Синявский» это и
    siniavskii, и sinyavsky, и sinjavskij — какой из них выбрал администратор почты, заранее
    неизвестно, а ошибка в одну букву превращает верную строку в подозрительную."""
    varianty = ['']
    for c in (s or '').lower():
        hvosty = TRANSLIT.get(c, [c])
        varianty = [v + h for v in varianty for h in hvosty][:64]
    return varianty


def chya_pochta(imya, pochta):
    """→ пометка о принадлежности адреса. Пустая строка означает «почты нет»."""
    if not pochta:
        return ''
    lok = pochta.split('@')[0].lower()
    # СЛИЧАЕМ ВСЕ ЧАСТИ ИМЕНИ, А НЕ ПЕРВОЕ СЛОВО. Первое слово не всегда фамилия: живьём
    # встретились «Анастасия Вачегина Александровна» (имя впереди) и «В. В. Марсакова»
    # (инициалы впереди) — у обеих почта своя, а пометка выходила «фамилия не его».
    # Совпадение любой части имени с адресом — довод, что адрес этого человека; наоборот
    # не бывает: чужую фамилию в своём адресе не пишут.
    chasti = [c for c in re.sub(r'[^А-ЯЁа-яё -]', ' ', imya or '').split() if len(c) > 3]
    for c in chasti:
        for v in latinicej(c):
            if len(v) >= 4 and (v[:5] in lok or lok[:5] in v):
                return 'именная, совпала с фамилией'
    if OBEZLICHENNYE.match(lok):
        return 'обезличенная — отдел или приёмная, не личная почта человека'
    return 'именная, но фамилия НЕ его — проверить принадлежность'


