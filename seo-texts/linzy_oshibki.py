def main():
    threads = int(sys.argv[sys.argv.index('--threads') + 1]) if '--threads' in sys.argv else 6
    only = sys.argv[sys.argv.index('--only') + 1].split(',') if '--only' in sys.argv else None
    os.makedirs(OUT, exist_ok=True)
    L = linzy()
    if only:
        L = {k: v for k, v in L.items() if k in only}
    for k, (doki, _) in L.items():
        print(f'  {k}: {sum(len(t) for _, t in doki) // 1024} КБ', file=sys.stderr)
    client = G.make_client()
    lock = threading.Lock()

    def odna(item):
        imya, (doki, zadacha) = item
        telo = MEHANIZMY + '\n'
        for zag, t in doki:
            telo += f'\n===== ФАЙЛ: {zag} =====\n{t}\n===== КОНЕЦ =====\n'
        telo += '\n' + zadacha + '\n\n' + VOPROS
        try:
            o = G.call(client, [{'role': 'user', 'content': telo}], model=MODEL)
            txt = ''.join(b.text for b in o.content if b.type == 'text').strip()
        except Exception as e:  # noqa: BLE001
            txt = f'ОШИБКА: {type(e).__name__}: {e}'
        with lock:
            open(os.path.join(OUT, f'meh-{imya}.md'), 'w', encoding='utf-8').write(txt + '\n')
        return imya, len(txt)

    with ThreadPoolExecutor(max_workers=threads) as pool:
        for imya, n in pool.map(odna, list(L.items())):
            print(f'  готово {imya}: {n} знаков', file=sys.stderr)
    print(f'всё → {OUT}', file=sys.stderr)


if __name__ == '__main__':
    main()
