def vstavit_v_kanon(kanon):
    """Вернуть НОВЫЙ список правил: ранние вставлены после «техконтакта», ГИП перецелен.

    Исходный список не меняется — накапливаем, а не заменяем.
    """
    out = []
    vstavleno = False
    for keys, canon in kanon:
        if canon == 'общий' and any('гип' in str(k) for k in keys):
            keys = tuple(keys) + ('главный инженер проекта', 'главного инженера проекта',
                                  'гип проекта')
            canon = 'ГИП'
        out.append((keys, canon))
        if canon == 'техконтакт' and not vstavleno:
            out.extend(PRAVILA_RANNIE)
            vstavleno = True
    if not vstavleno:                       # правила «техконтакт» не нашлось
        out = PRAVILA_RANNIE + out          # тогда наверх, но об этом надо знать
    return out


def _sovpalo(keys, r):
    for k in keys:
        if str(k).startswith('re:'):
            if _re.search(str(k)[3:], r):
                return True
        elif str(k) and str(k) in r:
            return True
    return False


def kanon_rannih(post):
    """Роль ТОЛЬКО по новым правилам, '' если ни одно не подошло.

    Нужна там, где полного канона нет под рукой (песочница, разбор выгрузки).
    """
    r = (post or '').strip().lower()
    if not r:
        return ''
    for keys, canon in PRAVILA_RANNIE:
        if _sovpalo(keys, r):
            return canon if canon in RANNIE_ROLES else ''
    return ''


