# -*- coding: utf-8 -*-
"""Стоит ли принимать приоритеты линзы: сверка `lens-02-roles.md` с ЖИВЫМИ должностями.

Найден готовый каталог `seo-texts/centrifugal/lens-02-roles.md` (530 строк): четырнадцать
ролей с приоритетами. Шести из них в живом каноне нет вовсе. Но «нет в каноне» само по
себе не довод — довод это СКОЛЬКО ЖИВЫХ ЛЮДЕЙ мимо него проходит. Считаю.

ЧТО МЕРЮ на `enrich.people.post` (9 906 человек с должностью, 3 153 разных):

  1. сколько людей попадают в роли, которых В КАНОНЕ НЕТ (нач. компрессорной станции,
     директор по эксплуатации/надёжности, зам. гл. механика, нач. ОГМ, инженер по
     надёжности, нач. РМЦ) — то есть сколько теряется молча;
  2. главное расхождение линзы и канона: у линзы круг 1 это ГЛ. МЕХАНИК и
     ГЛ. ЭНЕРГЕТИК («реальный хозяин компрессорного парка»), а гл.инженер идёт вторым
     как синоним техдиректора; в живом каноне гл.инженер первый. Считаю, скольких
     людей это разводит по разным кругам;
  3. сколько компаний ПОЛУЧАТ круг-1 контакт, если принять линзу, и сколько потеряют.

Ничего не меняет. Числа, а не мнение.
"""
import collections
import json
import re
import sqlite3

ENRICH = r'C:\sender\enrich.db'

# Роли линзы 02. Порядок = приоритет. Ключи — по вхождению, узкие раньше широких.
LINZA = [
    # круг 1 — «реальный хозяин компрессорного парка»
    ('нач. компрессорной станции/цеха', 1, (
        'начальник компрессорн', 'нач. компрессорн', 'нач.компрессорн',
        'начальник кс', 'руководитель компрессорн', 'начальник воздушн')),
    ('директор по эксплуатации/надёжности', 1, (
        'директор по эксплуатац', 'директор по надежност', 'директор по надёжност',
        'директор по техническому обслуживан', 'директор по тоир')),
    ('гл. механик', 1, ('главный механик', 'гл.механик', 'гл. механик')),
    ('гл. энергетик', 1, ('главный энергетик', 'гл.энергетик', 'гл. энергетик')),
    ('технический директор', 2, ('технический директор', 'техдиректор',
                                 'директор по технич')),
    # у линзы «главный инженер» — СИНОНИМ техдиректора, круг 2, а не 1
    ('главный инженер (по линзе = техдир)', 2, ('главный инженер', 'гл.инженер',
                                                'гл. инженер')),
    # круг 2 — исполнители, которых канон не знает
    ('зам. гл. механика/энергетика', 2, (
        'заместитель главного механик', 'зам. главного механик', 'зам.главного механик',
        'заместитель главного энергетик', 'зам. главного энергетик')),
    ('нач. ОГМ / службы гл. механика', 2, (
        'начальник службы главного механик', 'начальник огм', 'нач. огм',
        'начальник отдела главного механик')),
    ('инженер по надёжности/эксплуатации', 2, (
        'инженер по надежност', 'инженер по надёжност', 'инженер по эксплуатац')),
    ('нач. РМЦ', 2, ('ремонтно-механическ', 'начальник рмц', 'нач. рмц')),
    # круг 3-4
    ('закупки/МТО', 3, ('начальник отдела закуп', 'начальник мто', 'отдел закуп',
                        'снабжен', 'закупк', 'тендер')),
    ('гендиректор', 4, ('генеральный директор', 'ген.директор')),
]
# Эти шесть в живом каноне отсутствуют — их и считаем как «теряется молча».
NET_V_KANONE = {'нач. компрессорной станции/цеха', 'директор по эксплуатации/надёжности',
                'зам. гл. механика/энергетика', 'нач. ОГМ / службы гл. механика',
                'инженер по надёжности/эксплуатации', 'нач. РМЦ'}
NE_NASH = re.compile(r'кадр|персонал|подбор|ваканс|пресс|юрис|бухгалт|реклам|маркет|'
                     r'охран\w*\s+труда|качеств|эколог|сервис|претенз', re.I)


def po_linze(post):
    p = (post or '').strip().lower()
    if not p or NE_NASH.search(p):
        return '', 9
    for imya, prio, klyuchi in LINZA:
        for k in klyuchi:
            if k in p:
                return imya, prio
    return '', 9


def main():
    cx = sqlite3.connect('file:%s?mode=ro' % ENRICH.replace('\\', '/'), uri=True)
    sch = collections.Counter()
    po_roli = collections.Counter()
    primery = collections.defaultdict(list)
    krug1_inn, krug1_inn_kanon = set(), set()

    for inn, post, chel in cx.execute(
            'select inn, coalesce(post,""), coalesce(person,"") from people '
            'where coalesce(post,"")<>""'):
        imya, prio = po_linze(post)
        sch['людей с должностью'] += 1
        if not imya:
            sch['мимо линзы (роль не опознана)'] += 1
            continue
        po_roli['%d · %s' % (prio, imya)] += 1
        if imya in NET_V_KANONE:
            sch['РОЛЬ, КОТОРОЙ НЕТ В ЖИВОМ КАНОНЕ'] += 1
            if len(primery[imya]) < 3:
                primery[imya].append((str(inn), post[:44], chel[:24]))
        if prio == 1:
            krug1_inn.add(str(inn))
        # круг 1 по ЖИВОМУ канону: там гл.инженер первый, а нач.КС и дир. по
        # эксплуатации не существуют вовсе
        if imya in ('гл. механик', 'гл. энергетик',
                    'главный инженер (по линзе = техдир)'):
            krug1_inn_kanon.add(str(inn))

    print('=== люди по ролям линзы (приоритет · роль)')
    for k, v in sorted(po_roli.items()):
        pometka = '  <- В КАНОНЕ НЕТ' if k.split('· ')[1] in NET_V_KANONE else ''
        print('  %-46s %5d%s' % (k, v, pometka))

    print('\n=== примеры людей, которых канон назвать не может')
    for imya, sp in primery.items():
        for x in sp:
            print('  %-34s %s' % (imya[:34], ' | '.join(x)))

    sch['ИНН с человеком круга 1 ПО ЛИНЗЕ'] = len(krug1_inn)
    sch['ИНН с человеком круга 1 по живому канону'] = len(krug1_inn_kanon)
    sch['  предприятий, которые ЛИНЗА добавляет'] = len(krug1_inn - krug1_inn_kanon)
    cx.close()
    print()
    for k, v in sch.most_common():
        print('REC %s\t%d' % (k, v))
    print('ИТОГ ' + json.dumps({
        'людей в ролях, которых нет в каноне': sch.get('РОЛЬ, КОТОРОЙ НЕТ В ЖИВОМ КАНОНЕ', 0),
        'предприятий с кругом 1 по линзе': len(krug1_inn),
        'из них добавляет линза': len(krug1_inn - krug1_inn_kanon)}, ensure_ascii=False))


if __name__ == '__main__':
    main()
