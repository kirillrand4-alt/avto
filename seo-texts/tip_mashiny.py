def sreda_mashiny(marki, tekst):
    t = f'{marki} {tekst}'[:1200]
    v, g = bool(VOZDUH.search(t)), bool(GAZ.search(t))
    if v and g:
        return 'воздух и газ названы оба'
    if v:
        return 'воздух'
    if g:
        return 'газ или иная среда'
    return 'среда не названа'


def razobrat(marki, tekst, pokupatel=''):
    """Вернуть (объект, тип, оговорка). Порядок строгий: отсев чужого → «машина ли» → «какая».

    Оговорка не меняет тип, а честно называет, чем строка слабее прямой: предмет заключения был
    трубопроводом или теплообменником машины, либо услугой по ней. Продавцу это нужно знать до
    звонка, а панели — чтобы такие строки можно было скрыть отдельной галочкой.
    """
    t = f'{marki} {tekst}'[:1200]
    nashe = nasha_yavno(t, marki)
    ogovorka = ''
    # Заказчик решает там, где текст молчит. «Поставка воздуходувки» у МДОУ №66 «Берёзка» и у
    # ОГУП «Липецкоблводоканал» — разные машины на три порядка, а строка одна и та же.
    if SADOVAYA_MARKA.search(t):
        return 'не наша машина', 'садовый инструмент, не машина', ''
    if (POKUPATEL_NE_NASH.search(pokupatel or '') and not PROMYSHLENNYJ_PRIZNAK.search(t)
            and not (marki or '').strip()):
        return 'не наша машина', 'садовый инструмент, не машина', ''
    if TRANSPORTNAYA_MASHINA.search(t):
        return 'не наша машина', 'услуга или чужая техника, не наша машина', ''
    if POKUPATEL_TRANSPORT.search(pokupatel or '') and not PROM_STROGO.search(t) \
            and not (marki or '').strip():
        return 'не наша машина', 'услуга или чужая техника, не наша машина', ''
    # Отсев идёт ПЕРВЫМ. Иначе «воздуходувка бензиновая ранцевая» объявляется центробежной
    # по слову «воздуходувка», а «турбоагрегат ПТ 60-90/13» — по слову «турбоагрегат».
    for imya, rx, perekryvaemo in NE_NASHA:
        m = rx.search(t)
        if not m:
            continue
        if perekryvaemo == 'да' and nashe:
            ogovorka = f'машина названа прямо, но предмет строки — {imya.split(",")[0]}'
            continue
        if perekryvaemo == 'по позиции':
            # снимаем ярлык, если наша машина названа РАНЬШЕ чужой…
            n = NASHA_YAVNO.search(t)
            if nashe and n and n.start() < m.start():
                ogovorka = f'рядом упомянуто чужое ({imya.split(",")[0]}), но названо позже нашей машины'
                continue
            # …либо если чужое введено оборотом «включая» после названной машины: «Конечный
            # компрессор RD7B, ВКЛЮЧАЯ центробежный насос подачи масла ERP65-315»
            if vspomogatelnoe(t, m):
                ogovorka = (f'{imya.split(",")[0]} назван вспомогательным узлом машины '
                            f'(оборот «включая»)')
                continue
        return 'не наша машина', imya, ''
    est_mashina = bool(MASHINA.search(t))
    if est_mashina:
        obekt = 'машина'
    elif NE_MASHINA.search(t):
        obekt = 'не машина'
    else:
        obekt = 'не установлено'
    if obekt != 'машина':
        # Центробежность объявляем только там, где объект — машина. Обозначение серии в
        # заключении про газопровод доказательством машины не является.
        return obekt, ('не применимо' if obekt == 'не машина' else 'не установлен'), ogovorka
    # Порядок важен: сначала железный признак поршневой машины, потом слово о центробежности.
    # Иначе «восстановление коленвала компрессора» пройдёт по слову «компрессор».
    if NE_NASH_TIP.search(t) and not nashe:
        return obekt, 'поршневая или винтовая', ogovorka
    # Голая запчасть без марки и без указания машины типа не доказывает. «Поставка запасных
    # частей (турбокомпрессор)» у МУП «Служба организации движения» — это турбина наддува
    # автобуса, а строка числилась центробежной. Требуем хоть какую-то опору: марку или слово
    # о центробежности рядом.
    if (re.search(r'запасн\w+\s+част|запчаст', t, re.I) and len(t) < 110
            and not (marki or '').strip() and not re.search(r'центробежн|воздуходувк', t, re.I)
            and not re.search(r'\d|[«"\'](?:[^«»"\']{1,30})[»"\']', t)):
        return obekt, 'тип не установлен', 'только запчасть, машина ничем не опознана'
    if re.search(r'осушител', t, re.I) and not NASHA_YAVNO.search(t):
        # «Техобслуживание адсорбционных осушителей PNEUMATECH PB530HE» — осушитель стоит ПОСЛЕ
        # компрессора и доказывает сжатый воздух, но не вид машины
        return obekt, 'тип не установлен', 'объект — осушитель, вид компрессора не назван'
    if CENTR.search(t):
        return obekt, 'центробежная', ogovorka
    if TURBOAGREGAT.search(t):
        # слово-обманка: центробежность даёт только рядом с компрессорным контекстом
        if KOMPRESSORNYJ_KONTEKST.search(t):
            return obekt, 'центробежная', ogovorka
        return obekt, 'тип не установлен', 'назван турбоагрегат без компрессорного контекста'
    if any(CENTR_SERIYA.match(m.strip()) for m in (marki or '').split('|') if m.strip()):
        return obekt, 'центробежная по серии', ogovorka
    if OBSHCHEE.search(t):
        return obekt, 'вид не назван (общая формулировка)', ogovorka
    if NE_NASH_TIP.search(t):
        return obekt, 'поршневая или винтовая', ogovorka
    return obekt, 'тип не установлен', ogovorka


def main():
    fakty = list(csv.DictReader(open(FAKTY, encoding='utf-8-sig'), delimiter=';'))
    po_inn = defaultdict(lambda: {'obekt': set(), 'tip': set(), 'sost': set(), 'sreda': set()})
    schet = defaultdict(int)
    for x in fakty:
        o, t, og = razobrat(x.get('marki') or '', x.get('tekst') or '',
                            x.get('predpriyatie') or '')
        x['obekt'] = o
        x['tip_mashiny'] = t
        x['ogovorka'] = og
        # Среду, доузнанную другими каналами (sreda_dobor.py: перенос по марке, разбор
        # обозначения провайдером, род деятельности), НЕ затираем. Иначе каждый повторный запуск
        # этого файла откатывал бы работу провайдера обратно в «среда не названа» — и откат был
        # бы тихим: колонка на месте, значение прежнее, ошибку видно только по счётчикам.
        otkuda = x.get('sreda_otkuda') or ''
        if otkuda and otkuda != 'сказано прямо в тексте':
            pass
        else:
            x['sreda_mashiny'] = sreda_mashiny(x.get('marki') or '', x.get('tekst') or '')
        schet[f'{x["sostoyanie"]} | {o} | {t}'] += 1
        d = po_inn[x['inn']]
        d['obekt'].add(o)
        d['tip'].add(t)
        d['sost'].add(x['sostoyanie'])
        if t in ('центробежная', 'центробежная по серии'):
            d['sreda'].add(x['sreda_mashiny'])

    cols = list(fakty[0].keys())
    if 'ogovorka' not in cols:
        cols.append('ogovorka')
    with open(FAKTY, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter=';', extrasaction='ignore')
        w.writeheader()
        for x in fakty:
            w.writerow(x)

    DOKAZANO = {'центробежная', 'центробежная по серии'}
    SILNYE = {'есть', 'покупает', 'планирует', 'планировал'}
    pred = list(csv.DictReader(open(PO_PRED, encoding='utf-8-sig'), delimiter=';'))
    novye = ['mashina_dokazana', 'centrobezhnost_dokazana', 'tipy_mashin', 'sreda_dokazana']
    pcols = list(pred[0].keys()) + [c for c in novye if c not in pred[0]]
    for r in pred:
        d = po_inn.get(r['inn'])
        if not d:
            r['mashina_dokazana'] = r['centrobezhnost_dokazana'] = r['tipy_mashin'] = ''
            r['sreda_dokazana'] = ''
            continue
        silnoe = d['sost'] & SILNYE
        r['mashina_dokazana'] = '1' if ('машина' in d['obekt'] and silnoe) else ''
        r['centrobezhnost_dokazana'] = '1' if (d['tip'] & DOKAZANO and silnoe) else ''
        # сильное свидетельство печатаем первым: иначе в узкой колонке видно «не установлен»,
        # а «центробежная» уезжает за обрез — и строка читается наоборот тому, что доказано
        poryadok = {'центробежная': 0, 'центробежная по серии': 1, 'поршневая или винтовая': 2,
                    'тип не установлен': 3, 'не установлен': 4}
        r['tipy_mashin'] = ' | '.join(sorted(d['tip'] - {'не применимо'},
                                             key=lambda x: poryadok.get(x, 9)))[:80]
        # среда: воздух важнее всего, потом «оба названы», потом газ
        ps = {'воздух': 0, 'воздух и газ названы оба': 1, 'среда не названа': 2,
              'газ или иная среда': 3}
        r['sreda_dokazana'] = (sorted(d['sreda'], key=lambda x: ps.get(x, 9))[0]
                               if d['sreda'] else '')
    with open(PO_PRED, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=pcols, delimiter=';', extrasaction='ignore')
        w.writeheader()
        for r in pred:
            w.writerow(r)

    # очередь: центробежность доказана И среда воздух. Распоряжение владельца дословно:
    # «мне нужны только воздушные, остальные можешь выкидывать (где знаешь среду, а где не
    # знаешь = узнай)». Поэтому три файла вместо одного, и ни одна строка не пропадает:
    #   OCHERED-centrobezhnye.csv    — воздух, по нему звонят;
    #   OCHERED-sreda-neizvestna.csv — центробежная есть, среда ещё не установлена: это работа
    #                                  для sreda_dobor.py, а не повод выкинуть предприятие;
    #   OTSEV-gaz.csv                — доказан газ и только газ, чужой рынок.
    vse_c = [r for r in pred if r['centrobezhnost_dokazana'] == '1']
    och = [r for r in vse_c if str(r.get('sreda_dokazana') or '').startswith('воздух')]
    neyasno = [r for r in vse_c if not str(r.get('sreda_dokazana') or '').startswith('воздух')
               and r.get('sreda_dokazana') != 'газ или иная среда']
    gaz = [r for r in vse_c if r.get('sreda_dokazana') == 'газ или иная среда']

    def ves(x):
        # воздух наверх: правило владельца «воздух важнее газа»
        return (1 if x.get('sreda_dokazana') in ('воздух', 'воздух и газ названы оба') else 0,
                int(x.get('lyudej_tehnicheskih') or 0), 1 if x.get('telefony_predpriyatiya') else 0,
                1 if x.get('sayt') else 0, int(x.get('sostoyaniy') or 0))
    ocols = ['inn', 'predpriyatie', 'tipy_mashin', 'sreda_dokazana', 'marki', 'sostoyaniy', 'est', 'pokupaet',
             'planiruet', 'srok_sluzhby', 'vyvod_ekspertizy', 'data_zakluchenia', 'data_zakupki',
             'region', 'sayt', 'telefony_predpriyatiya', 'luchshaya_pochta', 'lyudej_tehnicheskih',
             'lyudej_s_telefonom', 'lyudi_podrobno', 'chego_ne_hvataet']
    for put, dannye in ((OCHERED, och),
                        (os.path.join(L, 'OCHERED-sreda-neizvestna.csv'), neyasno),
                        (os.path.join(L, 'OTSEV-gaz.csv'), gaz)):
        with open(put, 'w', encoding='utf-8-sig', newline='') as f:
            w = csv.DictWriter(f, fieldnames=ocols, delimiter=';', extrasaction='ignore')
            w.writeheader()
            for r in sorted(dannye, key=ves, reverse=True):
                w.writerow(r)

    # --- отчёт числами ИЗ ЗАПИСАННЫХ ФАЙЛОВ ---
    pf = list(csv.DictReader(open(FAKTY, encoding='utf-8-sig'), delimiter=';'))
    pp = list(csv.DictReader(open(PO_PRED, encoding='utf-8-sig'), delimiter=';'))
    po = list(csv.DictReader(open(OCHERED, encoding='utf-8-sig'), delimiter=';'))
    print(f'фактов: {len(pf)}')
    for k in sorted(schet, key=lambda k: -schet[k])[:12]:
        print(f'   {schet[k]:>6}  {k}')
    silnye = [r for r in pp if (r.get('sostoyaniy') or '0') != '0']
    print(f'\nпредприятий в сводке: {len(pp)}')
    print(f'  с сильным состоянием (есть/покупает/планирует): {len(silnye)}')
    print(f'    из них МАШИНА доказана:            {sum(1 for r in silnye if r["mashina_dokazana"])}')
    print(f'    из них ЦЕНТРОБЕЖНОСТЬ доказана:    {sum(1 for r in silnye if r["centrobezhnost_dokazana"])}')
    from collections import Counter as _C
    print('  среда у центробежных предприятий:',
          dict(_C(r['sreda_dokazana'] for r in pp if r['centrobezhnost_dokazana'])))
    print(f'  очередь центробежных → {len(po)} строк')
    print(f'    из них ВОЗДУХ: {sum(1 for r in po if r["sreda_dokazana"].startswith("воздух"))}')
    print(f'    из них с техническим человеком: {sum(1 for r in po if (r["lyudej_tehnicheskih"] or "0") != "0")}')
    print(f'    из них с телефоном предприятия: {sum(1 for r in po if r["telefony_predpriyatiya"])}')
    print(f'    из них без сайта:               {sum(1 for r in po if not r["sayt"])}')
    print(f'  среда не установлена → OCHERED-sreda-neizvestna.csv: {len(neyasno)} предприятий')
    print(f'  газ, выкинуты        → OTSEV-gaz.csv:                {len(gaz)} предприятий')
    import subprocess as _sp
    for put in (FAKTY, PO_PRED, OCHERED, os.path.join(L, 'OCHERED-sreda-neizvestna.csv'),
                os.path.join(L, 'OTSEV-gaz.csv')):
        _sp.run(['bash', os.path.join(BAZA, 'server', 'drop_client.sh'), 'up', put],
                capture_output=True, timeout=1800)
    print('выложено на дроп: SVOD-tri-sostoyaniya, SVOD-POLNYY-po-predpriyatiyam, '
          'OCHERED-centrobezhnye, OCHERED-sreda-neizvestna, OTSEV-gaz')
    print(f'→ {OCHERED}')


if __name__ == '__main__':
    main()
