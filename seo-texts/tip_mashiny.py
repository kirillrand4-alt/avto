# помечена «центробежная», то есть база сама себе противоречила.
VVODIT_VSPOMOGATELNOE = re.compile(r'(?:включа\w+|в\s+составе|в\s+том\s+числе|совместно\s+с)'
                                   r'[\s«"(]*$', re.I)
GLAVNAYA_MASHINA = re.compile(r'компрессор|воздуходувк|нагнетател[ьяиюе](?!н)|турбоагрегат', re.I)


def vspomogatelnoe(t, m):
    """Чужое слово стоит в придаточной части, а машина названа раньше — значит это узел машины."""
    g = GLAVNAYA_MASHINA.search(t)
    if not g or g.start() >= m.start():
        return False
    return bool(VVODIT_VSPOMOGATELNOE.search(t[max(0, m.start() - 26):m.start()]))


def nasha_yavno(t, marki):
    """Названа ли в строке наша машина прямо — словом или маркой центробежной серии."""
    if CHUZHOY_RYADOM.search(t):
        return False
    if NASHA_YAVNO.search(t):
        return True
    return any(CENTR_SERIYA.match(m.strip()) for m in (marki or '').split('|') if m.strip())


