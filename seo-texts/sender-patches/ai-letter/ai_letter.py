def log_results(db_path: str, campaign_id, items: list[dict]) -> None:
    """items: [{email, recipient_id, status ok|brak, subject, body, rounds}]."""
    cx = sqlite3.connect(db_path)
    cx.execute("""CREATE TABLE IF NOT EXISTS ai_letter_log(
        id INTEGER PRIMARY KEY AUTOINCREMENT, campaign_id INTEGER, recipient_id INTEGER,
        email TEXT, status TEXT, subject TEXT, body TEXT, rounds_json TEXT, created_at TEXT)""")
    now = datetime.now(timezone.utc).isoformat(timespec='seconds')
    for it in items:
        cx.execute("INSERT INTO ai_letter_log(campaign_id, recipient_id, email, status,"
                   " subject, body, rounds_json, created_at) VALUES(?,?,?,?,?,?,?,?)",
                   (campaign_id, it.get('recipient_id'), it.get('email'),
                    it.get('status'), it.get('subject'), it.get('body'),
                    json.dumps(it.get('rounds') or [], ensure_ascii=False), now))
    cx.commit()
    cx.close()
