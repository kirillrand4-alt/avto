VVERH = re.compile(r'\bзавод\w*|комбинат|\bгок\b|комплекс|фабрик|'
                   r'металлургическ|нефтехимическ|нефтеперерабатыва', re.I)
# «на УЧАСТКЕ по адресу», «на земельном УЧАСТКЕ с кадастровым номером» — это участок
