# Объект — подводка, пристройка или замена аппарата на подстанции. Компрессора от этого
# не появится. Эти формы не ловились классом «вспомогательный», потому что в названии
# стоит и завод: провайдер ставил им ноль, и это ровно его довод.
NE_NUZHEN = re.compile(r'^[^.]{0,40}(?:участок\s+трубопровода|трубопровод\w*\s+от\b)|'
                       r'подключени\w+\s+трубопровод|замен\w+\s+воздушн\w+\s+выключател|'
                       r'\bпс\s*\d+\s*кв\b|складск\w+\s+пристройк|холодн\w+\s+пристройк|'
                       r'вынос\s+и\s+восстановлен', re.I)
REMONT = re.compile(r'капитальн\w+\s+ремонт|текущ\w+\s+ремонт|ремонт\s+(?:кровл|фасад|'
                    r'систем|сет|здани)', re.I)

# «мощностью 150 000 тонн в год», «производительностью 120 т/ч», «на 3350 коров»
MOSHCH = re.compile(r'(?:мощностью|производительностью|объёмом|объемом)\s+(?:до\s+)?'
                    r'([\d\s.,]{1,14})\s*(тыс|млн|млрд)?\.?\s*'
                    r'(т/ч|тонн|т\b|м3|м³|куб|голов|шт|штук|литр|дал)', re.I)


def masshtab(t):
    m = MOSHCH.search(t)
    if not m:
        return None, ''
    try:
        chislo = float(re.sub(r'[^\d.,]', '', m.group(1)).replace(',', '.').replace(' ', ''))
    except ValueError:
        return None, ''
    mn = {'тыс': 1e3, 'млн': 1e6, 'млрд': 1e9}.get((m.group(2) or '').lower(), 1)
    chislo *= mn
    ed = m.group(3).lower()
    if ed in ('т/ч',):
        return (1.6 if chislo >= 50 else 1.0 if chislo >= 10 else 0.7), m.group(0)[:50]
    if ed.startswith('т') or ed.startswith('тонн'):
        return (1.6 if chislo >= 100000 else 1.0 if chislo >= 10000 else 0.7), m.group(0)[:50]
    if ed in ('голов',):
        return (1.6 if chislo >= 100000 else 1.0 if chislo >= 5000 else 0.7), m.group(0)[:50]
    return None, m.group(0)[:50]


